    lines.append("IF bCellStandby THEN dwSystemStatusWord := dwSystemStatusWord OR 16#0000_0200; END_IF;")
    lines.append("IF bCellFaulted THEN dwSystemStatusWord := dwSystemStatusWord OR 16#0000_0400; END_IF;")
    lines.append("IF bInfeedConveyorRunCmd THEN dwSystemStatusWord := dwSystemStatusWord OR 16#0000_0800; END_IF;")
    lines.append("IF bCartonConveyorRunCmd THEN dwSystemStatusWord := dwSystemStatusWord OR 16#0000_1000; END_IF;")
    lines.append("IF bCartonHoldClampSolenoid THEN dwSystemStatusWord := dwSystemStatusWord OR 16#0000_2000; END_IF;")
    lines.append("IF bCartonDischargeGateCmd THEN dwSystemStatusWord := dwSystemStatusWord OR 16#0000_4000; END_IF;")
    lines.append("IF bRejectPurgeDiverterCmd THEN dwSystemStatusWord := dwSystemStatusWord OR 16#0000_8000; END_IF;")
    lines.append("")
