    lines.append("IF lrMainAirPressure_bar < lrAlarm_AirPressure_L THEN dwAlarmStatusWord_Warning := dwAlarmStatusWord_Warning OR 16#0000_0002; END_IF;")
    lines.append("IF (iR1_RobotStatus = 2) AND (lrVoted_R1_Vac_kPa > lrAlarm_VacuumGrip_LL) THEN dwAlarmStatusWord_Warning := dwAlarmStatusWord_Warning OR 16#0000_0004; END_IF;")
    lines.append("IF (iR2_RobotStatus = 2) AND (lrVoted_R2_Vac_kPa > lrAlarm_VacuumGrip_LL) THEN dwAlarmStatusWord_Warning := dwAlarmStatusWord_Warning OR 16#0000_0008; END_IF;")
    lines.append("IF (iR3_RobotStatus = 2) AND (lrVoted_R3_Vac_kPa > lrAlarm_VacuumGrip_LL) THEN dwAlarmStatusWord_Warning := dwAlarmStatusWord_Warning OR 16#0000_0010; END_IF;")
    lines.append("IF (iR4_RobotStatus = 2) AND (lrVoted_R4_Vac_kPa > lrAlarm_VacuumGrip_LL) THEN dwAlarmStatusWord_Warning := dwAlarmStatusWord_Warning OR 16#0000_0020; END_IF;")
    lines.append("")
    lines.append("(* Advisories (Maintenance & Efficiency) *)")
    lines.append("IF iQueueCount > 50 THEN dwAlarmStatusWord_Advisory := dwAlarmStatusWord_Advisory OR 16#0000_0001; END_IF;")
