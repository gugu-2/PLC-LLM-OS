def get_tracking_fsm_code():
    lines = []
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 4: DYNAMIC CONVEYOR TRACKING & IN-LINE 3D LINE-SCAN VISION FIFO QUEUE                *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* 4.1 Ingestion of New Vision Inspection Packets into Circular Tracking Buffer *)")
    lines.append("IF bVisionDataReady AND (iQueueCount < 64) THEN")
    lines.append("    arrPkg_ID[iQueueHead] := diVisionPkg_ID;")
    lines.append("    arrPkg_X_Entry[iQueueHead] := lrVisionPkg_X;")
    lines.append("    arrPkg_Y_Entry[iQueueHead] := lrVisionPkg_Y;")
    lines.append("    arrPkg_Theta_Entry[iQueueHead] := lrVisionPkg_Theta;")
    lines.append("    arrPkg_EncSnapshot[iQueueHead] := diVisionTriggerBeltPos;")
    lines.append("    arrPkg_Defect[iQueueHead] := bVisionDefectFlag OR (lrVisionSealIntegrity < 85.0) OR (ABS(lrVisionPkg_Theta) > 55.0);")
    lines.append("    IF arrPkg_Defect[iQueueHead] THEN")
    lines.append("        arrPkg_State[iQueueHead] := 8; (* Flagged for reject diverter *)")
    lines.append("    ELSE")
    lines.append("        arrPkg_State[iQueueHead] := 1; (* Queued for picking *)")
    lines.append("    END_IF;")
    lines.append("    arrPkg_AssignedRobot[iQueueHead] := 0;")
    lines.append("    diTotalInfeedCount := diTotalInfeedCount + 1;")
    lines.append("    iQueueHead := (iQueueHead MOD 64) + 1;")
    lines.append("    iQueueCount := iQueueCount + 1;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 4.2 Dynamic Conveyor Position Propagation across All Active Queue Records *)")
    lines.append("FOR iIdx := 1 TO 64 DO")
    lines.append("    IF (arrPkg_State[iIdx] >= 1) AND (arrPkg_State[iIdx] <= 5) THEN")
    lines.append("        (* Compute instantaneous Cartesian coordinate along conveyor belt *)")
    lines.append("        IF lrBeltPulsesPerMM > 0.001 THEN")
    lines.append("            arrPkg_X_Entry[iIdx] := arrPkg_X_Entry[iIdx] + ((DINT_TO_LREAL(diVoted_InfeedBelt_Pos - arrPkg_EncSnapshot[iIdx]) / lrBeltPulsesPerMM));")
    lines.append("            arrPkg_EncSnapshot[iIdx] := diVoted_InfeedBelt_Pos;")
    lines.append("        END_IF;")
    lines.append("        (* Check if unpicked package escaped past the last robot picking envelope (X > 5400 mm) *)")
    lines.append("        IF (arrPkg_X_Entry[iIdx] > 5400.0) AND (arrPkg_State[iIdx] <> 6) AND (arrPkg_State[iIdx] <> 7) THEN")
    lines.append("            arrPkg_State[iIdx] := 9; (* Escaped unpicked package *)")
    lines.append("            diTotalRejectedCount := diTotalRejectedCount + 1;")
    lines.append("        END_IF;")
    lines.append("    END_IF;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 5: MULTI-ROBOT LOAD BALANCING & WORK-ENVELOPE COLLISION MUTUAL EXCLUSION             *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* 5.1 Dynamic Workload Allocation across Delta Robots 1..4 *)")
    lines.append("FOR iIdx := 1 TO 64 DO")
    lines.append("    IF arrPkg_State[iIdx] = 1 THEN (* Unassigned package *)")
    lines.append("        (* Check Robot 1 work window (X in [600..1400]) *)")
    lines.append("        IF (arrPkg_X_Entry[iIdx] >= 600.0) AND (arrPkg_X_Entry[iIdx] <= 1350.0) AND (iR1_RobotStatus = 0) THEN")
    lines.append("            arrPkg_AssignedRobot[iIdx] := 1;")
    lines.append("            arrPkg_State[iIdx] := 2; (* Assigned R1 *)")
    lines.append("            diR1_ActivePkg_ID := arrPkg_ID[iIdx];")
    lines.append("            iR1_RobotStatus := 1; (* Initiate track & pick *)")
    lines.append("        (* Check Robot 2 work window (X in [1800..2600]) *)")
    lines.append("        ELSIF (arrPkg_X_Entry[iIdx] >= 1800.0) AND (arrPkg_X_Entry[iIdx] <= 2550.0) AND (iR2_RobotStatus = 0) THEN")
    lines.append("            arrPkg_AssignedRobot[iIdx] := 2;")
    lines.append("            arrPkg_State[iIdx] := 3; (* Assigned R2 *)")
    lines.append("            diR2_ActivePkg_ID := arrPkg_ID[iIdx];")
    lines.append("            iR2_RobotStatus := 1;")
    lines.append("        (* Check Robot 3 work window (X in [3000..3800]) *)")
    lines.append("        ELSIF (arrPkg_X_Entry[iIdx] >= 3000.0) AND (arrPkg_X_Entry[iIdx] <= 3750.0) AND (iR3_RobotStatus = 0) THEN")
    lines.append("            arrPkg_AssignedRobot[iIdx] := 3;")
    lines.append("            arrPkg_State[iIdx] := 4; (* Assigned R3 *)")
    lines.append("            diR3_ActivePkg_ID := arrPkg_ID[iIdx];")
    lines.append("            iR3_RobotStatus := 1;")
    lines.append("        (* Check Robot 4 work window (X in [4200..5000]) *)")
    lines.append("        ELSIF (arrPkg_X_Entry[iIdx] >= 4200.0) AND (arrPkg_X_Entry[iIdx] <= 4950.0) AND (iR4_RobotStatus = 0) THEN")
    lines.append("            arrPkg_AssignedRobot[iIdx] := 4;")
    lines.append("            arrPkg_State[iIdx] := 5; (* Assigned R4 *)")
    lines.append("            diR4_ActivePkg_ID := arrPkg_ID[iIdx];")
    lines.append("            iR4_RobotStatus := 1;")
    lines.append("        END_IF;")
    lines.append("    END_IF;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 5.2 Work-Envelope Overlap Mutual Exclusion Tokens *)")
    lines.append("(* Zone R1-R2 Overlap: X_cell in [1450..1750 mm] *)")
    lines.append("IF (lrBase_X_R1 + lrR1_TCP_X > 1450.0) AND (iToken_Zone_R1_R2 = 0) THEN")
    lines.append("    iToken_Zone_R1_R2 := 1; (* Owned by R1 *)")
    lines.append("ELSIF (lrBase_X_R2 + lrR2_TCP_X < 1750.0) AND (iToken_Zone_R1_R2 = 0) THEN")
    lines.append("    iToken_Zone_R1_R2 := 2; (* Owned by R2 *)")
    lines.append("END_IF;")
    lines.append("IF (lrBase_X_R1 + lrR1_TCP_X <= 1450.0) AND (iToken_Zone_R1_R2 = 1) THEN iToken_Zone_R1_R2 := 0; END_IF;")
    lines.append("IF (lrBase_X_R2 + lrR2_TCP_X >= 1750.0) AND (iToken_Zone_R1_R2 = 2) THEN iToken_Zone_R1_R2 := 0; END_IF;")
    lines.append("")
    lines.append("(* Zone R2-R3 Overlap: X_cell in [2650..2950 mm] *)")
    lines.append("IF (lrBase_X_R2 + lrR2_TCP_X > 2650.0) AND (iToken_Zone_R2_R3 = 0) THEN")
    lines.append("    iToken_Zone_R2_R3 := 2;")
    lines.append("ELSIF (lrBase_X_R3 + lrR3_TCP_X < 2950.0) AND (iToken_Zone_R2_R3 = 0) THEN")
    lines.append("    iToken_Zone_R2_R3 := 3;")
    lines.append("END_IF;")
    lines.append("IF (lrBase_X_R2 + lrR2_TCP_X <= 2650.0) AND (iToken_Zone_R2_R3 = 2) THEN iToken_Zone_R2_R3 := 0; END_IF;")
    lines.append("IF (lrBase_X_R3 + lrR3_TCP_X >= 2950.0) AND (iToken_Zone_R2_R3 = 3) THEN iToken_Zone_R2_R3 := 0; END_IF;")
    lines.append("")
    lines.append("(* Zone R3-R4 Overlap: X_cell in [3850..4150 mm] *)")
    lines.append("IF (lrBase_X_R3 + lrR3_TCP_X > 3850.0) AND (iToken_Zone_R3_R4 = 0) THEN")
    lines.append("    iToken_Zone_R3_R4 := 3;")
    lines.append("ELSIF (lrBase_X_R4 + lrR4_TCP_X < 4150.0) AND (iToken_Zone_R3_R4 = 0) THEN")
    lines.append("    iToken_Zone_R3_R4 := 4;")
    lines.append("END_IF;")
    lines.append("IF (lrBase_X_R3 + lrR3_TCP_X <= 3850.0) AND (iToken_Zone_R3_R4 = 3) THEN iToken_Zone_R3_R4 := 0; END_IF;")
    lines.append("IF (lrBase_X_R4 + lrR4_TCP_X >= 4150.0) AND (iToken_Zone_R3_R4 = 4) THEN iToken_Zone_R3_R4 := 0; END_IF;")
    lines.append("")
    lines.append("dwRobotInterlockWord := 16#0000_0000;")
    lines.append("IF iToken_Zone_R1_R2 = 1 THEN dwRobotInterlockWord := dwRobotInterlockWord OR 16#0000_0001; END_IF;")
    lines.append("IF iToken_Zone_R1_R2 = 2 THEN dwRobotInterlockWord := dwRobotInterlockWord OR 16#0000_0002; END_IF;")
    lines.append("IF iToken_Zone_R2_R3 = 2 THEN dwRobotInterlockWord := dwRobotInterlockWord OR 16#0000_0004; END_IF;")
    lines.append("IF iToken_Zone_R2_R3 = 3 THEN dwRobotInterlockWord := dwRobotInterlockWord OR 16#0000_0008; END_IF;")
    lines.append("IF iToken_Zone_R3_R4 = 3 THEN dwRobotInterlockWord := dwRobotInterlockWord OR 16#0000_0010; END_IF;")
    lines.append("IF iToken_Zone_R3_R4 = 4 THEN dwRobotInterlockWord := dwRobotInterlockWord OR 16#0000_0020; END_IF;")
    lines.append("")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 6: DISCRETE STATE-SPACE PROPAGATION & RECEDING-HORIZON MPC S-CURVE TRAJECTORIES      *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* 6.1 State Vector Update from Hardware Feedback *)")
    lines.append("arrX[1] := (lrR1_MotorAngle1_deg - lrR1_CmdPos_M1_deg) * 0.01745329;")
    lines.append("arrX[2] := (lrR2_MotorAngle1_deg - lrR2_CmdPos_M1_deg) * 0.01745329;")
    lines.append("arrX[3] := (lrR3_MotorAngle1_deg - lrR3_CmdPos_M1_deg) * 0.01745329;")
    lines.append("arrX[4] := (lrR4_MotorAngle1_deg - lrR4_CmdPos_M1_deg) * 0.01745329;")
    lines.append("arrX[5] := lrR1_MotorVel1_deg_s * 0.01745329;")
    lines.append("arrX[6] := lrR2_MotorVel1_deg_s * 0.01745329;")
    lines.append("arrX[7] := lrR3_MotorVel1_deg_s * 0.01745329;")
    lines.append("arrX[8] := lrR4_MotorVel1_deg_s * 0.01745329;")
    lines.append("arrX[9] := lrR1_MotorCurrent1_A;")
    lines.append("arrX[10] := lrR2_MotorCurrent1_A;")
    lines.append("arrX[11] := lrR3_MotorCurrent1_A;")
    lines.append("arrX[12] := lrR4_MotorCurrent1_A;")
    lines.append("arrX[13] := lrVoted_R1_Vac_kPa;")
    lines.append("arrX[14] := lrVoted_R2_Vac_kPa;")
    lines.append("arrX[15] := lrVoted_R3_Vac_kPa;")
    lines.append("arrX[16] := lrVoted_R4_Vac_kPa;")
    lines.append("")
    lines.append("(* Control Inputs Vector compilation *)")
    lines.append("arrU[1] := lrR1_CmdTorqueFF_M1_Nm;")
    lines.append("arrU[2] := lrR2_CmdTorqueFF_M1_Nm;")
    lines.append("arrU[3] := lrR3_CmdTorqueFF_M1_Nm;")
    lines.append("arrU[4] := lrR4_CmdTorqueFF_M1_Nm;")
    lines.append("arrU[5] := SEL(bR1_VacuumValve_ON, 0.0, 1.0);")
    lines.append("arrU[6] := SEL(bR2_VacuumValve_ON, 0.0, 1.0);")
    lines.append("arrU[7] := SEL(bR3_VacuumValve_ON, 0.0, 1.0);")
    lines.append("arrU[8] := SEL(bR4_VacuumValve_ON, 0.0, 1.0);")
    lines.append("")
    lines.append("(* 6.2 State Propagation Equation: x_next = A * x + B * u *)")
    lines.append("FOR iIdx := 1 TO 16 DO")
    lines.append("    arrX_Next[iIdx] := 0.0;")
    lines.append("    FOR jIdx := 1 TO 16 DO")
    lines.append("        arrX_Next[iIdx] := arrX_Next[iIdx] + arrA[iIdx, jIdx] * arrX[jIdx];")
    lines.append("    END_FOR;")
    lines.append("    FOR jIdx := 1 TO 8 DO")
    lines.append("        arrX_Next[iIdx] := arrX_Next[iIdx] + arrB[iIdx, jIdx] * arrU[jIdx];")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 6.3 MPC Quadratic Cost Function Accumulator *)")
    lines.append("lrMPC_Cost_J := 0.0;")
    lines.append("FOR iIdx := 1 TO 16 DO")
    lines.append("    FOR jIdx := 1 TO 16 DO")
    lines.append("        lrMPC_Cost_J := lrMPC_Cost_J + (arrX[iIdx] - arrRef[iIdx]) * arrQ[iIdx, jIdx] * (arrX[jIdx] - arrRef[jIdx]);")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("FOR iIdx := 1 TO 8 DO")
    lines.append("    FOR jIdx := 1 TO 8 DO")
    lines.append("        lrMPC_Cost_J := lrMPC_Cost_J + arrU[iIdx] * arrR[iIdx, jIdx] * arrU[jIdx];")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 6.4 5th-Order Minimal-Jerk Trajectory Generators for Robots 1..4 *)")
    # Trajectory execution for R1..R4
    for r in range(1, 5):
        lines.append(f"(* Robot {r} 5th-Order Trajectory Engine *)")
        lines.append(f"IF lrR{r}_PhaseDuration_s > 0.001 THEN")
        lines.append(f"    lrR{r}_PhaseElapsed_s := lrR{r}_PhaseElapsed_s + lrCycleDeltaT_s;")
        lines.append(f"    lrTau := lrR{r}_PhaseElapsed_s / lrR{r}_PhaseDuration_s;")
        lines.append(f"    IF lrTau > 1.0 THEN lrTau := 1.0; END_IF;")
        lines.append(f"    lrPoly_s := (10.0 * lrTau * lrTau * lrTau) - (15.0 * lrTau * lrTau * lrTau * lrTau) + (6.0 * lrTau * lrTau * lrTau * lrTau * lrTau);")
        lines.append(f"    lrPoly_s_dot := ((30.0 * lrTau * lrTau) - (60.0 * lrTau * lrTau * lrTau) + (30.0 * lrTau * lrTau * lrTau * lrTau)) / lrR{r}_PhaseDuration_s;")
        lines.append(f"    lrR{r}_TCP_X := lrR{r}_P0_X + lrPoly_s * (lrR{r}_P1_X - lrR{r}_P0_X);")
        lines.append(f"    lrR{r}_TCP_Y := lrR{r}_P0_Y + lrPoly_s * (lrR{r}_P1_Y - lrR{r}_P0_Y);")
        lines.append(f"    lrR{r}_TCP_Z := lrR{r}_P0_Z + lrPoly_s * (lrR{r}_P1_Z - lrR{r}_P0_Z);")
        lines.append(f"    lrR{r}_TCP_Theta := lrR{r}_P0_Theta + lrPoly_s * (lrR{r}_P1_Theta - lrR{r}_P0_Theta);")
        lines.append(f"    lrR{r}_TCP_Vx := lrPoly_s_dot * (lrR{r}_P1_X - lrR{r}_P0_X);")
        lines.append(f"    lrR{r}_TCP_Vy := lrPoly_s_dot * (lrR{r}_P1_Y - lrR{r}_P0_Y);")
        lines.append(f"    lrR{r}_TCP_Vz := lrPoly_s_dot * (lrR{r}_P1_Z - lrR{r}_P0_Z);")
        lines.append(f"END_IF;")
        lines.append("")

    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 7: 12-STAGE OPERATIONAL FINITE STATE MACHINE (FSM)                                   *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("CASE iOperationalState OF")
    lines.append("    1: (* ST_CONVEYOR_HOMING_ACCEL: Calibrate encoder zeros & accelerate infeed belt *)")
    lines.append("        bCellRunning := FALSE;")
    lines.append("        bCellStandby := TRUE;")
    lines.append("        IF bMasterEnable AND bSafetyCircuitOK AND NOT bEmergencyStop THEN")
    lines.append("            bInfeedConveyorRunCmd := TRUE;")
    lines.append("            lrInfeedConveyorSpeed_mm_s := lrInfeedBeltTargetSpeed;")
    lines.append("            IF ABS(lrVoted_InfeedBelt_Speed - lrInfeedBeltTargetSpeed) < 30.0 THEN")
    lines.append("                iOperationalState := 2; (* Advance to vision check *)")
    lines.append("            END_IF;")
    lines.append("        ELSE")
    lines.append("            bInfeedConveyorRunCmd := FALSE;")
    lines.append("            lrInfeedConveyorSpeed_mm_s := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    2: (* ST_VISION_CALIBRATION_LIGHTING: Check strobe illumination & camera ready *)")
    lines.append("        IF bSafetyCircuitOK AND (lrMainAirPressure_bar > lrAlarm_AirPressure_LL) THEN")
    lines.append("            iOperationalState := 3; (* Advance to robot homing *)")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    3: (* ST_DELTA_KINEMATICS_HOMING: Synchronous homing of all 4 delta robots to standby *)")
    lines.append("        bR1_HoldingBrakeRelease := TRUE;")
    lines.append("        bR2_HoldingBrakeRelease := TRUE;")
    lines.append("        bR3_HoldingBrakeRelease := TRUE;")
    lines.append("        bR4_HoldingBrakeRelease := TRUE;")
    lines.append("        lrR1_P1_X := 0.0; lrR1_P1_Y := 0.0; lrR1_P1_Z := lrZ_Fly_Clearance; lrR1_P1_Theta := 0.0;")
    lines.append("        lrR2_P1_X := 0.0; lrR2_P1_Y := 0.0; lrR2_P1_Z := lrZ_Fly_Clearance; lrR2_P1_Theta := 0.0;")
    lines.append("        lrR3_P1_X := 0.0; lrR3_P1_Y := 0.0; lrR3_P1_Z := lrZ_Fly_Clearance; lrR3_P1_Theta := 0.0;")
    lines.append("        lrR4_P1_X := 0.0; lrR4_P1_Y := 0.0; lrR4_P1_Z := lrZ_Fly_Clearance; lrR4_P1_Theta := 0.0;")
    lines.append("        IF bR1_DriveReady AND bR2_DriveReady AND bR3_DriveReady AND bR4_DriveReady THEN")
    lines.append("            iOperationalState := 4; (* Advance to carton infeed *)")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    4: (* ST_CARTON_INFEED_VERIFY: Verify erected corrugated carton in pocket *)")
    lines.append("        IF bCartonPresentSensor AND bCartonFlapIntegritySensor THEN")
    lines.append("            bCartonHoldClampSolenoid := TRUE; (* Lock carton into pocket *)")
    lines.append("            bCartonConveyorRunCmd := FALSE;")
    lines.append("            iOperationalState := 5; (* Advance to tracking *)")
    lines.append("        ELSE")
    lines.append("            bCartonConveyorRunCmd := TRUE; (* Advance chain to index carton *)")
    lines.append("            bCartonHoldClampSolenoid := FALSE;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    5: (* ST_PACKAGE_COLLATION_TRACKING: Ingestion & conveyor synchronization *)")
    lines.append("        bCellRunning := TRUE;")
    lines.append("        bCellStandby := FALSE;")
    lines.append("        IF iQueueCount > 0 THEN")
    lines.append("            iOperationalState := 6; (* Advance to multi-robot pick and place *)")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    6: (* ST_MULTI_ROBOT_COORDINATED_PICK_PLACE: Active continuous collation *)")
    lines.append("        bCellRunning := TRUE;")
    lines.append("        (* Execution of pick-and-place subroutines for R1..R4 *)")
    lines.append("        IF iCaseCurrentUnits >= iCaseTargetUnits THEN")
    lines.append("            iOperationalState := 8; (* Carton full, advance to discharge *)")
    lines.append("        ELSIF bPurgeDumpEnable THEN")
    lines.append("            iOperationalState := 9; (* Divert to reject *)")
    lines.append("        ELSIF NOT bMasterEnable THEN")
    lines.append("            iOperationalState := 11; (* Controlled grind-out *)")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    7: (* ST_CASE_ARRAY_PATTERN_COLLATION: Update 4x6 grid matrix *)")
    lines.append("        IF iCaseCurrentUnits < iCaseTargetUnits THEN")
    lines.append("            iOperationalState := 6;")
    lines.append("        ELSE")
    lines.append("            iOperationalState := 8;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    8: (* ST_COMPLETED_CASE_INDEX_EGRESS: Release 24-unit case to outfeed *)")
    lines.append("        bCartonHoldClampSolenoid := FALSE;")
    lines.append("        bCartonDischargeGateCmd := TRUE;")
    lines.append("        bCartonConveyorRunCmd := TRUE;")
    lines.append("        diCompletedCaseCount := diCompletedCaseCount + 1;")
    lines.append("        (* Reset 4x6 grid *)")
    lines.append("        FOR iIdx := 1 TO 4 DO")
    lines.append("            FOR jIdx := 1 TO 6 DO")
    lines.append("                arrCaseGrid_Occupied[iIdx, jIdx] := FALSE;")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("        iCaseCurrentUnits := 0;")
    lines.append("        iOperationalState := 4; (* Index next empty carton *)")
    lines.append("")
    lines.append("    9: (* ST_REJECT_PURGE_DIVERTER: High-speed reject flipper actuation *)")
    lines.append("        bRejectPurgeDiverterCmd := TRUE;")
    lines.append("        diTotalRejectedCount := diTotalRejectedCount + 1;")
    lines.append("        IF NOT bPurgeDumpEnable THEN")
    lines.append("            bRejectPurgeDiverterCmd := FALSE;")
    lines.append("            iOperationalState := 6;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    10: (* ST_RECIPE_PACK_SHIFT: Dynamic recipe & pack pattern retooling *)")
    lines.append("        iCaseTargetUnits := iUnitsPerCaseRows * iUnitsPerCaseCols;")
    lines.append("        iOperationalState := 4;")
    lines.append("")
    lines.append("    11: (* ST_CONTROLLED_QUEUE_GRIND_OUT: Clear remaining FIFO packages *)")
    lines.append("        IF iQueueCount = 0 THEN")
    lines.append("            bInfeedConveyorRunCmd := FALSE;")
    lines.append("            bCellRunning := FALSE;")
    lines.append("            bCellStandby := TRUE;")
    lines.append("            iOperationalState := 1;")
    lines.append("        ELSE")
    lines.append("            iOperationalState := 6;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    12: (* ST_EMERGENCY_ESTOP_BRAKE_CLAMP: Safe torque off & pneumatic clamp *)")
    lines.append("        bInfeedConveyorRunCmd := FALSE;")
    lines.append("        bCartonConveyorRunCmd := FALSE;")
    lines.append("        bR1_HoldingBrakeRelease := FALSE;")
    lines.append("        bR2_HoldingBrakeRelease := FALSE;")
    lines.append("        bR3_HoldingBrakeRelease := FALSE;")
    lines.append("        bR4_HoldingBrakeRelease := FALSE;")
    lines.append("        bR1_VacuumValve_ON := FALSE; bR1_BlowOffValve_ON := FALSE;")
    lines.append("        bR2_VacuumValve_ON := FALSE; bR2_BlowOffValve_ON := FALSE;")
    lines.append("        bR3_VacuumValve_ON := FALSE; bR3_BlowOffValve_ON := FALSE;")
    lines.append("        bR4_VacuumValve_ON := FALSE; bR4_BlowOffValve_ON := FALSE;")
    lines.append("        bCellRunning := FALSE;")
    lines.append("        bCellFaulted := TRUE;")
    lines.append("        IF bResetFaults AND bSafetyCircuitOK AND NOT bEmergencyStop THEN")
    lines.append("            bCellFaulted := FALSE;")
    lines.append("            iOperationalState := 1;")
    lines.append("        END_IF;")
    lines.append("END_CASE;")
    lines.append("")
    lines.append("(* Emergency Stop Fast Interlock Override *)")
    lines.append("IF bEmergencyStop OR NOT bSafetyCircuitOK THEN")
    lines.append("    iOperationalState := 12;")
    lines.append("END_IF;")
