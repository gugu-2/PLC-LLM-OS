    lines.append("IF bR2_DriveFault THEN dwAlarmStatusWord_Critical := dwAlarmStatusWord_Critical OR 16#0000_0040; END_IF;")
    lines.append("IF bR3_DriveFault THEN dwAlarmStatusWord_Critical := dwAlarmStatusWord_Critical OR 16#0000_0080; END_IF;")
