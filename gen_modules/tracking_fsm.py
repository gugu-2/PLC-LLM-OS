    lines.append("(* Telemetry & KPI Computations *)")
    lines.append("IF diTotalInfeedCount > 0 THEN")
    lines.append("    lrCellEfficiency_OEE := (DINT_TO_LREAL(diTotalPackedCount) / DINT_TO_LREAL(diTotalInfeedCount)) * 100.0;")
    lines.append("ELSE")
    lines.append("    lrCellEfficiency_OEE := 100.0;")
    lines.append("END_IF;")
    lines.append("lrInstantThroughput_PPM := (lrVoted_InfeedBelt_Speed / 120.0) * 60.0; (* Approximate continuous unit feed *)")
    lines.append("")
    lines.append("(* Bit-Packed Master System Status Word *)")
    lines.append("dwSystemStatusWord := (INT_TO_DWORD(iOperationalState) AND 16#0000_00FF);")
