    lines.append("IF tScanDeltaTime_Sec > 0.001 THEN")
    lines.append("    rSlope_Derivative_nm_s :=")
    lines.append("        (2.0 * (rThicknessBuffer_Center[1] - rThicknessBuffer_Center[5]) +")
    lines.append("         1.0 * (rThicknessBuffer_Center[2] - rThicknessBuffer_Center[4])) / (10.0 * tScanDeltaTime_Sec);")
    lines.append("    (* Convert nm/s to Angstrom/min: RR = -slope * 10 [Angstrom/nm] * 60 [s/min] *)")
    lines.append("    rEstimatedRemovalRate_AngstromMin := -1.0 * rSlope_Derivative_nm_s * 600.0;")
    lines.append("    IF rEstimatedRemovalRate_AngstromMin < 0.0 THEN")
    lines.append("        rEstimatedRemovalRate_AngstromMin := 0.0;")
    lines.append("    END_IF;")
    lines.append("ELSE")
    lines.append("    rEstimatedRemovalRate_AngstromMin := 2800.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2nd Derivative Curvature: inflection point indicates barrier breakthrough *)")
    lines.append("rCurvature_2ndDeriv := (rThicknessBuffer_Center[1] - (2.0 * rThicknessBuffer_Center[3]) + rThicknessBuffer_Center[5]) /")
    lines.append("    EXPT(2.0 * tScanDeltaTime_Sec, 2.0);")
    lines.append("")
    lines.append("(* Within-Wafer Non-Uniformity (WIWNU) Across 7 Concentric Radial Zones *)")
    lines.append("rSum := 0.0;")
    lines.append("FOR iIdx := 1 TO 7 DO")
    lines.append("    rSum := rSum + rZoneThicknessArray[iIdx];")
    lines.append("END_FOR;")
    lines.append("rMeanThick := rSum / 7.0;")
    lines.append("")
    lines.append("rVariance := 0.0;")
    lines.append("FOR iIdx := 1 TO 7 DO")
    lines.append("    rVariance := rVariance + EXPT(rZoneThicknessArray[iIdx] - rMeanThick, 2.0);")
    lines.append("END_FOR;")
    lines.append("rStdDev := SQRT(rVariance / 7.0);")
    lines.append("")
    lines.append("IF rMeanThick > 0.1 THEN")
