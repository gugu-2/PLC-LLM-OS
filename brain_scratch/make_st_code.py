    lines.append("")
    lines.append("(* 2. Measurement State Correction: x_est = x_pred + L * Innovation *)")
    lines.append("FOR iRow := 1 TO 8 DO")
    lines.append("    rSum := 0.0;")
    lines.append("    FOR iCol := 1 TO 7 DO")
    lines.append("        rSum := rSum + (mL_Gain[iRow, iCol] * rInnovation[iCol]);")
    lines.append("    END_FOR;")
    lines.append("    xState_Est[iRow] := xState_Pred[iRow] + rSum;")
    lines.append("    xState[iRow] := xState_Est[iRow];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 3. Disturbance Vector Extraction *)")
    lines.append("dDisturbance[1] := rPlatenSpeed_Filt_rpm - 90.0;")
