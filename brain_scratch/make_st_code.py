    lines.append("    rCurrentFrictionCoeff_Mu := 0.35;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Dynamic Pad Micro-Asperity Glaze Saturation Index Tracking *)")
    lines.append("IF (iStateStep >= 40) AND (iStateStep <= 50) THEN")
