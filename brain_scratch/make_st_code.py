    lines.append("END_IF;")
    lines.append("")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 5: DISCRETE-TIME STATE-SPACE KALMAN STATE OBSERVER UPDATE                            *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* 1. Innovation Error: y_meas - C_d * x_pred *)")
    lines.append("FOR iRow := 1 TO 7 DO")
    lines.append("    (* Nominal target thickness trajectory difference in Angstroms: 1 nm = 10 Angstroms *)")
    lines.append("    rInnovation[iRow] := ((rZoneThicknessArray[iRow] - rTargetFinalThickness_nm) * 10.0) - xState_Pred[iRow];")
