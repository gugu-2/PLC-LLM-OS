    lines.append("            END_FOR;")
    lines.append("            xState_Pred[iRow] := rSum;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Compute Gradient: Grad_u = B_d^T * Q * (x_pred - x_ref) + R * u + S * (u - u_prev) *)")
