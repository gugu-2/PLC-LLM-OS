    lines.append("        rPadGlazingIndex_Pct := 0.0;")
    lines.append("    END_IF;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 4: IN-SITU SPECTROSCOPIC THICKNESS PROFILING & MULTI-ZONE ENDPOINT DETECTION (EPD)   *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* Shift 5-Point Thickness History Buffer for Savitzky-Golay Linear Regression Slope *)")
    lines.append("rThicknessBuffer_Center[5] := rThicknessBuffer_Center[4];")
    lines.append("rThicknessBuffer_Center[4] := rThicknessBuffer_Center[3];")
    lines.append("rThicknessBuffer_Center[3] := rThicknessBuffer_Center[2];")
    lines.append("rThicknessBuffer_Center[2] := rThicknessBuffer_Center[1];")
