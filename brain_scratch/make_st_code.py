    lines.append("                uControl[iCol] := rPressureMax_kPa - 20.0;")
    lines.append("            ELSIF uControl[iCol] < (rPressureMin_kPa - 20.0) THEN")
    lines.append("                uControl[iCol] := rPressureMin_kPa - 20.0;")
    lines.append("            END_IF;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* Store Previous Control Setpoint for Slew Penalty *)")
    lines.append("    FOR iCol := 1 TO 7 DO")
    lines.append("        uControl_Prev[iCol] := uControl[iCol];")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* Decouple Pneumatic Cross-Talk: P_valves = M_decouple * (P_baseline + uControl) *)")
    lines.append("    FOR iRow := 1 TO 7 DO")
    lines.append("        rSum := 0.0;")
    lines.append("        FOR iCol := 1 TO 7 DO")
    lines.append("            rTargetZoneP_kPa := 20.0 + uControl[iCol];")
