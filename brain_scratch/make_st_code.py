    lines.append("            rSum := 0.0;")
    lines.append("            FOR iRow := 1 TO 8 DO")
    lines.append("                rSum := rSum + (mB_d[iRow, iCol] * vQ_Diag[iRow] * (xState_Pred[iRow] - xState_Ref[iRow]));")
    lines.append("            END_FOR;")
    lines.append("            rSum := rSum + (vR_Diag[iCol] * uControl[iCol]) + (vS_Diag[iCol] * (uControl[iCol] - uControl_Prev[iCol]));")
    lines.append("")
    lines.append("            (* Edge Roll-Off Barrier Penalty: Penalize excessive pressure differential between Zone 6 and 7 *)")
