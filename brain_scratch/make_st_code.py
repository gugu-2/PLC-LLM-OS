    lines.append("ELSE")
    lines.append("    rWaferNonUniformity_WIWNU_Pct := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Spectroscopic EPD Trigger Detection *)")
    lines.append("rEndpointThreshold_nm := rTargetFinalThickness_nm + rAllowedOverpolish_nm;")
    lines.append("IF (rThickness_Filt_nm <= rEndpointThreshold_nm) AND (iStateStep == 40) THEN")
