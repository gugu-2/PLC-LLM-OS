    lines.append("                uControl[iCol] := uControl_Prev[iCol] + rMaxDeltaP_PerScan;")
    lines.append("            ELSIF (uControl[iCol] - uControl_Prev[iCol]) < -rMaxDeltaP_PerScan THEN")
    lines.append("                uControl[iCol] := uControl_Prev[iCol] - rMaxDeltaP_PerScan;")
    lines.append("            END_IF;")
    lines.append("            (* Enforce Absolute Pressure Bounds [rPressureMin_kPa - 20.0, rPressureMax_kPa - 20.0] *)")
