    lines.append("                rEdgeShearDeltaP_kPa := uControl[7] - uControl[6];")
    lines.append("                IF ABS(rEdgeShearDeltaP_kPa) > 4.5 THEN")
    lines.append("                    rSum := rSum + (rRhoEdgePenalty * (rEdgeShearDeltaP_kPa - 4.5));")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("            rGradJ[iCol] := rSum;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Gradient Descent Update with Projection into Feasible Pressure Bounds *)")
    lines.append("        FOR iCol := 1 TO 7 DO")
    lines.append("            uControl[iCol] := uControl[iCol] - (rAlphaStep * rGradJ[iCol]);")
