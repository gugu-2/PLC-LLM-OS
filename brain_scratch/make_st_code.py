    lines.append("        END_FOR;")
    lines.append("        uControl_Decoupled[iRow] := rSum;")
    lines.append("    END_FOR;")
    lines.append("ELSE")
    lines.append("    (* Default Idle / Zero Deviation Pressure Commands *)")
    lines.append("    FOR iCol := 1 TO 7 DO")
    lines.append("        uControl[iCol] := 0.0;")
    lines.append("        uControl_Prev[iCol] := 0.0;")
    lines.append("        uControl_Decoupled[iCol] := 0.0;")
    lines.append("    END_FOR;")
    lines.append("END_IF;")
    lines.append("")
