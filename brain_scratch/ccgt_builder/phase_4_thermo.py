"""
Phase 4: Thermodynamic and Chemical Auxiliary Control Loops for FB_PowerGen_CCGT_HRSG_SteamTurbineBypass
"""

def get_phase_4_thermo():
    lines = []
    def emit(s=""):
        lines.append(s)

    emit("(*")
    emit("    ========================================================================================================================")
    emit("    PHASE 4: THERMODYNAMIC, AERODYNAMIC & CHEMICAL AUXILIARY CONTROL LOOPS")
    emit("    ========================================================================================================================")
    emit("    - Sub-Phase 4A: Three-Element Boiler Drum Level Control with Dynamic Non-Linear Bubble Shrink-and-Swell Compensation")
    emit("    - Sub-Phase 4B: Water-to-Steam Desuperheating Spray Water Pressure & Enthalpy Cascade (Thermal Shock Protection)")
    emit("    - Sub-Phase 4C: Gas Turbine VIGV Airflow Optimization & DLN Wobbe Index Fuel Gas Splitter")
    emit("    - Sub-Phase 4D: Selective Catalytic Reduction (SCR) Ammonia Injection Grid (AIG) NOx Emission Trim & Slip Prevention")
    emit("    - Sub-Phase 4E: Steam Turbine Chest Metal Pre-Warming & Rotor Thermal Stress Evaluation")
    emit("    ========================================================================================================================")
    emit("*)")
    emit()
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* SUB-PHASE 4A: THREE-ELEMENT DRUM LEVEL CONTROL WITH SHRINK/SWELL BUBBLE COMPENSATION                                  *)")
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* Dynamic Helmholtz Formulation for Saturated Steam Temperature T_sat(P) in HP Drum *)")
    emit("IF rVotedHP_Pressure_bar > 1.0 THEN")
    emit("    rSteamSaturationTemp_degC := 179.91 + (14.502 * LN(rVotedHP_Pressure_bar)) + (0.125 * SQRT(rVotedHP_Pressure_bar));")
    emit("ELSE")
    emit("    rSteamSaturationTemp_degC := 100.0;")
    emit("END_IF;")
    emit()
    emit("(* Filtered Pressure Derivative for Bubble Shrink and Swell Compensation *)")
    emit("IF rDeltaTime_s > 0.001 THEN")
    emit("    rFiltereddP_dt_barps := rFiltereddP_dt_barps + ((rHP_Pressure_RoC_barps - rFiltereddP_dt_barps) * (rDeltaTime_s / rDrumBubbleTimeConst_s));")
    emit("END_IF;")
    emit()
    emit("(* Non-linear boiling bubble volume rate feedforward: rapid pressure drops create apparent level swell *)")
    emit("rDynamicSwellComp_kgs := -1.0 * rDrumSwellGain_kgs_per_barps * rFiltereddP_dt_barps;")
    emit()
    emit("(* Drum level error calculation *)")
    emit("rDrumLevelError_mm := rDrumLevelTarget_mm - rVotedHP_DrumLevel_mm;")
    emit()
    emit("(* Drum level integral accumulation with anti-windup clamping *)")
    emit("rDrumLevelIntError_mm := LIMIT(-800.0, rDrumLevelIntError_mm + (rDrumLevelError_mm * rDeltaTime_s), 800.0);")
    emit()
    emit("(* Three-Element Feedwater Demand: Steam Mass Flow + Level PI Trim - Swell Compensation *)")
    emit("rFeedwaterDemand_kgs := rHP_MainSteamFlow_kgs + (rDrumLevelKp * rDrumLevelError_mm) + ((rDrumLevelKp / rDrumLevelTi_s) * rDrumLevelIntError_mm) - rDynamicSwellComp_kgs;")
    emit("rFeedwaterDemand_kgs := LIMIT(0.0, rFeedwaterDemand_kgs, 135.0);")
    emit()
    emit("(* Feedwater Control Valve Positioning Command *)")
    emit("rHP_FeedwaterControlValveCmd_pct := LIMIT(0.0, (rFeedwaterDemand_kgs / rFeedwaterValveCv), 100.0);")
    emit()
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* SUB-PHASE 4B: WATER-TO-STEAM DESUPERHEATING SPRAY CASCADE (THERMAL SHOCK PROTECTION)                                  *)")
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* Target desuperheated steam temperature maintains safe superheat margin (+28.0 deg C) above saturation *)")
    emit("rTargetDesuperheatTemp_degC := rSteamSaturationTemp_degC + rSuperheatMargin_degC;")
    emit()
    emit("(* Enthalpy-based feedforward spray water flow calculation *)")
    emit("(* First-principles heat balance: W_spray = W_steam * (h_in - h_target) / (h_target - h_spray) *)")
    emit("IF (rTargetSteamEnthalpy_kJkg - rSprayWaterEnthalpy_kJkg) > 10.0 THEN")
    emit("    rCalculatedSprayDemand_kgs := rHP_MainSteamFlow_kgs * ((rHP_InletSteamEnthalpy_kJkg - rTargetSteamEnthalpy_kJkg) / (rTargetSteamEnthalpy_kJkg - rSprayWaterEnthalpy_kJkg));")
    emit("    rCalculatedSprayDemand_kgs := LIMIT(0.0, rCalculatedSprayDemand_kgs, 32.0);")
    emit("ELSE")
    emit("    rCalculatedSprayDemand_kgs := 0.0;")
    emit("END_IF;")
    emit()
    emit("(* Feedback temperature trim loop *)")
    emit("rSprayTempError_degC := rVotedHP_BypassTemp_degC - rTargetDesuperheatTemp_degC;")
    emit("rSprayTempIntError_degC := LIMIT(-500.0, rSprayTempIntError_degC + (rSprayTempError_degC * rDeltaTime_s), 500.0);")
    emit()
    emit("(* Total unconstrained spray valve demand *)")
    emit("rHP_DesuperheatSprayValveCmd_pct := (rCalculatedSprayDemand_kgs * 3.125) + (rSprayTempKp * rSprayTempError_degC) + ((rSprayTempKp / rSprayTempTi_s) * rSprayTempIntError_degC);")
    emit("rHP_DesuperheatSprayValveCmd_pct := LIMIT(0.0, rHP_DesuperheatSprayValveCmd_pct, 100.0);")
    emit()
    emit("(* Anti-Thermal Shock Slew Rate Limiter on Spray Valve *)")
    emit("IF (rHP_DesuperheatSprayValveCmd_pct - rCurrentSprayValveCmd_pct) > (rSprayValveMaxSlewRate_pctps * rDeltaTime_s) THEN")
    emit("    rCurrentSprayValveCmd_pct := rCurrentSprayValveCmd_pct + (rSprayValveMaxSlewRate_pctps * rDeltaTime_s);")
    emit("ELSIF (rCurrentSprayValveCmd_pct - rHP_DesuperheatSprayValveCmd_pct) > (rSprayValveMaxSlewRate_pctps * rDeltaTime_s) THEN")
    emit("    rCurrentSprayValveCmd_pct := rCurrentSprayValveCmd_pct - (rSprayValveMaxSlewRate_pctps * rDeltaTime_s);")
    emit("ELSE")
    emit("    rCurrentSprayValveCmd_pct := rHP_DesuperheatSprayValveCmd_pct;")
    emit("END_IF;")
    emit("rHP_DesuperheatSprayValveCmd_pct := rCurrentSprayValveCmd_pct;")
    emit()
    emit("(* IP Desuperheater Spray proportional to IP steam flow *)")
    emit("rIP_DesuperheatSprayValveCmd_pct := LIMIT(0.0, (rIP_SteamFlow_kgs * 0.75), 100.0);")
    emit()
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* SUB-PHASE 4C: GAS TURBINE VIGV AIRFLOW OPTIMIZATION & DLN WOBBE INDEX SPLITTER                                        *)")
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* Fuel Gas Wobbe Index dynamic normalization factor: K_wobbe = sqrt(WI_nom / WI_meas) *)")
    emit("IF rFuelGasWobbeIndex_MJm3 > 25.0 THEN")
    emit("    rWobbeCorrectionFactor := SQRT(rNominalWobbeIndex_MJm3 / rFuelGasWobbeIndex_MJm3);")
    emit("ELSE")
    emit("    rWobbeCorrectionFactor := 1.000;")
    emit("END_IF;")
    emit()
    emit("(* Dry Low NOx Combustor Fuel Gas Premix-to-Pilot Split Schedule *)")
    emit("IF rGeneratorActivePower_MW > 220.0 THEN")
    emit("    (* High Base Load: Pure Premix Mode to suppress flame temperature and NOx *)")
    emit("    rDLN_PremixSplitTarget_pct := 84.5 * rWobbeCorrectionFactor;")
    emit("    rDLN_PilotSplitTarget_pct := 100.0 - rDLN_PremixSplitTarget_pct;")
    emit("ELSIF rGeneratorActivePower_MW > 100.0 THEN")
    emit("    (* Intermediate Part Load: Transition Premix Mode *)")
    emit("    rDLN_PremixSplitTarget_pct := (65.0 + ((rGeneratorActivePower_MW - 100.0) / 120.0 * 19.5)) * rWobbeCorrectionFactor;")
    emit("    rDLN_PilotSplitTarget_pct := 100.0 - rDLN_PremixSplitTarget_pct;")
    emit("ELSE")
    emit("    (* Low Load / Warming: Pilot Diffusion Mode to prevent lean blowout (LBO) *)")
    emit("    rDLN_PremixSplitTarget_pct := 45.0 * rWobbeCorrectionFactor;")
    emit("    rDLN_PilotSplitTarget_pct := 100.0 - rDLN_PremixSplitTarget_pct;")
    emit("END_IF;")
    emit("rDLN_FuelGasSplitRatio_pct := LIMIT(35.0, rDLN_PremixSplitTarget_pct, 92.0);")
    emit()
    emit("(* Variable Inlet Guide Vane (VIGV) Airflow Optimization Schedule *)")
    emit("(* Modulates guide vanes to maintain exhaust TAT at 612 deg C for maximum HRSG superheater heat recovery *)")
    emit("IF rGeneratorActivePower_MW >= 290.0 THEN")
    emit("    rVIGV_ModulatedAngle_deg := rVIGV_BaseAngle_deg; (* 32.0 deg base load *)")
    emit("ELSIF rGeneratorActivePower_MW >= 60.0 THEN")
    emit("    (* Exhaust temperature holding ramp *)")
    emit("    rVIGV_ModulatedAngle_deg := rVIGV_IdleAngle_deg + ((rGeneratorActivePower_MW - 60.0) / (290.0 - 60.0) * (rVIGV_BaseAngle_deg - rVIGV_IdleAngle_deg));")
    emit("    (* Trim angle based on actual TAT exhaust deviation *)")
    emit("    IF rGT_ExhaustTemp_TAT_degC < (rTargetTAT_degC - 5.0) THEN")
    emit("        rVIGV_ModulatedAngle_deg := rVIGV_ModulatedAngle_deg - 1.5; (* Close slightly to raise exhaust temp *)")
    emit("    ELSIF rGT_ExhaustTemp_TAT_degC > (rTargetTAT_degC + 5.0) THEN")
    emit("        rVIGV_ModulatedAngle_deg := rVIGV_ModulatedAngle_deg + 1.5; (* Open slightly to protect exhaust duct *)")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rVIGV_ModulatedAngle_deg := rVIGV_IdleAngle_deg; (* 0.0 deg idle *)")
    emit("END_IF;")
    emit("rGT_VIGV_PositionCmd_deg := LIMIT(0.0, rVIGV_ModulatedAngle_deg, 32.0);")
    emit()
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* SUB-PHASE 4D: SELECTIVE CATALYTIC REDUCTION (SCR) AMMONIA INJECTION GRID (AIG) TRIM                                  *)")
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* Flue Gas NOx mass flow calculation: m_dot_NOx = W_flue * [NOx]_in * 10^-6 * (MW_NO / MW_flue) *)")
    emit("(* Ammonia stoichiometric requirement: m_dot_NH3 = m_dot_NOx * (MW_NH3 / MW_NO) * Molar_Ratio *)")
    emit("IF (rGT_ExhaustMassFlow_kgs > 50.0) AND (rSCR_InletNOx_ppm > 1.0) AND (rSCR_BedTemp_degC > 280.0) THEN")
    emit("    rSCR_AmmoniaInjectionFlowCmd_kgh := rGT_ExhaustMassFlow_kgs * rSCR_InletNOx_ppm * 0.000001 * (rMW_NH3 / 28.97) * rNOx_MolarRatio_NH3_NO * 3600.0;")
    emit("    (* CEMS Stack NOx closed-loop feedback trim *)")
    emit("    rSCR_IntError_ppm := LIMIT(-50.0, rSCR_IntError_ppm + ((rSCR_StackNOx_ppm - rTargetStackNOx_ppm) * rDeltaTime_s), 50.0);")
    emit("    rSCR_FeedbackTrim_kgh := (rSCR_Kp * (rSCR_StackNOx_ppm - rTargetStackNOx_ppm)) + ((rSCR_Kp / rSCR_Ti_s) * rSCR_IntError_ppm);")
    emit("    rSCR_AmmoniaInjectionFlowCmd_kgh := rSCR_AmmoniaInjectionFlowCmd_kgh + rSCR_FeedbackTrim_kgh;")
    emit("    (* Ammonia slip constraint: if slip approaches 2.0 ppm, throttle injection to prevent salt deposition *)")
    emit("    IF rSCR_AmmoniaSlip_ppm > 1.80 THEN")
    emit("        rSCR_AmmoniaInjectionFlowCmd_kgh := rSCR_AmmoniaInjectionFlowCmd_kgh * 0.85;")
    emit("        bAlarm_AmmoniaSlip_H := TRUE;")
    emit("    ELSE")
    emit("        bAlarm_AmmoniaSlip_H := FALSE;")
    emit("    END_IF;")
    emit("    rSCR_AmmoniaInjectionFlowCmd_kgh := LIMIT(0.0, rSCR_AmmoniaInjectionFlowCmd_kgh, 420.0);")
    emit("    (* Calculate real-time SCR conversion efficiency *)")
    emit("    IF rSCR_InletNOx_ppm > 5.0 THEN")
    emit("        rSCR_CalculatedEfficiency_pct := ((rSCR_InletNOx_ppm - rSCR_StackNOx_ppm) / rSCR_InletNOx_ppm) * 100.0;")
    emit("    ELSE")
    emit("        rSCR_CalculatedEfficiency_pct := 95.0;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rSCR_AmmoniaInjectionFlowCmd_kgh := 0.0;")
    emit("    rSCR_CalculatedEfficiency_pct := 0.0;")
    emit("END_IF;")
    emit()
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("(* SUB-PHASE 4E: STEAM TURBINE CHEST METAL PRE-WARMING & ROTOR THERMAL STRESS EVALUATION                                 *)")
    emit("(* --------------------------------------------------------------------------------------------------------------------- *)")
    emit("rSteamToChestTempDiff_degC := ABS(rVotedHP_BypassTemp_degC - rTurbineChestMetalTemp_degC);")
    emit("IF rAllowableRotorStress_MPa > 10.0 THEN")
    emit("    rCalculatedThermalStressMargin_pct := LIMIT(0.0, ((rAllowableRotorStress_MPa - ABS(rTurbineRotorStress_MPa)) / rAllowableRotorStress_MPa) * 100.0, 100.0);")
    emit("ELSE")
    emit("    rCalculatedThermalStressMargin_pct := 0.0;")
    emit("END_IF;")
    emit()
    emit("(* Rolling one-minute chest warming rate calculation *)")
    emit("rChestWarmRateTimer_s := rChestWarmRateTimer_s + rDeltaTime_s;")
    emit("IF rChestWarmRateTimer_s >= 60.0 THEN")
    emit("    rCalculatedChestWarmRate_degCpm := (rTurbineChestMetalTemp_degC - rChestTempPrev_degC);")
    emit("    rChestTempPrev_degC := rTurbineChestMetalTemp_degC;")
    emit("    rChestWarmRateTimer_s := 0.0;")
    emit("END_IF;")
    emit()
    emit("(* Permissive logic for steam turbine roll and synchronization *)")
    emit("bTurbinePermissiveToRoll := (rTurbineChestMetalTemp_degC > 185.0) AND (rCalculatedThermalStressMargin_pct > 30.0) AND bTurningGearEngaged AND bCondenserVacuumPermissive;")
    emit("bTurbinePermissiveToSync := (rTurbineSpeed_rpm > 2985.0) AND (rCalculatedThermalStressMargin_pct > 45.0) AND (rSteamToChestTempDiff_degC < 55.0);")
    emit()
    return "\n".join(lines)
