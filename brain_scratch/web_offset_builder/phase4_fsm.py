# -*- coding: utf-8 -*-
"""
Module: phase4_fsm.py
Generates Phase 4: 12-Stage Deterministic Production Finite State Machine (FSM).
Provides complete state transitions, state entry/exit actions, interlocks,
timer management, actuator overrides, and status reporting.
"""

def generate_phase4_fsm():
    s = []
    s.append("(* ================================================================================================= *)")
    s.append("(* PHASE 4: 12-STAGE DETERMINISTIC PRODUCTION FINITE STATE MACHINE (FSM)                             *)")
    s.append("(* ================================================================================================= *)")
    s.append("")
    s.append("(* Update FSM Elapsed Step Timer *)")
    s.append("IF n_FSM_Current_State = n_FSM_Next_State THEN")
    s.append("    r_FSM_State_Timer_Sec := r_FSM_State_Timer_Sec + T_SAMPLE_SEC;")
    s.append("    b_FSM_State_First_Scan := FALSE;")
    s.append("ELSE")
    s.append("    n_FSM_Current_State := n_FSM_Next_State;")
    s.append("    r_FSM_State_Timer_Sec := 0.0;")
    s.append("    b_FSM_State_First_Scan := TRUE;")
    s.append("END_IF;")
    s.append("")
    s.append("w_FSM_State_Active := n_FSM_Current_State;")
    s.append("")
    s.append("(* Check Global Emergency Trip Conditions *)")
    s.append("IF NOT b_Emergency_Stop_Hardwire THEN")
    s.append("    n_FSM_Next_State := c_STATE_EMERGENCY_ESTOP_BLANKET_LIFT;")
    s.append("ELSIF b_Web_Break_Trip_Latched THEN")
    s.append("    n_FSM_Next_State := c_STATE_WEB_SEVER_AND_CLAMP_CLEARED;")
    s.append("END_IF;")
    s.append("")
    s.append("CASE n_FSM_Current_State OF")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 0: PRESS_STANDBY_INCHING                                                            *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_PRESS_STANDBY_INCHING:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := TRUE; (* Blankets disengaged *)")
    s.append("        b_Web_Severing_Clamp_Fire_Fast  := FALSE;")
    s.append("        b_Splicer_Paster_Brush_Fire_Cmd := FALSE;")
    s.append("        b_Splicer_Cutoff_Knife_Fire_Cmd := FALSE;")
    s.append("        b_Dryer_Burner_Emergency_Trip   := FALSE;")
    s.append("        r_Infeed_Dancer_Pneumatic_Cmd   := 1.0;  (* Low park pressure [bar] *)")
    s.append("        r_Dryer_Zone1_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_Zone2_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_Zone3_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_Zone4_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_FreshAir_Purge_Damper_Cmd := 20.0;")
    s.append("        r_Chill_Water_Mod_Valve_Cmd     := 15.0;")
    s.append("        r_Cyan_Lateral_Plate_Screw_Cmd  := 0.0;")
    s.append("        r_Magenta_Lateral_Plate_Screw_Cmd := 0.0;")
    s.append("        r_Yellow_Lateral_Plate_Screw_Cmd  := 0.0;")
    s.append("        r_Black_Lateral_Plate_Screw_Cmd   := 0.0;")
    s.append("        IF b_Press_Master_Run_Cmd AND b_ELS_Speed_TMR_Healthy THEN")
    s.append("            n_FSM_Next_State := c_STATE_INK_WATER_PRE_EMULSIFY;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 1: INK_WATER_PRE_EMULSIFY                                                           *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_INK_WATER_PRE_EMULSIFY:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := TRUE;")
    s.append("        r_Dampening_Circ_Pump_Speed_Cmd := 1450.0; (* Recirculate chilled fountain fluid *)")
    s.append("        r_Cyan_Dampening_Brush_Speed_Cmd := 580.0;")
    s.append("        r_Magenta_Damp_Brush_Speed_Cmd  := 580.0;")
    s.append("        r_Yellow_Damp_Brush_Speed_Cmd   := 580.0;")
    s.append("        r_Black_Damp_Brush_Speed_Cmd    := 580.0;")
    s.append("        r_Infeed_Dancer_Pneumatic_Cmd   := 1.8;")
    s.append("        (* Establish emulsion boundary layer for 6.0 seconds *)")
    s.append("        IF r_FSM_State_Timer_Sec >= 6.0 THEN")
    s.append("            IF b_Damp_Cond_TMR_Healthy AND (r_Damp_Conductivity_Voted >= 1000.0) THEN")
    s.append("                n_FSM_Next_State := c_STATE_WEB_THREADING_LOW_SPEED;")
    s.append("            END_IF;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 2: WEB_THREADING_LOW_SPEED                                                          *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_WEB_THREADING_LOW_SPEED:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := TRUE;")
    s.append("        r_Infeed_Dancer_Pneumatic_Cmd   := 2.2;")
    s.append("        r_Infeed_Nip_Speed_Trim_Cmd     := 0.0;")
    s.append("        r_Chill_Roll_Master_Speed_Trim  := 0.0;")
    s.append("        (* Verify web presence through print towers and dryer *)")
    s.append("        IF r_FSM_State_Timer_Sec >= 4.0 THEN")
    s.append("            IF (NOT b_Web_Break_Tower_Voted) AND (NOT b_Web_Break_Dryer_Voted) THEN")
    s.append("                n_FSM_Next_State := c_STATE_ELS_VIRTUAL_LINE_SHAFT_LOCK;")
    s.append("            END_IF;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 3: ELS_VIRTUAL_LINE_SHAFT_LOCK                                                      *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_ELS_VIRTUAL_LINE_SHAFT_LOCK:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := TRUE;")
    s.append("        r_Cyan_Circ_Phase_Trim_Cmd      := 0.0;")
    s.append("        r_Magenta_Circ_Phase_Trim_Cmd   := 0.0;")
    s.append("        r_Yellow_Circ_Phase_Trim_Cmd    := 0.0;")
    s.append("        r_Black_Circ_Phase_Trim_Cmd     := 0.0;")
    s.append("        (* Confirm multi-axis electronic line shaft phase lock within 0.05 mrad *)")
    s.append("        IF r_FSM_State_Timer_Sec >= 3.0 THEN")
    s.append("            n_FSM_Next_State := c_STATE_DRYER_AND_CHILL_PREHEAT_RUN;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 4: DRYER_AND_CHILL_PREHEAT_RUN                                                      *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_DRYER_AND_CHILL_PREHEAT_RUN:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := TRUE;")
    s.append("        (* Warm-up burners in staggered sequence *)")
    s.append("        r_Dryer_Zone1_Gas_Valve_Cmd := 35.0;")
    s.append("        r_Dryer_Zone2_Gas_Valve_Cmd := 45.0;")
    s.append("        r_Dryer_Zone3_Gas_Valve_Cmd := 45.0;")
    s.append("        r_Dryer_Zone4_Gas_Valve_Cmd := 30.0;")
    s.append("        r_Dryer_Recirc_Damper_Pos_Cmd := 50.0;")
    s.append("        r_Dryer_FreshAir_Purge_Damper_Cmd := 30.0;")
    s.append("        r_Chill_Water_Mod_Valve_Cmd := 40.0;")
    s.append("        (* Once all zones reach operational threshold >= 220 deg C, start ramp *)")
    s.append("        IF (r_Dryer_Z1_Temp_Voted >= 210.0) AND (r_Dryer_Z2_Temp_Voted >= 240.0) AND")
    s.append("           (r_Dryer_Z3_Temp_Voted >= 240.0) AND (r_Dryer_Z4_Temp_Voted >= 210.0) THEN")
    s.append("            n_FSM_Next_State := c_STATE_SPEED_RAMP_TO_50K_CPH;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 5: SPEED_RAMP_TO_50K_CPH                                                            *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_SPEED_RAMP_TO_50K_CPH:")
    s.append("        r_Infeed_Dancer_Pneumatic_Cmd := 3.5; (* Running counter-pressure [bar] *)")
    s.append("        (* Engage printing blankets once line speed exceeds 3.5 m/s *)")
    s.append("        IF r_ELS_Speed_Voted >= 3.5 THEN")
    s.append("            b_Blanket_Cylinder_ThrowOff_Cmd := FALSE; (* On Impression! *)")
    s.append("        ELSE")
    s.append("            b_Blanket_Cylinder_ThrowOff_Cmd := TRUE;")
    s.append("        END_IF;")
    s.append("        (* Transition to auto register once approaching production speed 14.5 m/s *)")
    s.append("        IF (r_ELS_Speed_Voted >= 14.5) AND (NOT b_Blanket_Cylinder_ThrowOff_Cmd) THEN")
    s.append("            n_FSM_Next_State := c_STATE_AUTO_REGISTER_CLOSED_LOOP;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 6: AUTO_REGISTER_CLOSED_LOOP                                                        *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_AUTO_REGISTER_CLOSED_LOOP:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := FALSE; (* Solid impression *)")
    s.append("        (* Apply decoupled lateral motor screw adjustments *)")
    s.append("        r_Cyan_Lateral_Plate_Screw_Cmd    := -r_Cyan_Lat_Dev_Voted + r_Cyan_Calculated_FanOut_MM;")
    s.append("        r_Magenta_Lateral_Plate_Screw_Cmd := -r_Magenta_Lat_Dev_Voted + r_Magenta_Calculated_FanOut_MM;")
    s.append("        r_Yellow_Lateral_Plate_Screw_Cmd  := -r_Yellow_Lat_Dev_Voted + r_Yellow_Calculated_FanOut_MM;")
    s.append("        r_Black_Lateral_Plate_Screw_Cmd   := -r_Black_Lat_Dev_Voted + r_Black_Calculated_FanOut_MM;")
    s.append("        (* Check Flying Splicer trigger *)")
    s.append("        IF b_Splice_Sequence_Initiate OR (r_Splicer_Expiring_Roll_Dia_MM <= 115.0) THEN")
    s.append("            n_FSM_Next_State := c_STATE_CONTINUOUS_FLYING_SPLICE;")
    s.append("        ELSIF NOT b_Press_Master_Run_Cmd THEN")
    s.append("            n_FSM_Next_State := c_STATE_CONTROLLED_DECEL_AND_WASH;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 7: CONTINUOUS_FLYING_SPLICE                                                         *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_CONTINUOUS_FLYING_SPLICE:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := FALSE;")
    s.append("        r_Splicer_Predrive_Motor_Cmd    := r_Splicer_New_Roll_Target_RPM;")
    s.append("        (* Substep sequence based on expiring roll diameter *)")
    s.append("        IF (r_Splicer_Surface_Speed_Error <= 0.025) AND (r_Splicer_Expiring_Roll_Dia_MM <= 92.0) THEN")
    s.append("            b_Splicer_Ready_For_Paster := TRUE;")
    s.append("        END_IF;")
    s.append("        IF b_Splicer_Ready_For_Paster AND (r_Splicer_Expiring_Roll_Dia_MM <= 86.0) THEN")
    s.append("            b_Splicer_Paster_Brush_Fire_Cmd := TRUE; (* Paster brush fires *)")
    s.append("            b_Splicer_Paster_Contact_Made   := TRUE;")
    s.append("        END_IF;")
    s.append("        IF b_Splicer_Paster_Contact_Made AND (r_FSM_State_Timer_Sec >= 0.015) THEN")
    s.append("            b_Splicer_Cutoff_Knife_Fire_Cmd := TRUE; (* Severing knife fires *)")
    s.append("            b_Splicer_Sever_Complete        := TRUE;")
    s.append("        END_IF;")
    s.append("        (* Complete splice sequence after tension stabilization *)")
    s.append("        IF b_Splicer_Sever_Complete AND (r_FSM_State_Timer_Sec >= 1.5) THEN")
    s.append("            b_Splicer_Paster_Brush_Fire_Cmd := FALSE;")
    s.append("            b_Splicer_Cutoff_Knife_Fire_Cmd := FALSE;")
    s.append("            b_Splicer_Ready_For_Paster      := FALSE;")
    s.append("            b_Splicer_Paster_Contact_Made   := FALSE;")
    s.append("            b_Splicer_Sever_Complete        := FALSE;")
    s.append("            r_Splicer_Expiring_Roll_Dia_MM  := 1270.0; (* Reset to new roll diameter *)")
    s.append("            n_FSM_Next_State := c_STATE_AUTO_REGISTER_CLOSED_LOOP;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 8: INK_DENSITY_MICRO_REGULATE                                                       *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_INK_DENSITY_MICRO_REGULATE:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := FALSE;")
    s.append("        IF r_FSM_State_Timer_Sec >= 3.0 THEN")
    s.append("            n_FSM_Next_State := c_STATE_AUTO_REGISTER_CLOSED_LOOP;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 9: CONTROLLED_DECEL_AND_WASH                                                        *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_CONTROLLED_DECEL_AND_WASH:")
    s.append("        IF r_ELS_Speed_Voted <= 3.0 THEN")
    s.append("            b_Blanket_Cylinder_ThrowOff_Cmd := TRUE; (* Throw off blankets *)")
    s.append("        END_IF;")
    s.append("        r_Dryer_Zone1_Gas_Valve_Cmd := 0.0;")
    s.append("        r_Dryer_Zone2_Gas_Valve_Cmd := 0.0;")
    s.append("        r_Dryer_Zone3_Gas_Valve_Cmd := 0.0;")
    s.append("        r_Dryer_Zone4_Gas_Valve_Cmd := 0.0;")
    s.append("        r_Dryer_FreshAir_Purge_Damper_Cmd := 80.0; (* High fresh air purge *)")
    s.append("        IF (r_ELS_Speed_Voted <= 0.2) AND (r_FSM_State_Timer_Sec >= 8.0) THEN")
    s.append("            n_FSM_Next_State := c_STATE_PRESS_STANDBY_INCHING;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 10: WEB_SEVER_AND_CLAMP_CLEARED                                                     *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_WEB_SEVER_AND_CLAMP_CLEARED:")
    s.append("        b_Web_Severing_Clamp_Fire_Fast  := TRUE;  (* Fast web sever & clamp active *)")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := TRUE;  (* Rapid lift *)")
    s.append("        b_Dryer_Burner_Emergency_Trip   := TRUE;  (* Extinguish burners *)")
    s.append("        r_Dryer_FreshAir_Purge_Damper_Cmd := 100.0; (* 100% full purge *)")
    s.append("        r_Infeed_Nip_Speed_Trim_Cmd     := 0.0;")
    s.append("        r_Chill_Roll_Master_Speed_Trim  := 0.0;")
    s.append("        IF b_Alarm_Master_Reset_PB THEN")
    s.append("            b_Web_Break_Trip_Latched       := FALSE;")
    s.append("            b_Web_Severing_Clamp_Fire_Fast := FALSE;")
    s.append("            n_FSM_Next_State := c_STATE_PRESS_STANDBY_INCHING;")
    s.append("        END_IF;")
    s.append("")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    (* STATE 11: EMERGENCY_ESTOP_BLANKET_LIFT                                                    *)")
    s.append("    (* ----------------------------------------------------------------------------------------- *)")
    s.append("    c_STATE_EMERGENCY_ESTOP_BLANKET_LIFT:")
    s.append("        b_Blanket_Cylinder_ThrowOff_Cmd := TRUE;")
    s.append("        b_Dryer_Burner_Emergency_Trip   := TRUE;")
    s.append("        b_Web_Severing_Clamp_Fire_Fast  := TRUE;")
    s.append("        r_Dryer_Zone1_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_Zone2_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_Zone3_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_Zone4_Gas_Valve_Cmd     := 0.0;")
    s.append("        r_Dryer_FreshAir_Purge_Damper_Cmd := 100.0;")
    s.append("        r_Infeed_Nip_Speed_Trim_Cmd     := 0.0;")
    s.append("        r_Chill_Roll_Master_Speed_Trim  := 0.0;")
    s.append("        IF b_Emergency_Stop_Hardwire AND b_Alarm_Master_Reset_PB THEN")
    s.append("            b_Dryer_Burner_Emergency_Trip := FALSE;")
    s.append("            b_Web_Severing_Clamp_Fire_Fast := FALSE;")
    s.append("            n_FSM_Next_State := c_STATE_PRESS_STANDBY_INCHING;")
    s.append("        END_IF;")
    s.append("")
    s.append("ELSE")
    s.append("    n_FSM_Next_State := c_STATE_PRESS_STANDBY_INCHING;")
    s.append("END_CASE;")
    s.append("")

    return "\n".join(s)
