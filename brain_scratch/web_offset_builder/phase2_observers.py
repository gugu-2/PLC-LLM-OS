# -*- coding: utf-8 -*-
"""
Module: phase2_observers.py
Generates Phase 2: Cyber-Physical Observers & Multi-Span Web Dynamics.
Calculates Kelvin-Voigt dynamic paper modulus, multi-span strain and tension propagation,
4-color register decoupling, brush dampening emulsion dynamics, dryer solvent LEL mass balance,
chill stand thermal shock conditioning, and flying splicer kinematics.
"""

def generate_phase2_observers():
    s = []
    s.append("(* ================================================================================================= *)")
    s.append("(* PHASE 2: CYBER-PHYSICAL OBSERVERS & MULTI-SPAN WEB DYNAMICS                                       *)")
    s.append("(* ================================================================================================= *)")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 1. Viscoelastic Paper Web Strain Propagation & Kelvin-Voigt Dynamic Modulus                      *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* Cross-sectional web area A_cs [m2] = Caliper [m] * Width [m] *)")
    s.append("r_Web_Calculated_CrossSection := (r_Paper_Caliper_Microns * 0.000001) * r_Web_Width_Meters;")
    s.append("IF r_Web_Calculated_CrossSection < 0.00001 THEN")
    s.append("    r_Web_Calculated_CrossSection := 0.0000627; (* Safe fallback for 65 um x 0.965 m *)")
    s.append("END_IF;")
    s.append("")
    s.append("(* Effective temperature and moisture along web path *)")
    s.append("r_Temp_Val_1 := (r_Dryer_Z1_Temp_Voted + r_Dryer_Z2_Temp_Voted + r_Dryer_Z3_Temp_Voted + r_Dryer_Z4_Temp_Voted) * 0.25;")
    s.append("r_Web_Temperature_Dryer_Exit := 0.45 * r_Temp_Val_1 + 10.0; (* Web temp lags flue gas temp *)")
    s.append("IF r_ELS_Speed_Voted > 1.0 THEN")
    s.append("    (* Dynamic moisture loss in dryer: drops from infeed 6.2% to 1.8% at dryer exit *)")
    s.append("    r_Web_Moisture_Percent := 6.2 - (4.4 * (r_Temp_Val_1 / 280.0) * (1.0 - EXP(-0.35 * 12.5 / MAX(r_ELS_Speed_Voted, 0.5))));")
    s.append("ELSE")
    s.append("    r_Web_Moisture_Percent := 6.2;")
    s.append("END_IF;")
    s.append("IF r_Web_Moisture_Percent < 1.2 THEN")
    s.append("    r_Web_Moisture_Percent := 1.2;")
    s.append("END_IF;")
    s.append("")
    s.append("(* Longitudinal Strain Rate d(eps)/dt *)")
    s.append("r_Temp_Val_2 := r_Infeed_Tension_Voted / (MAX(r_Paper_Base_Modulus_E0, 1000.0) * 1.0E6 * r_Web_Calculated_CrossSection);")
    s.append("r_Web_Strain_Rate := (r_Temp_Val_2 - r_Web_Current_Strain) / T_SAMPLE_SEC;")
    s.append("r_Web_Current_Strain := r_Temp_Val_2;")
    s.append("")
    s.append("(* Kelvin-Voigt Dynamic Paper Modulus: E_eff(T, M, eps_dot) [MPa] *)")
    s.append("r_Effective_Web_Modulus_MPA := r_Paper_Base_Modulus_E0")
    s.append("    * (1.0 - r_Paper_Thermal_Coeff_Alpha * (r_Web_Temperature_Dryer_Exit - 23.0))")
    s.append("    * (1.0 - r_Paper_Moisture_Coeff_Beta * (r_Web_Moisture_Percent - 5.0))")
    s.append("    + (r_Paper_Kelvin_Voigt_Eta * r_Web_Strain_Rate);")
    s.append("IF r_Effective_Web_Modulus_MPA < 1400.0 THEN")
    s.append("    r_Effective_Web_Modulus_MPA := 1400.0;")
    s.append("ELSIF r_Effective_Web_Modulus_MPA > 5800.0 THEN")
    s.append("    r_Effective_Web_Modulus_MPA := 5800.0;")
    s.append("END_IF;")
    s.append("")
    s.append("(* Viscoelastic Multi-Span Dynamic Tension Propagation *)")
    s.append("(* Span 1: Infeed Span (L1 = 3.2 m) *)")
    s.append("r_Span_Tension_1_Infeed := r_Span_Tension_1_Infeed + (T_SAMPLE_SEC * (MAX(r_ELS_Speed_Voted, 0.1) / 3.2) * (")
    s.append("    (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection * (r_Infeed_Nip_Speed_Trim_Cmd / MAX(r_ELS_Speed_Voted, 0.5)))")
    s.append("    + r_Infeed_Tension_Voted - r_Span_Tension_1_Infeed ));")
    s.append("")
    s.append("(* Span 2: Cyan Couple (L2 = 1.85 m) *)")
    s.append("r_Span_Tension_2_Cyan := r_Span_Tension_2_Cyan + (T_SAMPLE_SEC * (MAX(r_ELS_Speed_Voted, 0.1) / 1.85) * (")
    s.append("    (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection * (r_Cyan_Circ_Phase_Trim_Cmd * 0.0001))")
    s.append("    + r_Span_Tension_1_Infeed - r_Span_Tension_2_Cyan ));")
    s.append("")
    s.append("(* Span 3: Magenta Couple (L3 = 1.85 m) *)")
    s.append("r_Span_Tension_3_Magenta := r_Span_Tension_3_Magenta + (T_SAMPLE_SEC * (MAX(r_ELS_Speed_Voted, 0.1) / 1.85) * (")
    s.append("    (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection * (r_Magenta_Circ_Phase_Trim_Cmd * 0.0001))")
    s.append("    + r_Span_Tension_2_Cyan - r_Span_Tension_3_Magenta ));")
    s.append("")
    s.append("(* Span 4: Yellow Couple (L4 = 1.85 m) *)")
    s.append("r_Span_Tension_4_Yellow := r_Span_Tension_4_Yellow + (T_SAMPLE_SEC * (MAX(r_ELS_Speed_Voted, 0.1) / 1.85) * (")
    s.append("    (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection * (r_Yellow_Circ_Phase_Trim_Cmd * 0.0001))")
    s.append("    + r_Span_Tension_3_Magenta - r_Span_Tension_4_Yellow ));")
    s.append("")
    s.append("(* Span 5: Black Couple (L5 = 1.85 m) *)")
    s.append("r_Span_Tension_5_Black := r_Span_Tension_5_Black + (T_SAMPLE_SEC * (MAX(r_ELS_Speed_Voted, 0.1) / 1.85) * (")
    s.append("    (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection * (r_Black_Circ_Phase_Trim_Cmd * 0.0001))")
    s.append("    + r_Span_Tension_4_Yellow - r_Span_Tension_5_Black ));")
    s.append("")
    s.append("(* Span 6: HVHA Dryer Span (L6 = 12.5 m) - Thermal Shrinkage Strain Induces Tension Surge *)")
    s.append("r_Delta_Scratch := -0.00085 * (r_Web_Temperature_Dryer_Exit - 30.0); (* Thermal contraction *)")
    s.append("r_Span_Tension_6_Dryer := r_Span_Tension_6_Dryer + (T_SAMPLE_SEC * (MAX(r_ELS_Speed_Voted, 0.1) / 12.5) * (")
    s.append("    (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection * (r_Delta_Scratch + (r_Chill_Roll_Master_Speed_Trim / MAX(r_ELS_Speed_Voted, 0.5))))")
    s.append("    + r_Span_Tension_5_Black - r_Span_Tension_6_Dryer ));")
    s.append("")
    s.append("(* Span 7: 4-Roll Chill Stand Span (L7 = 5.6 m) *)")
    s.append("r_Span_Tension_7_Chill := r_Span_Tension_7_Chill + (T_SAMPLE_SEC * (MAX(r_ELS_Speed_Voted, 0.1) / 5.6) * (")
    s.append("    r_Span_Tension_6_Dryer - r_Span_Tension_7_Chill + (r_Chill_Tension_Voted - r_Chill_Tension_SetPoint) * 0.1 ));")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 2. 4-Color (CMYK) Registration Decoupling & Hygroscopic Fan-Out Dynamic Model                     *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* Cross-Directional Web Expansion (Fan-Out) due to fountain water absorption *)")
    s.append("r_Cyan_Calculated_FanOut_MM    := r_Web_Width_Meters * r_Hygro_Expansion_Coeff_Cross * 0.25 * (r_Web_Moisture_Percent - 4.5);")
    s.append("r_Magenta_Calculated_FanOut_MM := r_Web_Width_Meters * r_Hygro_Expansion_Coeff_Cross * 0.50 * (r_Web_Moisture_Percent - 4.5);")
    s.append("r_Yellow_Calculated_FanOut_MM  := r_Web_Width_Meters * r_Hygro_Expansion_Coeff_Cross * 0.75 * (r_Web_Moisture_Percent - 4.5);")
    s.append("r_Black_Calculated_FanOut_MM   := r_Web_Width_Meters * r_Hygro_Expansion_Coeff_Cross * 1.00 * (r_Web_Moisture_Percent - 4.5);")
    s.append("")
    s.append("(* Net Lateral Errors Decoupled from Hygroscopic Fan-Out *)")
    s.append("r_Temp_Val_1 := ABS(r_Cyan_Lat_Dev_Voted - r_Cyan_Calculated_FanOut_MM);")
    s.append("r_Temp_Val_2 := ABS(r_Magenta_Lat_Dev_Voted - r_Magenta_Calculated_FanOut_MM);")
    s.append("r_Temp_Val_3 := ABS(r_Yellow_Lat_Dev_Voted - r_Yellow_Calculated_FanOut_MM);")
    s.append("r_Max_Registration_Lat_Error_MM := MAX(r_Temp_Val_1, MAX(r_Temp_Val_2, r_Temp_Val_3));")
    s.append("")
    s.append("(* Circumferential Errors Decoupled from Inter-Tower Tension Stretches *)")
    s.append("r_Temp_Val_1 := ABS(r_Cyan_Circ_Dev_Voted - (1.85 / (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection)) * (r_Span_Tension_2_Cyan - r_Infeed_Tension_SetPoint));")
    s.append("r_Temp_Val_2 := ABS(r_Magenta_Circ_Dev_Voted - (1.85 / (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection)) * (r_Span_Tension_3_Magenta - r_Infeed_Tension_SetPoint));")
    s.append("r_Temp_Val_3 := ABS(r_Yellow_Circ_Dev_Voted - (1.85 / (r_Effective_Web_Modulus_MPA * 1.0E6 * r_Web_Calculated_CrossSection)) * (r_Span_Tension_4_Yellow - r_Infeed_Tension_SetPoint));")
    s.append("r_Max_Registration_Circ_Error_MM := MAX(r_Temp_Val_1, MAX(r_Temp_Val_2, r_Temp_Val_3));")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 3. Brush Dampening Hydrophilic Emulsion & Ink Tackiness Boundary Layer                             *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* Surfactant dynamic surface tension gamma [mN/m] regulated by conductivity *)")
    s.append("r_Dynamic_Surface_Tension := 72.8 - ((72.8 - 35.0) * LIMIT(0.0, (r_Damp_Conductivity_Voted - 800.0) / 700.0, 1.0));")
    s.append("r_Fountain_Viscosity_mPas := 1.0 + 0.025 * (20.0 - r_Damp_Temp_Voted); (* Chilled viscosity compensation *)")
    s.append("")
    s.append("(* Transferred water film thickness on hydrophilic non-image plate areas [um] *)")
    s.append("r_Water_Film_Plate_Microns := 1.15 * (r_Cyan_Dampening_Brush_Speed_Cmd / 850.0) * SQRT(MAX(r_Fountain_Viscosity_mPas, 0.5) / MAX(r_Dynamic_Surface_Tension, 25.0));")
    s.append("")
    s.append("(* Boundary layer water evaporation flux m_dot_evap [g/(m2*s)] *)")
    s.append("r_Plate_Surface_Evap_Flux := 0.042 * (1.0 + 0.12 * r_ELS_Speed_Voted) * (1.0 - 0.45); (* 45% ambient relative humidity *)")
    s.append("")
    s.append("(* Lithographic Ink Dynamic Tackiness Tau_tack [g-m] *)")
    s.append("r_Emulsion_Water_Volume_Ratio := 0.18 + 0.05 * (r_Water_Film_Plate_Microns - 1.15);")
    s.append("r_Litho_Ink_Dynamic_Tack := 14.8 * EXP(-2.2 * r_Emulsion_Water_Volume_Ratio) * (1.0 + 0.04 * (r_ELS_Speed_Voted / 15.0));")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 4. HVHA Dryer Solvent Flash-Off & Lower Explosive Limit (LEL) Mass Balance                        *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* Mineral oil solvent mass evaporation rate m_dot_solv [g/s] *)")
    s.append("(* Inks deposited: ~1.2 g/m2 per side, 38% mineral oil solvent content *)")
    s.append("r_Temp_Val_1 := (r_Dryer_Z1_Temp_Voted * 0.15 + r_Dryer_Z2_Temp_Voted * 0.45 + r_Dryer_Z3_Temp_Voted * 0.30 + r_Dryer_Z4_Temp_Voted * 0.10);")
    s.append("r_Solvent_Mass_Evap_Rate_GPS := (2.4 * 0.38) * r_Web_Width_Meters * r_ELS_Speed_Voted * (1.0 - EXP(-0.012 * r_Temp_Val_1));")
    s.append("")
    s.append("(* Dynamic solvent vapor mass balance inside dryer enclosure: d(C_solv)/dt *)")
    s.append("r_Dryer_Recirc_Fraction := r_Dryer_Recirc_Damper_Pos_Cmd * 0.01;")
    s.append("r_Dryer_Exhaust_Flow_Rate_M3S := 4.85 * (1.0 - 0.35 * r_Dryer_Recirc_Fraction) + (r_Dryer_FreshAir_Purge_Damper_Cmd * 0.01 * 3.35);")
    s.append("r_Delta_Scratch := (r_Solvent_Mass_Evap_Rate_GPS - (r_Dryer_Exhaust_Flow_Rate_M3S * r_Dryer_LEL_Concentration_G_M3)) / r_Dryer_Internal_Volume_M3;")
    s.append("r_Dryer_LEL_Concentration_G_M3 := r_Dryer_LEL_Concentration_G_M3 + (T_SAMPLE_SEC * r_Delta_Scratch);")
    s.append("IF r_Dryer_LEL_Concentration_G_M3 < 0.0 THEN")
    s.append("    r_Dryer_LEL_Concentration_G_M3 := 0.0;")
    s.append("END_IF;")
    s.append("")
    s.append("(* Estimated LEL Percentage: 100% LEL = 40.0 g/m3 *)")
    s.append("r_Estimated_Flue_LEL_Percent := (r_Dryer_LEL_Concentration_G_M3 / r_LEL_Lower_Limit_Reference) * 100.0;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 5. 4-Roll Chill Stand Heat Transfer & Dewpoint Condensation Barrier                               *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* Paper mass flow rate [kg/s] = (GSM / 1000) * Width * Velocity *)")
    s.append("r_Temp_Val_1 := (r_Paper_Basis_Weight_GSM * 0.001) * r_Web_Width_Meters * MAX(r_ELS_Speed_Voted, 0.5);")
    s.append("(* Contact thermal shock cooling over 4 rolls: T_exit = T_roll + (T_in - T_roll)*exp(-UA / (m*cp)) *)")
    s.append("r_Temp_Val_2 := EXP( -(r_Chill_Contact_Heat_Transfer_U * r_Chill_Roll_Total_Wrap_Area) / MAX(r_Temp_Val_1 * r_Paper_Specific_Heat_Capacity, 10.0) );")
    s.append("r_Chill_Roll_Dewpoint_Margin_C := r_Chill_Temp_Voted - r_Ambient_Dewpoint_Temp;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 6. Turret Unwind Continuous Flying Splicer Kinematics                                             *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* Real-time expiring roll diameter integration: dD/dt = - (4 * caliper * v) / (pi * D) *)")
    s.append("IF (r_ELS_Speed_Voted > 1.0) AND (r_Splicer_Expiring_Roll_Dia_MM > 80.0) THEN")
    s.append("    r_Delta_Scratch := (4.0 * (r_Paper_Caliper_Microns * 0.000001) * r_ELS_Speed_Voted) / (3.14159265 * (r_Splicer_Expiring_Roll_Dia_MM * 0.001));")
    s.append("    r_Splicer_Expiring_Roll_Dia_MM := r_Splicer_Expiring_Roll_Dia_MM - (T_SAMPLE_SEC * r_Delta_Scratch * 1000.0);")
    s.append("END_IF;")
    s.append("(* Target RPM for new 1270 mm diameter paper roll *)")
    s.append("r_Splicer_New_Roll_Target_RPM := (r_ELS_Speed_Voted / (3.14159265 * 1.270)) * 60.0;")
    s.append("(* Linear surface speed discrepancy error [m/s] *)")
    s.append("r_Splicer_Surface_Speed_Error := ABS(((3.14159265 * 1.270 * r_Splicer_RPM_Voted) / 60.0) - r_ELS_Speed_Voted);")
    s.append("")

    return "\n".join(s)
