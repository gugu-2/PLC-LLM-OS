# -*- coding: utf-8 -*-
"""
Module: phase5_alarms.py
Generates Phase 5: ISA-18.2 Multi-Tier Process Alarms & Diagnostic Status Packing.
Includes HI_HI, HI, LO, LO_LO, and ROC alarm evaluation, fast web break trip (<15 ms),
dryer high LEL purge abort, chill roll condensation trip, and telemetry packing.
"""

def generate_phase5_alarms():
    s = []
    s.append("(* ================================================================================================= *)")
    s.append("(* PHASE 5: ISA-18.2 MULTI-TIER PROCESS ALARMS & DIAGNOSTIC WORD PACKING                             *)")
    s.append("(* ================================================================================================= *)")
    s.append("")
    s.append("(* Reset alarm words on each scan *)")
    s.append("dw_ISA_Alarm_Word_HI_HI := 16#00000000;")
    s.append("dw_ISA_Alarm_Word_HI    := 16#00000000;")
    s.append("dw_ISA_Alarm_Word_LO    := 16#00000000;")
    s.append("dw_ISA_Alarm_Word_LO_LO := 16#00000000;")
    s.append("dw_ISA_Alarm_Word_ROC   := 16#00000000;")
    s.append("dw_Press_System_Status_Word := 16#00000000;")
    s.append("")
    s.append("(* Dynamic Rate-Of-Change (ROC) Calculations *)")
    s.append("r_ROC_Infeed_Tension := (r_Infeed_Tension_Voted - r_Prev_Infeed_Tension) / T_SAMPLE_SEC;")
    s.append("r_Prev_Infeed_Tension := r_Infeed_Tension_Voted;")
    s.append("r_ROC_Dryer_LEL := (r_Dryer_LEL_Voted - r_Prev_Dryer_LEL) / T_SAMPLE_SEC;")
    s.append("r_Prev_Dryer_LEL := r_Dryer_LEL_Voted;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 1. Fast Web Break Protection Trip Logic (< 15 ms Fast Response)                                  *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("IF b_Web_Break_Tower_Voted OR b_Web_Break_Dryer_Voted OR (r_ROC_Infeed_Tension <= -r_ROC_Tension_Trip_Threshold) THEN")
    s.append("    b_Web_Break_Trip_Latched       := TRUE;")
    s.append("    b_Web_Severing_Clamp_Fire_Fast := TRUE; (* Fire infeed pneumatic web severing knife & clamp *)")
    s.append("    b_Blanket_Cylinder_ThrowOff_Cmd := TRUE; (* Rapid pneumatic impression cylinder throw-off *)")
    s.append("    b_Dryer_Burner_Emergency_Trip   := TRUE; (* Instantaneous dryer burner shutdown *)")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 10);")
    s.append("END_IF;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 2. Priority 1: Critical Trip Alarms (HI_HI)                                                      *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* Web Over-Tension Snap Risk *)")
    s.append("IF r_Infeed_Tension_Voted >= r_Tension_Infeed_HI_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 0);")
    s.append("END_IF;")
    s.append("IF r_Chill_Tension_Voted >= 650.0 THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 1);")
    s.append("END_IF;")
    s.append("(* Registration Critical Misalignment *)")
    s.append("IF r_Max_Registration_Circ_Error_MM >= r_Reg_Circ_Dev_HI_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 2);")
    s.append("END_IF;")
    s.append("IF r_Max_Registration_Lat_Error_MM >= 0.080 THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 3);")
    s.append("END_IF;")
    s.append("(* Dryer Overtemperature Trip (315 deg C) *)")
    s.append("IF r_Dryer_Z1_Temp_Voted >= r_Dryer_Temp_HI_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 4);")
    s.append("    b_Dryer_Burner_Emergency_Trip := TRUE;")
    s.append("END_IF;")
    s.append("IF r_Dryer_Z2_Temp_Voted >= r_Dryer_Temp_HI_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 5);")
    s.append("    b_Dryer_Burner_Emergency_Trip := TRUE;")
    s.append("END_IF;")
    s.append("IF r_Dryer_Z3_Temp_Voted >= r_Dryer_Temp_HI_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 6);")
    s.append("    b_Dryer_Burner_Emergency_Trip := TRUE;")
    s.append("END_IF;")
    s.append("IF r_Dryer_Z4_Temp_Voted >= r_Dryer_Temp_HI_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 7);")
    s.append("    b_Dryer_Burner_Emergency_Trip := TRUE;")
    s.append("END_IF;")
    s.append("(* Solvent Vapor LEL NFPA 86 Emergency Purge Trip (40% LEL) *)")
    s.append("IF (r_Dryer_LEL_Voted >= r_Dryer_LEL_HI_HI) OR (r_Estimated_Flue_LEL_Percent >= r_Dryer_LEL_HI_HI) THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 8);")
    s.append("    b_Dryer_Burner_Emergency_Trip := TRUE;")
    s.append("    r_Dryer_FreshAir_Purge_Damper_Cmd := 100.0; (* Force 100% full fresh air purge *)")
    s.append("    r_Dryer_Recirc_Damper_Pos_Cmd     := 0.0;   (* Isolate recirculation *)")
    s.append("END_IF;")
    s.append("(* Chill Roll Condensation Barrier Collapse *)")
    s.append("IF r_Chill_Roll_Dewpoint_Margin_C <= r_Chill_Dewpoint_Margin_LO_LO THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 9);")
    s.append("    b_Chill_Stand_Condensation_Alarm := TRUE;")
    s.append("    r_Chill_Water_Mod_Valve_Cmd := 0.0; (* Shut off chilled water *)")
    s.append("ELSE")
    s.append("    b_Chill_Stand_Condensation_Alarm := FALSE;")
    s.append("END_IF;")
    s.append("(* Hardwire E-Stop Trip *)")
    s.append("IF NOT b_Emergency_Stop_Hardwire THEN")
    s.append("    dw_ISA_Alarm_Word_HI_HI := dw_ISA_Alarm_Word_HI_HI OR SHL(16#00000001, 12);")
    s.append("END_IF;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 3. Priority 2: High Advisory Alarms (HI)                                                          *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("IF r_Infeed_Tension_Voted >= r_Tension_Infeed_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 0);")
    s.append("END_IF;")
    s.append("IF r_Chill_Tension_Voted >= 520.0 THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 1);")
    s.append("END_IF;")
    s.append("IF r_Max_Registration_Circ_Error_MM >= r_Reg_Circ_Dev_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 2);")
    s.append("END_IF;")
    s.append("IF r_Max_Registration_Lat_Error_MM >= 0.035 THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 3);")
    s.append("END_IF;")
    s.append("IF r_Dryer_Z2_Temp_Voted >= r_Dryer_Temp_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 4);")
    s.append("END_IF;")
    s.append("IF r_Dryer_Z3_Temp_Voted >= r_Dryer_Temp_HI THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 5);")
    s.append("END_IF;")
    s.append("IF (r_Dryer_LEL_Voted >= r_Dryer_LEL_HI) OR (r_Estimated_Flue_LEL_Percent >= r_Dryer_LEL_HI) THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 8);")
    s.append("    r_Dryer_FreshAir_Purge_Damper_Cmd := 65.0;")
    s.append("END_IF;")
    s.append("IF r_Damp_Conductivity_Voted >= 1800.0 THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 9);")
    s.append("END_IF;")
    s.append("IF r_Damp_Temp_Voted >= 14.5 THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 10);")
    s.append("END_IF;")
    s.append("IF r_Splicer_Expiring_Roll_Dia_MM <= 125.0 THEN")
    s.append("    dw_ISA_Alarm_Word_HI := dw_ISA_Alarm_Word_HI OR SHL(16#00000001, 11);")
    s.append("END_IF;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 4. Priority 3 & 4: Low & Critical Low Alarms (LO / LO_LO)                                         *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("IF r_Infeed_Tension_Voted <= r_Tension_Infeed_LO THEN")
    s.append("    dw_ISA_Alarm_Word_LO := dw_ISA_Alarm_Word_LO OR SHL(16#00000001, 0);")
    s.append("END_IF;")
    s.append("IF r_Infeed_Tension_Voted <= r_Tension_Infeed_LO_LO THEN")
    s.append("    dw_ISA_Alarm_Word_LO_LO := dw_ISA_Alarm_Word_LO_LO OR SHL(16#00000001, 0);")
    s.append("END_IF;")
    s.append("IF r_Chill_Tension_Voted <= 250.0 THEN")
    s.append("    dw_ISA_Alarm_Word_LO := dw_ISA_Alarm_Word_LO OR SHL(16#00000001, 1);")
    s.append("END_IF;")
    s.append("IF r_Chill_Tension_Voted <= 140.0 THEN")
    s.append("    dw_ISA_Alarm_Word_LO_LO := dw_ISA_Alarm_Word_LO_LO OR SHL(16#00000001, 1);")
    s.append("END_IF;")
    s.append("IF r_Dryer_Z2_Temp_Voted <= r_Dryer_Temp_LO THEN")
    s.append("    dw_ISA_Alarm_Word_LO := dw_ISA_Alarm_Word_LO OR SHL(16#00000001, 2);")
    s.append("END_IF;")
    s.append("IF r_Dryer_Z2_Temp_Voted <= r_Dryer_Temp_LO_LO THEN")
    s.append("    dw_ISA_Alarm_Word_LO_LO := dw_ISA_Alarm_Word_LO_LO OR SHL(16#00000001, 2);")
    s.append("END_IF;")
    s.append("IF r_Chill_Roll_Dewpoint_Margin_C <= r_Chill_Dewpoint_Margin_LO THEN")
    s.append("    dw_ISA_Alarm_Word_LO := dw_ISA_Alarm_Word_LO OR SHL(16#00000001, 7);")
    s.append("END_IF;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 5. Priority 5: Rate-Of-Change Anomaly Bitmask (ROC)                                               *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("IF ABS(r_ROC_Infeed_Tension) >= 1500.0 THEN")
    s.append("    dw_ISA_Alarm_Word_ROC := dw_ISA_Alarm_Word_ROC OR SHL(16#00000001, 0);")
    s.append("END_IF;")
    s.append("IF r_ROC_Dryer_LEL >= r_ROC_LEL_Trip_Threshold THEN")
    s.append("    dw_ISA_Alarm_Word_ROC := dw_ISA_Alarm_Word_ROC OR SHL(16#00000001, 1);")
    s.append("END_IF;")
    s.append("")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("(* 6. Pack Industrial Telemetry Status Word                                                          *)")
    s.append("(* ------------------------------------------------------------------------------------------------- *)")
    s.append("IF b_Press_Master_Run_Cmd THEN")
    s.append("    dw_Press_System_Status_Word := dw_Press_System_Status_Word OR 16#00000001;")
    s.append("END_IF;")
    s.append("IF NOT b_Blanket_Cylinder_ThrowOff_Cmd THEN")
    s.append("    dw_Press_System_Status_Word := dw_Press_System_Status_Word OR 16#00000002; (* Blanket On Impression *)")
    s.append("END_IF;")
    s.append("IF b_Auto_Register_Enable_Cmd AND (n_FSM_Current_State = c_STATE_AUTO_REGISTER_CLOSED_LOOP) THEN")
    s.append("    dw_Press_System_Status_Word := dw_Press_System_Status_Word OR 16#00000004; (* Closed-Loop Reg Active *)")
    s.append("END_IF;")
    s.append("IF n_FSM_Current_State = c_STATE_CONTINUOUS_FLYING_SPLICE THEN")
    s.append("    dw_Press_System_Status_Word := dw_Press_System_Status_Word OR 16#00000008; (* Flying Splice Active *)")
    s.append("END_IF;")
    s.append("IF (dw_ISA_Alarm_Word_HI_HI = 16#00000000) AND (dw_ISA_Alarm_Word_LO_LO = 16#00000000) THEN")
    s.append("    dw_Press_System_Status_Word := dw_Press_System_Status_Word OR 16#00000010; (* All Interlocks Healthy *)")
    s.append("END_IF;")
    s.append("")
    s.append("END_FUNCTION_BLOCK")
    s.append("")

    return "\n".join(s)
