# -*- coding: utf-8 -*-
"""
Module: biw_mod_phase3_mpc.py
Generates PHASE 3: Receding-Horizon Model Predictive Control (MPC) Solver
for FB_Automotive_BIW_GeoFraming_MultiRobotWelding.
Implements a projected gradient descent quadratic cost functional minimization:
  J = Sum( (x - r)^T * Q * (x - r) + u^T * R * u + du^T * S * du ) + (x_N - r)^T * P * (x_N - r)
over prediction horizon Np = 4 with adjoint backward pass, hard actuator saturation,
and slew rate limiting.
"""

def get_phase3_mpc() -> str:
    lines = [
        "(* =========================================================================================== *)",
        "(* === PHASE 3: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) OPTIMIZATION ENGINE        === *)",
        "(* =========================================================================================== *)",
        "",
        "(* 3.1 Initialize MPC Horizon Initial Condition *)",
        "FOR i := 1 TO 8 DO",
        "    x_pred[1, i] := x_state[i];",
        "END_FOR;",
        "",
        "(* Seed Horizon Actuator Trajectory with Previous Solution or Baseline *)",
        "FOR k_step := 1 TO 4 DO",
        "    FOR m_in := 1 TO 8 DO",
        "        IF u_prev[m_in] >= u_min[m_in] THEN",
        "            u_traj[k_step, m_in] := u_prev[m_in];",
        "        ELSE",
        "            u_traj[k_step, m_in] := (u_min[m_in] + u_max[m_in]) * 0.50;",
        "        END_IF;",
        "    END_FOR;",
        "END_FOR;",
        "",
        "(* 3.2 Projected Gradient Descent Optimization Loop (3 Iterations for Deterministic 2 ms Scan) *)",
        "FOR iter_mpc := 1 TO 3 DO",
        "    (* Forward State Trajectory Simulation across Horizon *)",
        "    FOR k_step := 1 TO 4 DO",
        "        FOR i := 1 TO 8 DO",
        "            rSum_State := 0.0;",
        "            FOR j := 1 TO 8 DO",
        "                rSum_State := rSum_State + (mat_A[i, j] * x_pred[k_step, j]);",
        "            END_FOR;",
        "            ",
        "            rSum_Input := 0.0;",
        "            FOR m_in := 1 TO 8 DO",
        "                rSum_Input := rSum_Input + (mat_B[i, m_in] * u_traj[k_step, m_in]);",
        "            END_FOR;",
        "            ",
        "            x_pred[k_step + 1, i] := rSum_State + rSum_Input;",
        "        END_FOR;",
        "    END_FOR;",
        "    ",
        "    (* Backward Adjoint Costate Simulation: Terminal Boundary Condition *)",
        "    FOR i := 1 TO 8 DO",
        "        p_adjoint[5, i] := mat_P[i, i] * (x_pred[5, i] - r_setpoint[i]);",
        "    END_FOR;",
        "    ",
        "    (* Backward Recursion: p[k] = Q * (x[k] - r) + A^T * p[k+1] *)",
        "    FOR k_step := 4 DOWNTO 1 DO",
        "        FOR i := 1 TO 8 DO",
        "            rSum_Grad := 0.0;",
        "            FOR j := 1 TO 8 DO",
        "                rSum_Grad := rSum_Grad + (mat_A[j, i] * p_adjoint[k_step + 1, j]);",
        "            END_FOR;",
        "            ",
        "            p_adjoint[k_step, i] := (mat_Q[i, i] * (x_pred[k_step, i] - r_setpoint[i])) + rSum_Grad;",
        "        END_FOR;",
        "    END_FOR;",
        "    ",
        "    (* Gradient Evaluation & Projected Actuator Step: grad_u = R * u + B^T * p[k+1] + S * du *)",
        "    FOR k_step := 1 TO 4 DO",
        "        FOR m_in := 1 TO 8 DO",
        "            rSum_Grad := 0.0;",
        "            FOR j := 1 TO 8 DO",
        "                rSum_Grad := rSum_Grad + (mat_B[j, m_in] * p_adjoint[k_step + 1, j]);",
        "            END_FOR;",
        "            ",
        "            grad_u[k_step, m_in] := (mat_R[m_in, m_in] * u_traj[k_step, m_in]) +",
        "                                   rSum_Grad +",
        "                                   (mat_S[m_in, m_in] * (u_traj[k_step, m_in] - u_prev[m_in]));",
        "            ",
        "            (* Gradient Step with Projection *)",
        "            rTemp_Val := u_traj[k_step, m_in] - (rMPC_StepSize * grad_u[k_step, m_in]);",
        "            ",
        "            (* Apply Hard Saturation Limits [u_min .. u_max] *)",
        "            IF rTemp_Val > u_max[m_in] THEN",
        "                rTemp_Val := u_max[m_in];",
        "            ELSIF rTemp_Val < u_min[m_in] THEN",
        "                rTemp_Val := u_min[m_in];",
        "            END_IF;",
        "            ",
        "            (* Apply Slew Rate Limiting [du_max] *)",
        "            IF (rTemp_Val - u_prev[m_in]) > du_max[m_in] THEN",
        "                rTemp_Val := u_prev[m_in] + du_max[m_in];",
        "            ELSIF (rTemp_Val - u_prev[m_in]) < -du_max[m_in] THEN",
        "                rTemp_Val := u_prev[m_in] - du_max[m_in];",
        "            END_IF;",
        "            ",
        "            u_traj[k_step, m_in] := rTemp_Val;",
        "        END_FOR;",
        "    END_FOR;",
        "END_FOR;",
        "",
        "(* 3.3 Harvest First Actuator Action from Receding Horizon *)",
        "FOR m_in := 1 TO 8 DO",
        "    u_control[m_in] := u_traj[1, m_in];",
        "    du_delta[m_in] := u_control[m_in] - u_prev[m_in];",
        "    u_prev[m_in] := u_control[m_in];",
        "END_FOR;",
        "",
        "(* 3.4 Dispatch Optimized Multivariable Commands to Physical Actuators *)",
        "(* u1: Servo Gun Approach Speed Override *)",
        "IF (iFsmState = 60) THEN",
        "    bServoGunElectrodeCloseCmd := TRUE;",
        "ELSE",
        "    bServoGunElectrodeCloseCmd := FALSE;",
        "END_IF;",
        "",
        "(* u2: Dynamic Tip Squeeze Force Command [kN] *)",
        "rServoGunForceCommand_kN := u_control[2] + rDynamicSqueezeForceAdj_kN;",
        "",
        "(* u3: MFDC Inverter Adaptive Weld Current Command [kA] *)",
        "IF (iFsmState = 60) AND (rRobotWeldCycleTimer_s >= (rWeldSqueezeTime_ms * 0.001)) AND",
        "   (rRobotWeldCycleTimer_s <= ((rWeldSqueezeTime_ms + rWeldCurrentTime_ms) * 0.001)) THEN",
        "    bMFDCWeldTimerEnableCmd := TRUE;",
        "    rMFDCCurrentCommand_kA := u_control[3] + rAdaptiveCurrentCorrection_kA;",
        "ELSE",
        "    bMFDCWeldTimerEnableCmd := FALSE;",
        "    rMFDCCurrentCommand_kA := 0.0;",
        "END_IF;",
        "",
        "(* u4: Skid Lifter VFD Speed Command [%] *)",
        "rLifterSpeedCommand_pct := u_control[4];",
        "",
        "(* u6: Continuous Roof Laser Brazing Power Command [kW] *)",
        "IF (iFsmState = 70) THEN",
        "    bLaserBrazingEnableCmd := TRUE;",
        "    rLaserPowerCommand_kW := u_control[6];",
        "    rLaserWireFeedCommand_mpm := rLaserWireFeedRate_mpm;",
        "ELSE",
        "    bLaserBrazingEnableCmd := FALSE;",
        "    rLaserPowerCommand_kW := 0.0;",
        "    rLaserWireFeedCommand_mpm := 0.0;",
        "END_IF;",
        "",
        "(* u7: 14-Robot Coordinated Kinematic Feedrate Scaling [%] *)",
        "rRobotFeedrateOverride_pct := u_control[7] * 100.0;",
        "",
        "(* u8: Secondary Cooling Water Booster Pump Contactor *)",
        "bCoolingWaterBoosterPumpCmd := (u_control[8] > 20.0) OR (rTransTemp_voted_degC > 45.0);"
    ]
    return "\n".join(lines)
