# Phase 6 generator: Alarms and Status Words
import os

def generate_phase6_alarms():
    lines = []
    lines.append("(* ========================================================================= *)")
    lines.append("(* PHASE 6: ISA-18.2 MULTI-TIER ALARMS & BIT-PACKED STATUS WORDS             *)")
    lines.append("(* ========================================================================= *)")
    lines.append("")

    # Rate of Change calculation
    lines.append("(* Compute Rate of Change (RoC) for High-Frequency Dynamic Transients *)")
    lines.append("rFeedPress_RoC  := (rFeedTrunnion_Voted - rFeedPress_PrevScan) / 0.050;")
    lines.append("rDischPress_RoC := (rDischTrunnion_Voted - rDischPress_PrevScan) / 0.050;")
    lines.append("rGMDPower_RoC   := (rGMDPower_Voted - rGMDPower_PrevScan) / 0.050;")
    lines.append("rSumpLevel_RoC  := (rSumpLevel_Voted - rSumpLevel_PrevScan) / 0.050;")
    lines.append("")
    lines.append("rFeedPress_PrevScan  := rFeedTrunnion_Voted;")
    lines.append("rDischPress_PrevScan := rDischTrunnion_Voted;")
    lines.append("rGMDPower_PrevScan   := rGMDPower_Voted;")
    lines.append("rSumpLevel_PrevScan  := rSumpLevel_Voted;")
    lines.append("")

    # Reset alarm words before recalculation
    lines.append("dwAlarmWord_Trips    := 16#00000000;")
    lines.append("dwAlarmWord_Warnings := 16#00000000;")
    lines.append("")

    # 1. Feed Trunnion Pressure
    lines.append("(* 1. SAG Feed Trunnion Pressure Alarms (HH, H, L, LL) *)")
    lines.append("IF rFeedTrunnion_Voted >= rLimit_FeedPress_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000001; (* Bit 0: Feed Press HH Trip *)")
    lines.append("ELSIF rFeedTrunnion_Voted >= rLimit_FeedPress_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000001; (* Bit 0: Feed Press H Warning *)")
    lines.append("END_IF;")
    lines.append("IF rFeedTrunnion_Voted <= rLimit_FeedPress_LL THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000002; (* Bit 1: Feed Press LL Trip *)")
    lines.append("ELSIF rFeedTrunnion_Voted <= rLimit_FeedPress_L THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000002; (* Bit 1: Feed Press L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 2. Discharge Trunnion Pressure
    lines.append("(* 2. SAG Discharge Trunnion Pressure Alarms (HH, H, L, LL) *)")
    lines.append("IF rDischTrunnion_Voted >= rLimit_DischPress_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000004; (* Bit 2: Disch Press HH Trip *)")
    lines.append("ELSIF rDischTrunnion_Voted >= rLimit_DischPress_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000004; (* Bit 2: Disch Press H Warning *)")
    lines.append("END_IF;")
    lines.append("IF rDischTrunnion_Voted <= rLimit_DischPress_LL THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000008; (* Bit 3: Disch Press LL Trip *)")
    lines.append("ELSIF rDischTrunnion_Voted <= rLimit_DischPress_L THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000008; (* Bit 3: Disch Press L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 3. Bearing Oil Supply Temp
    lines.append("(* 3. Hydrostatic Bearing Oil Supply Temp Alarms (HH, H, L, LL) *)")
    lines.append("IF rBearingOilSupplyTemp >= rLimit_LubeTemp_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000010; (* Bit 4: Lube Temp HH Trip *)")
    lines.append("ELSIF rBearingOilSupplyTemp >= rLimit_LubeTemp_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000010; (* Bit 4: Lube Temp H Warning *)")
    lines.append("END_IF;")
    lines.append("IF rBearingOilSupplyTemp <= rLimit_LubeTemp_LL THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000020; (* Bit 5: Lube Temp LL Trip *)")
    lines.append("ELSIF rBearingOilSupplyTemp <= rLimit_LubeTemp_L THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000020; (* Bit 5: Lube Temp L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 4. GMD Active Power Draw
    lines.append("(* 4. 28 MW GMD Active Power Draw Alarms (HH, H, L, LL) *)")
    lines.append("IF rGMDPower_Voted >= rLimit_GMDPower_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000040; (* Bit 6: GMD Power HH Trip *)")
    lines.append("ELSIF rGMDPower_Voted >= rLimit_GMDPower_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000040; (* Bit 6: GMD Power H Warning *)")
    lines.append("END_IF;")
    lines.append("IF (rGMDPower_Voted <= rLimit_GMDPower_LL) AND (nFSM_CurrentState >= 4) THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000080; (* Bit 7: GMD Power LL Trip *)")
    lines.append("ELSIF (rGMDPower_Voted <= rLimit_GMDPower_L) AND (nFSM_CurrentState >= 4) THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000080; (* Bit 7: GMD Power L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 5. Shell Acoustic Impact
    lines.append("(* 5. Shell Acoustic Ball-on-Liner Impact Alarms (HH, H) *)")
    lines.append("IF rShellHighFreq_Filtered >= rLimit_AcousticImpact_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000100; (* Bit 8: Acoustic Impact HH Trip *)")
    lines.append("ELSIF rShellHighFreq_Filtered >= rLimit_AcousticImpact_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000100; (* Bit 8: Acoustic Impact H Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 6. Cyclone Sump Slurry Level
    lines.append("(* 6. Cyclone Feed Sump Slurry Level Alarms (HH, H, L, LL) *)")
    lines.append("IF rSumpLevel_Voted >= rLimit_SumpLevel_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000200; (* Bit 9: Sump Level HH Trip *)")
    lines.append("ELSIF rSumpLevel_Voted >= rLimit_SumpLevel_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000200; (* Bit 9: Sump Level H Warning *)")
    lines.append("END_IF;")
    lines.append("IF rSumpLevel_Voted <= rLimit_SumpLevel_LL THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000400; (* Bit 10: Sump Level LL Trip *)")
    lines.append("ELSIF rSumpLevel_Voted <= rLimit_SumpLevel_L THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000400; (* Bit 10: Sump Level L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 7. Cyclone Feed Pressure
    lines.append("(* 7. Hydrocyclone Manifold Feed Pressure Alarms (HH, H, L, LL) *)")
    lines.append("IF rCycloneFeedPressure >= rLimit_CycPressure_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00000800; (* Bit 11: Cyclone Pressure HH Trip *)")
    lines.append("ELSIF rCycloneFeedPressure >= rLimit_CycPressure_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00000800; (* Bit 11: Cyclone Pressure H Warning *)")
    lines.append("END_IF;")
    lines.append("IF (rCycloneFeedPressure <= rLimit_CycPressure_LL) AND (nFSM_CurrentState >= 7) THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00001000; (* Bit 12: Cyclone Pressure LL Trip *)")
    lines.append("ELSIF (rCycloneFeedPressure <= rLimit_CycPressure_L) AND (nFSM_CurrentState >= 7) THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00001000; (* Bit 12: Cyclone Pressure L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 8. Cyclone Feed Slurry Density
    lines.append("(* 8. Cyclone Feed Slurry Density Alarms (HH, H, L, LL) *)")
    lines.append("IF rCycloneDensity_Voted >= rLimit_CycDensity_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00002000; (* Bit 13: Cyclone Density HH Trip *)")
    lines.append("ELSIF rCycloneDensity_Voted >= rLimit_CycDensity_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00002000; (* Bit 13: Cyclone Density H Warning *)")
    lines.append("END_IF;")
    lines.append("IF rCycloneDensity_Voted <= rLimit_CycDensity_LL THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00004000; (* Bit 14: Cyclone Density LL Trip *)")
    lines.append("ELSIF rCycloneDensity_Voted <= rLimit_CycDensity_L THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00004000; (* Bit 14: Cyclone Density L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 9. Cyclone Overflow Product Particle Size P80
    lines.append("(* 9. Cyclone Overflow Particle Size P80 Alarms (HH, H, L, LL) *)")
    lines.append("IF rCycloneOverflowP80 >= rLimit_OverflowP80_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00008000; (* Bit 15: Product P80 HH Trip *)")
    lines.append("ELSIF rCycloneOverflowP80 >= rLimit_OverflowP80_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00008000; (* Bit 15: Product P80 H Warning *)")
    lines.append("END_IF;")
    lines.append("IF rCycloneOverflowP80 <= rLimit_OverflowP80_LL THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00010000; (* Bit 16: Product P80 LL Trip *)")
    lines.append("ELSIF rCycloneOverflowP80 <= rLimit_OverflowP80_L THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00010000; (* Bit 16: Product P80 L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # 10. SAG Dynamic Total Charge Mass
    lines.append("(* 10. SAG Mill Dynamic Total Charge Mass Alarms (HH, H, L, LL) *)")
    lines.append("IF aState_x[1] >= rLimit_SAGCharge_HH THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00020000; (* Bit 17: SAG Charge HH Trip *)")
    lines.append("ELSIF aState_x[1] >= rLimit_SAGCharge_H THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00020000; (* Bit 17: SAG Charge H Warning *)")
    lines.append("END_IF;")
    lines.append("IF (aState_x[1] <= rLimit_SAGCharge_LL) AND (nFSM_CurrentState >= 6) THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00040000; (* Bit 18: SAG Charge LL Trip *)")
    lines.append("ELSIF (aState_x[1] <= rLimit_SAGCharge_L) AND (nFSM_CurrentState >= 6) THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00040000; (* Bit 18: SAG Charge L Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # Frozen charge and Estop alarms
    lines.append("(* Frozen Charge Drop & Safety Estop Alarm Bits *)")
    lines.append("IF bFrozenChargeTrip THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00080000; (* Bit 19: Frozen Charge Trip *)")
    lines.append("END_IF;")
    lines.append("IF bEmergencyStop THEN")
    lines.append("    dwAlarmWord_Trips := dwAlarmWord_Trips OR 16#00100000; (* Bit 20: Emergency Estop Active *)")
    lines.append("END_IF;")
    lines.append("")

    # Rate of Change Warnings
    lines.append("(* Rate-of-Change (RoC) Transient Warnings *)")
    lines.append("IF ABS(rFeedPress_RoC) > 8.50 THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00080000; (* Bit 19: Feed Press RoC Warning *)")
    lines.append("END_IF;")
    lines.append("IF ABS(rGMDPower_RoC) > 1200.0 THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00100000; (* Bit 20: GMD Power RoC Warning *)")
    lines.append("END_IF;")
    lines.append("IF ABS(rSumpLevel_RoC) > 4.50 THEN")
    lines.append("    dwAlarmWord_Warnings := dwAlarmWord_Warnings OR 16#00200000; (* Bit 21: Sump Level RoC Warning *)")
    lines.append("END_IF;")
    lines.append("")

    # Bit-Packed Status Words
    lines.append("(* --- BIT-PACKED STATUS WORD 1: CIRCUIT OPERATIONAL STATUS --- *)")
    lines.append("dwStatusWord_Circuit := 16#00000000;")
    lines.append("IF bReady THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000001; END_IF; (* Bit 0 *)")
    lines.append("IF bActive THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000002; END_IF; (* Bit 1 *)")
    lines.append("IF bFault THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000004; END_IF; (* Bit 2 *)")
    lines.append("IF bAutoMode THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000008; END_IF; (* Bit 3 *)")
    lines.append("IF bFrozenChargeTrip THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000010; END_IF; (* Bit 4 *)")
    lines.append("IF bAcousticLinerAlert THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000020; END_IF; (* Bit 5 *)")
    lines.append("IF bSlurryPoolAlert THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000040; END_IF; (* Bit 6 *)")
    lines.append("IF bJackingPermissive THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00000080; END_IF; (* Bit 7 *)")
    lines.append("dwStatusWord_Circuit := dwStatusWord_Circuit OR SHL(INT_TO_DWORD(nFSM_CurrentState AND 16#000F), 8); (* Bits 8..11 *)")
    lines.append("IF aControl_u[3] > 0.05 THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00002000; END_IF; (* Bit 13: GMD Rotating *)")
    lines.append("IF aControl_u[4] > 50.0 THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00004000; END_IF; (* Bit 14: Cyclone Pump Running *)")
    lines.append("IF aControl_u[7] > 5.0 THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00008000; END_IF; (* Bit 15: Pebble Recycle Active *)")
    lines.append("IF rBallMillActivePower > 2000.0 THEN dwStatusWord_Circuit := dwStatusWord_Circuit OR 16#00010000; END_IF; (* Bit 16: Ball Mill Running *)")
    lines.append("")

    # Bit-Packed TMR Health Word
    lines.append("(* --- BIT-PACKED STATUS WORD 2: 2oo3 TMR SENSOR HEALTH & DEGRADED MODES --- *)")
    lines.append("dwStatusWord_TMRHealth := 16#00000000;")
    lines.append("IF bFeedTrunnion_ChA_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000001; END_IF;")
    lines.append("IF bFeedTrunnion_ChB_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000002; END_IF;")
    lines.append("IF bFeedTrunnion_ChC_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000004; END_IF;")
    lines.append("IF nFeedTrunnion_HealthyCount < 3 THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000008; END_IF;")
    lines.append("IF bDischTrunnion_ChA_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000010; END_IF;")
    lines.append("IF bDischTrunnion_ChB_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000020; END_IF;")
    lines.append("IF bDischTrunnion_ChC_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000040; END_IF;")
    lines.append("IF nDischTrunnion_HealthyCount < 3 THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000080; END_IF;")
    lines.append("IF bGMDPower_ChA_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000100; END_IF;")
    lines.append("IF bGMDPower_ChB_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000200; END_IF;")
    lines.append("IF bGMDPower_ChC_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000400; END_IF;")
    lines.append("IF nGMDPower_HealthyCount < 3 THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00000800; END_IF;")
    lines.append("IF bShellAcoustic_ChA_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00001000; END_IF;")
    lines.append("IF bShellAcoustic_ChB_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00002000; END_IF;")
    lines.append("IF bShellAcoustic_ChC_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00004000; END_IF;")
    lines.append("IF nShellAcoustic_HealthyCount < 3 THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00008000; END_IF;")
    lines.append("IF bSumpLevel_ChA_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00010000; END_IF;")
    lines.append("IF bSumpLevel_ChB_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00020000; END_IF;")
    lines.append("IF bSumpLevel_ChC_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00040000; END_IF;")
    lines.append("IF nSumpLevel_HealthyCount < 3 THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00080000; END_IF;")
    lines.append("IF bCycloneDensity_ChA_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00100000; END_IF;")
    lines.append("IF bCycloneDensity_ChB_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00200000; END_IF;")
    lines.append("IF bCycloneDensity_ChC_Fault THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00400000; END_IF;")
    lines.append("IF nCycloneDensity_HealthyCount < 3 THEN dwStatusWord_TMRHealth := dwStatusWord_TMRHealth OR 16#00800000; END_IF;")
    lines.append("")

    # Assign Output Ports
    lines.append("(* --- ASSIGN ACTUATOR DISPATCH COMMAND OUTPUTS --- *)")
    lines.append("rFreshOreFeedRate_Cmd      := aControl_u[1]; (* [t/h] Ore Feeder Tonnage *)")
    lines.append("rSAGFeedWaterFlow_Cmd      := aControl_u[2]; (* [m3/h] SAG Chute Dilution Water *)")
    lines.append("rSAGSpeedSetpoint_Cmd      := aControl_u[3]; (* [rpm] GMD Speed Reference *)")
    lines.append("rCyclonePumpSpeed_Cmd      := aControl_u[4]; (* [rpm] Cyclone Pump VFD Speed *)")
    lines.append("rSumpWaterFlow_Cmd         := aControl_u[5]; (* [m3/h] Sump Dilution Water *)")
    lines.append("nActiveCyclones_Cmd        := REAL_TO_INT(aControl_u[6]); (* [count] Active Cyclones *)")
    lines.append("rPebbleRecycleRatio_Cmd    := aControl_u[7]; (* [%] Pebble Recycle Ratio *)")
    lines.append("rBallMillWaterFlow_Cmd     := aControl_u[8]; (* [m3/h] Ball Mill Water *)")
    lines.append("")
    lines.append("(* --- ASSIGN OBSERVED CYBER-PHYSICAL STATE OUTPUTS --- *)")
    lines.append("rEstimatedSAGCharge_Tonnes := aState_x[1];   (* [t] SAG Charge Mass *)")
    lines.append("rEstimatedSlurryPool_m3    := aState_x[2];   (* [m3] Mill Belly Slurry Pool *)")
    lines.append("rEstimatedToeAngle_Deg     := aState_x[3];   (* [deg] Dynamic Toe Angle *)")
    lines.append("")
    lines.append("END_FUNCTION_BLOCK")

    return "\n".join(lines)

print("Phase 6 generator written.")
