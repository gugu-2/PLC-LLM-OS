# Phase 4: Deterministic 14-Stage Operational Finite State Machine (FSM) Generator

def generate_phase4():
    lines = []
    def emit(text=""):
        lines.append(text)

    emit("(* ==================================================================================================== *)")
    emit("(* PHASE 4: 14-STAGE DETERMINISTIC PRODUCTION FINITE STATE MACHINE (FSM) & 12-SECTION TIMING DRUM       *)")
    emit("(* ==================================================================================================== *)")
    emit("(* Track State Transition & Dwell Duration Timer *)")
    emit("IF nFsmState <> nFsmStatePrevious THEN")
    emit("    rFsmStateTimeInCurrent_s := 0.0;")
    emit("    nFsmStatePrevious := nFsmState;")
    emit("ELSE")
    emit("    rFsmStateTimeInCurrent_s := rFsmStateTimeInCurrent_s + rSamplingPeriod_s;")
    emit("END_IF;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* MASTER EMERGENCY INTERLOCK EVALUATION                                                             *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("IF NOT bEmergencyStopOk OR NOT bSafetyGateInterlocksOk OR bMasterSafetyInterlockTrip THEN")
    emit("    nFsmState := 13; (* Immediate Transition to Cullet Divert & Emergency Shear Lockout *)")
    emit("END_IF;")
    emit("")
    emit("(* Manual Cullet Divert Override Command *)")
    emit("IF bManualCulletDivertCmd AND (nFsmState <> 13) THEN")
    emit("    nFsmState := 13;")
    emit("END_IF;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 14-STAGE MASTER OPERATIONAL FINITE STATE MACHINE (CASE nFsmState OF ... END_CASE)                 *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("CASE nFsmState OF")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 0: STANDBY & UNINITIALIZED HOLDING MODE                                             *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    0: (* STATE_STANDBY_INACTIVE *)")
    emit("        bSystemReady                    := FALSE;")
    emit("        bSystemActive                   := FALSE;")
    emit("        bSafetyTripActive               := FALSE;")
    emit("        bCulletDivertActive             := TRUE;  (* Keep Cullet Deflector Chute Diverted During Standby *)")
    emit("        bEmergencyShearLockOut          := FALSE;")
    emit("        bShearCutSolenoid               := FALSE;")
    emit("        bShearSprayLubricationCmd       := FALSE;")
    emit("        bGobDistributorIndexCmd         := FALSE;")
    emit("        bSectionSettleBlowValve         := FALSE;")
    emit("        bSectionCounterBlowValve        := FALSE;")
    emit("        bSectionInvertMotionPermissive  := FALSE;")
    emit("        bSectionFinalBlowValve          := FALSE;")
    emit("        bSectionTakeOutMotionPermissive := FALSE;")
    emit("        bDeadplateBaseAirBlastValve     := FALSE;")
    emit("        bSweepoutCylinderCmd            := FALSE;")
    emit("        bStackerPushbarAdvanceCmd       := FALSE;")
    emit("")
    emit("        (* Transition Guard: Master Enable & Health Verification *)")
    emit("        IF bEnableSystem AND bEmergencyStopOk AND bSafetyGateInterlocksOk AND NOT bMasterSafetyInterlockTrip THEN")
    emit("            nFsmState := 1; (* Proceed to Forehearth Thermal Soak *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 1: FOREHEARTH THERMAL CONDITIONING & VISCOSITY EQUALIZATION SOAK                   *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    1: (* STATE_FOREHEARTH_THERMAL_SOAK *)")
    emit("        bSystemReady        := FALSE;")
    emit("        bSystemActive       := FALSE;")
    emit("        bCulletDivertActive := TRUE;")
    emit("        rThermalSoakTimer_s := rThermalSoakTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Check Forehearth Spout Temperature Equilibrium within +/- 3.5 deg C of 1150 deg C *)")
    emit("        IF ABS(rVotedForehearthSpoutTemp_degC - 1150.0) <= 3.50 AND (rThermalSoakTimer_s >= 5.0) THEN")
    emit("            bThermalSoakComplete := TRUE;")
    emit("        ELSE")
    emit("            bThermalSoakComplete := FALSE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Transition Guard: Thermal Soak Verified & Auto Mode Selected *)")
    emit("        IF bThermalSoakComplete AND bAutoModeActive THEN")
    emit("            nFsmState := 2; (* Proceed to Feeder Plunger Pumping *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 2: GOB FEEDER DUAL SERVO PLUNGER PUMPING & HOMOGENIZATION                          *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    2: (* STATE_FEEDER_PLUNGER_PUMPING *)")
    emit("        bSystemReady        := TRUE;")
    emit("        bSystemActive       := TRUE;")
    emit("        bCulletDivertActive := TRUE; (* Divert initial unstable extruded gobs to cullet *)")
    emit("")
    emit("        (* Verify Revolving Ceramic Tube Speed & Plunger Position Synchronization *)")
    emit("        IF (rTubeRotationSpeed_rpm >= 3.5) AND (rFsmStateTimeInCurrent_s >= 3.0) THEN")
    emit("            nFsmState := 3; (* Proceed to High-Speed Shear Cut-Off *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 3: PNEUMATIC / SERVO SHEAR CUT-OFF & LUBRICOOLANT SPRAY                             *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    3: (* STATE_SHEAR_CUTOFF_AND_DROP *)")
    emit("        rShearCutCycleTimer_s := rShearCutCycleTimer_s + rSamplingPeriod_s;")
    emit("        (* Trigger Shear Solenoid at Nominal Stroke Pacing (e.g., every 0.50 s = 120 cuts/min) *)")
    emit("        IF rShearCutCycleTimer_s >= 0.50 THEN")
    emit("            bShearCutSolenoid           := TRUE;")
    emit("            bShearSprayLubricationCmd   := TRUE;")
    emit("            rShearCutCycleTimer_s       := 0.0;")
    emit("        ELSE")
    emit("            bShearCutSolenoid           := FALSE;")
    emit("            IF rShearCutCycleTimer_s > 0.080 THEN")
    emit("                bShearSprayLubricationCmd := FALSE;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")
    emit("        (* Verify Optical Gob Weight & Shape Quality *)")
    emit("        IF bGobWeightOutOfTolerance THEN")
    emit("            bCulletDivertActive := TRUE;")
    emit("        ELSE")
    emit("            bCulletDivertActive := FALSE; (* Retract Cullet Deflector to Allow Drop to Distributor *)")
    emit("        END_IF;")
    emit("")
    emit("        (* Transition Guard: Gob Severance Completed & Clear of Orifice *)")
    emit("        IF (rFsmStateTimeInCurrent_s >= 0.150) AND NOT bCulletDivertActive THEN")
    emit("            nFsmState := 4; (* Proceed to Gob Distributor Delivery *)")
    emit("        ELSIF bCulletDivertActive AND (rFsmStateTimeInCurrent_s >= 2.0) THEN")
    emit("            nFsmState := 13; (* Abort to Cullet Mode on Persistent Mass Deviation *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 4: REVOLVING SCOOP GOB DISTRIBUTOR & DELIVERY CHUTE RUNNERS                         *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    4: (* STATE_GOB_DISTRIBUTOR_DELIVERY *)")
    emit("        bGobDistributorIndexCmd := TRUE;")
    emit("        rGobDropFlightTimer_s   := rGobDropFlightTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Gob Travel Time Down Trough Runner to Target Section Blank Mold (~0.32 s) *)")
    emit("        IF rGobDropFlightTimer_s >= 0.320 THEN")
    emit("            bGobDistributorIndexCmd := FALSE;")
    emit("            rGobDropFlightTimer_s   := 0.0;")
    emit("            nFsmState               := 5; (* Proceed to Blank Mold Settle Blow *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 5: BLANK MOLD FUNNEL SEAT & SETTLE BLOW (FINISH FORMATION)                         *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    5: (* STATE_BLANK_MOLD_SETTLE_BLOW *)")
    emit("        bSectionSettleBlowValve := TRUE;")
    emit("        rSettleBlowTimer_s      := rSettleBlowTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Settle Blow Pulse Duration (~0.250 s) at 2.8 bar pushes gob into neck ring *)")
    emit("        IF rSettleBlowTimer_s >= 0.250 THEN")
    emit("            bSectionSettleBlowValve := FALSE;")
    emit("            rSettleBlowTimer_s      := 0.0;")
    emit("            nFsmState               := 6; (* Proceed to Baffle Seal & Counter Blow *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 6: BAFFLE SEAL SEATING & COUNTER BLOW (PARISON CAVITY FORMATION)                   *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    6: (* STATE_BAFFLE_SEAL_COUNTER_BLOW *)")
    emit("        bSectionCounterBlowValve := TRUE;")
    emit("        rCounterBlowTimer_s      := rCounterBlowTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Counter Blow Expansion Pulse (~0.450 s) at 2.4 bar expands glass against blank mold *)")
    emit("        IF rCounterBlowTimer_s >= 0.450 THEN")
    emit("            bSectionCounterBlowValve := FALSE;")
    emit("            rCounterBlowTimer_s      := 0.0;")
    emit("            nFsmState                := 7; (* Proceed to Invert Swing Transfer *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 7: SERVO INVERT MECHANISM 180-DEGREE SWING TO BLOW SIDE                            *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    7: (* STATE_INVERT_SWING_TRANSFER *)")
    emit("        bSectionInvertMotionPermissive := TRUE;")
    emit("        rInvertSwingTimer_s            := rInvertSwingTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* High-Speed Servo Invert Arm Motion Completes in ~0.380 s *)")
    emit("        IF rInvertSwingTimer_s >= 0.380 THEN")
    emit("            bSectionInvertMotionPermissive := FALSE;")
    emit("            rInvertSwingTimer_s            := 0.0;")
    emit("            nFsmState                      := 8; (* Proceed to Blow Mold Reheat & Stretch *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 8: BLOW MOLD CLAMP, PARISON REHEAT & GRAVITATIONAL ELONGATION                       *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    8: (* STATE_BLOW_MOLD_REHEAT_STRETCH *)")
    emit("        (* Parison skin reheats from core latent heat for ~0.280 s before final blow *)")
    emit("        IF rFsmStateTimeInCurrent_s >= 0.280 THEN")
    emit("            nFsmState := 9; (* Proceed to Final Blow Expansion *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 9: BLOWHEAD SEAL, VACUUM ASSIST & FINAL BLOW AIR EXPANSION                         *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    9: (* STATE_FINAL_BLOW_EXPANSION *)")
    emit("        bSectionFinalBlowValve := TRUE;")
    emit("        rFinalBlowTimer_s      := rFinalBlowTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Final Blow Duration (~0.850 s) at 3.2 bar with Internal Mold Exhaust Cooling *)")
    emit("        IF rFinalBlowTimer_s >= 0.850 THEN")
    emit("            bSectionFinalBlowValve := FALSE;")
    emit("            rFinalBlowTimer_s      := 0.0;")
    emit("            nFsmState              := 10; (* Proceed to Take-Out Deadplate Cooling *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 10: SERVO TAKE-OUT TRANSFER & PNEUMATIC DEADPLATE BASE QUENCH                      *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    10: (* STATE_TAKEOUT_DEADPLATE_COOLING *)")
    emit("        bSectionTakeOutMotionPermissive := TRUE;")
    emit("        bDeadplateBaseAirBlastValve     := TRUE;")
    emit("        rTakeOutSwingTimer_s            := rTakeOutSwingTimer_s + rSamplingPeriod_s;")
    emit("        rDeadplateCoolTimer_s           := rDeadplateCoolTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Take-Out Transfer (~0.420 s) & Deadplate Quench (~0.650 s) *)")
    emit("        IF rTakeOutSwingTimer_s >= 0.420 THEN")
    emit("            bSectionTakeOutMotionPermissive := FALSE;")
    emit("        END_IF;")
    emit("")
    emit("        IF rDeadplateCoolTimer_s >= 0.650 THEN")
    emit("            bDeadplateBaseAirBlastValve := FALSE;")
    emit("            rTakeOutSwingTimer_s        := 0.0;")
    emit("            rDeadplateCoolTimer_s       := 0.0;")
    emit("            nFsmState                   := 11; (* Proceed to Sweepout Conveyor *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 11: PNEUMATIC / SERVO SWEEPOUT TO MACHINE HIGH-SPEED CONVEYOR                      *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    11: (* STATE_SWEEPOUT_MACHINE_CONVEYOR *)")
    emit("        bSweepoutCylinderCmd := TRUE;")
    emit("        rSweepoutTimer_s     := rSweepoutTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Sweepout Push onto Silent Chain Conveyor (~0.280 s) *)")
    emit("        IF rSweepoutTimer_s >= 0.280 THEN")
    emit("            bSweepoutCylinderCmd := FALSE;")
    emit("            rSweepoutTimer_s     := 0.0;")
    emit("            nFsmState            := 12; (* Proceed to Lehr Stacker Annealing *)")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 12: 3-AXIS SERVO LEHR STACKER PUSHBAR & CONTINUOUS TUNNEL ANNEALING                 *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    12: (* STATE_LEHR_STACKER_ANNEALING *)")
    emit("        bStackerPushbarAdvanceCmd := TRUE;")
    emit("        rStackerPushTimer_s       := rStackerPushTimer_s + rSamplingPeriod_s;")
    emit("")
    emit("        (* Stacker Sweeps Full Row of Containers onto Lehr Mesh Belt (~0.450 s) *)")
    emit("        IF rStackerPushTimer_s >= 0.450 THEN")
    emit("            bStackerPushbarAdvanceCmd := FALSE;")
    emit("            rStackerPushTimer_s       := 0.0;")
    emit("            (* Continuous Loop Recycling: Re-enter Feeder Plunger / Shear Cut Phase *)")
    emit("            IF bAutoModeActive AND NOT bMasterSafetyInterlockTrip THEN")
    emit("                nFsmState := 3; (* Loop back to Shear Cut-Off for Continuous Production *)")
    emit("            ELSE")
    emit("                nFsmState := 0; (* Return to Standby Hold *)")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* STATE 13: CULLET DIVERT ABORT & EMERGENCY PNEUMATIC SHEAR LOCK                           *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    13: (* STATE_CULLET_DIVERT_EMERGENCY_LOCK *)")
    emit("        bSystemReady                    := FALSE;")
    emit("        bSystemActive                   := FALSE;")
    emit("        bSafetyTripActive               := TRUE;")
    emit("        bCulletDivertActive             := TRUE;  (* Keep Cullet Deflector Fully Extended to Basement *)")
    emit("        bEmergencyShearLockOut          := TRUE;  (* Mechanically Lock Shears in Retracted Safety Position *)")
    emit("        bShearCutSolenoid               := FALSE;")
    emit("        bShearSprayLubricationCmd       := FALSE;")
    emit("        bGobDistributorIndexCmd         := FALSE;")
    emit("        bSectionSettleBlowValve         := FALSE;")
    emit("        bSectionCounterBlowValve        := FALSE;")
    emit("        bSectionInvertMotionPermissive  := FALSE;")
    emit("        bSectionFinalBlowValve          := FALSE;")
    emit("        bSectionTakeOutMotionPermissive := FALSE;")
    emit("        bDeadplateBaseAirBlastValve     := FALSE;")
    emit("        bSweepoutCylinderCmd            := FALSE;")
    emit("        bStackerPushbarAdvanceCmd       := FALSE;")
    emit("")
    emit("        (* Reset & Recovery Guard *)")
    emit("        IF bAcknowledgeFaults AND bEmergencyStopOk AND bSafetyGateInterlocksOk AND NOT bManualCulletDivertCmd THEN")
    emit("            bMasterSafetyInterlockTrip := FALSE;")
    emit("            bEmergencyShearLockOut     := FALSE;")
    emit("            nFsmState                  := 0; (* Recover to Standby State *)")
    emit("        END_IF;")
    emit("")
    emit("    ELSE")
    emit("        nFsmState := 0;")
    emit("END_CASE;")
    emit("")
    emit("(* Export Current Operational State Code *)")
    emit("nFsmStateCurrent := nFsmState;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 12-SECTION QUAD-GOB ELECTRONIC TIMING DRUM SYNCHRONIZATION SUITE                                   *)")
    emit("(* Calculates Local Section Angles (0..360 deg) and Section-Specific Mechanism Permissives           *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("FOR idx_s := 1 TO 12 DO")
    emit("    (* Local Rotary Angle: (MasterAngle + PhaseOffset) MOD 360 *)")
    emit("    arrSectionLocalAngle_deg[idx_s] := rMasterTimingDrumAngle_deg + arrSectionPhaseOffset_deg[idx_s];")
    emit("    IF arrSectionLocalAngle_deg[idx_s] >= 360.0 THEN")
    emit("        arrSectionLocalAngle_deg[idx_s] := arrSectionLocalAngle_deg[idx_s] - 360.0;")
    emit("    END_IF;")
    emit("")
    emit("    (* Individual Section Electronic Drum Sequence Timing *)")
    emit("    IF arrSectionEnabledPermissive[idx_s] AND (nFsmState >= 2) AND (nFsmState <= 12) THEN")
    emit("        (* Blank Mold Halves Clamp Window: 345 deg to 130 deg *)")
    emit("        IF (arrSectionLocalAngle_deg[idx_s] >= 345.0) OR (arrSectionLocalAngle_deg[idx_s] <= 130.0) THEN")
    emit("            arrSectionBlankMoldClosed[idx_s] := TRUE;")
    emit("        ELSE")
    emit("            arrSectionBlankMoldClosed[idx_s] := FALSE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Invert Arm Neck Ring Position: At Blank (0..125 deg), In-Transit (125..180 deg), At Blow (180..320 deg) *)")
    emit("        IF (arrSectionLocalAngle_deg[idx_s] >= 0.0) AND (arrSectionLocalAngle_deg[idx_s] < 125.0) THEN")
    emit("            arrSectionInvertArmAtBlank[idx_s] := TRUE;")
    emit("            arrSectionInvertArmAtBlow[idx_s]  := FALSE;")
    emit("        ELSIF (arrSectionLocalAngle_deg[idx_s] >= 180.0) AND (arrSectionLocalAngle_deg[idx_s] < 320.0) THEN")
    emit("            arrSectionInvertArmAtBlank[idx_s] := FALSE;")
    emit("            arrSectionInvertArmAtBlow[idx_s]  := TRUE;")
    emit("        ELSE")
    emit("            arrSectionInvertArmAtBlank[idx_s] := FALSE;")
    emit("            arrSectionInvertArmAtBlow[idx_s]  := FALSE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Blow Mold Halves Clamp Window: 175 deg to 315 deg *)")
    emit("        IF (arrSectionLocalAngle_deg[idx_s] >= 175.0) AND (arrSectionLocalAngle_deg[idx_s] <= 315.0) THEN")
    emit("            arrSectionBlowMoldClosed[idx_s] := TRUE;")
    emit("        ELSE")
    emit("            arrSectionBlowMoldClosed[idx_s] := FALSE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Take-Out Mechanism Position: Clamped at Blow (310..325 deg), Swung to Deadplate (340..25 deg) *)")
    emit("        IF (arrSectionLocalAngle_deg[idx_s] >= 310.0) AND (arrSectionLocalAngle_deg[idx_s] <= 325.0) THEN")
    emit("            arrSectionTakeOutAtBlow[idx_s]      := TRUE;")
    emit("            arrSectionTakeOutAtDeadplate[idx_s] := FALSE;")
    emit("        ELSIF (arrSectionLocalAngle_deg[idx_s] >= 340.0) OR (arrSectionLocalAngle_deg[idx_s] <= 25.0) THEN")
    emit("            arrSectionTakeOutAtBlow[idx_s]      := FALSE;")
    emit("            arrSectionTakeOutAtDeadplate[idx_s] := TRUE;")
    emit("        ELSE")
    emit("            arrSectionTakeOutAtBlow[idx_s]      := FALSE;")
    emit("            arrSectionTakeOutAtDeadplate[idx_s] := FALSE;")
    emit("        END_IF;")
    emit("    ELSE")
    emit("        arrSectionBlankMoldClosed[idx_s]    := FALSE;")
    emit("        arrSectionBlowMoldClosed[idx_s]     := FALSE;")
    emit("        arrSectionInvertArmAtBlank[idx_s]   := TRUE;")
    emit("        arrSectionInvertArmAtBlow[idx_s]    := FALSE;")
    emit("        arrSectionTakeOutAtBlow[idx_s]      := FALSE;")
    emit("        arrSectionTakeOutAtDeadplate[idx_s] := TRUE;")
    emit("    END_IF;")
    emit("END_FOR;")
    emit("")

    return "\n".join(lines)

