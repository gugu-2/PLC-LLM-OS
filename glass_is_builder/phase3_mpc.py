    emit("    FOR idx_k := 1 TO 4 DO")
    emit("        FOR idx_i := 1 TO 8 DO")
    emit("            (* Gradient Step: u = u - alpha * grad_J *)")
    emit("            rTempDelta := arrU_CtrlHorizon[idx_k, idx_i] - (rMpcGradientStepSize * arrGradient_J[idx_k, idx_i]);")
    emit("")
    emit("            (* Slew Rate Clamping *)")
    emit("            IF idx_k = 1 THEN")
    emit("                rCalculatedDeltaU := rTempDelta - vecU_PreviousScan[idx_i];")
