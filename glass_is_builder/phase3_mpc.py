    emit("            ELSE")
    emit("                rTempGrad := rTempGrad + (2.0 * matS_SlewWeights[idx_i, idx_i] * (arrU_CtrlHorizon[idx_k, idx_i] - arrU_CtrlHorizon[idx_k - 1, idx_i]));")
    emit("            END_IF;")
    emit("")
    emit("            (* Dynamic coupling sensitivity gradient from prediction trajectory: 2 * B^T * Q * (x - x_ref) *)")
    emit("            FOR idx_j := 1 TO 8 DO")
    emit("                rTempGrad := rTempGrad + (2.0 * matB[idx_j, idx_i] * matQ_StateWeights[idx_j, idx_j] *")
    emit("                                          (arrX_PredHorizon[idx_k + 1, idx_j] - vecX_SetpointReference[idx_j]));")
    emit("            END_FOR;")
    emit("")
    emit("            arrGradient_J[idx_k, idx_i] := rTempGrad;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
