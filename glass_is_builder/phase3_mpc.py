    emit("    FOR idx_i := 1 TO 8 DO")
    emit("        arrX_PredHorizon[1, idx_i] := vecX_HatObserver[idx_i];")
    emit("    END_FOR;")
    emit("")
    emit("    FOR idx_k := 1 TO 9 DO")
    emit("        FOR idx_i := 1 TO 8 DO")
    emit("            rTempSum := 0.0;")
    emit("            (* State Transition Contribution A * x_pred[k] *)")
    emit("            FOR idx_j := 1 TO 8 DO")
    emit("                rTempSum := rTempSum + (matA[idx_i, idx_j] * arrX_PredHorizon[idx_k, idx_j]);")
    emit("            END_FOR;")
    emit("            (* Control Input Contribution B * u[k] (Hold last control if k > Nc) *)")
    emit("            IF idx_k <= 4 THEN")
    emit("                FOR idx_j := 1 TO 8 DO")
    emit("                    rTempSum := rTempSum + (matB[idx_i, idx_j] * arrU_CtrlHorizon[idx_k, idx_j]);")
    emit("                END_FOR;")
    emit("            ELSE")
    emit("                FOR idx_j := 1 TO 8 DO")
    emit("                    rTempSum := rTempSum + (matB[idx_i, idx_j] * arrU_CtrlHorizon[4, idx_j]);")
    emit("                END_FOR;")
    emit("            END_IF;")
    emit("            arrX_PredHorizon[idx_k + 1, idx_i] := rTempSum;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* 2. Evaluate Total Quadratic Cost Functional J *)")
    emit("    rMpcQuadraticCostJ := 0.0;")
    emit("    (* State Tracking Error Cost Sum: sum_k (x_k - x_ref)^T * Q * (x_k - x_ref) *)")
    emit("    FOR idx_k := 1 TO 10 DO")
    emit("        FOR idx_i := 1 TO 8 DO")
    emit("            rTempDelta := arrX_PredHorizon[idx_k, idx_i] - vecX_SetpointReference[idx_i];")
    emit("            rMpcQuadraticCostJ := rMpcQuadraticCostJ + (rTempDelta * matQ_StateWeights[idx_i, idx_i] * rTempDelta);")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* Actuation Effort Cost Sum: sum_m u_m^T * R * u_m *)")
    emit("    FOR idx_k := 1 TO 4 DO")
    emit("        FOR idx_i := 1 TO 8 DO")
    emit("            rMpcQuadraticCostJ := rMpcQuadraticCostJ + (arrU_CtrlHorizon[idx_k, idx_i] * matR_InputWeights[idx_i, idx_i] * arrU_CtrlHorizon[idx_k, idx_i]);")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* Actuator Slew Rate Cost Sum: sum_m (u_m - u_{m-1})^T * S * (u_m - u_{m-1}) *)")
    emit("    FOR idx_k := 1 TO 4 DO")
    emit("        FOR idx_i := 1 TO 8 DO")
    emit("            IF idx_k = 1 THEN")
    emit("                rCalculatedDeltaU := arrU_CtrlHorizon[1, idx_i] - vecU_PreviousScan[idx_i];")
    emit("            ELSE")
    emit("                rCalculatedDeltaU := arrU_CtrlHorizon[idx_k, idx_i] - arrU_CtrlHorizon[idx_k - 1, idx_i];")
    emit("            END_IF;")
    emit("            rMpcQuadraticCostJ := rMpcQuadraticCostJ + (rCalculatedDeltaU * matS_SlewWeights[idx_i, idx_i] * rCalculatedDeltaU);")
    emit("        END_FOR;")
    emit("    END_FOR;")
