# Phase 5: ISA-18.2 Alarm Engine & Diagnostic Word Bit Packing Generator

def generate_phase5():
    lines = []
    def emit(text=""):
        lines.append(text)

    emit("(* ==================================================================================================== *)")
    emit("(* PHASE 5: ISA-18.2 MULTI-TIER ALARM ENGINE & 32-BIT BIT-PACKED STATUS WORDS                           *)")
    emit("(* ==================================================================================================== *)")
    emit("(* Reset Alarm Bitmasks *)")
    emit("dwAlarmHierarchyWord1 := 16#00000000;")
    emit("dwAlarmHierarchyWord2 := 16#00000000;")
    emit("dwSystemStatusWord    := 16#00000000;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* EVALUATE ISA-18.2 ALARMS FOR ALL 8 MONITORED PHYSICAL STATES                                      *)")
    emit("(* Channels:                                                                                         *)")
    emit("(*   1: Spout Temp (deg C)          2: Gob Mass (g)              3: Shear Velocity (mm/s)            *)")
    emit("(*   4: Blank Mold Heat Flux (kW)   5: Final Blow Pressure (bar) 6: Parison Reheat Rate (deg C/s)    *)")
    emit("(*   7: Take-Out Servo Angle (deg)  8: Lehr Residual Stress (MPa)                                    *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("FOR idx_i := 1 TO 8 DO")
    emit("    (* 1. Dynamic Rate-of-Change Evaluation *)")
    emit("    rCalculatedRoc[idx_i] := ABS(vecX_TrueState[idx_i] - arrAlarmPrevSampleValue[idx_i]) / rSamplingPeriod_s;")
    emit("    arrAlarmPrevSampleValue[idx_i] := vecX_TrueState[idx_i];")
    emit("")
    emit("    IF rCalculatedRoc[idx_i] >= arrAlarmRateOfChangeLimit[idx_i] THEN")
    emit("        arrAlarmActive_Roc[idx_i] := TRUE;")
    emit("    ELSE")
    emit("        arrAlarmActive_Roc[idx_i] := FALSE;")
    emit("    END_IF;")
    emit("")
    emit("    (* 2. High-High (HH) Critical Safety Trip with Hysteresis Deadband *)")
    emit("    IF vecX_TrueState[idx_i] >= arrAlarmLimit_HH[idx_i] THEN")
    emit("        arrAlarmActive_HH[idx_i]   := TRUE;")
    emit("        arrAlarmTripLatched[idx_i] := TRUE;")
    emit("        bMasterSafetyInterlockTrip := TRUE;")
    emit("    ELSIF vecX_TrueState[idx_i] < (arrAlarmLimit_HH[idx_i] - arrAlarmDeadband[idx_i]) THEN")
    emit("        arrAlarmActive_HH[idx_i] := FALSE;")
    emit("    END_IF;")
    emit("")
    emit("    (* 3. High (H) Operational Warning with Hysteresis Deadband *)")
    emit("    IF vecX_TrueState[idx_i] >= arrAlarmLimit_H[idx_i] THEN")
    emit("        arrAlarmActive_H[idx_i] := TRUE;")
    emit("    ELSIF vecX_TrueState[idx_i] < (arrAlarmLimit_H[idx_i] - arrAlarmDeadband[idx_i]) THEN")
    emit("        arrAlarmActive_H[idx_i] := FALSE;")
    emit("    END_IF;")
    emit("")
    emit("    (* 4. Low (L) Operational Warning with Hysteresis Deadband *)")
    emit("    IF vecX_TrueState[idx_i] <= arrAlarmLimit_L[idx_i] THEN")
    emit("        arrAlarmActive_L[idx_i] := TRUE;")
    emit("    ELSIF vecX_TrueState[idx_i] > (arrAlarmLimit_L[idx_i] + arrAlarmDeadband[idx_i]) THEN")
    emit("        arrAlarmActive_L[idx_i] := FALSE;")
    emit("    END_IF;")
    emit("")
    emit("    (* 5. Low-Low (LL) Critical Safety Trip with Hysteresis Deadband *)")
    emit("    IF vecX_TrueState[idx_i] <= arrAlarmLimit_LL[idx_i] THEN")
    emit("        arrAlarmActive_LL[idx_i]   := TRUE;")
    emit("        arrAlarmTripLatched[idx_i] := TRUE;")
    emit("        bMasterSafetyInterlockTrip := TRUE;")
    emit("    ELSIF vecX_TrueState[idx_i] > (arrAlarmLimit_LL[idx_i] + arrAlarmDeadband[idx_i]) THEN")
    emit("        arrAlarmActive_LL[idx_i] := FALSE;")
    emit("    END_IF;")
    emit("")
    emit("    (* Reset Latched Trip on Operator Master Acknowledge *)")
    emit("    IF bAcknowledgeFaults THEN")
    emit("        arrAlarmTripLatched[idx_i] := FALSE;")
    emit("    END_IF;")
    emit("")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    (* PACK ISA-18.2 BITMASKS                                                                    *)")
    emit("    (* Word 1: Bits 0..7: HH Trips, Bits 8..15: LL Trips, Bits 16..23: H, Bits 24..31: L        *)")
    emit("    (* ----------------------------------------------------------------------------------------- *)")
    emit("    IF arrAlarmActive_HH[idx_i] OR arrAlarmTripLatched[idx_i] THEN")
    emit("        dwAlarmHierarchyWord1 := dwAlarmHierarchyWord1 OR SHL(DWORD#1, (idx_i - 1));")
    emit("    END_IF;")
    emit("    IF arrAlarmActive_LL[idx_i] OR arrAlarmTripLatched[idx_i] THEN")
    emit("        dwAlarmHierarchyWord1 := dwAlarmHierarchyWord1 OR SHL(DWORD#1, (idx_i - 1 + 8));")
    emit("    END_IF;")
    emit("    IF arrAlarmActive_H[idx_i] THEN")
    emit("        dwAlarmHierarchyWord1 := dwAlarmHierarchyWord1 OR SHL(DWORD#1, (idx_i - 1 + 16));")
    emit("    END_IF;")
    emit("    IF arrAlarmActive_L[idx_i] THEN")
    emit("        dwAlarmHierarchyWord1 := dwAlarmHierarchyWord1 OR SHL(DWORD#1, (idx_i - 1 + 24));")
    emit("    END_IF;")
    emit("")
    emit("    (* Word 2: Bits 0..7: Rate-of-Change Alarms *)")
    emit("    IF arrAlarmActive_Roc[idx_i] THEN")
    emit("        dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR SHL(DWORD#1, (idx_i - 1));")
    emit("    END_IF;")
    emit("END_FOR;")
    emit("")
    emit("(* Pack Process & Subsystem Advisory Alarms into Word 2 *)")
    emit("IF bGobWeightOutOfTolerance THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00000100; (* Bit 8: Gob Mass Tolerance Breach *)")
    emit("END_IF;")
    emit("IF rCulletWaterQuenchFlow_m3h < 12.0 THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00000200; (* Bit 9: Cullet Quench Flow Low *)")
    emit("END_IF;")
    emit("IF NOT bCulletConveyorRunning THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00000400; (* Bit 10: Cullet Scraper Stalled *)")
    emit("END_IF;")
    emit("IF rShearBladeTemp_degC > 110.0 THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00000800; (* Bit 11: Shear Blade Overheat *)")
    emit("END_IF;")
    emit("IF rShearLubricoolantPress_bar < 2.50 THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00001000; (* Bit 12: Shear Spray Pressure Low *)")
    emit("END_IF;")
    emit("IF rForehearthGasPressure_bar < 1.80 THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00002000; (* Bit 13: Forehearth Fuel Gas Low *)")
    emit("END_IF;")
    emit("IF dwTmrIntegrityStatus <> 16#00000000 THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00004000; (* Bit 14: TMR Degradation Present *)")
    emit("END_IF;")
    emit("IF bMasterSafetyInterlockTrip THEN")
    emit("    dwAlarmHierarchyWord2 := dwAlarmHierarchyWord2 OR 16#00008000; (* Bit 15: Master Safety Interlock Trip *)")
    emit("END_IF;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* PACK 32-BIT MACHINE OPERATIONAL STATUS REGISTER dwSystemStatusWord                                *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("IF bSystemReady THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000001; (* Bit 0: Machinery Ready *)")
    emit("END_IF;")
    emit("IF bSystemActive THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000002; (* Bit 1: Production Active *)")
    emit("END_IF;")
    emit("IF bAutoModeActive THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000004; (* Bit 2: Auto Mode Synchronized *)")
    emit("END_IF;")
    emit("IF bEmergencyStopOk THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000008; (* Bit 3: E-Stop Permissive OK *)")
    emit("END_IF;")
    emit("IF bSafetyGateInterlocksOk THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000010; (* Bit 4: Safety Enclosure Closed *)")
    emit("END_IF;")
    emit("IF bThermalSoakComplete THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000020; (* Bit 5: Forehearth Thermal Soak Done *)")
    emit("END_IF;")
    emit("IF bShearCutSolenoid THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000040; (* Bit 6: Shear Cut Active Pulse *)")
    emit("END_IF;")
    emit("IF bCulletDivertActive THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000080; (* Bit 7: Cullet Deflector Extended *)")
    emit("END_IF;")
    emit("IF bCulletConveyorRunning THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000100; (* Bit 8: Cullet Scraper Running *)")
    emit("END_IF;")
    emit("IF bEmergencyShearLockOut THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000200; (* Bit 9: Shears Emergency Locked *)")
    emit("END_IF;")
    emit("IF bSafetyTripActive THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000400; (* Bit 10: SIL-3 Safety Trip Latched *)")
    emit("END_IF;")
    emit("IF rMpcQuadraticCostJ > 0.0 THEN")
    emit("    dwSystemStatusWord := dwSystemStatusWord OR 16#00000800; (* Bit 11: MPC Solver Operational *)")
    emit("END_IF;")
    emit("")
    emit("(* Pack Current FSM State Code into Bits 16..23 *)")
    emit("dwSystemStatusWord := dwSystemStatusWord OR SHL(TO_DWORD(nFsmState), 16);")
    emit("")
    emit("(* Increment Real-Time Execution Scan Counters *)")
    emit("nCycleCounter := nCycleCounter + 1;")
    emit("IF rMasterTimingDrumAngle_deg < 5.0 THEN")
    emit("    nTimingMasterCycleCount := nTimingMasterCycleCount + 1;")
    emit("END_IF;")
    emit("")
    emit("END_FUNCTION_BLOCK")

    return "\n".join(lines)

if __name__ == "__main__":
    s = generate_phase5()
