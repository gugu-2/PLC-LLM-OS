# Phase 2: Cyber-Physical Observers & Multivariable State-Space Propagation Generator

def generate_phase2():
    lines = []
    def emit(text=""):
        lines.append(text)

    emit("(* ==================================================================================================== *)")
    emit("(* PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL OBSERVERS & MULTIVARIABLE STATE PROPAGATION                 *)")
    emit("(* ==================================================================================================== *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 1. THERMODYNAMIC GLASS MELT VISCOSITY OBSERVER (VOGEL-FULCHER-TAMMANN RELATION)                    *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("IF (rVotedForehearthSpoutTemp_degC - rVftConstant_T0) > 10.0 THEN")
    emit("    rViscosityExponent := rVftConstant_A + (rVftConstant_B / (rVotedForehearthSpoutTemp_degC - rVftConstant_T0));")
    emit("    (* Natural Exponential Conversion: 10^x = EXP(x * LN(10)) = EXP(x * 2.30258509) *)")
    emit("    rCalculatedGlassViscosity_dPas := EXP(rViscosityExponent * 2.30258509);")
    emit("ELSE")
    emit("    rCalculatedGlassViscosity_dPas := 50000.0; (* Viscosity cold-glass saturation clamp *)")
    emit("END_IF;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 2. QUAD-GOB GRAVITATIONAL EXTRUSION & PLUNGER PUMPING MASS OBSERVER                                *)")
    emit("(* Orifice Ring Area: A_orif = 4 * (PI / 4) * D^2; Mass flow = rho * Cd * A_orif * sqrt(2*g*h)       *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("rGlassFlowRate_kgs := rGlassDensity_kgm3 * rOrificeDischargeCoeff * (4.0 * 3.14159265 * 0.000001 *")
    emit("                      rOrificeQuadDiameter_mm * rOrificeQuadDiameter_mm * 0.25) *")
    emit("                      SQRT(2.0 * 9.80665 * 0.180) * (1200.0 / LIMIT(100.0, rCalculatedGlassViscosity_dPas, 10000.0));")
    emit("")
    emit("(* Verify Gob Mass Deviation from Setpoint *)")
    emit("IF ABS(rVotedGobMass_g - rGobMassTarget_g) > 8.50 THEN")
    emit("    bGobWeightOutOfTolerance := TRUE;")
    emit("ELSE")
    emit("    bGobWeightOutOfTolerance := FALSE;")
    emit("END_IF;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 3. BLANK MOLD TRANSIENT HEAT FLUX DISSIPATION OBSERVER                                            *)")
    emit("(* Heat extraction rate during gob contact and parison forming (kW)                                  *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("rParisonHeatFlux_kW := 1.850 * (rVotedForehearthSpoutTemp_degC - 480.0) *")
    emit("                       (0.042 * 3.14159265 * (rGobLengthMeasured_mm * 0.001)) *")
    emit("                       SQRT(LIMIT(0.5, rVotedBlankCoolAirPress_bar, 6.0) / 4.20);")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 4. PARISON SKIN REHEAT RATE CONDUCTION OBSERVER                                                   *)")
    emit("(* Core-to-skin conduction upon blank mold opening: q = k / (rho * Cp) * (T_core - T_skin) / dr^2   *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("rReheatThermalDiff_degCs := (rGlassThermalConductivity_WmK / (rGlassDensity_kgm3 * rGlassSpecificHeat_JkgK)) *")
    emit("                            ((rVotedForehearthSpoutTemp_degC - 820.0) / 0.000025);")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 5. LEHR CONTINUOUS ANNEALING MAXWELL VISCOELASTIC STRESS OBSERVER                                 *)")
    emit("(* Relaxation equation: d_sigma / dt = - (E / eta) * sigma + E * beta * (dT / dt)                    *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("rStressRelaxationRate_MPas := - (rGlassYoungsModulus_GPa * 1000.0 / LIMIT(1000.0, rCalculatedGlassViscosity_dPas * 100000.0, 1.0E12)) *")
    emit("                              rVotedLehrStress_MPa +")
    emit("                              (rGlassYoungsModulus_GPa * 1000.0 * rGlassThermalExpansionCoeff * ((rLehrZone1HeatingTemp_degC - rLehrZone3CoolTemp_degC) / 120.0));")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 6. POPULATE MEASURED OUTPUT VECTOR Y (DEVIATIONS FROM NOMINAL EQUILIBRIUM OPERATING POINT)        *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("vecY_MeasuredOutputs[1] := rVotedForehearthSpoutTemp_degC - 1150.0; (* Spout Temperature Dev [deg C] *)")
    emit("vecY_MeasuredOutputs[2] := rVotedGobMass_g - rGobMassTarget_g;     (* Gob Mass Dev [g] *)")
    emit("vecY_MeasuredOutputs[3] := rVotedShearVelocity_mms - 1250.0;       (* Shear Blade Velocity Dev [mm/s] *)")
    emit("vecY_MeasuredOutputs[4] := rParisonHeatFlux_kW - 45.0;              (* Blank Mold Heat Extraction Dev [kW] *)")
    emit("vecY_MeasuredOutputs[5] := rVotedFinalBlowPress_bar - 3.20;         (* Parison / Blow Pressure Dev [bar] *)")
    emit("vecY_MeasuredOutputs[6] := rReheatThermalDiff_degCs - 35.0;         (* Parison Skin Reheat Rate Dev [deg C/s] *)")
    emit("vecY_MeasuredOutputs[7] := rVotedTakeOutServoAngle_deg - 0.0;       (* Take-Out Servo Angle Dev [deg] *)")
    emit("vecY_MeasuredOutputs[8] := rVotedLehrStress_MPa - 1.85;             (* Lehr Residual Annealing Stress Dev [MPa] *)")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 7. OBSERVER OUTPUT ESTIMATION & INNOVATION RESIDUAL CALCULATION (y_hat = C * x_hat, e = y - y_hat) *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("FOR idx_i := 1 TO 8 DO")
    emit("    rTempSum := 0.0;")
    emit("    FOR idx_j := 1 TO 8 DO")
    emit("        rTempSum := rTempSum + (matC[idx_i, idx_j] * vecX_HatObserver[idx_j]);")
    emit("    END_FOR;")
    emit("    vecY_EstimatedOutputs[idx_i] := rTempSum;")
    emit("    vecInnovationResidual[idx_i] := vecY_MeasuredOutputs[idx_i] - vecY_EstimatedOutputs[idx_i];")
    emit("END_FOR;")
    emit("")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("(* 8. DISCRETE 8x8 STATE-SPACE PROPAGATION WITH LUENBERGER CORRECTION:                               *)")
    emit("(* x_hat[k+1] = A * x_hat[k] + B * u[k-1] + L_Obs * (y[k] - y_hat[k])                                *)")
    emit("(* ------------------------------------------------------------------------------------------------- *)")
    emit("FOR idx_i := 1 TO 8 DO")
    emit("    rTempSum := 0.0;")
    emit("    (* System Dynamics A * x_hat *)")
    emit("    FOR idx_j := 1 TO 8 DO")
    emit("        rTempSum := rTempSum + (matA[idx_i, idx_j] * vecX_HatObserver[idx_j]);")
    emit("    END_FOR;")
    emit("    (* Actuator Coupling B * u_prev *)")
    emit("    FOR idx_j := 1 TO 8 DO")
    emit("        rTempSum := rTempSum + (matB[idx_i, idx_j] * vecU_PreviousScan[idx_j]);")
    emit("    END_FOR;")
    emit("    (* Innovation Observer Correction L_obs * e_innov *)")
    emit("    FOR idx_j := 1 TO 8 DO")
    emit("        rTempSum := rTempSum + (matL_Obs[idx_i, idx_j] * vecInnovationResidual[idx_j]);")
    emit("    END_FOR;")
    emit("    vecX_TrueState[idx_i] := rTempSum;")
    emit("END_FOR;")
    emit("")
    emit("(* Update Observer State Vector for Next Iteration *)")
    emit("FOR idx_i := 1 TO 8 DO")
    emit("    vecX_HatObserver[idx_i] := vecX_TrueState[idx_i];")
    emit("END_FOR;")
    emit("")

    return "\n".join(lines)

