# -*- coding: utf-8 -*-
"""
Part 5: ISA-18.2 Multi-Tier Alarms, Bit-Packed Status & Diagnostic Words,
and END_FUNCTION_BLOCK.
"""

def get_part5():
    lines = []
    w = lines.append
    
    w("(* ============================================================================================== *)")
    w("(* PHASE 5: ISA-18.2 MULTI-TIER ALARMS & 32-BIT BIT-PACKED STATUS & DIAGNOSTIC WORDS              *)")
    w("(* ============================================================================================== *)")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 1. ISA-18.2 OVER-TEMPERATURE & UNDER-TEMPERATURE TRIP SUPERVISION                             *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("bAlarmTrip_Overtemp_HH := FALSE;")
    w("bAlarmTrip_Overtemp_H := FALSE;")
    w("bAlarmTrip_Undertemp_L := FALSE;")
    w("bAlarmTrip_Undertemp_LL := FALSE;")
    w("")
    w("FOR z := 1 TO 14 DO")
    w("    (* Critical High-High Over-Temperature Trip (SP + 16.0 deg C or absolute > 295.0 deg C) *)")
    w("    IF (rZone_PV_Array[z] >= (rZone_SP_Array[z] + 16.0)) OR (rZone_PV_Array[z] >= 295.0) THEN")
    w("        bAlarmTrip_Overtemp_HH := TRUE;")
    w("        nOvenOperationalState := 14; (* Emergency Trip *)")
    w("    END_IF;")
    w("    ")
    w("    (* High Over-Temperature Warning (SP + 8.0 deg C) *)")
    w("    IF rZone_PV_Array[z] >= (rZone_SP_Array[z] + 8.0) THEN")
    w("        bAlarmTrip_Overtemp_H := TRUE;")
    w("    END_IF;")
    w("    ")
    w("    (* Low Under-Temperature Warning (SP - 8.0 deg C) during Production *)")
    w("    IF (nOvenOperationalState = 6) AND (rZone_PV_Array[z] <= (rZone_SP_Array[z] - 8.0)) THEN")
    w("        bAlarmTrip_Undertemp_L := TRUE;")
    w("    END_IF;")
    w("    ")
    w("    (* Low-Low Under-Temperature Trip (SP - 18.0 deg C) during Production *)")
    w("    IF (nOvenOperationalState = 6) AND (rZone_PV_Array[z] <= (rZone_SP_Array[z] - 18.0)) THEN")
    w("        bAlarmTrip_Undertemp_LL := TRUE;")
    w("    END_IF;")
    w("END_FOR;")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 2. RESIDUAL OXYGEN CONCENTRATION ALARM MONITORING (ISA-18.2)                                    *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("IF rVotedOxygenConcentration_ppm > 80.0 THEN")
    w("    rAlarmDebounce_O2_s := rAlarmDebounce_O2_s + T_CYCLE_SEC;")
    w("    IF rAlarmDebounce_O2_s >= 2.0 THEN")
    w("        bAlarmTrip_O2_HighHigh := TRUE;")
    w("        (* In reflow stage, severe O2 ingress compromises solder wettability: drop SMEMA *)")
    w("        bSMEMA_InfeedAccept_L1 := FALSE;")
    w("        bSMEMA_InfeedAccept_L2 := FALSE;")
    w("    END_IF;")
    w("ELSIF rVotedOxygenConcentration_ppm > 35.0 THEN")
    w("    bAlarmTrip_O2_High := TRUE;")
    w("ELSIF rVotedOxygenConcentration_ppm <= (35.0 - rAlarmDeadband_ppm) THEN")
    w("    bAlarmTrip_O2_High := FALSE;")
    w("    IF rVotedOxygenConcentration_ppm <= (80.0 - rAlarmDeadband_ppm) THEN")
    w("        bAlarmTrip_O2_HighHigh := FALSE;")
    w("        rAlarmDebounce_O2_s := 0.0;")
    w("    END_IF;")
    w("END_IF;")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 3. BULK NITROGEN HEADER SUPPLY PRESSURE SUPERVISION                                           *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("IF rSupplyNitrogenPressure_bar < 2.5 THEN")
    w("    bAlarmTrip_N2_PressureLowLow := TRUE;")
    w("    nOvenOperationalState := 14; (* Abort: insufficient N2 to maintain inert blanket *)")
    w("ELSIF rSupplyNitrogenPressure_bar < 4.0 THEN")
    w("    bAlarmTrip_N2_PressureLow := TRUE;")
    w("ELSIF rSupplyNitrogenPressure_bar >= 4.5 THEN")
    w("    bAlarmTrip_N2_PressureLow := FALSE;")
    w("    bAlarmTrip_N2_PressureLowLow := FALSE;")
    w("END_IF;")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 4. THERMAL SHOCK HEATING/COOLING RATE SUPERVISION (dT/dt)                                      *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("bAlarmTrip_ThermalShockRate := FALSE;")
    w("FOR z := 1 TO 14 DO")
    w("    IF z <= 11 THEN")
    w("        IF rZone_RampRate_degCps[z] > (rMaxHeatingRampLimit_degCps + 0.5) THEN")
    w("            bAlarmTrip_ThermalShockRate := TRUE;")
    w("        END_IF;")
    w("    ELSE")
    w("        IF rZone_RampRate_degCps[z] < (rMaxCoolingRampLimit_degCps - 0.8) THEN")
    w("            bAlarmTrip_ThermalShockRate := TRUE;")
    w("        END_IF;")
    w("    END_IF;")
    w("END_FOR;")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 5. DUAL-LANE MESH BELT TACHOMETER TRACKING & SLIP SUPERVISION                                  *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("IF (nOvenOperationalState = 6) THEN")
    w("    IF ABS(rVotedBeltSpeed_L1_mmpm - rConveyorNominalSpeed_mmpm) > 25.0 THEN")
    w("        rAlarmDebounce_Belt_s := rAlarmDebounce_Belt_s + T_CYCLE_SEC;")
    w("        IF rAlarmDebounce_Belt_s >= 2.0 THEN")
    w("            bAlarmTrip_BeltSlip_L1 := TRUE;")
    w("        END_IF;")
    w("    ELSE")
    w("        rAlarmDebounce_Belt_s := 0.0;")
    w("        bAlarmTrip_BeltSlip_L1 := FALSE;")
    w("    END_IF;")
    w("    ")
    w("    IF ABS(rBeltSpeed_L2_mmpm - rConveyorNominalSpeed_mmpm) > 25.0 THEN")
    w("        bAlarmTrip_BeltSlip_L2 := TRUE;")
    w("    ELSE")
    w("        bAlarmTrip_BeltSlip_L2 := FALSE;")
    w("    END_IF;")
    w("ELSE")
    w("    bAlarmTrip_BeltSlip_L1 := FALSE;")
    w("    bAlarmTrip_BeltSlip_L2 := FALSE;")
    w("END_IF;")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 6. EXHAUST EXTRACTION BLOWER FLOW SUPERVISION                                                  *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("IF rExhaustExtractionFlow_Nm3h < 120.0 THEN")
    w("    bAlarmTrip_ExhaustBlocked := TRUE;")
    w("ELSE")
    w("    bAlarmTrip_ExhaustBlocked := FALSE;")
    w("END_IF;")
    w("")
    w("(* Map Group Alarm Outputs *)")
    w("bAlarmGroupHighHigh_Overtemp      := bAlarmTrip_Overtemp_HH;")
    w("bAlarmGroupHigh_O2_Ingress        := bAlarmTrip_O2_High OR bAlarmTrip_O2_HighHigh;")
    w("bAlarmGroupLow_N2_Pressure        := bAlarmTrip_N2_PressureLow OR bAlarmTrip_N2_PressureLowLow;")
    w("bAlarmGroup_VacuumDegasFault      := bAlarmTrip_VacPumpTimeout OR bAlarmTrip_VacLeakRateHigh OR bVacGateFault_Inlet OR bVacGateFault_Outlet;")
    w("bAlarmGroup_ConveyorDiscrepancy   := bAlarmTrip_BeltSlip_L1 OR bAlarmTrip_BeltSlip_L2;")
    w("bAlarmGroup_ThermalShockViolation := bAlarmTrip_ThermalShockRate;")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 7. CONSTRUCT 32-BIT BIT-PACKED dwOvenStatusWord                                                *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("dwOvenStatusWord := 16#00000000;")
    w("IF bSystemReady THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000001; END_IF; (* Bit 0 *)")
    w("IF bProductionActive THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000002; END_IF; (* Bit 1 *)")
    w("IF rVotedOxygenConcentration_ppm <= 35.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000004; END_IF; (* Bit 2 *)")
    w("IF (rPeakDeltaTAcrossOven_degC <= 4.0) THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000008; END_IF; (* Bit 3 *)")
    w("IF rBeltDriveCommand_L1_Hz > 0.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000010; END_IF; (* Bit 4 *)")
    w("IF rBeltDriveCommand_L2_Hz > 0.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000020; END_IF; (* Bit 5 *)")
    w("IF (nOvenOperationalState >= 7) AND (nOvenOperationalState <= 11) THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000040; END_IF; (* Bit 6: Vac Active *)")
    w("IF nOvenOperationalState = 9 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000080; END_IF; (* Bit 7: Vac Dwell *)")
    w("IF bSMEMA_InfeedAccept_L1 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000100; END_IF; (* Bit 8 *)")
    w("IF bSMEMA_InfeedAccept_L2 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000200; END_IF; (* Bit 9 *)")
    w("IF bSMEMA_OutfeedRequest_L1 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000400; END_IF; (* Bit 10 *)")
    w("IF bSMEMA_OutfeedRequest_L2 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00000800; END_IF; (* Bit 11 *)")
    w("IF x_state[5] >= 217.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00001000; END_IF; (* Bit 12: Liquidus TAL *)")
    w("IF nOvenOperationalState = 12 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00002000; END_IF; (* Bit 13: Cool Outfeed *)")
    w("IF nOvenOperationalState = 13 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00004000; END_IF; (* Bit 14: Shutdown *)")
    w("IF nOvenOperationalState = 14 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00008000; END_IF; (* Bit 15: Abort Trip *)")
    w("(* Bits 16..29: Zone 1..14 In-Band Temperature Flags (+/- 2.0 deg C of Setpoint) *)")
    w("IF ABS(rZone_PV_Array[1] - rZone_SP_Array[1]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00010000; END_IF; (* Bit 16 *)")
    w("IF ABS(rZone_PV_Array[2] - rZone_SP_Array[2]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00020000; END_IF; (* Bit 17 *)")
    w("IF ABS(rZone_PV_Array[3] - rZone_SP_Array[3]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00040000; END_IF; (* Bit 18 *)")
    w("IF ABS(rZone_PV_Array[4] - rZone_SP_Array[4]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00080000; END_IF; (* Bit 19 *)")
    w("IF ABS(rZone_PV_Array[5] - rZone_SP_Array[5]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00100000; END_IF; (* Bit 20 *)")
    w("IF ABS(rZone_PV_Array[6] - rZone_SP_Array[6]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00200000; END_IF; (* Bit 21 *)")
    w("IF ABS(rZone_PV_Array[7] - rZone_SP_Array[7]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00400000; END_IF; (* Bit 22 *)")
    w("IF ABS(rZone_PV_Array[8] - rZone_SP_Array[8]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#00800000; END_IF; (* Bit 23 *)")
    w("IF ABS(rZone_PV_Array[9] - rZone_SP_Array[9]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#01000000; END_IF; (* Bit 24 *)")
    w("IF ABS(rZone_PV_Array[10] - rZone_SP_Array[10]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#02000000; END_IF; (* Bit 25 *)")
    w("IF ABS(rZone_PV_Array[11] - rZone_SP_Array[11]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#04000000; END_IF; (* Bit 26 *)")
    w("IF ABS(rZone_PV_Array[12] - rZone_SP_Array[12]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#08000000; END_IF; (* Bit 27 *)")
    w("IF ABS(rZone_PV_Array[13] - rZone_SP_Array[13]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#10000000; END_IF; (* Bit 28 *)")
    w("IF ABS(rZone_PV_Array[14] - rZone_SP_Array[14]) <= 2.0 THEN dwOvenStatusWord := dwOvenStatusWord OR 16#20000000; END_IF; (* Bit 29 *)")
    w("IF bVacPumpRunCommand THEN dwOvenStatusWord := dwOvenStatusWord OR 16#40000000; END_IF; (* Bit 30 *)")
    w("dwOvenStatusWord := dwOvenStatusWord OR 16#80000000; (* Bit 31: Heartbeat Online *)")
    w("")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("(* 8. CONSTRUCT 32-BIT BIT-PACKED dwOvenDiagnosticWord                                            *)")
    w("(* ---------------------------------------------------------------------------------------------- *)")
    w("dwOvenDiagnosticWord := 16#00000000;")
    w("IF NOT bEmergencyStop THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000001; END_IF; (* Bit 0: E-Stop *)")
    w("IF bAlarmTrip_Overtemp_HH THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000002; END_IF; (* Bit 1: Over-Temp HH *)")
    w("IF bAlarmTrip_O2_HighHigh THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000004; END_IF; (* Bit 2: O2 HH *)")
    w("IF bAlarmTrip_N2_PressureLowLow THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000008; END_IF; (* Bit 3: N2 LowLow *)")
    w("IF bAlarmTrip_VacPumpTimeout THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000010; END_IF; (* Bit 4: Vac Timeout *)")
    w("IF bAlarmTrip_VacLeakRateHigh THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000020; END_IF; (* Bit 5: Vac Leak High *)")
    w("IF bVacGateFault_Inlet THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000040; END_IF; (* Bit 6: Inlet Gate Fault *)")
    w("IF bVacGateFault_Outlet THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000080; END_IF; (* Bit 7: Outlet Gate Fault *)")
    w("IF bAlarmTrip_BeltSlip_L1 THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000100; END_IF; (* Bit 8: Lane 1 Belt Slip *)")
    w("IF bAlarmTrip_BeltSlip_L2 THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000200; END_IF; (* Bit 9: Lane 2 Belt Slip *)")
    w("IF bAlarmTrip_ThermalShockRate THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000400; END_IF; (* Bit 10: Thermal Shock *)")
    w("IF nO2_DegradedVotingMode < 3 THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00000800; END_IF; (* Bit 11: O2 TMR Degraded *)")
    w("IF nReflow_DegradedVotingMode < 3 THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00001000; END_IF; (* Bit 12: RTD TMR Degraded *)")
    w("IF nVac_DegradedVotingMode < 3 THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00002000; END_IF; (* Bit 13: Vac CM TMR Degraded *)")
    w("IF nBelt_DegradedVotingMode < 3 THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00004000; END_IF; (* Bit 14: Belt Tacho Degraded *)")
    w("IF bAlarmTrip_ExhaustBlocked THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00008000; END_IF; (* Bit 15: Exhaust Blocked *)")
    w("IF bAlarmTrip_Overtemp_H THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00010000; END_IF; (* Bit 16: Overtemp H *)")
    w("IF bAlarmTrip_Undertemp_L THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00020000; END_IF; (* Bit 17: Undertemp L *)")
    w("IF bAlarmTrip_Undertemp_LL THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00040000; END_IF; (* Bit 18: Undertemp LL *)")
    w("IF bAlarmTrip_O2_High THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00080000; END_IF; (* Bit 19: O2 High *)")
    w("IF bAlarmTrip_N2_PressureLow THEN dwOvenDiagnosticWord := dwOvenDiagnosticWord OR 16#00100000; END_IF; (* Bit 20: N2 Low *)")
    w("")
    w("END_FUNCTION_BLOCK")
    
    return "\n".join(lines)

if __name__ == "__main__":
    p5 = get_part5()
    print(f"Part 5 length: {len(p5)} characters")
