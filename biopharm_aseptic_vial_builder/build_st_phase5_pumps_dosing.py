def get_phase5_pumps_dosing():
    lines = []
    lines.append("(* ========================================================================================= *)")
    lines.append("(* PHASE 5: 10-HEAD CERAMIC ROTARY VALVELESS PISTON PUMP KINEMATICS & MICRO-VOLUME TRIMMING  *)")
    lines.append("(* 5th-Order S-Curve Needle Trajectory & Anti-Drip Reverse Suckback Meniscus Tracking       *)")
    lines.append("(* ========================================================================================= *)")
    lines.append("(* Normalized Dosing Profile Phase Time Tau [0.0 - 1.0] *)")
    lines.append("IF nFSM_State = STATE_7_SYNCHRONOUS_DOSE_NEEDLE THEN")
    lines.append("    rTau := LIMIT(0.0, rFSM_StateTimer_s / 0.120, 1.0);")
    lines.append("ELSIF nFSM_State = STATE_8_RETRACT_ANTI_DRIP_SUCK THEN")
    lines.append("    rTau := LIMIT(0.0, rFSM_StateTimer_s / 0.030, 1.0);")
    lines.append("ELSE")
    lines.append("    rTau := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("rTau2 := rTau * rTau;")
    lines.append("rTau3 := rTau2 * rTau;")
    lines.append("rTau4 := rTau3 * rTau;")
    lines.append("rTau5 := rTau4 * rTau;")
    lines.append("")
    lines.append("(* 10-Head Synchronous Ceramic Rotary Valveless Piston Actuation *)")
    lines.append("FOR h := 1 TO 10 DO")
    lines.append("    (* --- 1. Ceramic Piston Rotary Valve Angle [deg] --- *)")
    lines.append("    (* 360-degree rotation per index: 0-180 intake suction, 180-360 discharge --- *)")
    lines.append("    aPistonRotaryAngle_deg[h] := aPistonRotaryAngle_deg[h] + ((rPistonRotaryMasterCmd_Pct * 0.01) * 360.0 * (rCycleTime_ms / 150.0));")
    lines.append("    IF aPistonRotaryAngle_deg[h] >= 360.0 THEN")
    lines.append("        aPistonRotaryAngle_deg[h] := aPistonRotaryAngle_deg[h] - 360.0;")
    lines.append("    END_IF;")
    lines.append("")
    lines.append("    (* --- 2. Ceramic Piston Linear Stroke Kinematics [mm] --- *)")
    lines.append("    IF nFSM_State = STATE_7_SYNCHRONOUS_DOSE_NEEDLE THEN")
    lines.append("        (* 5th-Order S-Curve Delivery Stroke: s(tau) = S_max * (10*tau^3 - 15*tau^4 + 6*tau^5) *)")
    lines.append("        aPistonLinearStroke_mm[h] := (rTargetDosingVol_ml / (0.25 * 3.14159265 * 14.0 * 14.0 * 0.001)) * ((10.0 * rTau3) - (15.0 * rTau4) + (6.0 * rTau5));")
    lines.append("        aPistonVolumeDosed_ml[h] := 0.25 * 3.14159265 * 14.0 * 14.0 * aPistonLinearStroke_mm[h] * 0.001;")
    lines.append("    ELSIF nFSM_State = STATE_8_RETRACT_ANTI_DRIP_SUCK THEN")
    lines.append("        (* Anti-Drip Reverse Aspiration Suckback *)")
    lines.append("        aPistonLinearStroke_mm[h] := aPistonLinearStroke_mm[h] - (rSuckbackStroke_mm * rTau);")
    lines.append("        aPistonVolumeDosed_ml[h] := aPistonVolumeDosed_ml[h] - (rSuckbackVolume_ml * rTau);")
    lines.append("    ELSE")
    lines.append("        aPistonLinearStroke_mm[h] := 0.0;")
    lines.append("        aPistonVolumeDosed_ml[h] := 0.0;")
    lines.append("    END_IF;")
    lines.append("")
    lines.append("    (* --- 3. Liquid Meniscus Ascent Inside Vial [mm] --- *)")
    lines.append("    (* Meniscus height = V_dosed / (PI * r_inner^2) *)")
    lines.append("    rMeniscusRise_mm := (aPistonVolumeDosed_ml[h] * 1000.0) / (0.25 * 3.14159265 * rVialNeckInternalDiam_mm * rVialNeckInternalDiam_mm);")
    lines.append("")
    lines.append("    (* --- 4. Diving Needle Bottom-Up Meniscus Tracking Trajectory [mm] --- *)")
    lines.append("    IF nFSM_State = STATE_7_SYNCHRONOUS_DOSE_NEEDLE THEN")
    lines.append("        (* Bottom-up ascent tracking meniscus plus safety offset *)")
    lines.append("        aNeedleZ_mm[h] := 2.00 + rMeniscusRise_mm + rMeniscusOffsetDist_mm;")
    lines.append("        aNeedleV_mps[h] := (aNeedleZ_mm[h] - 2.00) / 0.120 * 0.001;")
    lines.append("        aNeedleClearance_mm[h] := aNeedleZ_mm[h] - rMeniscusRise_mm;")
    lines.append("    ELSIF nFSM_State = STATE_8_RETRACT_ANTI_DRIP_SUCK THEN")
    lines.append("        (* High-speed retract to clear vial top rim *)")
    lines.append("        aNeedleZ_mm[h] := (2.00 + rMeniscusRise_mm + rMeniscusOffsetDist_mm) + ((rDivingNeedleStroke_mm - 20.0) * ((10.0 * rTau3) - (15.0 * rTau4) + (6.0 * rTau5)));")
    lines.append("        aNeedleClearance_mm[h] := aNeedleZ_mm[h] - rMeniscusRise_mm;")
    lines.append("    ELSE")
    lines.append("        aNeedleZ_mm[h] := rDivingNeedleStroke_mm; (* Parked home position *)")
    lines.append("        aNeedleV_mps[h] := 0.0;")
    lines.append("        aNeedleClearance_mm[h] := rDivingNeedleStroke_mm;")
    lines.append("    END_IF;")
    lines.append("")
    lines.append("    (* --- 5. Automated Closed-Loop Peristaltic Micro-Volume Trim --- *)")
    lines.append("    IF nFSM_State = STATE_9_INLINE_100PCT_GROSS_WEIGH THEN")
    lines.append("        rTempDiff := rTargetDosingVol_ml - rDerivedNetDose_ml;")
    lines.append("        aTrimIntegral_ml[h] := aTrimIntegral_ml[h] + (rTempDiff * (rCycleTime_ms * 0.001));")
    lines.append("        (* Anti-windup clamping on trim integrator *)")
    lines.append("        aTrimIntegral_ml[h] := LIMIT(-0.25, aTrimIntegral_ml[h], 0.25);")
    lines.append("        aMicroTrimOutput_Pct[h] := (rTrimKp * rTempDiff) + (rTrimKi * aTrimIntegral_ml[h]);")
    lines.append("        aMicroTrimOutput_Pct[h] := LIMIT(-5.0, aMicroTrimOutput_Pct[h], 5.0);")
    lines.append("    END_IF;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Map Individual Channel Micro-Trim Commands to Outputs *)")
    lines.append("rMicroTrimPumpCmd_Head1_Pct := 50.0 + aMicroTrimOutput_Pct[1];")
    lines.append("rMicroTrimPumpCmd_Head2_Pct := 50.0 + aMicroTrimOutput_Pct[2];")
    lines.append("rMicroTrimPumpCmd_Head3_Pct := 50.0 + aMicroTrimOutput_Pct[3];")
    lines.append("rMicroTrimPumpCmd_Head4_Pct := 50.0 + aMicroTrimOutput_Pct[4];")
    lines.append("rMicroTrimPumpCmd_Head5_Pct := 50.0 + aMicroTrimOutput_Pct[5];")
    lines.append("rMicroTrimPumpCmd_Head6_Pct := 50.0 + aMicroTrimOutput_Pct[6];")
    lines.append("rMicroTrimPumpCmd_Head7_Pct := 50.0 + aMicroTrimOutput_Pct[7];")
    lines.append("rMicroTrimPumpCmd_Head8_Pct := 50.0 + aMicroTrimOutput_Pct[8];")
    lines.append("rMicroTrimPumpCmd_Head9_Pct := 50.0 + aMicroTrimOutput_Pct[9];")
    lines.append("rMicroTrimPumpCmd_Head10_Pct := 50.0 + aMicroTrimOutput_Pct[10];")
    lines.append("")
    return "\n".join(lines)
