def get_phase2_state_space():
    lines = []
    lines.append("(* ========================================================================================= *)")
    lines.append("(* PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL STATE-SPACE ESTIMATION & OBSERVER                *)")
    lines.append("(* x[k+1] = A*x[k] + B*u[k] + Ew*w[k], y_hat = C*x_hat + D*u, Kalman Update                  *)")
    lines.append("(* ========================================================================================= *)")
    lines.append("(* Assign Process Disturbance Vector vecW [4] *)")
    lines.append("vecW[1] := rLiquidViscosity_mPas - 4.150;      (* Dynamic formulation viscosity drift [mPas] *)")
    lines.append("vecW[2] := 0.05 * SIN(rFSM_StateTimer_s * 2.5); (* Manifold pump supply pulsation ripple [bar] *)")
    lines.append("IF bBioSafetyBreachDetected THEN")
    lines.append("    vecW[3] := -2.50;                          (* Glove breach / glove box displacement volume [L] *)")
    lines.append("ELSE")
    lines.append("    vecW[3] := 0.00;                          (* Normal glove integrity *)")
    lines.append("END_IF;")
    lines.append("vecW[4] := 0.15 * COS(rFSM_StateTimer_s * 0.8); (* Cleanroom HVAC barometric pressure drift [Pa] *)")
    lines.append("")
    lines.append("(* Step 1: Compute Predicted Output Vector vecY_hat = C * vecX_hat + D * vecU *)")
    lines.append("FOR i := 1 TO 8 DO")
    lines.append("    rSum := 0.0;")
    lines.append("    FOR j := 1 TO 12 DO")
    lines.append("        rSum := rSum + (mC[i, j] * vecX_hat[j]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j := 1 TO 8 DO")
    lines.append("        rSum := rSum + (mD[i, j] * vecU[j]);")
    lines.append("    END_FOR;")
    lines.append("    vecY_hat[i] := rSum;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Step 2: Compute Innovation Residual Vector vecInnov = vecY_meas - vecY_hat *)")
    lines.append("FOR i := 1 TO 8 DO")
    lines.append("    vecInnov[i] := vecY_meas[i] - vecY_hat[i];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Step 3: Compute Next State Estimate vecX_hat[k+1] = A * vecX_hat + B * vecU + K * vecInnov *)")
    lines.append("FOR i := 1 TO 12 DO")
    lines.append("    rSum := 0.0;")
    lines.append("    FOR j := 1 TO 12 DO")
    lines.append("        rSum := rSum + (mA[i, j] * vecX_hat[j]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j := 1 TO 8 DO")
    lines.append("        rSum := rSum + (mB[i, j] * vecU[j]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j := 1 TO 8 DO")
    lines.append("        rSum := rSum + (mK[i, j] * vecInnov[j]);")
    lines.append("    END_FOR;")
    lines.append("    vecX_next[i] := rSum;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Step 4: Propagate True Plant Model vecX[k+1] = A * vecX + B * vecU + Ew * vecW *)")
    lines.append("FOR i := 1 TO 12 DO")
    lines.append("    rSum := 0.0;")
    lines.append("    FOR j := 1 TO 12 DO")
    lines.append("        rSum := rSum + (mA[i, j] * vecX[j]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j := 1 TO 8 DO")
    lines.append("        rSum := rSum + (mB[i, j] * vecU[j]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j := 1 TO 4 DO")
    lines.append("        rSum := rSum + (mEw[i, j] * vecW[j]);")
    lines.append("    END_FOR;")
    lines.append("    vecX[i] := rSum;")
    lines.append("    vecX_hat[i] := vecX_next[i]; (* Update state estimate *)")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Step 5: Extract Cyber-Physical State Feedback *)")
    lines.append("rNeedleLiquidClearance_mm := vecX_hat[5] - vecX_hat[7];")
    lines.append("rCalculatedNetDose_ml := vecX_hat[7] * (3.14159265 * 12.0 * 12.0 / 4000.0); (* Net dose from meniscus *)")
    lines.append("")
    return "\n".join(lines)
