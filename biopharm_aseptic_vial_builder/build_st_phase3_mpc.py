# biopharm_aseptic_vial_builder/build_st_phase3_mpc.py

def get_phase3_mpc():
    lines = []
    lines.append("(* ========================================================================================= *)")
    lines.append("(* PHASE 3: RECEDING-HORIZON MPC OPTIMIZATION WITH PROJECTED GRADIENT DESCENT (PGD)          *)")
    lines.append("(* Minimizes Meniscus Needle Dive Splashing, Pressure Deviation & Actuator Slew at 400 VPM  *)")
    lines.append("(* ========================================================================================= *)")
    lines.append("(* Step 1: Define Dynamic Recipe Target Trajectory vecY_ref [8] *)")
    lines.append("IF (nFSM_State = STATE_7_SYNCHRONOUS_DOSE_NEEDLE) THEN")
    lines.append("    vecY_ref[1] := rTargetDosingVol_ml / 0.120;             (* Dosing flow velocity target [mL/s] *)")
    lines.append("    vecY_ref[2] := rMeniscusOffsetDist_mm;                  (* Meniscus clearance setpoint [mm] *)")
    lines.append("ELSE")
    lines.append("    vecY_ref[1] := 0.0;")
    lines.append("    vecY_ref[2] := rMeniscusOffsetDist_mm + 5.0;            (* Parked clearance *)")
    lines.append("END_IF;")
    lines.append("vecY_ref[3] := rVotedTareWeight_mg + (rTargetDosingVol_ml * rLiquidDensity_g_cm3 * 1000.0);")
    lines.append("vecY_ref[4] := rIsolatorDiffPress_Set_Pa;                  (* Isolator pressure target [Pa] *)")
    lines.append("vecY_ref[5] := rLaminarAirVelocity_Set_mps;              (* Laminar airflow target [m/s] *)")
    lines.append("IF (nFSM_State = STATE_2_H2O2_BIO_DECON_DWELL) THEN")
    lines.append("    vecY_ref[6] := rVHP_DeconTargetConc_ppm;              (* 1200 ppm bio-decon target *)")
    lines.append("ELSIF (nFSM_State = STATE_3_CATALYTIC_AERATION) THEN")
    lines.append("    vecY_ref[6] := 0.0;                                   (* Purge target < 1 ppm *)")
    lines.append("ELSE")
    lines.append("    vecY_ref[6] := 0.0;")
    lines.append("END_IF;")
    lines.append("vecY_ref[7] := rVHP_ConditioningRH_Set_Pct;               (* Target chamber humidity [%] *)")
    lines.append("vecY_ref[8] := rCrimpForce_Nominal_N;                     (* 145 N RSF capper force *)")
    lines.append("")
    lines.append("(* Step 2: Initialize Optimization Vector from Prior Scan vecU_opt = vecU_prev *)")
    lines.append("FOR m := 1 TO 8 DO")
    lines.append("    vecU_opt[m] := vecU_prev[m];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Step 3: Unrolled Projected Gradient Descent (PGD) Solver (8 Iterations) *)")
    lines.append("FOR iter := 1 TO 8 DO")
    lines.append("    (* --- Sub-step A: Forward Simulation over Prediction Horizon Np = 6 --- *)")
    lines.append("    FOR k := 1 TO 6 DO")
    lines.append("        FOR i := 1 TO 12 DO")
    lines.append("            rSum := 0.0;")
    lines.append("            IF k = 1 THEN")
    lines.append("                FOR j := 1 TO 12 DO")
    lines.append("                    rSum := rSum + (mA[i, j] * vecX_hat[j]);")
    lines.append("                END_FOR;")
    lines.append("            ELSE")
    lines.append("                FOR j := 1 TO 12 DO")
    lines.append("                    rSum := rSum + (mA[i, j] * vecPredX[k - 1, j]);")
    lines.append("                END_FOR;")
    lines.append("            END_IF;")
    lines.append("            FOR j := 1 TO 8 DO")
    lines.append("                rSum := rSum + (mB[i, j] * vecU_opt[j]);")
    lines.append("            END_FOR;")
    lines.append("            vecPredX[k, i] := rSum;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Output Prediction *)")
    lines.append("        FOR i := 1 TO 8 DO")
    lines.append("            rSum := 0.0;")
    lines.append("            FOR j := 1 TO 12 DO")
    lines.append("                rSum := rSum + (mC[i, j] * vecPredX[k, j]);")
    lines.append("            END_FOR;")
    lines.append("            FOR j := 1 TO 8 DO")
    lines.append("                rSum := rSum + (mD[i, j] * vecU_opt[j]);")
    lines.append("            END_FOR;")
    lines.append("            vecPredY[k, i] := rSum;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* --- Sub-step B: Compute Quadratic Cost Functional J --- *)")
    lines.append("    rCostTotal := 0.0;")
    lines.append("    FOR k := 1 TO 6 DO")
    lines.append("        FOR i := 1 TO 8 DO")
    lines.append("            rTempDiff := vecPredY[k, i] - vecY_ref[i];")
    lines.append("            rCostTotal := rCostTotal + (mQ[i, i] * rTempDiff * rTempDiff);")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("    FOR i := 1 TO 8 DO")
    lines.append("        rCostTotal := rCostTotal + (mR[i, i] * vecU_opt[i] * vecU_opt[i]);")
    lines.append("        rTempDiff := vecU_opt[i] - vecU_prev[i];")
    lines.append("        rCostTotal := rCostTotal + (mS[i, i] * rTempDiff * rTempDiff);")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* --- Sub-step C: Gradient Calculation vecGrad = dJ/du --- *)")
    lines.append("    FOR m := 1 TO 8 DO")
    lines.append("        rSum := 0.0;")
    lines.append("        FOR k := 1 TO 6 DO")
    lines.append("            FOR i := 1 TO 8 DO")
    lines.append("                rTempDiff := vecPredY[k, i] - vecY_ref[i];")
    lines.append("                (* Approximate sensitivity dy_i/du_m = mD[i,m] + mC[i,:]*mB[:,m] *)")
    lines.append("                rTemp1 := mD[i, m];")
    lines.append("                FOR j := 1 TO 12 DO")
    lines.append("                    rTemp1 := rTemp1 + (mC[i, j] * mB[j, m]);")
    lines.append("                END_FOR;")
    lines.append("                rSum := rSum + (2.0 * mQ[i, i] * rTempDiff * rTemp1);")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("        (* Effort and Slew Penalties *)")
    lines.append("        rSum := rSum + (2.0 * mR[m, m] * vecU_opt[m]);")
    lines.append("        rSum := rSum + (2.0 * mS[m, m] * (vecU_opt[m] - vecU_prev[m]));")
    lines.append("        vecGrad[m] := rSum;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* --- Sub-step D: Gradient Step & Projection with Slew Limiting --- *)")
    lines.append("    FOR m := 1 TO 8 DO")
    lines.append("        vecU_opt[m] := vecU_opt[m] - (rStepAlpha * vecGrad[m]);")
    lines.append("        (* Hard Box Actuator Limits [0.0 - 100.0 %] *)")
    lines.append("        IF vecU_opt[m] < 0.0 THEN")
    lines.append("            vecU_opt[m] := 0.0;")
    lines.append("        ELSIF vecU_opt[m] > 100.0 THEN")
    lines.append("            vecU_opt[m] := 100.0;")
    lines.append("        END_IF;")
    lines.append("        (* Rate of Change Slew Rate Limiting *)")
    lines.append("        IF (vecU_opt[m] - vecU_prev[m]) > rSlewLimit_PctPerScan THEN")
    lines.append("            vecU_opt[m] := vecU_prev[m] + rSlewLimit_PctPerScan;")
    lines.append("        ELSIF (vecU_prev[m] - vecU_opt[m]) > rSlewLimit_PctPerScan THEN")
    lines.append("            vecU_opt[m] := vecU_prev[m] - rSlewLimit_PctPerScan;")
    lines.append("        END_IF;")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Step 4: Dispatch Actuator Commands & Update Plant Input Vector *)")
    lines.append("rPistonLinearMasterCmd_Pct := vecU_opt[1];")
    lines.append("rPistonRotaryMasterCmd_Pct := vecU_opt[2];")
    lines.append("rDivingNeedleServoCmd_Pct  := vecU_opt[3];")
    lines.append("rIsolatorSupplyFanSpeed_Pct:= vecU_opt[5];")
    lines.append("rIsolatorExhaustDamper_Pct := vecU_opt[6];")
    lines.append("rVHP_EvaporatorInjection_Pct:= vecU_opt[7];")
    lines.append("rCapperServoForceCmd_Pct   := vecU_opt[8];")
    lines.append("")
    lines.append("FOR m := 1 TO 8 DO")
    lines.append("    vecU[m] := vecU_opt[m];")
    lines.append("    vecU_prev[m] := vecU_opt[m];")
    lines.append("END_FOR;")
    lines.append("")
    return "\n".join(lines)
