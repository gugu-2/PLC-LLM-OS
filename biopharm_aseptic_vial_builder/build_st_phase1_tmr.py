# biopharm_aseptic_vial_builder/build_st_phase1_tmr.py

def get_phase1_tmr():
    lines = []
    lines.append("(* ========================================================================================= *)")
    lines.append("(* PHASE 1: 2oo3 TRIPLE MODULAR REDUNDANCY (TMR) VOTING WITH DISCREPANCY TIMERS            *)")
    lines.append("(* Bumpless Degradation Across 7 Critical In-Line CQA Instrumentation Channels               *)")
    lines.append("(* ========================================================================================= *)")

    banks = [
        ("Tare", "rTareLoadCell_ChA_mg", "rTareLoadCell_ChB_mg", "rTareLoadCell_ChC_mg", "rTol_Tare_mg", "rTMR_Tare"),
        ("Gross", "rGrossLoadCell_ChA_mg", "rGrossLoadCell_ChB_mg", "rGrossLoadCell_ChC_mg", "rTol_Gross_mg", "rTMR_Gross"),
        ("IsoPress", "rIsoDiffPress_ChA_Pa", "rIsoDiffPress_ChB_Pa", "rIsoDiffPress_ChC_Pa", "rTol_IsoDiffPress_Pa", "rTMR_IsoPress"),
        ("VHP", "rVHP_Conc_ChA_ppm", "rVHP_Conc_ChB_ppm", "rVHP_Conc_ChC_ppm", "rTol_VHP_ppm", "rTMR_VHP"),
        ("Glove", "rGlovePress_ChA_Pa", "rGlovePress_ChB_Pa", "rGlovePress_ChC_Pa", "rTol_GlovePress_Pa", "rTMR_Glove"),
        ("Laminar", "rLaminarVelocity_ChA_mps", "rLaminarVelocity_ChB_mps", "rLaminarVelocity_ChC_mps", "rTol_LaminarAir_mps", "rTMR_Laminar"),
        ("Crimp", "rCrimpForce_ChA_N", "rCrimpForce_ChB_N", "rCrimpForce_ChC_N", "rTol_CrimpForce_N", "rTMR_Crimp")
    ]

    for name, chA, chB, chC, tol, pfx in banks:
        lines.append(f"(* --- 2oo3 Voting Bank: {name} --- *)")
        lines.append(f"(* Median Selection *)")
        lines.append(f"{pfx}_Mid := MAX(MIN({chA}, {chB}), MIN(MAX({chA}, {chB}), {chC}));")
        lines.append(f"{pfx}_DiffAB := ABS({chA} - {chB});")
        lines.append(f"{pfx}_DiffBC := ABS({chB} - {chC});")
        lines.append(f"{pfx}_DiffCA := ABS({chC} - {chA});")
        lines.append("")
        lines.append(f"(* Discrepancy Timer - Channel A *)")
        lines.append(f"IF ({pfx}_DiffAB > {tol}) AND ({pfx}_DiffCA > {tol}) THEN")
        lines.append(f"    {pfx}_TimerA_ms := {pfx}_TimerA_ms + rCycleTime_ms;")
        lines.append(f"    IF {pfx}_TimerA_ms >= rTMR_DiscrepancyLimit_ms THEN")
        lines.append(f"        {pfx}_FaultA := TRUE;")
        lines.append(f"    END_IF;")
        lines.append(f"ELSE")
        lines.append(f"    {pfx}_TimerA_ms := MAX(0.0, {pfx}_TimerA_ms - (rCycleTime_ms * 0.5));")
        lines.append(f"    IF NOT bEmergencyStop THEN")
        lines.append(f"        {pfx}_FaultA := FALSE;")
        lines.append(f"    END_IF;")
        lines.append(f"END_IF;")
        lines.append("")
        lines.append(f"(* Discrepancy Timer - Channel B *)")
        lines.append(f"IF ({pfx}_DiffAB > {tol}) AND ({pfx}_DiffBC > {tol}) THEN")
        lines.append(f"    {pfx}_TimerB_ms := {pfx}_TimerB_ms + rCycleTime_ms;")
        lines.append(f"    IF {pfx}_TimerB_ms >= rTMR_DiscrepancyLimit_ms THEN")
        lines.append(f"        {pfx}_FaultB := TRUE;")
        lines.append(f"    END_IF;")
        lines.append(f"ELSE")
        lines.append(f"    {pfx}_TimerB_ms := MAX(0.0, {pfx}_TimerB_ms - (rCycleTime_ms * 0.5));")
        lines.append(f"    IF NOT bEmergencyStop THEN")
        lines.append(f"        {pfx}_FaultB := FALSE;")
        lines.append(f"    END_IF;")
        lines.append(f"END_IF;")
        lines.append("")
        lines.append(f"(* Discrepancy Timer - Channel C *)")
        lines.append(f"IF ({pfx}_DiffBC > {tol}) AND ({pfx}_DiffCA > {tol}) THEN")
        lines.append(f"    {pfx}_TimerC_ms := {pfx}_TimerC_ms + rCycleTime_ms;")
        lines.append(f"    IF {pfx}_TimerC_ms >= rTMR_DiscrepancyLimit_ms THEN")
        lines.append(f"        {pfx}_FaultC := TRUE;")
        lines.append(f"    END_IF;")
        lines.append(f"ELSE")
        lines.append(f"    {pfx}_TimerC_ms := MAX(0.0, {pfx}_TimerC_ms - (rCycleTime_ms * 0.5));")
        lines.append(f"    IF NOT bEmergencyStop THEN")
        lines.append(f"        {pfx}_FaultC := FALSE;")
        lines.append(f"    END_IF;")
        lines.append(f"END_IF;")
        lines.append("")
        lines.append(f"(* Bumpless Degradation Logic: 2oo3 -> 1oo2 -> 1oo1 -> Failsafe *)")
        lines.append(f"IF (NOT {pfx}_FaultA) AND (NOT {pfx}_FaultB) AND (NOT {pfx}_FaultC) THEN")
        lines.append(f"    {pfx}_Voted := {pfx}_Mid;")
        lines.append(f"    {pfx}_Degraded_1oo2 := FALSE;")
        lines.append(f"    {pfx}_Degraded_1oo1 := FALSE;")
        lines.append(f"    {pfx}_BankFailure := FALSE;")
        lines.append(f"ELSIF {pfx}_FaultA AND (NOT {pfx}_FaultB) AND (NOT {pfx}_FaultC) THEN")
        lines.append(f"    {pfx}_Voted := 0.5 * ({chB} + {chC});")
        lines.append(f"    {pfx}_Degraded_1oo2 := TRUE;")
        lines.append(f"    {pfx}_Degraded_1oo1 := FALSE;")
        lines.append(f"    {pfx}_BankFailure := FALSE;")
        lines.append(f"ELSIF (NOT {pfx}_FaultA) AND {pfx}_FaultB AND (NOT {pfx}_FaultC) THEN")
        lines.append(f"    {pfx}_Voted := 0.5 * ({chA} + {chC});")
        lines.append(f"    {pfx}_Degraded_1oo2 := TRUE;")
        lines.append(f"    {pfx}_Degraded_1oo1 := FALSE;")
        lines.append(f"    {pfx}_BankFailure := FALSE;")
        lines.append(f"ELSIF (NOT {pfx}_FaultA) AND (NOT {pfx}_FaultB) AND {pfx}_FaultC THEN")
        lines.append(f"    {pfx}_Voted := 0.5 * ({chA} + {chB});")
        lines.append(f"    {pfx}_Degraded_1oo2 := TRUE;")
        lines.append(f"    {pfx}_Degraded_1oo1 := FALSE;")
        lines.append(f"    {pfx}_BankFailure := FALSE;")
        lines.append(f"ELSIF (NOT {pfx}_FaultA) AND {pfx}_FaultB AND {pfx}_FaultC THEN")
        lines.append(f"    {pfx}_Voted := {chA};")
        lines.append(f"    {pfx}_Degraded_1oo2 := FALSE;")
        lines.append(f"    {pfx}_Degraded_1oo1 := TRUE;")
        lines.append(f"    {pfx}_BankFailure := FALSE;")
        lines.append(f"ELSIF {pfx}_FaultA AND (NOT {pfx}_FaultB) AND {pfx}_FaultC THEN")
        lines.append(f"    {pfx}_Voted := {chB};")
        lines.append(f"    {pfx}_Degraded_1oo2 := FALSE;")
        lines.append(f"    {pfx}_Degraded_1oo1 := TRUE;")
        lines.append(f"    {pfx}_BankFailure := FALSE;")
        lines.append(f"ELSIF {pfx}_FaultA AND {pfx}_FaultB AND (NOT {pfx}_FaultC) THEN")
        lines.append(f"    {pfx}_Voted := {chC};")
        lines.append(f"    {pfx}_Degraded_1oo2 := FALSE;")
        lines.append(f"    {pfx}_Degraded_1oo1 := TRUE;")
        lines.append(f"    {pfx}_BankFailure := FALSE;")
        lines.append(f"ELSE")
        lines.append(f"    {pfx}_Voted := {pfx}_Mid;")
        lines.append(f"    {pfx}_BankFailure := TRUE;")
        lines.append(f"END_IF;")
        lines.append("")

    lines.append("(* Assign Voted Outputs *)")
    lines.append("rVotedTareWeight_mg := rTMR_Tare_Voted;")
    lines.append("rVotedGrossWeight_mg := rTMR_Gross_Voted;")
    lines.append("rVotedIsoDiffPress_Pa := rTMR_IsoPress_Voted;")
    lines.append("rVotedVHP_Conc_ppm := rTMR_VHP_Voted;")
    lines.append("rVotedLaminarVelocity_mps := rTMR_Laminar_Voted;")
    lines.append("rVotedCrimpForce_N := rTMR_Crimp_Voted;")
    lines.append("")
    lines.append("(* Assemble Measurement Vector vecY_meas [8] *)")
    lines.append("vecY_meas[1] := 0.0; (* Flow rate proxy *)")
    lines.append("vecY_meas[2] := aNeedleClearance_mm[1];")
    lines.append("vecY_meas[3] := rVotedGrossWeight_mg;")
    lines.append("vecY_meas[4] := rVotedIsoDiffPress_Pa;")
    lines.append("vecY_meas[5] := rVotedLaminarVelocity_mps;")
    lines.append("vecY_meas[6] := rVotedVHP_Conc_ppm;")
    lines.append("vecY_meas[7] := rIsolatorRH_Pct;")
    lines.append("vecY_meas[8] := rVotedCrimpForce_N;")
    lines.append("")
    return "\n".join(lines)
