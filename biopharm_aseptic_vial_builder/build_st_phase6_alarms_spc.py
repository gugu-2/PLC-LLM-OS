# biopharm_aseptic_vial_builder/build_st_phase6_alarms_spc.py

def get_phase6_alarms_spc():
    lines = []
    lines.append("(* ========================================================================================= *)")
    lines.append("(* PHASE 6: ISA-18.2 MULTI-TIERED ALARMS, 30-SAMPLE SPC & BIT-PACKED TELEMETRY DWORDS       *)")
    lines.append("(* Statistical Process Control (Mean, Sigma, Cp, Cpk) & Container Closure Integrity (CCI)   *)")
    lines.append("(* ========================================================================================= *)")
    lines.append("(* Step 1: Statistical Process Control (SPC) Circular Buffer Update *)")
    lines.append("IF (nFSM_State = STATE_12_OUTFEED_DEFECT_EJECT) AND bStateEntryTrigger THEN")
    lines.append("    aDosingHist_ml[nHistIdx] := rDerivedNetDose_ml;")
    lines.append("    aTareHist_mg[nHistIdx]   := rFilteredTare_mg;")
    lines.append("    aGrossHist_mg[nHistIdx]  := rFilteredGross_mg;")
    lines.append("    aCrimpHist_N[nHistIdx]   := rVotedCrimpForce_N;")
    lines.append("    nHistIdx := (nHistIdx MOD 30) + 1;")
    lines.append("    IF nHistCount < 30 THEN")
    lines.append("        nHistCount := nHistCount + 1;")
    lines.append("    END_IF;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Step 2: Calculate Moving Average, Variance, Sigma, Cp & Cpk *)")
    lines.append("IF nHistCount > 0 THEN")
    lines.append("    rMovingSum_ml := 0.0;")
    lines.append("    FOR i := 1 TO nHistCount DO")
    lines.append("        rMovingSum_ml := rMovingSum_ml + aDosingHist_ml[i];")
    lines.append("    END_FOR;")
    lines.append("    rDosingMean_ml := rMovingSum_ml / INT_TO_REAL(nHistCount);")
    lines.append("")
    lines.append("    IF nHistCount > 1 THEN")
    lines.append("        rMovingSumSquares_ml := 0.0;")
    lines.append("        FOR i := 1 TO nHistCount DO")
    lines.append("            rTempDiff := aDosingHist_ml[i] - rDosingMean_ml;")
    lines.append("            rMovingSumSquares_ml := rMovingSumSquares_ml + (rTempDiff * rTempDiff);")
    lines.append("        END_FOR;")
    lines.append("        rDosingVariance_ml2 := rMovingSumSquares_ml / INT_TO_REAL(nHistCount - 1);")
    lines.append("        rDosingStdDev_ml := SQRT(MAX(0.0000001, rDosingVariance_ml2));")
    lines.append("    ELSE")
    lines.append("        rDosingStdDev_ml := 0.0010;")
    lines.append("    END_IF;")
    lines.append("")
    lines.append("    (* Process Capability Formulations *)")
    lines.append("    rUSL_Dose_ml := rTargetDosingVol_ml * (1.0 + (rDosingTolerance_Pct * 0.01));")
    lines.append("    rLSL_Dose_ml := rTargetDosingVol_ml * (1.0 - (rDosingTolerance_Pct * 0.01));")
    lines.append("    IF rDosingStdDev_ml > 0.000001 THEN")
    lines.append("        rDosingCp := (rUSL_Dose_ml - rLSL_Dose_ml) / (6.0 * rDosingStdDev_ml);")
    lines.append("        rTemp1 := (rUSL_Dose_ml - rDosingMean_ml) / (3.0 * rDosingStdDev_ml);")
    lines.append("        rTemp2 := (rDosingMean_ml - rLSL_Dose_ml) / (3.0 * rDosingStdDev_ml);")
    lines.append("        rDosingCpk := MIN(rTemp1, rTemp2);")
    lines.append("    ELSE")
    lines.append("        rDosingCp := 2.0;")
    lines.append("        rDosingCpk := 2.0;")
    lines.append("    END_IF;")
    lines.append("ELSE")
    lines.append("    rDosingMean_ml := rTargetDosingVol_ml;")
    lines.append("    rDosingStdDev_ml := 0.001;")
    lines.append("    rDosingCp := 2.0;")
    lines.append("    rDosingCpk := 2.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Step 3: ISA-18.2 Priority 1 Critical Alarms (dwAlarm_Critical_Trips) *)")
    lines.append("dwAlarm_Critical_Trips := 16#00000000;")
    lines.append("(* Bit 0: Isolator Differential Pressure LL Loss of Containment Trip *)")
    lines.append("IF rVotedIsoDiffPress_Pa < rIsoPress_TripLL_Pa THEN")
    lines.append("    rAlarmTimer_IsoPressLL_ms := rAlarmTimer_IsoPressLL_ms + rCycleTime_ms;")
    lines.append("    IF rAlarmTimer_IsoPressLL_ms >= 100.0 THEN")
    lines.append("        dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000001;")
    lines.append("    END_IF;")
    lines.append("ELSE")
    lines.append("    rAlarmTimer_IsoPressLL_ms := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Bit 1: Glove Port Pressure Decay Breach *)")
    lines.append("IF bBioSafetyBreachDetected OR (rLeakTestDecay_Pa_min > rGloveLeakMaxDecayRate_Pa_min AND nFSM_State = STATE_0_PRESSURE_DECAY_LEAK_TEST) THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000002;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Bit 2: Grade A Laminar Airflow LL Trip *)")
    lines.append("IF (rVotedLaminarVelocity_mps < rLaminar_TripLL_mps) AND (nFSM_State >= STATE_4_GRADE_A_LAMINAR_AIR_LOCK) THEN")
    lines.append("    rAlarmTimer_LaminarLL_ms := rAlarmTimer_LaminarLL_ms + rCycleTime_ms;")
    lines.append("    IF rAlarmTimer_LaminarLL_ms >= 500.0 THEN")
    lines.append("        dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000004;")
    lines.append("    END_IF;")
    lines.append("ELSE")
    lines.append("    rAlarmTimer_LaminarLL_ms := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Bit 3: VHP Bio-Decon Low Concentration Trip *)")
    lines.append("IF (nFSM_State = STATE_2_H2O2_BIO_DECON_DWELL) AND (rVotedVHP_Conc_ppm < rVHP_TripLL_ppm) AND (rFSM_StateTimer_s > 120.0) THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000008;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Bit 4: Emergency Stop Activated *)")
    lines.append("IF bEmergencyStop THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000010;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Bit 5: Infeed Starwheel Jam *)")
    lines.append("IF bVialInfeedJamDetected THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000020;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Bit 6: Capper Severe Glass Neck Crush Fault *)")
    lines.append("IF rVotedCrimpForce_N > rCrimp_TripHH_N THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000040;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Bits 7-9: TMR Sensor Bank Total Failures *)")
    lines.append("IF bTMR_Tare_BankFailure THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000080;")
    lines.append("END_IF;")
    lines.append("IF bTMR_Gross_BankFailure THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000100;")
    lines.append("END_IF;")
    lines.append("IF bTMR_IsoPress_BankFailure THEN")
    lines.append("    dwAlarm_Critical_Trips := dwAlarm_Critical_Trips OR 16#00000200;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Step 4: ISA-18.2 Priority 2 & 3 Process Warnings (dwAlarm_Process_Warnings) *)")
    lines.append("dwAlarm_Process_Warnings := 16#00000000;")
    lines.append("IF rVotedIsoDiffPress_Pa > (rIsoPress_TripH_Pa + rIsoPress_Deadband_Pa) THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000001;")
    lines.append("END_IF;")
    lines.append("IF rVotedIsoDiffPress_Pa < (rIsoPress_TripL_Pa - rIsoPress_Deadband_Pa) THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000002;")
    lines.append("END_IF;")
    lines.append("IF rVotedLaminarVelocity_mps > (rLaminar_TripHH_mps + rLaminar_Deadband_mps) THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000004;")
    lines.append("END_IF;")
    lines.append("IF bStopperHopperLowLevel THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000008;")
    lines.append("END_IF;")
    lines.append("IF bAluminumCapChuteEmpty THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000010;")
    lines.append("END_IF;")
    lines.append("IF NOT bNitrogenPurgePressureOK THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000020;")
    lines.append("END_IF;")
    lines.append("IF rDosingCpk < 1.33 THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000040;")
    lines.append("END_IF;")
    lines.append("IF (nFSM_State = STATE_1_VHP_CONDITIONING) AND (rIsolatorRH_Pct > rVHP_ConditioningRH_Set_Pct) THEN")
    lines.append("    dwAlarm_Process_Warnings := dwAlarm_Process_Warnings OR 16#00000080;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Step 5: TMR Sensor Bank Diagnostic Health Status (dwTMR_Sensor_Health) *)")
    lines.append("dwTMR_Sensor_Health := 16#00000000;")
    lines.append("IF bTMR_Tare_FaultA THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000001; END_IF;")
    lines.append("IF bTMR_Tare_FaultB THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000002; END_IF;")
    lines.append("IF bTMR_Tare_FaultC THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000004; END_IF;")
    lines.append("IF bTMR_Tare_Degraded_1oo2 OR bTMR_Tare_Degraded_1oo1 THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000008; END_IF;")
    lines.append("")
    lines.append("IF bTMR_Gross_FaultA THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000010; END_IF;")
    lines.append("IF bTMR_Gross_FaultB THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000020; END_IF;")
    lines.append("IF bTMR_Gross_FaultC THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000040; END_IF;")
    lines.append("IF bTMR_Gross_Degraded_1oo2 OR bTMR_Gross_Degraded_1oo1 THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000080; END_IF;")
    lines.append("")
    lines.append("IF bTMR_IsoPress_FaultA THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000100; END_IF;")
    lines.append("IF bTMR_IsoPress_FaultB THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000200; END_IF;")
    lines.append("IF bTMR_IsoPress_FaultC THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000400; END_IF;")
    lines.append("IF bTMR_IsoPress_Degraded_1oo2 OR bTMR_IsoPress_Degraded_1oo1 THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00000800; END_IF;")
    lines.append("")
    lines.append("IF bTMR_VHP_FaultA THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00001000; END_IF;")
    lines.append("IF bTMR_VHP_FaultB THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00002000; END_IF;")
    lines.append("IF bTMR_VHP_FaultC THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00004000; END_IF;")
    lines.append("IF bTMR_VHP_Degraded_1oo2 OR bTMR_VHP_Degraded_1oo1 THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00008000; END_IF;")
    lines.append("")
    lines.append("IF bTMR_Glove_FaultA THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00010000; END_IF;")
    lines.append("IF bTMR_Glove_FaultB THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00020000; END_IF;")
    lines.append("IF bTMR_Glove_FaultC THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00040000; END_IF;")
    lines.append("IF bTMR_Glove_Degraded_1oo2 OR bTMR_Glove_Degraded_1oo1 THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00080000; END_IF;")
    lines.append("")
    lines.append("IF bTMR_Laminar_FaultA THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00100000; END_IF;")
    lines.append("IF bTMR_Laminar_FaultB THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00200000; END_IF;")
    lines.append("IF bTMR_Laminar_FaultC THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00400000; END_IF;")
    lines.append("IF bTMR_Laminar_Degraded_1oo2 OR bTMR_Laminar_Degraded_1oo1 THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#00800000; END_IF;")
    lines.append("")
    lines.append("IF bTMR_Crimp_FaultA THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#01000000; END_IF;")
    lines.append("IF bTMR_Crimp_FaultB THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#02000000; END_IF;")
    lines.append("IF bTMR_Crimp_FaultC THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#04000000; END_IF;")
    lines.append("IF bTMR_Crimp_Degraded_1oo2 OR bTMR_Crimp_Degraded_1oo1 THEN dwTMR_Sensor_Health := dwTMR_Sensor_Health OR 16#08000000; END_IF;")
    lines.append("")
    lines.append("(* Step 6: Telemetry Status DWORDs *)")
    lines.append("dwStatus_FSM_Phase := SHL(INT_TO_DWORD(nFSM_State), 0);")
    lines.append("IF bLineRunningAseptic THEN dwStatus_FSM_Phase := dwStatus_FSM_Phase OR 16#00010000; END_IF;")
    lines.append("IF bLeakTestPassed THEN dwStatus_FSM_Phase := dwStatus_FSM_Phase OR 16#00020000; END_IF;")
    lines.append("IF bVHP_DeconCompleted THEN dwStatus_FSM_Phase := dwStatus_FSM_Phase OR 16#00040000; END_IF;")
    lines.append("IF bAerationCompleted THEN dwStatus_FSM_Phase := dwStatus_FSM_Phase OR 16#00080000; END_IF;")
    lines.append("IF bEmergencyLockdownActive THEN dwStatus_FSM_Phase := dwStatus_FSM_Phase OR 16#00100000; END_IF;")
    lines.append("")
    lines.append("dwStatus_Pumps_Active := 16#00000000;")
    lines.append("FOR h := 1 TO 10 DO")
    lines.append("    IF aPistonVolumeDosed_ml[h] > 0.001 THEN")
    lines.append("        dwStatus_Pumps_Active := dwStatus_Pumps_Active OR SHL(16#00000001, h - 1);")
    lines.append("    END_IF;")
    lines.append("    IF ABS(aMicroTrimOutput_Pct[h]) > 0.05 THEN")
    lines.append("        dwStatus_Pumps_Active := dwStatus_Pumps_Active OR SHL(16#00000001, h + 9);")
    lines.append("    END_IF;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("dwSPC_Quality_Flags := 16#00000000;")
    lines.append("IF rDosingCpk >= 1.33 THEN dwSPC_Quality_Flags := dwSPC_Quality_Flags OR 16#00000001; END_IF;")
    lines.append("IF ABS(rDosingMean_ml - rTargetDosingVol_ml) <= (rTargetDosingVol_ml * rDosingTolerance_Pct * 0.01) THEN dwSPC_Quality_Flags := dwSPC_Quality_Flags OR 16#00000002; END_IF;")
    lines.append("IF NOT bDefectRejectGateActivate THEN dwSPC_Quality_Flags := dwSPC_Quality_Flags OR 16#00000004; END_IF;")
    lines.append("")
    lines.append("END_FUNCTION_BLOCK")
    return "\n".join(lines)
