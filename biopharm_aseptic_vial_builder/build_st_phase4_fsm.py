# biopharm_aseptic_vial_builder/build_st_phase4_fsm.py

def get_phase4_fsm():
    lines = []
    lines.append("(* ========================================================================================= *)")
    lines.append("(* PHASE 4: DETERMINISTIC 14-STAGE PRODUCTION FINITE STATE MACHINE (FSM)                    *)")
    lines.append("(* Compliant with EU GMP Annex 1 Isolator Bio-Decon, High-Speed Dosing & Aseptic Stoppering *)")
    lines.append("(* ========================================================================================= *)")
    lines.append("(* State Elapsed Timer Accumulation *)")
    lines.append("IF nFSM_State = nFSM_PrevState THEN")
    lines.append("    rFSM_StateTimer_s := rFSM_StateTimer_s + (rCycleTime_ms * 0.001);")
    lines.append("    bStateEntryTrigger := FALSE;")
    lines.append("ELSE")
    lines.append("    rFSM_StateTimer_s := 0.0;")
    lines.append("    bStateEntryTrigger := TRUE;")
    lines.append("    nFSM_PrevState := nFSM_State;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Safety Interlock Override: Immediate Transition to Barrier Breach Lockdown *)")
    lines.append("IF (bEmergencyStop OR bBioSafetyBreachDetected OR (rVotedIsoDiffPress_Pa < rIsoPress_TripLL_Pa AND nFSM_State >= STATE_4_GRADE_A_LAMINAR_AIR_LOCK)) AND (nFSM_State <> STATE_13_BARRIER_BREACH_LOCKDOWN) THEN")
    lines.append("    nFSM_State := STATE_13_BARRIER_BREACH_LOCKDOWN;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("CASE nFSM_State OF")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 0: ISOLATOR PRESSURE DECAY LEAK RATE TEST (ISO 10648-2 CLASS 1/2)              *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_0_PRESSURE_DECAY_LEAK_TEST:")
    lines.append("        bLineRunningAseptic := FALSE;")
    lines.append("        bEmergencyLockdownActive := FALSE;")
    lines.append("        rCurrentMachineSpeed_VPM := 0.0;")
    lines.append("        IF bStateEntryTrigger THEN")
    lines.append("            rLeakTestStartPress_Pa := rVotedIsoDiffPress_Pa;")
    lines.append("            bLeakTestPassed := FALSE;")
    lines.append("        END_IF;")
    lines.append("        (* Pressurize to test level and monitor leak rate *)")
    lines.append("        IF rFSM_StateTimer_s < 30.0 THEN")
    lines.append("            rIsolatorSupplyFanSpeed_Pct := 75.0;")
    lines.append("            rIsolatorExhaustDamper_Pct := 5.0;")
    lines.append("        ELSIF rFSM_StateTimer_s < 150.0 THEN")
    lines.append("            rIsolatorSupplyFanSpeed_Pct := 0.0;")
    lines.append("            rIsolatorExhaustDamper_Pct := 0.0;")
    lines.append("            rLeakTestDecay_Pa_min := (rLeakTestStartPress_Pa - rVotedIsoDiffPress_Pa) / ((rFSM_StateTimer_s - 30.0) / 60.0);")
    lines.append("        ELSE")
    lines.append("            IF rLeakTestDecay_Pa_min <= rGloveLeakMaxDecayRate_Pa_min THEN")
    lines.append("                bLeakTestPassed := TRUE;")
    lines.append("                IF bStartExecution THEN")
    lines.append("                    nFSM_State := STATE_1_VHP_CONDITIONING;")
    lines.append("                END_IF;")
    lines.append("            ELSE")
    lines.append("                bLeakTestPassed := FALSE;")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 1: VHP BIO-DECONTAMINATION CONDITIONING PHASE (DEHUMIDIFICATION & PRE-HEAT)     *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_1_VHP_CONDITIONING:")
    lines.append("        bLineRunningAseptic := FALSE;")
    lines.append("        rCurrentMachineSpeed_VPM := 0.0;")
    lines.append("        rIsolatorSupplyFanSpeed_Pct := 45.0;")
    lines.append("        rIsolatorExhaustDamper_Pct := 15.0;")
    lines.append("        (* Heat isolator to 30 deg C and reduce RH < 25% *)")
    lines.append("        IF (rIsolatorTemp_degC >= (rVHP_ConditioningTemp_Set_degC - 2.0)) AND (rIsolatorRH_Pct <= rVHP_ConditioningRH_Set_Pct) THEN")
    lines.append("            nFSM_State := STATE_2_H2O2_BIO_DECON_DWELL;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 2: H2O2 VAPOR INJECTION & BIO-DECONTAMINATION DWELL (1200 PPM, 6-LOG SPORE KILL)*)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_2_H2O2_BIO_DECON_DWELL:")
    lines.append("        bLineRunningAseptic := FALSE;")
    lines.append("        rCurrentMachineSpeed_VPM := 0.0;")
    lines.append("        IF rVotedVHP_Conc_ppm < rVHP_DeconTargetConc_ppm THEN")
    lines.append("            rVHP_InjPumpSpeed_Pct := 65.0;")
    lines.append("        ELSE")
    lines.append("            rVHP_InjPumpSpeed_Pct := 20.0; (* Maintain concentration plateau *)")
    lines.append("        END_IF;")
    lines.append("        IF rFSM_StateTimer_s >= rVHP_DeconDwellTime_s THEN")
    lines.append("            bVHP_DeconCompleted := TRUE;")
    lines.append("            nFSM_State := STATE_3_CATALYTIC_AERATION;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 3: CATALYTIC AERATION & RESIDUAL PURGE (< 0.8 PPM TARGET)                       *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_3_CATALYTIC_AERATION:")
    lines.append("        bLineRunningAseptic := FALSE;")
    lines.append("        rVHP_InjPumpSpeed_Pct := 0.0;")
    lines.append("        rIsolatorSupplyFanSpeed_Pct := 90.0; (* Maximum fresh air flush through catalytic filter *)")
    lines.append("        rIsolatorExhaustDamper_Pct := 90.0;")
    lines.append("        IF rVotedVHP_Conc_ppm <= rVHP_AerationThreshold_ppm THEN")
    lines.append("            bAerationCompleted := TRUE;")
    lines.append("            nFSM_State := STATE_4_GRADE_A_LAMINAR_AIR_LOCK;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 4: GRADE A UNIDIRECTIONAL LAMINAR AIRFLOW STABILIZATION & PRESSURE LOCK (+45 Pa)*)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_4_GRADE_A_LAMINAR_AIR_LOCK:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := 0.0;")
    lines.append("        rIsolatorSupplyFanSpeed_Pct := 58.0;")
    lines.append("        rIsolatorExhaustDamper_Pct := 42.0;")
    lines.append("        (* Verify laminar flow within 0.45 m/s +/- 0.05 and pressure +45 Pa +/- 5 *)")
    lines.append("        IF (ABS(rVotedLaminarVelocity_mps - rLaminarAirVelocity_Set_mps) <= 0.05) AND (ABS(rVotedIsoDiffPress_Pa - rIsolatorDiffPress_Set_Pa) <= 5.0) THEN")
    lines.append("            IF rFSM_StateTimer_s >= 60.0 THEN (* Airborne particulate stabilization dwell *)")
    lines.append("                nFSM_State := STATE_5_VIAL_INFEED_SYNC;")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 5: VIAL INFEED STARWHEEL & ELECTRONIC CAM SYNCHRONIZATION (400 VPM)             *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_5_VIAL_INFEED_SYNC:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        IF bVialInfeedJamDetected THEN")
    lines.append("            rCurrentMachineSpeed_VPM := 0.0;")
    lines.append("        ELSIF rFSM_StateTimer_s >= 0.150 THEN (* 150 ms pitch cycle advance *)")
    lines.append("            nFSM_State := STATE_6_INLINE_100PCT_TARE_WEIGH;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 6: IN-LINE 100% DUAL-PAN EMFR TARE WEIGHING & ZERO TRACKING                     *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_6_INLINE_100PCT_TARE_WEIGH:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        (* First-order filter tare reading *)")
    lines.append("        rFilteredTare_mg := (rEMFR_FilterAlpha * rVotedTareWeight_mg) + ((1.0 - rEMFR_FilterAlpha) * rFilteredTare_mg);")
    lines.append("        IF rFSM_StateTimer_s >= 0.045 THEN (* 45 ms settling window *)")
    lines.append("            nFSM_State := STATE_7_SYNCHRONOUS_DOSE_NEEDLE;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 7: SYNCHRONOUS NEEDLE DIVE & 10-HEAD ROTARY CERAMIC PISTON DOSING               *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_7_SYNCHRONOUS_DOSE_NEEDLE:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        (* Piston dosing stroke execution and MPC meniscus tracking active *)")
    lines.append("        IF rFSM_StateTimer_s >= 0.120 THEN (* 120 ms dosing execution *)")
    lines.append("            nFSM_State := STATE_8_RETRACT_ANTI_DRIP_SUCK;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 8: NEEDLE RETRACT WITH ANTI-DRIP SUCK-BACK & HEADSPACE N2 PURGING              *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_8_RETRACT_ANTI_DRIP_SUCK:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        (* Anti-drip micro-reverse stroke and needle acceleration *)")
    lines.append("        IF rFSM_StateTimer_s >= 0.030 THEN (* 30 ms retraction *)")
    lines.append("            nFSM_State := STATE_9_INLINE_100PCT_GROSS_WEIGH;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 9: IN-LINE 100% GROSS CHECKWEIGHING & REAL-TIME TREND VOLUME TRIMMING          *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_9_INLINE_100PCT_GROSS_WEIGH:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        rFilteredGross_mg := (rEMFR_FilterAlpha * rVotedGrossWeight_mg) + ((1.0 - rEMFR_FilterAlpha) * rFilteredGross_mg);")
    lines.append("        rDerivedNetDose_ml := (rFilteredGross_mg - rFilteredTare_mg) / (rLiquidDensity_g_cm3 * 1000.0);")
    lines.append("        IF rFSM_StateTimer_s >= 0.045 THEN")
    lines.append("            nFSM_State := STATE_10_VACUUM_STOPPER_INSERT;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 10: 24-POCKET ROTARY VACUUM STOPPER PICK & SEAT INSERTION                       *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_10_VACUUM_STOPPER_INSERT:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        IF rFSM_StateTimer_s >= 0.050 THEN")
    lines.append("            nFSM_State := STATE_11_SERVO_CRIMP_INTEGRITY;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 11: 16-HEAD ROTARY ALUMINUM CAP SERVO CRIMPING & RSF INTEGRITY INSPECTION       *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_11_SERVO_CRIMP_INTEGRITY:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        IF rFSM_StateTimer_s >= 0.050 THEN")
    lines.append("            nFSM_State := STATE_12_OUTFEED_DEFECT_EJECT;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 12: OUTFEED DEFECT STARWHEEL PNEUMATIC EJECTION & PRODUCTION DISPATCH           *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_12_OUTFEED_DEFECT_EJECT:")
    lines.append("        bLineRunningAseptic := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := rTargetSpeed_VPM;")
    lines.append("        udiTotalVialsProcessed := udiTotalVialsProcessed + 1;")
    lines.append("        (* Evaluate Defect Criteria *)")
    lines.append("        IF (ABS(rDerivedNetDose_ml - rTargetDosingVol_ml) > (rTargetDosingVol_ml * rDosingTolerance_Pct * 0.01)) THEN")
    lines.append("            bDefectRejectGateActivate := TRUE;")
    lines.append("            udiTotalWeightRejects := udiTotalWeightRejects + 1;")
    lines.append("        ELSIF (ABS(rVotedCrimpForce_N - rCrimpForce_Nominal_N) > rCrimpForce_Tol_N) THEN")
    lines.append("            bDefectRejectGateActivate := TRUE;")
    lines.append("            udiTotalCrimpRejects := udiTotalCrimpRejects + 1;")
    lines.append("        ELSE")
    lines.append("            bDefectRejectGateActivate := FALSE;")
    lines.append("            udiTotalVialsAccepted := udiTotalVialsAccepted + 1;")
    lines.append("        END_IF;")
    lines.append("        (* Loop back to Infeed for continuous continuous 400 VPM production *)")
    lines.append("        IF bStopExecution THEN")
    lines.append("            nFSM_State := STATE_4_GRADE_A_LAMINAR_AIR_LOCK;")
    lines.append("        ELSE")
    lines.append("            nFSM_State := STATE_5_VIAL_INFEED_SYNC;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    (* STAGE 13: ISOLATOR BARRIER BREACH EMERGENCY CONTAINMENT LOCKDOWN                      *)")
    lines.append("    (* ------------------------------------------------------------------------------------- *)")
    lines.append("    STATE_13_BARRIER_BREACH_LOCKDOWN:")
    lines.append("        bLineRunningAseptic := FALSE;")
    lines.append("        bEmergencyLockdownActive := TRUE;")
    lines.append("        rCurrentMachineSpeed_VPM := 0.0;")
    lines.append("        rPistonLinearMasterCmd_Pct := 0.0;")
    lines.append("        rDivingNeedleServoCmd_Pct := 0.0;")
    lines.append("        rCapperServoForceCmd_Pct := 0.0;")
    lines.append("        rVHP_EvaporatorInjection_Pct := 0.0;")
    lines.append("        (* Emergency damper seal *)")
    lines.append("        rIsolatorSupplyFanSpeed_Pct := 0.0;")
    lines.append("        rIsolatorExhaustDamper_Pct := 0.0;")
    lines.append("        (* Reset on acknowledge and interlocks restored *)")
    lines.append("        IF bAcknowledgeAlarms AND NOT bEmergencyStop AND NOT bBioSafetyBreachDetected THEN")
    lines.append("            nFSM_State := STATE_0_PRESSURE_DECAY_LEAK_TEST;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("END_CASE;")
    lines.append("")
    return "\n".join(lines)
