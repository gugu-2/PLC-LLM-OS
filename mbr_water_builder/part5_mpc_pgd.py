# Part 5: Receding-Horizon MPC with Projected Gradient Descent (PGD)
import sys

def get_part5_mpc_pgd():
    code = []
    code.append("(* ============================================================================================== *)")
    code.append("(* PHASE 3: RECEDING-HORIZON MPC OPTIMIZATION WITH PROJECTED GRADIENT DESCENT (PGD)              *)")
    code.append("(* ============================================================================================== *)")
    code.append("    (* Initialize Control Trajectory Buffer from Current Actuator Settings *)")
    code.append("    FOR c_step := 1 TO 3 DO")
    code.append("        FOR j := 1 TO 8 DO")
    code.append("            trajU[c_step, j] := vecU_Current[j];")
    code.append("        END_FOR;")
    code.append("    END_FOR;")
    code.append("")
    code.append("    (* --- Projected Gradient Descent Iterative Optimization (10 Iterations) --- *)")
    code.append("    FOR iter := 1 TO 10 DO")
    code.append("        (* Step 3.1: Forward State Trajectory Simulation over Prediction Horizon (Np = 5) *)")
    code.append("        FOR p_step := 1 TO 5 DO")
    code.append("            (* Select active control step: hold final control after control horizon Nc = 3 *)")
    code.append("            IF p_step <= 3 THEN")
    code.append("                c_step := p_step;")
    code.append("            ELSE")
    code.append("                c_step := 3;")
    code.append("            END_IF;")
    code.append("")
    code.append("            (* Propagate x[p] = A * x[p-1] + B * u[c] + E * d *)")
    code.append("            FOR i := 1 TO 8 DO")
    code.append("                rSum := 0.0;")
    code.append("                (* State transition contribution *)")
    code.append("                IF p_step = 1 THEN")
    code.append("                    FOR j := 1 TO 8 DO")
    code.append("                        rSum := rSum + (matA[i, j] * vecX_Est[j]);")
    code.append("                    END_FOR;")
    code.append("                ELSE")
    code.append("                    FOR j := 1 TO 8 DO")
    code.append("                        rSum := rSum + (matA[i, j] * predX[p_step - 1, j]);")
    code.append("                    END_FOR;")
    code.append("                END_IF;")
    code.append("")
    code.append("                (* Control input contribution *)")
    code.append("                FOR j := 1 TO 8 DO")
    code.append("                    rSum := rSum + (matB[i, j] * trajU[c_step, j]);")
    code.append("                END_FOR;")
    code.append("")
    code.append("                (* Disturbance feedforward contribution *)")
    code.append("                FOR j := 1 TO 8 DO")
    code.append("                    rSum := rSum + (matE[i, j] * vecDisturbance[j]);")
    code.append("                END_FOR;")
    code.append("                predX[p_step, i] := rSum;")
    code.append("            END_FOR;")
    code.append("        END_FOR;")
    code.append("")
    code.append("        (* Step 3.2: Gradient Computation wrt Control Horizon Steps (Nc = 3) *)")
    code.append("        FOR c_step := 1 TO 3 DO")
    code.append("            FOR j := 1 TO 8 DO")
    code.append("                rGrad := 0.0;")
    code.append("")
    code.append("                (* 1. Tracking Error Cost Gradient: d/du sum( (x_p - x_ref)^T * Q * (x_p - x_ref) ) *)")
    code.append("                FOR p_step := c_step TO 5 DO")
    code.append("                    FOR k := 1 TO 8 DO")
    code.append("                        (* Error at step p_step *)")
    code.append("                        rTemp := predX[p_step, k] - vecX_Ref[k];")
    code.append("                        (* Backpropagation of state error through B matrix *)")
    code.append("                        rGrad := rGrad + (matB[k, j] * matQ[k, k] * rTemp * 0.05);")
    code.append("                    END_FOR;")
    code.append("                END_FOR;")
    code.append("")
    code.append("                (* 2. Terminal Cost Gradient: d/du ( (x_5 - x_ref)^T * P * (x_5 - x_ref) ) *)")
    code.append("                FOR k := 1 TO 8 DO")
    code.append("                    rTemp := predX[5, k] - vecX_Ref[k];")
    code.append("                    rGrad := rGrad + (matB[k, j] * matP[k, k] * rTemp * 0.02);")
    code.append("                END_FOR;")
    code.append("")
    code.append("                (* 3. Actuator Effort Penalty Gradient: R * u *)")
    code.append("                rGrad := rGrad + (matR[j, j] * trajU[c_step, j] * 0.01);")
    code.append("")
    code.append("                (* 4. Actuator Slew Rate Penalty Gradient: S * Delta_u *)")
    code.append("                IF c_step = 1 THEN")
    code.append("                    rTemp := trajU[1, j] - vecU_Prev[j];")
    code.append("                ELSE")
    code.append("                    rTemp := trajU[c_step, j] - trajU[c_step - 1, j];")
    code.append("                END_IF;")
    code.append("                rGrad := rGrad + (matS[j, j] * rTemp * 0.02);")
    code.append("")
    code.append("                gradU[c_step, j] := rGrad;")
    code.append("            END_FOR;")
    code.append("        END_FOR;")
    code.append("")
    code.append("        (* Step 3.3: Adaptive Step Size & Projected Descent Update *)")
    code.append("        (* Decaying learning rate for guaranteed convergence: alpha = 0.012 / (1 + 0.08 * iter) *)")
    code.append("        rAlpha := 0.012 / (1.0 + (0.08 * INT_TO_REAL(iter)));")
    code.append("")
    code.append("        FOR c_step := 1 TO 3 DO")
    code.append("            FOR j := 1 TO 8 DO")
    code.append("                (* Gradient descent step *)")
    code.append("                rTemp := trajU[c_step, j] - (rAlpha * gradU[c_step, j]);")
    code.append("")
    code.append("                (* Actuator Physical Box Constraint Projection: u in [u_min, u_max] *)")
    code.append("                IF rTemp < vecU_Min[j] THEN")
    code.append("                    rTemp := vecU_Min[j];")
    code.append("                ELSIF rTemp > vecU_Max[j] THEN")
    code.append("                    rTemp := vecU_Max[j];")
    code.append("                END_IF;")
    code.append("")
    code.append("                (* Dynamic Slew Rate Limit Projection *)")
    code.append("                IF c_step = 1 THEN")
    code.append("                    rSum := rTemp - vecU_Prev[j];")
    code.append("                    IF rSum > vecDeltaU_Max[j] THEN")
    code.append("                        rTemp := vecU_Prev[j] + vecDeltaU_Max[j];")
    code.append("                    ELSIF rSum < -vecDeltaU_Max[j] THEN")
    code.append("                        rTemp := vecU_Prev[j] - vecDeltaU_Max[j];")
    code.append("                    END_IF;")
    code.append("                END_IF;")
    code.append("")
    code.append("                trajU[c_step, j] := rTemp;")
    code.append("            END_FOR;")
    code.append("        END_FOR;")
    code.append("    END_FOR;")
    code.append("")
    code.append("    (* --- Step 3.4: Extract Optimal First Control Step for Plant Application --- *)")
    code.append("    FOR j := 1 TO 8 DO")
    code.append("        vecU_Optimal[j] := trajU[1, j];")
    code.append("    END_FOR;")
    code.append("")
    return "\n".join(code)
