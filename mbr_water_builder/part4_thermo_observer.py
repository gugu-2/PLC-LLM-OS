    code.append("    END_IF;")
    code.append("    rMembranePermeability := rPermeability_Calc;")
    code.append("")
    code.append("    (* --- Step 2.5: Total Darcy Filtration Resistance & Cake Layer Observer --- *)")
    code.append("    (* R_total = DeltaP_Pa / (mu_T * v_filtration) in [10^11 m^-1] *)")
    code.append("    (* v_filtration [m/s] = J [LMH] * (1e-3 / 3600) = J * 2.777778e-7 m/s *)")
    code.append("    (* DeltaP [Pa] = DeltaP [mbar] * 100.0 *)")
    code.append("    (* mu_T [Pa.s] = rEstimatedDynamicViscosity * 1e-3 *)")
    code.append("    IF (rMeasuredFlux > 0.5) AND (rEstimatedDynamicViscosity > 0.1) THEN")
    code.append("        rTotalDarcy_Calc := (rRawTMP_Calc * 100.0) / ")
    code.append("                            ((rEstimatedDynamicViscosity * 0.001) * (rMeasuredFlux * 0.0000002777778) * 1.0E11);")
    code.append("    ELSE")
    code.append("        rTotalDarcy_Calc := rIntrinsicMembraneResistance_Rm * 1.0E-11;")
    code.append("    END_IF;")
