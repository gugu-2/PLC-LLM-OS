    code.append("    (* P_head = rho * g * H_tank in mbar (1 bar = 100,000 Pa = 1,000 mbar) *)")
    code.append("    rHydrostaticHeadPressure := (rWaterDensity * rGravitationalConstant * rBasinLiquidLevel) * 0.01;")
