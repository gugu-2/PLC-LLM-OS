    code.append("    (* --- Step 2.1: Dynamic Water Viscosity Temperature Correction (Arrhenius-Poiseuille) --- *)")
    code.append("    (* mu_20 = 1.002 mPa.s at 20 deg C. Temperature sensitivity polynomial expansion *)")
    code.append("    rTemp := rMixedLiquorTemp - 20.0;")
