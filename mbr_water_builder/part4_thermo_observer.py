    code.append("    (* J = (Q_permeate [m3/h] * 1000.0 [L/m3]) / A_membrane [m2] in [LMH] *)")
    code.append("    IF rMembraneAreaPerTrain > 100.0 THEN")
    code.append("        rMeasuredFlux := (rVotedPermeateFlow * 1000.0) / rMembraneAreaPerTrain;")
