add("    IF tWindSpd_DiscrepTimer_C > tCycleTime_ms THEN")
add("        tWindSpd_DiscrepTimer_C := tWindSpd_DiscrepTimer_C - tCycleTime_ms;")
add("    ELSE")
add("        tWindSpd_DiscrepTimer_C := T#0ms;")
add("    END_IF;")
add("END_IF;")
add("")
add("IF tWindSpd_DiscrepTimer_A > T#1500ms AND tWindSpd_DiscrepTimer_C > T#1500ms THEN")
add("    bWindSpd_ChA_Fault := TRUE;")
add("END_IF;")
add("IF tWindSpd_DiscrepTimer_A > T#1500ms AND tWindSpd_DiscrepTimer_B > T#1500ms THEN")
add("    bWindSpd_ChB_Fault := TRUE;")
add("END_IF;")
add("IF tWindSpd_DiscrepTimer_B > T#1500ms AND tWindSpd_DiscrepTimer_C > T#1500ms THEN")
add("    bWindSpd_ChC_Fault := TRUE;")
add("END_IF;")
add("")
add("(* Wind Speed Median Voting *)")
add("IF NOT bWindSpd_ChA_Fault AND NOT bWindSpd_ChB_Fault AND NOT bWindSpd_ChC_Fault THEN")
add("    IF (rWindSpeed_A_mps >= rWindSpeed_B_mps AND rWindSpeed_A_mps <= rWindSpeed_C_mps) OR")
add("       (rWindSpeed_A_mps <= rWindSpeed_B_mps AND rWindSpeed_A_mps >= rWindSpeed_C_mps) THEN")
add("        rVotedWindSpeed_mps := rWindSpeed_A_mps;")
add("    ELSIF (rWindSpeed_B_mps >= rWindSpeed_A_mps AND rWindSpeed_B_mps <= rWindSpeed_C_mps) OR")
add("          (rWindSpeed_B_mps <= rWindSpeed_A_mps AND rWindSpeed_B_mps >= rWindSpeed_C_mps) THEN")
add("        rVotedWindSpeed_mps := rWindSpeed_B_mps;")
add("    ELSE")
add("        rVotedWindSpeed_mps := rWindSpeed_C_mps;")
add("    END_IF;")
add("ELSIF bWindSpd_ChA_Fault AND NOT bWindSpd_ChB_Fault AND NOT bWindSpd_ChC_Fault THEN")
add("    rVotedWindSpeed_mps := (rWindSpeed_B_mps + rWindSpeed_C_mps) * 0.5;")
add("ELSIF bWindSpd_ChB_Fault AND NOT bWindSpd_ChA_Fault AND NOT bWindSpd_ChC_Fault THEN")
add("    rVotedWindSpeed_mps := (rWindSpeed_A_mps + rWindSpeed_C_mps) * 0.5;")
add("ELSIF bWindSpd_ChC_Fault AND NOT bWindSpd_ChA_Fault AND NOT bWindSpd_ChB_Fault THEN")
add("    rVotedWindSpeed_mps := (rWindSpeed_A_mps + rWindSpeed_B_mps) * 0.5;")
add("ELSE")
add("    (* Highest reading fallback for gust safety *)")
add("    rVotedWindSpeed_mps := rWindSpeed_A_mps;")
add("    IF rWindSpeed_B_mps > rVotedWindSpeed_mps THEN rVotedWindSpeed_mps := rWindSpeed_B_mps; END_IF;")
add("    IF rWindSpeed_C_mps > rVotedWindSpeed_mps THEN rVotedWindSpeed_mps := rWindSpeed_C_mps; END_IF;")
add("END_IF;")
add("")
add("(* --- TRIAD 2: NACELLE WIND VANE RELATIVE INFLOW ANGLE (A, B, C) --- *)")
add("IF ABS(rWindDirection_A_deg - rWindDirection_B_deg) > 8.0 THEN")
add("    tWindDir_DiscrepTimer_A := tWindDir_DiscrepTimer_A + tCycleTime_ms;")
add("ELSE")
add("    tWindDir_DiscrepTimer_A := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rWindDirection_B_deg - rWindDirection_C_deg) > 8.0 THEN")
add("    tWindDir_DiscrepTimer_B := tWindDir_DiscrepTimer_B + tCycleTime_ms;")
add("ELSE")
add("    tWindDir_DiscrepTimer_B := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rWindDirection_A_deg - rWindDirection_C_deg) > 8.0 THEN")
add("    tWindDir_DiscrepTimer_C := tWindDir_DiscrepTimer_C + tCycleTime_ms;")
add("ELSE")
add("    tWindDir_DiscrepTimer_C := T#0ms;")
add("END_IF;")
add("")
add("IF tWindDir_DiscrepTimer_A > T#2000ms AND tWindDir_DiscrepTimer_C > T#2000ms THEN bWindDir_ChA_Fault := TRUE; END_IF;")
add("IF tWindDir_DiscrepTimer_A > T#2000ms AND tWindDir_DiscrepTimer_B > T#2000ms THEN bWindDir_ChB_Fault := TRUE; END_IF;")
add("IF tWindDir_DiscrepTimer_B > T#2000ms AND tWindDir_DiscrepTimer_C > T#2000ms THEN bWindDir_ChC_Fault := TRUE; END_IF;")
add("")
add("(* Relative Inflow Angle Median Selection *)")
add("IF NOT bWindDir_ChA_Fault AND NOT bWindDir_ChB_Fault AND NOT bWindDir_ChC_Fault THEN")
add("    IF (rWindDirection_A_deg >= rWindDirection_B_deg AND rWindDirection_A_deg <= rWindDirection_C_deg) OR")
add("       (rWindDirection_A_deg <= rWindDirection_B_deg AND rWindDirection_A_deg >= rWindDirection_C_deg) THEN")
add("        rVotedWindDirection_deg := rWindDirection_A_deg;")
add("    ELSIF (rWindDirection_B_deg >= rWindDirection_A_deg AND rWindDirection_B_deg <= rWindDirection_C_deg) OR")
add("          (rWindDirection_B_deg <= rWindDirection_A_deg AND rWindDirection_B_deg >= rWindDirection_C_deg) THEN")
add("        rVotedWindDirection_deg := rWindDirection_B_deg;")
add("    ELSE")
add("        rVotedWindDirection_deg := rWindDirection_C_deg;")
add("    END_IF;")
add("ELSIF bWindDir_ChA_Fault AND NOT bWindDir_ChB_Fault AND NOT bWindDir_ChC_Fault THEN")
add("    rVotedWindDirection_deg := (rWindDirection_B_deg + rWindDirection_C_deg) * 0.5;")
add("ELSE")
add("    rVotedWindDirection_deg := rWindDirection_A_deg;")
add("END_IF;")
add("")
add("(* --- TRIAD 3: ROTOR LOW-SPEED SHAFT INDUCTIVE SPEED SENSORS (A, B, C) --- *)")
add("IF ABS(rRotorSpeed_A_rpm - rRotorSpeed_B_rpm) > 0.40 THEN")
add("    tRotorSpd_DiscrepTimer_A := tRotorSpd_DiscrepTimer_A + tCycleTime_ms;")
add("ELSE")
add("    tRotorSpd_DiscrepTimer_A := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rRotorSpeed_B_rpm - rRotorSpeed_C_rpm) > 0.40 THEN")
add("    tRotorSpd_DiscrepTimer_B := tRotorSpd_DiscrepTimer_B + tCycleTime_ms;")
add("ELSE")
add("    tRotorSpd_DiscrepTimer_B := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rRotorSpeed_A_rpm - rRotorSpeed_C_rpm) > 0.40 THEN")
add("    tRotorSpd_DiscrepTimer_C := tRotorSpd_DiscrepTimer_C + tCycleTime_ms;")
add("ELSE")
add("    tRotorSpd_DiscrepTimer_C := T#0ms;")
add("END_IF;")
add("")
add("IF tRotorSpd_DiscrepTimer_A > T#400ms AND tRotorSpd_DiscrepTimer_C > T#400ms THEN bRotorSpd_ChA_Fault := TRUE; END_IF;")
add("IF tRotorSpd_DiscrepTimer_A > T#400ms AND tRotorSpd_DiscrepTimer_B > T#400ms THEN bRotorSpd_ChB_Fault := TRUE; END_IF;")
add("IF tRotorSpd_DiscrepTimer_B > T#400ms AND tRotorSpd_DiscrepTimer_C > T#400ms THEN bRotorSpd_ChC_Fault := TRUE; END_IF;")
add("")
add("(* Rotor Speed Median Selection *)")
add("IF NOT bRotorSpd_ChA_Fault AND NOT bRotorSpd_ChB_Fault AND NOT bRotorSpd_ChC_Fault THEN")
add("    IF (rRotorSpeed_A_rpm >= rRotorSpeed_B_rpm AND rRotorSpeed_A_rpm <= rRotorSpeed_C_rpm) OR")
add("       (rRotorSpeed_A_rpm <= rRotorSpeed_B_rpm AND rRotorSpeed_A_rpm >= rRotorSpeed_C_rpm) THEN")
add("        rVotedRotorSpeed_rpm := rRotorSpeed_A_rpm;")
add("    ELSIF (rRotorSpeed_B_rpm >= rRotorSpeed_A_rpm AND rRotorSpeed_B_rpm <= rRotorSpeed_C_rpm) OR")
add("          (rRotorSpeed_B_rpm <= rRotorSpeed_A_rpm AND rRotorSpeed_B_rpm >= rRotorSpeed_C_rpm) THEN")
add("        rVotedRotorSpeed_rpm := rRotorSpeed_B_rpm;")
add("    ELSE")
add("        rVotedRotorSpeed_rpm := rRotorSpeed_C_rpm;")
add("    END_IF;")
add("ELSIF bRotorSpd_ChA_Fault AND NOT bRotorSpd_ChB_Fault AND NOT bRotorSpd_ChC_Fault THEN")
add("    rVotedRotorSpeed_rpm := (rRotorSpeed_B_rpm + rRotorSpeed_C_rpm) * 0.5;")
add("ELSE")
add("    (* Conservative high speed pick for overspeed trip protection *)")
add("    rVotedRotorSpeed_rpm := rRotorSpeed_A_rpm;")
add("    IF rRotorSpeed_B_rpm > rVotedRotorSpeed_rpm THEN rVotedRotorSpeed_rpm := rRotorSpeed_B_rpm; END_IF;")
add("    IF rRotorSpeed_C_rpm > rVotedRotorSpeed_rpm THEN rVotedRotorSpeed_rpm := rRotorSpeed_C_rpm; END_IF;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 2: ROTOR AERODYNAMIC POWER & TIP SPEED RATIO EVALUATION                              *)")
add("(* P_aero = 0.5 * rho * A_swept * v_wind^3 * Cp(lambda, theta)                              *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("IF rVotedWindSpeed_mps > 0.5 THEN")
add("    (* Tip Speed Ratio lambda = (omega * R) / v_wind *)")
add("    rTipSpeedRatio := ((rVotedRotorSpeed_rpm * 0.1047197) * rRotorRadius_m) / rVotedWindSpeed_mps;")
add("ELSE")
add("    rTipSpeedRatio := 0.0;")
add("END_IF;")
add("")
add("(* Empirical Betz-limit polynomial approximation for 8MW offshore blade airfoil profile *)")
add("IF rTipSpeedRatio > 2.0 AND rTipSpeedRatio < 14.0 THEN")
add("    rCp_Estimate := 0.48 * (1.0 - 0.015 * (rCollectivePitch_deg * rCollectivePitch_deg)) * ")
add("                    (1.0 - 0.02 * ((rTipSpeedRatio - 8.2) * (rTipSpeedRatio - 8.2)));")
add("    IF rCp_Estimate < 0.0 THEN")
add("        rCp_Estimate := 0.0;")
add("    END_IF;")
add("ELSE")
add("    rCp_Estimate := 0.05;")
add("END_IF;")
add("")
add("(* Aerodynamic rotor power estimate [kW] *)")
add("rAerodynamicPowerEst_kW := 0.5 * rAirDensity_kg_m3 * rRotorSweptArea_m2 * ")
add("                           (rVotedWindSpeed_mps * rVotedWindSpeed_mps * rVotedWindSpeed_mps) * ")
add("                           rCp_Estimate * 0.001;")
add("IF rAerodynamicPowerEst_kW > 12000.0 THEN")
add("    rAerodynamicPowerEst_kW := 12000.0;")
add("ELSIF rAerodynamicPowerEst_kW < 0.0 THEN")
add("    rAerodynamicPowerEst_kW := 0.0;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 3: COLEMAN (d-q) MULTIBLADE COORDINATE (MBC) TRANSFORM & IPC 1P/2P FATIGUE REDUCTION *)")
add("(* M_d = (2/3) * sum( M_i * cos(psi_i) ) -> Aerodynamic Rotor Tilt Moment                    *)")
add("(* M_q = (2/3) * sum( M_i * sin(psi_i) ) -> Aerodynamic Rotor Yaw Moment                     *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Azimuth angles for Blade 1 (0 deg offset), Blade 2 (120 deg offset), Blade 3 (240 deg) *)")
add("rAzimuthRad_A := rRotorAzimuth_deg * 0.01745329; (* Convert to radians *)")
add("rAzimuthRad_B := (rRotorAzimuth_deg + 120.0) * 0.01745329;")
add("rAzimuthRad_C := (rRotorAzimuth_deg + 240.0) * 0.01745329;")
add("")
add("(* Taylor series / trigonometric approximations for fast deterministic PAC cycle *)")
add("rCosA := COS(rAzimuthRad_A); rSinA := SIN(rAzimuthRad_A);")
add("rCosB := COS(rAzimuthRad_B); rSinB := SIN(rAzimuthRad_B);")
add("rCosC := COS(rAzimuthRad_C); rSinC := SIN(rAzimuthRad_C);")
add("")
add("(* Forward Coleman Transformation: Rotating FBG Loads -> Non-Rotating Tilt/Yaw Moments *)")
add("rColemanTiltMoment_kNm := 0.666667 * ((rBladeRootFlapLoad_A_kNm * rCosA) + ")
add("                                      (rBladeRootFlapLoad_B_kNm * rCosB) + ")
add("                                      (rBladeRootFlapLoad_C_kNm * rCosC));")
add("")
add("rColemanYawMoment_kNm  := 0.666667 * ((rBladeRootFlapLoad_A_kNm * rSinA) + ")
add("                                      (rBladeRootFlapLoad_B_kNm * rSinB) + ")
add("                                      (rBladeRootFlapLoad_C_kNm * rSinC));")
add("")
add("(* IPC PI Decoupled Regulators for Tilt and Yaw Bending Axes *)")
add("IF (iStepState = 5) AND (rVotedRotorSpeed_rpm >= 8.5) THEN")
add("    bIpcActiveStatus := TRUE;")
add("    ")
add("    (* Tilt Axis Integrator *)")
add("    rTiltMomentIntegral := rTiltMomentIntegral + (rIpcGain_I * rColemanTiltMoment_kNm * rDt_sec);")
add("    IF rTiltMomentIntegral > 2.5 THEN rTiltMomentIntegral := 2.5; END_IF;")
add("    IF rTiltMomentIntegral < -2.5 THEN rTiltMomentIntegral := -2.5; END_IF;")
add("    rTiltPitchDemand := (rIpcGain_P * rColemanTiltMoment_kNm) + rTiltMomentIntegral;")
add("    ")
add("    (* Yaw Axis Integrator *)")
add("    rYawMomentIntegral := rYawMomentIntegral + (rIpcGain_I * rColemanYawMoment_kNm * rDt_sec);")
add("    IF rYawMomentIntegral > 2.5 THEN rYawMomentIntegral := 2.5; END_IF;")
add("    IF rYawMomentIntegral < -2.5 THEN rYawMomentIntegral := -2.5; END_IF;")
add("    rYawPitchDemand := (rIpcGain_P * rColemanYawMoment_kNm) + rYawMomentIntegral;")
add("    ")
add("    (* Inverse Coleman Transformation: Non-Rotating Pitch Demands -> Rotating Blade Pitch Offsets *)")
add("    rIpcPitchOffset_A_deg := (rTiltPitchDemand * rCosA) + (rYawPitchDemand * rSinA);")
add("    rIpcPitchOffset_B_deg := (rTiltPitchDemand * rCosB) + (rYawPitchDemand * rSinB);")
add("    rIpcPitchOffset_C_deg := (rTiltPitchDemand * rCosC) + (rYawPitchDemand * rSinC);")
add("    ")
add("    (* Limit individual pitch stroke delta to +/- 3.0 degrees for actuator fatigue safety *)")
add("    IF rIpcPitchOffset_A_deg > 3.0 THEN rIpcPitchOffset_A_deg := 3.0; END_IF;")
add("    IF rIpcPitchOffset_A_deg < -3.0 THEN rIpcPitchOffset_A_deg := -3.0; END_IF;")
add("    IF rIpcPitchOffset_B_deg > 3.0 THEN rIpcPitchOffset_B_deg := 3.0; END_IF;")
add("    IF rIpcPitchOffset_B_deg < -3.0 THEN rIpcPitchOffset_B_deg := -3.0; END_IF;")
add("    IF rIpcPitchOffset_C_deg > 3.0 THEN rIpcPitchOffset_C_deg := 3.0; END_IF;")
add("    IF rIpcPitchOffset_C_deg < -3.0 THEN rIpcPitchOffset_C_deg := -3.0; END_IF;")
add("ELSE")
add("    bIpcActiveStatus := FALSE;")
add("    rIpcPitchOffset_A_deg := 0.0;")
add("    rIpcPitchOffset_B_deg := 0.0;")
add("    rIpcPitchOffset_C_deg := 0.0;")
add("    rTiltMomentIntegral := 0.0;")
add("    rYawMomentIntegral := 0.0;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 4: ACTIVE TOWER FORE-AFT & SIDE-TO-SIDE AERODYNAMIC DAMPING                          *)")
add("(* Fore-aft damping modulates collective pitch: Delta_theta_fa = -K_fa * v_tower_fa          *)")
add("(* Side-to-side damping modulates generator torque: Delta_T_gen = K_ss * v_tower_ss         *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Integrate fore-aft acceleration through bandpass filter to reconstruct tower top velocity *)")
add("rTowerForeAftVelocityEst_mps := rTowerForeAftVelocityEst_mps + (rTowerForeAftAcc_m_s2 * rDt_sec) - ")
add("                                (0.15 * rTowerForeAftVelocityEst_mps * rDt_sec); (* High-pass wash *)")
add("")
add("IF ABS(rTowerForeAftAcc_m_s2) > 0.05 AND (iStepState = 5) THEN")
add("    bTowerDampingActive := TRUE;")
add("    rTowerDampingPitchOffset_deg := -1.8 * rTowerForeAftVelocityEst_mps;")
add("    IF rTowerDampingPitchOffset_deg > 1.5 THEN rTowerDampingPitchOffset_deg := 1.5; END_IF;")
add("    IF rTowerDampingPitchOffset_deg < -1.5 THEN rTowerDampingPitchOffset_deg := -1.5; END_IF;")
add("ELSE")
add("    bTowerDampingActive := FALSE;")
add("    rTowerDampingPitchOffset_deg := 0.0;")
add("END_IF;")
add("")
add("(* Side-to-side tower damping injected directly into generator torque loop *)")
add("rTowerSideSideTorqueDamping_kNm := 120.0 * rTowerSideSideAcc_m_s2;")
add("IF rTowerSideSideTorqueDamping_kNm > 250.0 THEN rTowerSideSideTorqueDamping_kNm := 250.0; END_IF;")
add("IF rTowerSideSideTorqueDamping_kNm < -250.0 THEN rTowerSideSideTorqueDamping_kNm := -250.0; END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 5: DISCRETE AEROELASTIC STATE-SPACE OBSERVER PROPAGATION                             *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("vecY_meas[0] := (rVotedRotorSpeed_rpm - rRatedRotorSpeed_rpm) * 0.1047197; (* Speed dev [rad/s] *)")
add("vecY_meas[1] := rTowerForeAftVelocityEst_mps;")
add("vecY_meas[2] := (rGeneratorSpeed_rpm - (rVotedRotorSpeed_rpm * 1.0)) * 0.1047197; (* Shaft twist *)")
add("")
add("(* Compute estimated measurement: y_est = C * x_k *)")
add("FOR i := 0 TO 2 DO")
add("    vecY_est[i] := 0.0;")
add("    FOR j := 0 TO 5 DO")
add("        vecY_est[i] := vecY_est[i] + (matC[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    vecErr_Y[i] := vecY_meas[i] - vecY_est[i];")
add("END_FOR;")
add("")
add("(* State update: x_next = A * x_k + B * u_k + L * (y_meas - y_est) *)")
add("FOR i := 0 TO 5 DO")
add("    rTempSum := 0.0;")
add("    FOR j := 0 TO 5 DO")
add("        rTempSum := rTempSum + (matA[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matB[i, j] * vecU_k[j]);")
add("    END_FOR;")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matL_Obs[i, j] * vecErr_Y[j]);")
add("    END_FOR;")
add("    vecX_next[i] := rTempSum;")
add("END_FOR;")
add("")
add("FOR i := 0 TO 5 DO")
add("    vecX_k[i] := vecX_next[i];")
add("END_FOR;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 6: NACELLE YAW WIND VANE TRACKING & CABLE TWIST ACCUMULATION                         *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Filter relative inflow wind direction angle: tau = 1.5 seconds *)")
add("rFilteredYawMisalignment_deg := rFilteredYawMisalignment_deg + ")
add("                                (rDt_sec / (1.5 + rDt_sec)) * (rVotedWindDirection_deg - rFilteredYawMisalignment_deg);")
add("")
add("(* Check for cable twist limit (over 3.0 full rotations = 1080 deg requires automatic untwist) *)")
add("IF ABS(rTotalCableTwistTurns) > 3.0 THEN")
add("    bCableUntwistActive := TRUE;")
add("END_IF;")
add("")
add("IF bCableUntwistActive THEN")
add("    (* Yaw until twist counter returns to zero *)")
add("    IF rTotalCableTwistTurns > 0.05 THEN")
add("        bYawClockwiseCmd := FALSE;")
add("        bYawCounterClockwiseCmd := TRUE;")
add("        rYawBrakeHydraulicPressure_bar := 15.0; (* Slipping brake during yaw *)")
add("        rTotalCableTwistTurns := rTotalCableTwistTurns - (0.5 * rDt_sec / 360.0);")
add("    ELSIF rTotalCableTwistTurns < -0.05 THEN")
add("        bYawClockwiseCmd := TRUE;")
add("        bYawCounterClockwiseCmd := FALSE;")
add("        rYawBrakeHydraulicPressure_bar := 15.0;")
add("        rTotalCableTwistTurns := rTotalCableTwistTurns + (0.5 * rDt_sec / 360.0);")
add("    ELSE")
add("        bYawClockwiseCmd := FALSE;")
add("        bYawCounterClockwiseCmd := FALSE;")
add("        rYawBrakeHydraulicPressure_bar := 140.0; (* Full mechanical clamp *)")
add("        bCableUntwistActive := FALSE;")
add("    END_IF;")
add("ELSE")
add("    (* Normal active wind tracking: engage yaw if misalignment > 6.0 deg for > 8.0 seconds *)")
add("    IF ABS(rFilteredYawMisalignment_deg) > 6.0 THEN")
add("        tYawMisalignmentDeadbandTimer := tYawMisalignmentDeadbandTimer + tCycleTime_ms;")
add("    ELSE")
add("        tYawMisalignmentDeadbandTimer := T#0ms;")
add("    END_IF;")
add("    ")
add("    IF tYawMisalignmentDeadbandTimer >= T#8000ms AND (rYawGearboxTorque_kNm < rYawOverTorque_HH_kNm) THEN")
add("        rYawBrakeHydraulicPressure_bar := 20.0; (* Slip pressure *)")
add("        IF rFilteredYawMisalignment_deg > 0.0 THEN")
add("            bYawClockwiseCmd := TRUE;")
add("            bYawCounterClockwiseCmd := FALSE;")
add("            rTotalCableTwistTurns := rTotalCableTwistTurns + (0.5 * rDt_sec / 360.0);")
add("        ELSE")
add("            bYawClockwiseCmd := FALSE;")
add("            bYawCounterClockwiseCmd := TRUE;")
add("            rTotalCableTwistTurns := rTotalCableTwistTurns - (0.5 * rDt_sec / 360.0);")
add("        END_IF;")
add("    ELSE")
add("        bYawClockwiseCmd := FALSE;")
add("        bYawCounterClockwiseCmd := FALSE;")
add("        rYawBrakeHydraulicPressure_bar := 140.0; (* Full hold *)")
add("    END_IF;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 7: IEC 61400 FINITE STATE MACHINE (10 OPERATIONAL STATES)                            *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("CASE iStepState OF")
add("    0: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 0: SYSTEM_ULTRACAPACITOR_HEALTH_CHECK                                        *)")
add("       (* Verify pitch emergency ultracapacitors (> 82V), sensor health, and grid status     *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bTurbineTrippedStatus         := FALSE;")
add("       bUltracapEmergencyFeatherCmd  := FALSE;")
add("       bMechanicalRotorBrakeRelease  := FALSE; (* Keep mechanical brake clamped *)")
add("       rCollectivePitch_deg          := rFullFeatherAngle_deg; (* 90 deg feather *)")
add("       rGeneratorTorqueCmd_kNm       := 0.0;")
add("       rActivePowerDemand_kW         := 0.0;")
add("       ")
add("       IF bHardEmergencyStop_ESD THEN")
add("           (* Check all three ultracapacitor banks *)")
