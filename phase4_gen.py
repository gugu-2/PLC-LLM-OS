# Phase 4 generator: 14-Stage Production FSM
import os

def generate_phase4_fsm():
    lines = []
    lines.append("(* ========================================================================= *)")
    lines.append("(* PHASE 4: DETERMINISTIC 14-STAGE PRODUCTION FINITE STATE MACHINE (FSM)     *)")
    lines.append("(* ========================================================================= *)")
    lines.append("")
    lines.append("tFSM_StateTimer := tFSM_StateTimer + 0.050; (* Increment state dwell timer at 50ms scan *)")
    lines.append("")
    lines.append("CASE nFSM_CurrentState OF")
    lines.append("")

    # Stage 0: STATE_INACTIVE_COLD_STOP (0)
    lines.append("    0: (* STATE_INACTIVE_COLD_STOP: Mill at complete standstill, zero power, safe access *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := FALSE;")
    lines.append("        aControl_u[1] := 0.0; (* Ore feed halted *)")
    lines.append("        aControl_u[2] := 0.0; (* SAG feed water closed *)")
    lines.append("        aControl_u[3] := 0.0; (* GMD speed zero *)")
    lines.append("        aControl_u[4] := 0.0; (* Cyclone pump stopped *)")
    lines.append("        aControl_u[5] := 0.0; (* Sump dilution water closed *)")
    lines.append("        aControl_u[6] := 0.0; (* All cyclone knife gates closed *)")
    lines.append("        aControl_u[7] := 0.0; (* Pebble recycle diverted to bypass stockpile *)")
    lines.append("        aControl_u[8] := 0.0; (* Ball mill water closed *)")
    lines.append("        rBearingCoolingWaterValve_Cmd := 10.0; (* Keep minimum cooling circuit circulation *)")
    lines.append("        ")
    lines.append("        IF bStartCommand AND NOT bFault AND NOT bEmergencyStop THEN")
    lines.append("            nFSM_CurrentState := 1; (* Transition to Trunnion Jacking *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 1: STATE_TRUNNION_JACKING_PERMISSIVE (1)
    lines.append("    1: (* STATE_TRUNNION_JACKING_PERMISSIVE: Jacking pumps start, verify hydrostatic lift *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := FALSE;")
    lines.append("        ")
    lines.append("        (* Verify Jacking Lift Conditions: Pressure > 320 bar, Lift > 140 um, Temp 35..50 C *)")
    lines.append("        IF (rFeedTrunnion_Voted >= 52.0) AND (rDischTrunnion_Voted >= 54.0) AND")
    lines.append("           (rTrunnionOilFilm_Feed >= 140.0) AND (rTrunnionOilFilm_Disch >= 140.0) AND")
    lines.append("           (rBearingOilSupplyTemp >= 35.0) AND (rBearingOilSupplyTemp <= 50.0) THEN")
    lines.append("            bJackingPermissive := TRUE;")
    lines.append("        ELSE")
    lines.append("            bJackingPermissive := FALSE;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        IF bJackingPermissive AND (tFSM_StateTimer >= 15.0) THEN")
    lines.append("            nFSM_CurrentState := 2; (* Transition to Inching Drive Engage *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("        ELSIF tFSM_StateTimer >= 90.0 THEN")
    lines.append("            (* Jacking failed to establish lift within 90 seconds timeout *)")
    lines.append("            bFault := TRUE;")
    lines.append("            nFSM_CurrentState := 13; (* Emergency Trip Failsafe *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 2: STATE_INCHING_ENGAGE_INSPECTION (2)
    lines.append("    2: (* STATE_INCHING_ENGAGE_INSPECTION: Auxiliary creep crawl drive engaged (0.15 rpm) *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := FALSE;")
    lines.append("        aControl_u[3] := 0.15; (* Slow creep crawl rotational speed *)")
    lines.append("        ")
    lines.append("        (* Confirm smooth rotation, resolver tracking, and liner visual clearance *)")
    lines.append("        IF tFSM_StateTimer >= 20.0 THEN")
    lines.append("            aControl_u[3] := 0.0; (* Disengage auxiliary inching drive *)")
    lines.append("            nFSM_CurrentState := 3; (* Transition to Frozen Charge Test Roll *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("            rRotorAngle_Integrated := 0.0;")
    lines.append("            rTorque_PeakDetected   := 0.0;")
    lines.append("            bTorqueBreakoverObserved := FALSE;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 3: STATE_FROZEN_CHARGE_TEST_ROLL (3)
    lines.append("    3: (* STATE_FROZEN_CHARGE_TEST_ROLL: Slow roll test (0.8 rpm) for frozen charge breakaway *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := FALSE;")
    lines.append("        aControl_u[3] := 0.80; (* Low speed test roll *)")
    lines.append("        ")
    lines.append("        (* Integrate angular rotation *)")
    lines.append("        rRotorAngle_Delta := ABS(rGMDRotorAngle - rRotorAngle_Prev);")
    lines.append("        IF rRotorAngle_Delta < 180.0 THEN")
    lines.append("            rRotorAngle_Integrated := rRotorAngle_Integrated + rRotorAngle_Delta;")
    lines.append("        END_IF;")
    lines.append("        rRotorAngle_Prev := rGMDRotorAngle;")
    lines.append("        ")
    lines.append("        (* Calculate actual motor torque T = P / omega *)")
    lines.append("        IF rGMDSpeed_Actual > 0.10 THEN")
    lines.append("            rTorque_Actual := (rGMDPower_Voted * 9.5488) / rGMDSpeed_Actual;")
    lines.append("        ELSE")
    lines.append("            rTorque_Actual := 0.0;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        IF rTorque_Actual > rTorque_PeakDetected THEN")
    lines.append("            rTorque_PeakDetected := rTorque_Actual;")
    lines.append("            rAngle_AtTorquePeak  := rRotorAngle_Integrated;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        (* Check for natural charge cascading breakaway (torque relaxation > 450 kNm) *)")
    lines.append("        IF (rTorque_PeakDetected > 4500.0) AND ((rTorque_PeakDetected - rTorque_Actual) > 450.0) THEN")
    lines.append("            bTorqueBreakoverObserved := TRUE;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        (* CRITICAL SAFETY DECISION: *)")
    lines.append("        (* If rotor angle passes 58 degrees without breakover or if acoustic tumbling energy is zero *)")
    lines.append("        IF (rRotorAngle_Integrated >= 58.0) AND (NOT bTorqueBreakoverObserved OR (rShellAcoustic_Voted < 12.0)) THEN")
    lines.append("            (* FROZEN CHARGE DETECTED! INITIATE EMERGENCY HIGH-SPEED SHUTDOWN *)")
    lines.append("            bFrozenChargeTrip := TRUE;")
    lines.append("            bFault := TRUE;")
    lines.append("            nFSM_CurrentState := 13; (* Trip Failsafe *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        ELSIF bTorqueBreakoverObserved AND (rRotorAngle_Integrated >= 65.0) THEN")
    lines.append("            (* Charge safely cascading! Permitted to accelerate to operating speed *)")
    lines.append("            nFSM_CurrentState := 4; (* Transition to Main Acceleration Ramp *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("            rSpeedRampTarget  := 0.80;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 4: STATE_GMD_MAIN_ACCELERATION_RAMP (4)
    lines.append("    4: (* STATE_GMD_MAIN_ACCELERATION_RAMP: Controlled S-curve ramp from 0.8 to 9.8 rpm *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := FALSE;")
    lines.append("        ")
    lines.append("        (* Linear acceleration ramp rate: +0.075 rpm per second *)")
    lines.append("        IF rSpeedRampTarget < 9.80 THEN")
    lines.append("            rSpeedRampTarget := rSpeedRampTarget + (0.075 * 0.050);")
    lines.append("        ELSE")
    lines.append("            rSpeedRampTarget := 9.80;")
    lines.append("        END_IF;")
    lines.append("        aControl_u[3] := rSpeedRampTarget;")
    lines.append("        ")
    lines.append("        (* Hydrodynamic lift wedge fully established above 4.5 rpm *)")
    lines.append("        IF (rGMDSpeed_Actual >= 9.60) AND (tFSM_StateTimer >= 120.0) THEN")
    lines.append("            nFSM_CurrentState := 5; (* Transition to Water Prime & Ratio Lock *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 5: STATE_WATER_PRIME_RATIO_LOCK (5)
    lines.append("    5: (* STATE_WATER_PRIME_RATIO_LOCK: Prime mill chute water, establish sump pool *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := FALSE;")
    lines.append("        aControl_u[3] := 9.80; (* Hold nominal mill speed *)")
    lines.append("        aControl_u[2] := 450.0; (* Open SAG chute flush water to 450 m3/h *)")
    lines.append("        aControl_u[5] := 350.0; (* Open sump prime water to 350 m3/h *)")
    lines.append("        ")
    lines.append("        (* Once sump level reaches 45% minimum suction head, prepare for ore feeding *)")
    lines.append("        IF (rSumpLevel_Voted >= 45.0) AND (tFSM_StateTimer >= 45.0) THEN")
    lines.append("            nFSM_CurrentState := 6; (* Transition to Ore Feed Ramp-Up *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("            rOreFeedRampTarget := 0.0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 6: STATE_ORE_FEED_RAMP_UP (6)
    lines.append("    6: (* STATE_ORE_FEED_RAMP_UP: Ramp fresh ore feeders from 0 to 2600 t/h *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := TRUE;")
    lines.append("        aControl_u[3] := 9.80; (* Nominal mill speed *)")
    lines.append("        ")
    lines.append("        (* Feeder ramp rate: +15.0 t/h per second *)")
    lines.append("        IF rOreFeedRampTarget < 2600.0 THEN")
    lines.append("            rOreFeedRampTarget := rOreFeedRampTarget + (15.0 * 0.050);")
    lines.append("        ELSE")
    lines.append("            rOreFeedRampTarget := 2600.0;")
    lines.append("        END_IF;")
    lines.append("        aControl_u[1] := rOreFeedRampTarget;")
    lines.append("        ")
    lines.append("        (* Feed Water Ratio Controller: 0.32 m3 water per tonne of raw ore *)")
    lines.append("        aControl_u[2] := LIMIT(250.0, aControl_u[1] * 0.32, 1100.0);")
    lines.append("        ")
    lines.append("        IF (aControl_u[1] >= 2400.0) AND (tFSM_StateTimer >= 180.0) THEN")
    lines.append("            nFSM_CurrentState := 7; (* Transition to Cyclone Staging *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 7: STATE_CYCLONE_MANIFOLD_STAGING (7)
    lines.append("    7: (* STATE_CYCLONE_MANIFOLD_STAGING: Start 1600 kW pump, stage cyclones (6->8->10->12) *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := TRUE;")
    lines.append("        aControl_u[4] := 680.0; (* Ramp slurry pump to 680 rpm *)")
    lines.append("        ")
    lines.append("        (* Cyclone knife gate sequencing based on manifold feed pressure *)")
    lines.append("        IF rCycloneFeedPressure < 85.0 THEN")
    lines.append("            aControl_u[6] := 8.0; (* Consolidate flow to raise inlet velocity *)")
    lines.append("        ELSIF rCycloneFeedPressure > 125.0 THEN")
    lines.append("            aControl_u[6] := 12.0; (* Open additional cyclone to relieve manifold pressure *)")
    lines.append("        ELSE")
    lines.append("            aControl_u[6] := 10.0; (* Nominal 10 active cyclones *)")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        (* When classification pressure and density stabilize, proceed to closed-circuit *)")
    lines.append("        IF (rCycloneFeedPressure >= 90.0) AND (rCycloneFeedPressure <= 125.0) AND (tFSM_StateTimer >= 90.0) THEN")
    lines.append("            nFSM_CurrentState := 8; (* Transition to Closed-Circuit Equilibrium *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            nFSM_SubPhase     := 0;")
    lines.append("            bReady            := TRUE;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 8: STATE_CLOSED_CIRCUIT_EQUILIBRIUM (8)
    lines.append("    8: (* STATE_CLOSED_CIRCUIT_EQUILIBRIUM: Steady-state production with MPC closed-loop *)")
    lines.append("        bReady  := TRUE;")
    lines.append("        bActive := TRUE;")
    lines.append("        ")
    lines.append("        (* Monitor for Process Disturbance Branches *)")
    lines.append("        IF rShellAcousticHighFreqPct > 65.0 THEN")
    lines.append("            nFSM_CurrentState := 9; (* Divert to Acoustic Shell Protection *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        ELSIF (aState_x[2] > 28.0) OR (rSumpLevel_Voted > 82.0) THEN")
    lines.append("            nFSM_CurrentState := 10; (* Divert to Slurry Overfill Mitigation *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        ELSIF bStopCommand THEN")
    lines.append("            nFSM_CurrentState := 12; (* Controlled Grind-Out Flush Stop *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            tGrindOutTimer    := 720.0; (* 12 minute countdown *)")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 9: STATE_ACOUSTIC_SHELL_PROTECTION (9)
    lines.append("    9: (* STATE_ACOUSTIC_SHELL_PROTECTION: Direct ball-on-liner impact mitigation *)")
    lines.append("        bReady  := TRUE;")
    lines.append("        bActive := TRUE;")
    lines.append("        bAcousticLinerAlert := TRUE;")
    lines.append("        ")
    lines.append("        (* Trim SAG speed downwards to prevent cataracting balls striking bare steel *)")
    lines.append("        aControl_u[3] := LIMIT(8.20, aControl_u[3] - 0.020, 9.40);")
    lines.append("        (* Boost ore feed to build kidney toe cushioning bed *)")
    lines.append("        aControl_u[1] := LIMIT(1800.0, aControl_u[1] + 10.0, 3100.0);")
    lines.append("        ")
    lines.append("        IF (rShellAcousticHighFreqPct <= 45.0) AND (tFSM_StateTimer >= 30.0) THEN")
    lines.append("            bAcousticLinerAlert := FALSE;")
    lines.append("            nFSM_CurrentState := 8; (* Return to Equilibrium *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 10: STATE_SLURRY_OVERFILL_MITIGATION (10)
    lines.append("    10: (* STATE_SLURRY_OVERFILL_MITIGATION: Pulp lifter carryover & sump high level cutback *)")
    lines.append("        bReady  := TRUE;")
    lines.append("        bActive := TRUE;")
    lines.append("        bSlurryPoolAlert := TRUE;")
    lines.append("        ")
    lines.append("        (* Cut fresh ore feed rate by 35% *)")
    lines.append("        aControl_u[1] := aControl_u[1] * 0.995;")
    lines.append("        (* Accelerate mill speed slightly (+0.2 rpm) to boost pulp lifter discharge *)")
    lines.append("        aControl_u[3] := LIMIT(8.50, aControl_u[3] + 0.010, 10.40);")
    lines.append("        (* Ramp cyclone pump speed to drain sump *)")
    lines.append("        aControl_u[4] := LIMIT(500.0, aControl_u[4] + 2.0, 850.0);")
    lines.append("        (* Close sump dilution water to reduce hydraulic inflow *)")
    lines.append("        aControl_u[5] := MAX(50.0, aControl_u[5] - 5.0);")
    lines.append("        ")
    lines.append("        IF (aState_x[2] <= 18.0) AND (rSumpLevel_Voted <= 60.0) AND (tFSM_StateTimer >= 45.0) THEN")
    lines.append("            bSlurryPoolAlert := FALSE;")
    lines.append("            nFSM_CurrentState := 8; (* Return to Equilibrium *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 11: STATE_PEBBLE_CRUSHER_RECYCLE_OPT (11)
    lines.append("    11: (* STATE_PEBBLE_CRUSHER_RECYCLE_OPT: Modulate pebble split ratio based on hardness *)")
    lines.append("        bReady  := TRUE;")
    lines.append("        bActive := TRUE;")
    lines.append("        ")
    lines.append("        IF rBondWorkIndex_Estimated > 16.5 THEN")
    lines.append("            (* Hard competent ore: divert pebbles to pebble crushers and recycle 85% to SAG *)")
    lines.append("            aControl_u[7] := 85.0;")
    lines.append("        ELSIF rBondWorkIndex_Estimated < 12.5 THEN")
    lines.append("            (* Soft friable ore: bypass crusher directly to ball mill, recycle 25% to SAG *)")
    lines.append("            aControl_u[7] := 25.0;")
    lines.append("        ELSE")
    lines.append("            aControl_u[7] := 55.0;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        IF tFSM_StateTimer >= 60.0 THEN")
    lines.append("            nFSM_CurrentState := 8; (* Return to Equilibrium *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 12: STATE_CONTROLLED_GRIND_OUT_FLUSH (12)
    lines.append("    12: (* STATE_CONTROLLED_GRIND_OUT_FLUSH: Flush mill with water to evacuate charge mass *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := TRUE;")
    lines.append("        aControl_u[1] := 0.0; (* Ore feed completely stopped *)")
    lines.append("        aControl_u[2] := 650.0; (* Heavy water flush to clear pulp lifters *)")
    lines.append("        aControl_u[3] := 8.50; (* Moderate speed for wash-out *)")
    lines.append("        ")
    lines.append("        tGrindOutTimer := tGrindOutTimer - 0.050;")
    lines.append("        IF (tGrindOutTimer <= 0.0) OR (aState_x[1] <= 1150.0) THEN")
    lines.append("            (* Mill cleared of ore rock, only ball charge remains *)")
    lines.append("            nFSM_CurrentState := 0; (* Cold Stop Standstill *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("            bActive           := FALSE;")
    lines.append("        END_IF;")
    lines.append("")

    # Stage 13: STATE_EMERGENCY_TRIP_FAILSAFE (13)
    lines.append("    13: (* STATE_EMERGENCY_TRIP_FAILSAFE: SIL-3 rapid trip, disc brakes, jacking sustain *)")
    lines.append("        bReady  := FALSE;")
    lines.append("        bActive := FALSE;")
    lines.append("        bFault  := TRUE;")
    lines.append("        aControl_u[1] := 0.0; (* Feed conveyor tripped immediately *)")
    lines.append("        aControl_u[2] := 0.0; (* Chute water isolated *)")
    lines.append("        aControl_u[3] := 0.0; (* Inverter gate pulse inhibit & disc brake engage *)")
    lines.append("        aControl_u[4] := 0.0; (* Cyclone pump tripped *)")
    lines.append("        aControl_u[5] := 0.0; (* Sump water isolated *)")
    lines.append("        aControl_u[6] := 0.0; (* Knife gates parked *)")
    lines.append("        aControl_u[7] := 0.0; (* Pebble recycle diverted *)")
    lines.append("        aControl_u[8] := 0.0; (* Ball mill water isolated *)")
    lines.append("        rBearingCoolingWaterValve_Cmd := 100.0; (* Maximum cooling on bearing oil *)")
    lines.append("        ")
    lines.append("        IF bReset AND NOT bEmergencyStop THEN")
    lines.append("            bFault := FALSE;")
    lines.append("            bFrozenChargeTrip := FALSE;")
    lines.append("            nFSM_CurrentState := 0; (* Return to Cold Stop *)")
    lines.append("            tFSM_StateTimer   := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("END_CASE;")
    lines.append("")

    return "\n".join(lines)

print("Phase 4 generator written.")
