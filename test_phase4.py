# Python generator to build Phase 4: 64 CD Thermal Slice Lip Control

def build_phase4():
    st = []
    st.append("(* ==================================================================================================== *)\n")
    st.append("(* PHASE 4: 64 CROSS-DIRECTION (CD) THERMAL MICRO-EXPANSION SLICE LIP CONTROL                          *)\n")
    st.append("(* Spatial Deconvolution, Beam Curvature & Adjacent Bending Moment Projection, Spindle Thermal Dynamics *)\n")
    st.append("(* ==================================================================================================== *)\n\n")

    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("(* Sub-Phase 4.1: Cross-Machine Basis Weight Scanner Profile Spatial Statistical Analysis              *)\n")
    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("IF bScannerDataValid THEN\n")
    st.append("    rTempProfileMean := 0.0;\n")
    st.append("    FOR iAct := 1 TO 64 DO\n")
    st.append("        rTempProfileMean := rTempProfileMean + arrScanner_BasisWeight_gpm2[iAct];\n")
    st.append("    END_FOR;\n")
    st.append("    rCalc_MeanBasisWeight_gpm2 := rTempProfileMean / 64.0;\n\n")

    st.append("    (* Compute Variance & Standard Deviation (Sigma) Across 64 Transverse CD Zones *)\n")
    st.append("    rTempProfileVariance := 0.0;\n")
    st.append("    FOR iAct := 1 TO 64 DO\n")
    st.append("        rTempDelta := arrScanner_BasisWeight_gpm2[iAct] - rCalc_MeanBasisWeight_gpm2;\n")
    st.append("        rTempProfileVariance := rTempProfileVariance + (rTempDelta * rTempDelta);\n")
    st.append("    END_FOR;\n")
    st.append("    rCalc_Sigma_BasisWeight_gpm2 := SQRT(rTempProfileVariance / 64.0);\n")
    st.append("    IF rCalc_MeanBasisWeight_gpm2 > 1.0 THEN\n")
    st.append("        rCalc_TwoSigma_Pct := (2.0 * rCalc_Sigma_BasisWeight_gpm2 / rCalc_MeanBasisWeight_gpm2) * 100.0;\n")
    st.append("    ELSE\n")
    st.append("        rCalc_TwoSigma_Pct := 0.0;\n")
    st.append("    END_IF;\n")
    st.append("ELSE\n")
    st.append("    (* Retain Last Calculated Statistics in Event of Scanner Intermittent Loss *)\n")
    st.append("    rCalc_TwoSigma_Pct := rCalc_TwoSigma_Pct;\n")
    st.append("END_IF;\n\n")

    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("(* Sub-Phase 4.2: Spatial Error Filtering & Cross-Machine Error Integration                              *)\n")
    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("FOR iAct := 1 TO 64 DO\n")
    st.append("    arrErrorBasisWeight_CD[iAct] := arrScanner_BasisWeight_gpm2[iAct] - arrTargetBasisWeight_CD[iAct];\n")
    st.append("END_FOR;\n\n")

    st.append("(* 3-Point Spatial Moving Average Filter with Reflected Boundary Conditions *)\n")
    st.append("FOR iAct := 1 TO 64 DO\n")
    st.append("    IF iAct = 1 THEN\n")
    st.append("        arrFilteredError_CD[1] := (0.50 * arrErrorBasisWeight_CD[1]) + (0.50 * arrErrorBasisWeight_CD[2]);\n")
    st.append("    ELSIF iAct = 64 THEN\n")
    st.append("        arrFilteredError_CD[64] := (0.50 * arrErrorBasisWeight_CD[64]) + (0.50 * arrErrorBasisWeight_CD[63]);\n")
    st.append("    ELSE\n")
    st.append("        arrFilteredError_CD[iAct] := (0.25 * arrErrorBasisWeight_CD[iAct - 1]) + (0.50 * arrErrorBasisWeight_CD[iAct]) + (0.25 * arrErrorBasisWeight_CD[iAct + 1]);\n")
    st.append("    END_IF;\n\n")

    st.append("    (* Integral Accumulation with Anti-Windup Clamping Bounds [-250.0 .. +250.0] *)\n")
    st.append("    IF bCdControlEnable AND (eState >= 7) AND NOT bSheetBreakDetected THEN\n")
    st.append("        arrIntegralError_CD[iAct] := arrIntegralError_CD[iAct] + (arrFilteredError_CD[iAct] * tScanCycleTime_s);\n")
    st.append("        IF arrIntegralError_CD[iAct] > 250.0 THEN\n")
    st.append("            arrIntegralError_CD[iAct] := 250.0;\n")
    st.append("        ELSIF arrIntegralError_CD[iAct] < -250.0 THEN\n")
    st.append("            arrIntegralError_CD[iAct] := -250.0;\n")
    st.append("        END_IF;\n")
    st.append("    ELSE\n")
    st.append("        arrIntegralError_CD[iAct] := arrIntegralError_CD[iAct] * 0.998; (* Slow Exponential Drain in Hold *)\n")
    st.append("    END_IF;\n")
    st.append("END_FOR;\n\n")

    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("(* Sub-Phase 4.3: Spatial Toeplitz Cross-Coupling Deconvolution & Spindle Displacement Generation        *)\n")
    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("FOR iAct := 1 TO 64 DO\n")
    st.append("    rTempSum := 0.0;\n")
    st.append("    (* Spatial Convolution with Attenuation Kernel Matrix G *)\n")
    st.append("    FOR jAct := 1 TO 64 DO\n")
    st.append("        IF matG_Toeplitz[iAct, jAct] > 0.001 THEN\n")
    st.append("            rTempSum := rTempSum + (matG_Toeplitz[iAct, jAct] * ((rCdProfileGain_Kp * arrFilteredError_CD[jAct]) + (rCdProfileGain_Ki * arrIntegralError_CD[jAct])));\n")
    st.append("        END_IF;\n")
    st.append("    END_FOR;\n\n")

    st.append("    IF bCdControlEnable AND (eState >= 7) AND NOT bSheetBreakDetected THEN\n")
    st.append("        (* Positive Error (Heavier Basis Weight) -> Thermal Expansion to Narrow Gap -> Increase Spindle Length *)\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := arrSliceSpindlePrev_um[iAct] + (rTempSum * 8.5);\n")
    st.append("    ELSE\n")
    st.append("        (* Idle / Baseline Thermal Warmup Setpoint *)\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := 12500.0;\n")
    st.append("    END_IF;\n\n")

    st.append("    (* Absolute Spindle Travel Bounds: [8,000 .. 18,000 um] (8.0 mm .. 18.0 mm) *)\n")
    st.append("    IF arrSliceSpindleCmd_um[iAct] > 18000.0 THEN\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := 18000.0;\n")
    st.append("    ELSIF arrSliceSpindleCmd_um[iAct] < 8000.0 THEN\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := 8000.0;\n")
    st.append("    END_IF;\n")
    st.append("END_FOR;\n\n")

    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("(* Sub-Phase 4.4: Mechanical Slice Lip Bending Moment & Curvature Constraint Protection Projection       *)\n")
    st.append("(* Forward & Backward Passes to Enforce: |u[i] - u[i-1]| <= 25 [um] & |u[i+1] - 2*u[i] + u[i-1]| <= 18 [um] *)\n")
    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("(* Forward Adjacent Delta Step Limiting *)\n")
    st.append("FOR iAct := 2 TO 64 DO\n")
    st.append("    rTempDelta := arrSliceSpindleCmd_um[iAct] - arrSliceSpindleCmd_um[iAct - 1];\n")
    st.append("    IF rTempDelta > rMaxAllowedAdjacentDelta_um THEN\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := arrSliceSpindleCmd_um[iAct - 1] + rMaxAllowedAdjacentDelta_um;\n")
    st.append("    ELSIF rTempDelta < -rMaxAllowedAdjacentDelta_um THEN\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := arrSliceSpindleCmd_um[iAct - 1] - rMaxAllowedAdjacentDelta_um;\n")
    st.append("    END_IF;\n")
    st.append("END_FOR;\n\n")

    st.append("(* Backward Adjacent Delta Step Limiting *)\n")
    st.append("FOR iAct := 63 DOWNTO 1 DO\n")
    st.append("    rTempDelta := arrSliceSpindleCmd_um[iAct] - arrSliceSpindleCmd_um[iAct + 1];\n")
    st.append("    IF rTempDelta > rMaxAllowedAdjacentDelta_um THEN\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := arrSliceSpindleCmd_um[iAct + 1] + rMaxAllowedAdjacentDelta_um;\n")
    st.append("    ELSIF rTempDelta < -rMaxAllowedAdjacentDelta_um THEN\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := arrSliceSpindleCmd_um[iAct + 1] - rMaxAllowedAdjacentDelta_um;\n")
    st.append("    END_IF;\n")
    st.append("END_FOR;\n\n")

    st.append("(* Beam Curvature Smoothing & Maximum Metric Logging *)\n")
    st.append("rCalc_MaxSliceCurvature_um := 0.0;\n")
    st.append("rCalc_MaxAdjacentDelta_um := 0.0;\n")
    st.append("FOR iAct := 2 TO 63 DO\n")
    st.append("    rTempDelta := ABS(arrSliceSpindleCmd_um[iAct] - arrSliceSpindleCmd_um[iAct - 1]);\n")
    st.append("    arrAdjacentDelta_um[iAct] := rTempDelta;\n")
    st.append("    IF rTempDelta > rCalc_MaxAdjacentDelta_um THEN\n")
    st.append("        rCalc_MaxAdjacentDelta_um := rTempDelta;\n")
    st.append("    END_IF;\n\n")

    st.append("    (* Second Difference Discrete Curvature: u[i+1] - 2*u[i] + u[i-1] *)\n")
    st.append("    rTempSum := arrSliceSpindleCmd_um[iAct + 1] - (2.0 * arrSliceSpindleCmd_um[iAct]) + arrSliceSpindleCmd_um[iAct - 1];\n")
    st.append("    arrCurvature_um[iAct] := ABS(rTempSum);\n")
    st.append("    IF arrCurvature_um[iAct] > rCalc_MaxSliceCurvature_um THEN\n")
    st.append("        rCalc_MaxSliceCurvature_um := arrCurvature_um[iAct];\n")
    st.append("    END_IF;\n")
    st.append("    IF arrCurvature_um[iAct] > rMaxAllowedCurvature_um THEN\n")
    st.append("        (* Soft Geometric Curvature Relief *)\n")
    st.append("        arrSliceSpindleCmd_um[iAct] := (0.50 * (arrSliceSpindleCmd_um[iAct + 1] + arrSliceSpindleCmd_um[iAct - 1]));\n")
    st.append("    END_IF;\n")
    st.append("END_FOR;\n\n")

    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("(* Sub-Phase 4.5: Electro-Thermal Expansion Physics & Electrical Heater Command Generation              *)\n")
    st.append("(* Delta_L = alpha * L_spindle * (T_core - T_ambient) [um]                                              *)\n")
    st.append("(* ---------------------------------------------------------------------------------------------------- *)\n")
    st.append("FOR iAct := 1 TO 64 DO\n")
    st.append("    (* Desired Thermal Micro-Expansion Relative to Cold Baseline *)\n")
    st.append("    rTempDelta := arrSliceSpindleCmd_um[iAct] - 8000.0; (* 8000 um is full cold retraction *)\n")
    st.append("    (* Invert Thermal Model: Required Steady-State Core Temperature *)\n")
    st.append("    rTempCandidate := rAmbientTemp_degC + (rTempDelta / (rSliceThermalAlpha * (rSpindleLength_mm * 1000.0)));\n\n")

    st.append("    (* Compute Required Heater Electrical Power Duty Cycle [%] *)\n")
    st.append("    IF rTempCandidate > rAmbientTemp_degC THEN\n")
    st.append("        rTempSum := (rTempCandidate - rAmbientTemp_degC) / rSpindleHeaterGain_K_pct;\n")
    st.append("    ELSE\n")
    st.append("        rTempSum := 0.0;\n")
    st.append("    END_IF;\n\n")

    st.append("    (* Power Command Physical Bounds [0.0 .. 100.0 %] *)\n")
    st.append("    IF rTempSum > 100.0 THEN\n")
    st.append("        arrThermalHeater_PowerCmd_pct[iAct] := 100.0;\n")
    st.append("    ELSIF rTempSum < 0.0 THEN\n")
    st.append("        arrThermalHeater_PowerCmd_pct[iAct] := 0.0;\n")
    st.append("    ELSE\n")
    st.append("        arrThermalHeater_PowerCmd_pct[iAct] := rTempSum;\n")
    st.append("    END_IF;\n\n")

    st.append("    (* Discrete Simulation of Spindle Core Thermal Response *)\n")
    st.append("    arrThermalModelTemp_degC[iAct] := arrThermalModelTemp_degC[iAct] + ((tScanCycleTime_s / rSpindleThermalTau_s) * ((rAmbientTemp_degC + (arrThermalHeater_PowerCmd_pct[iAct] * rSpindleHeaterGain_K_pct)) - arrThermalModelTemp_degC[iAct]));\n\n")

    st.append("    (* Resultant Physical Spindle Thermal Expansion [um] *)\n")
    st.append("    arrThermalExpansion_um[iAct] := rSliceThermalAlpha * (rSpindleLength_mm * 1000.0) * (arrThermalModelTemp_degC[iAct] - rAmbientTemp_degC);\n")
    st.append("    arrSliceSpindle_EstGap_um[iAct] := 18000.0 - arrThermalExpansion_um[iAct];\n")
    st.append("    arrSliceSpindlePrev_um[iAct] := arrSliceSpindleCmd_um[iAct];\n")
    st.append("END_FOR;\n\n")

    return "".join(st)

print("build_phase4 len:", len(build_phase4()))
