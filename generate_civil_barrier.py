    c.append("ELSIF bHealthy_RightStroke_A AND bHealthy_RightStroke_B THEN")
    c.append("    rVoted_RightCylinderStroke := 0.5 * (rCylinderStroke_Right_A + rCylinderStroke_Right_B);")
    c.append("    iDiscrepancyCount_RightStroke := iDiscrepancyCount_RightStroke + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0008;")
    c.append("ELSIF bHealthy_RightStroke_B AND bHealthy_RightStroke_C THEN")
    c.append("    rVoted_RightCylinderStroke := 0.5 * (rCylinderStroke_Right_B + rCylinderStroke_Right_C);")
    c.append("    iDiscrepancyCount_RightStroke := iDiscrepancyCount_RightStroke + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0008;")
    c.append("ELSIF bHealthy_RightStroke_A AND bHealthy_RightStroke_C THEN")
    c.append("    rVoted_RightCylinderStroke := 0.5 * (rCylinderStroke_Right_A + rCylinderStroke_Right_C);")
    c.append("    iDiscrepancyCount_RightStroke := iDiscrepancyCount_RightStroke + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0008;")
    c.append("ELSE")
    c.append("    bSystemTripMaster := TRUE;")
    c.append("    dwTripWord := dwTripWord OR 16#0000_0010; (* Right Stroke Tri-Sensor Divergence Trip *)")
    c.append("END_IF;")
    c.append("")

    # 1.5 Hydraulic Pressure
    c.append("(* 1.5 Main Hydraulic Power Unit (HPU) Manifold Pressure Voting *)")
    c.append("rDiffAB := ABS(rHydraulicSupplyPress_A - rHydraulicSupplyPress_B);")
    c.append("rDiffBC := ABS(rHydraulicSupplyPress_B - rHydraulicSupplyPress_C);")
    c.append("rDiffCA := ABS(rHydraulicSupplyPress_C - rHydraulicSupplyPress_A);")
    c.append("bHealthy_HPU_Press_A := (rDiffAB <= c_Tolerance_HydraulicPress) OR (rDiffCA <= c_Tolerance_HydraulicPress);")
    c.append("bHealthy_HPU_Press_B := (rDiffAB <= c_Tolerance_HydraulicPress) OR (rDiffBC <= c_Tolerance_HydraulicPress);")
    c.append("bHealthy_HPU_Press_C := (rDiffBC <= c_Tolerance_HydraulicPress) OR (rDiffCA <= c_Tolerance_HydraulicPress);")
    c.append("IF bHealthy_HPU_Press_A AND bHealthy_HPU_Press_B AND bHealthy_HPU_Press_C THEN")
    c.append("    IF (rHydraulicSupplyPress_A >= rHydraulicSupplyPress_B AND rHydraulicSupplyPress_A <= rHydraulicSupplyPress_C) OR (rHydraulicSupplyPress_A >= rHydraulicSupplyPress_C AND rHydraulicSupplyPress_A <= rHydraulicSupplyPress_B) THEN")
    c.append("        rVoted_HydraulicSupplyPress := rHydraulicSupplyPress_A;")
    c.append("    ELSIF (rHydraulicSupplyPress_B >= rHydraulicSupplyPress_A AND rHydraulicSupplyPress_B <= rHydraulicSupplyPress_C) OR (rHydraulicSupplyPress_B >= rHydraulicSupplyPress_C AND rHydraulicSupplyPress_B <= rHydraulicSupplyPress_A) THEN")
    c.append("        rVoted_HydraulicSupplyPress := rHydraulicSupplyPress_B;")
    c.append("    ELSE")
    c.append("        rVoted_HydraulicSupplyPress := rHydraulicSupplyPress_C;")
    c.append("    END_IF;")
    c.append("    iDiscrepancyCount_HPU_Press := 0;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 AND NOT 16#0000_0010;")
    c.append("ELSIF bHealthy_HPU_Press_A AND bHealthy_HPU_Press_B THEN")
    c.append("    rVoted_HydraulicSupplyPress := 0.5 * (rHydraulicSupplyPress_A + rHydraulicSupplyPress_B);")
    c.append("    iDiscrepancyCount_HPU_Press := iDiscrepancyCount_HPU_Press + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0010;")
    c.append("ELSIF bHealthy_HPU_Press_B AND bHealthy_HPU_Press_C THEN")
    c.append("    rVoted_HydraulicSupplyPress := 0.5 * (rHydraulicSupplyPress_B + rHydraulicSupplyPress_C);")
    c.append("    iDiscrepancyCount_HPU_Press := iDiscrepancyCount_HPU_Press + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0010;")
    c.append("ELSIF bHealthy_HPU_Press_A AND bHealthy_HPU_Press_C THEN")
    c.append("    rVoted_HydraulicSupplyPress := 0.5 * (rHydraulicSupplyPress_A + rHydraulicSupplyPress_C);")
    c.append("    iDiscrepancyCount_HPU_Press := iDiscrepancyCount_HPU_Press + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0010;")
    c.append("ELSE")
    c.append("    bSystemTripMaster := TRUE;")
    c.append("    dwTripWord := dwTripWord OR 16#0000_0020;")
    c.append("END_IF;")
    c.append("")

    # Calculate Differential Head and Skew
    c.append("(* Calculate Validated Process Coordinates *)")
    c.append("rVoted_DifferentialHead := rVoted_SeaWaterLevel - rVoted_RiverWaterLevel;")
    c.append("rCalculated_GateSkew_Delta := rVoted_LeftCylinderStroke - rVoted_RightCylinderStroke;")
    c.append("rSectorGateAngularPosition_Deg := (rVoted_LeftCylinderStroke / c_MaxGateStroke_mm) * 68.0;")
    c.append("")
    c.append("(* Synchronize State Vector with Process Feedback *)")
    c.append("rState_Vector_x[1] := rVoted_LeftCylinderStroke;")
    c.append("rState_Vector_x[2] := rVoted_RightCylinderStroke;")
    c.append("rState_Vector_x[3] := rCalculated_GateSkew_Delta;")
    c.append("rState_Vector_x[4] := rVoted_DifferentialHead;")
    c.append("rState_Vector_x[5] := rCulvertVolumetricFlow_m3_s;")
    c.append("")

    # Phase 2: State-Space Prediction
    c.append("(* === PHASE 2: STATE-SPACE PREDICTION (x[k+1] = A*x[k] + B*u[k]) === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Evaluates matrix multiplication for 6-state, 3-control sector gate dynamics.              *)")
    c.append("(* Propagates state trajectory forward in time across discrete scan interval Ts = 5 ms.      *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("FOR iIdx := 1 TO 6 DO")
    c.append("    rMatrixAcc := 0.0;")
    c.append("    FOR jIdx := 1 TO 6 DO")
    c.append("        rMatrixAcc := rMatrixAcc + (A_Matrix[iIdx, jIdx] * rState_Vector_x[jIdx]);")
    c.append("    END_FOR;")
    c.append("    FOR kIdx := 1 TO 3 DO")
    c.append("        rMatrixAcc := rMatrixAcc + (B_Matrix[iIdx, kIdx] * rControl_Vector_u[kIdx]);")
    c.append("    END_FOR;")
    c.append("    rState_Vector_x_pred[iIdx] := rMatrixAcc;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Enforce Physical Safety Bounds on State Estimator *)")
    c.append("IF rState_Vector_x_pred[1] < 0.0 THEN")
    c.append("    rState_Vector_x_pred[1] := 0.0;")
    c.append("ELSIF rState_Vector_x_pred[1] > c_MaxGateStroke_mm THEN")
    c.append("    rState_Vector_x_pred[1] := c_MaxGateStroke_mm;")
    c.append("END_IF;")
    c.append("")
    c.append("IF rState_Vector_x_pred[2] < 0.0 THEN")
    c.append("    rState_Vector_x_pred[2] := 0.0;")
    c.append("ELSIF rState_Vector_x_pred[2] > c_MaxGateStroke_mm THEN")
    c.append("    rState_Vector_x_pred[2] := c_MaxGateStroke_mm;")
    c.append("END_IF;")
    c.append("")

    # Phase 3: Receding-Horizon MPC Action
    c.append("(* === PHASE 3: RECEDING-HORIZON MPC CONTROL ACTION === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Solves receding-horizon quadratic optimization over control horizon Nc = 3:             *)")
    c.append("(* min J = (x_pred - x_ref)^T * Q * (x_pred - x_ref) + u^T * R * u + Delta_u^T * S * Delta_u *)")
    c.append("(* Uses projected gradient descent with explicit actuator hard constraints & slew rate.     *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("FOR rMPC_IterationCount := 1 TO rMPC_MaxIterations DO")
    c.append("    FOR kIdx := 1 TO 3 DO")
    c.append("        rMPC_Gradient[kIdx] := R_WeightDiag[kIdx] * rControl_Vector_u[kIdx];")
    c.append("        rMPC_Gradient[kIdx] := rMPC_Gradient[kIdx] + (S_RateWeightDiag[kIdx] * (rControl_Vector_u[kIdx] - rControl_Vector_u_prev[kIdx]));")
    c.append("        FOR iIdx := 1 TO 6 DO")
    c.append("            rPredError := rState_Vector_x_pred[iIdx] - rState_Setpoint_xref[iIdx];")
    c.append("            rMPC_Gradient[kIdx] := rMPC_Gradient[kIdx] + (B_Matrix[iIdx, kIdx] * Q_WeightDiag[iIdx] * rPredError);")
    c.append("        END_FOR;")
    c.append("    END_FOR;")
    c.append("")
    c.append("    (* Descent Update *)")
    c.append("    rControl_Vector_u[1] := rControl_Vector_u[1] - (rMPC_StepSize * rMPC_Gradient[1]);")
    c.append("    rControl_Vector_u[2] := rControl_Vector_u[2] - (rMPC_StepSize * rMPC_Gradient[2]);")
    c.append("    rControl_Vector_u[3] := rControl_Vector_u[3] - (rMPC_StepSize * rMPC_Gradient[3]);")
    c.append("")
    c.append("    (* Hard Saturation Limits [-100%, 100%] *)")
    c.append("    IF rControl_Vector_u[1] < c_u1_Min THEN")
    c.append("        rControl_Vector_u[1] := c_u1_Min;")
    c.append("    ELSIF rControl_Vector_u[1] > c_u1_Max THEN")
    c.append("        rControl_Vector_u[1] := c_u1_Max;")
    c.append("    END_IF;")
    c.append("")
    c.append("    IF rControl_Vector_u[2] < c_u2_Min THEN")
    c.append("        rControl_Vector_u[2] := c_u2_Min;")
    c.append("    ELSIF rControl_Vector_u[2] > c_u2_Max THEN")
    c.append("        rControl_Vector_u[2] := c_u2_Max;")
    c.append("    END_IF;")
    c.append("")
    c.append("    IF rControl_Vector_u[3] < c_u3_Min THEN")
    c.append("        rControl_Vector_u[3] := c_u3_Min;")
    c.append("    ELSIF rControl_Vector_u[3] > c_u3_Max THEN")
    c.append("        rControl_Vector_u[3] := c_u3_Max;")
    c.append("    END_IF;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Physical Slew Rate Limiter Implementation *)")
    c.append("rDeltaU_Clamped := rControl_Vector_u[1] - rControl_Vector_u_prev[1];")
    c.append("IF rDeltaU_Clamped > (c_u1_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[1] := rControl_Vector_u_prev[1] + (c_u1_MaxRate * rCycleScanTime_Ts);")
    c.append("ELSIF rDeltaU_Clamped < -(c_u1_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[1] := rControl_Vector_u_prev[1] - (c_u1_MaxRate * rCycleScanTime_Ts);")
    c.append("END_IF;")
    c.append("")
    c.append("rDeltaU_Clamped := rControl_Vector_u[2] - rControl_Vector_u_prev[2];")
    c.append("IF rDeltaU_Clamped > (c_u2_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[2] := rControl_Vector_u_prev[2] + (c_u2_MaxRate * rCycleScanTime_Ts);")
    c.append("ELSIF rDeltaU_Clamped < -(c_u2_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[2] := rControl_Vector_u_prev[2] - (c_u2_MaxRate * rCycleScanTime_Ts);")
    c.append("END_IF;")
    c.append("")
    c.append("rDeltaU_Clamped := rControl_Vector_u[3] - rControl_Vector_u_prev[3];")
    c.append("IF rDeltaU_Clamped > (c_u3_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[3] := rControl_Vector_u_prev[3] + (c_u3_MaxRate * rCycleScanTime_Ts);")
    c.append("ELSIF rDeltaU_Clamped < -(c_u3_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[3] := rControl_Vector_u_prev[3] - (c_u3_MaxRate * rCycleScanTime_Ts);")
    c.append("END_IF;")
    c.append("")
    c.append("rControl_Vector_u_prev[1] := rControl_Vector_u[1];")
    c.append("rControl_Vector_u_prev[2] := rControl_Vector_u[2];")
    c.append("rControl_Vector_u_prev[3] := rControl_Vector_u[3];")
    c.append("")

    # Phase 4: Anti-Twist Skew Synchronizer & Hydrodynamic Observers
    c.append("(* === PHASE 4: ANTI-TWIST SKEW SYNCHRONIZER & HYDRODYNAMICS === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Computes cross-coupled proportional skew compensation to enforce |Delta_y| <= 1.0 mm.     *)")
    c.append("(* Calculates resultant hydrostatic thrust [MN], overturning moment [MNm], culvert flow     *)")
    c.append("(* rate [m3/s], and cavitation index sigma.                                                  *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("")
    c.append("(* 4.1 Cross-Coupled Anti-Twist Skew Compensator *)")
    c.append("rCalculated_GateSkew_Delta := rVoted_LeftCylinderStroke - rVoted_RightCylinderStroke;")
    c.append("rSkewTrim_Left := - (rCalculated_GateSkew_Delta * rSkewCorrectionFactor_Kp);")
    c.append("rSkewTrim_Right := + (rCalculated_GateSkew_Delta * rSkewCorrectionFactor_Kp);")
    c.append("")
    c.append("(* Clamp trim signals to +/- 18% *)")
    c.append("IF rSkewTrim_Left > 18.0 THEN")
    c.append("    rSkewTrim_Left := 18.0;")
    c.append("ELSIF rSkewTrim_Left < -18.0 THEN")
    c.append("    rSkewTrim_Left := -18.0;")
    c.append("END_IF;")
    c.append("")
    c.append("IF rSkewTrim_Right > 18.0 THEN")
    c.append("    rSkewTrim_Right := 18.0;")
    c.append("ELSIF rSkewTrim_Right < -18.0 THEN")
    c.append("    rSkewTrim_Right := -18.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* Apply Skew Trim on Top of MPC Base Flow Output *)")
    c.append("rLeftServoValve_FlowCmd := rControl_Vector_u[1] + rSkewTrim_Left;")
    c.append("rRightServoValve_FlowCmd := rControl_Vector_u[2] + rSkewTrim_Right;")
    c.append("")
    c.append("(* 4.2 Hydrostatic Thrust & Overturning Moment Calculations *)")
    c.append("IF (rVoted_SeaWaterLevel > 0.0) AND (rVoted_RiverWaterLevel > 0.0) THEN")
    c.append("    rHydrostaticNetThrust_MN := (0.5 * c_SeawaterDensity * c_GravitationalAcc * c_GateSpanWidth_m * ((rVoted_SeaWaterLevel ** 2.0) - (rVoted_RiverWaterLevel ** 2.0))) / 1000000.0;")
    c.append("    rOverturningMoment_MNm := ((1.0 / 6.0) * c_SeawaterDensity * c_GravitationalAcc * c_GateSpanWidth_m * ((rVoted_SeaWaterLevel ** 3.0) - (rVoted_RiverWaterLevel ** 3.0))) / 1000000.0;")
    c.append("ELSE")
    c.append("    rHydrostaticNetThrust_MN := 0.0;")
    c.append("    rOverturningMoment_MNm := 0.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* 4.3 Culvert Equalization Conduit Hydraulics *)")
    c.append("rCulvertDeltaHeadAbs := ABS(rVoted_SeaWaterLevel - rVoted_RiverWaterLevel);")
    c.append("IF rCulvertDeltaHeadAbs > 0.02 THEN")
    c.append("    rCulvertVolumetricFlow_m3_s := c_CulvertDischargeCoeff_Cd * (c_CulvertCrossSectionArea_m2 * (rCulvertSluicePosition_Fbk / 100.0)) * SQRT(2.0 * c_GravitationalAcc * rCulvertDeltaHeadAbs);")
    c.append("ELSE")
    c.append("    rCulvertVolumetricFlow_m3_s := 0.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* Lock Basin Rise Rate [m/min] *)")
    c.append("rLockChamberFillingRate_m_min := (rCulvertVolumetricFlow_m3_s * 60.0) / c_LockChamberSurfaceArea_m2;")
    c.append("")
    c.append("(* 4.4 Culvert Cavitation Number Sigma *)")
    c.append("rCulvertDeltaP_bar := ABS(rCulvertUpstreamPress - rCulvertDownstreamPress);")
    c.append("IF rCulvertDeltaP_bar > 0.15 THEN")
    c.append("    rCulvertCavitationIndex_Sigma := (rCulvertDownstreamPress - c_SeawaterVaporPressure_bar) / rCulvertDeltaP_bar;")
    c.append("ELSE")
    c.append("    rCulvertCavitationIndex_Sigma := 3.50; (* Safe non-cavitating baseline *)")
    c.append("END_IF;")
    c.append("")
    c.append("IF rCulvertCavitationIndex_Sigma <= c_CulvertCavitation_Alarm_L THEN")
    c.append("    bCulvertCavitationWarning := TRUE;")
    c.append("    dwAlarmWord1 := dwAlarmWord1 OR 16#0000_0001; (* Culvert Cavitation Alert *)")
    c.append("ELSE")
    c.append("    bCulvertCavitationWarning := FALSE;")
    c.append("    dwAlarmWord1 := dwAlarmWord1 AND NOT 16#0000_0001;")
    c.append("END_IF;")
    c.append("")

    # Phase 5: Multi-Stage FSM
    c.append("(* === PHASE 5: MULTI-STAGE CASE FINITE STATE MACHINE === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Deterministic 13-stage barrier storm deployment & retraction supervisor:                 *)")
    c.append("(* Standby open, storm warning armed, ship radar clear, controlled drop, bottom sill flush,  *)")
    c.append("(* seal lock, storm hold, paced equalization fill, seal deflation, re-opening lift, latch.  *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("CASE iActiveFSM_State OF")
    c.append("")
    c.append("    0: (* STATE 0: BARRIER STANDBY OPEN & CHANNEL FREE NAVIGATION *)")
    c.append("        rLeftServoValve_FlowCmd         := 0.0;")
    c.append("        rRightServoValve_FlowCmd        := 0.0;")
    c.append("        rCulvertSluiceValve_Cmd         := 0.0;")
    c.append("        rInflatableSillSeal_PressCmd    := 0.0;")
    c.append("        bMainHPU_Pump1_RunCmd           := FALSE;")
    c.append("        bMainHPU_Pump2_RunCmd           := FALSE;")
    c.append("        bMechanicalGateLatch_Disengage  := FALSE; (* Mechanically hooked in dry recess *)")
    c.append("        bSafetyIsolatorValves_Energize  := FALSE;")
    c.append("        bBarrierFullyOpen               := TRUE;")
    c.append("        bBarrierFullyClosed             := FALSE;")
    c.append("        rStateDwellTimer_Sec            := 0.0;")
    c.append("        rTotalDeploymentTime_Sec        := 0.0;")
    c.append("        IF bEnableSupervisorySystem AND bStormSurgeWarningDeclared AND NOT bSystemTripMaster THEN")
    c.append("            iActiveFSM_State := 10; (* Proceed to Storm Warning Armed *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    10: (* STATE 10: STORM SURGE WARNING ARMED & HPU WARM-UP *)")
    c.append("        bMainHPU_Pump1_RunCmd := TRUE; (* Start primary hydraulic pump *)")
    c.append("        bMainHPU_Pump2_RunCmd := TRUE; (* Start secondary pump to charge accumulators *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF (rStateDwellTimer_Sec >= 15.0) AND (rVoted_HydraulicSupplyPress >= 210.0) THEN")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 20; (* Proceed to Ship Radar Clearance *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    20: (* STATE 20: PRE-CLOSING NAVIGATION RADAR SWEEP & HORN WARNING *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF bShipClearanceRadarVerified AND bBarrierCloseInitiateCommand THEN")
    c.append("            bNavigationClearanceVerified := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 30; (* Proceed to Unlatch Gate *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    30: (* STATE 30: MECHANICAL LATCH DISENGAGEMENT & SINK PREPARATION *)")
    c.append("        bSafetyIsolatorValves_Energize := TRUE;")
    c.append("        bMechanicalGateLatch_Disengage := TRUE; (* Hydraulic cylinders retract locking dogs *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF rStateDwellTimer_Sec >= 8.0 THEN")
    c.append("            bMechanicalLatchesDisengaged := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 40; (* Proceed to Controlled Hydraulic Drop *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    40: (* STATE 40: GATE CONTROLLED DESCENT WITH CLOSED-LOOP SKEW REGULATION *)")
    c.append("        bBarrierFullyOpen := FALSE;")
    c.append("        bSafetyIsolatorValves_Energize := TRUE;")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        rTotalDeploymentTime_Sec := rTotalDeploymentTime_Sec + rCycleScanTime_Ts;")
    c.append("        (* Target setpoints for MPC in lowering sequence *)")
    c.append("        rState_Setpoint_xref[1] := c_MaxGateStroke_mm;")
    c.append("        rState_Setpoint_xref[2] := c_MaxGateStroke_mm;")
    c.append("        rState_Setpoint_xref[3] := 0.0; (* Zero skew demand *)")
    c.append("        (* Verify gate reaches pre-touchdown clearance (11,800 mm) *)")
    c.append("        IF (rVoted_LeftCylinderStroke >= 11800.0) AND (rVoted_RightCylinderStroke >= 11800.0) THEN")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 50; (* Proceed to Sill Touchdown & Flush *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    50: (* STATE 50: SILL TOUCHDOWN FLUSH & DEBRIS ELIMINATION *)")
    c.append("        (* Crack culverts slightly to flush sediment from bottom concrete sill *)")
    c.append("        rCulvertSluiceValve_Cmd := 15.0;")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF (rVoted_LeftCylinderStroke >= (c_MaxGateStroke_mm - 20.0)) AND (rVoted_RightCylinderStroke >= (c_MaxGateStroke_mm - 20.0)) THEN")
    c.append("            bGateTouchdownVerified := TRUE;")
    c.append("            rCulvertSluiceValve_Cmd := 0.0;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 60; (* Proceed to Seal Pressurization *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    60: (* STATE 60: INFLATABLE BOTTOM SILL SEAL PRESSURIZATION & INTERLOCK *)")
    c.append("        rInflatableSillSeal_PressCmd := 12.0; (* Inflate EPDM seal with 12 bar water/air *)")
