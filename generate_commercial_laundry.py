    c.append("bHealthy_IntakeWeight_A := (rDiffAB <= c_Tolerance_BatchWeight) OR (rDiffCA <= c_Tolerance_BatchWeight);")
    c.append("bHealthy_IntakeWeight_B := (rDiffAB <= c_Tolerance_BatchWeight) OR (rDiffBC <= c_Tolerance_BatchWeight);")
    c.append("bHealthy_IntakeWeight_C := (rDiffBC <= c_Tolerance_BatchWeight) OR (rDiffCA <= c_Tolerance_BatchWeight);")
    c.append("IF bHealthy_IntakeWeight_A AND bHealthy_IntakeWeight_B AND bHealthy_IntakeWeight_C THEN")
    c.append("    IF (rBatchWeighHopper_A >= rBatchWeighHopper_B AND rBatchWeighHopper_A <= rBatchWeighHopper_C) OR (rBatchWeighHopper_A >= rBatchWeighHopper_C AND rBatchWeighHopper_A <= rBatchWeighHopper_B) THEN")
    c.append("        rVoted_BatchIntakeWeight := rBatchWeighHopper_A;")
    c.append("    ELSIF (rBatchWeighHopper_B >= rBatchWeighHopper_A AND rBatchWeighHopper_B <= rBatchWeighHopper_C) OR (rBatchWeighHopper_B >= rBatchWeighHopper_C AND rBatchWeighHopper_B <= rBatchWeighHopper_A) THEN")
    c.append("        rVoted_BatchIntakeWeight := rBatchWeighHopper_B;")
    c.append("    ELSE")
    c.append("        rVoted_BatchIntakeWeight := rBatchWeighHopper_C;")
    c.append("    END_IF;")
    c.append("    iDiscrepancyCount_IntakeWeight := 0;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 AND NOT 16#0000_0010;")
    c.append("ELSIF bHealthy_IntakeWeight_A AND bHealthy_IntakeWeight_B THEN")
    c.append("    rVoted_BatchIntakeWeight := 0.5 * (rBatchWeighHopper_A + rBatchWeighHopper_B);")
    c.append("    iDiscrepancyCount_IntakeWeight := iDiscrepancyCount_IntakeWeight + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0010;")
    c.append("ELSIF bHealthy_IntakeWeight_B AND bHealthy_IntakeWeight_C THEN")
    c.append("    rVoted_BatchIntakeWeight := 0.5 * (rBatchWeighHopper_B + rBatchWeighHopper_C);")
    c.append("    iDiscrepancyCount_IntakeWeight := iDiscrepancyCount_IntakeWeight + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0010;")
    c.append("ELSIF bHealthy_IntakeWeight_A AND bHealthy_IntakeWeight_C THEN")
    c.append("    rVoted_BatchIntakeWeight := 0.5 * (rBatchWeighHopper_A + rBatchWeighHopper_C);")
    c.append("    iDiscrepancyCount_IntakeWeight := iDiscrepancyCount_IntakeWeight + 1;")
    c.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0010;")
    c.append("ELSE")
    c.append("    bSystemTripMaster := TRUE;")
    c.append("    dwTripWord := dwTripWord OR 16#0000_0020;")
    c.append("END_IF;")
    c.append("")

    # Map state vector
    c.append("(* Synchronize State Vector with Process Feedback *)")
    c.append("rState_Vector_x[1] := rVoted_MainWashTemp;")
    c.append("rState_Vector_x[2] := rAlkaliConductivity_mS;")
    c.append("rState_Vector_x[3] := rRamPosition_mm;")
    c.append("rState_Vector_x[4] := rVoted_RamChamberPress;")
    c.append("rState_Vector_x[5] := rEstimatedCakeMoisture_Pct;")
    c.append("")

    # Phase 2: State-Space Prediction
    c.append("(* === PHASE 2: STATE-SPACE PREDICTION (x[k+1] = A*x[k] + B*u[k]) === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Linearized discrete prediction for 6-state, 3-control laundry and dewatering mechanics.   *)")
    c.append("(* Propagates state trajectory forward in time across discrete scan interval Ts = 5 ms.      *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("FOR iIdx := 1 TO 6 DO")
    c.append("    rMatrixAcc := 0.0;")
    c.append("    FOR jIdx := 1 TO 6 DO")
    c.append("        rMatrixAcc := rMatrixAcc + (A_Matrix[iIdx, jIdx] * rState_Vector_x[jIdx]);")
    c.append("    END_FOR;")
    c.append("    FOR kIdx := 1 TO 3 DO")
    c.append("        rMatrixAcc := rMatrixAcc + (B_Matrix[iIdx, kIdx] * rControl_Vector_u[kIdx]);")
    c.append("    END_FOR;")
    c.append("    rState_Vector_x_pred[iIdx] := rMatrixAcc;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Physical bounds on state estimator *)")
    c.append("IF rState_Vector_x_pred[1] < 15.0 THEN")
    c.append("    rState_Vector_x_pred[1] := 15.0;")
    c.append("ELSIF rState_Vector_x_pred[1] > 98.0 THEN")
    c.append("    rState_Vector_x_pred[1] := 98.0;")
    c.append("END_IF;")
    c.append("")
    c.append("IF rState_Vector_x_pred[4] < 0.0 THEN")
    c.append("    rState_Vector_x_pred[4] := 0.0;")
    c.append("ELSIF rState_Vector_x_pred[4] > 45.0 THEN")
    c.append("    rState_Vector_x_pred[4] := 45.0;")
    c.append("END_IF;")
    c.append("")

    # Phase 3: Receding-Horizon MPC Action
    c.append("(* === PHASE 3: RECEDING-HORIZON MPC CONTROL ACTION === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Solves receding-horizon quadratic optimization over control horizon Nc = 3:             *)")
    c.append("(* min J = (x_pred - x_ref)^T * Q * (x_pred - x_ref) + u^T * R * u + Delta_u^T * S * Delta_u *)")
    c.append("(* Applies projected gradient descent with explicit actuator hard constraints & slew rate.     *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("FOR rMPC_IterationCount := 1 TO rMPC_MaxIterations DO")
    c.append("    FOR kIdx := 1 TO 3 DO")
    c.append("        rMPC_Gradient[kIdx] := R_WeightDiag[kIdx] * rControl_Vector_u[kIdx];")
    c.append("        rMPC_Gradient[kIdx] := rMPC_Gradient[kIdx] + (S_RateWeightDiag[kIdx] * (rControl_Vector_u[kIdx] - rControl_Vector_u_prev[kIdx]));")
    c.append("        FOR iIdx := 1 TO 6 DO")
    c.append("            rPredError := rState_Vector_x_pred[iIdx] - rState_Setpoint_xref[iIdx];")
    c.append("            rMPC_Gradient[kIdx] := rMPC_Gradient[kIdx] + (B_Matrix[iIdx, kIdx] * Q_WeightDiag[iIdx] * rPredError);")
    c.append("        END_FOR;")
    c.append("    END_FOR;")
    c.append("")
    c.append("    (* Projected Gradient Step *)")
    c.append("    rControl_Vector_u[1] := rControl_Vector_u[1] - (rMPC_StepSize * rMPC_Gradient[1]);")
    c.append("    rControl_Vector_u[2] := rControl_Vector_u[2] - (rMPC_StepSize * rMPC_Gradient[2]);")
    c.append("    rControl_Vector_u[3] := rControl_Vector_u[3] - (rMPC_StepSize * rMPC_Gradient[3]);")
    c.append("")
    c.append("    (* Enforce Hard Box Saturation Limits [0%, 100%] *)")
    c.append("    IF rControl_Vector_u[1] < c_u1_Min THEN")
    c.append("        rControl_Vector_u[1] := c_u1_Min;")
    c.append("    ELSIF rControl_Vector_u[1] > c_u1_Max THEN")
    c.append("        rControl_Vector_u[1] := c_u1_Max;")
    c.append("    END_IF;")
    c.append("")
    c.append("    IF rControl_Vector_u[2] < c_u2_Min THEN")
    c.append("        rControl_Vector_u[2] := c_u2_Min;")
    c.append("    ELSIF rControl_Vector_u[2] > c_u2_Max THEN")
    c.append("        rControl_Vector_u[2] := c_u2_Max;")
    c.append("    END_IF;")
    c.append("")
    c.append("    IF rControl_Vector_u[3] < c_u3_Min THEN")
    c.append("        rControl_Vector_u[3] := c_u3_Min;")
    c.append("    ELSIF rControl_Vector_u[3] > c_u3_Max THEN")
    c.append("        rControl_Vector_u[3] := c_u3_Max;")
    c.append("    END_IF;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Physical Slew Rate Limiter Implementation *)")
    c.append("rDeltaU_Clamped := rControl_Vector_u[1] - rControl_Vector_u_prev[1];")
    c.append("IF rDeltaU_Clamped > (c_u1_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[1] := rControl_Vector_u_prev[1] + (c_u1_MaxRate * rCycleScanTime_Ts);")
    c.append("ELSIF rDeltaU_Clamped < -(c_u1_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[1] := rControl_Vector_u_prev[1] - (c_u1_MaxRate * rCycleScanTime_Ts);")
    c.append("END_IF;")
    c.append("")
    c.append("rDeltaU_Clamped := rControl_Vector_u[2] - rControl_Vector_u_prev[2];")
    c.append("IF rDeltaU_Clamped > (c_u2_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[2] := rControl_Vector_u_prev[2] + (c_u2_MaxRate * rCycleScanTime_Ts);")
    c.append("ELSIF rDeltaU_Clamped < -(c_u2_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[2] := rControl_Vector_u_prev[2] - (c_u2_MaxRate * rCycleScanTime_Ts);")
    c.append("END_IF;")
    c.append("")
    c.append("rDeltaU_Clamped := rControl_Vector_u[3] - rControl_Vector_u_prev[3];")
    c.append("IF rDeltaU_Clamped > (c_u3_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[3] := rControl_Vector_u_prev[3] + (c_u3_MaxRate * rCycleScanTime_Ts);")
    c.append("ELSIF rDeltaU_Clamped < -(c_u3_MaxRate * rCycleScanTime_Ts) THEN")
    c.append("    rControl_Vector_u[3] := rControl_Vector_u_prev[3] - (c_u3_MaxRate * rCycleScanTime_Ts);")
    c.append("END_IF;")
    c.append("")
    c.append("rControl_Vector_u_prev[1] := rControl_Vector_u[1];")
    c.append("rControl_Vector_u_prev[2] := rControl_Vector_u[2];")
    c.append("rControl_Vector_u_prev[3] := rControl_Vector_u[3];")
    c.append("")
    c.append("(* Assign MPC Optimized Control Actions to Actuators *)")
    c.append("rMainSteamValve_Cmd             := rControl_Vector_u[1];")
    c.append("rHydraulicProportionalValve_Cmd := rControl_Vector_u[2];")
    c.append("rCounterFlowPump_Speed          := rControl_Vector_u[3];")
    c.append("")

    # Phase 4: Cake Moisture Optimizer & Thermal Disinfection
    c.append("(* === PHASE 4: CAKE DEWATERING OPTIMIZER & THERMAL HYGIENE === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Monitors ram penetration velocity decay dz/dt and drainage flow to hold peak 40-bar      *)")
    c.append("(* consolidation. Computes cumulative EN 14065 / ISO 15883 A0 thermal disinfection.        *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("")
    c.append("(* 4.1 Ram Displacement Velocity Decay Computation *)")
    c.append("rRamDisplacementRate_mms := (rRamPosition_mm - rPrevRamPosition_mm) / rCycleScanTime_Ts;")
    c.append("rPrevRamPosition_mm := rRamPosition_mm;")
    c.append("")
    c.append("(* 4.2 Real-Time Cake Residual Moisture Estimation *)")
    c.append("IF rVoted_BatchIntakeWeight > 10.0 THEN")
    c.append("    rEstimatedCakeMoisture_Pct := ((rVoted_CakeDischargeWeight - rVoted_BatchIntakeWeight) / rVoted_BatchIntakeWeight) * 100.0;")
    c.append("    IF rEstimatedCakeMoisture_Pct < 35.0 THEN")
    c.append("        rEstimatedCakeMoisture_Pct := 35.0;")
    c.append("    END_IF;")
    c.append("ELSE")
    c.append("    rEstimatedCakeMoisture_Pct := 45.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* 4.3 Downstream Gas Dryer Savings Calculation *)")
    c.append("(* Benchmark: 50% moisture at 30-bar vs actual % at 40-bar *)")
    c.append("rDryerGasSavings_Pct := (50.0 - rEstimatedCakeMoisture_Pct) * 2.80;")
    c.append("IF rDryerGasSavings_Pct < 0.0 THEN")
    c.append("    rDryerGasSavings_Pct := 0.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* 4.4 EN 14065 / ISO 15883 A0 Thermal Lethality Integration *)")
    c.append("IF rVoted_MainWashTemp >= 80.0 THEN")
    c.append("    rThermalDisinfectionA0_Val := rThermalDisinfectionA0_Val + (EXP((rVoted_MainWashTemp - 80.0) / 4.3429) * rCycleScanTime_Ts);")
    c.append("END_IF;")
    c.append("")
    c.append("IF rThermalDisinfectionA0_Val >= 600.0 THEN")
    c.append("    bThermalDisinfectionSatisfied := TRUE;")
    c.append("ELSE")
    c.append("    bThermalDisinfectionSatisfied := FALSE;")
    c.append("END_IF;")
    c.append("")

    # Phase 5: Multi-Stage FSM
    c.append("(* === PHASE 5: MULTI-STAGE CASE FINITE STATE MACHINE === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Manages 13 sequential operational states: Intake weighing, counter-flow wash, steam      *)")
    c.append("(* disinfection, rinse neutralize, 360-deg top transfer arch, 40-bar dewater, & discharge. *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("CASE iActiveFSM_State OF")
    c.append("")
    c.append("    0: (* STATE 0: SYSTEM STANDBY & INTERLOCK VERIFICATION *)")
    c.append("        rMainSteamValve_Cmd             := 0.0;")
    c.append("        rCounterFlowPump_Speed          := 0.0;")
    c.append("        rHydraulicProportionalValve_Cmd := 0.0;")
    c.append("        bHydraulicPumpMain_Run          := FALSE;")
    c.append("        bHydraulicRamExtend             := FALSE;")
    c.append("        bHydraulicRamRetract            := FALSE;")
    c.append("        bTunnelDrumRock_Run             := FALSE;")
    c.append("        bTunnelDrumTransfer_Run         := FALSE;")
    c.append("        bShuttleConveyor_Run            := FALSE;")
    c.append("        rStateDwellTimer_Sec            := 0.0;")
    c.append("        rThermalDisinfectionA0_Val      := 0.0;")
    c.append("        IF bEnableSystem AND bMainSteamSupplyHeaderReady AND NOT bSystemTripMaster THEN")
    c.append("            iActiveFSM_State := 10; (* Proceed to Batch Intake Weighing *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    10: (* STATE 10: BATCH LOAD & DRY WEIGHBRIDGE INTEGRITY *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF bBatchLoadPermissive AND (rVoted_BatchIntakeWeight >= 45.0 AND rVoted_BatchIntakeWeight <= 75.0) THEN")
    c.append("            bBatchWeighedAndAccepted := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 20; (* Proceed to Pre-Wash Wetting *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    20: (* STATE 20: PRE-WASH COMPARTMENT WETTING & SOIL FLUSH *)")
    c.append("        bTunnelDrumRock_Run := TRUE; (* Rock drum 270 degrees *)")
    c.append("        rCounterFlowPump_Speed := 40.0;")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF rStateDwellTimer_Sec >= 30.0 THEN")
    c.append("            bPreWashCompleted := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 30; (* Proceed to Main Counter-Flow Wash *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    30: (* STATE 30: COUNTER-FLOW MAIN WASH & CHEMICAL DOSING *)")
    c.append("        bTunnelDrumRock_Run := TRUE;")
    c.append("        rCounterFlowPump_Speed := 85.0;")
    c.append("        bDetergentDosingPump_Run := TRUE;")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF rStateDwellTimer_Sec >= 60.0 THEN")
    c.append("            bDetergentDosingPump_Run := FALSE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 40; (* Proceed to Steam Disinfection Hold *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    40: (* STATE 40: STEAM INJECTION DISINFECTION HOLD (85 DEG C, A0 >= 600 S) *)")
    c.append("        bTunnelDrumRock_Run := TRUE;")
    c.append("        bBleachDosingPump_Run := TRUE; (* Peroxide injection *)")
    c.append("        (* Steam modulating valve driven by MPC *)")
    c.append("        rState_Setpoint_xref[1] := c_WashTemp_Disinfection_Target;")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF bThermalDisinfectionSatisfied AND (rStateDwellTimer_Sec >= 120.0) THEN")
    c.append("            bBleachDosingPump_Run := FALSE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 50; (* Proceed to Rinse & Neutralize *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    50: (* STATE 50: RINSE COMPARTMENT NEUTRALIZATION & SOUR DOSING *)")
    c.append("        bTunnelDrumRock_Run := TRUE;")
    c.append("        rCounterFlowPump_Speed := 100.0; (* Flush fresh water into rinse *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF rStateDwellTimer_Sec >= 60.0 THEN")
    c.append("            bTunnelWashCycleComplete := TRUE;")
    c.append("            bReadyForBatchTransfer := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 60; (* Proceed to 360-deg Top Transfer Arch *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    60: (* STATE 60: 360-DEGREE TOP-TRANSFER DRUM ARCH ROTATION *)")
    c.append("        bTunnelDrumRock_Run := FALSE;")
    c.append("        bTunnelDrumTransfer_Run := TRUE; (* Full 360 degree revolution moves batches forward *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF rStateDwellTimer_Sec >= 14.5 THEN")
    c.append("            bTunnelDrumTransfer_Run := FALSE;")
    c.append("            bTopTransferComplete := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 70; (* Proceed to Press Chamber Load *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    70: (* STATE 70: EXTRACTION PRESS BASKET TEXTILE CAKE LOADING *)")
    c.append("        bHydraulicPumpMain_Run := TRUE;")
    c.append("        bHydraulicRamExtend := FALSE;")
    c.append("        bHydraulicRamRetract := TRUE; (* Ensure ram is at top dead center *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF rStateDwellTimer_Sec >= 8.0 THEN")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 80; (* Proceed to Multi-Stage Hydraulic Dewatering *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    80: (* STATE 80: MULTI-STAGE HYDRAULIC EXTRACTION PRESS DEWATERING *)")
    c.append("        bHydraulicRamRetract := FALSE;")
    c.append("        bHydraulicRamExtend := TRUE;")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        rTotalPressDuration_Sec := rTotalPressDuration_Sec + rCycleScanTime_Ts;")
    c.append("        (* Stage 1: Soft Pre-Press (8 bar) *)")
    c.append("        IF rStateDwellTimer_Sec <= 15.0 THEN")
    c.append("            rPressStageTargetPressure := 8.0;")
    c.append("        (* Stage 2: Medium Compaction (22 bar) *)")
    c.append("        ELSIF rStateDwellTimer_Sec <= 35.0 THEN")
    c.append("            rPressStageTargetPressure := 22.0;")
    c.append("        (* Stage 3: High Dewatering (36 bar) *)")
    c.append("        ELSIF rStateDwellTimer_Sec <= 60.0 THEN")
    c.append("            rPressStageTargetPressure := 36.0;")
    c.append("        ELSE")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 90; (* Proceed to Peak 40-Bar Consolidation *)")
    c.append("        END_IF;")
    c.append("        rState_Setpoint_xref[4] := rPressStageTargetPressure;")
    c.append("")
    c.append("    90: (* STATE 90: PEAK 40-BAR HYDRAULIC CONSOLIDATION HOLD *)")
    c.append("        rPressStageTargetPressure := 40.0;")
    c.append("        rState_Setpoint_xref[4] := 40.0;")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        (* Hold until displacement decay dz/dt <= 0.12 mm/s and minimum dwell 20 s *)")
    c.append("        IF (rStateDwellTimer_Sec >= 20.0) AND (ABS(rRamDisplacementRate_mms) <= rConsolidationThreshold_mms) THEN")
    c.append("            bPressCakeDewateringFinished := TRUE;")
    c.append("            bExtractionCycleComplete := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 100; (* Proceed to Ram Decompression *)")
    c.append("        ELSIF rStateDwellTimer_Sec >= 65.0 THEN")
    c.append("            (* Maximum press dwell safety timeout *)")
    c.append("            bPressCakeDewateringFinished := TRUE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 100;")
    c.append("        END_IF;")
    c.append("")
    c.append("    100: (* STATE 100: RAM DECOMPRESSION & RETRACTION LIFT *)")
    c.append("        bHydraulicRamExtend := FALSE;")
    c.append("        bHydraulicRamRetract := TRUE; (* Lift ram head *)")
    c.append("        rHydraulicProportionalValve_Cmd := 0.0; (* Vent cap chamber *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF (rRamPosition_mm <= 50.0) OR (rStateDwellTimer_Sec >= 12.0) THEN")
    c.append("            bHydraulicRamRetract := FALSE;")
    c.append("            rStateDwellTimer_Sec := 0.0;")
    c.append("            iActiveFSM_State := 110; (* Proceed to Cake Discharge Shuttle *)")
    c.append("        END_IF;")
    c.append("")
    c.append("    110: (* STATE 110: CAKE DISCHARGE SHUTTLE CONVEYOR ADVANCE *)")
    c.append("        IF bDryerShuttleInPosition THEN")
    c.append("            bShuttleConveyor_Run := TRUE;")
    c.append("            rShuttleConveyor_Speed_mps := 0.65;")
    c.append("            rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("            IF rStateDwellTimer_Sec >= 8.5 THEN")
    c.append("                bShuttleConveyor_Run := FALSE;")
    c.append("                rShuttleConveyor_Speed_mps := 0.0;")
    c.append("                bCakeDischargedToShuttle := TRUE;")
    c.append("                iCurrentBatchID := iCurrentBatchID + 1;")
    c.append("                rStateDwellTimer_Sec := 0.0;")
    c.append("                iActiveFSM_State := 0; (* Cycle complete: return to Standby *)")
    c.append("            END_IF;")
