# -*- coding: utf-8 -*-
"""
Module: biw_mod_phase4_fsm.py
Generates PHASE 4: 12-Stage Operational Finite State Machine (FSM)
for FB_Automotive_BIW_GeoFraming_MultiRobotWelding.
States:
  10: SYSTEM_OFFLINE_SAFETY_ZONE_CLEAR
  20: SKID_CONVEYOR_TRANSFER_IN
  30: GEO_LIFTER_RAISE_LOCATING_PINS
  40: HYDRAULIC_PNEUMATIC_CLAMP_LOCK
  50: ROBOT_GEO_WELD_PERMIT_INTERLOCK
  60: SYNCHRONOUS_14ROBOT_WELD_CYCLE
  70: LASER_BRAZING_ROOF_SEAM
  80: CLAMP_UNLATCH_SEQUENCE_VERIFY
  90: GEO_LIFTER_LOWER_TO_CONVEYOR
  100: SKID_TRANSFER_OUT_RESPOT
  110: WELD_EXPULSION_QUALITY_ALARM_HOLD
  999: EMERGENCY_ESTOP_ROBOT_HALT
"""

def get_phase4_fsm() -> str:
    lines = [
        "(* =========================================================================================== *)",
        "(* === PHASE 4: 12-STAGE OPERATIONAL FINITE STATE MACHINE (FSM)                            === *)",
        "(* =========================================================================================== *)",
        "",
        "(* Master Safety Pre-emption Check: SIL-3 / Category 4 Immediate Emergency Abort *)",
        "IF (NOT bSafetyCircuitOK) OR bEmergencyTripLatched OR (NOT bMasterEnable) THEN",
        "    iFsmNextState := 999;",
        "END_IF;",
        "",
        "(* State Transition Dispatch & Elapsed Timer Management *)",
        "IF iFsmNextState <> iFsmState THEN",
        "    iFsmState := iFsmNextState;",
        "    rStateTimer_s := 0.0;",
        "    bStateEntryTrigger := TRUE;",
        "ELSE",
        "    rStateTimer_s := rStateTimer_s + rCycleTime_s;",
        "    bStateEntryTrigger := FALSE;",
        "END_IF;",
        "",
        "iCurrentState := iFsmState;",
        "",
        "CASE iFsmState OF",
        "    (* ======================================================================================= *)",
        "    (* STATE 10: SYSTEM OFFLINE & SAFETY PERIMETER ZONE CLEAR                                  *)",
        "    (* ======================================================================================= *)",
        "    10: (* SYSTEM_OFFLINE_SAFETY_ZONE_CLEAR *)",
        "        bStationInCycle := FALSE;",
        "        bCycleComplete := FALSE;",
        "        rTotalCycleTimer_s := 0.0;",
        "        rCurrentCycleElapsed_s := 0.0;",
        "        bLifterMotorRun := FALSE;",
        "        bConveyorMotorRun := FALSE;",
        "        bClampCylinderAdvanceCmd := FALSE;",
        "        bClampCylinderRetractCmd := TRUE; (* Keep tooling retracted in home resting state *)",
        "        bGateLockPinsEngageCmd := FALSE;",
        "        bPneumaticHeaderDumpValveCmd := FALSE;",
        "        bServoGunElectrodeCloseCmd := FALSE;",
        "        bMFDCWeldTimerEnableCmd := FALSE;",
        "        bLaserBrazingEnableCmd := FALSE;",
        "        wRobotWeldPermitWord := 16#0000; (* All robot motions inhibited *)",
        "        wRobotInterferenceZoneRelease := 16#0000;",
        "        bEmergencyHaltActive := FALSE;",
        "        ",
        "        (* Readiness Preconditions for Automatic Cycle Start *)",
        "        IF bMasterEnable AND bSafetyCircuitOK AND bLightCurtain_voted AND bClampRetract_voted AND",
        "           bAllRobotsHome AND (rClampPressure_voted_bar >= rPneumaticHeaderPressureMin_bar) AND",
        "           (rWaterFlow_voted_Lpm >= rCoolingWaterFlowMin_Lpm) AND (rTransTemp_voted_degC <= rTransformerTempMax_degC) THEN",
        "            ",
        "            IF bAutoCycleStart AND bSkidPresentAtEntry THEN",
        "                iFsmNextState := 20; (* Proceed to skid conveyor transfer in *)",
        "            END_IF;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 20: SKID CONVEYOR TRANSFER IN (PACED ROLLER FRICTION INGRESS)                     *)",
        "    (* ======================================================================================= *)",
        "    20: (* SKID_CONVEYOR_TRANSFER_IN *)",
        "        bStationInCycle := TRUE;",
        "        bCycleComplete := FALSE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        ",
        "        (* Run Paced Roller Skid Conveyor *)",
        "        bConveyorMotorRun := TRUE;",
        "        rConveyorSpeedCommand_mps := rConveyorSpeedSetpoint_mps;",
        "        bLifterMotorRun := FALSE;",
        "        bClampCylinderAdvanceCmd := FALSE;",
        "        bClampCylinderRetractCmd := TRUE;",
        "        wRobotWeldPermitWord := 16#0000;",
        "        ",
        "        rTransferInTimer_s := rStateTimer_s;",
        "        ",
        "        (* Skid Arrival at Geo-Framing Station Working Center *)",
        "        IF (rTransferInTimer_s > 1.20) AND (rConveyorVel_voted_mps < 0.08) THEN",
        "            bConveyorMotorRun := FALSE;",
        "            rConveyorSpeedCommand_mps := 0.0;",
        "            iFsmNextState := 30; (* Proceed to raise locating datum pins *)",
        "        ELSIF rTransferInTimer_s > 8.50 THEN",
        "            (* Conveyor Transfer In Ingress Timeout Trip *)",
        "            bConveyorMotorRun := FALSE;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 30: GEO-LIFTER RAISE LOCATING DATUM PINS (4-CORNER SYNCHRONOUS LIFT)              *)",
        "    (* ======================================================================================= *)",
        "    30: (* GEO_LIFTER_RAISE_LOCATING_PINS *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        bConveyorMotorRun := FALSE;",
        "        ",
        "        (* Command 4-Corner Geo-Lifter Table Ascend to Framing Working Height *)",
        "        bLifterMotorRun := TRUE;",
        "        bLifterMotorDirectionUp := TRUE;",
        "        ",
        "        rLifterRaiseTimer_s := rStateTimer_s;",
        "        ",
        "        (* Verify Lifter Height via 2oo3 Transducer Group *)",
        "        IF ABS(rLifterPos_voted_mm - rLifterTargetHeight_mm) <= 0.35 THEN",
        "            bLifterMotorRun := FALSE;",
        "            rLifterSpeedCommand_pct := 0.0;",
        "            iFsmNextState := 40; (* Proceed to side gate clamp lock *)",
        "        ELSIF rLifterRaiseTimer_s > 6.00 THEN",
        "            (* Lifter Ascend Timeout Trip *)",
        "            bLifterMotorRun := FALSE;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 40: HYDRAULIC & PNEUMATIC CLAMP LOCK (FRAMING SIDE GATES DOCKING)                 *)",
        "    (* ======================================================================================= *)",
        "    40: (* HYDRAULIC_PNEUMATIC_CLAMP_LOCK *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        bLifterMotorRun := FALSE;",
        "        ",
        "        (* Energize Side Gate Clamping Cylinders & NC Locating Wedge Pins *)",
        "        bClampCylinderRetractCmd := FALSE;",
        "        bClampCylinderAdvanceCmd := TRUE;",
        "        bGateLockPinsEngageCmd := TRUE;",
        "        ",
        "        rClampLockTimer_s := rStateTimer_s;",
        "        ",
        "        (* Verification of Advance Proximity Sensors and Pneumatic Line Pressure *)",
        "        IF bClampAdvance_voted AND (NOT bClampRetract_voted) AND",
        "           (rClampPressure_voted_bar >= rPneumaticHeaderPressureMin_bar) AND",
        "           (rClampLockTimer_s >= 0.350) THEN (* Allow 350 ms mechanical settling *)",
        "            ",
        "            (* Check Geometric Body Alignment Tolerance (< 0.05 mm structural spec) *)",
        "            IF rGeometricAlignmentError_mm <= 0.050 THEN",
        "                iFsmNextState := 50; (* Proceed to robot weld permit interlock *)",
        "            ELSIF rClampLockTimer_s > 4.50 THEN",
        "                (* Precision Framing Tolerance Exceeded *)",
        "                bClampDiscrepancyTripLatched := TRUE;",
        "                iFsmNextState := 999;",
        "            END_IF;",
        "        ELSIF rClampLockTimer_s > 5.00 THEN",
        "            (* Clamp Advance Timeout Trip *)",
        "            bClampDiscrepancyTripLatched := TRUE;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 50: ROBOT GEO-WELD PERMIT INTERLOCK & COLLISION ZONE CLEARANCE                     *)",
        "    (* ======================================================================================= *)",
        "    50: (* ROBOT_GEO_WELD_PERMIT_INTERLOCK *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        ",
        "        (* Cross-Check Water Cooling Flow & Transformer Overheat Protection *)",
        "        IF (rWaterFlow_voted_Lpm >= rCoolingWaterFlowMin_Lpm) AND (rTransTemp_voted_degC <= rTransformerTempMax_degC) AND",
        "           bClampAdvance_voted AND (rGeometricAlignmentError_mm <= 0.050) THEN",
        "            ",
        "            (* Issue Master Hardware Weld Permit Word to all 14 Industrial Manipulators *)",
        "            wRobotWeldPermitWord := 16#3FFF; (* Bits 0..13 Enabled *)",
        "            wRobotInterferenceZoneRelease := 16#3FFF;",
        "            ",
        "            IF rStateTimer_s >= 0.200 THEN",
        "                iFsmNextState := 60; (* Initiate synchronous 14-robot welding cycle *)",
        "            END_IF;",
        "        ELSE",
        "            wRobotWeldPermitWord := 16#0000;",
        "            IF rStateTimer_s > 3.00 THEN",
        "                bCoolingWaterTripLatched := TRUE;",
        "                iFsmNextState := 999;",
        "            END_IF;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 60: SYNCHRONOUS 14-ROBOT WELD CYCLE (MULTI-SPOT GEO-FRAMING)                      *)",
        "    (* ======================================================================================= *)",
        "    60: (* SYNCHRONOUS_14ROBOT_WELD_CYCLE *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        rRobotWeldCycleTimer_s := rStateTimer_s;",
        "        ",
        "        wRobotWeldPermitWord := 16#3FFF;",
        "        ",
        "        (* Safety Interlock: Monitor Cooling Water during Active Welding *)",
        "        IF rWaterFlow_voted_Lpm < 8.0 THEN",
        "            bCoolingWaterTripLatched := TRUE;",
        "            bMFDCWeldTimerEnableCmd := FALSE;",
        "            wRobotWeldPermitWord := 16#0000;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "        ",
        "        (* Check Completion of all Spot Welding Tasks *)",
        "        IF bAllSpotWeldsComplete THEN",
        "            bMFDCWeldTimerEnableCmd := FALSE;",
        "            bServoGunElectrodeCloseCmd := FALSE;",
        "            ",
        "            (* Check if Weld Expulsion Occurred during Spot Cycle *)",
        "            IF bExpulsionSpatterDetected THEN",
        "                bWeldingQualityPass := FALSE;",
        "            ELSE",
        "                bWeldingQualityPass := TRUE;",
        "            END_IF;",
        "            ",
        "            iFsmNextState := 70; (* Proceed to roof seam laser brazing *)",
        "        ELSIF rRobotWeldCycleTimer_s > 24.00 THEN",
        "            (* Spot Welding Cycle Timeout Trip *)",
        "            wRobotWeldPermitWord := 16#0000;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 70: CONTINUOUS ROOF SEAM LASER BRAZING (ROBOTS 09 & 10)                           *)",
        "    (* ======================================================================================= *)",
        "    70: (* LASER_BRAZING_ROOF_SEAM *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        rLaserBrazingTimer_s := rStateTimer_s;",
        "        ",
        "        (* Robots 09 and 10 Permissive Active *)",
        "        wRobotWeldPermitWord := 16#0300; (* Bits 8 and 9 Active *)",
        "        ",
        "        (* Verify Joint Tracking Gap Quality *)",
        "        IF ABS(rLaserGap_voted_mm) > 0.40 THEN",
        "            bLaserSeamQualityPass := FALSE;",
        "        ELSE",
        "            bLaserSeamQualityPass := TRUE;",
        "        END_IF;",
        "        ",
        "        (* Laser Seam Brazing Completion Evaluation *)",
        "        IF bLaserBrazingComplete OR (rLaserCurrentPosition_mm >= rLaserBrazingLength_mm) THEN",
        "            bLaserBrazingEnableCmd := FALSE;",
        "            rLaserPowerCommand_kW := 0.0;",
        "            rLaserWireFeedCommand_mpm := 0.0;",
        "            iFsmNextState := 80; (* Proceed to clamp unlatch sequence *)",
        "        ELSIF rLaserBrazingTimer_s > 14.00 THEN",
        "            (* Laser Brazing Cycle Timeout Trip *)",
        "            bLaserBrazingEnableCmd := FALSE;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 80: CLAMP UNLATCH SEQUENCE & CLEARANCE VERIFICATION                               *)",
        "    (* ======================================================================================= *)",
        "    80: (* CLAMP_UNLATCH_SEQUENCE_VERIFY *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        ",
        "        (* Inhibit Robot Motions during Gate Unlatching *)",
        "        wRobotWeldPermitWord := 16#0000;",
        "        ",
        "        (* Disengage Wedge Pins and Retract Side Gate Clamps *)",
        "        bGateLockPinsEngageCmd := FALSE;",
        "        bClampCylinderAdvanceCmd := FALSE;",
        "        bClampCylinderRetractCmd := TRUE;",
        "        ",
        "        rClampUnlatchTimer_s := rStateTimer_s;",
        "        ",
        "        (* Verify Clamps Fully Retracted via 2oo3 Transducers *)",
        "        IF bClampRetract_voted AND (NOT bClampAdvance_voted) AND (rClampUnlatchTimer_s >= 0.400) THEN",
        "            iFsmNextState := 90; (* Proceed to lower geo-lifter table *)",
        "        ELSIF rClampUnlatchTimer_s > 5.00 THEN",
        "            (* Clamp Retract Timeout Trip *)",
        "            bClampDiscrepancyTripLatched := TRUE;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 90: GEO-LIFTER LOWER TO CONVEYOR (RETURN TO CONVEYOR LINE)                         *)",
        "    (* ======================================================================================= *)",
        "    90: (* GEO_LIFTER_LOWER_TO_CONVEYOR *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        ",
        "        (* Command Geo-Lifter Table Descend to Conveyor Roller Bed Height (0.0 mm) *)",
        "        bLifterMotorRun := TRUE;",
        "        bLifterMotorDirectionUp := FALSE;",
        "        ",
        "        rLifterLowerTimer_s := rStateTimer_s;",
        "        ",
        "        IF rLifterPos_voted_mm <= (rLifterLowerHeight_mm + 0.50) THEN",
        "            bLifterMotorRun := FALSE;",
        "            rLifterSpeedCommand_pct := 0.0;",
        "            iFsmNextState := 100; (* Proceed to skid transfer out *)",
        "        ELSIF rLifterLowerTimer_s > 6.00 THEN",
        "            (* Lifter Descend Timeout Trip *)",
        "            bLifterMotorRun := FALSE;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 100: SKID TRANSFER OUT TO RESPOT LINE                                             *)",
        "    (* ======================================================================================= *)",
        "    100: (* SKID_TRANSFER_OUT_RESPOT *)",
        "        bStationInCycle := TRUE;",
        "        rTotalCycleTimer_s := rTotalCycleTimer_s + rCycleTime_s;",
        "        rCurrentCycleElapsed_s := rTotalCycleTimer_s;",
        "        ",
        "        (* Run Conveyor Outwards *)",
        "        bConveyorMotorRun := TRUE;",
        "        rConveyorSpeedCommand_mps := rConveyorSpeedSetpoint_mps;",
        "        ",
        "        rTransferOutTimer_s := rStateTimer_s;",
        "        ",
        "        (* Check Skid Egress Confirmation Photocell *)",
        "        IF (rTransferOutTimer_s > 2.00) AND bSkidPresentAtExit THEN",
        "            bConveyorMotorRun := FALSE;",
        "            rConveyorSpeedCommand_mps := 0.0;",
        "            bCycleComplete := TRUE; (* 45.0 s Total Station Cycle Completed Successfully *)",
        "            ",
        "            (* If Spatter Expulsion Occurred, Branch to Quality Alarm Quarantine *)",
        "            IF bExpulsionSpatterDetected THEN",
        "                iFsmNextState := 110;",
        "            ELSE",
        "                iFsmNextState := 10; (* Return to idle waiting for next body *)",
        "            END_IF;",
        "        ELSIF rTransferOutTimer_s > 9.00 THEN",
        "            bConveyorMotorRun := FALSE;",
        "            iFsmNextState := 999;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 110: WELD EXPULSION QUALITY ALARM HOLD (QUARANTINE INSPECTION)                     *)",
        "    (* ======================================================================================= *)",
        "    110: (* WELD_EXPULSION_QUALITY_ALARM_HOLD *)",
        "        bStationInCycle := FALSE;",
        "        bConveyorMotorRun := FALSE;",
        "        bLifterMotorRun := FALSE;",
        "        wRobotWeldPermitWord := 16#0000;",
        "        rExpulsionHoldTimer_s := rStateTimer_s;",
        "        ",
        "        (* Operator or QA Specialist Inspection Release *)",
        "        IF bAlarmReset THEN",
        "            bExpulsionSpatterDetected := FALSE;",
        "            iFsmNextState := 10;",
        "        END_IF;",
        "",
        "    (* ======================================================================================= *)",
        "    (* STATE 999: EMERGENCY ESTOP & ROBOT PERIMETER HALT (ISO 13849 PL e / SIL-3)             *)",
        "    (* ======================================================================================= *)",
        "    999: (* EMERGENCY_ESTOP_ROBOT_HALT *)",
        "        bStationInCycle := FALSE;",
        "        bEmergencyHaltActive := TRUE;",
        "        ",
        "        (* Immediate Actuator and Tooling De-Energization *)",
        "        bConveyorMotorRun := FALSE;",
        "        rConveyorSpeedCommand_mps := 0.0;",
        "        bLifterMotorRun := FALSE;",
        "        rLifterSpeedCommand_pct := 0.0;",
        "        bClampCylinderAdvanceCmd := FALSE;",
        "        bClampCylinderRetractCmd := FALSE;",
        "        bPneumaticHeaderDumpValveCmd := TRUE; (* Dump air header immediately *)",
        "        bServoGunElectrodeCloseCmd := FALSE;",
        "        bMFDCWeldTimerEnableCmd := FALSE;",
        "        rMFDCCurrentCommand_kA := 0.0;",
        "        bLaserBrazingEnableCmd := FALSE;",
        "        rLaserPowerCommand_kW := 0.0;",
        "        wRobotWeldPermitWord := 16#0000; (* Inhibit all 14 robots in < 5 ms *)",
        "        wRobotInterferenceZoneRelease := 16#0000;",
        "        ",
        "        (* Fault Reset Handshake *)",
        "        IF bAlarmReset AND bSafetyCircuitOK AND bLightCurtain_voted THEN",
        "            bEmergencyTripLatched := FALSE;",
        "            bCoolingWaterTripLatched := FALSE;",
        "            bClampDiscrepancyTripLatched := FALSE;",
        "            bSafetyZoneTripped := FALSE;",
        "            bPneumaticHeaderDumpValveCmd := FALSE;",
        "            iFsmNextState := 10;",
        "        END_IF;",
        "END_CASE;"
    ]
    return "\n".join(lines)
