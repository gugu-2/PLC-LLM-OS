    w("    FOR i := 1 TO 8 DO")
    w("        rTempAccum := 0.0;")
    w("        FOR j := 1 TO 8 DO")
    w("            IF k = 1 THEN")
    w("                rTempAccum := rTempAccum + (a_mat[i, j] * x_state[j]) + (b_mat[i, j] * u_ctrl[j]);")
    w("            ELSE")
    w("                rTempAccum := rTempAccum + (a_mat[i, j] * u_mpc_traj[k - 1, j]) + (b_mat[i, j] * u_ctrl[j]);")
    w("            END_IF;")
    w("        END_FOR;")
    w("        u_mpc_traj[k, i] := rTempAccum;")
