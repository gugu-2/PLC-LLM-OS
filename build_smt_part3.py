    w("        rZone_Int_Array[z] := 35.0;")
    w("    ELSIF rZone_Int_Array[z] < -20.0 THEN")
    w("        rZone_Int_Array[z] := -20.0;")
    w("    END_IF;")
    w("    rTempAccum := rTempAccum + rZone_Int_Array[z];")
    w("    ")
    w("    (* 4. Filtered Derivative Action *)")
    w("    rTempAccum := rTempAccum + (rZone_Kd[z] * (rZone_Err_Array[z] - rZone_Err_Prev[z]) / T_CYCLE_SEC);")
    w("    rZone_Err_Prev[z] := rZone_Err_Array[z];")
