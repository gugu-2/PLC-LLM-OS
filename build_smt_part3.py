    w("rTotalInfeedFeedforwardPower_pct := d_dist[1] * 3.85; (* Proportional feedforward power boost [%] *)")
    w("IF rTotalInfeedFeedforwardPower_pct > 15.0 THEN")
    w("    rTotalInfeedFeedforwardPower_pct := 15.0; (* Clamp feedforward ceiling *)")
    w("END_IF;")
    w("")
    w("FOR z := 1 TO 14 DO")
    w("    (* 1. Calculate Error *)")
    w("    rZone_Err_Array[z] := rZone_SP_Array[z] - rZone_PV_Array[z];")
    w("    ")
    w("    (* 2. Proportional Action *)")
    w("    rTempAccum := rZone_Kp[z] * rZone_Err_Array[z];")
    w("    ")
    w("    (* 3. Anti-Windup Integral Action *)")
