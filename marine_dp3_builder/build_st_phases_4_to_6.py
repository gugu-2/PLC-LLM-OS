# marine_dp3_builder/build_st_phases_4_to_6.py

def get_phases_4_to_6():
    lines = []
    def emit(s=""):
        lines.append(s)

    emit("(* ==================================================================================================================== *)")
    emit("(* PHASE 4: RECEDING-HORIZON MPC OPTIMIZATION WITH PROJECTED GRADIENT DESCENT (PGD)                                    *)")
    emit("(* ==================================================================================================================== *)")
    emit("(* 4.1 Unroll Prediction Horizon (Np = 5 steps) from Current State *)")
    emit("FOR j := 1 TO 8 DO")
    emit("    matX_traj[1, j] := vecX_state[j];")
    emit("END_FOR;")
    emit("")
    emit("FOR k := 1 TO 4 DO")
    emit("    FOR i := 1 TO 8 DO")
    emit("        rTempSum := 0.0;")
    emit("        FOR j := 1 TO 8 DO")
    emit("            rTempSum := rTempSum + matA[i, j] * matX_traj[k, j] + matB[i, j] * vecU_cmd[j];")
    emit("        END_FOR;")
    emit("        matX_traj[k + 1, i] := rTempSum;")
    emit("    END_FOR;")
    emit("END_FOR;")
    emit("")
    emit("(* 4.2 Projected Gradient Descent Iterative Loop (nPGD_MaxIter = 8) *)")
    emit("FOR p := 1 TO nPGD_MaxIter DO")
    emit("    (* Compute Gradient of Quadratic Functional J w.r.t Control Action u *)")
    emit("    FOR i := 1 TO 8 DO")
    emit("        (* Actuator Effort Penalty Gradient Term: 2 * R * u *)")
    emit("        vecGrad[i] := 2.0 * matR[i, i] * vecU_cmd[i];")
    emit("        (* Slew Rate Acceleration Penalty Gradient Term: 2 * S * (u - u_prev) *)")
    emit("        vecGrad[i] := vecGrad[i] + 2.0 * matS[i, i] * (vecU_cmd[i] - vecU_prev[i]);")
    emit("        (* State Tracking Cost Back-Propagation through Horizon *)")
    emit("        FOR k := 1 TO 5 DO")
    emit("            rTempSum := 0.0;")
    emit("            FOR j := 1 TO 8 DO")
    emit("                rTempSum := rTempSum + matB[j, i] * matQ[j, j] * (matX_traj[k, j] - vecX_setpoint[j]);")
    emit("            END_FOR;")
    emit("            vecGrad[i] := vecGrad[i] + 2.0 * rTempSum;")
    emit("        END_FOR;")
    emit("        (* Terminal State Stability Gradient Term *)")
    emit("        rTempSum := 0.0;")
    emit("        FOR j := 1 TO 8 DO")
    emit("            rTempSum := rTempSum + matB[j, i] * matP[j, j] * (matX_traj[5, j] - vecX_setpoint[j]);")
    emit("        END_FOR;")
    emit("        vecGrad[i] := vecGrad[i] + 2.0 * rTempSum;")
    emit("    END_FOR;")
    emit("")
    emit("    (* PGD Step Update with Learning Rate rMPC_StepSize *)")
    emit("    FOR i := 1 TO 8 DO")
    emit("        vecU_cmd[i] := vecU_cmd[i] - rMPC_StepSize * vecGrad[i];")
    emit("    END_FOR;")
    emit("")
    emit("    (* Projection onto Physical Actuator Box Saturation Constraints *)")
    emit("    vecU_cmd[1] := LIMIT(-1500.0, vecU_cmd[1], 1500.0); (* Surge Force Fx [-1500..+1500 kN] *)")
    emit("    vecU_cmd[2] := LIMIT(-1500.0, vecU_cmd[2], 1500.0); (* Sway Force Fy [-1500..+1500 kN] *)")
    emit("    vecU_cmd[3] := LIMIT(-45000.0, vecU_cmd[3], 45000.0); (* Yaw Moment Mz [-45000..+45000 kNm] *)")
    emit("    vecU_cmd[4] := LIMIT(-1500.0, vecU_cmd[4], 1500.0); (* Anti-Heel Pump Flow [-1500..+1500 m3/h] *)")
    emit("    vecU_cmd[5] := LIMIT(-1500.0, vecU_cmd[5], 1500.0); (* Anti-Trim Pump Flow [-1500..+1500 m3/h] *)")
    emit("    vecU_cmd[6] := LIMIT(0.0, vecU_cmd[6], 40.0);       (* Thruster Internal Bias Load [0..40 %] *)")
    emit("    vecU_cmd[7] := LIMIT(0.0, vecU_cmd[7], 48000.0);    (* PMS Max Power Cap [0..48000 kW] *)")
    emit("    vecU_cmd[8] := LIMIT(-25000.0, vecU_cmd[8], 25000.0); (* Active Roll Damping Moment [-25000..+25000 kNm] *)")
    emit("END_FOR;")
    emit("")
    emit("(* 4.3 Dynamic Slew Rate Limiters on Generalized Force Commands (Ts = 0.025 s) *)")
    emit("vecU_cmd[1] := LIMIT(vecU_prev[1] - 45.0 * 0.025, vecU_cmd[1], vecU_prev[1] + 45.0 * 0.025);")
    emit("vecU_cmd[2] := LIMIT(vecU_prev[2] - 45.0 * 0.025, vecU_cmd[2], vecU_prev[2] + 45.0 * 0.025);")
    emit("vecU_cmd[3] := LIMIT(vecU_prev[3] - 1200.0 * 0.025, vecU_cmd[3], vecU_prev[3] + 1200.0 * 0.025);")
    emit("vecU_cmd[4] := LIMIT(vecU_prev[4] - 250.0 * 0.025, vecU_cmd[4], vecU_prev[4] + 250.0 * 0.025);")
    emit("vecU_cmd[5] := LIMIT(vecU_prev[5] - 250.0 * 0.025, vecU_cmd[5], vecU_prev[5] + 250.0 * 0.025);")
    emit("")
    emit("(* ==================================================================================================================== *)")
    emit("(* PHASE 5: 8-AZIMUTH THRUSTER HYDRODYNAMIC ALLOCATION & FORBIDDEN ZONE BARRING                                         *)")
    emit("(* ==================================================================================================================== *)")
    emit("(* 5.1 Aerodynamic Wind Feedforward Pre-Compensation *)")
    emit("rRelWindAngle_rad := (rWind_VotedDir_deg) * 3.14159265 / 180.0;")
    emit("rWindForceSurge_kN := 0.5 * 1.225 * 0.85 * 850.0 * EXPT(rWind_VotedSpeed_mps, 2) * COS(rRelWindAngle_rad) / 1000.0;")
    emit("rWindForceSway_kN := 0.5 * 1.225 * 0.95 * 1250.0 * EXPT(rWind_VotedSpeed_mps, 2) * SIN(rRelWindAngle_rad) / 1000.0;")
    emit("rWindMomentYaw_kNm := 0.5 * 1.225 * 0.15 * 1250.0 * 115.0 * EXPT(rWind_VotedSpeed_mps, 2) * SIN(2.0 * rRelWindAngle_rad) / 1000.0;")
    emit("")
    emit("(* Net Generalized Forces including MPC commands, Feedforward, and Power Derating *)")
    emit("rDemandFx := (vecU_cmd[1] + rWindForceSurge_kN) * rPMS_CurtailmentRatio;")
    emit("rDemandFy := (vecU_cmd[2] + rWindForceSway_kN) * rPMS_CurtailmentRatio;")
    emit("rDemandMz := (vecU_cmd[3] + rWindMomentYaw_kNm) * rPMS_CurtailmentRatio;")
    emit("")
    emit("(* 5.2 Geometric Allocation across 8 Azimuth Thrusters *)")
    emit("(* Equal thrust share baseline + Rotational moment distribution *)")
    emit("(* Sum of squared radii: 4*(42^2 + 26^2) + 4*(18^2 + 31^2) = 4*(1764+676) + 4*(324+961) = 9760 + 5140 = 14900 m2 *)")
    emit("")
    for i in range(1, 9):
        emit(f"(* --- Thruster {i} Allocation --- *)")
        emit(f"rTemp1 := (rDemandFx / 8.0) - (rThruster_Y_pos[{i}] / 14900.0) * rDemandMz;")
        emit(f"rTemp2 := (rDemandFy / 8.0) + (rThruster_X_pos[{i}] / 14900.0) * rDemandMz;")
        emit("")
        emit(f"(* Inject Counter-Biasing to eliminate zero-thrust hunt and gear backlash *)")
        emit(f"IF bThrusterBiasRequest THEN")
        # Alternate bias sign for opposing pairs
        bias_sign = "+1.0" if i in [1, 4, 5, 8] else "-1.0"
        emit(f"    rTemp2 := rTemp2 + ({bias_sign}) * (vecU_cmd[6] * 6.50);")
        emit(f"END_IF;")
        emit("")
        emit(f"(* Compute Raw Magnitude and Angle *)")
        emit(f"rTemp3 := SQRT(EXPT(rTemp1, 2) + EXPT(rTemp2, 2));")
        emit(f"IF rTemp3 > 0.01 THEN")
        emit(f"    rAngleDelta := ATAN2(rTemp2, rTemp1) * 180.0 / 3.14159265;")
        emit(f"    IF rAngleDelta < 0.0 THEN rAngleDelta := rAngleDelta + 360.0; END_IF;")
        emit(f"ELSE")
        emit(f"    rAngleDelta := rThruster_PrevAzimuth_deg[{i}];")
        emit(f"END_IF;")
        emit("")
        emit(f"(* Azimuth Shortest Path Optimization: 180-deg reverse thrust vs steering slew *)")
        emit(f"rShortestAngle := rAngleDelta - rThruster_PrevAzimuth_deg[{i}];")
        emit(f"IF rShortestAngle > 180.0 THEN rShortestAngle := rShortestAngle - 360.0; END_IF;")
        emit(f"IF rShortestAngle < -180.0 THEN rShortestAngle := rShortestAngle + 360.0; END_IF;")
        emit("")
        emit(f"(* Clamp Steering Azimuth Slew Rate (max 16.0 deg/s * 0.025 s = 0.40 deg/step) *)")
        emit(f"rShortestAngle := LIMIT(-16.0 * 0.025, rShortestAngle, 16.0 * 0.025);")
        emit(f"rThruster_AllocAzimuth_deg[{i}] := rThruster_PrevAzimuth_deg[{i}] + rShortestAngle;")
        emit(f"IF rThruster_AllocAzimuth_deg[{i}] >= 360.0 THEN rThruster_AllocAzimuth_deg[{i}] := rThruster_AllocAzimuth_deg[{i}] - 360.0; END_IF;")
        emit(f"IF rThruster_AllocAzimuth_deg[{i}] < 0.0 THEN rThruster_AllocAzimuth_deg[{i}] := rThruster_AllocAzimuth_deg[{i}] + 360.0; END_IF;")
        emit("")
        emit(f"(* Forbidden Azimuth Barring Check for Thruster {i} *)")
        emit(f"IF (rThruster_AllocAzimuth_deg[{i}] >= rBarredMin_deg[{i}, 1] AND rThruster_AllocAzimuth_deg[{i}] <= rBarredMax_deg[{i}, 1]) THEN")
        emit(f"    bBarredActive[{i}] := TRUE;")
        emit(f"    IF ABS(rThruster_AllocAzimuth_deg[{i}] - rBarredMin_deg[{i}, 1]) < ABS(rThruster_AllocAzimuth_deg[{i}] - rBarredMax_deg[{i}, 1]) THEN")
        emit(f"        rThruster_AllocAzimuth_deg[{i}] := rBarredMin_deg[{i}, 1] - 2.0;")
        emit(f"    ELSE")
        emit(f"        rThruster_AllocAzimuth_deg[{i}] := rBarredMax_deg[{i}, 1] + 2.0;")
        emit(f"    END_IF;")
        emit(f"ELSIF (rThruster_AllocAzimuth_deg[{i}] >= rBarredMin_deg[{i}, 2] AND rThruster_AllocAzimuth_deg[{i}] <= rBarredMax_deg[{i}, 2]) THEN")
        emit(f"    bBarredActive[{i}] := TRUE;")
        emit(f"    IF ABS(rThruster_AllocAzimuth_deg[{i}] - rBarredMin_deg[{i}, 2]) < ABS(rThruster_AllocAzimuth_deg[{i}] - rBarredMax_deg[{i}, 2]) THEN")
        emit(f"        rThruster_AllocAzimuth_deg[{i}] := rBarredMin_deg[{i}, 2] - 2.0;")
        emit(f"    ELSE")
        emit(f"        rThruster_AllocAzimuth_deg[{i}] := rBarredMax_deg[{i}, 2] + 2.0;")
        emit(f"    END_IF;")
        emit(f"ELSE")
        emit(f"    bBarredActive[{i}] := FALSE;")
        emit(f"END_IF;")
        emit("")
        emit(f"(* Clamp Thrust Ramp Rate (max 25.0 kN/s * 0.025 s = 0.625 kN/step) and Bollard Pull *)")
        emit(f"rTemp3 := LIMIT(rThruster_PrevThrust_kN[{i}] - 25.0 * 0.025, rTemp3, rThruster_PrevThrust_kN[{i}] + 25.0 * 0.025);")
        emit(f"rThruster_AllocThrust_kN[{i}] := LIMIT(rThruster_MinThrust_kN[{i}], rTemp3, rThruster_MaxThrust_kN[{i}]);")
        emit("")
        emit(f"(* Update Prior States for Thruster {i} *)")
        emit(f"rThruster_PrevAzimuth_deg[{i}] := rThruster_AllocAzimuth_deg[{i}];")
        emit(f"rThruster_PrevThrust_kN[{i}] := rThruster_AllocThrust_kN[{i}];")
        emit(f"rThruster_CmdThrust_kN_T{i} := rThruster_AllocThrust_kN[{i}];")
        emit(f"rThruster_CmdAzimuth_deg_T{i} := rThruster_AllocAzimuth_deg[{i}];")
        emit(f"bThruster_Enable_T{i} := bMasterDP3Engage AND bThruster_Ready_T{i} AND NOT bThruster_Fault_T{i};")
        emit("")

    emit("(* 5.3 Quadratic Thruster-Thruster Wake Interaction Loss Modeling *)")
    emit("(* Check wake shadow: T1->T3, T2->T4, T3->T5, T4->T6, T5->T7, T6->T8 *)")
    emit("IF (rThruster_AllocAzimuth_deg[1] > 170.0 AND rThruster_AllocAzimuth_deg[1] < 190.0) THEN")
    emit("    rThruster_LossCoeff[3] := 1.0 - 0.28 * EXPT(rThruster_AllocThrust_kN[1] / 650.0, 2);")
    emit("ELSE")
    emit("    rThruster_LossCoeff[3] := 1.00;")
    emit("END_IF;")
    emit("IF (rThruster_AllocAzimuth_deg[2] > 170.0 AND rThruster_AllocAzimuth_deg[2] < 190.0) THEN")
    emit("    rThruster_LossCoeff[4] := 1.0 - 0.28 * EXPT(rThruster_AllocThrust_kN[2] / 650.0, 2);")
    emit("ELSE")
    emit("    rThruster_LossCoeff[4] := 1.00;")
    emit("END_IF;")
    emit("IF (rThruster_AllocAzimuth_deg[3] > 170.0 AND rThruster_AllocAzimuth_deg[3] < 190.0) THEN")
    emit("    rThruster_LossCoeff[5] := 1.0 - 0.28 * EXPT(rThruster_AllocThrust_kN[3] / 650.0, 2);")
    emit("ELSE")
    emit("    rThruster_LossCoeff[5] := 1.00;")
    emit("END_IF;")
    emit("IF (rThruster_AllocAzimuth_deg[4] > 170.0 AND rThruster_AllocAzimuth_deg[4] < 190.0) THEN")
    emit("    rThruster_LossCoeff[6] := 1.0 - 0.28 * EXPT(rThruster_AllocThrust_kN[4] / 650.0, 2);")
    emit("ELSE")
    emit("    rThruster_LossCoeff[6] := 1.00;")
    emit("END_IF;")
    emit("IF (rThruster_AllocAzimuth_deg[5] > 170.0 AND rThruster_AllocAzimuth_deg[5] < 190.0) THEN")
    emit("    rThruster_LossCoeff[7] := 1.0 - 0.28 * EXPT(rThruster_AllocThrust_kN[5] / 650.0, 2);")
    emit("ELSE")
    emit("    rThruster_LossCoeff[7] := 1.00;")
    emit("END_IF;")
    emit("IF (rThruster_AllocAzimuth_deg[6] > 170.0 AND rThruster_AllocAzimuth_deg[6] < 190.0) THEN")
    emit("    rThruster_LossCoeff[8] := 1.0 - 0.28 * EXPT(rThruster_AllocThrust_kN[6] / 650.0, 2);")
    emit("ELSE")
    emit("    rThruster_LossCoeff[8] := 1.00;")
    emit("END_IF;")
    emit("")
    emit("(* 5.4 Compute Summed Allocated Metrics *)")
    emit("rTotalAllocatedThrust_kN := 0.0;")
    emit("rTotalElectricalLoad_kW := 0.0;")
    emit("FOR i := 1 TO 8 DO")
    emit("    rTotalAllocatedThrust_kN := rTotalAllocatedThrust_kN + rThruster_AllocThrust_kN[i] * rThruster_LossCoeff[i];")
    emit("    rTotalElectricalLoad_kW := rTotalElectricalLoad_kW + EXPT(rThruster_AllocThrust_kN[i], 1.5) * 0.218;")
    emit("END_FOR;")
    emit("")
    emit("(* ==================================================================================================================== *)")
    emit("(* PHASE 6: ACTIVE HYDRAULIC ANTI-HEELING & ANTI-TRIM BALLAST HIGH-SPEED TRANSFER                                      *)")
    emit("(* ==================================================================================================================== *)")
    emit("(* 6.1 Cyber-Physical Moment Equilibrium Balance *)")
    emit("(* Thrusters are mounted 12.5 m below waterline; vessel center of gravity is 8.0 m above keel *)")
    emit("(* Effective roll overturning lever arm = 9.5 m; pitch overturning lever arm = 9.5 m *)")
    emit("rHeelingMomentResidual_kNm := 0.0;")
    emit("rTrimMomentResidual_kNm := 0.0;")
    emit("FOR i := 1 TO 8 DO")
    emit("    rHeelingMomentResidual_kNm := rHeelingMomentResidual_kNm + (rThruster_AllocThrust_kN[i] * SIN(rThruster_AllocAzimuth_deg[i] * 3.14159265 / 180.0)) * 9.50;")
    emit("    rTrimMomentResidual_kNm := rTrimMomentResidual_kNm - (rThruster_AllocThrust_kN[i] * COS(rThruster_AllocAzimuth_deg[i] * 3.14159265 / 180.0)) * 9.50;")
    emit("END_FOR;")
    emit("")
    emit("(* Add Hydrostatic Restoring Stiffness Moments *)")
    emit("(* M_heel_hydro = Displacement * g * GM_T * sin(Roll) *)")
    emit("rHeelingMomentResidual_kNm := rHeelingMomentResidual_kNm + (rVessel_Displacement_kg * 9.81 / 1000.0) * rVessel_GMT_m * SIN(vecX_state[7] * 3.14159265 / 180.0);")
    emit("(* M_trim_hydro = Displacement * g * GM_L * sin(Pitch) *)")
    emit("rTrimMomentResidual_kNm := rTrimMomentResidual_kNm + (rVessel_Displacement_kg * 9.81 / 1000.0) * rVessel_GML_m * SIN(vecX_state[8] * 3.14159265 / 180.0);")
    emit("")
    emit("(* 6.2 Closed-Loop Pump Command Synthesis *)")
    emit("IF bAntiHeelActiveRequest THEN")
    emit("    (* Distribute Counter-Heel Demand across Pump 1 (Fwd) and Pump 2 (Aft) *)")
    emit("    rHeelDemand_Moment_kNm := -rHeelingMomentResidual_kNm + vecU_cmd[4] * 25.0;")
    emit("    rTemp1 := rHeelDemand_Moment_kNm / (2.0 * 1025.0 * 9.81 / 1000.0 * 28.0); (* Flow in m3/s *)")
    emit("    rTemp1 := LIMIT(-rBallast_MaxPumpFlow_m3h, rTemp1 * 3600.0, rBallast_MaxPumpFlow_m3h);")
    emit("    rPumpCmd_FlowRate_P1_m3h := ABS(rTemp1);")
    emit("    rPumpCmd_FlowRate_P2_m3h := ABS(rTemp1);")
    emit("    bPumpCmd_RunForward_P1 := (rTemp1 > 10.0);")
    emit("    bPumpCmd_RunReverse_P1 := (rTemp1 < -10.0);")
    emit("    bPumpCmd_RunForward_P2 := (rTemp1 > 10.0);")
    emit("    bPumpCmd_RunReverse_P2 := (rTemp1 < -10.0);")
    emit("    (* Actuate Wing Isolation Valves *)")
    emit("    IF ABS(rTemp1) > 10.0 THEN")
    emit("        rValveCmd_OpenPct_V1 := 100.0; rValveCmd_OpenPct_V2 := 100.0;")
    emit("        rValveCmd_OpenPct_V7 := 100.0; rValveCmd_OpenPct_V8 := 100.0;")
    emit("    ELSE")
    emit("        rValveCmd_OpenPct_V1 := 0.0; rValveCmd_OpenPct_V2 := 0.0;")
    emit("        rValveCmd_OpenPct_V7 := 0.0; rValveCmd_OpenPct_V8 := 0.0;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rPumpCmd_FlowRate_P1_m3h := 0.0;")
    emit("    rPumpCmd_FlowRate_P2_m3h := 0.0;")
    emit("    bPumpCmd_RunForward_P1 := FALSE;")
    emit("    bPumpCmd_RunReverse_P1 := FALSE;")
    emit("    bPumpCmd_RunForward_P2 := FALSE;")
    emit("    bPumpCmd_RunReverse_P2 := FALSE;")
    emit("END_IF;")
    emit("")
    emit("IF bAntiTrimActiveRequest THEN")
    emit("    (* Distribute Counter-Trim Demand across Pump 3 (Port) and Pump 4 (Stbd) *)")
    emit("    rTrimDemand_Moment_kNm := -rTrimMomentResidual_kNm + vecU_cmd[5] * 25.0;")
    emit("    rTemp2 := rTrimDemand_Moment_kNm / (2.0 * 1025.0 * 9.81 / 1000.0 * 38.0); (* Flow in m3/s *)")
    emit("    rTemp2 := LIMIT(-rBallast_MaxPumpFlow_m3h, rTemp2 * 3600.0, rBallast_MaxPumpFlow_m3h);")
    emit("    rPumpCmd_FlowRate_P3_m3h := ABS(rTemp2);")
    emit("    rPumpCmd_FlowRate_P4_m3h := ABS(rTemp2);")
    emit("    bPumpCmd_RunForward_P3 := (rTemp2 > 10.0);")
    emit("    bPumpCmd_RunReverse_P3 := (rTemp2 < -10.0);")
    emit("    bPumpCmd_RunForward_P4 := (rTemp2 > 10.0);")
    emit("    bPumpCmd_RunReverse_P4 := (rTemp2 < -10.0);")
    emit("    IF ABS(rTemp2) > 10.0 THEN")
    emit("        rValveCmd_OpenPct_V3 := 100.0; rValveCmd_OpenPct_V4 := 100.0;")
    emit("        rValveCmd_OpenPct_V5 := 100.0; rValveCmd_OpenPct_V6 := 100.0;")
    emit("    ELSE")
    emit("        rValveCmd_OpenPct_V3 := 0.0; rValveCmd_OpenPct_V4 := 0.0;")
    emit("        rValveCmd_OpenPct_V5 := 0.0; rValveCmd_OpenPct_V6 := 0.0;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rPumpCmd_FlowRate_P3_m3h := 0.0;")
    emit("    rPumpCmd_FlowRate_P4_m3h := 0.0;")
    emit("    bPumpCmd_RunForward_P3 := FALSE;")
    emit("    bPumpCmd_RunReverse_P3 := FALSE;")
    emit("    bPumpCmd_RunForward_P4 := FALSE;")
    emit("    bPumpCmd_RunReverse_P4 := FALSE;")
    emit("END_IF;")
    return "\n".join(lines)

