    c.append("    bAllBlowersHealthy            : BOOL := TRUE;")
    c.append("    nFreeSlotIdx                  : INT := 0;")
    c.append("END_VAR\n")
    
    # Logic sections
    c.append("(* ============================================================================================= *)")
    c.append("(* PHASE 1: SIGNAL CONDITIONING, CONVEYOR KINEMATICS & DUAL ENCODER SLIPPAGE ANALYSIS           *)")
    c.append("(* ============================================================================================= *)")
    c.append("(* 1. Pin-chain and wire mesh belt incremental displacement calculation *)")
    c.append("rDeltaDistA := rConveyorEncoderPulseA - rEncoderA_Prev;")
    c.append("rDeltaDistB := rConveyorEncoderPulseB - rEncoderB_Prev;")
    c.append("rEncoderA_Prev := rConveyorEncoderPulseA;")
    c.append("rEncoderB_Prev := rConveyorEncoderPulseB;")
    c.append("")
    c.append("(* Bound negative pulse rollover if encoder wrap-around occurs *)")
    c.append("IF rDeltaDistA < 0.0 THEN")
    c.append("    rDeltaDistA := 0.0;")
    c.append("END_IF;")
    c.append("IF rDeltaDistB < 0.0 THEN")
    c.append("    rDeltaDistB := 0.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* Instantaneous velocity conversion from mm per cycle to m/min *)")
    c.append("rSpeedRaw := (rDeltaDistA / dt) * (60.0 / 1000.0);")
    c.append("")
    c.append("(* First-order digital low-pass filtering: Tau = 0.5 s, alpha = 0.166 *)")
    c.append("rSpeedFiltered := (0.834 * rSpeedFiltered) + (0.166 * rSpeedRaw);")
    c.append("rActualConveyorSpeed := rSpeedFiltered;")
    c.append("")
    c.append("(* Mechanical slippage / skew evaluation between pin chain and secondary mesh belt *)")
    c.append("rTempDiff := ABS(rDeltaDistA - rDeltaDistB);")
    c.append("IF rDeltaDistA > 0.05 THEN")
    c.append("    rConveyorSlipRatio := (rTempDiff / rDeltaDistA) * 100.0;")
    c.append("ELSE")
    c.append("    rConveyorSlipRatio := 0.0;")
    c.append("END_IF;")
    c.append("")
    c.append("IF rConveyorSlipRatio > 15.0 THEN")
    c.append("    rSlipAccumulator := rSlipAccumulator + dt;")
    c.append("    IF rSlipAccumulator > 2.5 THEN")
    c.append("        bConveyorSlipTrip := TRUE;")
    c.append("    END_IF;")
    c.append("ELSE")
    c.append("    rSlipAccumulator := MAX(0.0, rSlipAccumulator - (dt * 0.5));")
    c.append("    bConveyorSlipTrip := FALSE;")
    c.append("END_IF;\n")
    
    # Phase 2: 2oo3 TMR Sensor Voting
    c.append("(* ============================================================================================= *)")
    c.append("(* PHASE 2: 2oo3 TRIPLE MODULAR REDUNDANCY (TMR) VOTING & SENSOR HEALTH DEGRADATION             *)")
    c.append("(* ============================================================================================= *)")
    c.append("(* Triplicated Thermocouple Voting across all 12 forced-convection zones *)")
    c.append("FOR i := 1 TO 12 DO")
    c.append("    (* Range validation: Plausibility bounds 0.0 deg C to 320.0 deg C *)")
    c.append("    aTC_ChannelHealth[i, 1] := (aRawTC_ZoneA[i] >= 0.0) AND (aRawTC_ZoneA[i] <= 320.0);")
    c.append("    aTC_ChannelHealth[i, 2] := (aRawTC_ZoneB[i] >= 0.0) AND (aRawTC_ZoneB[i] <= 320.0);")
    c.append("    aTC_ChannelHealth[i, 3] := (aRawTC_ZoneC[i] >= 0.0) AND (aRawTC_ZoneC[i] <= 320.0);")
    c.append("    ")
    c.append("    (* Full 2oo3 voting when all 3 channels are healthy *)")
    c.append("    IF aTC_ChannelHealth[i, 1] AND aTC_ChannelHealth[i, 2] AND aTC_ChannelHealth[i, 3] THEN")
    c.append("        aTC_HealthMode[i] := 3; (* 2oo3 Mode *)")
    c.append("        ")
    c.append("        (* Compute median across A, B, and C *)")
    c.append("        IF (aRawTC_ZoneA[i] >= aRawTC_ZoneB[i] AND aRawTC_ZoneA[i] <= aRawTC_ZoneC[i]) OR")
    c.append("           (aRawTC_ZoneA[i] >= aRawTC_ZoneC[i] AND aRawTC_ZoneA[i] <= aRawTC_ZoneB[i]) THEN")
    c.append("            aVotedTC[i] := aRawTC_ZoneA[i];")
    c.append("        ELSIF (aRawTC_ZoneB[i] >= aRawTC_ZoneA[i] AND aRawTC_ZoneB[i] <= aRawTC_ZoneC[i]) OR")
    c.append("              (aRawTC_ZoneB[i] >= aRawTC_ZoneC[i] AND aRawTC_ZoneB[i] <= aRawTC_ZoneA[i]) THEN")
    c.append("            aVotedTC[i] := aRawTC_ZoneB[i];")
    c.append("        ELSE")
    c.append("            aVotedTC[i] := aRawTC_ZoneC[i];")
    c.append("        END_IF;")
    c.append("        ")
    c.append("        (* Cross-channel discrepancy monitoring (tolerance = 3.5 deg C) *)")
    c.append("        IF (ABS(aRawTC_ZoneA[i] - aRawTC_ZoneB[i]) > 3.5) OR")
    c.append("           (ABS(aRawTC_ZoneB[i] - aRawTC_ZoneC[i]) > 3.5) OR")
    c.append("           (ABS(aRawTC_ZoneA[i] - aRawTC_ZoneC[i]) > 3.5) THEN")
    c.append("            aTC_DiscrepTimer[i] := aTC_DiscrepTimer[i] + dt;")
    c.append("            IF aTC_DiscrepTimer[i] > 1.5 THEN")
    c.append("                aTC_DiscrepAlarm[i] := TRUE;")
    c.append("            END_IF;")
    c.append("        ELSE")
    c.append("            aTC_DiscrepTimer[i] := MAX(0.0, aTC_DiscrepTimer[i] - dt);")
    c.append("            aTC_DiscrepAlarm[i] := FALSE;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* Degraded 1oo2 mode with 2 healthy channels *)")
    c.append("    ELSIF aTC_ChannelHealth[i, 1] AND aTC_ChannelHealth[i, 2] THEN")
    c.append("        aTC_HealthMode[i] := 2;")
    c.append("        aVotedTC[i] := (aRawTC_ZoneA[i] + aRawTC_ZoneB[i]) * 0.5;")
    c.append("    ELSIF aTC_ChannelHealth[i, 2] AND aTC_ChannelHealth[i, 3] THEN")
    c.append("        aTC_HealthMode[i] := 2;")
    c.append("        aVotedTC[i] := (aRawTC_ZoneB[i] + aRawTC_ZoneC[i]) * 0.5;")
    c.append("    ELSIF aTC_ChannelHealth[i, 1] AND aTC_ChannelHealth[i, 3] THEN")
    c.append("        aTC_HealthMode[i] := 2;")
    c.append("        aVotedTC[i] := (aRawTC_ZoneA[i] + aRawTC_ZoneC[i]) * 0.5;")
    c.append("        ")
    c.append("    (* Critical 1oo1 fallback mode with single surviving channel *)")
    c.append("    ELSIF aTC_ChannelHealth[i, 1] THEN")
    c.append("        aTC_HealthMode[i] := 1;")
    c.append("        aVotedTC[i] := aRawTC_ZoneA[i];")
    c.append("    ELSIF aTC_ChannelHealth[i, 2] THEN")
    c.append("        aTC_HealthMode[i] := 1;")
    c.append("        aVotedTC[i] := aRawTC_ZoneB[i];")
    c.append("    ELSIF aTC_ChannelHealth[i, 3] THEN")
    c.append("        aTC_HealthMode[i] := 1;")
    c.append("        aVotedTC[i] := aRawTC_ZoneC[i];")
    c.append("    ELSE")
    c.append("        (* Complete sensor failure trip *)")
    c.append("        aTC_HealthMode[i] := 0;")
    c.append("        bSafetyFaultTripped := TRUE;")
    c.append("    END_IF;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Triplicated Zirconium Oxide (ZrO2) Residual Oxygen Sensor Voting *)")
    c.append("aO2_ChannelHealth[1] := (rRawO2_SensorA >= 0.0) AND (rRawO2_SensorA <= 250000.0);")
    c.append("aO2_ChannelHealth[2] := (rRawO2_SensorB >= 0.0) AND (rRawO2_SensorB <= 250000.0);")
    c.append("aO2_ChannelHealth[3] := (rRawO2_SensorC >= 0.0) AND (rRawO2_SensorC <= 250000.0);")
    c.append("")
    c.append("IF aO2_ChannelHealth[1] AND aO2_ChannelHealth[2] AND aO2_ChannelHealth[3] THEN")
    c.append("    nO2_HealthMode := 3;")
    c.append("    IF (rRawO2_SensorA >= rRawO2_SensorB AND rRawO2_SensorA <= rRawO2_SensorC) OR")
    c.append("       (rRawO2_SensorA >= rRawO2_SensorC AND rRawO2_SensorA <= rRawO2_SensorB) THEN")
    c.append("        rVotedO2 := rRawO2_SensorA;")
    c.append("    ELSIF (rRawO2_SensorB >= rRawO2_SensorA AND rRawO2_SensorB <= rRawO2_SensorC) OR")
    c.append("          (rRawO2_SensorB >= rRawO2_SensorC AND rRawO2_SensorB <= rRawO2_SensorA) THEN")
    c.append("        rVotedO2 := rRawO2_SensorB;")
    c.append("    ELSE")
    c.append("        rVotedO2 := rRawO2_SensorC;")
    c.append("    END_IF;")
    c.append("    ")
    c.append("    IF (ABS(rRawO2_SensorA - rRawO2_SensorB) > 45.0) OR")
    c.append("       (ABS(rRawO2_SensorB - rRawO2_SensorC) > 45.0) OR")
    c.append("       (ABS(rRawO2_SensorA - rRawO2_SensorC) > 45.0) THEN")
    c.append("        rO2_DiscrepTimer := rO2_DiscrepTimer + dt;")
    c.append("        IF rO2_DiscrepTimer > 2.0 THEN")
    c.append("            bO2_DiscrepAlarm := TRUE;")
    c.append("        END_IF;")
    c.append("    ELSE")
    c.append("        rO2_DiscrepTimer := MAX(0.0, rO2_DiscrepTimer - dt);")
    c.append("        bO2_DiscrepAlarm := FALSE;")
    c.append("    END_IF;")
    c.append("ELSIF aO2_ChannelHealth[1] AND aO2_ChannelHealth[2] THEN")
    c.append("    nO2_HealthMode := 2;")
    c.append("    rVotedO2 := (rRawO2_SensorA + rRawO2_SensorB) * 0.5;")
    c.append("ELSIF aO2_ChannelHealth[2] AND aO2_ChannelHealth[3] THEN")
    c.append("    nO2_HealthMode := 2;")
    c.append("    rVotedO2 := (rRawO2_SensorB + rRawO2_SensorC) * 0.5;")
    c.append("ELSIF aO2_ChannelHealth[1] AND aO2_ChannelHealth[3] THEN")
    c.append("    nO2_HealthMode := 2;")
    c.append("    rVotedO2 := (rRawO2_SensorA + rRawO2_SensorC) * 0.5;")
    c.append("ELSIF aO2_ChannelHealth[1] THEN")
    c.append("    nO2_HealthMode := 1;")
    c.append("    rVotedO2 := rRawO2_SensorA;")
    c.append("ELSIF aO2_ChannelHealth[2] THEN")
    c.append("    nO2_HealthMode := 1;")
    c.append("    rVotedO2 := rRawO2_SensorB;")
    c.append("ELSIF aO2_ChannelHealth[3] THEN")
    c.append("    nO2_HealthMode := 1;")
    c.append("    rVotedO2 := rRawO2_SensorC;")
    c.append("ELSE")
    c.append("    nO2_HealthMode := 0;")
    c.append("    rVotedO2 := 209000.0; (* Fail-safe fallback to atmospheric O2 *)")
    c.append("END_IF;")
    c.append("rActualO2Ppm := rVotedO2;")
    c.append("")
    c.append("(* Forced-Convection Blower Tachometer Supervision & Stall Detection *)")
    c.append("bAllBlowersHealthy := TRUE;")
    c.append("FOR i := 1 TO 12 DO")
    c.append("    aVotedBlowerTop[i] := aRawBlowerTachTop[i];")
    c.append("    aVotedBlowerBot[i] := aRawBlowerTachBot[i];")
    c.append("    ")
    c.append("    (* Commanded frequency to nominal RPM mapping: 50 Hz -> 2850 RPM *)")
    c.append("    IF aBlowerSpeedTopOut[i] > 10.0 THEN")
    c.append("        IF aVotedBlowerTop[i] < (aBlowerSpeedTopOut[i] * 57.0 * 0.65) THEN")
    c.append("            aBlowerStallTop[i] := TRUE;")
    c.append("            bAllBlowersHealthy := FALSE;")
    c.append("        ELSE")
    c.append("            aBlowerStallTop[i] := FALSE;")
    c.append("        END_IF;")
    c.append("    ELSE")
    c.append("        aBlowerStallTop[i] := FALSE;")
    c.append("    END_IF;")
    c.append("    ")
    c.append("    IF aBlowerSpeedBotOut[i] > 10.0 THEN")
    c.append("        IF aVotedBlowerBot[i] < (aBlowerSpeedBotOut[i] * 57.0 * 0.65) THEN")
    c.append("            aBlowerStallBot[i] := TRUE;")
    c.append("            bAllBlowersHealthy := FALSE;")
    c.append("        ELSE")
    c.append("            aBlowerStallBot[i] := FALSE;")
    c.append("        END_IF;")
    c.append("    ELSE")
    c.append("        aBlowerStallBot[i] := FALSE;")
    c.append("    END_IF;")
    c.append("END_FOR;")
    c.append("bBlowerStallTrip := NOT bAllBlowersHealthy;\n")
    
    # Phase 3: Discrete State-Space Model
    c.append("(* ============================================================================================= *)")
    c.append("(* PHASE 3: DISCRETE STATE-SPACE MODEL & THERMAL OBSERVER (12x12 TRIDIAGONAL MATRICES)          *)")
    c.append("(* ============================================================================================= *)")
    c.append("(* Initialize Physical Constants for 12 Thermal Zones *)")
    c.append("(* Preheat Zones 1..3: Capacitance ~4600 J/K, Convection ~60 W/m2K, Max Power ~12 kW *)")
    c.append("(* Soak Zones 4..6: Capacitance ~4200 J/K, Convection ~68 W/m2K, Max Power ~10 kW *)")
    c.append("(* Spike/Reflow Zones 7..9: Capacitance ~3800 J/K, Convection ~75 W/m2K, Max Power ~16 kW *)")
    c.append("(* Active Cooling Zones 10..12: Capacitance ~5200 J/K, Convection ~85 W/m2K, Cooling capacity *)")
    c.append("")
    c.append("aZoneThermalCapacitance[1] := 4600.0;   aZoneConvectiveCoeff[1] := 58.0;   aHeaterPowerMaxKw[1] := 12.0;   aLongitudinalLeakCoeff[1] := 35.0;")
    c.append("aZoneThermalCapacitance[2] := 4500.0;   aZoneConvectiveCoeff[2] := 62.0;   aHeaterPowerMaxKw[2] := 12.0;   aLongitudinalLeakCoeff[2] := 42.0;")
    c.append("aZoneThermalCapacitance[3] := 4400.0;   aZoneConvectiveCoeff[3] := 65.0;   aHeaterPowerMaxKw[3] := 12.0;   aLongitudinalLeakCoeff[3] := 45.0;")
    c.append("aZoneThermalCapacitance[4] := 4200.0;   aZoneConvectiveCoeff[4] := 68.0;   aHeaterPowerMaxKw[4] := 10.0;   aLongitudinalLeakCoeff[4] := 48.0;")
    c.append("aZoneThermalCapacitance[5] := 4100.0;   aZoneConvectiveCoeff[5] := 70.0;   aHeaterPowerMaxKw[5] := 10.0;   aLongitudinalLeakCoeff[5] := 50.0;")
    c.append("aZoneThermalCapacitance[6] := 4000.0;   aZoneConvectiveCoeff[6] := 72.0;   aHeaterPowerMaxKw[6] := 10.0;   aLongitudinalLeakCoeff[6] := 52.0;")
    c.append("aZoneThermalCapacitance[7] := 3800.0;   aZoneConvectiveCoeff[7] := 75.0;   aHeaterPowerMaxKw[7] := 16.0;   aLongitudinalLeakCoeff[7] := 55.0;")
    c.append("aZoneThermalCapacitance[8] := 3700.0;   aZoneConvectiveCoeff[8] := 78.0;   aHeaterPowerMaxKw[8] := 18.0;   aLongitudinalLeakCoeff[8] := 58.0;")
    c.append("aZoneThermalCapacitance[9] := 3900.0;   aZoneConvectiveCoeff[9] := 74.0;   aHeaterPowerMaxKw[9] := 14.0;   aLongitudinalLeakCoeff[9] := 50.0;")
    c.append("aZoneThermalCapacitance[10] := 5000.0;  aZoneConvectiveCoeff[10] := 82.0;  aHeaterPowerMaxKw[10] := 8.0;   aLongitudinalLeakCoeff[10] := 44.0;")
    c.append("aZoneThermalCapacitance[11] := 5200.0;  aZoneConvectiveCoeff[11] := 85.0;  aHeaterPowerMaxKw[11] := 6.0;   aLongitudinalLeakCoeff[11] := 38.0;")
    c.append("aZoneThermalCapacitance[12] := 5400.0;  aZoneConvectiveCoeff[12] := 88.0;  aHeaterPowerMaxKw[12] := 4.0;   aLongitudinalLeakCoeff[12] := 30.0;")
    c.append("")
    c.append("(* Formulate Discrete State Transition Matrix matA (12x12) and Input Matrix matB (12x12) *)")
    c.append("FOR i := 1 TO 12 DO")
    c.append("    FOR j := 1 TO 12 DO")
    c.append("        matA[i, j] := 0.0;")
    c.append("        matB[i, j] := 0.0;")
    c.append("        matC[i, j] := 0.0;")
    c.append("        matD[i, j] := 0.0;")
    c.append("    END_FOR;")
    c.append("    matC[i, i] := 1.0; (* Direct state measurement *)")
    c.append("END_FOR;")
    c.append("")
    c.append("FOR i := 1 TO 12 DO")
    c.append("    (* Diagonal heat storage decay *)")
    c.append("    matA[i, i] := 1.0 - (dt / aZoneThermalCapacitance[i]) * ")
    c.append("                  (aZoneConvectiveCoeff[i] + (2.0 * aLongitudinalLeakCoeff[i]));")
    c.append("    ")
    c.append("    (* Input heating authority: 100% duty cycle maps to installed kW *)")
    c.append("    matB[i, i] := (dt / aZoneThermalCapacitance[i]) * (aHeaterPowerMaxKw[i] * 10.0);")
    c.append("    ")
    c.append("    (* Longitudinal inter-zone thermal leakage coupling *)")
    c.append("    IF i > 1 THEN")
    c.append("        matA[i, i - 1] := (dt / aZoneThermalCapacitance[i]) * aLongitudinalLeakCoeff[i];")
    c.append("    END_IF;")
    c.append("    IF i < 12 THEN")
    c.append("        matA[i, i + 1] := (dt / aZoneThermalCapacitance[i]) * aLongitudinalLeakCoeff[i];")
    c.append("    END_IF;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Dynamic State Prediction: x_pred[k+1] = matA * x_state[k] + matB * u[k] *)")
    c.append("FOR i := 1 TO 12 DO")
    c.append("    x_pred[i] := 0.0;")
    c.append("    FOR j := 1 TO 12 DO")
    c.append("        x_pred[i] := x_pred[i] + (matA[i, j] * x_state[j]);")
    c.append("    END_FOR;")
    c.append("    x_pred[i] := x_pred[i] + (matB[i, i] * u_mpc_opt[i]);")
    c.append("    ")
    c.append("    (* Luenberger observer correction: fuse prediction with 2oo3 voted sensor feedback *)")
    c.append("    x_state[i] := x_pred[i] + (0.28 * (aVotedTC[i] - x_pred[i]));")
    c.append("    y_output[i] := x_state[i];")
    c.append("END_FOR;\n")
    
    # Phase 4: Board Tracking Collation & Feedforward
    c.append("(* ============================================================================================= *)")
    c.append("(* PHASE 4: BOARD ENTRY COLLATION, 32-SLOT FIFO SHIFT TRACKING & DYNAMIC FEEDFORWARD           *)")
    c.append("(* ============================================================================================= *)")
    c.append("(* 1. Optical Entrance Edge Trigger Detection *)")
    c.append("IF bEntrancePhotoEye AND NOT bEntranceSensorPrev THEN")
    c.append("    (* Find lowest available slot in 32-slot FIFO tracking array *)")
    c.append("    nFreeSlotIdx := 0;")
    c.append("    FOR j := 1 TO 32 DO")
    c.append("        IF (NOT aBoardValid[j]) AND (nFreeSlotIdx = 0) THEN")
    c.append("            nFreeSlotIdx := j;")
    c.append("        END_IF;")
    c.append("    END_FOR;")
    c.append("    ")
    c.append("    IF nFreeSlotIdx > 0 THEN")
    c.append("        nBoardGlobalCounter := nBoardGlobalCounter + 1;")
    c.append("        aBoardValid[nFreeSlotIdx] := TRUE;")
    c.append("        aBoardSerial[nFreeSlotIdx] := nBoardGlobalCounter;")
    c.append("        aBoardXPos[nFreeSlotIdx] := 0.0;")
    c.append("        aBoardCurrentZone[nFreeSlotIdx] := 1;")
    c.append("        aBoardPeakTemp[nFreeSlotIdx] := rAmbientTemperature;")
    c.append("        aBoardTAL_Timer[nFreeSlotIdx] := 0.0;")
    c.append("        aBoardResidenceTime[nFreeSlotIdx] := 0.0;")
    c.append("    END_IF;")
    c.append("END_IF;")
    c.append("bEntranceSensorPrev := bEntrancePhotoEye;")
    c.append("")
    c.append("(* 2. Advance all occupied PCB positions according to filtered conveyor transport *)")
    c.append("nActiveBoardCount := 0;")
    c.append("FOR j := 1 TO 32 DO")
    c.append("    IF aBoardValid[j] THEN")
    c.append("        nActiveBoardCount := nActiveBoardCount + 1;")
    c.append("        aBoardXPos[j] := aBoardXPos[j] + ((rActualConveyorSpeed * 1000.0 / 60.0) * dt);")
    c.append("        aBoardResidenceTime[j] := aBoardResidenceTime[j] + dt;")
    c.append("        ")
    c.append("        (* Identify physical zone index based on longitudinal length (450 mm / zone) *)")
    c.append("        k := REAL_TO_INT(TRUNC(aBoardXPos[j] / ZONE_LENGTH_MM)) + 1;")
    c.append("        IF k < 1 THEN")
    c.append("            k := 1;")
    c.append("        ELSIF k > 12 THEN")
    c.append("            k := 12;")
    c.append("        END_IF;")
    c.append("        aBoardCurrentZone[j] := k;")
    c.append("        ")
    c.append("        (* Real-time thermal profiling audit: Track peak temperature seen *)")
    c.append("        IF aVotedTC[k] > aBoardPeakTemp[j] THEN")
    c.append("            aBoardPeakTemp[j] := aVotedTC[k];")
    c.append("        END_IF;")
    c.append("        ")
    c.append("        (* Accumulate Time Above Liquidus (TAL > 217.0 deg C) *)")
    c.append("        IF aVotedTC[k] >= LIQUIDUS_TEMP_C THEN")
    c.append("            aBoardTAL_Timer[j] := aBoardTAL_Timer[j] + dt;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("        (* Discharge detection: PCB reaches oven tunnel exit (5400 mm) *)")
    c.append("        IF aBoardXPos[j] >= TOTAL_TUNNEL_LENGTH_MM THEN")
    c.append("            rPeakTemperatureRecorded := aBoardPeakTemp[j];")
    c.append("            rTAL_SecondsRecorded := aBoardTAL_Timer[j];")
    c.append("            aBoardValid[j] := FALSE;")
    c.append("        END_IF;")
    c.append("    END_IF;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* 3. Dynamic Cold PCB Thermal Mass Disturbance Feedforward Compensation *)")
    c.append("FOR i := 1 TO 12 DO")
    c.append("    u_feedforward[i] := 0.0;")
    c.append("    (* Tally boards currently traversing zone i *)")
    c.append("    FOR j := 1 TO 32 DO")
    c.append("        IF aBoardValid[j] AND (aBoardCurrentZone[j] = i) THEN")
    c.append("            (* Compute dynamic convective heat absorption load Delta_P = m*Cp*v*(T_set - T_pcb) *)")
    c.append("            u_feedforward[i] := u_feedforward[i] + ")
    c.append("                ((rBoardThermalMass * (rActualConveyorSpeed / 60.0) * ")
    c.append("                 (aZoneSetpoints[i] - aBoardPeakTemp[j])) / (aHeaterPowerMaxKw[i] * 1000.0) * 100.0);")
    c.append("        END_IF;")
    c.append("    END_FOR;")
    c.append("    (* Bound feedforward injection to maximum 25% duty cycle to avoid thermal runaway *)")
    c.append("    IF u_feedforward[i] > 25.0 THEN")
    c.append("        u_feedforward[i] := 25.0;")
    c.append("    ELSIF u_feedforward[i] < 0.0 THEN")
    c.append("        u_feedforward[i] := 0.0;")
    c.append("    END_IF;")
    c.append("END_FOR;\n")
    
    # Phase 5: Receding Horizon MPC
    c.append("(* ============================================================================================= *)")
    c.append("(* PHASE 5: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) OPTIMIZATION                        *)")
    c.append("(* ============================================================================================= *)")
    c.append("(* MPC Tuning Penalty Matrices: Quadratic state tracking Q, actuator slew R, terminal cost P *)")
    c.append("(* Zones 1..3 (Preheat): Moderate tracking Q, gentle slew R *)")
    c.append("diagQ[1] := 2.2;  diagR[1] := 0.85;  diagP[1] := 5.0;")
    c.append("diagQ[2] := 2.5;  diagR[2] := 0.85;  diagP[2] := 6.0;")
    c.append("diagQ[3] := 3.0;  diagR[3] := 0.90;  diagP[3] := 7.5;")
    c.append("(* Zones 4..6 (Soak Plateau): High tracking Q to preserve thermal equalization across PCBA *)")
    c.append("diagQ[4] := 4.8;  diagR[4] := 1.20;  diagP[4] := 11.0;")
    c.append("diagQ[5] := 5.5;  diagR[5] := 1.30;  diagP[5] := 13.0;")
    c.append("diagQ[6] := 6.2;  diagR[6] := 1.40;  diagP[6] := 15.0;")
    c.append("(* Zones 7..9 (Spike/Reflow): Critical tracking Q to hit SAC305 peak & TAL without exceeding 250C *)")
    c.append("diagQ[7] := 14.0; diagR[7] := 1.60;  diagP[7] := 38.0;")
    c.append("diagQ[8] := 20.0; diagR[8] := 2.10;  diagP[8] := 55.0;")
    c.append("diagQ[9] := 16.0; diagR[9] := 1.80;  diagP[9] := 42.0;")
    c.append("(* Zones 10..12 (Active Cooling): High quench penalty Q to enforce -2.5 to -4.0 deg C/s dendritic slope *)")
    c.append("diagQ[10] := 9.0; diagR[10] := 1.10; diagP[10] := 22.0;")
    c.append("diagQ[11] := 7.5; diagR[11] := 1.00; diagP[11] := 18.0;")
    c.append("diagQ[12] := 5.0; diagR[12] := 0.80; diagP[12] := 12.0;")
    c.append("")
    c.append("(* MPC Gradient Descent Iteration: Solve quadratic objective J = e^T*Q*e + delta_u^T*R*delta_u *)")
    c.append("rSumPower := 0.0;")
    c.append("FOR i := 1 TO 12 DO")
    c.append("    rTempDiff := x_state[i] - aZoneSetpoints[i];")
    c.append("    ")
    c.append("    (* Gradient of cost function with respect to duty cycle u[i] *)")
    c.append("    u_mpc_opt[i] := u_prev[i] - (rMpcGradStep * ((diagQ[i] * rTempDiff * matB[i, i]) + ")
    c.append("                                                 (diagR[i] * (u_prev[i] - u_mpc_opt[i]))));")
    c.append("    ")
    c.append("    (* Superimpose dynamic feedforward compensation for cold board passage *)")
    c.append("    u_mpc_opt[i] := u_mpc_opt[i] + u_feedforward[i];")
    c.append("    ")
    c.append("    (* Actuator saturation limits: 0.0% to 100.0% PWM duty cycle *)")
    c.append("    IF u_mpc_opt[i] > 100.0 THEN")
    c.append("        u_mpc_opt[i] := 100.0;")
    c.append("    ELSIF u_mpc_opt[i] < 0.0 THEN")
    c.append("        u_mpc_opt[i] := 0.0;")
    c.append("    END_IF;")
    c.append("    u_prev[i] := u_mpc_opt[i];")
    c.append("    ")
    c.append("    (* Split duty cycle command into top and bottom heater zones *)")
    c.append("    (* Bottom heaters receive a +1.5% duty bias to offset pin-chain convective heatsink effect *)")
    c.append("    aHeaterDutyTop[i] := u_mpc_opt[i];")
    c.append("    aHeaterDutyBot[i] := MIN(100.0, u_mpc_opt[i] + 1.5);")
    c.append("    ")
    c.append("    (* Instantaneous power consumption accumulation: P = Duty% * Installed_kW *)")
    c.append("    rSumPower := rSumPower + ((aHeaterDutyTop[i] + aHeaterDutyBot[i]) * 0.5 * 0.01 * aHeaterPowerMaxKw[i]);")
    c.append("END_FOR;")
    c.append("rTotalPowerConsumptionKw := rSumPower;\n")
    
    # Phase 6: Dynamic N2 Inerting Atmosphere Control
    c.append("(* ============================================================================================= *)")
    c.append("(* PHASE 6: CLOSED-LOOP NITROGEN (N2) ATMOSPHERE INERTING & ZIRCONIUM SENSOR REGULATION         *)")
    c.append("(* ============================================================================================= *)")
    c.append("(* Residual oxygen error calculation: e_O2 = Actual_voted_ppm - Target_setpoint_ppm *)")
    c.append("rO2_Error := rActualO2Ppm - rTargetO2Concentration;")
    c.append("")
    c.append("(* Derivative term with high-frequency noise smoothing *)")
    c.append("rO2_Derivative := (rO2_Error - rO2_PrevError) / dt;")
    c.append("rO2_PrevError := rO2_Error;")
    c.append("")
    c.append("(* Anti-windup clamped integral accumulator *)")
    c.append("rO2_Integral := rO2_Integral + (rO2_Error * dt);")
    c.append("IF rO2_Integral > 450.0 THEN")
    c.append("    rO2_Integral := 450.0;")
    c.append("ELSIF rO2_Integral < -150.0 THEN")
    c.append("    rO2_Integral := -150.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* Proportional valve command: Base flow + PID action *)")
    c.append("rN2ProportionalValveCmd := rN2BaseFlowCmd + (rKp_N2 * rO2_Error) + ")
    c.append("                          (rKi_N2 * rO2_Integral) + (rKd_N2 * rO2_Derivative);")
    c.append("")
    c.append("(* Dynamic entrance/exit curtain trim: increase barrier purge when conveyor is moving *)")
    c.append("IF rActualConveyorSpeed > 0.1 THEN")
    c.append("    rN2CurtainInletCmd := 65.0 + (15.0 * (rActualConveyorSpeed / 1.5));")
    c.append("    rN2CurtainOutletCmd := 60.0 + (15.0 * (rActualConveyorSpeed / 1.5));")
    c.append("ELSE")
    c.append("    rN2CurtainInletCmd := 35.0;")
    c.append("    rN2CurtainOutletCmd := 30.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* Total nitrogen consumption estimation: Q = Q_main + Q_inlet + Q_outlet [m3/h] *)")
    c.append("rTotalN2ConsumptionM3H := (0.28 * rN2ProportionalValveCmd) + ")
    c.append("                          (0.08 * rN2CurtainInletCmd) + (0.08 * rN2CurtainOutletCmd);")
    c.append("")
    c.append("(* Flux extraction exhaust damper control based on delta-P plenum pressure *)")
    c.append("IF rExhaustPressureDelta < 1.8 THEN")
    c.append("    rExhaustExtractionCmd := 85.0; (* Elevate exhaust damper to maintain negative pressure draft *)")
    c.append("ELSE")
    c.append("    rExhaustExtractionCmd := 45.0;")
    c.append("END_IF;\n")
    
    # Phase 7: 12-Stage Operational FSM
    c.append("(* ============================================================================================= *)")
    c.append("(* PHASE 7: 12-STAGE OPERATIONAL FINITE STATE MACHINE (FSM)                                      *)")
    c.append("(* ============================================================================================= *)")
    c.append("rStateTimer := rStateTimer + dt;")
    c.append("")
    c.append("CASE eCurrentState OF")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 0: OVEN COLD PURGE (Exhaust solvent volatiles prior to heating)                     *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    0: (* STATE_OVEN_COLD_PURGE *)")
    c.append("        bOvenReadyForBoard := FALSE;")
    c.append("        bSmemaEntranceGood := FALSE;")
    c.append("        bSmemaExitAvail := FALSE;")
    c.append("        bAutoCycleRunning := FALSE;")
    c.append("        ")
    c.append("        (* Heaters disabled for safety *)")
    c.append("        FOR i := 1 TO 12 DO")
    c.append("            aHeaterDutyTop[i] := 0.0;")
    c.append("            aHeaterDutyBot[i] := 0.0;")
    c.append("            aBlowerSpeedTopOut[i] := 45.0; (* Full convective flush *)")
    c.append("            aBlowerSpeedBotOut[i] := 45.0;")
    c.append("        END_FOR;")
    c.append("        rN2ProportionalValveCmd := 0.0;")
    c.append("        rExhaustExtractionCmd := 100.0; (* Maximum exhaust extraction damper *)")
    c.append("        ")
    c.append("        IF bStateFirstScan THEN")
    c.append("            rPurgeTimer := 60.0; (* 60 s solvent evacuation purge *)")
    c.append("            bStateFirstScan := FALSE;")
    c.append("        END_IF;")
    c.append("        rPurgeTimer := rPurgeTimer - dt;")
    c.append("        ")
    c.append("        IF (rPurgeTimer <= 0.0) AND bSystemEnable AND bEmergencyStopOk THEN")
    c.append("            eCurrentState := 1; (* Advance to N2 Displacement *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 1: N2 ATMOSPHERE DISPLACEMENT (High volume inerting flush to displace oxygen)       *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    1: (* STATE_N2_DISPLACEMENT *)")
    c.append("        bOvenReadyForBoard := FALSE;")
    c.append("        bSmemaEntranceGood := FALSE;")
    c.append("        bAutoCycleRunning := FALSE;")
    c.append("        ")
    c.append("        (* High purge flow command to drive O2 below 1,000 ppm *)")
    c.append("        rN2ProportionalValveCmd := 85.0;")
    c.append("        rN2CurtainInletCmd := 90.0;")
    c.append("        rN2CurtainOutletCmd := 90.0;")
    c.append("        rExhaustExtractionCmd := 35.0;")
    c.append("        ")
    c.append("        IF bStateFirstScan THEN")
    c.append("            rDisplacementTimer := 120.0; (* 120 s timed flush *)")
    c.append("            bStateFirstScan := FALSE;")
    c.append("        END_IF;")
    c.append("        rDisplacementTimer := rDisplacementTimer - dt;")
    c.append("        ")
    c.append("        IF (rDisplacementTimer <= 0.0) AND (rActualO2Ppm <= 1000.0) THEN")
    c.append("            eCurrentState := 2; (* Advance to Ramp-to-Soak *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 2: RAMP-TO-SOAK (Controlled preheat ramp up to 150 deg C soak plateau)              *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    2: (* STATE_RAMP_TO_SOAK *)")
    c.append("        bOvenReadyForBoard := FALSE;")
    c.append("        bSmemaEntranceGood := FALSE;")
    c.append("        bAutoCycleRunning := FALSE;")
    c.append("        ")
    c.append("        (* Recipe loading: SAC305 standard thermal setpoints *)")
    c.append("        aZoneSetpoints[1] := 90.0;   aZoneSetpoints[2] := 125.0;  aZoneSetpoints[3] := 145.0;")
    c.append("        aZoneSetpoints[4] := 160.0;  aZoneSetpoints[5] := 172.0;  aZoneSetpoints[6] := 182.0;")
    c.append("        aZoneSetpoints[7] := 210.0;  aZoneSetpoints[8] := 242.0;  aZoneSetpoints[9] := 228.0;")
    c.append("        aZoneSetpoints[10] := 165.0; aZoneSetpoints[11] := 115.0; aZoneSetpoints[12] := 45.0;")
    c.append("        ")
    c.append("        FOR i := 1 TO 12 DO")
    c.append("            aBlowerSpeedTopOut[i] := 40.0;")
    c.append("            aBlowerSpeedBotOut[i] := 40.0;")
    c.append("        END_FOR;")
    c.append("        ")
    c.append("        (* Transition when preheat and soak zones reach 85% of setpoint *)")
    c.append("        IF (aVotedTC[1] >= 75.0) AND (aVotedTC[4] >= 140.0) AND (aVotedTC[7] >= 180.0) THEN")
    c.append("            eCurrentState := 3; (* Advance to Thermal Stabilization *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 3: THERMAL STABILIZATION (Dwell until all 12 zones are within +/- 2.5 deg C)        *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    3: (* STATE_THERMAL_STABILIZATION *)")
    c.append("        bOvenReadyForBoard := FALSE;")
    c.append("        bSmemaEntranceGood := FALSE;")
    c.append("        bAutoCycleRunning := FALSE;")
    c.append("        ")
    c.append("        (* Verify stability across all 12 zones *)")
    c.append("        bAllZonesStabilized := TRUE;")
    c.append("        FOR i := 1 TO 12 DO")
    c.append("            IF ABS(aVotedTC[i] - aZoneSetpoints[i]) > PEAK_TARGET_TOL_C THEN")
    c.append("                bAllZonesStabilized := FALSE;")
    c.append("            END_IF;")
    c.append("        END_FOR;")
    c.append("        ")
    c.append("        IF bStateFirstScan THEN")
    c.append("            rStabilizationTimer := 45.0; (* 45 s continuous dwell *)")
    c.append("            bStateFirstScan := FALSE;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("        IF bAllZonesStabilized AND (rActualO2Ppm <= rTargetO2Concentration) THEN")
    c.append("            rStabilizationTimer := rStabilizationTimer - dt;")
    c.append("        ELSE")
    c.append("            rStabilizationTimer := 45.0; (* Reset dwell if disturbed *)")
    c.append("        END_IF;")
    c.append("        ")
    c.append("        IF rStabilizationTimer <= 0.0 THEN")
    c.append("            eCurrentState := 4; (* Advance to Board Entry Collation *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 4: BOARD ENTRY COLLATION (Oven primed, ready to accept PCBs from upstream SMT)     *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    4: (* STATE_BOARD_ENTRY_COLLATION *)")
    c.append("        bOvenReadyForBoard := TRUE;")
    c.append("        bSmemaEntranceGood := TRUE;")
    c.append("        bAutoCycleRunning := TRUE;")
    c.append("        ")
    c.append("        IF bEntrancePhotoEye OR (nActiveBoardCount > 0) THEN")
    c.append("            eCurrentState := 5; (* Advance to Dynamic Reflow Pacing *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 5: DYNAMIC REFLOW PACING (Continuous active production with MPC & feedforward)     *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    5: (* STATE_DYNAMIC_REFLOW_PACING *)")
    c.append("        bOvenReadyForBoard := TRUE;")
    c.append("        bSmemaEntranceGood := NOT bSmemaDownstreamBusy; (* Flow control *)")
    c.append("        bSmemaExitAvail := bExitPhotoEye;")
    c.append("        bAutoCycleRunning := TRUE;")
    c.append("        ")
    c.append("        (* Starvation timeout detection: No boards for 180 seconds *)")
    c.append("        IF nActiveBoardCount = 0 THEN")
    c.append("            rStandbyInactivityTimer := rStandbyInactivityTimer + dt;")
    c.append("            IF rStandbyInactivityTimer > 180.0 THEN")
    c.append("                eCurrentState := 6; (* Advance to N2 Conservation Standby *)")
    c.append("                bStateFirstScan := TRUE;")
    c.append("                rStateTimer := 0.0;")
    c.append("            END_IF;")
    c.append("        ELSE")
    c.append("            rStandbyInactivityTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("        IF bAutoCycleStop THEN")
    c.append("            eCurrentState := 8; (* Controlled Cool-Down *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 6: N2 CONSERVATION STANDBY (Conveyor idle, N2 flow throttled to save gas)           *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    6: (* STATE_N2_CONSERVATION_STANDBY *)")
    c.append("        bOvenReadyForBoard := TRUE;")
    c.append("        bSmemaEntranceGood := TRUE;")
    c.append("        ")
    c.append("        (* Throttle N2 flow by 50% to conserve expensive high-purity nitrogen *)")
    c.append("        rN2BaseFlowCmd := 9.0;")
    c.append("        rN2CurtainInletCmd := 20.0;")
    c.append("        rN2CurtainOutletCmd := 20.0;")
    c.append("        ")
    c.append("        (* Wake up immediately upon upstream SMEMA ready or board arrival *)")
    c.append("        IF bSmemaUpstreamReady OR bEntrancePhotoEye THEN")
    c.append("            rN2BaseFlowCmd := 18.0; (* Restore full production flow *)")
    c.append("            eCurrentState := 4;     (* Re-enter Board Entry Collation *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 7: RECIPE SWITCH (On-the-fly setpoint adaptation & conveyor rail motorized adjust)   *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    7: (* STATE_RECIPE_SWITCH *)")
    c.append("        bOvenReadyForBoard := FALSE;")
    c.append("        bSmemaEntranceGood := FALSE;")
    c.append("        ")
    c.append("        IF nRecipeProfileId = 2 THEN")
    c.append("            (* Recipe 2: High Thermal Mass SAC305 profile (heavier soak) *)")
    c.append("            aZoneSetpoints[4] := 168.0; aZoneSetpoints[5] := 178.0; aZoneSetpoints[6] := 188.0;")
    c.append("            aZoneSetpoints[8] := 246.0;")
    c.append("        ELSIF nRecipeProfileId = 3 THEN")
    c.append("            (* Recipe 3: Sn42Bi58 Low-Temperature Eutectic (Liquidus 138 deg C) *)")
    c.append("            aZoneSetpoints[1] := 70.0;  aZoneSetpoints[2] := 95.0;   aZoneSetpoints[3] := 115.0;")
    c.append("            aZoneSetpoints[4] := 125.0; aZoneSetpoints[5] := 132.0;  aZoneSetpoints[6] := 138.0;")
    c.append("            aZoneSetpoints[7] := 155.0; aZoneSetpoints[8] := 168.0;  aZoneSetpoints[9] := 150.0;")
    c.append("            aZoneSetpoints[10] := 110.0;aZoneSetpoints[11] := 80.0;  aZoneSetpoints[12] := 35.0;")
    c.append("        ELSE")
    c.append("            (* Standard SAC305 default *)")
    c.append("            aZoneSetpoints[1] := 90.0;  aZoneSetpoints[2] := 125.0;  aZoneSetpoints[3] := 145.0;")
    c.append("            aZoneSetpoints[4] := 160.0; aZoneSetpoints[5] := 172.0;  aZoneSetpoints[6] := 182.0;")
    c.append("            aZoneSetpoints[7] := 210.0; aZoneSetpoints[8] := 242.0;  aZoneSetpoints[9] := 228.0;")
    c.append("            aZoneSetpoints[10] := 165.0;aZoneSetpoints[11] := 115.0; aZoneSetpoints[12] := 45.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("        (* Once clear of boards and retuned, return to stabilization *)")
    c.append("        IF nActiveBoardCount = 0 THEN")
    c.append("            eCurrentState := 3; (* Thermal Stabilization *)")
    c.append("            bStateFirstScan := TRUE;")
    c.append("            rStateTimer := 0.0;")
    c.append("        END_IF;")
    c.append("        ")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    (* STATE 8: CONTROLLED COOL-DOWN (Orderly ramp down to protect heating element coils)        *)")
    c.append("    (* ----------------------------------------------------------------------------------------- *)")
    c.append("    8: (* STATE_CONTROLLED_COOL_DOWN *)")
    c.append("        bOvenReadyForBoard := FALSE;")
    c.append("        bSmemaEntranceGood := FALSE;")
    c.append("        bAutoCycleRunning := FALSE;")
    c.append("        ")
    c.append("        FOR i := 1 TO 12 DO")
    c.append("            aHeaterDutyTop[i] := 0.0;")
    c.append("            aHeaterDutyBot[i] := 0.0;")
    c.append("            aBlowerSpeedTopOut[i] := 30.0; (* Moderate blower speed during cool-down *)")
    c.append("            aBlowerSpeedBotOut[i] := 30.0;")
    c.append("        END_FOR;")
    c.append("        rN2ProportionalValveCmd := 0.0;")
