def get_section_recoater_dsp_lines():
    return [
        "(* ==================================================================================== *)",
        "(* SECTION 2: RECOATER HIGH-SPEED ACOUSTIC EMISSION DSP & TRIBOLOGICAL FRICTION ANALYSIS*)",
        "(* Processes piezoceramic AE signals across sliding 32-sample window for Kurtosis & Crest*)",
        "(* Evaluates carriage strain gauge load cell for dynamic friction jam thresholding     *)",
        "(* ==================================================================================== *)",
        "",
        "(* Store incoming samples into circular ring buffer *)",
        "arrAE_History_Ch1[iAE_RingPtr] := rRecoaterAE_Sensor1_dB;",
        "arrAE_History_Ch2[iAE_RingPtr] := rRecoaterAE_Sensor2_dB;",
        "iAE_RingPtr := iAE_RingPtr + 1;",
        "IF iAE_RingPtr > 32 THEN",
        "    iAE_RingPtr := 1;",
        "END_IF;",
        "",
        "(* Compute running mean, variance, and fourth statistical moment *)",
        "rAE_SumCh1 := 0.0;",
        "rAE_SumCh2 := 0.0;",
        "FOR idxI := 1 TO 32 DO",
        "    rAE_SumCh1 := rAE_SumCh1 + arrAE_History_Ch1[idxI];",
        "    rAE_SumCh2 := rAE_SumCh2 + arrAE_History_Ch2[idxI];",
        "END_FOR;",
        "rAE_SumCh1 := rAE_SumCh1 / 32.0; (* Sample mean Ch1 *)",
        "rAE_SumCh2 := rAE_SumCh2 / 32.0; (* Sample mean Ch2 *)",
        "",
        "rAE_SumSqCh1 := 0.0;",
        "rAE_SumSqCh2 := 0.0;",
        "rAE_SumPow4Ch1 := 0.0;",
        "rAE_SumPow4Ch2 := 0.0;",
        "rAE_PeakHoldCh1 := 0.0;",
        "rAE_PeakHoldCh2 := 0.0;",
        "",
        "FOR idxI := 1 TO 32 DO",
        "    rDeltaPos := arrAE_History_Ch1[idxI] - rAE_SumCh1;",
        "    rAE_SumSqCh1 := rAE_SumSqCh1 + (rDeltaPos * rDeltaPos);",
        "    rAE_SumPow4Ch1 := rAE_SumPow4Ch1 + (rDeltaPos * rDeltaPos * rDeltaPos * rDeltaPos);",
        "    IF arrAE_History_Ch1[idxI] > rAE_PeakHoldCh1 THEN",
        "        rAE_PeakHoldCh1 := arrAE_History_Ch1[idxI];",
        "    END_IF;",
        "",
        "    rDeltaPos := arrAE_History_Ch2[idxI] - rAE_SumCh2;",
        "    rAE_SumSqCh2 := rAE_SumSqCh2 + (rDeltaPos * rDeltaPos);",
        "    rAE_SumPow4Ch2 := rAE_SumPow4Ch2 + (rDeltaPos * rDeltaPos * rDeltaPos * rDeltaPos);",
        "    IF arrAE_History_Ch2[idxI] > rAE_PeakHoldCh2 THEN",
        "        rAE_PeakHoldCh2 := arrAE_History_Ch2[idxI];",
        "    END_IF;",
        "END_FOR;",
        "",
        "(* Calculate variance (sigma^2) and fourth standardized moment (Kurtosis) *)",
        "rAE_VarianceCh1 := rAE_SumSqCh1 / 32.0;",
        "rAE_VarianceCh2 := rAE_SumSqCh2 / 32.0;",
        "",
        "IF rAE_VarianceCh1 > 0.001 THEN",
        "    rAE_KurtosisCh1 := (rAE_SumPow4Ch1 / 32.0) / (rAE_VarianceCh1 * rAE_VarianceCh1);",
        "    rAE_CrestFactorCh1 := rAE_PeakHoldCh1 / SQRT(rAE_VarianceCh1 + 0.0001);",
        "ELSE",
        "    rAE_KurtosisCh1 := 3.0;",
        "    rAE_CrestFactorCh1 := 1.414;",
        "END_IF;",
        "",
        "IF rAE_VarianceCh2 > 0.001 THEN",
        "    rAE_KurtosisCh2 := (rAE_SumPow4Ch2 / 32.0) / (rAE_VarianceCh2 * rAE_VarianceCh2);",
        "    rAE_CrestFactorCh2 := rAE_PeakHoldCh2 / SQRT(rAE_VarianceCh2 + 0.0001);",
        "ELSE",
        "    rAE_KurtosisCh2 := 3.0;",
        "    rAE_CrestFactorCh2 := 1.414;",
        "END_IF;",
        "",
        "(* First-order low-pass filter on dynamic carriage friction load [N] *)",
        "rRecoaterFrictionFilt_N := (0.85 * rRecoaterFrictionFilt_N) + (0.15 * rRecoaterFrictionLoad_N);",
        "",
        "(* Collision & Jam Discrimination Logic *)",
        "IF (rAE_KurtosisCh1 > c_rAcousticBurstTripKurtosis OR rAE_KurtosisCh2 > c_rAcousticBurstTripKurtosis) AND",
        "   (rAE_CrestFactorCh1 > c_rAcousticBurstTripCrest OR rAE_CrestFactorCh2 > c_rAcousticBurstTripCrest) AND",
        "   (rRecoaterAE_PeakFrequency_kHz > 85.0) THEN",
        "    tonRecoaterCollisionTrip(IN := TRUE, PT := T#15MS);",
        "    IF tonRecoaterCollisionTrip.Q THEN",
        "        bRecoaterCollisionAlert := TRUE;",
        "        arrAlarm_Active[6] := TRUE; (* Alarm 6: Recoater Acoustic Burst Part Curl Warning *)",
        "    END_IF;",
        "ELSE",
        "    tonRecoaterCollisionTrip(IN := FALSE, PT := T#15MS);",
        "    IF bAcknowledgeFaults AND arrAlarm_Acknowledged[6] THEN",
        "        bRecoaterCollisionAlert := FALSE;",
        "        arrAlarm_Active[6] := FALSE;",
        "    END_IF;",
        "END_IF;",
        "",
        "IF rRecoaterFrictionFilt_N > c_rRecoaterFrictionTripLimit_N THEN",
        "    bRecoaterBladeJamTrip := TRUE;",
        "    arrAlarm_Active[5] := TRUE; (* Alarm 5: Recoater Blade Mechanical Jam Trip *)",
        "    IF NOT bFirstOutLatched THEN",
        "        arrAlarm_FirstOut[5] := TRUE;",
        "        bFirstOutLatched := TRUE;",
        "        wActiveFaultCode := 16#E005;",
        "    END_IF;",
        "ELSE",
        "    IF bAcknowledgeFaults AND arrAlarm_Acknowledged[5] THEN",
        "        bRecoaterBladeJamTrip := FALSE;",
        "        arrAlarm_Active[5] := FALSE;",
        "        arrAlarm_FirstOut[5] := FALSE;",
        "    END_IF;",
        "END_IF;",
        ""
    ]

