    a("")
    a("(* 3.3 8 Geometric Interference Collision Zones Token Arbitration *)")
    a("(* Zone 1: Engine Bay (Robots 1, 2, 11) *)")
    a("(* Zone 2: Cowl & Windshield (Robots 3, 4, 15) *)")
    a("(* Zone 3: LH A/B-Pillar (Robots 5, 12, 17) *)")
    a("(* Zone 4: RH A/B-Pillar (Robots 6, 13, 18) *)")
