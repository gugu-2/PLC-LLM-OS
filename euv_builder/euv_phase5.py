def get_phase5():
    lines = []
    lines.append("(* === PHASE 5: ISA-18.2 / SEMI S2 ALARMS & DIAGNOSTIC WORD BITFIELD PACKING === *)")
    lines.append("(* Comprehensive safety interlocks, multi-tiered process limit trips (HH/LL), high/low *)")
    lines.append("(* pre-alarms with deadband hysteresis, and bit-packed telemetry status DWORDs.          *)")
    lines.append("")

    lines.append("(* 5.1 Initialize Diagnostic Words for Current Scan *)")
    lines.append("dwAlarmWord_1 := 16#0000_0000;")
    lines.append("dwAlarmWord_2 := 16#0000_0000;")
    lines.append("dwWarningWord_2 := 16#0000_0000;")
    lines.append("dwDiagnosticStatus := 16#0000_0000;")
    lines.append("")

    lines.append("(* 5.2 Critical SEMI S2 SIL-3 Plant Shutdown Interlocks (dwAlarmWord_1) *)")
    lines.append("IF NOT bEmergencyStop THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0001; (* E-Stop active *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF NOT bVesselSealsLocked THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0002; (* Vessel door seal unlocked *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF NOT bTurbopumpsOnline AND (iState >= 40) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0004; (* Turbomolecular pump skid offline *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF NOT bRoughingVacuumOk AND (iState >= 10) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0008; (* Roughing vacuum lost *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF NOT bCoolingWaterFlowOk AND (iState >= 40) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0010; (* Cooling water loop flow failure *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (NOT bMagnetCryoPermissive OR (rMagnetField_Tesla < 0.2 AND iState >= 70)) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0020; (* Superconducting magnet quench / field failure *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF NOT bCO2LaserMOPAReady AND (iState >= 80) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0040; (* CO2 drive laser MOPA chain fault *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF NOT bPrePulseLaserReady AND (iState >= 70) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0080; (* Pre-pulse laser fault *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rHydrogenGasDetector_LEL >= 25.0) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0100; (* Hydrogen gas leak HH trip (>=25% LEL) *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedVesselPressure_Pa >= 15.0) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0200; (* Vessel vacuum overpressure HH trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedMirrorCenterTemp_DegC >= 65.0) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0400; (* Collector mirror center temp runaway HH trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rDropletPosJitter_um >= 3.5) AND (iState >= 80) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_0800; (* Droplet positional loss trip while firing laser *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF ((ABS(rBeamGalvoOffsetX_urad - rGalvoSteerX_urad) > 15.0) OR (ABS(rBeamGalvoOffsetY_urad - rGalvoSteerY_urad) > 15.0)) AND (iState >= 70) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_1000; (* Galvo beam delivery steering misalignment trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rTinReservoirPress_bar >= 125.0) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_2000; (* Molten tin reservoir overpressure HH trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rTinReservoirTemp_DegC >= 280.0) THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_4000; (* Molten tin reservoir temperature runaway HH trip *)")
    lines.append("END_IF;")
    lines.append("")

    lines.append("(* 5.3 Process Parameter High-High / Low-Low Limit Trips (dwAlarmWord_2) *)")
    lines.append("IF (rVotedMirrorMidTemp_DegC >= 63.5) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0001; (* Collector mirror mid-zone temp HH trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedVesselPressure_Pa <= 0.0005) AND (iState >= 60) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0002; (* Vessel pressure LL trip during gas flow *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedDropletVel_mps <= 60.0) AND (iState >= 40) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0004; (* Droplet stream velocity LL trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedDropletVel_mps >= 90.0) AND (iState >= 40) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0008; (* Droplet stream velocity HH trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedDropletDiam_um <= 18.0) AND (iState >= 40) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0010; (* Droplet diameter LL trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedDropletDiam_um >= 30.0) AND (iState >= 40) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0020; (* Droplet diameter HH trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedIFEUVPower_W <= 300.0) AND (iState = 90) AND tPowerStabTimer.Q THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0040; (* IF EUV power LL trip in production *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedIFEUVPower_W >= 650.0) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0080; (* IF EUV power HH trip *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rStannaneRGA_PartialPress_Pa >= 0.15) THEN")
    lines.append("    dwAlarmWord_2 := dwAlarmWord_2 OR 16#0000_0100; (* Stannane SnH4 partial pressure HH trip *)")
    lines.append("END_IF;")
    lines.append("")

    lines.append("(* Evaluate Master Plant Trip Status *)")
    lines.append("bSystemTripped := (dwAlarmWord_1 <> 16#0000_0000) OR (dwAlarmWord_2 <> 16#0000_0000);")
    lines.append("IF bSystemTripped THEN")
    lines.append("    dwAlarmWord_1 := dwAlarmWord_1 OR 16#0000_8000; (* Master trip latch bit *)")
    lines.append("    iState := 120; (* Immediate Emergency Lockout State *)")
    lines.append("END_IF;")
    lines.append("")

    lines.append("(* 5.4 Operating Boundary Pre-Alarm Warnings with Deadband (dwWarningWord_2) *)")
    lines.append("IF (rVotedMirrorCenterTemp_DegC >= 62.0) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0001; (* Collector center temp High Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedMirrorCenterTemp_DegC <= 55.0) AND (iState >= 80) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0002; (* Collector center temp Low Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedVesselPressure_Pa >= 5.0) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0004; (* Vessel pressure High Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedVesselPressure_Pa <= 2.0) AND (iState >= 60) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0008; (* Vessel pressure Low Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rHydrogenGasDetector_LEL >= 10.0) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0010; (* Ambient H2 concentration High Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rDropletPosJitter_um >= 1.2) AND (iState >= 50) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0020; (* Droplet positional jitter High Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedIFEUVPower_W >= 550.0) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0040; (* IF EUV power High Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rVotedIFEUVPower_W <= 450.0) AND (iState = 90) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0080; (* IF EUV power Low Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rTinReservoirTemp_DegC >= 265.0) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0100; (* Tin reservoir temp High Warning *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF (rTinReservoirTemp_DegC <= 255.0) AND (iState >= 20) THEN")
    lines.append("    dwWarningWord_2 := dwWarningWord_2 OR 16#0000_0200; (* Tin reservoir temp Low Warning *)")
    lines.append("END_IF;")
    lines.append("")

    lines.append("(* 5.5 Bit-Packed Subsystem Diagnostic Word (dwDiagnosticStatus) *)")
    lines.append("IF bSystemRunning THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0001; END_IF;")
    lines.append("IF bSystemReady THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0002; END_IF;")
    lines.append("IF bEUVLightEmitting THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0004; END_IF;")
    lines.append("IF bPlasmaIgnited THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0008; END_IF;")
    lines.append("IF bDropletStreamLocked THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0010; END_IF;")
    lines.append("IF bTMRDegradedMode THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0020; END_IF;")
    lines.append("IF bCriticalTripActive THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0040; END_IF;")
    lines.append("IF bTurbopumpsOnline THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0080; END_IF;")
    lines.append("IF (iState >= 20) THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0100; END_IF;")
    lines.append("IF (iState >= 40) THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0200; END_IF;")
    lines.append("IF (iState >= 60) THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0400; END_IF;")
    lines.append("IF (iState >= 70) THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_0800; END_IF;")
    lines.append("IF (iState >= 80) THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_1000; END_IF;")
    lines.append("IF (iState = 90) THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_2000; END_IF;")
    lines.append("IF (iState = 100) THEN dwDiagnosticStatus := dwDiagnosticStatus OR 16#0000_4000; END_IF;")
    lines.append("")

    lines.append("(* Reset first scan latch *)")
    lines.append("bFirstScan := FALSE;")
    lines.append("")
    lines.append("END_FUNCTION_BLOCK")

    return "\n".join(lines)
