    lines.append("(* Real-time unrolled Projected Gradient Descent (PGD) quadratic program optimizing *)")
    lines.append("(* 8 multivariable actuators against 16 states, enforcing actuator box & slew limits. *)")
    lines.append("")

    # 3.1 Stage-Dependent Reference Setpoint Trajectory
    lines.append("(* 3.1 Load Stage-Dependent Reference Setpoint Trajectory *)")
    lines.append("IF (iState = 70) THEN")
    lines.append("    (* Pre-Pulse Alignment Stage: Cold pancake discs, no main ionization *)")
    lines.append("    aSetpoint_ref[1] := 0.0;    (* PosX_um *)")
    lines.append("    aSetpoint_ref[2] := 0.0;    (* PosY_um *)")
    lines.append("    aSetpoint_ref[3] := 0.0;    (* PosZ_um *)")
    lines.append("    aSetpoint_ref[4] := 75.0;   (* Vel_mps *)")
    lines.append("    aSetpoint_ref[5] := 24.0;   (* Diam_um *)")
    lines.append("    aSetpoint_ref[6] := 140.0;  (* PancakeDiam_um *)")
    lines.append("    aSetpoint_ref[7] := 2.5;    (* Te_eV *)")
    lines.append("    aSetpoint_ref[8] := 0.05;   (* ne_1e19cm3 *)")
    lines.append("    aSetpoint_ref[9] := 0.0;    (* EUV_Plasma_W *)")
    lines.append("    aSetpoint_ref[10] := 0.0;   (* EUV_IF_W *)")
    lines.append("    aSetpoint_ref[11] := 35.0;  (* T_Center_DegC *)")
    lines.append("    aSetpoint_ref[12] := 34.0;  (* T_Mid_DegC *)")
    lines.append("    aSetpoint_ref[13] := 32.0;  (* T_Outer_DegC *)")
    lines.append("    aSetpoint_ref[14] := 2.5;   (* P_Vessel_Pa *)")
    lines.append("    aSetpoint_ref[15] := 0.0;   (* Sn_IonFlux *)")
    lines.append("    aSetpoint_ref[16] := 0.005; (* SnH4_Rate *)")
    lines.append("ELSIF (iState = 80) THEN")
    lines.append("    (* Main-Pulse Plasma Ignition: Initial plasma breakdown & light capture *)")
    lines.append("    aSetpoint_ref[1] := 0.0;")
    lines.append("    aSetpoint_ref[2] := 0.0;")
    lines.append("    aSetpoint_ref[3] := 0.0;")
    lines.append("    aSetpoint_ref[4] := 75.0;")
    lines.append("    aSetpoint_ref[5] := 24.0;")
    lines.append("    aSetpoint_ref[6] := 195.0;")
    lines.append("    aSetpoint_ref[7] := 28.5;")
    lines.append("    aSetpoint_ref[8] := 0.90;")
    lines.append("    aSetpoint_ref[9] := 950.0;")
    lines.append("    aSetpoint_ref[10] := 320.0;")
    lines.append("    aSetpoint_ref[11] := 52.0;")
    lines.append("    aSetpoint_ref[12] := 50.0;")
    lines.append("    aSetpoint_ref[13] := 48.0;")
    lines.append("    aSetpoint_ref[14] := 3.2;")
    lines.append("    aSetpoint_ref[15] := 1.2E12;")
    lines.append("    aSetpoint_ref[16] := 0.025;")
    lines.append("ELSIF (iState = 90) THEN")
    lines.append("    (* Closed-Loop 500W In-Band EUV Production: Full MPC power stabilization *)")
    lines.append("    aSetpoint_ref[1] := 0.0;            (* PosX locked to PlaP center *)")
    lines.append("    aSetpoint_ref[2] := 0.0;            (* PosY locked to PlaP center *)")
    lines.append("    aSetpoint_ref[3] := 0.0;            (* Flight timing synchronization *)")
    lines.append("    aSetpoint_ref[4] := 75.0;           (* 75.0 m/s droplet stream *)")
    lines.append("    aSetpoint_ref[5] := 24.0;           (* 24.0 um nominal droplet *)")
    lines.append("    aSetpoint_ref[6] := 210.0;          (* 210 um expanded pancake *)")
    lines.append("    aSetpoint_ref[7] := 34.5;           (* 34.5 eV electron temperature *)")
    lines.append("    aSetpoint_ref[8] := 1.05;           (* Critical electron density *)")
    lines.append("    aSetpoint_ref[9] := 1420.0;         (* 1,420 W in-band 2pi EUV *)")
    lines.append("    aSetpoint_ref[10] := 500.0;         (* Exactly 500.0 W at IF *)")
    lines.append("    aSetpoint_ref[11] := 60.0;          (* Collector center 60.0 deg C *)")
    lines.append("    aSetpoint_ref[12] := 58.5;          (* Collector mid-zone *)")
    lines.append("    aSetpoint_ref[13] := 56.0;          (* Collector outer rim *)")
    lines.append("    aSetpoint_ref[14] := 3.5;           (* 3.5 Pa H2 buffer gas *)")
    lines.append("    aSetpoint_ref[15] := 8.5E11;        (* Deflected tin ion flux *)")
    lines.append("    aSetpoint_ref[16] := 0.045;         (* 0.045 nm/s chemical etch *)")
    lines.append("ELSIF (iState = 100) THEN")
    lines.append("    (* Collector In-Situ Debris Etch & Mirror Conditioning *)")
    lines.append("    aSetpoint_ref[1] := 0.0;")
    lines.append("    aSetpoint_ref[2] := 0.0;")
    lines.append("    aSetpoint_ref[3] := 0.0;")
    lines.append("    aSetpoint_ref[4] := 75.0;")
    lines.append("    aSetpoint_ref[5] := 24.0;")
    lines.append("    aSetpoint_ref[6] := 180.0;")
    lines.append("    aSetpoint_ref[7] := 30.0;")
    lines.append("    aSetpoint_ref[8] := 0.85;")
    lines.append("    aSetpoint_ref[9] := 1150.0;")
    lines.append("    aSetpoint_ref[10] := 420.0;")
    lines.append("    aSetpoint_ref[11] := 62.0;          (* Elevated temp accelerates SnH4 desorption *)")
    lines.append("    aSetpoint_ref[12] := 60.5;")
    lines.append("    aSetpoint_ref[13] := 58.0;")
    lines.append("    aSetpoint_ref[14] := 4.8;           (* Elevated H2 partial pressure *)")
    lines.append("    aSetpoint_ref[15] := 4.5E11;")
    lines.append("    aSetpoint_ref[16] := 0.085;         (* High chemical etch rate *)")
    lines.append("ELSE")
    lines.append("    (* Standby / Safe Parked Setpoints *)")
    for i in range(1, 17):
        lines.append(f"    aSetpoint_ref[{i}] := 0.0;")
    lines.append("END_IF;")
    lines.append("")

    # 3.2 Quadratic penalty weights Q and R
    lines.append("(* 3.2 Quadratic State Tracking Weights Q[1..16] and Actuator Effort Weights R[1..8] *)")
    q_weights = [120.0, 120.0, 50.0, 45.0, 30.0, 65.0, 85.0, 70.0, 95.0, 250.0, 180.0, 150.0, 110.0, 80.0, 90.0, 40.0]
    for i, w in enumerate(q_weights, start=1):
        lines.append(f"aWeight_Q[{i}] := {w:.1f};")

    r_weights = [1.5, 2.0, 0.8, 1.2, 3.5, 5.0, 5.0, 0.5]
    for j, w in enumerate(r_weights, start=1):
        lines.append(f"aWeight_R[{j}] := {w:.1f};")

    lines.append("")

    # 3.3 Projected Gradient Descent (PGD) optimization (Iteration 1)
    lines.append("(* 3.3 Projected Gradient Descent Optimization Iterations *)")
    for iter_num in range(1, 3+1):
        lines.append(f"(* --- PGD Optimization Iteration {iter_num} of 3 --- *)")
        for j in range(1, 8+1):
            grad_terms = []
            for i in range(1, 17):
                grad_terms.append(f"(2.0 * aMatrix_B[{i},{j}] * aWeight_Q[{i}] * (aState_x[{i}] - aSetpoint_ref[{i}]))")
            grad_expr = " + ".join(grad_terms)
            lines.append(f"aGrad_J[{j}] := ({grad_expr}) + (2.0 * aWeight_R[{j}] * aControl_u[{j}]);")
            # Step update with learning rate 0.0005
            lines.append(f"aStep_u[{j}] := aControl_u[{j}] - (0.0005 * aGrad_J[{j}]);")

        # Actuator box bounds
        lines.append("(* Actuator Box Constraints Hard Projection *)")
        lines.append("IF aStep_u[1] < -2.5 THEN aStep_u[1] := -2.5; END_IF; (* u1: Piezo Freq Trim kHz *)")
        lines.append("IF aStep_u[1] >  2.5 THEN aStep_u[1] :=  2.5; END_IF;")
        lines.append("IF aStep_u[2] < -15.0 THEN aStep_u[2] := -15.0; END_IF; (* u2: Piezo Volt Trim V *)")
        lines.append("IF aStep_u[2] >  15.0 THEN aStep_u[2] :=  15.0; END_IF;")
        lines.append("IF aStep_u[3] < -20.0 THEN aStep_u[3] := -20.0; END_IF; (* u3: Tin Press Trim bar *)")
        lines.append("IF aStep_u[3] >  20.0 THEN aStep_u[3] :=  20.0; END_IF;")
        lines.append("IF aStep_u[4] < -8.0 THEN aStep_u[4] := -8.0; END_IF; (* u4: PrePulse Energy Trim mJ *)")
        lines.append("IF aStep_u[4] >  8.0 THEN aStep_u[4] :=  8.0; END_IF;")
        lines.append("IF aStep_u[5] < -0.30 THEN aStep_u[5] := -0.30; END_IF; (* u5: MainPulse Energy Trim J *)")
        lines.append("IF aStep_u[5] >  0.30 THEN aStep_u[5] :=  0.30; END_IF;")
        lines.append("IF aStep_u[6] < -25.0 THEN aStep_u[6] := -25.0; END_IF; (* u6: Galvo Steer X urad *)")
        lines.append("IF aStep_u[6] >  25.0 THEN aStep_u[6] :=  25.0; END_IF;")
        lines.append("IF aStep_u[7] < -25.0 THEN aStep_u[7] := -25.0; END_IF; (* u7: Galvo Steer Y urad *)")
        lines.append("IF aStep_u[7] >  25.0 THEN aStep_u[7] :=  25.0; END_IF;")
        lines.append("IF aStep_u[8] < -40.0 THEN aStep_u[8] := -40.0; END_IF; (* u8: H2 Gas Flow Trim slpm *)")
        lines.append("IF aStep_u[8] >  40.0 THEN aStep_u[8] :=  40.0; END_IF;")
        for j in range(1, 8+1):
            lines.append(f"aControl_u[{j}] := aStep_u[{j}];")
        lines.append("")

    # 3.4 Slew Rate Limiting and Plant Feed-Forward Coordination
    lines.append("(* 3.4 Actuator Slew Rate Limiting & Nominal Centerline Integration *)")
    lines.append("IF (iState = 90) OR (iState = 80) OR (iState = 70) OR (iState = 100) THEN")
    lines.append("    rTargetPiezoFreq_kHz := 50.0 + aControl_u[1];")
    lines.append("    rTargetPiezoVolt_V := 32.0 + aControl_u[2];")
    lines.append("    rTargetTinPress_bar := 82.5 + aControl_u[3];")
    lines.append("    rTargetPrePulse_mJ := 18.5 + aControl_u[4];")
    lines.append("    rTargetMainPulse_J := 0.95 + aControl_u[5];")
    lines.append("    rTargetGalvoSteerX_urad := aControl_u[6];")
    lines.append("    rTargetGalvoSteerY_urad := aControl_u[7];")
    lines.append("    rTargetH2Flow_slpm := 150.0 + aControl_u[8];")
    lines.append("    rTargetInterPulseDelay_us := 2.80 + (0.015 * aControl_u[4]);")
    lines.append("ELSE")
    lines.append("    rTargetPiezoFreq_kHz := 50.0;")
    lines.append("    rTargetPiezoVolt_V := 0.0;")
    lines.append("    rTargetTinPress_bar := 0.0;")
    lines.append("    rTargetPrePulse_mJ := 0.0;")
    lines.append("    rTargetMainPulse_J := 0.0;")
    lines.append("    rTargetGalvoSteerX_urad := 0.0;")
    lines.append("    rTargetGalvoSteerY_urad := 0.0;")
    lines.append("    rTargetH2Flow_slpm := 20.0;")
    lines.append("    rTargetInterPulseDelay_us := 2.80;")
    lines.append("END_IF;")
    lines.append("")

    lines.append("(* Enforce Actuator Physical Slew Limiters *)")
    lines.append("IF rPiezoFrequencyCmd_kHz < (rTargetPiezoFreq_kHz - (rMaxSlewPiezoFreq_kHz_s * rCycleTime_sec)) THEN")
    lines.append("    rPiezoFrequencyCmd_kHz := rPiezoFrequencyCmd_kHz + (rMaxSlewPiezoFreq_kHz_s * rCycleTime_sec);")
    lines.append("ELSIF rPiezoFrequencyCmd_kHz > (rTargetPiezoFreq_kHz + (rMaxSlewPiezoFreq_kHz_s * rCycleTime_sec)) THEN")
    lines.append("    rPiezoFrequencyCmd_kHz := rPiezoFrequencyCmd_kHz - (rMaxSlewPiezoFreq_kHz_s * rCycleTime_sec);")
    lines.append("ELSE")
    lines.append("    rPiezoFrequencyCmd_kHz := rTargetPiezoFreq_kHz;")
    lines.append("END_IF;")
    lines.append("")

    lines.append("IF rPiezoVoltageCmd_V < (rTargetPiezoVolt_V - (rMaxSlewPiezoVolt_V_s * rCycleTime_sec)) THEN")
    lines.append("    rPiezoVoltageCmd_V := rPiezoVoltageCmd_V + (rMaxSlewPiezoVolt_V_s * rCycleTime_sec);")
    lines.append("ELSIF rPiezoVoltageCmd_V > (rTargetPiezoVolt_V + (rMaxSlewPiezoVolt_V_s * rCycleTime_sec)) THEN")
    lines.append("    rPiezoVoltageCmd_V := rPiezoVoltageCmd_V - (rMaxSlewPiezoVolt_V_s * rCycleTime_sec);")
    lines.append("ELSE")
    lines.append("    rPiezoVoltageCmd_V := rTargetPiezoVolt_V;")
    lines.append("END_IF;")
    lines.append("")

    lines.append("IF rTinPressureCmd_bar < (rTargetTinPress_bar - (rMaxSlewTinPress_bar_s * rCycleTime_sec)) THEN")
    lines.append("    rTinPressureCmd_bar := rTinPressureCmd_bar + (rMaxSlewTinPress_bar_s * rCycleTime_sec);")
    lines.append("ELSIF rTinPressureCmd_bar > (rTargetTinPress_bar + (rMaxSlewTinPress_bar_s * rCycleTime_sec)) THEN")
    lines.append("    rTinPressureCmd_bar := rTinPressureCmd_bar - (rMaxSlewTinPress_bar_s * rCycleTime_sec);")
    lines.append("ELSE")
    lines.append("    rTinPressureCmd_bar := rTargetTinPress_bar;")
    lines.append("END_IF;")
    lines.append("")

    lines.append("IF rPrePulseEnergyCmd_mJ < (rTargetPrePulse_mJ - (rMaxSlewPrePulse_mJ_s * rCycleTime_sec)) THEN")
    lines.append("    rPrePulseEnergyCmd_mJ := rPrePulseEnergyCmd_mJ + (rMaxSlewPrePulse_mJ_s * rCycleTime_sec);")
