    lines.append("    rMainPulseEnergyCmd_J := rMainPulseEnergyCmd_J + (rMaxSlewMainPulse_J_s * rCycleTime_sec);")
    lines.append("ELSIF rMainPulseEnergyCmd_J > (rTargetMainPulse_J + (rMaxSlewMainPulse_J_s * rCycleTime_sec)) THEN")
    lines.append("    rMainPulseEnergyCmd_J := rMainPulseEnergyCmd_J - (rMaxSlewMainPulse_J_s * rCycleTime_sec);")
    lines.append("ELSE")
    lines.append("    rMainPulseEnergyCmd_J := rTargetMainPulse_J;")
    lines.append("END_IF;")
    lines.append("")

    lines.append("rInterPulseDelayCmd_us := rTargetInterPulseDelay_us;")
    lines.append("rGalvoSteerX_urad := rTargetGalvoSteerX_urad;")
    lines.append("rGalvoSteerY_urad := rTargetGalvoSteerY_urad;")
    lines.append("")

    lines.append("IF rH2MassFlowCmd_slpm < (rTargetH2Flow_slpm - (rMaxSlewH2Flow_slpm_s * rCycleTime_sec)) THEN")
    lines.append("    rH2MassFlowCmd_slpm := rH2MassFlowCmd_slpm + (rMaxSlewH2Flow_slpm_s * rCycleTime_sec);")
    lines.append("ELSIF rH2MassFlowCmd_slpm > (rTargetH2Flow_slpm + (rMaxSlewH2Flow_slpm_s * rCycleTime_sec)) THEN")
    lines.append("    rH2MassFlowCmd_slpm := rH2MassFlowCmd_slpm - (rMaxSlewH2Flow_slpm_s * rCycleTime_sec);")
    lines.append("ELSE")
    lines.append("    rH2MassFlowCmd_slpm := rTargetH2Flow_slpm;")
    lines.append("END_IF;")
    lines.append("")

    lines.append("(* Collector Mirror Multi-Zone Closed-Loop Proportional Coolant Valve Command *)")
    lines.append("rTargetMirrorCoolingFlow_Pct := 45.0 + (12.5 * (rVotedMirrorCenterTemp_DegC - 60.0)) + (4.5 * (rMeasuredEUVPower_IF_W / 500.0));")
    lines.append("IF rTargetMirrorCoolingFlow_Pct < 5.0 THEN rTargetMirrorCoolingFlow_Pct := 5.0; END_IF;")
    lines.append("IF rTargetMirrorCoolingFlow_Pct > 100.0 THEN rTargetMirrorCoolingFlow_Pct := 100.0; END_IF;")
    lines.append("rMirrorCoolingValveCmd_Pct := rTargetMirrorCoolingFlow_Pct;")
    lines.append("")

    return "\n".join(lines)
