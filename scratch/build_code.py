    st_lines.append("(* --- Channel 4: Syngas H2/CO Molar Ratio 2oo3 Voting --- *)")
    st_lines.append("bRatio_SensorA_Valid := (rSyngasRatio_H2_CO_A_molmol >= 0.15) AND (rSyngasRatio_H2_CO_A_molmol <= 4.50);")
