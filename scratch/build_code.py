    st_lines.append("ELSIF bFilterDP_SensorA_Valid AND bFilterDP_SensorB_Valid THEN")
    st_lines.append("    rVotedFilterDiffPress_mbar := (rCeramicFilterDiffPress_A_mbar + rCeramicFilterDiffPress_B_mbar) * 0.5;")
    st_lines.append("    bFilterDP_Degraded_1oo2 := TRUE;")
    st_lines.append("ELSE")
    st_lines.append("    rVotedFilterDiffPress_mbar := 45.0;")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* Sensor degradation composite flag *)")
    st_lines.append("bDegradedSensorMode := bHearth_Degraded_1oo2 OR bFreeboard_Degraded_1oo2 OR")
    st_lines.append("                       bPress_Degraded_1oo2 OR bRatio_Degraded_1oo2 OR bFilterDP_Degraded_1oo2;")
    st_lines.append("")
    st_lines.append("(* ========================================================================================= *)")
    st_lines.append("(* 3.0 SLAG TAPHOLE INDUCTION FREEZE-LINING STEFAN THERMAL EQUILIBRIUM SOLVER                *)")
    st_lines.append("(* ========================================================================================= *)")
    st_lines.append("(* Computes 1D transient boundary phase change at taphole copper stave / molten slag bath.   *)")
    st_lines.append("(* Preserves a protective autogenous skull (15-35 mm) against aggressive corrosive slag,    *)")
    st_lines.append("(* dynamically balancing stave forced-water cooling against mid-frequency induction heating.*)")
    st_lines.append("")
    st_lines.append("(* Calculate convective heat flux from liquid slag bath to solidus interface *)")
    st_lines.append("IF rVotedHearthSlagTemp_DegC > rSlagLiquidusTemp_DegC THEN")
    st_lines.append("    rHeatFluxInward_Wm2 := rSlagConvectiveCoeff_Wm2K * (rVotedHearthSlagTemp_DegC - rSlagSolidusTemp_DegC);")
    st_lines.append("ELSE")
    st_lines.append("    rHeatFluxInward_Wm2 := 1500.0; (* Minimum convective creep *)")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* Clamp thickness to prevent division by zero in conduction formula *)")
    st_lines.append("IF rCalculatedLiningThickness_m < 0.002 THEN")
    st_lines.append("    rCalculatedLiningThickness_m := 0.002; (* 2mm minimum refractory skin *)")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* Calculate outward conductive heat flux extracted through frozen slag & copper stave *)")
    st_lines.append("(* Total thermal resistance: R_total = (s_skull / k_skull) + (s_copper / k_copper) + (1 / h_coolant) *)")
    st_lines.append("rHeatFluxOutward_Wm2 := (rSlagSolidusTemp_DegC - rTapholeCoolingReturnTemp_DegC) /")
    st_lines.append("    ((rCalculatedLiningThickness_m / rSlagThermalConductivity_WmK) +")
    st_lines.append("     (rCopperStaveThickness_m / rCopperStaveConductivity_WmK) +")
    st_lines.append("     (1.0 / rCoolantHeatTransferCoeff_Wm2K));")
    st_lines.append("")
    st_lines.append("(* Induction power energy deposition at taphole interior perimeter *)")
    st_lines.append("(* P_induction deposits volumetric Joule heating in the near-boundary slag zone *)")
    st_lines.append("IF bInductionActive AND (rInductionCoilPowerDemand_kW > 0.0) THEN")
    st_lines.append("    (* Effective surface heat flux equivalent: P_kW * 1000 / A_taphole (A_taphole approx 0.35 m2) *)")
    st_lines.append("    rHeatFluxInward_Wm2 := rHeatFluxInward_Wm2 + (rInductionCoilPowerDemand_kW * 1000.0 / 0.35);")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* Stefan phase change interface velocity: ds/dt = (Q_outward - Q_inward) / (rho * L_fus) *)")
    st_lines.append("rStefanFrontVelocity_ms := (rHeatFluxOutward_Wm2 - rHeatFluxInward_Wm2) / (rSlagDensity_kgm3 * (rSlagLatentHeat_kJkg * 1000.0));")
    st_lines.append("")
    st_lines.append("(* Integrate freeze-lining thickness over deterministic cycle time *)")
    st_lines.append("rCalculatedLiningThickness_m := rCalculatedLiningThickness_m + (rStefanFrontVelocity_ms * rCycleTime_sec);")
    st_lines.append("IF rCalculatedLiningThickness_m > 0.080 THEN rCalculatedLiningThickness_m := 0.080; END_IF; (* 80mm Max *)")
    st_lines.append("IF rCalculatedLiningThickness_m < 0.001 THEN rCalculatedLiningThickness_m := 0.001; END_IF; (* 1mm Min *)")
    st_lines.append("rEstimatedFreezeLiningThickness_mm := rCalculatedLiningThickness_m * 1000.0;")
    st_lines.append("")
    st_lines.append("(* Closed-Loop Induction Coil Power Regulation for Freeze-Lining Equilibrium *)")
    st_lines.append("IF bInductionPermissive AND (iState >= 40) AND (iState < 90) THEN")
    st_lines.append("    bInductionActive := TRUE;")
    st_lines.append("    (* If freeze lining is thicker than target, increase induction power to melt back *)")
    st_lines.append("    (* Error = Estimated - Target *)")
    st_lines.append("    rInduction_Integral := rInduction_Integral + (rInduction_Ki * (rEstimatedFreezeLiningThickness_mm - rFreezeLiningTarget_mm) * rCycleTime_sec);")
    st_lines.append("    IF rInduction_Integral > rInduction_MaxPower_kW THEN rInduction_Integral := rInduction_MaxPower_kW; END_IF;")
    st_lines.append("    IF rInduction_Integral < 0.0 THEN rInduction_Integral := 0.0; END_IF;")
    st_lines.append("    ")
    st_lines.append("    rInductionCoilPowerDemand_kW := (rInduction_Kp * (rEstimatedFreezeLiningThickness_mm - rFreezeLiningTarget_mm)) + rInduction_Integral;")
    st_lines.append("    ")
    st_lines.append("    (* Viscosity Compensation Trim: high viscosity demands additional induction heat *)")
    st_lines.append("    IF rTapholeSlagViscosity_Pas > 15.0 THEN")
    st_lines.append("        rInductionCoilPowerDemand_kW := rInductionCoilPowerDemand_kW + ((rTapholeSlagViscosity_Pas - 15.0) * 3.5);")
    st_lines.append("    END_IF;")
    st_lines.append("    ")
    st_lines.append("    IF rInductionCoilPowerDemand_kW > rInduction_MaxPower_kW THEN rInductionCoilPowerDemand_kW := rInduction_MaxPower_kW; END_IF;")
    st_lines.append("    IF rInductionCoilPowerDemand_kW < 0.0 THEN rInductionCoilPowerDemand_kW := 0.0; END_IF;")
    st_lines.append("ELSE")
    st_lines.append("    bInductionActive := FALSE;")
    st_lines.append("    rInductionCoilPowerDemand_kW := 0.0;")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* Dynamic Taphole Copper Cooling Pump Control *)")
    st_lines.append("rCoolingPump_Integral := rCoolingPump_Integral + (rCoolingPump_Ki * (rTapholeCopperTemp_DegC - 85.0) * rCycleTime_sec);")
    st_lines.append("IF rCoolingPump_Integral > 30.0 THEN rCoolingPump_Integral := 30.0; END_IF;")
    st_lines.append("IF rCoolingPump_Integral < 5.0 THEN rCoolingPump_Integral := 5.0; END_IF;")
    st_lines.append("rTapholeCoolingFlowDemand_m3h := (rCoolingPump_Kp * (rTapholeCopperTemp_DegC - 85.0)) + rCoolingPump_Integral;")
    st_lines.append("IF rTapholeCoolingFlowDemand_m3h > 30.0 THEN rTapholeCoolingFlowDemand_m3h := 30.0; END_IF;")
    st_lines.append("IF rTapholeCoolingFlowDemand_m3h < 5.0 THEN rTapholeCoolingFlowDemand_m3h := 5.0; END_IF;")
    st_lines.append("")
    st_lines.append("(* Freeze-Lining Alarm Hazards *)")
    st_lines.append("IF rEstimatedFreezeLiningThickness_mm < 8.0 THEN")
    st_lines.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0010; (* Freeze lining dangerously thin: erosion hazard *)")
    st_lines.append("END_IF;")
    st_lines.append("IF rEstimatedFreezeLiningThickness_mm > 55.0 THEN")
    st_lines.append("    dwWarningWord := dwWarningWord OR 16#0000_0080; (* Taphole choking / freeze-lock warning *)")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* ========================================================================================= *)")
    st_lines.append("(* 4.0 MODEL PREDICTIVE CONTROL (MPC) SYNGAS RATIO & STOICHIOMETRIC REGULATOR               *)")
    st_lines.append("(* ========================================================================================= *)")
    st_lines.append("(* Solves dynamic multivariable cross-coupling between Secondary Oxygen, Superheated Steam, *)")
    st_lines.append("(* and Plasma DC Torch Power. Optimizes H2/CO molar ratio, gasifier freeboard temperature,   *)")
    st_lines.append("(* dome pressure, and Syngas LHV via quadratic cost minimization over receding horizon.    *)")
    st_lines.append("")
    st_lines.append("IF bAutoRatioMode AND bSystemRunning AND (iState >= 60) AND (iState < 90) THEN")
    st_lines.append("    (* 4.1 Compute State Tracking Deviations *)")
    st_lines.append("    rStateX_0 := rVotedFreeboardTemp_DegC - rTargetFreeboardTemp_DegC;      (* Temp error [deg C] *)")
    st_lines.append("    rStateX_1 := rCalculatedSyngasRatio_molmol - rTargetSyngasRatio_molmol;  (* Ratio error [mol/mol] *)")
    st_lines.append("    rStateX_2 := rVotedVesselPressure_bar - rTargetVesselPress_bar;          (* Press error [bar] *)")
    st_lines.append("    rStateX_3 := rSyngasLowerHeatingValue_MJNm3 - 8.50;                     (* LHV deviation [MJ/Nm3] *)")
    st_lines.append("    ")
    st_lines.append("    (* 4.2 Disturbance Estimation (Waste Feed & Moisture Swings) *)")
    st_lines.append("    rDistD_0 := (rSolidWasteFeedRate_kgh - 1500.0) / 1000.0;                (* Normalized feed disturbance *)")
    st_lines.append("    rDistD_1 := (rWasteMoistureContent_pct - 20.0) / 10.0;                  (* Normalized moisture disturbance *)")
    st_lines.append("    ")
    st_lines.append("    (* 4.3 State Space Prediction: x_next = A * x + B * u_delta + E * d *)")
    st_lines.append("    (* Normalized Delta Control Inputs relative to operating nominals *)")
    st_lines.append("    rPredX_0 := (rMatA_00 * rStateX_0) + (rMatA_01 * rStateX_1) + (rMatA_02 * rStateX_2) + (rMatA_03 * rStateX_3) +")
    st_lines.append("                (rMatB_00 * (rControlU_0 - 650.0) * 0.01) + (rMatB_01 * (rControlU_1 - 1200.0) * 0.005) + (rMatB_02 * (rControlU_2 - 850.0) * 0.01) +")
    st_lines.append("                (rMatE_00 * rDistD_0) + (rMatE_01 * rDistD_1);")
    st_lines.append("                ")
    st_lines.append("    rPredX_1 := (rMatA_10 * rStateX_0) + (rMatA_11 * rStateX_1) + (rMatA_12 * rStateX_2) + (rMatA_13 * rStateX_3) +")
    st_lines.append("                (rMatB_10 * (rControlU_0 - 650.0) * 0.01) + (rMatB_11 * (rControlU_1 - 1200.0) * 0.005) + (rMatB_12 * (rControlU_2 - 850.0) * 0.01) +")
    st_lines.append("                (rMatE_10 * rDistD_0) + (rMatE_11 * rDistD_1);")
    st_lines.append("                ")
    st_lines.append("    rPredX_2 := (rMatA_20 * rStateX_0) + (rMatA_21 * rStateX_1) + (rMatA_22 * rStateX_2) + (rMatA_23 * rStateX_3) +")
    st_lines.append("                (rMatB_20 * (rControlU_0 - 650.0) * 0.01) + (rMatB_21 * (rControlU_1 - 1200.0) * 0.005) + (rMatB_22 * (rControlU_2 - 850.0) * 0.01) +")
    st_lines.append("                (rMatE_20 * rDistD_0) + (rMatE_21 * rDistD_1);")
    st_lines.append("                ")
    st_lines.append("    rPredX_3 := (rMatA_30 * rStateX_0) + (rMatA_31 * rStateX_1) + (rMatA_32 * rStateX_2) + (rMatA_33 * rStateX_3) +")
    st_lines.append("                (rMatB_30 * (rControlU_0 - 650.0) * 0.01) + (rMatB_31 * (rControlU_1 - 1200.0) * 0.005) + (rMatB_32 * (rControlU_2 - 850.0) * 0.01) +")
    st_lines.append("                (rMatE_30 * rDistD_0) + (rMatE_31 * rDistD_1);")
    st_lines.append("                ")
    st_lines.append("    (* 4.4 Analytical Quadratic Cost Gradient: Grad_J = B^T * Q * x_pred + R * u + S * (u - u_prev) *)")
    st_lines.append("    rGradJ_0 := (rMatB_00 * rWeightQ_Temp * rPredX_0) + (rMatB_10 * rWeightQ_Ratio * rPredX_1) +")
    st_lines.append("                (rMatB_20 * rWeightQ_Press * rPredX_2) + (rMatB_30 * rWeightQ_LHV * rPredX_3) +")
    st_lines.append("                (rWeightR_O2 * (rControlU_0 - 650.0) * 0.01) + (rWeightS_O2 * (rControlU_0 - rControlU_Prev_0) * 0.05);")
    st_lines.append("                ")
    st_lines.append("    rGradJ_1 := (rMatB_01 * rWeightQ_Temp * rPredX_0) + (rMatB_11 * rWeightQ_Ratio * rPredX_1) +")
    st_lines.append("                (rMatB_21 * rWeightQ_Press * rPredX_2) + (rMatB_31 * rWeightQ_LHV * rPredX_3) +")
    st_lines.append("                (rWeightR_Steam * (rControlU_1 - 1200.0) * 0.005) + (rWeightS_Steam * (rControlU_1 - rControlU_Prev_1) * 0.02);")
    st_lines.append("                ")
    st_lines.append("    rGradJ_2 := (rMatB_02 * rWeightQ_Temp * rPredX_0) + (rMatB_12 * rWeightQ_Ratio * rPredX_1) +")
    st_lines.append("                (rMatB_22 * rWeightQ_Press * rPredX_2) + (rMatB_32 * rWeightQ_LHV * rPredX_3) +")
    st_lines.append("                (rWeightR_Torch * (rControlU_2 - 850.0) * 0.01) + (rWeightS_Torch * (rControlU_2 - rControlU_Prev_2) * 0.05);")
    st_lines.append("                ")
    st_lines.append("    (* 4.5 Projected Gradient Descent Step *)")
    st_lines.append("    rControlU_Prev_0 := rControlU_0;")
    st_lines.append("    rControlU_Prev_1 := rControlU_1;")
    st_lines.append("    rControlU_Prev_2 := rControlU_2;")
    st_lines.append("    ")
    st_lines.append("    rControlU_0 := rControlU_0 - (rMpcStepSize * rGradJ_0 * 450.0);")
    st_lines.append("    rControlU_1 := rControlU_1 - (rMpcStepSize * rGradJ_1 * 850.0);")
    st_lines.append("    rControlU_2 := rControlU_2 - (rMpcStepSize * rGradJ_2 * 350.0);")
    st_lines.append("    ")
    st_lines.append("    (* 4.6 Slew Rate Limiting Enforcement *)")
    st_lines.append("    IF (rControlU_0 - rControlU_Prev_0) > (rMaxSlewO2_Nm3hs * rCycleTime_sec) THEN")
    st_lines.append("        rControlU_0 := rControlU_Prev_0 + (rMaxSlewO2_Nm3hs * rCycleTime_sec);")
    st_lines.append("    ELSIF (rControlU_Prev_0 - rControlU_0) > (rMaxSlewO2_Nm3hs * rCycleTime_sec) THEN")
    st_lines.append("        rControlU_0 := rControlU_Prev_0 - (rMaxSlewO2_Nm3hs * rCycleTime_sec);")
    st_lines.append("    END_IF;")
    st_lines.append("    ")
    st_lines.append("    IF (rControlU_1 - rControlU_Prev_1) > (rMaxSlewSteam_kghs * rCycleTime_sec) THEN")
    st_lines.append("        rControlU_1 := rControlU_Prev_1 + (rMaxSlewSteam_kghs * rCycleTime_sec);")
    st_lines.append("    ELSIF (rControlU_Prev_1 - rControlU_1) > (rMaxSlewSteam_kghs * rCycleTime_sec) THEN")
    st_lines.append("        rControlU_1 := rControlU_Prev_1 - (rMaxSlewSteam_kghs * rCycleTime_sec);")
    st_lines.append("    END_IF;")
    st_lines.append("    ")
    st_lines.append("    IF (rControlU_2 - rControlU_Prev_2) > (rMaxSlewTorch_kWs * rCycleTime_sec) THEN")
    st_lines.append("        rControlU_2 := rControlU_Prev_2 + (rMaxSlewTorch_kWs * rCycleTime_sec);")
    st_lines.append("    ELSIF (rControlU_Prev_2 - rControlU_2) > (rMaxSlewTorch_kWs * rCycleTime_sec) THEN")
    st_lines.append("        rControlU_2 := rControlU_Prev_2 - (rMaxSlewTorch_kWs * rCycleTime_sec);")
    st_lines.append("    END_IF;")
    st_lines.append("    ")
    st_lines.append("    (* 4.7 Hard Actuator Saturation Clamping *)")
    st_lines.append("    IF rControlU_0 > rMaxO2Flow_Nm3h THEN rControlU_0 := rMaxO2Flow_Nm3h; END_IF;")
    st_lines.append("    IF rControlU_0 < rMinO2Flow_Nm3h THEN rControlU_0 := rMinO2Flow_Nm3h; END_IF;")
    st_lines.append("    IF rControlU_1 > rMaxSteamFlow_kgh THEN rControlU_1 := rMaxSteamFlow_kgh; END_IF;")
    st_lines.append("    IF rControlU_1 < rMinSteamFlow_kgh THEN rControlU_1 := rMinSteamFlow_kgh; END_IF;")
    st_lines.append("    IF rControlU_2 > rMaxTorchPower_kW THEN rControlU_2 := rMaxTorchPower_kW; END_IF;")
    st_lines.append("    IF rControlU_2 < rMinTorchPower_kW THEN rControlU_2 := rMinTorchPower_kW; END_IF;")
    st_lines.append("    ")
    st_lines.append("    rOxygenFlowDemand_Nm3h := rControlU_0;")
    st_lines.append("    rSteamFlowDemand_kgh := rControlU_1;")
    st_lines.append("    rTorchPowerDemand_kW := rControlU_2;")
    st_lines.append("    ")
    st_lines.append("    (* 4.8 Compute Total Scalar MPC Objective Cost J *)")
    st_lines.append("    rMpcObjectiveCost := (rWeightQ_Temp * rPredX_0 * rPredX_0) +")
    st_lines.append("                         (rWeightQ_Ratio * rPredX_1 * rPredX_1) +")
    st_lines.append("                         (rWeightQ_Press * rPredX_2 * rPredX_2) +")
    st_lines.append("                         (rWeightQ_LHV * rPredX_3 * rPredX_3) +")
    st_lines.append("                         (rWeightR_O2 * (rControlU_0 - 650.0) * (rControlU_0 - 650.0) * 0.0001) +")
    st_lines.append("                         (rWeightR_Steam * (rControlU_1 - 1200.0) * (rControlU_1 - 1200.0) * 0.00002) +")
    st_lines.append("                         (rWeightR_Torch * (rControlU_2 - 850.0) * (rControlU_2 - 850.0) * 0.0001);")
    st_lines.append("    bMpcInOptimization := TRUE;")
    st_lines.append("ELSE")
    st_lines.append("    bMpcInOptimization := FALSE;")
    st_lines.append("    IF NOT bSystemRunning THEN")
    st_lines.append("        rOxygenFlowDemand_Nm3h := 0.0;")
    st_lines.append("        rSteamFlowDemand_kgh := 0.0;")
    st_lines.append("    END_IF;")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* ========================================================================================= *)")
    st_lines.append("(* 5.0 HIGH-TEMPERATURE CERAMIC CANDLE FILTER & PULSED-JET BACKWASH ENGINE                  *)")
    st_lines.append("(* ========================================================================================= *)")
    st_lines.append("(* Models compressible particulate cake deposition (Darcy-Forchheimer law) and manages      *)")
    st_lines.append("(* multi-manifold supersonic reverse pulse-jet blowback sequencing across 4 filter banks.    *)")
    st_lines.append("")
    st_lines.append("(* Gas face filtration superficial velocity: v_face = Q_syngas / A_filter *)")
    st_lines.append("(* Syngas actual volumetric flow [m3/s] at operating temperature & pressure *)")
    st_lines.append("IF rVotedVesselPressure_bar > 0.5 THEN")
    st_lines.append("    (* Actual m3/h = Nm3/h * (1.013 / P_bar) * ((T_inlet + 273.15) / 273.15) *)")
