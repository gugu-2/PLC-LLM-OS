    st_lines.append("        dwWarningWord := dwWarningWord OR 16#0000_0020; (* Dome pressure spread *)")
    st_lines.append("    END_IF;")
    st_lines.append("ELSIF bPress_SensorA_Valid AND bPress_SensorB_Valid THEN")
    st_lines.append("    rVotedVesselPressure_bar := (rGasifierVesselPress_A_bar + rGasifierVesselPress_B_bar) * 0.5;")
