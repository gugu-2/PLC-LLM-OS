    st_lines.append("bRatio_SensorC_Valid := (rSyngasRatio_H2_CO_C_molmol >= 0.15) AND (rSyngasRatio_H2_CO_C_molmol <= 4.50);")
    st_lines.append("")
    st_lines.append("IF bRatio_SensorA_Valid AND bRatio_SensorB_Valid AND bRatio_SensorC_Valid THEN")
    st_lines.append("    IF ((rSyngasRatio_H2_CO_A_molmol >= rSyngasRatio_H2_CO_B_molmol) AND (rSyngasRatio_H2_CO_A_molmol <= rSyngasRatio_H2_CO_C_molmol)) OR")
    st_lines.append("       ((rSyngasRatio_H2_CO_A_molmol >= rSyngasRatio_H2_CO_C_molmol) AND (rSyngasRatio_H2_CO_A_molmol <= rSyngasRatio_H2_CO_B_molmol)) THEN")
