    st_lines.append("    bPress_Degraded_1oo2 := TRUE;")
    st_lines.append("ELSE")
    st_lines.append("    rVotedVesselPressure_bar := 1.15; (* Fallback safe pressure *)")
    st_lines.append("    dwAlarmWord2 := dwAlarmWord2 OR 16#0000_0004; (* Complete Dome pressure sensor failure *)")
    st_lines.append("END_IF;")
