    st_lines.append("        rVotedVesselPressure_bar := rGasifierVesselPress_C_bar;")
    st_lines.append("    END_IF;")
    st_lines.append("    bPress_Degraded_1oo2 := FALSE;")
    st_lines.append("    ")
    st_lines.append("    IF (ABS(rGasifierVesselPress_A_bar - rGasifierVesselPress_B_bar) > rPressDiscrepancyThreshold_bar) OR")
    st_lines.append("       (ABS(rGasifierVesselPress_B_bar - rGasifierVesselPress_C_bar) > rPressDiscrepancyThreshold_bar) OR")
