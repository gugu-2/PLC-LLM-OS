    st_lines.append("          ((rSyngasRatio_H2_CO_B_molmol >= rSyngasRatio_H2_CO_C_molmol) AND (rSyngasRatio_H2_CO_B_molmol <= rSyngasRatio_H2_CO_A_molmol)) THEN")
    st_lines.append("        rCalculatedSyngasRatio_molmol := rSyngasRatio_H2_CO_B_molmol;")
    st_lines.append("    ELSE")
    st_lines.append("        rCalculatedSyngasRatio_molmol := rSyngasRatio_H2_CO_C_molmol;")
    st_lines.append("    END_IF;")
    st_lines.append("    bRatio_Degraded_1oo2 := FALSE;")
    st_lines.append("ELSIF bRatio_SensorA_Valid AND bRatio_SensorB_Valid THEN")
    st_lines.append("    rCalculatedSyngasRatio_molmol := (rSyngasRatio_H2_CO_A_molmol + rSyngasRatio_H2_CO_B_molmol) * 0.5;")
    st_lines.append("    bRatio_Degraded_1oo2 := TRUE;")
    st_lines.append("ELSIF bRatio_SensorA_Valid AND bRatio_SensorC_Valid THEN")
    st_lines.append("    rCalculatedSyngasRatio_molmol := (rSyngasRatio_H2_CO_A_molmol + rSyngasRatio_H2_CO_C_molmol) * 0.5;")
    st_lines.append("    bRatio_Degraded_1oo2 := TRUE;")
    st_lines.append("ELSIF bRatio_SensorB_Valid AND bRatio_SensorC_Valid THEN")
    st_lines.append("    rCalculatedSyngasRatio_molmol := (rSyngasRatio_H2_CO_B_molmol + rSyngasRatio_H2_CO_C_molmol) * 0.5;")
    st_lines.append("    bRatio_Degraded_1oo2 := TRUE;")
    st_lines.append("ELSE")
    st_lines.append("    (* Analytical fallback based on feed composition and stoichiometry *)")
    st_lines.append("    rCalculatedSyngasRatio_molmol := 1.85;")
    st_lines.append("    dwWarningWord := dwWarningWord OR 16#0000_0040; (* Analytical ratio inference fallback *)")
    st_lines.append("END_IF;")
    st_lines.append("")
    st_lines.append("(* --- Channel 5: Ceramic Filter Differential Pressure 2oo3 Voting --- *)")
    st_lines.append("bFilterDP_SensorA_Valid := (rCeramicFilterDiffPress_A_mbar >= 0.0) AND (rCeramicFilterDiffPress_A_mbar <= 280.0);")
    st_lines.append("bFilterDP_SensorB_Valid := (rCeramicFilterDiffPress_B_mbar >= 0.0) AND (rCeramicFilterDiffPress_B_mbar <= 280.0);")
    st_lines.append("bFilterDP_SensorC_Valid := (rCeramicFilterDiffPress_C_mbar >= 0.0) AND (rCeramicFilterDiffPress_C_mbar <= 280.0);")
    st_lines.append("")
    st_lines.append("IF bFilterDP_SensorA_Valid AND bFilterDP_SensorB_Valid AND bFilterDP_SensorC_Valid THEN")
    st_lines.append("    IF ((rCeramicFilterDiffPress_A_mbar >= rCeramicFilterDiffPress_B_mbar) AND (rCeramicFilterDiffPress_A_mbar <= rCeramicFilterDiffPress_C_mbar)) OR")
    st_lines.append("       ((rCeramicFilterDiffPress_A_mbar >= rCeramicFilterDiffPress_C_mbar) AND (rCeramicFilterDiffPress_A_mbar <= rCeramicFilterDiffPress_B_mbar)) THEN")
    st_lines.append("        rVotedFilterDiffPress_mbar := rCeramicFilterDiffPress_A_mbar;")
    st_lines.append("    ELSIF ((rCeramicFilterDiffPress_B_mbar >= rCeramicFilterDiffPress_A_mbar) AND (rCeramicFilterDiffPress_B_mbar <= rCeramicFilterDiffPress_C_mbar)) OR")
    st_lines.append("          ((rCeramicFilterDiffPress_B_mbar >= rCeramicFilterDiffPress_C_mbar) AND (rCeramicFilterDiffPress_B_mbar <= rCeramicFilterDiffPress_A_mbar)) THEN")
