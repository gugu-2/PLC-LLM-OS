    lines.append("    END_FOR;")
    lines.append("    ")
    lines.append("    (* 4. Projected Gradient Descent update with slew-rate and box saturation limits *)")
    lines.append("    FOR nRow := 1 TO 6 DO")
    lines.append("        (* Step against cost gradient *)")
    lines.append("        vecU_Opt[nRow] := vecU_Opt[nRow] - (rPgdStepSize * vecGrad[nRow]);")
    lines.append("        ")
    lines.append("        (* Enforce dynamic slew-rate limit projection *)")
    lines.append("        rDeltaVal := vecU_Opt[nRow] - vecU_Prev[nRow];")
    lines.append("        IF rDeltaVal > vecDeltaU_Max[nRow] THEN")
    lines.append("            vecU_Opt[nRow] := vecU_Prev[nRow] + vecDeltaU_Max[nRow];")
    lines.append("        ELSIF rDeltaVal < -vecDeltaU_Max[nRow] THEN")
    lines.append("            vecU_Opt[nRow] := vecU_Prev[nRow] - vecDeltaU_Max[nRow];")
    lines.append("        END_IF;")
