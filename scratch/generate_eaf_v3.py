        a(f"    ELSE")
        a(f"        rTMR_Voted_{p} := {chC};")
        a(f"    END_IF;")
        a(f"    bTMR_Degraded_1oo2_{p} := FALSE;")
        a(f"    bTMR_Failed_2oo3_{p} := FALSE;")
        a(f"ELSIF bTMR_Fault_A_{p} AND NOT bTMR_Fault_B_{p} AND NOT bTMR_Fault_C_{p} THEN")
        a(f"    (* Degraded 1oo2 arithmetic mean of channels B and C *)")
        a(f"    rTMR_Voted_{p} := 0.50 * ({chB} + {chC});")
        a(f"    bTMR_Degraded_1oo2_{p} := TRUE;")
        a(f"    bTMR_Failed_2oo3_{p} := FALSE;")
        a(f"ELSIF bTMR_Fault_B_{p} AND NOT bTMR_Fault_A_{p} AND NOT bTMR_Fault_C_{p} THEN")
        a(f"    (* Degraded 1oo2 arithmetic mean of channels A and C *)")
        a(f"    rTMR_Voted_{p} := 0.50 * ({chA} + {chC});")
        a(f"    bTMR_Degraded_1oo2_{p} := TRUE;")
        a(f"    bTMR_Failed_2oo3_{p} := FALSE;")
