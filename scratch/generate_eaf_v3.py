    a("        x_horiz[iRow, kStep] := rMatAcc;")
    a("    END_FOR;")
    a("END_FOR;")
    a("")
    a("(* Evaluate Gradient of Quadratic Cost Functional dJ/du *)")
    a("FOR jCol := 1 TO 5 DO")
