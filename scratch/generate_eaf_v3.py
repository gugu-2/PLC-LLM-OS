    a("        FOR iRow := 1 TO 8 DO")
    a("            grad_J[jCol] := grad_J[jCol] + (B_ss[iRow, jCol] * Q_mpc[iRow] * (x_horiz[iRow, kStep] - r_ref[iRow]));")
