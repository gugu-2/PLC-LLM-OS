    a("    rMatAcc := 0.0;")
    a("    FOR jCol := 1 TO 8 DO")
    a("        rMatAcc := rMatAcc + (A_ss[iRow, jCol] * x_state[jCol]);")
    a("    END_FOR;")
    a("    FOR jCol := 1 TO 5 DO")
