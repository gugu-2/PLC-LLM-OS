        a(f"END_IF;")
        a("")
        a(f"(* Median selection / degradation synthesis *)")
        a(f"IF NOT bTMR_Fault_A_{p} AND NOT bTMR_Fault_B_{p} AND NOT bTMR_Fault_C_{p} THEN")
        a(f"    (* Nominal 2oo3 median voting *)")
