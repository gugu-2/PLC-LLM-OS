    a("IF u_cand[5] >  100.0 THEN u_cand[5] :=  100.0; ELSIF u_cand[5] <    0.0 THEN u_cand[5] :=    0.0; END_IF;")
    a("")
    a("(* Store Previous Controls and Commit *)")
    a("FOR jCol := 1 TO 5 DO")
    a("    u_prev[jCol] := u_ctrl[jCol];")
    a("    u_ctrl[jCol] := u_cand[jCol];")
    a("    delta_u[jCol] := u_ctrl[jCol] - u_prev[jCol];")
    a("END_FOR;")
    a("")
    a("(* Map MPC Controls to Physical Actuators *)")
    a("rServoSpoolCmd_PhaseA_mA := u_ctrl[1];")
    a("rServoSpoolCmd_PhaseB_mA := u_ctrl[2];")
    a("rServoSpoolCmd_PhaseC_mA := u_ctrl[3];")
    a("rOxygenLanceValveCmd_pct := u_ctrl[4];")
    a("rIDFanDraftDamperCmd_pct := u_ctrl[5];")
    a("")
    a("(* Dynamic Slag Foaming Carbon Feeder Coordination *)")
    a("IF rSlagFoamingIndex_pct < 65.0 THEN")
    a("    (* Boost carbon injection to stimulate CO gas generation under slag *)")
    a("    rCarbonInjectorRateCmd_kg_min := 45.0 + ((65.0 - rSlagFoamingIndex_pct) * 1.50);")
    a("    IF rCarbonInjectorRateCmd_kg_min > 110.0 THEN rCarbonInjectorRateCmd_kg_min := 110.0; END_IF;")
    a("ELSE")
    a("    rCarbonInjectorRateCmd_kg_min := 25.0;")
    a("END_IF;")
    a("")
    a("(* Post-Combustion Decarburization Air & Evaporative Spray Control *)")
    a("rPostCombustionAirDamperCmd_pct := rVotedCO_Concentration_pct * 8.5;")
    a("IF rPostCombustionAirDamperCmd_pct > 100.0 THEN rPostCombustionAirDamperCmd_pct := 100.0; END_IF;")
    a("IF rTMR_Voted_RoofWaterTemp > 55.0 THEN")
    a("    rRoofCoolingSprayValveCmd_pct := (rTMR_Voted_RoofWaterTemp - 55.0) * 3.33;")
