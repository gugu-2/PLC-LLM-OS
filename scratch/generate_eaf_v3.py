    a("    END_FOR;")
    a("    y_pred[iRow] := rMatAcc;")
    a("    y_err[iRow] := y_meas[iRow] - y_pred[iRow];")
    a("END_FOR;")
    a("")
    a("(* Propagate Discrete State Observer: x[k+1] = A_ss * x[k] + B_ss * u[k] + L_obs * y_err *)")
