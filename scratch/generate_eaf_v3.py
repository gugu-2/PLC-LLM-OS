    # Phase 2: Arc Conductance & State-Space Observer
    a("(* ========================================================================================= *)")
    a("(* === PHASE 2: CASSIE-MAYR ARC DYNAMICS & STATE-SPACE OBSERVER ESTIMATION                 === *)")
    a("(* ========================================================================================= *)")
    a("(* ")
    a("   Dynamic Cassie-Mayr non-linear formulation:")
    a("   Calculates dynamic arc conductance for all 3 phases taking into account thermal time")
    a("   constants and ionization field gradients. Propagates discrete 8x8 Luenberger observer.")
    a("*)")
    a("")
    a("(* Calculate Dynamic Arc Impedance Z = V / I [mOhm] *)")
    a("IF rVotedCurrent_PhaseA_kA > 1.0 THEN")
    a("    rActualImpedance_PhaseA_mOhm := (rVotedVoltage_PhaseA_V / rVotedCurrent_PhaseA_kA) * 1.0;")
    a("ELSE")
    a("    rActualImpedance_PhaseA_mOhm := 999.0; (* Open circuit datum *)")
    a("END_IF;")
    a("")
    a("IF rVotedCurrent_PhaseB_kA > 1.0 THEN")
    a("    rActualImpedance_PhaseB_mOhm := (rVotedVoltage_PhaseB_V / rVotedCurrent_PhaseB_kA) * 1.0;")
    a("ELSE")
    a("    rActualImpedance_PhaseB_mOhm := 999.0;")
    a("END_IF;")
    a("")
    a("IF rVotedCurrent_PhaseC_kA > 1.0 THEN")
    a("    rActualImpedance_PhaseC_mOhm := (rVotedVoltage_PhaseC_V / rVotedCurrent_PhaseC_kA) * 1.0;")
    a("ELSE")
    a("    rActualImpedance_PhaseC_mOhm := 999.0;")
    a("END_IF;")
    a("")
    a("(* Cassie-Mayr Dynamic Conductance Integration: Phase A *)")
    a("rBlendFactor_PhaseA := EXP(-((rVotedCurrent_PhaseA_kA / c_rTransitionCurrent_kA) * (rVotedCurrent_PhaseA_kA / c_rTransitionCurrent_kA)));")
    a("IF rMayrConductance_PhaseA > 0.001 THEN")
    a("    rMayrConductance_PhaseA := rMayrConductance_PhaseA + (c_rTs / c_rTauMayr_s) * ")
    a("        (((rVotedVoltage_PhaseA_V * rVotedCurrent_PhaseA_kA * 1000.0) / c_rMayrPowerLoss_P0) - 1.0) * rMayrConductance_PhaseA;")
    a("END_IF;")
    a("IF rCassieConductance_PhaseA > 0.001 THEN")
    a("    rCassieConductance_PhaseA := rCassieConductance_PhaseA + (c_rTs / c_rTauCassie_s) * ")
    a("        (((rVotedVoltage_PhaseA_V / (c_rCassieField_E0 * 0.150)) * (rVotedVoltage_PhaseA_V / (c_rCassieField_E0 * 0.150))) - 1.0) * rCassieConductance_PhaseA;")
    a("END_IF;")
    a("rArcConductance_PhaseA_S := (1.0 - rBlendFactor_PhaseA) * rCassieConductance_PhaseA + (rBlendFactor_PhaseA * rMayrConductance_PhaseA);")
    a("IF rArcConductance_PhaseA_S < 0.005 THEN rArcConductance_PhaseA_S := 0.005; END_IF;")
    a("")
    a("(* Cassie-Mayr Dynamic Conductance Integration: Phase B *)")
    a("rBlendFactor_PhaseB := EXP(-((rVotedCurrent_PhaseB_kA / c_rTransitionCurrent_kA) * (rVotedCurrent_PhaseB_kA / c_rTransitionCurrent_kA)));")
    a("IF rMayrConductance_PhaseB > 0.001 THEN")
    a("    rMayrConductance_PhaseB := rMayrConductance_PhaseB + (c_rTs / c_rTauMayr_s) * ")
    a("        (((rVotedVoltage_PhaseB_V * rVotedCurrent_PhaseB_kA * 1000.0) / c_rMayrPowerLoss_P0) - 1.0) * rMayrConductance_PhaseB;")
    a("END_IF;")
    a("IF rCassieConductance_PhaseB > 0.001 THEN")
    a("    rCassieConductance_PhaseB := rCassieConductance_PhaseB + (c_rTs / c_rTauCassie_s) * ")
    a("        (((rVotedVoltage_PhaseB_V / (c_rCassieField_E0 * 0.150)) * (rVotedVoltage_PhaseB_V / (c_rCassieField_E0 * 0.150))) - 1.0) * rCassieConductance_PhaseB;")
    a("END_IF;")
    a("rArcConductance_PhaseB_S := (1.0 - rBlendFactor_PhaseB) * rCassieConductance_PhaseB + (rBlendFactor_PhaseB * rMayrConductance_PhaseB);")
    a("IF rArcConductance_PhaseB_S < 0.005 THEN rArcConductance_PhaseB_S := 0.005; END_IF;")
    a("")
    a("(* Cassie-Mayr Dynamic Conductance Integration: Phase C *)")
    a("rBlendFactor_PhaseC := EXP(-((rVotedCurrent_PhaseC_kA / c_rTransitionCurrent_kA) * (rVotedCurrent_PhaseC_kA / c_rTransitionCurrent_kA)));")
    a("IF rMayrConductance_PhaseC > 0.001 THEN")
    a("    rMayrConductance_PhaseC := rMayrConductance_PhaseC + (c_rTs / c_rTauMayr_s) * ")
    a("        (((rVotedVoltage_PhaseC_V * rVotedCurrent_PhaseC_kA * 1000.0) / c_rMayrPowerLoss_P0) - 1.0) * rMayrConductance_PhaseC;")
    a("END_IF;")
    a("IF rCassieConductance_PhaseC > 0.001 THEN")
    a("    rCassieConductance_PhaseC := rCassieConductance_PhaseC + (c_rTs / c_rTauCassie_s) * ")
    a("        (((rVotedVoltage_PhaseC_V / (c_rCassieField_E0 * 0.150)) * (rVotedVoltage_PhaseC_V / (c_rCassieField_E0 * 0.150))) - 1.0) * rCassieConductance_PhaseC;")
    a("END_IF;")
    a("rArcConductance_PhaseC_S := (1.0 - rBlendFactor_PhaseC) * rCassieConductance_PhaseC + (rBlendFactor_PhaseC * rMayrConductance_PhaseC);")
    a("IF rArcConductance_PhaseC_S < 0.005 THEN rArcConductance_PhaseC_S := 0.005; END_IF;")
    a("")
    a("(* Estimated Arc Physical Length L_arc = (V_arc - V_drop) / E_arc [mm] *)")
