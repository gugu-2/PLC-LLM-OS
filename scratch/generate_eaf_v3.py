    a("END_IF;")
    a("")
    a("(* Formulate Observer Measurement Vector y_meas [6] *)")
    a("y_meas[1] := rActualImpedance_PhaseA_mOhm - rTargetImpedance_PhaseA_mOhm;")
    a("y_meas[2] := rActualImpedance_PhaseB_mOhm - rTargetImpedance_PhaseB_mOhm;")
    a("y_meas[3] := rActualImpedance_PhaseC_mOhm - rTargetImpedance_PhaseC_mOhm;")
