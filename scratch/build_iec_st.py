    lines.append("    END_FOR;")
    lines.append("    rTempSum := rTempSum + (aR_Weight[iLoopJ] * aU_Current[iLoopJ]);")
    lines.append("    rTempSum := rTempSum + (aS_Weight[iLoopJ] * (aU_Current[iLoopJ] - aU_Prev[iLoopJ]));")
    lines.append("    aGrad_J[iLoopJ] := rTempSum;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Projected Gradient Descent Update Step *)")
    lines.append("FOR iLoopJ := 1 TO 3 DO")
    lines.append("    aU_Prev[iLoopJ] := aU_Current[iLoopJ];")
    lines.append("    aU_Current[iLoopJ] := aU_Current[iLoopJ] - (rStepAlpha * aGrad_J[iLoopJ]);")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Box Constraints on Commanded Accelerations [m/s^2] *)")
    lines.append("IF aU_Current[1] < 0.20 THEN")
    lines.append("    aU_Current[1] := 0.20; (* Lower vertical accel limit to avoid free-fall *)")
    lines.append("ELSIF aU_Current[1] > 6.20 THEN")
    lines.append("    aU_Current[1] := 6.20; (* Upper vertical accel clamp *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF aU_Current[2] < -1.80 THEN")
    lines.append("    aU_Current[2] := -1.80;")
    lines.append("ELSIF aU_Current[2] > 1.80 THEN")
    lines.append("    aU_Current[2] := 1.80;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF aU_Current[3] < -1.80 THEN")
    lines.append("    aU_Current[3] := -1.80;")
    lines.append("ELSIF aU_Current[3] > 1.80 THEN")
    lines.append("    aU_Current[3] := 1.80;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("(* 5.4 Transform Commanded Accelerations to Total Thrust Vector & Gimbal Attitude Angles        *)")
    lines.append("(* Total Net Acceleration: a_total = sqrt((a_z + g_Moon)^2 + a_x^2 + a_y^2)                    *)")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("rNormAccel := SQRT(((aU_Current[1] + c_rMoonGravity_mps2) * (aU_Current[1] + c_rMoonGravity_mps2)) +")
    lines.append("                   (aU_Current[2] * aU_Current[2]) + (aU_Current[3] * aU_Current[3]));")
    lines.append("")
    lines.append("(* Convert to commanded Newtons and kilonewtons *)")
    lines.append("rTotalThrustForce_N := rEstimatedMass_kg * rNormAccel;")
    lines.append("rDesiredThrust_kN := rTotalThrustForce_N * 0.0010;")
    lines.append("")
    lines.append("(* Gimbal Angle Spherical Projections [rad to deg] *)")
    lines.append("IF (aU_Current[1] + c_rMoonGravity_mps2) > 0.05 THEN")
    lines.append("    rPitchAngleRad := aU_Current[2] / (aU_Current[1] + c_rMoonGravity_mps2);")
    lines.append("    rYawAngleRad   := aU_Current[3] / (aU_Current[1] + c_rMoonGravity_mps2);")
    lines.append("    rGimbalPitch_Unfiltered_deg := rPitchAngleRad * 57.29578;")
    lines.append("    rGimbalYaw_Unfiltered_deg   := rYawAngleRad   * 57.29578;")
    lines.append("ELSE")
    lines.append("    rGimbalPitch_Unfiltered_deg := 0.0;")
    lines.append("    rGimbalYaw_Unfiltered_deg   := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 6: VARIABLE-AREA PINTLE INJECTOR 10:1 DEEP THROTTLING & MIXTURE CONTROL              *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* First-order lag thrust demand filtering to prevent acoustic shockwave *)")
    lines.append("rFilteredThrust_kN := rFilteredThrust_kN + (c_rCycleDeltaT_s * 15.0 * (rDesiredThrust_kN - rFilteredThrust_kN));")
    lines.append("")
    lines.append("(* Deep Throttling Dynamic Saturation: Strict 10:1 envelope [6.50 kN to 65.00 kN] *)")
    lines.append("IF rFilteredThrust_kN > c_rMaxThrust_kN THEN")
    lines.append("    rFilteredThrust_kN := c_rMaxThrust_kN;")
    lines.append("ELSIF rFilteredThrust_kN < c_rMinThrust_kN THEN")
    lines.append("    rFilteredThrust_kN := c_rMinThrust_kN;")
    lines.append("END_IF;")
    lines.append("rThrustCmd_kN := rFilteredThrust_kN;")
    lines.append("")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("(* 6.1 Non-Linear Pintle Sleeve Stroke Characteristic Mapping                                   *)")
    lines.append("(* Cubic Spline Interpolation: x_p = 0.285*F - 0.0014*F^2 + 0.000008*F^3                        *)")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("rPintleFeedforward_mm := (0.2850 * rThrustCmd_kN) -")
    lines.append("                        (0.00140 * rThrustCmd_kN * rThrustCmd_kN) +")
    lines.append("                        (0.0000080 * rThrustCmd_kN * rThrustCmd_kN * rThrustCmd_kN);")
    lines.append("")
    lines.append("(* Closed-Loop Chamber Pressure Feedback Trim *)")
    lines.append("rChamberPress_Target_bar := (rThrustCmd_kN / c_rMaxThrust_kN) * 70.0; (* 7.0 bar to 70.0 bar *)")
    lines.append("rChamberPress_Error_bar  := rChamberPress_Target_bar - rChamberPress_Pc_bar;")
    lines.append("rChamberPress_Integrator := rChamberPress_Integrator + (rChamberPress_Error_bar * c_rCycleDeltaT_s * 0.45);")
    lines.append("IF rChamberPress_Integrator > 1.25 THEN")
    lines.append("    rChamberPress_Integrator := 1.25;")
    lines.append("ELSIF rChamberPress_Integrator < -1.25 THEN")
    lines.append("    rChamberPress_Integrator := -1.25;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("rPintleSleeveCmd_Unclamped_mm := rPintleFeedforward_mm + (rChamberPress_Error_bar * 0.085) + rChamberPress_Integrator;")
    lines.append("")
    lines.append("(* Pintle Sleeve Stroke Mechanical Clamping [1.85 mm to 18.50 mm] *)")
    lines.append("IF rPintleSleeveCmd_Unclamped_mm > c_rMaxPintleStroke_mm THEN")
    lines.append("    rPintleStrokeCmd_mm := c_rMaxPintleStroke_mm;")
    lines.append("ELSIF rPintleSleeveCmd_Unclamped_mm < c_rMinPintleStroke_mm THEN")
    lines.append("    rPintleStrokeCmd_mm := c_rMinPintleStroke_mm;")
    lines.append("ELSE")
    lines.append("    rPintleStrokeCmd_mm := rPintleSleeveCmd_Unclamped_mm;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Pintle Actuator Dynamic Slew Rate Limiter (max 50.0 mm/s) *)")
    lines.append("rPintleSlewRate_mmps := (rPintleStrokeCmd_mm - rPrevPintleCmd_mm) / c_rCycleDeltaT_s;")
    lines.append("IF rPintleSlewRate_mmps > 50.0 THEN")
    lines.append("    rPintleStrokeCmd_mm := rPrevPintleCmd_mm + (50.0 * c_rCycleDeltaT_s);")
    lines.append("ELSIF rPintleSlewRate_mmps < -50.0 THEN")
    lines.append("    rPintleStrokeCmd_mm := rPrevPintleCmd_mm - (50.0 * c_rCycleDeltaT_s);")
    lines.append("END_IF;")
    lines.append("rPrevPintleCmd_mm := rPintleStrokeCmd_mm;")
    lines.append("")
    lines.append("(* Pintle Acoustic Stability Check: Injection Differential Ratio *)")
    lines.append("IF rChamberPress_Pc_bar > 2.0 THEN")
    lines.append("    rCavitationAcousticMargin := (rVoted_TankPress_LOX_bar - rChamberPress_Pc_bar) / rChamberPress_Pc_bar;")
    lines.append("    IF rCavitationAcousticMargin < 0.18 THEN")
    lines.append("        wFaultWord_Degraded.6 := TRUE; (* Impending acoustic chugging detected *)")
    lines.append("    END_IF;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Mixture Ratio Monitoring *)")
    lines.append("IF rMassFlow_LCH4_kgps > 0.05 THEN")
    lines.append("    rActiveMixtureRatio := rMassFlow_LOX_kgps / rMassFlow_LCH4_kgps;")
    lines.append("ELSE")
    lines.append("    rActiveMixtureRatio := c_rNominalMixtureRatio;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 7: DUAL-AXIS ELECTROMECHANICAL GIMBAL & ANTI-SLOSH NOTCH FILTERING                   *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("(* 7.1 Pitch Gimbal Discrete Biquad Notch Filter (Removes Propellant Slosh Mode at 1.45 Hz)     *)")
    lines.append("(* Difference equation: y[k] = b0*x[k] + b1*x[k-1] + b2*x[k-2] - a1*y[k-1] - a2*y[k-2]          *)")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("rTempSum := (c_b0_notch * rGimbalPitch_Unfiltered_deg) +")
    lines.append("            (c_b1_notch * rSloshFilter_Pitch_X1) +")
    lines.append("            (c_b2_notch * rSloshFilter_Pitch_X2) -")
    lines.append("            (c_a1_notch * rSloshFilter_Pitch_Y1) -")
    lines.append("            (c_a2_notch * rSloshFilter_Pitch_Y2);")
    lines.append("")
    lines.append("rSloshFilter_Pitch_X2 := rSloshFilter_Pitch_X1;")
    lines.append("rSloshFilter_Pitch_X1 := rGimbalPitch_Unfiltered_deg;")
    lines.append("rSloshFilter_Pitch_Y2 := rSloshFilter_Pitch_Y1;")
    lines.append("rSloshFilter_Pitch_Y1 := rTempSum;")
    lines.append("rGimbalPitchCmd_deg   := rTempSum;")
    lines.append("")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("(* 7.2 Yaw Gimbal Discrete Biquad Notch Filter                                                  *)")
    lines.append("(* --------------------------------------------------------------------------------------------- *)")
    lines.append("rTempSum := (c_b0_notch * rGimbalYaw_Unfiltered_deg) +")
    lines.append("            (c_b1_notch * rSloshFilter_Yaw_X1) +")
    lines.append("            (c_b2_notch * rSloshFilter_Yaw_X2) -")
    lines.append("            (c_a1_notch * rSloshFilter_Yaw_Y1) -")
    lines.append("            (c_a2_notch * rSloshFilter_Yaw_Y2);")
    lines.append("")
    lines.append("rSloshFilter_Yaw_X2 := rSloshFilter_Yaw_X1;")
    lines.append("rSloshFilter_Yaw_X1 := rGimbalYaw_Unfiltered_deg;")
    lines.append("rSloshFilter_Yaw_Y2 := rSloshFilter_Yaw_Y1;")
    lines.append("rSloshFilter_Yaw_Y1 := rTempSum;")
    lines.append("rGimbalYawCmd_deg   := rTempSum;")
    lines.append("")
    lines.append("(* Mechanical Slew Rate Clamping: 20.0 deg/s *)")
    lines.append("IF (rGimbalPitchCmd_deg - rPrevGimbalPitchCmd_deg) > (c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s) THEN")
    lines.append("    rGimbalPitchCmd_deg := rPrevGimbalPitchCmd_deg + (c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s);")
    lines.append("ELSIF (rGimbalPitchCmd_deg - rPrevGimbalPitchCmd_deg) < (-c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s) THEN")
    lines.append("    rGimbalPitchCmd_deg := rPrevGimbalPitchCmd_deg - (c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s);")
    lines.append("END_IF;")
    lines.append("rPrevGimbalPitchCmd_deg := rGimbalPitchCmd_deg;")
    lines.append("")
    lines.append("IF (rGimbalYawCmd_deg - rPrevGimbalYawCmd_deg) > (c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s) THEN")
    lines.append("    rGimbalYawCmd_deg := rPrevGimbalYawCmd_deg + (c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s);")
    lines.append("ELSIF (rGimbalYawCmd_deg - rPrevGimbalYawCmd_deg) < (-c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s) THEN")
    lines.append("    rGimbalYawCmd_deg := rPrevGimbalYawCmd_deg - (c_rMaxGimbalSlewRate_degps * c_rCycleDeltaT_s);")
    lines.append("END_IF;")
    lines.append("rPrevGimbalYawCmd_deg := rGimbalYawCmd_deg;")
    lines.append("")
    lines.append("(* Gimbal Angle Bounds Check: +/- 8.00 deg *)")
    lines.append("IF rGimbalPitchCmd_deg > c_rMaxGimbalAngle_deg THEN")
    lines.append("    rGimbalPitchCmd_deg := c_rMaxGimbalAngle_deg;")
    lines.append("ELSIF rGimbalPitchCmd_deg < -c_rMaxGimbalAngle_deg THEN")
    lines.append("    rGimbalPitchCmd_deg := -c_rMaxGimbalAngle_deg;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF rGimbalYawCmd_deg > c_rMaxGimbalAngle_deg THEN")
    lines.append("    rGimbalYawCmd_deg := c_rMaxGimbalAngle_deg;")
    lines.append("ELSIF rGimbalYawCmd_deg < -c_rMaxGimbalAngle_deg THEN")
    lines.append("    rGimbalYawCmd_deg := -c_rMaxGimbalAngle_deg;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* SECTION 8: MULTI-STAGE AUTONOMOUS DESCENT FLIGHT STATE MACHINE                               *)")
    lines.append("(* ============================================================================================= *)")
    lines.append("(* Master Abort Override Logic *)")
    lines.append("IF bEmergencyAbortCmd OR (wFaultWord_Critical <> 16#0000) THEN")
    lines.append("    IF (iStateStep <> 70) AND (iStateStep <> 80) AND (iStateStep <> 99) THEN")
    lines.append("        iStateStep := 90; (* Transition immediately to Emergency Abort Ascent *)")
    lines.append("    END_IF;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("CASE iStateStep OF")
    lines.append("    0: (* STATE_STANDBY_PRE_DESCENT: Orbit verification and sub-Kelvin TVS priming *)")
    lines.append("        bEngineMainValvesCmd  := FALSE;")
    lines.append("        bEngineMainIgniterCmd := FALSE;")
    lines.append("        rThrustCmd_kN         := 0.0;")
    lines.append("        rPintleStrokeCmd_mm   := c_rMinPintleStroke_mm;")
    lines.append("        rGimbalPitchCmd_deg   := 0.0;")
    lines.append("        rGimbalYawCmd_deg     := 0.0;")
    lines.append("        bHazardAvoidanceActive:= FALSE;")
    lines.append("        bTouchdownConfirmed   := FALSE;")
    lines.append("        rDescentPhaseProgress_Pct := 0.0;")
    lines.append("        wFlightStateWord      := 16#0001;")
    lines.append("")
    lines.append("        IF bMissionEnable AND (wFaultWord_Critical = 16#0000) THEN")
    lines.append("            iStateStep := 10;")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    10: (* STATE_CHILLDOWN_AND_TVS_CONDITIONING: Line conditioning, subcooling verification *)")
    lines.append("        bEngineMainValvesCmd  := FALSE;")
    lines.append("        bEngineMainIgniterCmd := FALSE;")
    lines.append("        rThrustCmd_kN         := 0.0;")
    lines.append("        wFlightStateWord      := 16#0003;")
    lines.append("        rDescentPhaseProgress_Pct := 5.0;")
    lines.append("")
    lines.append("        (* Verify propellant subcooling margins > 0.80 K and tank pressures conditioned *)")
    lines.append("        IF (rLOX_SubcoolingMargin_K >= 0.80) AND (rLCH4_SubcoolingMargin_K >= 0.80) AND (rStateTimer_Sec >= 3.0) THEN")
    lines.append("            iStateStep := 20;")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    20: (* STATE_ULLAGE_AND_IGNITION: Torch igniter excitation and pintle pre-positioning *)")
    lines.append("        bEngineMainIgniterCmd := TRUE;")
    lines.append("        rPintleStrokeCmd_mm   := 3.20; (* Initial ignition pintle crack *)")
    lines.append("        wFlightStateWord      := 16#0007;")
    lines.append("        rDescentPhaseProgress_Pct := 10.0;")
    lines.append("")
    lines.append("        IF rStateTimer_Sec >= 0.350 THEN")
    lines.append("            bEngineMainValvesCmd := TRUE; (* Open main propellant cryogenic valves *)")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("        (* Confirm chamber pressure rise Pc >= 12.0 bar to verify flame establishment *)")
    lines.append("        IF (rChamberPress_Pc_bar >= 12.0) AND (rStateTimer_Sec >= 0.850) THEN")
    lines.append("            iStateStep := 30; (* Main engine lit, enter powered braking phase *)")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    30: (* STATE_POWERED_BRAKING_BURN: High thrust decel from orbital velocity (100% to 70%) *)")
    lines.append("        bEngineMainValvesCmd  := TRUE;")
    lines.append("        bEngineMainIgniterCmd := FALSE; (* De-energize torch spark once combustion steady *)")
    lines.append("        wFlightStateWord      := 16#000F;")
    lines.append("        rDescentPhaseProgress_Pct := 20.0 + ((2500.0 - rVoted_Alt_m) / 2500.0 * 40.0);")
    lines.append("")
    lines.append("        (* Trajectory state-space reference targets for high-altitude braking *)")
    lines.append("        aX_Target[1] := 450.0; (* Approach gate altitude *)")
    lines.append("        aX_Target[2] := -15.0; (* Vertical velocity gate [m/s] *)")
    lines.append("")
    lines.append("        (* Transition gate: Altitude <= 450 m and vertical speed reduced below -18 m/s *)")
    lines.append("        IF (rVoted_Alt_m <= 450.0) AND (rVoted_VelZ_mps >= -18.0) THEN")
    lines.append("            iStateStep := 40; (* Enter pitch-over approach *)")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    40: (* STATE_PITCH_OVER_APPROACH: Throttle to 50%-35%, orient lander vertical for sensors *)")
    lines.append("        bEngineMainValvesCmd  := TRUE;")
    lines.append("        wFlightStateWord      := 16#001F;")
    lines.append("        rDescentPhaseProgress_Pct := 60.0 + ((450.0 - rVoted_Alt_m) / 450.0 * 20.0);")
    lines.append("")
    lines.append("        aX_Target[1] := 60.0;  (* Terminal gate altitude *)")
    lines.append("        aX_Target[2] := -4.0;  (* Approach vertical speed *)")
    lines.append("")
    lines.append("        (* If hazard detected by Flash LIDAR, transition to divert phase *)")
    lines.append("        IF bDivertInitiated THEN")
    lines.append("            iStateStep := 50;")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        ELSIF (rVoted_Alt_m <= 60.0) AND (rVoted_VelZ_mps >= -5.0) THEN")
    lines.append("            iStateStep := 60; (* Clear terrain, transition directly to terminal descent *)")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    50: (* STATE_HAZARD_AVOIDANCE_REPLAN: Active lateral divert maneuver via 5th order poly *)")
    lines.append("        bEngineMainValvesCmd  := TRUE;")
    lines.append("        wFlightStateWord      := 16#003F;")
    lines.append("        rDescentPhaseProgress_Pct := 80.0;")
    lines.append("")
    lines.append("        (* Hold altitude rate stable while performing lateral translation *)")
    lines.append("        aX_Target[1] := 45.0;")
    lines.append("        aX_Target[2] := -2.0;")
    lines.append("")
    lines.append("        (* Divert completed or altitude drops below 35 m *)")
    lines.append("        IF (NOT bHazardAvoidanceActive) OR (rVoted_Alt_m <= 35.0) THEN")
    lines.append("            iStateStep := 60; (* Proceed to terminal touchdown descent *)")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    60: (* STATE_TERMINAL_VERTICAL_DESCENT: Deep-throttle (15%-10%) constant velocity soft descent *)")
    lines.append("        bEngineMainValvesCmd  := TRUE;")
    lines.append("        wFlightStateWord      := 16#007F;")
    lines.append("        rDescentPhaseProgress_Pct := 90.0 + ((35.0 - rVoted_Alt_m) / 35.0 * 9.0);")
    lines.append("")
    lines.append("        (* Target exact -1.0 m/s vertical touchdown velocity and zero lateral drift *)")
    lines.append("        aX_Target[1] := 0.0;")
    lines.append("        aX_Target[2] := -1.00; (* 1.0 m/s gentle touchdown *)")
    lines.append("        aX_Target[3] := 0.0;")
    lines.append("        aX_Target[4] := 0.0;")
    lines.append("        aX_Target[5] := 0.0;")
    lines.append("        aX_Target[6] := 0.0;")
    lines.append("")
    lines.append("        (* Touchdown detection criteria: probe contact or ultra-low radar altitude *)")
    lines.append("        IF bTouchdownProbesTripped OR (rVoted_Alt_m <= 0.40) THEN")
    lines.append("            rTouchdownLatchTimer_Sec := rTouchdownLatchTimer_Sec + c_rCycleDeltaT_s;")
    lines.append("            IF rTouchdownLatchTimer_Sec >= 0.030 THEN (* 30 ms debounced contact *)")
    lines.append("                iStateStep := 70; (* Instant Engine Cutoff *)")
    lines.append("                rStateTimer_Sec := 0.0;")
    lines.append("            END_IF;")
    lines.append("        ELSE")
    lines.append("            rTouchdownLatchTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    70: (* STATE_TOUCHDOWN_DETECTION_AND_CUTOFF: Immediate shutdown to prevent soil erosion *)")
    lines.append("        bEngineMainValvesCmd  := FALSE; (* Slam propellant shutoff valves closed *)")
    lines.append("        bEngineMainIgniterCmd := FALSE;")
    lines.append("        rThrustCmd_kN         := 0.0;")
    lines.append("        rPintleStrokeCmd_mm   := c_rMinPintleStroke_mm;")
    lines.append("        rGimbalPitchCmd_deg   := 0.0;")
    lines.append("        rGimbalYawCmd_deg     := 0.0;")
    lines.append("        bTouchdownConfirmed   := TRUE;")
    lines.append("        rDescentPhaseProgress_Pct := 100.0;")
    lines.append("        wFlightStateWord      := 16#00FF; (* Touchdown achieved *)")
    lines.append("")
    lines.append("        IF rStateTimer_Sec >= 5.0 THEN")
    lines.append("            iStateStep := 80; (* Proceed to propellant passivation *)")
    lines.append("            rStateTimer_Sec := 0.0;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("    80: (* STATE_POST_LANDING_PASSIVATION: Blowdown cryo lines, depressurize tanks *)")
    lines.append("        bEngineMainValvesCmd  := FALSE;")
    lines.append("        rThrustCmd_kN         := 0.0;")
    lines.append("        (* Open TVS vent valves 100% to vent residual ullage and passivate lander *)")
    lines.append("        rVentValve_LOX_Cmd_Pct  := 100.0;")
    lines.append("        rVentValve_LCH4_Cmd_Pct := 100.0;")
    lines.append("        bTVS_MixerPump_LOX_Cmd  := FALSE;")
    lines.append("        bTVS_MixerPump_LCH4_Cmd := FALSE;")
    lines.append("        wFlightStateWord        := 16#01FF;")
    lines.append("")
    lines.append("    90: (* STATE_EMERGENCY_ABORT_ASCENT: Full-throttle abort climb to safe parking orbit *)")
    lines.append("        bEngineMainValvesCmd  := TRUE;")
    lines.append("        bEngineMainIgniterCmd := TRUE;")
