    a("(* Global Maximum Temperature Rate-of-Rise Selection *)")
    a("rMaxRateOfRise_degC_min := rBed1_RateOfRise_degC_min;")
    a("IF rBed2_RateOfRise_degC_min > rMaxRateOfRise_degC_min THEN rMaxRateOfRise_degC_min := rBed2_RateOfRise_degC_min; END_IF;")
