    a("IF rBed4_RateOfRise_degC_min > rMaxRateOfRise_degC_min THEN rMaxRateOfRise_degC_min := rBed4_RateOfRise_degC_min; END_IF;")
    a("")
    a("(* ========================================================================================= *)")
    a("(* 4.0 CENTRIFUGAL RECYCLE COMPRESSOR AERODYNAMICS & ANTI-SURGE CONTROLLER                   *)")
    a("(* ========================================================================================= *)")
    a("(* Real-time calculation of recycle gas molecular weight, polytropic head, and coordinates. *)")
    a("(* Evaluates normalized surge margin: d_s = (q_r - q_surge) / q_r * 100%.                   *)")
    a("(* Anti-surge control valve with fast opening profile (<750 ms full stroke response).      *)")
    a("")
    a("(* Mean gas molecular weight derived from recycle gas hydrogen purity *)")
    a("IF rH2Purity_mol_pct < 40.0 THEN")
    a("    rH2Purity_mol_pct := 40.0; (* Lower safety bound *)")
    a("ELSIF rH2Purity_mol_pct > 99.9 THEN")
    a("    rH2Purity_mol_pct := 99.9;")
    a("END_IF;")
    a("rGasMolecularWeight := (rH2Purity_mol_pct / 100.0) * rMW_HYDROGEN + ((100.0 - rH2Purity_mol_pct) / 100.0) * rMW_HYDROCARBONS;")
    a("rGasConstant_R := rR_GAS_CONSTANT / rGasMolecularWeight; (* [kJ/(kg*K)] *)")
    a("")
    a("(* Thermodynamic pressures and temperatures converted to absolute units *)")
    a("rP_in_abs := rCompressorSuctionPress_bar + 1.01325; (* bar(a) *)")
    a("rP_out_abs := rCompressorDischPress_bar + 1.01325; (* bar(a) *)")
    a("IF rP_in_abs < 1.0 THEN rP_in_abs := 1.0; END_IF;")
    a("rPressureRatio_Rc := rP_out_abs / rP_in_abs;")
    a("IF rPressureRatio_Rc < 1.02 THEN rPressureRatio_Rc := 1.02; END_IF;")
    a("")
    a("rT_in_K := rCompressorSuctionTemp_degC + 273.15;")
    a("rT_out_K := rCompressorDischTemp_degC + 273.15;")
    a("IF rT_in_K < 200.0 THEN rT_in_K := 200.0; END_IF;")
    a("IF rT_out_K < rT_in_K THEN rT_out_K := rT_in_K + 5.0; END_IF;")
    a("")
    a("(* Gas density at compressor suction inlet [kg/m3]: rho = P / (Z * R * T) *)")
    a("rDensityRecycle_kg_m3 := (rP_in_abs * 100.0) / (rGasCompressibility_Z * rGasConstant_R * rT_in_K);")
    a("IF rDensityRecycle_kg_m3 < 0.20 THEN rDensityRecycle_kg_m3 := 0.20; END_IF;")
    a("")
    a("(* Processed recycle mass flow rate [kg/h] via orifice equation: m_dot = C_d * A * sqrt(2*rho*DP) *)")
    a("rEffectiveDP_mbar := rVoted_DP_mbar;")
    a("rRecycleMassFlow_kg_h := 3600.0 * 0.0524 * SQRT(2.0 * rDensityRecycle_kg_m3 * (rEffectiveDP_mbar * 100.0));")
    a("")
    a("(* Polytropic temperature exponent m = (n-1)/n = ln(T_out/T_in) / ln(P_out/P_in) *)")
    a("IF rPressureRatio_Rc > 1.05 AND rT_out_K > rT_in_K THEN")
    a("    rPolytropicExponent_m := LN(rT_out_K / rT_in_K) / LN(rPressureRatio_Rc);")
    a("    IF rPolytropicExponent_m < 0.150 THEN rPolytropicExponent_m := 0.150; END_IF;")
    a("    IF rPolytropicExponent_m > 0.450 THEN rPolytropicExponent_m := 0.450; END_IF;")
    a("ELSE")
    a("    rPolytropicExponent_m := 0.2857; (* Default diatomic / light gas polytropic exponent *)")
    a("END_IF;")
    a("")
    a("(* Invariant Polytropic Head [kJ/kg]: H_p = Z * R * T_in * (Rc^m - 1) / m *)")
    a("rPolytropicHead_kJ_kg := (rGasCompressibility_Z * rGasConstant_R * rT_in_K / rPolytropicExponent_m) * (EXPT(rPressureRatio_Rc, rPolytropicExponent_m) - 1.0);")
    a("IF rPolytropicHead_kJ_kg < 0.0 THEN rPolytropicHead_kJ_kg := 0.0; END_IF;")
    a("")
    a("(* Real-time compressor polytropic thermodynamic efficiency [%] *)")
    a("rPolytropicEfficiency_pct := (rPolytropicExponent_m / 0.2857) * 76.50;")
    a("IF rPolytropicEfficiency_pct > 88.0 THEN rPolytropicEfficiency_pct := 88.0; END_IF;")
    a("IF rPolytropicEfficiency_pct < 60.0 THEN rPolytropicEfficiency_pct := 60.0; END_IF;")
    a("")
    a("(* Turbine mechanical shaft power estimate: P_shaft = m_dot * H_poly / (eta_poly * 3600) *)")
    a("rTurbinePower_MW := (rRecycleMassFlow_kg_h * rPolytropicHead_kJ_kg) / (0.765 * 3600.0 * 1000.0);")
    a("")
    a("(* Invariant Aerodynamic Coordinates: *)")
    a("(* Reduced volumetric flow squared: q_r = (DP_orifice / P_suction) *)")
    a("rReducedVolumetricFlowSq_qr := (rEffectiveDP_mbar * 0.001) / rP_in_abs;")
    a("(* Reduced polytropic head: h_r = (P_disch / P_suct)^m - 1.0 *)")
    a("rReducedHead_hr := EXPT(rPressureRatio_Rc, rPolytropicExponent_m) - 1.0;")
    a("")
    a("(* Surge Limit Line (SLL): h_surge = Ks * q_surge + Bs => q_surge = (h_r - Bs) / Ks *)")
    a("IF rReducedHead_hr > rSURGE_LINE_INTERCEPT_B THEN")
    a("    rSurgePoint_qr := (rReducedHead_hr - rSURGE_LINE_INTERCEPT_B) / rSURGE_LINE_SLOPE_K;")
    a("ELSE")
    a("    rSurgePoint_qr := 0.001;")
    a("END_IF;")
    a("IF rSurgePoint_qr < 0.0005 THEN rSurgePoint_qr := 0.0005; END_IF;")
    a("")
    a("(* Surge Control Line (SCL) with 10% safety margin bias: q_scl = q_surge * (1.0 + margin/100) *)")
    a("rControlLine_qr := rSurgePoint_qr * (1.0 + rANTI_SURGE_SAFETY_MARGIN / 100.0);")
    a("")
    a("(* Real-Time Normalized Surge Margin [%]: d_s = (q_r - q_surge) / q_surge * 100.0 *)")
    a("rSurgeMargin_pct := ((rReducedVolumetricFlowSq_qr - rSurgePoint_qr) / rSurgePoint_qr) * 100.0;")
    a("")
    a("(* Anti-Surge Controller Error Deviation (Relative to Surge Control Line) *)")
    a("rSurgeDeviation_d := (rControlLine_qr - rReducedVolumetricFlowSq_qr) / rControlLine_qr;")
    a("")
    a("(* Proportional-Integral-Derivative Anti-Surge Governor *)")
    a("IF rSurgeDeviation_d > 0.0 THEN")
    a("    (* Operating inside safety margin zone: integrate rapidly to force anti-surge valve open *)")
    a("    rAntiSurge_IntegralSum := rAntiSurge_IntegralSum + (rAntiSurge_Kp / rAntiSurge_Ti_s) * rSurgeDeviation_d * rScanTime_s;")
    a("ELSE")
    a("    (* Safe operating zone: gently bleed off integral term to allow valve closure *)")
    a("    rAntiSurge_IntegralSum := rAntiSurge_IntegralSum + (rAntiSurge_Kp / (rAntiSurge_Ti_s * 5.0)) * rSurgeDeviation_d * rScanTime_s;")
    a("END_IF;")
    a("")
    a("(* Clamp anti-surge integral windup *)")
    a("IF rAntiSurge_IntegralSum > 100.0 THEN rAntiSurge_IntegralSum := 100.0; END_IF;")
    a("IF rAntiSurge_IntegralSum < 0.0 THEN rAntiSurge_IntegralSum := 0.0; END_IF;")
    a("")
    a("(* Compute raw anti-surge valve demand with derivative anticipator *)")
    a("rAntiSurge_RawCmd_pct := rAntiSurge_Kp * (rSurgeDeviation_d + (rAntiSurge_Td_s / rScanTime_s) * (rSurgeDeviation_d - rAntiSurge_PrevDeviation)) + rAntiSurge_IntegralSum;")
    a("rAntiSurge_PrevDeviation := rSurgeDeviation_d;")
    a("")
    a("(* Asymmetric Slew Rate Limiting: Fast Opening (< 750 ms = 133.3 %/s), Slow Closing (12.5 %/s) *)")
    a("IF rAntiSurge_RawCmd_pct > rAntiSurgeValve_Cmd_pct THEN")
    a("    rMaxSlew := rFAST_OPEN_SLEW_LIMIT_PCT_S * rScanTime_s;")
    a("    rDeltaCmd := rAntiSurge_RawCmd_pct - rAntiSurgeValve_Cmd_pct;")
    a("    IF rDeltaCmd > rMaxSlew THEN rDeltaCmd := rMaxSlew; END_IF;")
    a("    rAntiSurgeValve_Cmd_pct := rAntiSurgeValve_Cmd_pct + rDeltaCmd;")
    a("ELSE")
    a("    rMaxSlew := rNORMAL_CLOSE_SLEW_LIMIT_PCT_S * rScanTime_s;")
    a("    rDeltaCmd := rAntiSurgeValve_Cmd_pct - rAntiSurge_RawCmd_pct;")
    a("    IF rDeltaCmd > rMaxSlew THEN rDeltaCmd := rMaxSlew; END_IF;")
    a("    rAntiSurgeValve_Cmd_pct := rAntiSurgeValve_Cmd_pct - rDeltaCmd;")
    a("END_IF;")
    a("")
    a("(* Enforce Hard Actuator Output Bounds *)")
    a("IF rAntiSurgeValve_Cmd_pct > 100.0 THEN rAntiSurgeValve_Cmd_pct := 100.0; END_IF;")
    a("IF rAntiSurgeValve_Cmd_pct < 0.0 THEN rAntiSurgeValve_Cmd_pct := 0.0; END_IF;")
    a("")
    a("(* ========================================================================================= *)")
    a("(* 5.0 STEAM TURBINE GOVERNOR & API 670 ROTORDYNAMICS MONITORING                             *)")
    a("(* ========================================================================================= *)")
    a("(* Computes vector magnitude of orthogonal X-Y proximity probes on turbine and compressor.   *)")
    a("(* Closed-loop electro-hydraulic turbine speed governor (10,500 RPM rated setpoint).        *)")
    a("")
    a("(* API 670 Composite Vibration Vector Calculations: S_max = sqrt(X^2 + Y^2) *)")
    a("rTurbineVibVector_um := SQRT(rVib_TurbineShaft_X_um * rVib_TurbineShaft_X_um + rVib_TurbineShaft_Y_um * rVib_TurbineShaft_Y_um);")
    a("rCompressorVibVector_um := SQRT(rVib_CompressorDE_X_um * rVib_CompressorDE_X_um + rVib_CompressorDE_Y_um * rVib_CompressorDE_Y_um);")
    a("")
    a("(* Turbine Speed PI Governor Loop *)")
    a("IF iFSM_State >= 20 AND NOT bTurbineTripSolenoid THEN")
    a("    rDeltaCmd := rTurbineSpeedSetpoint_RPM - rTurbineSpeed_RPM;")
    a("    rTurbineGov_IntegralSum := rTurbineGov_IntegralSum + (rTurbineGov_Kp / rTurbineGov_Ti_s) * rDeltaCmd * rScanTime_s;")
    a("    IF rTurbineGov_IntegralSum > 100.0 THEN rTurbineGov_IntegralSum := 100.0; END_IF;")
    a("    IF rTurbineGov_IntegralSum < 5.0 THEN rTurbineGov_IntegralSum := 5.0; END_IF;")
    a("    rTurbineGovValve_Cmd_pct := rTurbineGov_Kp * rDeltaCmd + rTurbineGov_IntegralSum;")
    a("    IF rTurbineGovValve_Cmd_pct > 100.0 THEN rTurbineGovValve_Cmd_pct := 100.0; END_IF;")
    a("    IF rTurbineGovValve_Cmd_pct < 0.0 THEN rTurbineGovValve_Cmd_pct := 0.0; END_IF;")
    a("ELSE")
    a("    rTurbineGovValve_Cmd_pct := 0.0;")
    a("    rTurbineGov_IntegralSum := 0.0;")
    a("END_IF;")
    a("")
    a("(* ========================================================================================= *)")
    a("(* 6.0 4-BED DISCRETE STATE-SPACE MODEL & OBSERVER PROPAGATION                               *)")
    a("(* ========================================================================================= *)")
    a("(* Discrete dynamic propagation across 4 beds: x[k+1] = A * x[k] + B * u[k] + Bd * d[k]     *)")
    a("(* State vector: x = [T_bed1_outlet, T_bed2_outlet, T_bed3_outlet, T_bed4_outlet]           *)")
    a("(* Actuator vector: u = [Quench1, Quench2, Quench3, Quench4]                                 *)")
    a("(* Disturbance vector: d = [dFeedFlow_kg_h, dHeaterOutletTemp_degC]                          *)")
    a("")
    a("(* Compute normalized process disturbances *)")
    a("vDisturbance[1] := rNaphthaFeedFlow_kg_h - 185000.0;          (* Feed flow delta [kg/h] *)")
    a("vDisturbance[2] := rFiredHeaterOutTemp_degC - 515.0;         (* Heater coil temp delta [deg C] *)")
    a("")
    a("(* Synchronize current actuator states *)")
    a("vU_curr[1] := rQuenchValve1_Cmd_pct;")
    a("vU_curr[2] := rQuenchValve2_Cmd_pct;")
    a("vU_curr[3] := rQuenchValve3_Cmd_pct;")
    a("vU_curr[4] := rQuenchValve4_Cmd_pct;")
    a("")
    a("(* Observer Innovation: Correct current state estimates towards measured bed peak temperatures *)")
    a("vX_est[1] := vX_est[1] + 0.150 * (rBed1_MaxTemp_degC - vX_est[1]);")
    a("vX_est[2] := vX_est[2] + 0.140 * (rBed2_MaxTemp_degC - vX_est[2]);")
    a("vX_est[3] := vX_est[3] + 0.135 * (rBed3_MaxTemp_degC - vX_est[3]);")
    a("vX_est[4] := vX_est[4] + 0.130 * (rBed4_MaxTemp_degC - vX_est[4]);")
    a("")
    a("(* Matrix-Vector Multiplication: One-Step-Ahead Dynamic State Propagation *)")
    a("FOR idx := 1 TO 4 DO")
    a("    rTempSum := 0.0;")
    a("    (* A * x contribution *)")
    a("    FOR jdx := 1 TO 4 DO")
    a("        rTempSum := rTempSum + mA[idx, jdx] * (vX_est[jdx] - 510.0);")
    a("    END_FOR;")
    a("    (* B * u contribution *)")
    a("    FOR jdx := 1 TO 4 DO")
    a("        rTempSum := rTempSum + mB[idx, jdx] * (vU_curr[jdx] - 20.0);")
    a("    END_FOR;")
    a("    (* Bd * d contribution *)")
    a("    rTempSum := rTempSum + mBd[idx, 1] * (vDisturbance[1] / 1000.0) + mBd[idx, 2] * vDisturbance[2];")
    a("    vX_pred[idx] := 510.0 + rTempSum;")
    a("END_FOR;")
    a("")
    a("(* Assign State-Space Observer outputs *)")
    a("rEstBed1_OutletTemp_degC := vX_pred[1];")
    a("rEstBed2_OutletTemp_degC := vX_pred[2];")
    a("rEstBed3_OutletTemp_degC := vX_pred[3];")
    a("rEstBed4_OutletTemp_degC := vX_pred[4];")
    a("")
    a("(* ========================================================================================= *)")
    a("(* 7.0 MODEL PREDICTIVE CONTROL (MPC) RECEDING-HORIZON QUADRATIC OPTIMIZATION              *)")
    a("(* ========================================================================================= *)")
    a("(* Formulates multi-step quadratic cost function:                                          *)")
    a("(*   J = sum(e_k' * Q * e_k) + sum(du_k' * R * du_k) + e_N' * P * e_N + W_h2 * sum(u_k)     *)")
    a("(* Executes iterative projected gradient descent across N=3 steps to resolve optimal u.   *)")
    a("")
    a("IF NOT bManualQuenchMode THEN")
    a("    (* Initialize optimization candidate control vector from previous solution *)")
    a("    vU_opt[1] := vU_curr[1];")
    a("    vU_opt[2] := vU_curr[2];")
    a("    vU_opt[3] := vU_curr[3];")
    a("    vU_opt[4] := vU_curr[4];")
    a("")
    a("    (* Deterministic Projected Gradient Descent Loop *)")
    a("    FOR kdx := 1 TO iMPC_MaxIterations DO")
    a("        (* --- Horizon Step 1: Predict State x[k+1] --- *)")
    a("        FOR idx := 1 TO 4 DO")
    a("            rTempSum := 0.0;")
    a("            FOR jdx := 1 TO 4 DO")
    a("                rTempSum := rTempSum + mA[idx, jdx] * (vX_est[jdx] - rBedTargetTemp_degC);")
    a("                rTempSum := rTempSum + mB[idx, jdx] * (vU_opt[jdx] - 20.0);")
    a("            END_FOR;")
    a("            vX_pred_k1[idx] := rBedTargetTemp_degC + rTempSum;")
    a("            vError_k1[idx] := vX_pred_k1[idx] - rBedTargetTemp_degC;")
    a("        END_FOR;")
    a("")
    a("        (* --- Horizon Step 2: Predict State x[k+2] --- *)")
    a("        FOR idx := 1 TO 4 DO")
    a("            rTempSum := 0.0;")
    a("            FOR jdx := 1 TO 4 DO")
    a("                rTempSum := rTempSum + mA[idx, jdx] * (vX_pred_k1[jdx] - rBedTargetTemp_degC);")
    a("                rTempSum := rTempSum + mB[idx, jdx] * (vU_opt[jdx] - 20.0);")
    a("            END_FOR;")
    a("            vX_pred_k2[idx] := rBedTargetTemp_degC + rTempSum;")
    a("            vError_k2[idx] := vX_pred_k2[idx] - rBedTargetTemp_degC;")
    a("        END_FOR;")
    a("")
    a("        (* --- Horizon Step 3: Predict State x[k+3] (Terminal) --- *)")
