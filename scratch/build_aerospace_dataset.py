    a("        ")
    a("        IF rStateTimer_s >= 20.0 THEN")
    a("            rStateTimer_s := 0.0;")
    a("            iFSM_State := 8; (* Transition to TVC Gimbal Sweep *)")
    a("        END_IF;")
    a("")
    a("    8: (* TVC_GIMBAL_SLEW_DYNAMIC_TEST *)")
    a("        (* Maintain 100% thrust while executing dynamic TVC slew sweep *)")
    a("        rCmd_MOV_MainOxidizerValve_pct := 100.0 + au_control[3];")
    a("        rCmd_MFV_MainFuelValve_pct := 100.0 + au_control[4];")
    a("        rCmd_OPCV_Position_pct := 95.0 + au_control[1];")
    a("        rCmd_FPCV_Position_pct := 95.0 + au_control[2];")
