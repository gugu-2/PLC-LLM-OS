    a("        ")
    a("        IF bStartTestSequence AND bEnable AND bEmergencyStop_NC AND bFacilityCryoGSE_Ready AND bPadWaterDelugeActive THEN")
    a("            IF (rFacilityGHeSupplyPressure_bar >= 280.0) AND (rFacilityGN2PurgePressure_bar >= 200.0) THEN")
    a("                rStateTimer_s := 0.0;")
    a("                iFSM_State := 2; (* Transition to Cryo Chilldown *)")
    a("            END_IF;")
    a("        END_IF;")
    a("")
    a("    2: (* CRYO_LINE_CHILLDOWN_LOX_CH4 *)")
    a("        bBusy := TRUE; bReady := FALSE;")
    a("        bCmd_CryoChilldownBleedLOX := TRUE; bCmd_CryoChilldownBleedCH4 := TRUE;")
    a("        bCmd_GN2FacilityPurge := TRUE;")
    a("        ")
    a("        (* Verify both propellant lines reach cryogenic liquid saturation temperatures *)")
    a("        IF (TT_LOX_PUMP_INLET_801A <= 93.0) AND (TT_CH4_PUMP_INLET_802A <= 115.0) AND (rStateTimer_s >= 5.0) THEN")
    a("            rStateTimer_s := 0.0;")
    a("            iFSM_State := 3; (* Transition to Pre-Ignition Purge *)")
    a("        ELSIF rStateTimer_s >= 60.0 THEN")
    a("            (* Chilldown timeout fault *)")
    a("            iFSM_State := 12; (* Fast Abort *)")
    a("        END_IF;")
    a("")
    a("    3: (* PRE_IGNITION_PURGE_AND_PRIME *)")
    a("        bCmd_CryoChilldownBleedLOX := FALSE; bCmd_CryoChilldownBleedCH4 := FALSE;")
    a("        bCmd_GHeFastPurgeValve := TRUE; (* Spin-purge turbopump seals with helium *)")
    a("        ")
    a("        IF rStateTimer_s >= 1.50 THEN")
    a("            bCmd_GHeFastPurgeValve := FALSE;")
    a("            rStateTimer_s := 0.0;")
    a("            iFSM_State := 4; (* Transition to Torch Igniter *)")
    a("        END_IF;")
    a("")
    a("    4: (* TORCH_IGNITER_ESTABLISH *)")
    a("        bCmd_SparkTorchIgniter := TRUE; (* Spark exciter firing *)")
    a("        ")
    a("        (* Confirm chamber pre-pressure rise indicating stable torch flame *)")
    a("        IF (rChamberPressureVoted_bar >= 2.50) AND (rStateTimer_s >= 0.80) THEN")
    a("            rStateTimer_s := 0.0;")
    a("            iFSM_State := 5; (* Transition to Preburner Bootstrap *)")
    a("        ELSIF rStateTimer_s >= 3.0 THEN")
    a("            (* Ignition flameout abort *)")
    a("            iFSM_State := 12;")
    a("        END_IF;")
    a("")
    a("    5: (* PREBURNER_BOOTSTRAP_START *)")
    a("        (* Crack preburner valves open to bootstrap hot gas turbines *)")
