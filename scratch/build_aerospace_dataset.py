    a("        rCmd_MOV_MainOxidizerValve_pct := 0.0; rCmd_MFV_MainFuelValve_pct := 0.0;")
    a("        rCmd_OPCV_Position_pct := 0.0; rCmd_FPCV_Position_pct := 0.0;")
