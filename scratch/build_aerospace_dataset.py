    a("        rCmd_FPCV_Position_pct := 60.0 + (rMainStageRampTimer_s * 35.0) + au_control[2];")
    a("        rCmd_RegenCoolingBypass_pct := 15.0;")
    a("        ")
    a("        IF (rChamberPressureVoted_bar >= 240.0) AND (rStateTimer_s >= 2.20) THEN")
    a("            bCmd_SparkTorchIgniter := FALSE; (* De-energize torch igniter *)")
    a("            rStateTimer_s := 0.0;")
    a("            iFSM_State := 7; (* Transition to Acoustic Instability Sweep *)")
    a("        ELSIF rStateTimer_s >= 5.0 THEN")
    a("            iFSM_State := 12; (* Failed to reach main stage pressure *)")
    a("        END_IF;")
    a("")
    a("    7: (* CHAMBER_ACOUSTIC_FREQUENCY_SWEEP *)")
