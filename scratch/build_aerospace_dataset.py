    a("            bAcousticInstabilityAborted := FALSE;")
    a("            bTurbopumpOverspeedTripped := FALSE;")
    a("            bCmd_EmergencyDumpValves := FALSE;")
    a("            bCmd_GHeFastPurgeValve := FALSE;")
    a("            rStateTimer_s := 0.0;")
    a("            iFSM_State := 1;")
