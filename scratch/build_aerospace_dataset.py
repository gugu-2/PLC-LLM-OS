    a(" * =================================================================================================================== *)")
    a("(* 3.1 Calculate State Vector Tracking Errors (x[k] = y_meas[k] - x_ref[k]) *)")
    a("ax_ref[1] := rTargetChamberPressure_bar;")
    a("ax_ref[2] := rTargetMixtureRatio_OF;")
    a("ax_ref[3] := 35000.0; (* Nominal LOX turbopump speed RPM *)")
    a("ax_ref[4] := 42000.0; (* Nominal CH4 turbopump speed RPM *)")
    a("ax_ref[5] := 750.0;   (* Target copper throat temperature K *)")
    a("ax_ref[6] := 0.0;     (* Zero transverse acoustic resonance *)")
    a("ax_ref[7] := rTargetTVC_Pitch_deg * (c_rPi / 180.0) * 1000.0; (* mrad *)")
    a("ax_ref[8] := rTargetTVC_Yaw_deg * (c_rPi / 180.0) * 1000.0;   (* mrad *)")
    a("")
    a("ax_state[1] := rChamberPressureVoted_bar - ax_ref[1];")
    a("ax_state[2] := rCalculatedMixtureRatio_OF - ax_ref[2];")
    a("ax_state[3] := rLOX_TurbopumpSpeedVoted_RPM - ax_ref[3];")
    a("ax_state[4] := rCH4_TurbopumpSpeedVoted_RPM - ax_ref[4];")
    a("ax_state[5] := rThroatMetalTempVoted_K - ax_ref[5];")
    a("ax_state[6] := rAcousticBandpower_Screeching - ax_ref[6];")
    a("ax_state[7] := (rTVC_DecoupledPitchAngle_deg * (c_rPi / 180.0) * 1000.0) - ax_ref[7];")
    a("ax_state[8] := (rTVC_DecoupledYawAngle_deg * (c_rPi / 180.0) * 1000.0) - ax_ref[8];")
    a("")
    a("(* 3.2 1-Step Receding Horizon State Prediction: x_pred = A * x + B * u *)")
    a("FOR iIdx := 1 TO 8 DO")
    a("    rTempSum := 0.0;")
    a("    FOR jIdx := 1 TO 8 DO")
    a("        rTempSum := rTempSum + (aA[iIdx, jIdx] * ax_state[jIdx]);")
    a("    END_FOR;")
    a("    FOR kIdx := 1 TO 6 DO")
    a("        rTempSum := rTempSum + (aB[iIdx, kIdx] * au_control[kIdx]);")
    a("    END_FOR;")
    a("    aPredictedState[iIdx] := rTempSum;")
    a("END_FOR;")
    a("")
    a("(* 3.3 MPC Quadratic Objective Cost Evaluation: J = x^T Q x + u^T R u + Delta_u^T S Delta_u + x_pred^T P x_pred *)")
    a("rMPC_CostJ := 0.0;")
    a("FOR iIdx := 1 TO 8 DO")
    a("    rMPC_CostJ := rMPC_CostJ + (aQ_Weight[iIdx] * ax_state[iIdx] * ax_state[iIdx]);")
    a("    rMPC_CostJ := rMPC_CostJ + (aP_TerminalWeight[iIdx] * aPredictedState[iIdx] * aPredictedState[iIdx]);")
    a("END_FOR;")
    a("FOR jIdx := 1 TO 6 DO")
    a("    au_delta[jIdx] := au_control[jIdx] - au_prev[jIdx];")
    a("    rMPC_CostJ := rMPC_CostJ + (aR_Weight[jIdx] * au_control[jIdx] * au_control[jIdx]);")
    a("    rMPC_CostJ := rMPC_CostJ + (aS_Weight[jIdx] * au_delta[jIdx] * au_delta[jIdx]);")
    a("END_FOR;")
    a("")
    a("(* 3.4 Multi-Iteration Projected Gradient Descent (PGD) Solver (3 Iterations per 100 us cycle) *)")
    a("FOR mIdx := 1 TO 3 DO")
    a("    (* Compute Analytical Cost Gradient: dJ/du = 2*R*u + 2*S*(u - u_prev) + 2*B^T*P*x_pred *)")
    a("    FOR jIdx := 1 TO 6 DO")
    a("        rTempSum := 0.0;")
    a("        FOR iIdx := 1 TO 8 DO")
    a("            rTempSum := rTempSum + (aB[iIdx, jIdx] * aP_TerminalWeight[iIdx] * aPredictedState[iIdx]);")
    a("        END_FOR;")
    a("        aGrad_u[jIdx] := (2.0 * aR_Weight[jIdx] * au_control[jIdx]) + (2.0 * aS_Weight[jIdx] * (au_control[jIdx] - au_prev[jIdx])) + (2.0 * rTempSum);")
    a("        (* Gradient Descent Step *)")
    a("        au_control[jIdx] := au_control[jIdx] - (c_rPGD_Alpha * aGrad_u[jIdx]);")
    a("        (* Hard Actuator Saturation Constraints Projection *)")
    a("        IF au_control[jIdx] > au_max[jIdx] THEN au_control[jIdx] := au_max[jIdx]; END_IF;")
    a("        IF au_control[jIdx] < au_min[jIdx] THEN au_control[jIdx] := au_min[jIdx]; END_IF;")
    a("        (* Slew Rate Boundary Projection *)")
    a("        IF (au_control[jIdx] - au_prev[jIdx]) > adelta_u_max[jIdx] THEN")
    a("            au_control[jIdx] := au_prev[jIdx] + adelta_u_max[jIdx];")
    a("        ELSIF (au_control[jIdx] - au_prev[jIdx]) < -adelta_u_max[jIdx] THEN")
    a("            au_control[jIdx] := au_prev[jIdx] - adelta_u_max[jIdx];")
    a("        END_IF;")
    a("    END_FOR;")
    a("END_FOR;")
    a("")
    a("(* Store previous control vector *)")
    a("FOR jIdx := 1 TO 6 DO")
    a("    au_prev[jIdx] := au_control[jIdx];")
    a("END_FOR;")
    a("")
    a("(* 3.5 Discrete State Space Forward Propagation: x[k+1] = A * x[k] + B * u[k] *)")
    a("FOR iIdx := 1 TO 8 DO")
    a("    rTempSum := 0.0;")
    a("    FOR jIdx := 1 TO 8 DO")
    a("        rTempSum := rTempSum + (aA[iIdx, jIdx] * ax_state[jIdx]);")
    a("    END_FOR;")
    a("    FOR kIdx := 1 TO 6 DO")
    a("        rTempSum := rTempSum + (aB[iIdx, kIdx] * au_control[kIdx]);")
    a("    END_FOR;")
    a("    ax_next[iIdx] := rTempSum;")
    a("END_FOR;")
    a("")

