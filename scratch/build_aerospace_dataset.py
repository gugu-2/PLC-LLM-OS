    a("(* ===================================================================================================================")
    a(" * PHASE 4: 12-STAGE OPERATIONAL FINITE STATE MACHINE (FSM)")
    a(" * =================================================================================================================== *)")
    a("rCycleTimer_s := rCycleTimer_s + c_rTs;")
    a("rStateTimer_s := rStateTimer_s + c_rTs;")
    a("")
