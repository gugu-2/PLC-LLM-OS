    a("END_IF;")
    a("")
    a("IF (rHighFreqPeakToPeak_bar >= c_rAcousticScreech_Alarm_HI) OR (rAcousticBandpower_Screeching >= 8.0) THEN")
    a("    bAlarm_AcousticScreech_HI := TRUE;")
    a("ELSIF rHighFreqPeakToPeak_bar <= (c_rAcousticScreech_Alarm_HI - c_rAcousticScreech_Deadband) THEN")
    a("    bAlarm_AcousticScreech_HI := FALSE;")
    a("END_IF;")
    a("")
    a("(* 5.3 Turbopump Overspeed & Stall Redline Trips *)")
