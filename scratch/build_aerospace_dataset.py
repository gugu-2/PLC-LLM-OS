    a("        ")
    a("        IF rStateTimer_s >= 15.0 THEN")
    a("            rCmd_TVC_Pitch_Torque_Nm := 0.0; rCmd_TVC_Yaw_Torque_Nm := 0.0;")
    a("            rStateTimer_s := 0.0;")
    a("            iFSM_State := 9; (* Transition to Supersonic Diffuser Vacuum Simulation *)")
    a("        END_IF;")
    a("")
    a("    9: (* HIGH_ALTITUDE_SIMULATION_DIFFUSER *)")
    a("        (* Low back-pressure altitude simulation with peak throat heat flux *)")
    a("        rCmd_MOV_MainOxidizerValve_pct := 100.0 + au_control[3];")
    a("        rCmd_MFV_MainFuelValve_pct := 100.0 + au_control[4];")
    a("        rCmd_OPCV_Position_pct := 95.0 + au_control[1];")
    a("        rCmd_FPCV_Position_pct := 95.0 + au_control[2];")
