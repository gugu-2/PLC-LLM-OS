    code_lines.append("(* PHASE 7: ANSI 79 MULTI-SHOT AUTO-RECLOSING FINITE STATE MACHINE           *)")
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* Master Protection Lockout Reset Action *)")
    code_lines.append("IF bCmd_Reset_Lockout THEN")
    code_lines.append("    IF (rSF6_Voted_Pressure_bar > rP_SF6_Lockout_Trip_bar) AND NOT bTrip_BreakerFailure_50BF THEN")
    code_lines.append("        bBreaker_Lockout_86 := FALSE;")
    code_lines.append("        dwTripWord_Staging := 16#0000_0000;")
    code_lines.append("        iFSM_Reclose_State := 0; (* Return to Normal Idle *)")
    code_lines.append("        iAutoReclose_Current_Shot := 0;")
    code_lines.append("    END_IF;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("CASE iFSM_Reclose_State OF")
    code_lines.append("    0: (* STATE 0: IDLE_CLOSED - Normal Grid Transmission Bay Healthy *)")
    code_lines.append("        bAutoReclose_InProgress := FALSE;")
    code_lines.append("        iAutoReclose_Current_Shot := 0;")
    code_lines.append("        rTimer_DeadTime_Active_Sec := 0.0;")
    code_lines.append("        rTimer_Reclaim_Active_Sec := 0.0;")
    code_lines.append("        bBreaker_Trip_Coil_1 := FALSE;")
    code_lines.append("        bBreaker_Trip_Coil_2 := FALSE;")
    code_lines.append("")
    code_lines.append("        (* Manual Trip Command Handling *)")
    code_lines.append("        IF bCmd_Trip_Manual THEN")
    code_lines.append("            bBreaker_Trip_Coil_1 := TRUE;")
    code_lines.append("            bBreaker_Trip_Coil_2 := TRUE;")
    code_lines.append("            iFSM_Reclose_State := 130; (* Manual Open Standby *)")
    code_lines.append("        (* Protection Trip Triggered *)")
    code_lines.append("        ELSIF (dwTripWord_Staging <> 16#0000_0000) THEN")
    code_lines.append("            bBreaker_Trip_Coil_1 := TRUE;")
    code_lines.append("            bBreaker_Trip_Coil_2 := TRUE;")
    code_lines.append("            IF bTrip_SF6_LowPressure_Lockout OR bTrip_BreakerFailure_50BF OR NOT bCmd_AutoReclose_Enable THEN")
    code_lines.append("                bBreaker_Lockout_86 := TRUE;")
    code_lines.append("                iFSM_Reclose_State := 110; (* Permanent Fault Lockout *)")
    code_lines.append("            ELSE")
    code_lines.append("                iFSM_Reclose_State := 10; (* Fault Detected, Initiate Shot 1 *)")
    code_lines.append("            END_IF;")
    code_lines.append("        END_IF;")
    code_lines.append("")
    code_lines.append("    10: (* STATE 10: FAULT_INITIATION - Breaker Contacts Separating *)")
    code_lines.append("        bAutoReclose_InProgress := TRUE;")
    code_lines.append("        iAutoReclose_Current_Shot := 1;")
    code_lines.append("        rTimer_DeadTime_Active_Sec := 0.0;")
    code_lines.append("        iFSM_Reclose_State := 20; (* Advance to Shot 1 Dead Time *)")
    code_lines.append("")
    code_lines.append("    20: (* STATE 20: SHOT_1_DEAD_TIME - High-Speed 350 ms Deionization *)")
    code_lines.append("        rTimer_DeadTime_Active_Sec := rTimer_DeadTime_Active_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("        bBreaker_Trip_Coil_1 := FALSE;")
    code_lines.append("        bBreaker_Trip_Coil_2 := FALSE;")
    code_lines.append("        IF rTimer_DeadTime_Active_Sec >= rDeadTime_Shot1_Sec THEN")
    code_lines.append("            rTimer_DeadTime_Active_Sec := 0.0;")
    code_lines.append("            bPOW_Arm_Closing_Sequence := TRUE;")
    code_lines.append("            iFSM_Reclose_State := 30; (* Shot 1 Synchronous Close *)")
    code_lines.append("        END_IF;")
    code_lines.append("")
    code_lines.append("    30: (* STATE 30: SHOT_1_RECLOSE_SYNC - Close Breaker & Monitor *)")
    code_lines.append("        IF bBreaker_Aux_52a THEN")
    code_lines.append("            rTimer_Reclaim_Active_Sec := 0.0;")
    code_lines.append("            iFSM_Reclose_State := 40; (* Advance to Shot 1 Reclaim Window *)")
    code_lines.append("        END_IF;")
    code_lines.append("")
    code_lines.append("    40: (* STATE 40: SHOT_1_RECLAIM_WAIT - 180s Reclaim Timer *)")
    code_lines.append("        rTimer_Reclaim_Active_Sec := rTimer_Reclaim_Active_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("        (* If fault strikes again before reclaim completes -> Advance to Shot 2 *)")
    code_lines.append("        IF (dwTripWord_Staging <> 16#0000_0000) THEN")
    code_lines.append("            bBreaker_Trip_Coil_1 := TRUE;")
    code_lines.append("            bBreaker_Trip_Coil_2 := TRUE;")
    code_lines.append("            iAutoReclose_Current_Shot := 2;")
    code_lines.append("            rTimer_DeadTime_Active_Sec := 0.0;")
    code_lines.append("            iFSM_Reclose_State := 50; (* Shot 2 Dead Time *)")
    code_lines.append("        ELSIF rTimer_Reclaim_Active_Sec >= rReclaimTime_Nominal_Sec THEN")
    code_lines.append("            (* Fault cleared successfully on Shot 1 *)")
    code_lines.append("            iFSM_Reclose_State := 100; (* Reclaim Success *)")
    code_lines.append("        END_IF;")
    code_lines.append("")
    code_lines.append("    50: (* STATE 50: SHOT_2_DEAD_TIME - Medium 15.0 s Dead Time *)")
    code_lines.append("        rTimer_DeadTime_Active_Sec := rTimer_DeadTime_Active_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("        bBreaker_Trip_Coil_1 := FALSE;")
    code_lines.append("        bBreaker_Trip_Coil_2 := FALSE;")
    code_lines.append("        IF rTimer_DeadTime_Active_Sec >= rDeadTime_Shot2_Sec THEN")
    code_lines.append("            rTimer_DeadTime_Active_Sec := 0.0;")
    code_lines.append("            bPOW_Arm_Closing_Sequence := TRUE;")
    code_lines.append("            iFSM_Reclose_State := 60; (* Shot 2 Synchronous Close *)")
    code_lines.append("        END_IF;")
    code_lines.append("")
    code_lines.append("    60: (* STATE 60: SHOT_2_RECLOSE_SYNC - Close Breaker & Monitor *)")
    code_lines.append("        IF bBreaker_Aux_52a THEN")
    code_lines.append("            rTimer_Reclaim_Active_Sec := 0.0;")
    code_lines.append("            iFSM_Reclose_State := 70; (* Advance to Shot 2 Reclaim Window *)")
    code_lines.append("        END_IF;")
