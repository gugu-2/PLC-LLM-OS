    code_lines.append("ELSIF (rDiffA <= rCT_Discrepancy_Tolerance_A) THEN")
    code_lines.append("    rI_Line_C_Voted := (rI_Line_C_Ch1 + rI_Line_C_Ch2) / 2.0;")
    code_lines.append("ELSIF (rDiffB <= rCT_Discrepancy_Tolerance_A) THEN")
    code_lines.append("    rI_Line_C_Voted := (rI_Line_C_Ch2 + rI_Line_C_Ch3) / 2.0;")
    code_lines.append("ELSE")
    code_lines.append("    rI_Line_C_Voted := rI_Line_C_Ch1;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* 1.5 SF6 Gas Density & Temperature-Compensated Pressure 2oo3 Voting *)")
    code_lines.append("(* Normalized Gas Temperature Voting *)")
    code_lines.append("rT_SF6_Voted_degC := (rT_SF6_Tank_Ch1 + rT_SF6_Tank_Ch2 + rT_SF6_Tank_Ch3) / 3.0;")
    code_lines.append("")
    code_lines.append("rDiffA := ABS(rP_SF6_Density_Ch1 - rP_SF6_Density_Ch2);")
    code_lines.append("rDiffB := ABS(rP_SF6_Density_Ch2 - rP_SF6_Density_Ch3);")
    code_lines.append("rDiffC := ABS(rP_SF6_Density_Ch1 - rP_SF6_Density_Ch3);")
    code_lines.append("IF (rDiffA <= rSF6_Discrepancy_Tolerance_bar) AND (rDiffB <= rSF6_Discrepancy_Tolerance_bar) THEN")
    code_lines.append("    rSF6_Voted_Pressure_bar := (rP_SF6_Density_Ch1 + rP_SF6_Density_Ch2 + rP_SF6_Density_Ch3) / 3.0;")
    code_lines.append("    bFault_SF6_Channel1 := FALSE;")
    code_lines.append("    bFault_SF6_Channel2 := FALSE;")
    code_lines.append("    bFault_SF6_Channel3 := FALSE;")
    code_lines.append("ELSIF (rDiffA <= rSF6_Discrepancy_Tolerance_bar) THEN")
    code_lines.append("    rSF6_Voted_Pressure_bar := (rP_SF6_Density_Ch1 + rP_SF6_Density_Ch2) / 2.0;")
    code_lines.append("    bFault_SF6_Channel3 := TRUE;")
    code_lines.append("ELSIF (rDiffB <= rSF6_Discrepancy_Tolerance_bar) THEN")
    code_lines.append("    rSF6_Voted_Pressure_bar := (rP_SF6_Density_Ch2 + rP_SF6_Density_Ch3) / 2.0;")
    code_lines.append("    bFault_SF6_Channel1 := TRUE;")
    code_lines.append("ELSIF (rDiffC <= rSF6_Discrepancy_Tolerance_bar) THEN")
    code_lines.append("    rSF6_Voted_Pressure_bar := (rP_SF6_Density_Ch1 + rP_SF6_Density_Ch3) / 2.0;")
    code_lines.append("    bFault_SF6_Channel2 := TRUE;")
    code_lines.append("ELSE")
    code_lines.append("    rSF6_Voted_Pressure_bar := rP_SF6_Density_Ch1;")
    code_lines.append("    bFault_SF6_Channel1 := TRUE;")
    code_lines.append("    bFault_SF6_Channel2 := TRUE;")
    code_lines.append("    bFault_SF6_Channel3 := TRUE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* Standard Temperature Density Compensation (Beattie-Bridgeman ideal factor at 20 deg C) *)")
    code_lines.append("IF (rT_SF6_Voted_degC > -40.0) AND (rT_SF6_Voted_degC < 85.0) THEN")
    code_lines.append("    rSF6_Voted_Pressure_bar := rSF6_Voted_Pressure_bar * (293.15 / (rT_SF6_Voted_degC + 273.15));")
    code_lines.append("END_IF;")
    code_lines.append("")
    
    # Phase 2: Clarke/Park & SRF-PLL & SSR Notch Filter
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* PHASE 2: CLARKE & PARK TRANSFORMS, SRF-PLL & SSR NOTCH FILTER             *)")
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* 2.1 Clarke Transformation: 3-Phase (a, b, c) -> Stationary 2-Phase (Alpha, Beta, Zero) *)")
    code_lines.append("rV_Alpha := (2.0 / 3.0) * (rV_Grid_A_Voted - 0.5 * rV_Grid_B_Voted - 0.5 * rV_Grid_C_Voted);")
    code_lines.append("rV_Beta  := (2.0 / 3.0) * (0.8660254 * rV_Grid_B_Voted - 0.8660254 * rV_Grid_C_Voted);")
    code_lines.append("rV_Zero  := (1.0 / 3.0) * (rV_Grid_A_Voted + rV_Grid_B_Voted + rV_Grid_C_Voted);")
    code_lines.append("")
    code_lines.append("rI_Alpha := (2.0 / 3.0) * (rI_Line_A_Voted - 0.5 * rI_Line_B_Voted - 0.5 * rI_Line_C_Voted);")
    code_lines.append("rI_Beta  := (2.0 / 3.0) * (0.8660254 * rI_Line_B_Voted - 0.8660254 * rI_Line_C_Voted);")
    code_lines.append("rI_Zero  := (1.0 / 3.0) * (rI_Line_A_Voted + rI_Line_B_Voted + rI_Line_C_Voted);")
    code_lines.append("")
    code_lines.append("(* 2.2 Synchronous Reference Frame Phase Locked Loop (SRF-PLL) *)")
    code_lines.append("(* Park Rotation using current PLL phase estimate *)")
    code_lines.append("rV_d_Grid :=  rV_Alpha * COS(rPLL_Phase_Rad) + rV_Beta * SIN(rPLL_Phase_Rad);")
    code_lines.append("rV_q_Grid := -rV_Alpha * SIN(rPLL_Phase_Rad) + rV_Beta * COS(rPLL_Phase_Rad);")
    code_lines.append("")
    code_lines.append("(* PLL PI Loop Filter to force V_q to Zero *)")
    code_lines.append("rPLL_Integral_Term := rPLL_Integral_Term + (rPLL_Ki * rV_q_Grid * rSamplingTime_Ts_Sec);")
    code_lines.append("IF rPLL_Integral_Term > 150.0 THEN")
    code_lines.append("    rPLL_Integral_Term := 150.0;")
    code_lines.append("ELSIF rPLL_Integral_Term < -150.0 THEN")
    code_lines.append("    rPLL_Integral_Term := -150.0;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("rPLL_Omega_RadSec := (2.0 * 3.14159265 * rGrid_Nominal_Freq_Hz) + (rPLL_Kp * rV_q_Grid) + rPLL_Integral_Term;")
    code_lines.append("rGrid_Frequency_Hz := rPLL_Omega_RadSec / (2.0 * 3.14159265);")
    code_lines.append("rPLL_Phase_Rad := rPLL_Phase_Rad + (rPLL_Omega_RadSec * rSamplingTime_Ts_Sec);")
    code_lines.append("")
    code_lines.append("(* Angle Wrapping [0, 2*PI) *)")
    code_lines.append("WHILE rPLL_Phase_Rad >= 6.2831853 DO")
    code_lines.append("    rPLL_Phase_Rad := rPLL_Phase_Rad - 6.2831853;")
    code_lines.append("END_WHILE;")
    code_lines.append("WHILE rPLL_Phase_Rad < 0.0 DO")
    code_lines.append("    rPLL_Phase_Rad := rPLL_Phase_Rad + 6.2831853;")
    code_lines.append("END_WHILE;")
    code_lines.append("")
    code_lines.append("(* 2.3 Park Rotation of Transmission Line Currents into Synchronous dq-Frame *)")
    code_lines.append("rI_d_Line :=  rI_Alpha * COS(rPLL_Phase_Rad) + rI_Beta * SIN(rPLL_Phase_Rad);")
    code_lines.append("rI_q_Line := -rI_Alpha * SIN(rPLL_Phase_Rad) + rI_Beta * COS(rPLL_Phase_Rad);")
    code_lines.append("")
    code_lines.append("(* Park Rotation of STATCOM Converter Injected Currents *)")
    code_lines.append("rI_d_STATCOM := (2.0 / 3.0) * (rI_STATCOM_PhaseA - 0.5 * rI_STATCOM_PhaseB - 0.5 * rI_STATCOM_PhaseC) * COS(rPLL_Phase_Rad)")
    code_lines.append("              + (2.0 / 3.0) * (0.8660254 * rI_STATCOM_PhaseB - 0.8660254 * rI_STATCOM_PhaseC) * SIN(rPLL_Phase_Rad);")
    code_lines.append("rI_q_STATCOM := -(2.0 / 3.0) * (rI_STATCOM_PhaseA - 0.5 * rI_STATCOM_PhaseB - 0.5 * rI_STATCOM_PhaseC) * SIN(rPLL_Phase_Rad)")
    code_lines.append("              + (2.0 / 3.0) * (0.8660254 * rI_STATCOM_PhaseB - 0.8660254 * rI_STATCOM_PhaseC) * COS(rPLL_Phase_Rad);")
    code_lines.append("")
    code_lines.append("(* 2.4 Transmission Line Active, Reactive & Apparent Power Flow Computation *)")
    code_lines.append("rActivePower_MW     := 1.5 * (rV_d_Grid * rI_d_Line + rV_q_Grid * rI_q_Line) * 0.001;")
    code_lines.append("rReactivePower_MVAR := 1.5 * (rV_q_Grid * rI_d_Line - rV_d_Grid * rI_q_Line) * 0.001;")
    code_lines.append("rApparentPower_MVA  := SQRT((rActivePower_MW * rActivePower_MW) + (rReactivePower_MVAR * rReactivePower_MVAR));")
    code_lines.append("")
    code_lines.append("IF rApparentPower_MVA > 0.05 THEN")
    code_lines.append("    rPowerFactor_Current := rActivePower_MW / rApparentPower_MVA;")
    code_lines.append("    IF rReactivePower_MVAR < 0.0 THEN")
    code_lines.append("        rPowerFactor_Current := -rPowerFactor_Current; (* Leading PF *)")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    rPowerFactor_Current := 1.0;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* 2.5 Sub-Synchronous Resonance (SSR) Biquad IIR Notch Filter *)")
    code_lines.append("(* Suppress 22.0 Hz torsional oscillations on the STATCOM q-axis current *)")
    code_lines.append("rSSR_Damping_Current_q := (rNotch_b0 * rI_q_Line) + (rNotch_b1 * rNotch_In_Hist1) + (rNotch_b2 * rNotch_In_Hist2)")
    code_lines.append("                        - (rNotch_a1 * rNotch_Out_Hist1) - (rNotch_a2 * rNotch_Out_Hist2);")
    code_lines.append("rNotch_In_Hist2  := rNotch_In_Hist1;")
    code_lines.append("rNotch_In_Hist1  := rI_q_Line;")
    code_lines.append("rNotch_Out_Hist2 := rNotch_Out_Hist1;")
    code_lines.append("rNotch_Out_Hist1 := rSSR_Damping_Current_q;")
    code_lines.append("")
    
    # Phase 3: Discrete State-Space & Cassie-Mayr Arc Kinetics
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* PHASE 3: DISCRETE STATE-SPACE PREDICTION & CASSIE-MAYR ARC KINETICS       *)")
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* Update current continuous state vector x[k] *)")
    code_lines.append("x_state[1] := rI_d_STATCOM;")
    code_lines.append("x_state[2] := rI_q_STATCOM;")
    code_lines.append("x_state[3] := rV_d_Grid;")
    code_lines.append("x_state[4] := rV_q_Grid;")
    code_lines.append("x_state[5] := rV_DC_Link_V;")
    code_lines.append("x_state[6] := rArc_Conductance_Siemens;")
    code_lines.append("")
    code_lines.append("(* Determine Peak Interrupting Current for Contact Ablation *)")
    code_lines.append("rBreaker_Current_A_Peak := SQRT((rI_d_Line * rI_d_Line) + (rI_q_Line * rI_q_Line));")
    code_lines.append("")
    code_lines.append("(* SF6 Circuit Breaker Arc Conductance Kinetics (Hybrid Cassie-Mayr Model) *)")
    code_lines.append("(* When breaker auxiliary contacts open (52a falls, 52b rises) or trip coil engaged *)")
    code_lines.append("IF (bBreaker_Trip_Coil_1 OR bBreaker_Trip_Coil_2 OR NOT bBreaker_Aux_52a) THEN")
    code_lines.append("    (* If current is high (Cassie regime), arc voltage is constant E0 *)")
    code_lines.append("    IF rBreaker_Current_A_Peak > rArc_Transition_Current_A THEN")
    code_lines.append("        rArc_Voltage_Instantaneous := rCassie_E0_Volts * 28.5; (* 550 kV Chamber Gap Volts *)")
    code_lines.append("        rArc_Conductance_Siemens   := rArc_Conductance_Siemens + (rSamplingTime_Ts_Sec / rCassie_TimeConstant_Sec)")
    code_lines.append("                                    * (((rArc_Voltage_Instantaneous * rBreaker_Current_A_Peak) / ((rCassie_E0_Volts * 28.5) * (rCassie_E0_Volts * 28.5) * (rArc_Conductance_Siemens + 0.000001))) - 1.0) * rArc_Conductance_Siemens;")
    code_lines.append("    ELSE")
    code_lines.append("        (* Near current zero (Mayr regime), thermal cooling dissipation dominates *)")
    code_lines.append("        rArc_Voltage_Instantaneous := (rBreaker_Current_A_Peak / (rArc_Conductance_Siemens + 0.000001));")
    code_lines.append("        rArc_Conductance_Siemens   := rArc_Conductance_Siemens + (rSamplingTime_Ts_Sec / rMayr_TimeConstant_Sec)")
    code_lines.append("                                    * (((rArc_Voltage_Instantaneous * rBreaker_Current_A_Peak) / rMayr_P0_CoolingPower_Watts) - 1.0) * rArc_Conductance_Siemens;")
    code_lines.append("    END_IF;")
    code_lines.append("")
    code_lines.append("    (* Clamp Conductance Limits *)")
    code_lines.append("    IF rArc_Conductance_Siemens < 0.00001 THEN")
    code_lines.append("        rArc_Conductance_Siemens := 0.00001; (* Arc Extinguished / Fully Deionized Gap *)")
    code_lines.append("    ELSIF rArc_Conductance_Siemens > 150.0 THEN")
    code_lines.append("        rArc_Conductance_Siemens := 150.0;   (* Heavy Heavy Arc Core *)")
    code_lines.append("    END_IF;")
    code_lines.append("")
    code_lines.append("    (* Contact Mass Erosion Integration: Integral of I^2 * dt [kA^2 * s] *)")
    code_lines.append("    rCumulative_Arc_Energy_kA2s := rCumulative_Arc_Energy_kA2s + ((rBreaker_Current_A_Peak * 0.001) * (rBreaker_Current_A_Peak * 0.001) * rSamplingTime_Ts_Sec);")
    code_lines.append("    rBreaker_ArcWear_kA2s := rCumulative_Arc_Energy_kA2s;")
    code_lines.append("    rBreaker_Contact_Life_Pct := 100.0 * (1.0 - (rCumulative_Arc_Energy_kA2s / rMax_Rated_Arc_Wear_kA2s));")
    code_lines.append("    IF rBreaker_Contact_Life_Pct < 0.0 THEN")
    code_lines.append("        rBreaker_Contact_Life_Pct := 0.0;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    (* Breaker Fully Closed, No Active Arc *)")
    code_lines.append("    rArc_Conductance_Siemens := 0.00001;")
    code_lines.append("    rArc_Voltage_Instantaneous := 0.0;")
    code_lines.append("END_IF;")
    code_lines.append("x_state[6] := rArc_Conductance_Siemens;")
    code_lines.append("")
    code_lines.append("(* State Propagation: x[k+1] = A * x[k] + B * u[k] *)")
    code_lines.append("FOR idx_i := 1 TO 6 DO")
    code_lines.append("    rTempSum := 0.0;")
    code_lines.append("    FOR idx_j := 1 TO 6 DO")
    code_lines.append("        rTempSum := rTempSum + (matA[idx_i, idx_j] * x_state[idx_j]);")
    code_lines.append("    END_FOR;")
    code_lines.append("    FOR idx_k := 1 TO 4 DO")
    code_lines.append("        rTempSum := rTempSum + (matB[idx_i, idx_k] * u_control[idx_k]);")
    code_lines.append("    END_FOR;")
    code_lines.append("    x_state_next[idx_i] := rTempSum;")
    code_lines.append("END_FOR;")
    code_lines.append("")
    
    # Phase 4: Model Predictive Control Receding Horizon Optimization
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* PHASE 4: RECEDING-HORIZON MPC OPTIMIZER FOR STATCOM VSC VOLTAGE & PF     *)")
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* Target Reference Formulation *)")
    code_lines.append("x_reference[1] := 0.0; (* d-axis Converter Current Reference (Maintained by DC-Link Controller) *)")
    code_lines.append("(* Target Reactive Current Reference for Power Factor and Bus Voltage Regulation *)")
    code_lines.append("IF bCmd_STATCOM_Enable THEN")
    code_lines.append("    (* Voltage Regulation Error Term *)")
    code_lines.append("    x_reference[3] := rV_Target_Setpoint_kV;")
    code_lines.append("    x_reference[4] := 0.0;")
    code_lines.append("    x_reference[5] := rV_DC_Link_Nominal_V;")
    code_lines.append("    x_reference[6] := 0.00001;")
    code_lines.append("")
    code_lines.append("    (* Compute Desired Injected Reactive Current from PF Target & Bus Voltage Deviation *)")
    code_lines.append("    x_reference[2] := ((rV_Target_Setpoint_kV - rV_d_Grid) * 35.0) - (rSSR_Gain * rSSR_Damping_Current_q);")
    code_lines.append("    IF x_reference[2] > rMpcCurrentLimiterRMS THEN")
    code_lines.append("        x_reference[2] := rMpcCurrentLimiterRMS;")
    code_lines.append("    ELSIF x_reference[2] < -rMpcCurrentLimiterRMS THEN")
    code_lines.append("        x_reference[2] := -rMpcCurrentLimiterRMS;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    x_reference[1] := 0.0;")
    code_lines.append("    x_reference[2] := 0.0;")
    code_lines.append("    x_reference[3] := rV_d_Grid;")
    code_lines.append("    x_reference[4] := 0.0;")
    code_lines.append("    x_reference[5] := rV_DC_Link_Nominal_V;")
    code_lines.append("    x_reference[6] := 0.00001;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* Initialize 5-Step Prediction Horizon Trajectory *)")
    code_lines.append("FOR idx_j := 1 TO 6 DO")
    code_lines.append("    rPredHorizonStates[1, idx_j] := x_state_next[idx_j];")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("FOR idx_i := 1 TO 4 DO")
    code_lines.append("    FOR idx_j := 1 TO 6 DO")
    code_lines.append("        rTempSum := 0.0;")
    code_lines.append("        FOR idx_k := 1 TO 6 DO")
    code_lines.append("            rTempSum := rTempSum + (matA[idx_j, idx_k] * rPredHorizonStates[idx_i, idx_k]);")
    code_lines.append("        END_FOR;")
    code_lines.append("        rTempSum := rTempSum + (matB[idx_j, 1] * u_control[1]) + (matB[idx_j, 2] * u_control[2]);")
    code_lines.append("        rPredHorizonStates[idx_i + 1, idx_j] := rTempSum;")
    code_lines.append("    END_FOR;")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("(* Quadratic Cost Evaluation & Analytical Gradient Projection *)")
    code_lines.append("rMpcCostTotal := 0.0;")
    code_lines.append("FOR idx_i := 1 TO 5 DO")
    code_lines.append("    rMpcCostStage := 0.0;")
    code_lines.append("    FOR idx_j := 1 TO 6 DO")
    code_lines.append("        rDiffA := rPredHorizonStates[idx_i, idx_j] - x_reference[idx_j];")
    code_lines.append("        IF idx_i = 5 THEN")
    code_lines.append("            rMpcCostStage := rMpcCostStage + (rDiffA * matP_TerminalWeight[idx_j, idx_j] * rDiffA);")
    code_lines.append("        ELSE")
    code_lines.append("            rMpcCostStage := rMpcCostStage + (rDiffA * matQ_Weight[idx_j, idx_j] * rDiffA);")
    code_lines.append("        END_IF;")
    code_lines.append("    END_FOR;")
    code_lines.append("    rMpcCostStage := rMpcCostStage + (u_control[1] * matR_Weight[1, 1] * u_control[1]) + (u_control[2] * matR_Weight[2, 2] * u_control[2]);")
    code_lines.append("    rMpcCostTotal := rMpcCostTotal + rMpcCostStage;")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("(* Projected Gradient Vector Update for STATCOM Converter Modulation Voltages *)")
    code_lines.append("rMpcGrad_u[1] := 2.0 * matR_Weight[1, 1] * u_control[1] + 2.0 * matB[1, 1] * matQ_Weight[1, 1] * (rPredHorizonStates[1, 1] - x_reference[1]);")
    code_lines.append("rMpcGrad_u[2] := 2.0 * matR_Weight[2, 2] * u_control[2] + 2.0 * matB[2, 2] * matQ_Weight[2, 2] * (rPredHorizonStates[1, 2] - x_reference[2]);")
    code_lines.append("")
    code_lines.append("IF bCmd_STATCOM_Enable THEN")
    code_lines.append("    u_control[1] := u_control[1] - (rMpcStepSize * rMpcGrad_u[1]);")
    code_lines.append("    u_control[2] := u_control[2] - (rMpcStepSize * rMpcGrad_u[2]);")
    code_lines.append("ELSE")
    code_lines.append("    u_control[1] := 0.0;")
    code_lines.append("    u_control[2] := 0.0;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* Space Vector Modulation Limit Enforcement: Overmodulation Clamp *)")
    code_lines.append("rSTATCOM_Modulation_Index := SQRT((u_control[1] * u_control[1]) + (u_control[2] * u_control[2])) / (rV_DC_Link_V * 0.57735);")
    code_lines.append("IF rSTATCOM_Modulation_Index > rMpcMaxVoltageLimit THEN")
    code_lines.append("    u_control[1] := u_control[1] * (rMpcMaxVoltageLimit / rSTATCOM_Modulation_Index);")
    code_lines.append("    u_control[2] := u_control[2] * (rMpcMaxVoltageLimit / rSTATCOM_Modulation_Index);")
    code_lines.append("    rSTATCOM_Modulation_Index := rMpcMaxVoltageLimit;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("IF ABS(u_control[1]) > 0.001 OR ABS(u_control[2]) > 0.001 THEN")
    code_lines.append("    rSTATCOM_Firing_Angle_Rad := ATAN2(u_control[2], u_control[1]);")
    code_lines.append("ELSE")
    code_lines.append("    rSTATCOM_Firing_Angle_Rad := 0.0;")
    code_lines.append("END_IF;")
    code_lines.append("rSTATCOM_Q_Injected_MVAR := 1.5 * (rV_d_Grid * rI_q_STATCOM - rV_q_Grid * rI_d_STATCOM) * 0.001;")
    code_lines.append("")
    code_lines.append("(* 4.3 Automated On-Load Tap Changer (OLTC) Stepping Coordination *)")
    code_lines.append("(* If STATCOM reactive injection is saturated (> 65 MVAR) for > 25 s, step OLTC to unload STATCOM *)")
    code_lines.append("IF bOLTC_Pulse_Active THEN")
    code_lines.append("    rTimer_OLTC_Pulse_Sec := rTimer_OLTC_Pulse_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("    IF rTimer_OLTC_Pulse_Sec >= 1.500 THEN")
    code_lines.append("        bOLTC_Raise_Command := FALSE;")
    code_lines.append("        bOLTC_Lower_Command := FALSE;")
    code_lines.append("        bOLTC_Pulse_Active := FALSE;")
    code_lines.append("        rTimer_OLTC_Pulse_Sec := 0.0;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSIF (rSTATCOM_Q_Injected_MVAR > rOLTC_STATCOM_Threshold_MVAR) AND (rV_d_Grid < (rV_Target_Setpoint_kV - rOLTC_Voltage_Deadband_kV)) THEN")
    code_lines.append("    rOLTC_Timer_Integrator_Sec := rOLTC_Timer_Integrator_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("    IF rOLTC_Timer_Integrator_Sec >= rOLTC_Dwell_Timeout_Sec THEN")
    code_lines.append("        IF iOLTC_Current_Tap < 16 THEN")
    code_lines.append("            bOLTC_Raise_Command := TRUE;")
    code_lines.append("            bOLTC_Lower_Command := FALSE;")
    code_lines.append("            bOLTC_Pulse_Active  := TRUE;")
    code_lines.append("            rOLTC_Timer_Integrator_Sec := 0.0;")
    code_lines.append("        END_IF;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSIF (rSTATCOM_Q_Injected_MVAR < -rOLTC_STATCOM_Threshold_MVAR) AND (rV_d_Grid > (rV_Target_Setpoint_kV + rOLTC_Voltage_Deadband_kV)) THEN")
    code_lines.append("    rOLTC_Timer_Integrator_Sec := rOLTC_Timer_Integrator_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("    IF rOLTC_Timer_Integrator_Sec >= rOLTC_Dwell_Timeout_Sec THEN")
    code_lines.append("        IF iOLTC_Current_Tap > -16 THEN")
    code_lines.append("            bOLTC_Lower_Command := TRUE;")
    code_lines.append("            bOLTC_Raise_Command := FALSE;")
    code_lines.append("            bOLTC_Pulse_Active  := TRUE;")
    code_lines.append("            rOLTC_Timer_Integrator_Sec := 0.0;")
    code_lines.append("        END_IF;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    rOLTC_Timer_Integrator_Sec := 0.0;")
    code_lines.append("END_IF;")
    code_lines.append("")
    
    # Phase 5: Protection Algorithms
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* PHASE 5: ULTRA-FAST PROTECTION ALGORITHMS (ANSI 50/51/67/81R/78/50BF)     *)")
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* 5.1 ANSI 50: Instantaneous Sub-Cycle Overcurrent Protection (< 15 ms Trip) *)")
    code_lines.append("IF rBreaker_Current_A_Peak >= rPickupCurrent_50_Instant_A THEN")
    code_lines.append("    bTrip_Instantaneous_50 := TRUE;")
    code_lines.append("    dwTripWord_Staging := dwTripWord_Staging OR 16#0000_0001;")
    code_lines.append("ELSE")
    code_lines.append("    bTrip_Instantaneous_50 := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* 5.2 ANSI 51: IDMT Inverse Time Overcurrent (IEC 60255 Standard Inverse Curve) *)")
    code_lines.append("IF rBreaker_Current_A_Peak > rPickupCurrent_51_IDMT_A THEN")
    code_lines.append("    rDiffA := (rBreaker_Current_A_Peak / rPickupCurrent_51_IDMT_A);")
    code_lines.append("    (* IEC Standard Inverse: t = TMS * (0.14 / ((I/Is)^0.02 - 1.0)) *)")
    code_lines.append("    rDiffB := (EXPT(rDiffA, 0.02) - 1.0);")
    code_lines.append("    IF rDiffB > 0.0001 THEN")
    code_lines.append("        rTempSum := rTMS_TimeMultiplierSetting * (0.14 / rDiffB);")
    code_lines.append("        rIDMT_Accumulator := rIDMT_Accumulator + (rSamplingTime_Ts_Sec / rTempSum);")
    code_lines.append("    ELSE")
    code_lines.append("        rIDMT_Accumulator := rIDMT_Accumulator + 0.1;")
    code_lines.append("    END_IF;")
    code_lines.append("    IF rIDMT_Accumulator >= 1.0 THEN")
    code_lines.append("        bTrip_TimeOvercurrent_51 := TRUE;")
    code_lines.append("        dwTripWord_Staging := dwTripWord_Staging OR 16#0000_0002;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    (* Linear Cooling Emulation / Reset Integrator *)")
    code_lines.append("    rIDMT_Accumulator := rIDMT_Accumulator - (rSamplingTime_Ts_Sec * 0.5);")
    code_lines.append("    IF rIDMT_Accumulator < 0.0 THEN")
    code_lines.append("        rIDMT_Accumulator := 0.0;")
    code_lines.append("    END_IF;")
    code_lines.append("    bTrip_TimeOvercurrent_51 := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* 5.3 ANSI 67: Directional Overcurrent Discrimination (Sub-Cycle Phase Angle Quadrant) *)")
    code_lines.append("IF rBreaker_Current_A_Peak > (rPickupCurrent_51_IDMT_A * 1.5) THEN")
    code_lines.append("    (* Calculate Fault Phase Angle relative to Polarizing Voltage *)")
    code_lines.append("    rDirectional_TorqueAngle := (ATAN2(rI_q_Line, rI_d_Line) - ATAN2(rV_q_Grid, rV_d_Grid)) * 57.29578; (* to Degrees *)")
    code_lines.append("    WHILE rDirectional_TorqueAngle > 180.0 DO")
    code_lines.append("        rDirectional_TorqueAngle := rDirectional_TorqueAngle - 360.0;")
    code_lines.append("    END_WHILE;")
    code_lines.append("    WHILE rDirectional_TorqueAngle < -180.0 DO")
    code_lines.append("        rDirectional_TorqueAngle := rDirectional_TorqueAngle + 360.0;")
    code_lines.append("    END_WHILE;")
    code_lines.append("")
    code_lines.append("    (* Forward Fault Quadrant: -15 deg to +115 deg *)")
    code_lines.append("    IF (rDirectional_TorqueAngle >= -15.0) AND (rDirectional_TorqueAngle <= 115.0) THEN")
    code_lines.append("        bDirectional_ForwardFault := TRUE;")
    code_lines.append("        bDirectional_ReverseFault := FALSE;")
    code_lines.append("        bTrip_Directional_67      := TRUE;")
    code_lines.append("        dwTripWord_Staging        := dwTripWord_Staging OR 16#0000_0004;")
    code_lines.append("    ELSE")
    code_lines.append("        bDirectional_ForwardFault := FALSE;")
    code_lines.append("        bDirectional_ReverseFault := TRUE;")
    code_lines.append("        bTrip_Directional_67      := FALSE;")
    code_lines.append("        dwWarnWord_Staging        := dwWarnWord_Staging OR 16#0000_0010; (* Reverse Fault Warning *)")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    bDirectional_ForwardFault := FALSE;")
    code_lines.append("    bDirectional_ReverseFault := FALSE;")
    code_lines.append("    bTrip_Directional_67      := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* 5.4 ANSI 81R & ANSI 78: Rate of Change of Frequency (RoCoF) & Vector Shift Islanding *)")
    code_lines.append("FOR idx_i := 10 TO 2 BY -1 DO")
    code_lines.append("    rRoCoF_Window_Hist[idx_i] := rRoCoF_Window_Hist[idx_i - 1];")
    code_lines.append("END_FOR;")
    code_lines.append("rRoCoF_Window_Hist[1] := rGrid_Frequency_Hz;")
    code_lines.append("rRoCoF_Value_HzSec := ABS(rRoCoF_Window_Hist[1] - rRoCoF_Window_Hist[10]) / (9.0 * rSamplingTime_Ts_Sec);")
    code_lines.append("")
    code_lines.append("IF rRoCoF_Value_HzSec >= rRoCoF_Trip_Threshold_HzSec THEN")
    code_lines.append("    rTimer_RoCoF_Persist_Sec := rTimer_RoCoF_Persist_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("    IF rTimer_RoCoF_Persist_Sec >= 0.080 THEN (* 80 ms confirmation window *)")
    code_lines.append("        bTrip_LossOfMains_Islanding := TRUE;")
    code_lines.append("        dwTripWord_Staging := dwTripWord_Staging OR 16#0000_0008;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    rTimer_RoCoF_Persist_Sec := 0.0;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* Vector Shift Jump Detection: Cycle-to-cycle zero crossing displacement *)")
    code_lines.append("rVectorShift_Degrees := ABS(rPLL_Phase_Rad - rPrevCycle_ZeroCross_Angle) * 57.29578;")
    code_lines.append("IF (rVectorShift_Degrees > rVectorShift_Threshold_Deg) AND (rVectorShift_Degrees < 120.0) THEN")
    code_lines.append("    bTrip_LossOfMains_Islanding := TRUE;")
    code_lines.append("    dwTripWord_Staging := dwTripWord_Staging OR 16#0000_0008;")
    code_lines.append("END_IF;")
    code_lines.append("rPrevCycle_ZeroCross_Angle := rPLL_Phase_Rad;")
    code_lines.append("")
    code_lines.append("(* 5.5 ANSI 50BF: Breaker Failure Protection Logic *)")
    code_lines.append("IF (bBreaker_Trip_Coil_1 OR bBreaker_Trip_Coil_2) THEN")
    code_lines.append("    IF (bBreaker_Aux_52a OR (rBreaker_Current_A_Peak > 200.0)) THEN")
    code_lines.append("        rTimer_50BF_BreakerFailure_Sec := rTimer_50BF_BreakerFailure_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("        IF rTimer_50BF_BreakerFailure_Sec >= rBreakerFailure_Timeout_Sec THEN")
    code_lines.append("            bTrip_BreakerFailure_50BF := TRUE;")
    code_lines.append("            dwTripWord_Staging := dwTripWord_Staging OR 16#0000_0020;")
    code_lines.append("            bBreaker_Lockout_86 := TRUE; (* Lockout 86 latched *)")
    code_lines.append("        END_IF;")
    code_lines.append("    ELSE")
    code_lines.append("        rTimer_50BF_BreakerFailure_Sec := 0.0;")
    code_lines.append("        bTrip_BreakerFailure_50BF := FALSE;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    rTimer_50BF_BreakerFailure_Sec := 0.0;")
    code_lines.append("    bTrip_BreakerFailure_50BF := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* 5.6 SF6 Gas Density Stage 2 Lockout Evaluation *)")
    code_lines.append("IF rSF6_Voted_Pressure_bar <= rP_SF6_Lockout_Trip_bar THEN")
    code_lines.append("    bTrip_SF6_LowPressure_Lockout := TRUE;")
    code_lines.append("    dwTripWord_Staging := dwTripWord_Staging OR 16#0000_0040;")
    code_lines.append("    bBreaker_Lockout_86 := TRUE;")
    code_lines.append("ELSE")
    code_lines.append("    bTrip_SF6_LowPressure_Lockout := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* 5.7 Auxiliary Contact Discrepancy Monitoring (52a vs 52b) *)")
    code_lines.append("IF (bBreaker_Aux_52a = bBreaker_Aux_52b) THEN")
    code_lines.append("    rTimer_AuxDiscrepancy_Sec := rTimer_AuxDiscrepancy_Sec + rSamplingTime_Ts_Sec;")
    code_lines.append("    IF rTimer_AuxDiscrepancy_Sec >= 0.050 THEN (* 50 ms auxiliary inconsistency *)")
    code_lines.append("        bAuxContactDiscrepancy := TRUE;")
    code_lines.append("        dwWarnWord_Staging := dwWarnWord_Staging OR 16#0000_0020;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    rTimer_AuxDiscrepancy_Sec := 0.0;")
    code_lines.append("    bAuxContactDiscrepancy := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    
    # Phase 6: Point-on-wave & Anti-pumping
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* PHASE 6: POINT-ON-WAVE (POW) SYNCHRONOUS SWITCHING & ANTI-PUMPING         *)")
    code_lines.append("(* ========================================================================= *)")
    code_lines.append("(* Breaker Anti-Pumping Protection: Prevents continuous hunting on stuck close *)")
    code_lines.append("IF bCmd_Close_Manual AND NOT bCmd_Close_Prev THEN")
    code_lines.append("    IF NOT bBreaker_Lockout_86 AND NOT bBreaker_AntiPumping_Active THEN")
    code_lines.append("        bPOW_Arm_Closing_Sequence := TRUE;")
    code_lines.append("    END_IF;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* If close command is held continuously while breaker trips, latch anti-pumping *)")
    code_lines.append("IF bCmd_Close_Manual AND (bBreaker_Trip_Coil_1 OR bBreaker_Trip_Coil_2 OR NOT bBreaker_Aux_52a) THEN")
    code_lines.append("    bAntiPumping_Latched := TRUE;")
    code_lines.append("END_IF;")
    code_lines.append("IF NOT bCmd_Close_Manual THEN")
    code_lines.append("    bAntiPumping_Latched := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("bBreaker_AntiPumping_Active := bAntiPumping_Latched;")
    code_lines.append("bCmd_Close_Prev := bCmd_Close_Manual;")
    code_lines.append("")
    code_lines.append("(* Synchronous Closing Calculation at Target Phase Angle *)")
    code_lines.append("IF bPOW_Arm_Closing_Sequence AND NOT bBreaker_Lockout_86 AND NOT bBreaker_AntiPumping_Active THEN")
    code_lines.append("    (* Phase angle to travel before reaching target voltage peak *)")
    code_lines.append("    rPOW_Angle_Remaining_Rad := rPOW_Target_Angle_Rad - rPLL_Phase_Rad;")
    code_lines.append("    WHILE rPOW_Angle_Remaining_Rad < 0.0 DO")
    code_lines.append("        rPOW_Angle_Remaining_Rad := rPOW_Angle_Remaining_Rad + 6.2831853;")
    code_lines.append("    END_WHILE;")
    code_lines.append("")
    code_lines.append("    (* Time until prospective target angle *)")
    code_lines.append("    rTimer_POW_Lead_Sec := rPOW_Angle_Remaining_Rad / rPLL_Omega_RadSec;")
    code_lines.append("    (* Compare with mechanical breaker closing flight time (42.5 ms) *)")
    code_lines.append("    IF (rTimer_POW_Lead_Sec <= rBreaker_Mechanical_Time_Sec) AND (rTimer_POW_Lead_Sec >= (rBreaker_Mechanical_Time_Sec - 0.002)) THEN")
    code_lines.append("        bBreaker_Close_Coil := TRUE;")
    code_lines.append("        bPOW_Arm_Closing_Sequence := FALSE;")
    code_lines.append("    ELSE")
    code_lines.append("        bBreaker_Close_Coil := FALSE;")
    code_lines.append("    END_IF;")
    code_lines.append("ELSE")
    code_lines.append("    bBreaker_Close_Coil := FALSE;")
    code_lines.append("END_IF;")
    code_lines.append("")
    
    # Phase 7: ANSI 79 Multi-Shot Auto-Reclosing FSM
