# gen_part5.py - Phase 3: Receding-Horizon MPC with 10-step PGD
def get_part5():
    lines = []
    def w(s=""):
        lines.append(s)

    w("(* ==================================================================================================== *)")
    w("(* === PHASE 3: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) WITH 10-STEP PGD OPTIMIZER === *)")
    w("(* ==================================================================================================== *)")
    w("")
    w("(* Initialize MPC Reference Trajectories over 10-Step Prediction Horizon *)")
    w("FOR k := 0 TO 10 DO")
    w("    a_MPC_x_ref[k, 1] := 2.050; (* Target Body Hook Length [mm] *)")
    w("    a_MPC_x_ref[k, 2] := 2.050; (* Target Cover Hook Length [mm] *)")
    w("    a_MPC_x_ref[k, 3] := r_SeamThicknessNominal_mm; (* Target Seam Thickness [mm] *)")
    w("    a_MPC_x_ref[k, 4] := r_SeamHeightNominal_mm;    (* Target Seam Height [mm] *)")
    w("    a_MPC_x_ref[k, 5] := 1.350; (* Target Seam Overlap [mm] *)")
    w("    a_MPC_x_ref[k, 6] := 1.850; (* Target Lifter Spring Stroke [mm] *)")
    w("    a_MPC_x_ref[k, 7] := 1800.0;(* Target Lifter Axial Clamping Force [N] *)")
    w("    a_MPC_x_ref[k, 8] := 0.0;   (* Target Spindle Centrifugal Deflection [um] *)")
    w("    a_MPC_x_ref[k, 9] := a_x_hat[9]; (* Tooling Thermal Drift Reference [deg C] *)")
    w("    a_MPC_x_ref[k, 10]:= a_x_hat[10];")
    w("    a_MPC_x_ref[k, 11]:= a_x_hat[11];")
    w("    a_MPC_x_ref[k, 12]:= 0.0;   (* Target Zero Net Deflection *)")
    w("END_FOR;")
    w("")
    w("(* Initialize State Trajectory at Horizon Step 0 *)")
    w("FOR i := 1 TO 12 DO")
    w("    a_MPC_x_traj[0, i] := a_x_hat[i];")
    w("END_FOR;")
    w("")
    w("(* Seed Control Actuator Sequence from Previous Commands *)")
    w("FOR k := 0 TO 9 DO")
    w("    a_MPC_u_seq[k, 1] := a_u_vec[1];")
    w("    a_MPC_u_seq[k, 2] := a_u_vec[2];")
    w("    a_MPC_u_seq[k, 3] := a_u_vec[3];")
    w("    a_MPC_u_seq[k, 4] := a_u_vec[4];")
    w("END_FOR;")
    w("")
    w("(* ==================== 5 UNROLLED PROJECTED GRADIENT DESCENT (PGD) ITERATIONS ==================== *)")
    w("FOR iter := 1 TO 5 DO")
    w("    (* 1. Forward State Trajectory Simulation Across Horizon (0..9) *)")
    w("    FOR k := 0 TO 9 DO")
    w("        FOR i := 1 TO 12 DO")
    w("            r_temp_val := 0.0;")
    w("            FOR j := 1 TO 12 DO")
    w("                r_temp_val := r_temp_val + a_SS_A[i, j] * a_MPC_x_traj[k, j];")
    w("            END_FOR;")
    w("            (* Control input coupling (first 4 actuators) *)")
    w("            FOR m := 1 TO 4 DO")
    w("                r_temp_val := r_temp_val + a_SS_B[i, m] * a_MPC_u_seq[k, m];")
    w("            END_FOR;")
    w("            (* Constant inputs 5 and 6 *)")
    w("            r_temp_val := r_temp_val + a_SS_B[i, 5] * a_u_vec[5] + a_SS_B[i, 6] * a_u_vec[6];")
    w("            a_MPC_x_traj[k + 1, i] := r_temp_val;")
    w("        END_FOR;")
    w("    END_FOR;")
    w("")
    w("    (* 2. Backward Adjoint Costate Propagation From Terminal Horizon (k=10 down to 0) *)")
    w("    FOR i := 1 TO 12 DO")
    w("        a_MPC_lambda[10, i] := a_MPC_P[i] * (a_MPC_x_traj[10, i] - a_MPC_x_ref[10, i]);")
    w("    END_FOR;")
    w("")
    w("    FOR k := 9 TO 0 BY -1 DO")
    w("        FOR i := 1 TO 12 DO")
    w("            r_temp_val := a_MPC_Q[i] * (a_MPC_x_traj[k, i] - a_MPC_x_ref[k, i]);")
    w("            FOR j := 1 TO 12 DO")
    w("                r_temp_val := r_temp_val + a_SS_A[j, i] * a_MPC_lambda[k + 1, j];")
    w("            END_FOR;")
    w("            a_MPC_lambda[k, i] := r_temp_val;")
    w("        END_FOR;")
    w("    END_FOR;")
    w("")
    w("    (* 3. Analytic Gradient Evaluation & Projected Gradient Step *)")
    w("    FOR k := 0 TO 9 DO")
    w("        FOR m := 1 TO 4 DO")
    w("            r_temp_grad := a_MPC_R[m] * a_MPC_u_seq[k, m];")
    w("            FOR j := 1 TO 12 DO")
    w("                r_temp_grad := r_temp_grad + a_SS_B[j, m] * a_MPC_lambda[k + 1, j];")
    w("            END_FOR;")
    w("            (* Slew rate penalty gradient *)")
    w("            IF k > 0 THEN")
    w("                r_temp_grad := r_temp_grad + a_MPC_S[m] * (a_MPC_u_seq[k, m] - a_MPC_u_seq[k - 1, m]);")
    w("            ELSE")
    w("                r_temp_grad := r_temp_grad + a_MPC_S[m] * (a_MPC_u_seq[0, m] - a_u_vec[m]);")
    w("            END_IF;")
    w("")
    w("            (* Soft Barrier Penalty on Seam Over-compression *)")
    w("            IF m = 2 AND a_MPC_x_traj[k + 1, 3] < 1.050 THEN")
    w("                r_barrier_grad := -r_Barrier_Weight_Thickness * (1.050 - a_MPC_x_traj[k + 1, 3]);")
    w("                r_temp_grad := r_temp_grad + r_barrier_grad;")
    w("            END_IF;")
    w("")
    w("            (* Soft Barrier Penalty on Excessive 2nd Op Ironing Force *)")
    w("            IF m = 2 AND a_MPC_x_traj[k + 1, 3] > 1.450 THEN")
    w("                r_barrier_grad := r_Barrier_Weight_Force * (a_MPC_x_traj[k + 1, 3] - 1.450);")
    w("                r_temp_grad := r_temp_grad + r_barrier_grad;")
    w("            END_IF;")
    w("")
    w("            (* Soft Barrier Penalty on Insufficient Lifter Clamping Preload *)")
    w("            IF m = 3 AND a_MPC_x_traj[k + 1, 7] < 1200.0 THEN")
    w("                r_barrier_grad := -15.0 * (1200.0 - a_MPC_x_traj[k + 1, 7]);")
    w("                r_temp_grad := r_temp_grad + r_barrier_grad;")
    w("            END_IF;")
    w("")
    w("            a_MPC_grad_u[k, m] := r_temp_grad;")
    w("")
    w("            (* Gradient Step *)")
    w("            a_MPC_u_seq[k, m] := a_MPC_u_seq[k, m] - r_MPC_alpha * a_MPC_grad_u[k, m];")
    w("")
    w("            (* Projection onto Box Saturation Constraints *)")
    w("            a_MPC_u_seq[k, m] := MAX(a_MPC_u_min[m], MIN(a_MPC_u_max[m], a_MPC_u_seq[k, m]));")
    w("")
    w("            (* Projection onto Maximum Dynamic Slew Rate *)")
    w("            IF k > 0 THEN")
    w("                IF a_MPC_u_seq[k, m] - a_MPC_u_seq[k - 1, m] > a_MPC_du_max[m] THEN")
    w("                    a_MPC_u_seq[k, m] := a_MPC_u_seq[k - 1, m] + a_MPC_du_max[m];")
    w("                ELSIF a_MPC_u_seq[k, m] - a_MPC_u_seq[k - 1, m] < -a_MPC_du_max[m] THEN")
    w("                    a_MPC_u_seq[k, m] := a_MPC_u_seq[k - 1, m] - a_MPC_du_max[m];")
    w("                END_IF;")
    w("            END_IF;")
    w("        END_FOR;")
    w("    END_FOR;")
    w("END_FOR;")
    w("")

    return "\n".join(lines)

if __name__ == "__main__":
    p5 = get_part5()
    print("Part 5 length:", len(p5))
