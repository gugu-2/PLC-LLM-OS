    emit("    IF rEst_HiPotInsulationRes > 9999.00 THEN")
    emit("        rEst_HiPotInsulationRes := 9999.00;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rEst_HiPotInsulationRes := 5000.00;")
    emit("END_IF;")
    emit("")
    emit("(* 4-Wire Kelvin Contact Resistance True Temperature-Compensated Value [uOhm]: *)")
    emit("(* Compensates for Copper-Aluminum Seebeck thermoelectric EMF (approx 3.5 uV/deg C) *)")
    emit("IF bCmd_KelvinMeterTrigger THEN")
    emit("    rEst_KelvinTrueContactRes := rVoted_KelvinResist_uOhm - (0.0035 * (arrStateX[8] - 25.00));")
    emit("    IF rEst_KelvinTrueContactRes < 0.50 THEN")
    emit("        rEst_KelvinTrueContactRes := 0.50;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rEst_KelvinTrueContactRes := rVoted_KelvinResist_uOhm;")
    emit("END_IF;")
    emit("")

    return "\n".join(L)
