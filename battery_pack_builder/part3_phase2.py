def get_part3():
    L = []
    def emit(s=""):
        L.append(s)

    emit("(* ========================================================================================= *)")
    emit("(* PHASE 2: CYBER-PHYSICAL OBSERVERS, RHEOLOGY & WELD/THERMAL PHYSICS ESTIMATORS            *)")
    emit("(* ========================================================================================= *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("(* 2.1 DUAL-COMPONENT POLYURETHANE HERSCHEL-BULKLEY RHEOLOGY & DISPENSE OBSERVER             *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("(* Volumetric flow rate sum from servo pump feedback [cm3/s] *)")
    emit("IF (arrControlU[1] > 0.050) AND (arrControlU[2] > 0.050) THEN")
    emit("    (* Convert volumetric flow rate from cm3/s to mm3/s (1 cm3 = 1000 mm3) *)")
    emit("    (* Nozzle bore diameter D_nozzle = 3.20 mm, Radius R_nozzle = 1.60 mm *)")
    emit("    (* Cross-sectional nozzle area A_nozzle = pi * R^2 = 3.14159 * 1.60^2 = 8.0425 mm2 *)")
    emit("    (* Mean flow velocity in nozzle v_flow = Q_total_mm3 / A_nozzle *)")
    emit("    (* Apparent wall shear rate gamma_dot = 8.0 * v_flow / D_nozzle = 32.0 * Q_total / (pi * D^3) *)")
    emit("    rEst_ShearRate := (32.0 * (arrControlU[1] + arrControlU[2]) * 1000.00) / (3.141592 * 3.20 * 3.20 * 3.20);")
    emit("    IF rEst_ShearRate < 1.00 THEN")
    emit("        rEst_ShearRate := 1.00; (* Prevent division by zero below yield point *)")
    emit("    END_IF;")
    emit("")
    emit("    (* Herschel-Bulkley Apparent Dynamic Viscosity eta_app [Pa*s]: *)")
    emit("    (* tau_0 = 220.0 Pa (Yield stress), K_hb = 58.5 Pa*s^n, n_hb = 0.42 (Shear-thinning index) *)")
    emit("    (* eta_app = tau_0 / gamma_dot + K_hb * (gamma_dot)^(n_hb - 1) *)")
    emit("    (* Note: (gamma_dot)^(-0.58) approximated via stable polynomial expansion around operating point *)")
    emit("    rEst_DynamicViscosity := (220.00 / rEst_ShearRate) + (58.50 / (1.00 + 0.58 * LN(rEst_ShearRate) + 0.168 * LN(rEst_ShearRate) * LN(rEst_ShearRate)));")
    emit("    IF rEst_DynamicViscosity < 2.50 THEN")
    emit("        rEst_DynamicViscosity := 2.50; (* High-shear lower limit asymptote *)")
    emit("    ELSIF rEst_DynamicViscosity > 180.00 THEN")
    emit("        rEst_DynamicViscosity := 180.00; (* Low-shear upper yield limit *)")
    emit("    END_IF;")
    emit("")
    emit("    (* Hagen-Poiseuille Non-Newtonian Pressure Drop across 65mm static mixer & nozzle tip [bar]: *)")
    emit("    (* Delta P = [ (2 * L_nozzle / R_nozzle) * (tau_0 + K_hb * ((3*n+1)/(4*n) * 4*Q / (pi*R^3))^n) ] * 1.0E-5 bar/Pa *)")
    emit("    rEst_NozzlePressureDrop := (2.0 * 65.00 / 1.60) * (220.00 + 58.50 * (rEst_ShearRate * 0.085)) * 0.000010;")
    emit("")
    emit("    (* Expected bead cross-sectional area A_bead [mm2] = Q_total [mm3/s] / v_robot_tcp [mm/s] *)")
    emit("    IF rVoted_RobotVelocity_mms > 10.00 THEN")
    emit("        rEst_CalculatedBeadArea := ((arrControlU[1] + arrControlU[2]) * 1000.00) / rVoted_RobotVelocity_mms;")
    emit("    ELSE")
    emit("        rEst_CalculatedBeadArea := rSp_BeadCrossSectionArea;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rEst_ShearRate := 0.00;")
    emit("    rEst_DynamicViscosity := 150.00;")
    emit("    rEst_NozzlePressureDrop := 0.00;")
    emit("    rEst_CalculatedBeadArea := 0.00;")
    emit("END_IF;")
    emit("")
    emit("(* Continuous volume integration during active dispensing [cm3 / mL] *)")
    emit("IF (bCmd_NozzleValvePWM > 10.00) AND (arrControlU[1] > 0.10) THEN")
    emit("    rDispenseIntegrator_Volume := rDispenseIntegrator_Volume + (arrControlU[1] + arrControlU[2]) * 0.0050;")
    emit("    rTotalAdhesiveDispensed_mL := rDispenseIntegrator_Volume;")
    emit("END_IF;")
    emit("")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("(* 2.2 FIBER LASER WELD POOL ROSENTHAL THERMAL MODEL & KEYHOLE PENETRATION                   *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("IF (bCmd_LaserEmissionEnable) AND (arrControlU[4] > 0.100) THEN")
    emit("    (* Temperature-dependent Fresnel optical absorption efficiency eta_opt at 1070 nm: *)")
    emit("    (* Solid Cu absorption starts at approx 5.0%, jumping to 18-24% at melting point (1085 deg C) *)")
    emit("    (* and exceeding 65% inside multi-reflection keyhole vapor cavity *)")
    emit("    IF rVoted_PyrometerTemp_degC < 1085.00 THEN")
    emit("        rEst_LaserAbsorptivity := 0.0500 + 0.000120 * (rVoted_PyrometerTemp_degC - 25.00);")
    emit("    ELSIF rVoted_PyrometerTemp_degC < 2562.00 THEN (* Copper boiling point 2562 deg C *)")
    emit("        rEst_LaserAbsorptivity := 0.1800 + 0.000280 * (rVoted_PyrometerTemp_degC - 1085.00);")
    emit("    ELSE")
    emit("        rEst_LaserAbsorptivity := 0.6500; (* Trapped multi-reflection keyhole mode *)")
    emit("    END_IF;")
    emit("")
    emit("    (* 3D Moving Heat Source Rosenthal Surface Peak Temperature [deg C]: *)")
    emit("    (* T_peak = T_ambient + [ (eta_abs * P_laser) / (2 * pi * k_th * r_eff) ] *)")
    emit("    (* For Cu/Al busbar joint: k_th_eff = 280.0 W/(m*K), r_eff = 0.65 mm = 0.00065 m *)")
    emit("    rEst_RosenthalSurfaceTemp := 25.00 + (rEst_LaserAbsorptivity * arrControlU[4] * 1000.00) / (2.00 * 3.141592 * 280.00 * 0.00065);")
    emit("")
    emit("    (* Keyhole Vapor Capillary Penetration Depth d_pen [um]: *)")
    emit("    (* d_pen = K_pen * [ (eta_abs * P_laser_W) / (v_weld_mms * sqrt(2 * R_wobble_mm * d_spot_mm)) ] *)")
    emit("    (* K_pen = 0.0385 um*mm2 / (W*s) *)")
    emit("    IF (rVoted_RobotVelocity_mms > 5.00) AND (arrControlU[6] > 0.10) THEN")
    emit("        rEst_WeldPenetrationDepth := 0.0385 * (rEst_LaserAbsorptivity * arrControlU[4] * 1000.00) /")
    emit("                                     (rVoted_RobotVelocity_mms * SQRT(2.0 * arrControlU[6] * 0.120));")
    emit("    ELSE")
    emit("        rEst_WeldPenetrationDepth := 850.00; (* Default nominal target fallback *)")
    emit("    END_IF;")
    emit("")
    emit("    (* Spatter Dynamic Instability Index (0-100%): *)")
    emit("    (* Evaluates plume optical radiation fluctuations relative to core pyrometry *)")
    emit("    IF rVoted_PyrometerTemp_degC > 2100.00 THEN")
    emit("        rEst_SpatterInstabilityRisk := (rVoted_PyrometerTemp_degC - 2100.00) * 0.25 + (rVoted_PlumeIntensity_pct * 0.35);")
    emit("    ELSE")
    emit("        rEst_SpatterInstabilityRisk := rVoted_PlumeIntensity_pct * 0.20;")
    emit("    END_IF;")
    emit("    IF rEst_SpatterInstabilityRisk > 100.00 THEN")
    emit("        rEst_SpatterInstabilityRisk := 100.00;")
    emit("    END_IF;")
    emit("")
    emit("    (* Cumulative Laser Optical Energy Integration [kJ] (P in kW * 0.005 s = kJ) *)")
    emit("    rLaserEnergyIntegrator_kJ := rLaserEnergyIntegrator_kJ + (arrControlU[4] * 0.0050);")
    emit("    rTotalLaserEnergyDelivered_kJ := rLaserEnergyIntegrator_kJ;")
    emit("ELSE")
    emit("    rEst_LaserAbsorptivity := 0.050;")
    emit("    rEst_RosenthalSurfaceTemp := 25.00;")
    emit("    rEst_WeldPenetrationDepth := 0.00;")
    emit("    rEst_SpatterInstabilityRisk := 0.00;")
    emit("END_IF;")
    emit("")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("(* 2.3 HIGH-VOLTAGE HI-POT INSULATION & KELVIN MICRO-OHMMETER OBSERVER                       *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
