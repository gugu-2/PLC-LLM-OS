"""
Part 5: Phase 4 (Actuator Control Conditioning, Galvo Scanner Wobble Trajectories, Laser Safety Interlocks & Gas Flow)
"""

def get_part5():
    L = []
    def emit(s=""):
        L.append(s)

    emit("(* ========================================================================================= *)")
    emit("(* PHASE 4: ACTUATOR CONTROL CONDITIONING, GALVO SCANNER & LASER SAFETY GATING              *)")
    emit("(* ========================================================================================= *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("(* 4.1 Galvo Scanner Wobble Scan Trajectory Kinematics (Circular & Elliptical Oscillation)   *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("IF (bCmd_LaserEmissionEnable) AND (arrControlU[5] > 50.00) THEN")
    emit("    (* Dynamic phase angle increment: Delta theta = 2.0 * pi * f_wobble * Ts (Ts = 0.005 s) *)")
    emit("    rWobbleScanPhaseAngle := rWobbleScanPhaseAngle + (2.0 * 3.141592 * arrControlU[5] * 0.0050);")
    emit("    IF rWobbleScanPhaseAngle >= (2.0 * 3.141592) THEN")
    emit("        rWobbleScanPhaseAngle := rWobbleScanPhaseAngle - (2.0 * 3.141592);")
    emit("    END_IF;")
    emit("")
    emit("    (* Circular wobble scan path: X = (D/2)*cos(theta), Y = (D/2)*sin(theta) *)")
    emit("    rCmd_GalvoScannerAmpX := (arrControlU[6] * 0.50) * COS(rWobbleScanPhaseAngle);")
    emit("    rCmd_GalvoScannerAmpY := (arrControlU[6] * 0.50) * SIN(rWobbleScanPhaseAngle);")
    emit("    rCmd_GalvoScannerFreq := arrControlU[5];")
    emit("ELSE")
    emit("    rWobbleScanPhaseAngle := 0.00;")
    emit("    rCmd_GalvoScannerAmpX := 0.00;")
    emit("    rCmd_GalvoScannerAmpY := 0.00;")
    emit("    rCmd_GalvoScannerFreq := 0.00;")
    emit("END_IF;")
    emit("")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("(* 4.2 Class 4 Laser Safety Enclosure Hardware Interlock & Emission Gating                   *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("IF (NOT bEStopOk) OR")
    emit("   (NOT bLaserEnclosureDoorClosed) OR")
    emit("   (NOT bFumeExtractionRunning) OR")
    emit("   (NOT bLaserCoolingFlowOk) OR")
    emit("   (bCycleFaultAbortLatched) THEN")
    emit("    (* Emergency Hardware Laser Gating Inhibit *)")
    emit("    bCmd_LaserEmissionEnable := FALSE;")
    emit("    rCmd_LaserAnalogPower := 0.00;")
    emit("    bCmd_CrossJetAirKnife := FALSE;")
    emit("    rCmd_ShieldGasValveDuty := 0.00;")
    emit("    dwAlarmWord3_SafetyHiPot := dwAlarmWord3_SafetyHiPot OR 16#00000001; (* Safety Interlock Trip *)")
    emit("ELSE")
    emit("    (* Normal Laser Emission State Permissive: only allowed in FSM Step 10 (WELD_ACTIVE) *)")
    emit("    IF (nFsmState = 10) THEN")
    emit("        bCmd_LaserEmissionEnable := TRUE;")
    emit("        rCmd_LaserAnalogPower := arrControlU[4];")
    emit("        bCmd_CrossJetAirKnife := TRUE;")
    emit("        (* Shield gas proportional valve scaling: 0 to 40 l/min -> 0 to 100% duty *)")
    emit("        rCmd_ShieldGasValveDuty := (arrControlU[7] / 40.00) * 100.00;")
    emit("        IF rCmd_ShieldGasValveDuty > 100.00 THEN")
    emit("            rCmd_ShieldGasValveDuty := 100.00;")
    emit("        END_IF;")
    emit("    ELSE")
    emit("        bCmd_LaserEmissionEnable := FALSE;")
    emit("        rCmd_LaserAnalogPower := 0.00;")
    emit("        IF (nFsmState = 9) OR (nFsmState = 11) THEN")
    emit("            (* Maintain optics protective cross-jet and shield gas pre/post purge *)")
    emit("            bCmd_CrossJetAirKnife := TRUE;")
    emit("            rCmd_ShieldGasValveDuty := 35.00; (* 35% purge flow *)")
    emit("        ELSE")
    emit("            bCmd_CrossJetAirKnife := FALSE;")
    emit("            rCmd_ShieldGasValveDuty := 0.00;")
    emit("        END_IF;")
    emit("    END_IF;")
    emit("END_IF;")
    emit("")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("(* 4.3 Polyurethane Volumetric Dispense Servo Pumps & Snuff-Back Shot Nozzle                *)")
    emit("(* ----------------------------------------------------------------------------------------- *)")
    emit("IF (nFsmState = 5) THEN")
    emit("    (* Active Dispensing State: assign closed-loop MPC optimized flow rates *)")
    emit("    rCmd_ServoPumpA_Flow := arrControlU[1];")
    emit("    rCmd_ServoPumpB_Flow := arrControlU[2];")
    emit("    rCmd_NozzleValvePWM := 100.00; (* Full nozzle shot valve open *)")
    emit("    rCmd_RobotVelOverride := arrControlU[3];")
    emit("ELSIF (nFsmState = 6) THEN")
    emit("    (* Snuff-Back Cutoff Phase: reverse metering pumps by 0.5 cm3 to suck back adhesive droplet *)")
    emit("    rCmd_ServoPumpA_Flow := -0.50;")
    emit("    rCmd_ServoPumpB_Flow := -0.50;")
    emit("    rCmd_NozzleValvePWM := 0.00; (* Closed snuff-back position *)")
    emit("    rCmd_RobotVelOverride := 100.00;")
    emit("ELSIF (nFsmState = 4) THEN")
    emit("    (* Nozzle Prime and Purge Phase *)")
    emit("    rCmd_ServoPumpA_Flow := 4.50;")
    emit("    rCmd_ServoPumpB_Flow := 4.50;")
    emit("    rCmd_NozzleValvePWM := 100.00;")
    emit("    rCmd_RobotVelOverride := 25.00;")
    emit("ELSE")
    emit("    rCmd_ServoPumpA_Flow := 0.00;")
    emit("    rCmd_ServoPumpB_Flow := 0.00;")
    emit("    rCmd_NozzleValvePWM := 0.00;")
    emit("    rCmd_RobotVelOverride := 100.00;")
    emit("END_IF;")
    emit("")
    emit("(* High-Speed Fume Extraction Boost Logic *)")
    emit("IF (nFsmState = 3) OR (nFsmState = 5) OR (nFsmState = 10) THEN")
    emit("    bCmd_FumeExtractorBoost := TRUE;")
    emit("ELSE")
    emit("    bCmd_FumeExtractorBoost := FALSE;")
    emit("END_IF;")
    emit("")

    return "\n".join(L)
