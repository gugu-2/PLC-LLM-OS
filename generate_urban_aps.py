    # Phase 4: Dynamic Vehicle Envelope & CoG Optimization
    c.append("(* === PHASE 4: VEHICLE ENVELOPE & DYNAMIC TORQUE COMPENSATION === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Verifies vehicle physical envelope against vault clearance standards.                     *)")
    c.append("(* Computes VFD torque limit offsets based on CoG eccentricities and gross vehicle payload.  *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("")
    c.append("(* 4.1 Envelope Dimension Verification *)")
    c.append("IF (rScannedVehicleLength_mm <= c_MaxVehicleLength_mm) AND")
