    # CoG and Mass Calculations
    c.append("(* Total Gross Vehicle Mass and CoG Computation *)")
    c.append("rVoted_TotalVehicleMass_Kg := rVoted_FrontLeftWeight + rVoted_FrontRightWeight + rVoted_RearLeftWeight + rVoted_RearRightWeight;")
