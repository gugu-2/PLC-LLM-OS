    # Phase 5: Multi-Stage FSM
    c.append("(* === PHASE 5: MULTI-STAGE CASE FINITE STATE MACHINE === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Coordinates automated parking vault operations: Entry inspection, weigh & lock, door     *)")
    c.append("(* latch, vertical hoist transit, shuttle alignment, comb plate deposit, and home return.    *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("CASE iActiveFSM_State OF")
    c.append("")
    c.append("    0: (* STATE 0: STANDBY IDLE & CABIN READY *)")
