    c.append("(* 4.2 Dynamic VFD Torque Limit Clamping *)")
    c.append("IF rVoted_TotalVehicleMass_Kg > 2800.0 THEN")
    c.append("    (* Heavy SUV / EV mode: Increase torque headroom, clamp max lift speed to 75% *)")
    c.append("    rHoistVFD_TorqueLimit_Pct := 140.0;")
    c.append("ELSIF rVoted_TotalVehicleMass_Kg > 1500.0 THEN")
    c.append("    rHoistVFD_TorqueLimit_Pct := 115.0;")
    c.append("ELSE")
    c.append("    rHoistVFD_TorqueLimit_Pct := 100.0;")
