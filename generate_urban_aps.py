    c.append("            ELSE")
    c.append("                (* Unbalanced load *)")
    c.append("                dwAlarmWord1 := dwAlarmWord1 OR 16#0000_0002;")
    c.append("            END_IF;")
    c.append("        END_IF;")
    c.append("")
    c.append("    30: (* STATE 30: ENTRY CABIN DOOR INTERLOCK VERIFICATION & PAWL RETRACT *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF bEntryRollDoorClosed_Fbk AND bCabinSafetyCurtainIntact THEN")
    c.append("            bCabinDoorLocked := TRUE;")
    c.append("            bLockingPawlExtend_Cmd := FALSE; (* Retract leveling pawls *)")
    c.append("            bHoistBrakeRelease_Cmd := TRUE;  (* Energize brake release *)")
    c.append("            IF rStateDwellTimer_Sec >= 1.5 THEN")
    c.append("                rTargetLevelElevation_mm := DINT_TO_REAL(iTargetVaultLevel) * c_FloorPitchElevation_mm;")
    c.append("                rTargetBayPosition_mm := DINT_TO_REAL(iTargetVaultBaySlot) * c_BaySlotPitchWidth_mm;")
