    c.append("rDiffBC := ABS(rLoadCell_RearRight_B - rLoadCell_RearRight_C);")
    c.append("rDiffCA := ABS(rLoadCell_RearRight_C - rLoadCell_RearRight_A);")
    c.append("bHealthy_RearRightWeight_A := (rDiffAB <= c_Tolerance_CornerWeight) OR (rDiffCA <= c_Tolerance_CornerWeight);")
    c.append("bHealthy_RearRightWeight_B := (rDiffAB <= c_Tolerance_CornerWeight) OR (rDiffBC <= c_Tolerance_CornerWeight);")
    c.append("bHealthy_RearRightWeight_C := (rDiffBC <= c_Tolerance_CornerWeight) OR (rDiffCA <= c_Tolerance_CornerWeight);")
    c.append("IF bHealthy_RearRightWeight_A AND bHealthy_RearRightWeight_B AND bHealthy_RearRightWeight_C THEN")
