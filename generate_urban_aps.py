    c.append("    20: (* STATE 20: PLATFORM WEIGHBRIDGE & CENTER-OF-GRAVITY LOCK *)")
    c.append("        rStateDwellTimer_Sec := rStateDwellTimer_Sec + rCycleScanTime_Ts;")
    c.append("        IF (rStateDwellTimer_Sec >= 2.0) AND (rVoted_TotalVehicleMass_Kg <= c_MaxRatedPayloadMass_Kg) THEN")
    c.append("            IF (ABS(rCoG_LongitudinalOffset_mm) <= rMaxAllowableCoG_Offset_mm) AND (ABS(rCoG_LateralOffset_mm) <= rMaxAllowableCoG_Offset_mm) THEN")
