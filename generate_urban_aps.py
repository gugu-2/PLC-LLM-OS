    c.append("    rCoG_LateralOffset_mm := (((rVoted_FrontLeftWeight + rVoted_RearLeftWeight) * (rNominalTrackWidth_mm * 0.5)) - ((rVoted_FrontRightWeight + rVoted_RearRightWeight) * (rNominalTrackWidth_mm * 0.5))) / rVoted_TotalVehicleMass_Kg;")
    c.append("ELSE")
    c.append("    rCoG_LongitudinalOffset_mm := 0.0;")
    c.append("    rCoG_LateralOffset_mm := 0.0;")
    c.append("END_IF;")
    c.append("")
    c.append("(* Traction Sheave Net Imbalance: F_net = ((M_cage + M_veh) - M_cwt) * g *)")
    c.append("rNetHoistImbalanceForce_kN := (((c_HoistCageTareMass_Kg + rVoted_TotalVehicleMass_Kg) - c_CounterweightMass_Kg) * c_GravitationalAcc) / 1000.0;")
    c.append("")
    c.append("(* Velocity & Acceleration Observers *)")
    c.append("rMeasuredHoistVelocity_mps := ((rVoted_HoistPos_Z - rPrevHoistPosition_mm) / 1000.0) / rCycleScanTime_Ts;")
    c.append("rPrevHoistPosition_mm := rVoted_HoistPos_Z;")
    c.append("rMeasuredHoistAcceleration_mps2 := (rMeasuredHoistVelocity_mps - rPrevHoistVelocity_mps) / rCycleScanTime_Ts;")
    c.append("rPrevHoistVelocity_mps := rMeasuredHoistVelocity_mps;")
    c.append("")
    c.append("(* Synchronize State Vector *)")
    c.append("rState_Vector_x[1] := rVoted_HoistPos_Z;")
    c.append("rState_Vector_x[2] := rMeasuredHoistVelocity_mps * 1000.0;")
    c.append("rState_Vector_x[3] := rMeasuredHoistAcceleration_mps2 * 1000.0;")
    c.append("rState_Vector_x[4] := rVoted_ShuttlePos_Y;")
    c.append("rState_Vector_x[6] := rVoted_CombExtension_X;")
    c.append("")

    # Phase 2: State-Space Prediction
    c.append("(* === PHASE 2: STATE-SPACE PREDICTION (x[k+1] = A*x[k] + B*u[k]) === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Evaluates matrix multiplication for 6-state, 3-control multi-axis robotic parking motions. *)")
    c.append("(* Propagates state trajectory forward in time across discrete scan interval Ts = 5 ms.      *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("FOR iIdx := 1 TO 6 DO")
    c.append("    rMatrixAcc := 0.0;")
    c.append("    FOR jIdx := 1 TO 6 DO")
    c.append("        rMatrixAcc := rMatrixAcc + (A_Matrix[iIdx, jIdx] * rState_Vector_x[jIdx]);")
    c.append("    END_FOR;")
    c.append("    FOR kIdx := 1 TO 3 DO")
    c.append("        rMatrixAcc := rMatrixAcc + (B_Matrix[iIdx, kIdx] * rControl_Vector_u[kIdx]);")
    c.append("    END_FOR;")
    c.append("    rState_Vector_x_pred[iIdx] := rMatrixAcc;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Enforce physical travel limits *)")
