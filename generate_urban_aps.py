    c.append("")
    c.append("    IF rControl_Vector_u[3] < c_u3_Min THEN")
    c.append("        rControl_Vector_u[3] := c_u3_Min;")
    c.append("    ELSIF rControl_Vector_u[3] > c_u3_Max THEN")
    c.append("        rControl_Vector_u[3] := c_u3_Max;")
    c.append("    END_IF;")
    c.append("END_FOR;")
    c.append("")
    c.append("(* Actuator Slew Rate Limiter Implementation *)")
