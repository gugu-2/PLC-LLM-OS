    c.append("        rVoted_RearRightWeight := rLoadCell_RearRight_A;")
    c.append("    ELSIF (rLoadCell_RearRight_B >= rLoadCell_RearRight_A AND rLoadCell_RearRight_B <= rLoadCell_RearRight_C) OR (rLoadCell_RearRight_B >= rLoadCell_RearRight_C AND rLoadCell_RearRight_B <= rLoadCell_RearRight_A) THEN")
    c.append("        rVoted_RearRightWeight := rLoadCell_RearRight_B;")
