    c.append("(* === PHASE 3: RECEDING-HORIZON MPC CONTROL ACTION === *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("(* Solves receding-horizon quadratic optimization over control horizon Nc = 3:             *)")
    c.append("(* min J = (x_pred - x_ref)^T * Q * (x_pred - x_ref) + u^T * R * u + Delta_u^T * S * Delta_u *)")
    c.append("(* Coordinates multi-axis hoist and shuttle speed profiles with smooth deceleration.        *)")
    c.append("(* ----------------------------------------------------------------------------------------- *)")
    c.append("FOR rMPC_IterationCount := 1 TO rMPC_MaxIterations DO")
    c.append("    FOR kIdx := 1 TO 3 DO")
