# Module to generate Finite State Machine and Output Packing for FB_AdditiveManufacturing_MultiLaserPBF_ThermalSync

def get_section_fsm_lines():
    return [
        "(* ==================================================================================== *)",
        "(* SECTION 10: MULTI-STAGE HIERARCHICAL FINITE STATE MACHINE (FSM)                      *)",
        "(* State 0   : UNINITIALIZED_COLD_BOOT                                                  *)",
        "(* State 10  : SAFETY_CIRCUIT_HEALTH_CHECK                                               *)",
        "(* State 20  : INERT_GAS_PURGE_AND_PRESSURE_SEAL                                        *)",
        "(* State 30  : SUBSTRATE_PREHEAT_HOMING                                                 *)",
        "(* State 40  : POWDER_DOSE_AND_RECOAT_PASS                                               *)",
        "(* State 50  : SCANHEAD_PREFLIGHT_AND_STITCH_MAP                                        *)",
        "(* State 60  : MULTI_BEAM_EXPOSURE_MPC_ACTIVE                                           *)",
        "(* State 70  : INTER_LAYER_THERMAL_EQUILIBRATION                                        *)",
        "(* State 80  : SUBSTRATE_INCREMENTAL_INDEXING                                           *)",
        "(* State 90  : GRACEFUL_DEGRADATION_RECONFIGURATION                                     *)",
        "(* State 95  : ABNORMAL_RECOATER_RETRACT_RECOVERY                                       *)",
        "(* State 100 : EMERGENCY_SHUTDOWN_PURGE                                                 *)",
        "(* ==================================================================================== *)",
        "",
        "CASE iState OF",
        "    0: (* --- UNINITIALIZED COLD BOOT --- *)",
        "        bSystemReady := FALSE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#0000;",
        "        rLaser1_ModulatedPower_W := 0.0;",
        "        rLaser2_ModulatedPower_W := 0.0;",
        "        rLaser3_ModulatedPower_W := 0.0;",
        "        rLaser4_ModulatedPower_W := 0.0;",
        "        ",
        "        IF bMasterEnable AND (NOT bAnySafetyTrip) THEN",
        "            iPrevState := iState;",
        "            iState := 10; (* Transition to Safety Check *)",
        "        END_IF;",
        "",
        "    10: (* --- SAFETY CIRCUIT HEALTH CHECK --- *)",
        "        bSystemReady := FALSE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#000A;",
        "        ",
        "        IF bEmergencyStop_ChA AND bEmergencyStop_ChB AND bSafetyDoorInterlock AND (NOT tonEStopDiscrepancy.Q) THEN",
        "            iPrevState := iState;",
        "            iState := 20; (* Proceed to Inert Gas Purge *)",
        "        ELSIF bAnySafetyTrip THEN",
        "            iPrevState := iState;",
        "            iState := 100; (* Trip to Emergency Shutdown *)",
        "        END_IF;",
        "",
        "    20: (* --- INERT GAS PURGE AND PRESSURE REGULATION --- *)",
        "        bSystemReady := FALSE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#0014;",
        "        ",
        "        (* 300 second purge timeout monitoring *)",
        "        tonPurgeTimeout(IN := (iState = 20), PT := T#300S);",
        "        ",
        "        IF (rO2_VotedValue_ppm < 80.0) AND (rPressure_VotedValue_mbar >= 12.0) AND (rPressure_VotedValue_mbar <= 25.0) THEN",
        "            tonPurgeTimeout(IN := FALSE, PT := T#300S);",
        "            iPrevState := iState;",
        "            iState := 30; (* Proceed to Substrate Preheat *)",
        "        ELSIF tonPurgeTimeout.Q THEN",
        "            arrAlarm_Active[3] := TRUE;",
        "            iPrevState := iState;",
        "            iState := 100; (* Purge failure -> Shutdown *)",
        "        END_IF;",
        "",
        "    30: (* --- SUBSTRATE PREHEAT & THERMAL HOMING --- *)",
        "        bSystemReady := FALSE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#001E;",
        "        ",
        "        (* Settle timer for uniform heat distribution across 500x500mm plate *)",
        "        tonPreheatSettle(IN := (ABS(rTemp_VotedValue_degC - rPlatformTempSetpoint_degC) <= 3.0), PT := T#60S);",
        "        ",
        "        IF tonPreheatSettle.Q THEN",
        "            bSystemReady := TRUE;",
        "            iPrevState := iState;",
        "            iState := 40; (* Ready to Recoat *)",
        "        END_IF;",
        "",
        "    40: (* --- POWDER DOSE & RECOATER PASS --- *)",
        "        bSystemReady := TRUE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#0028;",
        "        ",
        "        tonRecoaterPass(IN := (iState = 40), PT := T#25S);",
        "        ",
        "        IF bRecoaterBladeJamTrip OR bRecoaterCollisionAlert THEN",
        "            iPrevState := iState;",
        "            iState := 95; (* Collision abort and blade retract *)",
        "        ELSIF (rRecoaterBladePosition_mm >= 550.0) OR tonRecoaterPass.Q THEN",
        "            tonRecoaterPass(IN := FALSE, PT := T#25S);",
        "            iPrevState := iState;",
        "            iState := 50; (* Preflight Galvo Planning *)",
        "        END_IF;",
        "",
        "    50: (* --- SCANHEAD PREFLIGHT & STITCH MAP ARBITRATION --- *)",
        "        bSystemReady := TRUE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#0032;",
        "        ",
        "        IF bLayerTrigger THEN",
        "            dintCurrentLayerIndex := dintCurrentLayerIndex + 1;",
        "            rTotalEnergyDeposited_kJ := 0.0;",
        "            iPrevState := iState;",
        "            iState := 60; (* Initiate Active Exposure *)",
        "        END_IF;",
        "",
        "    60: (* --- MULTI-BEAM EXPOSURE WITH ACTIVE MPC & STITCHING --- *)",
        "        bSystemReady := TRUE;",
        "        bProcessActive := TRUE;",
        "        wSystemStateWord := 16#003C;",
        "        ",
        "        (* Layer execution watchdog: 120s max exposure duration *)",
        "        tonLayerWatchdog(IN := (iState = 60), PT := T#120S);",
        "        ",
        "        (* Real-time energy deposition integration: E = Sum(P_i * Ts) *)",
        "        rTotalEnergyDeposited_kJ := rTotalEnergyDeposited_kJ +",
        "            ((rLaser1_ModulatedPower_W + rLaser2_ModulatedPower_W + rLaser3_ModulatedPower_W + rLaser4_ModulatedPower_W) * 0.000100 * 0.001);",
        "        ",
        "        IF bGracefulDegradationActive AND (iDegradedLaserMask <> 16#0F) THEN",
        "            iPrevState := iState;",
        "            iState := 90; (* Reconfigure optical paths *)",
        "        ELSIF bOxygen2oo3Trip OR bPressure2oo3Trip OR bAnySafetyTrip THEN",
        "            iPrevState := iState;",
        "            iState := 100; (* Emergency shutdown *)",
        "        ELSIF (NOT bLayerTrigger) OR tonLayerWatchdog.Q THEN",
        "            tonLayerWatchdog(IN := FALSE, PT := T#120S);",
        "            rLaser1_ModulatedPower_W := 0.0;",
        "            rLaser2_ModulatedPower_W := 0.0;",
        "            rLaser3_ModulatedPower_W := 0.0;",
        "            rLaser4_ModulatedPower_W := 0.0;",
        "            iPrevState := iState;",
        "            iState := 70; (* Inter-layer cooldown *)",
        "        END_IF;",
        "",
        "    70: (* --- INTER-LAYER THERMAL EQUILIBRATION --- *)",
        "        bSystemReady := TRUE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#0046;",
        "        ",
        "        (* Allow 2.5 seconds for surface pool to reach preheat plateau *)",
        "        tonPreheatSettle(IN := (iState = 70), PT := T#2500MS);",
        "        ",
        "        IF tonPreheatSettle.Q THEN",
        "            tonPreheatSettle(IN := FALSE, PT := T#2500MS);",
        "            iPrevState := iState;",
        "            iState := 80; (* Index Z Platform *)",
        "        END_IF;",
        "",
        "    80: (* --- SUBSTRATE INCREMENTAL INDEXING --- *)",
        "        bSystemReady := TRUE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#0050;",
        "        ",
        "        (* Indexing completed signal simulation (500 ms) *)",
        "        tonPreheatSettle(IN := (iState = 80), PT := T#500MS);",
        "        ",
        "        IF tonPreheatSettle.Q THEN",
        "            tonPreheatSettle(IN := FALSE, PT := T#500MS);",
        "            iPrevState := iState;",
        "            iState := 40; (* Loop back to powder recoating *)",
        "        END_IF;",
        "",
        "    90: (* --- GRACEFUL DEGRADATION RECONFIGURATION --- *)",
        "        bSystemReady := TRUE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#005A;",
        "        ",
        "        (* Settle scanhead vectors for 50 ms before re-entering exposure *)",
        "        tonPreheatSettle(IN := (iState = 90), PT := T#50MS);",
        "        ",
        "        IF tonPreheatSettle.Q THEN",
        "            tonPreheatSettle(IN := FALSE, PT := T#50MS);",
        "            iPrevState := iState;",
        "            iState := 60; (* Resume exposure with degraded mask *)",
        "        END_IF;",
        "",
        "    95: (* --- ABNORMAL RECOATER RETRACT & OBSTACLE RECOVERY --- *)",
        "        bSystemReady := FALSE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#005F;",
        "        rLaser1_ModulatedPower_W := 0.0;",
        "        rLaser2_ModulatedPower_W := 0.0;",
        "        rLaser3_ModulatedPower_W := 0.0;",
        "        rLaser4_ModulatedPower_W := 0.0;",
        "        ",
        "        (* Wait for manual operator inspection or reverse command *)",
        "        IF bAcknowledgeFaults AND (NOT bRecoaterBladeJamTrip) AND (NOT bRecoaterCollisionAlert) THEN",
        "            iPrevState := iState;",
        "            iState := 40; (* Re-attempt recoater pass *)",
        "        END_IF;",
        "",
        "    100: (* --- EMERGENCY SHUTDOWN PURGE --- *)",
        "        bSystemReady := FALSE;",
        "        bProcessActive := FALSE;",
        "        wSystemStateWord := 16#0064;",
        "        rLaser1_ModulatedPower_W := 0.0;",
        "        rLaser2_ModulatedPower_W := 0.0;",
        "        rLaser3_ModulatedPower_W := 0.0;",
        "        rLaser4_ModulatedPower_W := 0.0;",
        "        rLaser1_ModulatedSpeed_mmpers := 0.0;",
        "        rLaser2_ModulatedSpeed_mmpers := 0.0;",
        "        rLaser3_ModulatedSpeed_mmpers := 0.0;",
        "        rLaser4_ModulatedSpeed_mmpers := 0.0;",
        "        ",
        "        IF bAcknowledgeFaults AND (NOT bAnySafetyTrip) AND (NOT bOxygen2oo3Trip) AND (NOT bPressure2oo3Trip) THEN",
        "            iPrevState := iState;",
        "            iState := 0; (* Reset to cold boot state *)",
        "        END_IF;",
        "",
        "    ELSE",
        "        iPrevState := iState;",
        "        iState := 0;",
        "END_CASE;",
        ""
    ]

def get_section_output_packing_lines():
    return [
        "(* ==================================================================================== *)",
        "(* SECTION 11: FINAL DIAGNOSTIC PACKING & PROCESS SUPERVISORY EQUILIBRATION             *)",
        "(* ==================================================================================== *)",
        "wSystemStateWord := (wSystemStateWord AND 16#00FF) OR SHL(INT_TO_WORD(iState), 8);",
        "",
        "(* If system is unready or process inactive, guarantee optical zero-emission *)",
        "IF NOT bProcessActive THEN",
        "    rLaser1_ModulatedPower_W := 0.0;",
        "    rLaser2_ModulatedPower_W := 0.0;",
        "    rLaser3_ModulatedPower_W := 0.0;",
        "    rLaser4_ModulatedPower_W := 0.0;",
        "END_IF;",
        ""
    ]

print("FSM and Output Packing lines generated")
