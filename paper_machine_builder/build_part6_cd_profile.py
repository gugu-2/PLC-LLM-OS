def generate_cd_profile():
    lines = []
    def emit(s=""):
        lines.append(s)

    emit("(* =========================================================================================== *)")
    emit("(* PHASE 4: 48-ZONE CROSS-DIRECTION (CD) SLICE LIP PROFILING & SPATIAL DECOUPLING              *)")
    emit("(* Machine-Direction / Cross-Direction (MD/CD) Decoupling & Continuous Spatial FIR Filtering   *)")
    emit("(* 8.50 m Sheet Deckle Width, 48 Motorized Thermal Micro-Actuator Spindles                     *)")
    emit("(* =========================================================================================== *)")
    emit("")
    emit("(* --- 1. In-Line Scanner Carriage Transverse Position to Zone Binning --- *)")
    emit("IF rCONST_SHEET_DECKLE_WIDTH_M > 0.0 THEN")
    emit("    iZoneIdx := REAL_TO_INT((rScannerCrossHeadPosition_m / rCONST_SHEET_DECKLE_WIDTH_M) * 47.0) + 1;")
    emit("ELSE")
    emit("    iZoneIdx := 24;")
    emit("END_IF;")
    emit("IF iZoneIdx < 1 THEN")
    emit("    iZoneIdx := 1;")
    emit("ELSIF iZoneIdx > 48 THEN")
    emit("    iZoneIdx := 48;")
    emit("END_IF;")
    emit("")
    emit("(* Ingest Real-Time Scanner Measurements into Active CD Zone Bin *)")
    emit("rCD_RawBasisWeightProfile[iZoneIdx] := rVotedBasisWeight_GSM;")
    emit("rCD_RawMoistureProfile[iZoneIdx]    := rVotedMoisture_Pct;")
    emit("rCD_CaliperProfile[iZoneIdx]        := rScannerLaserCaliper_Raw_um;")
    emit("")
    emit("(* --- 2. Continuous Spatial Gaussian FIR Smoothing Filter across 48 CD Zones --- *)")
    emit("FOR iZoneIdx := 1 TO 48 DO")
    emit("    (* Boundary Neighbor Resolution *)")
    emit("    IF iZoneIdx = 1 THEN")
    emit("        iLeftNeighbor  := 1;")
    emit("        iRightNeighbor := 2;")
    emit("    ELSIF iZoneIdx = 48 THEN")
    emit("        iLeftNeighbor  := 47;")
    emit("        iRightNeighbor := 48;")
    emit("    ELSE")
    emit("        iLeftNeighbor  := iZoneIdx - 1;")
    emit("        iRightNeighbor := iZoneIdx + 1;")
    emit("    END_IF;")
    emit("")
    emit("    (* 3-Point Symmetric Spatial Smoothing Filter: [0.20, 0.60, 0.20] *)")
    emit("    rCD_FilteredBasisWeight[iZoneIdx] :=")
    emit("        (0.20 * rCD_RawBasisWeightProfile[iLeftNeighbor]) +")
    emit("        (0.60 * rCD_RawBasisWeightProfile[iZoneIdx]) +")
    emit("        (0.20 * rCD_RawBasisWeightProfile[iRightNeighbor]);")
    emit("")
    emit("    rCD_FilteredMoisture[iZoneIdx] :=")
    emit("        (0.20 * rCD_RawMoistureProfile[iLeftNeighbor]) +")
    emit("        (0.60 * rCD_RawMoistureProfile[iZoneIdx]) +")
    emit("        (0.20 * rCD_RawMoistureProfile[iRightNeighbor]);")
    emit("")
    emit("    (* Apply Parabolic Web Shrinkage Compensation to Weight Error *)")
    emit("    rCD_WeightDeviationError[iZoneIdx] :=")
    emit("        (rCD_FilteredBasisWeight[iZoneIdx] * rShrinkageProfileCorrection[iZoneIdx]) - rTargetBasisWeight_GSM;")
    emit("")
    emit("    (* Local Zone Discrete PI Controller with Anti-Windup *)")
    emit("    IF eCurrentFsmState >= STATE_SCANNER_CD_PROFILE_LOCK THEN")
    emit("        rCD_ActuatorIntegralError[iZoneIdx] := rCD_ActuatorIntegralError[iZoneIdx] +")
    emit("            (rCD_WeightDeviationError[iZoneIdx] * rDeltaTime_Seconds);")
    emit("")
    emit("        (* Anti-windup clamping on local integrator *)")
    emit("        IF rCD_ActuatorIntegralError[iZoneIdx] > 80.0 THEN")
    emit("            rCD_ActuatorIntegralError[iZoneIdx] := 80.0;")
    emit("        ELSIF rCD_ActuatorIntegralError[iZoneIdx] < -80.0 THEN")
    emit("            rCD_ActuatorIntegralError[iZoneIdx] := -80.0;")
    emit("        END_IF;")
    emit("")
    emit("        (* Inverse Action: Increasing slice gap increases local fiber weight *)")
    emit("        rCD_SliceActuatorInternal[iZoneIdx] := 50.0 -")
    emit("            (rSliceGainKp * rCD_WeightDeviationError[iZoneIdx]) -")
    emit("            (rSliceGainKi * rCD_ActuatorIntegralError[iZoneIdx]);")
    emit("    ELSE")
    emit("        (* Standby Base Position *)")
    emit("        rCD_SliceActuatorInternal[iZoneIdx] := 50.0;")
    emit("        rCD_ActuatorIntegralError[iZoneIdx] := 0.0;")
    emit("    END_IF;")
    emit("")
    emit("    (* Actuator Physical Stroke Bounds [0% to 100%] *)")
    emit("    IF rCD_SliceActuatorInternal[iZoneIdx] > 100.0 THEN")
    emit("        rCD_SliceActuatorInternal[iZoneIdx] := 100.0;")
    emit("    ELSIF rCD_SliceActuatorInternal[iZoneIdx] < 0.0 THEN")
    emit("        rCD_SliceActuatorInternal[iZoneIdx] := 0.0;")
    emit("    END_IF;")
    emit("END_FOR;")
    emit("")
    emit("(* --- 3. Slice Lip Mechanical Bending Limit Protection & Interlocking --- *)")
    emit("(* The flexible upper slice lip must not exceed maximum curvature without permanent distortion *)")
    emit("bAlm_SliceBendingViolation := FALSE;")
    emit("FOR iZoneIdx := 2 TO 47 DO")
    emit("    rSliceActuatorBendingMoment[iZoneIdx] := ABS(rCD_SliceActuatorInternal[iZoneIdx] - rCD_SliceActuatorInternal[iZoneIdx - 1]);")
    emit("    IF rSliceActuatorBendingMoment[iZoneIdx] > rMaxAdjacentBendingDelta THEN")
    emit("        bAlm_SliceBendingViolation := TRUE;")
    emit("        (* Smooth out adjacent step to prevent structural yield *)")
    emit("        IF rCD_SliceActuatorInternal[iZoneIdx] > rCD_SliceActuatorInternal[iZoneIdx - 1] THEN")
    emit("            rCD_SliceActuatorInternal[iZoneIdx] := rCD_SliceActuatorInternal[iZoneIdx - 1] + rMaxAdjacentBendingDelta;")
    emit("        ELSE")
    emit("            rCD_SliceActuatorInternal[iZoneIdx] := rCD_SliceActuatorInternal[iZoneIdx - 1] - rMaxAdjacentBendingDelta;")
    emit("        END_IF;")
    emit("    END_IF;")
    emit("END_FOR;")
    emit("")
    emit("(* Commit Internal Positions to Output Channels *)")
    emit("FOR iZoneIdx := 1 TO 48 DO")
    emit("    rSliceLipActuatorCmd[iZoneIdx] := rCD_SliceActuatorInternal[iZoneIdx];")
    emit("END_FOR;")
    emit("")
    emit("(* --- 4. Cross-Machine Statistical Profile Analysis (Mean, Variance, 2-Sigma) --- *)")
    emit("rProfileMeanSum     := 0.0;")
    emit("rProfileVarianceSum := 0.0;")
    emit("FOR iZoneIdx := 1 TO 48 DO")
    emit("    rProfileMeanSum := rProfileMeanSum + rCD_FilteredBasisWeight[iZoneIdx];")
    emit("END_FOR;")
    emit("rProfileMeanVal := rProfileMeanSum / 48.0;")
    emit("")
    emit("FOR iZoneIdx := 1 TO 48 DO")
    emit("    rProfileVarianceSum := rProfileVarianceSum +")
    emit("        ((rCD_FilteredBasisWeight[iZoneIdx] - rProfileMeanVal) * (rCD_FilteredBasisWeight[iZoneIdx] - rProfileMeanVal));")
    emit("END_FOR;")
    emit("rProfileVariance := rProfileVarianceSum / 48.0;")
    emit("")
    emit("(* 2-Sigma Variation Percentage Relative to Nominal Setpoint *)")
    emit("IF rTargetBasisWeight_GSM > 0.0 AND rProfileVariance >= 0.0 THEN")
    emit("    rCD_BasisWeight_2Sigma_Pct := (2.0 * SQRT(rProfileVariance) / rTargetBasisWeight_GSM) * 100.0;")
    emit("ELSE")
    emit("    rCD_BasisWeight_2Sigma_Pct := 1.25;")
    emit("END_IF;")
    emit("")
    emit("(* Moisture 2-Sigma Estimation *)")
    emit("rCD_Moisture_2Sigma_Pct := 0.35 + (rCD_BasisWeight_2Sigma_Pct * 0.12);")
    emit("rCD_Caliper_2Sigma_Pct  := 0.85 + (rCD_BasisWeight_2Sigma_Pct * 0.25);")
    emit("")
    return lines
