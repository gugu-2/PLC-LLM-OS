    def emit(s=""):
        lines.append(s)

    emit("(* =========================================================================================== *)")
    emit("(* PHASE 1: 2oo3 TRIPLE MODULAR REDUNDANCY SENSOR VOTING WITH DISCREPANCY TIMERS              *)")
    emit("(* IEC 61508 SIL-3 High-Integrity Architecture across 7 Critical Pulp & Paper Channels        *)")
    emit("(* Bumpless Degradation: 2oo3 Triplicated -> 1oo2 Dual -> Single Channel -> Fail-Safe Latch  *)")
    emit("(* =========================================================================================== *)")

    channels = [
        ("Headbox Hydraulic Total Pressure", "HBP", "rHeadboxPress_kPa", "rVotedHeadboxPress_kPa", "rTMR_Tol_HeadboxPress", "bFault_HBP", "tTimer_HBP", "rDiff_HBP", "iHealthyCount_HBP", "445.0", "[kPa]"),
        ("Headbox Stock Fiber Consistency", "SC", "rStockConsistency_Pct", "rVotedStockConsistency_Pct", "rTMR_Tol_StockConsistency", "bFault_SC", "tTimer_SC", "rDiff_SC", "iHealthyCount_SC", "0.720", "[%]"),
        ("Forming Wire Linear Velocity", "WS", "rWireSpeed_MPM", "rVotedWireSpeed_MPM", "rTMR_Tol_WireSpeed", "bFault_WS", "tTimer_WS", "rDiff_WS", "iHealthyCount_WS", "1800.0", "[m/min]"),
        ("Scanner Beta-Gauge Basis Weight", "BW", "rScannerBasisWeight_GSM", "rVotedBasisWeight_GSM", "rTMR_Tol_BasisWeight", "bFault_BW", "tTimer_BW", "rDiff_BW", "iHealthyCount_BW", "120.0", "[g/m2]"),
        ("Scanner Microwave Moisture", "MO", "rScannerMoisture_Pct", "rVotedMoisture_Pct", "rTMR_Tol_Moisture", "bFault_MO", "tTimer_MO", "rDiff_MO", "iHealthyCount_MO", "7.50", "[%]"),
        ("Web Sectional Draw Tension", "DT", "rDrawTension_NM", "rVotedDrawTension_NM", "rTMR_Tol_DrawTension", "bFault_DT", "tTimer_DT", "rDiff_DT", "iHealthyCount_DT", "450.0", "[N/m]"),
        ("Dryer Steam Main Header Pressure", "SP", "rSteamHeaderPress_kPa", "rVotedSteamHeaderPress_kPa", "rTMR_Tol_SteamPress", "bFault_SP", "tTimer_SP", "rDiff_SP", "iHealthyCount_SP", "420.0", "[kPa]")
    ]

    for title, tag, var_in, var_out, tol, fault_prefix, timer_prefix, diff_prefix, count_var, default_val, unit in channels:
        emit(f"(* --- 2oo3 TMR Channel: {title} {unit} --- *)")
        emit(f"{diff_prefix}_AB := ABS({var_in}_A - {var_in}_B);")
        emit(f"{diff_prefix}_BC := ABS({var_in}_B - {var_in}_C);")
        emit(f"{diff_prefix}_CA := ABS({var_in}_C - {var_in}_A);")
        emit("")
        emit(f"IF {diff_prefix}_AB > {tol} THEN")
        emit(f"    {timer_prefix}_AB := {timer_prefix}_AB + tTaskScanInterval;")
        emit("ELSE")
        emit(f"    {timer_prefix}_AB := T#0S;")
        emit("END_IF;")
        emit("")
        emit(f"IF {diff_prefix}_BC > {tol} THEN")
        emit(f"    {timer_prefix}_BC := {timer_prefix}_BC + tTaskScanInterval;")
        emit("ELSE")
        emit(f"    {timer_prefix}_BC := T#0S;")
        emit("END_IF;")
        emit("")
        emit(f"IF {diff_prefix}_CA > {tol} THEN")
        emit(f"    {timer_prefix}_CA := {timer_prefix}_CA + tTaskScanInterval;")
        emit("ELSE")
        emit(f"    {timer_prefix}_CA := T#0S;")
        emit("END_IF;")
        emit("")
        emit(f"(* Outlier Fault Identification via Discrepancy Debounce Timers *)")
        emit(f"IF ({timer_prefix}_AB >= tTMR_DiscrepancyFilter) AND ({timer_prefix}_CA >= tTMR_DiscrepancyFilter) THEN")
        emit(f"    {fault_prefix}_A := TRUE;")
        emit("END_IF;")
        emit(f"IF ({timer_prefix}_AB >= tTMR_DiscrepancyFilter) AND ({timer_prefix}_BC >= tTMR_DiscrepancyFilter) THEN")
        emit(f"    {fault_prefix}_B := TRUE;")
        emit("END_IF;")
        emit(f"IF ({timer_prefix}_BC >= tTMR_DiscrepancyFilter) AND ({timer_prefix}_CA >= tTMR_DiscrepancyFilter) THEN")
        emit(f"    {fault_prefix}_C := TRUE;")
        emit("END_IF;")
        emit("")
        emit(f"(* Fault Reset Logic *)")
        emit("IF bAcknowledgeFault THEN")
        emit(f"    IF {diff_prefix}_AB <= {tol} AND {diff_prefix}_CA <= {tol} THEN")
        emit(f"        {fault_prefix}_A := FALSE;")
        emit("    END_IF;")
        emit(f"    IF {diff_prefix}_AB <= {tol} AND {diff_prefix}_BC <= {tol} THEN")
        emit(f"        {fault_prefix}_B := FALSE;")
        emit("    END_IF;")
        emit(f"    IF {diff_prefix}_BC <= {tol} AND {diff_prefix}_CA <= {tol} THEN")
        emit(f"        {fault_prefix}_C := FALSE;")
        emit("    END_IF;")
        emit("END_IF;")
        emit("")
        emit(f"(* Count Healthy Transducer Channels *)")
        emit(f"{count_var} := 3;")
        emit(f"IF {fault_prefix}_A THEN")
        emit(f"    {count_var} := {count_var} - 1;")
        emit("END_IF;")
        emit(f"IF {fault_prefix}_B THEN")
        emit(f"    {count_var} := {count_var} - 1;")
        emit("END_IF;")
        emit(f"IF {fault_prefix}_C THEN")
        emit(f"    {count_var} := {count_var} - 1;")
        emit("END_IF;")
        emit("")
        emit(f"(* Voted Output Evaluation with Bumpless Degradation *)")
        emit(f"IF {count_var} = 3 THEN")
        emit(f"    (* Full 2oo3 Median Voting Architecture *)")
        emit(f"    IF (({var_in}_A >= {var_in}_B) AND ({var_in}_A <= {var_in}_C)) OR (({var_in}_A >= {var_in}_C) AND ({var_in}_A <= {var_in}_B)) THEN")
        emit(f"        {var_out} := {var_in}_A;")
        emit(f"    ELSIF (({var_in}_B >= {var_in}_A) AND ({var_in}_B <= {var_in}_C)) OR (({var_in}_B >= {var_in}_C) AND ({var_in}_B <= {var_in}_A)) THEN")
        emit(f"        {var_out} := {var_in}_B;")
        emit("    ELSE")
        emit(f"        {var_out} := {var_in}_C;")
        emit("    END_IF;")
        emit(f"ELSIF {count_var} = 2 THEN")
        emit(f"    (* 1oo2 Degraded Dual-Sensor Averaging *)")
        emit(f"    IF {fault_prefix}_A THEN")
        emit(f"        {var_out} := ({var_in}_B + {var_in}_C) / 2.0;")
        emit(f"    ELSIF {fault_prefix}_B THEN")
        emit(f"        {var_out} := ({var_in}_A + {var_in}_C) / 2.0;")
        emit("    ELSE")
        emit(f"        {var_out} := ({var_in}_A + {var_in}_B) / 2.0;")
        emit("    END_IF;")
        emit(f"ELSIF {count_var} = 1 THEN")
        emit(f"    (* Single Channel Fallback with Diagnostic Warning *)")
        emit(f"    IF NOT {fault_prefix}_A THEN")
        emit(f"        {var_out} := {var_in}_A;")
        emit(f"    ELSIF NOT {fault_prefix}_B THEN")
        emit(f"        {var_out} := {var_in}_B;")
        emit("    ELSE")
        emit(f"        {var_out} := {var_in}_C;")
        emit("    END_IF;")
        emit("ELSE")
        emit(f"    (* Critical Sensor Loss: Latch Safe Fallback Default {default_val} {unit} *)")
        emit(f"    {var_out} := {default_val};")
        emit("END_IF;")
        emit("")

    return lines
