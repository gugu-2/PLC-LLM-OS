def generate_mpc():
    lines = []
    def emit(s=""):
        lines.append(s)

    emit("(* =========================================================================================== *)")
    emit("(* PHASE 3: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) OPTIMIZATION WITH PGD              *)")
    emit("(* Multi-Objective Quadratic Cost Functional, Box Saturation & Dynamic Slew Limiters           *)")
    emit("(* Prediction Horizon Np = 5 Stages at Ts = 10.0 ms                                            *)")
    emit("(* =========================================================================================== *)")
    emit("")
    emit("(* Initialize Candidate Control Trajectory across Horizon Steps 1 to 5 *)")
    emit("FOR iHorizonStep := 1 TO 5 DO")
    emit("    FOR mInputIdx := 1 TO 8 DO")
    emit("        uHorizonCandidate[iHorizonStep, mInputIdx] := uPrevious[mInputIdx];")
    emit("    END_FOR;")
    emit("END_FOR;")
    emit("")
    emit("(* --- Projected Gradient Descent (PGD) Multi-Iteration Optimization Loop --- *)")
    emit("FOR iMpcIter := 1 TO 3 DO")
    emit("    rTotalQuadraticCost := 0.0;")
    emit("    rStateCostAccum     := 0.0;")
    emit("    rControlCostAccum   := 0.0;")
    emit("    rTerminalCostAccum  := 0.0;")
    emit("")
    emit("    (* Stage 1 Forward Horizon State Propagation from Measured xState *)")
    emit("    FOR iRowIdx := 1 TO 8 DO")
    emit("        xHorizonTrajectory[1, iRowIdx] := 0.0;")
    emit("        FOR iColIdx := 1 TO 8 DO")
    emit("            xHorizonTrajectory[1, iRowIdx] := xHorizonTrajectory[1, iRowIdx] + (matA[iRowIdx, iColIdx] * xState[iColIdx]);")
    emit("        END_FOR;")
    emit("        FOR mInputIdx := 1 TO 8 DO")
    emit("            xHorizonTrajectory[1, iRowIdx] := xHorizonTrajectory[1, iRowIdx] + (matB[iRowIdx, mInputIdx] * uHorizonCandidate[1, mInputIdx]);")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* Stages 2 to 5 Forward Horizon Propagation *)")
    emit("    FOR iHorizonStep := 2 TO 5 DO")
    emit("        FOR iRowIdx := 1 TO 8 DO")
    emit("            xHorizonTrajectory[iHorizonStep, iRowIdx] := 0.0;")
    emit("            FOR iColIdx := 1 TO 8 DO")
    emit("                xHorizonTrajectory[iHorizonStep, iRowIdx] := xHorizonTrajectory[iHorizonStep, iRowIdx] + (matA[iRowIdx, iColIdx] * xHorizonTrajectory[iHorizonStep - 1, iColIdx]);")
    emit("            END_FOR;")
    emit("            FOR mInputIdx := 1 TO 8 DO")
    emit("                xHorizonTrajectory[iHorizonStep, iRowIdx] := xHorizonTrajectory[iHorizonStep, iRowIdx] + (matB[iRowIdx, mInputIdx] * uHorizonCandidate[iHorizonStep, mInputIdx]);")
    emit("            END_FOR;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* Quadratic Cost Functional Evaluation: Tracking Error & Actuator Energy *)")
    emit("    FOR iHorizonStep := 1 TO 4 DO")
    emit("        FOR kStateIdx := 1 TO 8 DO")
    emit("            rStateCostAccum := rStateCostAccum + matQ[kStateIdx, kStateIdx] *")
    emit("                (xHorizonTrajectory[iHorizonStep, kStateIdx] - xSetpoint[kStateIdx]) *")
    emit("                (xHorizonTrajectory[iHorizonStep, kStateIdx] - xSetpoint[kStateIdx]);")
    emit("        END_FOR;")
    emit("        FOR mInputIdx := 1 TO 8 DO")
    emit("            rControlCostAccum := rControlCostAccum + matR[mInputIdx, mInputIdx] *")
    emit("                (uHorizonCandidate[iHorizonStep, mInputIdx] - uPrevious[mInputIdx]) *")
    emit("                (uHorizonCandidate[iHorizonStep, mInputIdx] - uPrevious[mInputIdx]);")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* Stage 5 Terminal Riccati Cost Evaluation *)")
    emit("    FOR kStateIdx := 1 TO 8 DO")
    emit("        rTerminalCostAccum := rTerminalCostAccum + matP[kStateIdx, kStateIdx] *")
    emit("            (xHorizonTrajectory[5, kStateIdx] - xSetpoint[kStateIdx]) *")
    emit("            (xHorizonTrajectory[5, kStateIdx] - xSetpoint[kStateIdx]);")
    emit("    END_FOR;")
    emit("    rTotalQuadraticCost := rStateCostAccum + rControlCostAccum + rTerminalCostAccum;")
    emit("")
    emit("    (* Analytical Cost Gradient Computation with respect to First Actuator Sequence u[1, m] *)")
    emit("    FOR mInputIdx := 1 TO 8 DO")
    emit("        rMpcGrad[mInputIdx] := 0.0;")
    emit("        (* State error backpropagation through input matrix B and weight Q *)")
    emit("        FOR kStateIdx := 1 TO 8 DO")
    emit("            rMpcGrad[mInputIdx] := rMpcGrad[mInputIdx] +")
    emit("                2.0 * matB[kStateIdx, mInputIdx] * matQ[kStateIdx, kStateIdx] *")
    emit("                (xHorizonTrajectory[1, kStateIdx] - xSetpoint[kStateIdx]);")
    emit("        END_FOR;")
    emit("        (* Actuator slew rate penalty contribution *)")
    emit("        rMpcGrad[mInputIdx] := rMpcGrad[mInputIdx] +")
    emit("            2.0 * matR[mInputIdx, mInputIdx] * (uHorizonCandidate[1, mInputIdx] - uPrevious[mInputIdx]);")
    emit("    END_FOR;")
    emit("")
    emit("    (* Projected Gradient Update with Physical Saturation & Dynamic Slew Limits *)")
    emit("    FOR mInputIdx := 1 TO 8 DO")
    emit("        (* Gradient Descent Step *)")
    emit("        uOptimal[mInputIdx] := uHorizonCandidate[1, mInputIdx] - (rMpcStepSize * rMpcGrad[mInputIdx]);")
    emit("")
    emit("        (* Slew Rate Acceleration Limiter: |u[k] - u[k-1]| <= deltaUMax *)")
    emit("        IF (uOptimal[mInputIdx] - uPrevious[mInputIdx]) > deltaUMax[mInputIdx] THEN")
    emit("            uOptimal[mInputIdx] := uPrevious[mInputIdx] + deltaUMax[mInputIdx];")
    emit("        ELSIF (uOptimal[mInputIdx] - uPrevious[mInputIdx]) < -deltaUMax[mInputIdx] THEN")
    emit("            uOptimal[mInputIdx] := uPrevious[mInputIdx] - deltaUMax[mInputIdx];")
    emit("        END_IF;")
    emit("")
    emit("        (* Actuator Box Saturation Constraints *)")
    emit("        IF uOptimal[mInputIdx] > uUpperBound[mInputIdx] THEN")
    emit("            uOptimal[mInputIdx] := uUpperBound[mInputIdx];")
    emit("        ELSIF uOptimal[mInputIdx] < uLowerBound[mInputIdx] THEN")
    emit("            uOptimal[mInputIdx] := uLowerBound[mInputIdx];")
    emit("        END_IF;")
    emit("")
    emit("        (* Feed back into candidate array for next iteration *)")
    emit("        uHorizonCandidate[1, mInputIdx] := uOptimal[mInputIdx];")
    emit("    END_FOR;")
    emit("END_FOR;")
    emit("")
    emit("(* Commit Optimal Control Signals to Actuator Channels in Auto Mode *)")
    emit("IF bAutoModeSelector AND (eCurrentFsmState >= STATE_JET_TO_WIRE_CASCADE_SYNC) THEN")
    emit("    rFanPumpSpeedCmd_Pct           := uOptimal[1];")
    emit("    rDilutionHeaderPressCmd_kPa    := uOptimal[2];")
    emit("    rMainSteamValveCmd_Pct         := uOptimal[4];")
    emit("    rThermocompressorMotiveCmd_Pct := uOptimal[5];")
    emit("    rBlowthroughDiffPressCmd_Pct   := uOptimal[6];")
    emit("    rCalenderCrownHydrPressCmd_bar := uOptimal[8];")
    emit("END_IF;")
    emit("")
    emit("(* Update Previous Actuators for Next Cycle Slew Rate Computation *)")
    emit("FOR mInputIdx := 1 TO 8 DO")
    emit("    uPrevious[mInputIdx] := uOptimal[mInputIdx];")
    emit("    uActuator[mInputIdx] := uOptimal[mInputIdx];")
    emit("END_FOR;")
    emit("")
    return lines
