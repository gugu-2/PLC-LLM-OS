add("IF tRopeSpd_DiscrepTimer_A > T#300ms AND tRopeSpd_DiscrepTimer_C > T#300ms THEN bRopeSpd_ChA_Fault := TRUE; END_IF;")
add("IF tRopeSpd_DiscrepTimer_A > T#300ms AND tRopeSpd_DiscrepTimer_B > T#300ms THEN bRopeSpd_ChB_Fault := TRUE; END_IF;")
add("IF tRopeSpd_DiscrepTimer_B > T#300ms AND tRopeSpd_DiscrepTimer_C > T#300ms THEN bRopeSpd_ChC_Fault := TRUE; END_IF;")
add("")
add("(* Rope Speed Median Selection *)")
add("IF NOT bRopeSpd_ChA_Fault AND NOT bRopeSpd_ChB_Fault AND NOT bRopeSpd_ChC_Fault THEN")
add("    IF (rRopeSpeed_A_mps >= rRopeSpeed_B_mps AND rRopeSpeed_A_mps <= rRopeSpeed_C_mps) OR")
add("       (rRopeSpeed_A_mps <= rRopeSpeed_B_mps AND rRopeSpeed_A_mps >= rRopeSpeed_C_mps) THEN")
add("        rVotedRopeSpeed_mps := rRopeSpeed_A_mps;")
add("    ELSIF (rRopeSpeed_B_mps >= rRopeSpeed_A_mps AND rRopeSpeed_B_mps <= rRopeSpeed_C_mps) OR")
add("          (rRopeSpeed_B_mps <= rRopeSpeed_A_mps AND rRopeSpeed_B_mps >= rRopeSpeed_C_mps) THEN")
add("        rVotedRopeSpeed_mps := rRopeSpeed_B_mps;")
add("    ELSE")
add("        rVotedRopeSpeed_mps := rRopeSpeed_C_mps;")
add("    END_IF;")
add("ELSIF bRopeSpd_ChA_Fault AND NOT bRopeSpd_ChB_Fault AND NOT bRopeSpd_ChC_Fault THEN")
add("    rVotedRopeSpeed_mps := (rRopeSpeed_B_mps + rRopeSpeed_C_mps) * 0.5;")
add("ELSIF bRopeSpd_ChB_Fault AND NOT bRopeSpd_ChA_Fault AND NOT bRopeSpd_ChC_Fault THEN")
add("    rVotedRopeSpeed_mps := (rRopeSpeed_A_mps + rRopeSpeed_C_mps) * 0.5;")
add("ELSIF bRopeSpd_ChC_Fault AND NOT bRopeSpd_ChA_Fault AND NOT bRopeSpd_ChB_Fault THEN")
add("    rVotedRopeSpeed_mps := (rRopeSpeed_A_mps + rRopeSpeed_B_mps) * 0.5;")
add("ELSE")
add("    (* Highest reading for overspeed safety trip guarantee *)")
add("    rVotedRopeSpeed_mps := rRopeSpeed_A_mps;")
add("    IF rRopeSpeed_B_mps > rVotedRopeSpeed_mps THEN rVotedRopeSpeed_mps := rRopeSpeed_B_mps; END_IF;")
add("    IF rRopeSpeed_C_mps > rVotedRopeSpeed_mps THEN rVotedRopeSpeed_mps := rRopeSpeed_C_mps; END_IF;")
add("END_IF;")
add("")
add("(* --- TRIAD 2: BULLWHEEL HYDRAULIC TENSION CYLINDER PRESSURE (A, B, C) --- *)")
add("IF ABS(rTensionPress_A_bar - rTensionPress_B_bar) > 5.0 THEN")
add("    tTension_DiscrepTimer_A := tTension_DiscrepTimer_A + tCycleTime_ms;")
add("ELSE")
add("    tTension_DiscrepTimer_A := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rTensionPress_B_bar - rTensionPress_C_bar) > 5.0 THEN")
add("    tTension_DiscrepTimer_B := tTension_DiscrepTimer_B + tCycleTime_ms;")
add("ELSE")
add("    tTension_DiscrepTimer_B := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rTensionPress_A_bar - rTensionPress_C_bar) > 5.0 THEN")
add("    tTension_DiscrepTimer_C := tTension_DiscrepTimer_C + tCycleTime_ms;")
add("ELSE")
add("    tTension_DiscrepTimer_C := T#0ms;")
add("END_IF;")
add("")
add("IF tTension_DiscrepTimer_A > T#800ms AND tTension_DiscrepTimer_C > T#800ms THEN bTension_ChA_Fault := TRUE; END_IF;")
add("IF tTension_DiscrepTimer_A > T#800ms AND tTension_DiscrepTimer_B > T#800ms THEN bTension_ChB_Fault := TRUE; END_IF;")
add("IF tTension_DiscrepTimer_B > T#800ms AND tTension_DiscrepTimer_C > T#800ms THEN bTension_ChC_Fault := TRUE; END_IF;")
add("")
add("(* Tension Pressure Median Selection *)")
add("IF NOT bTension_ChA_Fault AND NOT bTension_ChB_Fault AND NOT bTension_ChC_Fault THEN")
add("    IF (rTensionPress_A_bar >= rTensionPress_B_bar AND rTensionPress_A_bar <= rTensionPress_C_bar) OR")
add("       (rTensionPress_A_bar <= rTensionPress_B_bar AND rTensionPress_A_bar >= rTensionPress_C_bar) THEN")
add("        rVotedTensionPress_bar := rTensionPress_A_bar;")
add("    ELSIF (rTensionPress_B_bar >= rTensionPress_A_bar AND rTensionPress_B_bar <= rTensionPress_C_bar) OR")
add("          (rTensionPress_B_bar <= rTensionPress_A_bar AND rTensionPress_B_bar >= rTensionPress_C_bar) THEN")
add("        rVotedTensionPress_bar := rTensionPress_B_bar;")
add("    ELSE")
add("        rVotedTensionPress_bar := rTensionPress_C_bar;")
add("    END_IF;")
add("ELSIF bTension_ChA_Fault AND NOT bTension_ChB_Fault AND NOT bTension_ChC_Fault THEN")
add("    rVotedTensionPress_bar := (rTensionPress_B_bar + rTensionPress_C_bar) * 0.5;")
add("ELSE")
add("    rVotedTensionPress_bar := rTensionPress_A_bar;")
add("END_IF;")
add("")
add("(* Compute continuous catenary tension force: T = P * Area [kN] *)")
add("rCalculatedCatenaryTension_kN := (rVotedTensionPress_bar * 100.0) * rTensionPistonArea_m2; (* bar -> kN *)")
add("")
add("(* --- TRIAD 3: TOWER CROSS-WIND ANEMOMETER VECTORS (A, B, C) --- *)")
add("IF ABS(rTowerWindSpeed_A_mps - rTowerWindSpeed_B_mps) > 3.0 THEN")
add("    tWind_DiscrepTimer_A := tWind_DiscrepTimer_A + tCycleTime_ms;")
add("ELSE")
add("    tWind_DiscrepTimer_A := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rTowerWindSpeed_B_mps - rTowerWindSpeed_C_mps) > 3.0 THEN")
add("    tWind_DiscrepTimer_B := tWind_DiscrepTimer_B + tCycleTime_ms;")
add("ELSE")
add("    tWind_DiscrepTimer_B := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rTowerWindSpeed_A_mps - rTowerWindSpeed_C_mps) > 3.0 THEN")
add("    tWind_DiscrepTimer_C := tWind_DiscrepTimer_C + tCycleTime_ms;")
add("ELSE")
add("    tWind_DiscrepTimer_C := T#0ms;")
add("END_IF;")
add("")
add("IF tWind_DiscrepTimer_A > T#1000ms AND tWind_DiscrepTimer_C > T#1000ms THEN bWind_ChA_Fault := TRUE; END_IF;")
add("IF tWind_DiscrepTimer_A > T#1000ms AND tWind_DiscrepTimer_B > T#1000ms THEN bWind_ChB_Fault := TRUE; END_IF;")
add("IF tWind_DiscrepTimer_B > T#1000ms AND tWind_DiscrepTimer_C > T#1000ms THEN bWind_ChC_Fault := TRUE; END_IF;")
add("")
add("(* Maximum cross-wind select for passenger cabin swing safety *)")
add("rVotedCrossWind_mps := rTowerWindSpeed_A_mps;")
add("IF NOT bWind_ChB_Fault AND (rTowerWindSpeed_B_mps > rVotedCrossWind_mps) THEN")
add("    rVotedCrossWind_mps := rTowerWindSpeed_B_mps;")
add("END_IF;")
add("IF NOT bWind_ChC_Fault AND (rTowerWindSpeed_C_mps > rVotedCrossWind_mps) THEN")
add("    rVotedCrossWind_mps := rTowerWindSpeed_C_mps;")
add("END_IF;")
add("")
add("(* --- TRIAD 4: TOWER SHEAVE CABLE DERAILMENT BREAK-WIRE CIRCUITS --- *)")
add("(* Closed loop circuit nominal 16 to 20 mA; < 4.0 mA indicates sheave derailment or severed wire *)")
add("IF rTowerDerailCurrent_A_mA < 4.0 THEN bDerail_ChA_Fault := TRUE; ELSE bDerail_ChA_Fault := FALSE; END_IF;")
add("IF rTowerDerailCurrent_B_mA < 4.0 THEN bDerail_ChB_Fault := TRUE; ELSE bDerail_ChB_Fault := FALSE; END_IF;")
add("IF rTowerDerailCurrent_C_mA < 4.0 THEN bDerail_ChC_Fault := TRUE; ELSE bDerail_ChC_Fault := FALSE; END_IF;")
add("")
add("(* 2oo3 voting on catastrophic cable derailment *)")
add("IF (bDerail_ChA_Fault AND bDerail_ChB_Fault) OR ")
add("   (bDerail_ChB_Fault AND bDerail_ChC_Fault) OR ")
add("   (bDerail_ChA_Fault AND bDerail_ChC_Fault) OR ")
add("   (ABS(rRopePositionSheaveOffset_mm) > 28.0) THEN")
add("    bDerailmentEmergencyTrip := TRUE;")
add("    bAlarm_CableDerailment_HH := TRUE;")
add("ELSE")
add("    bDerailmentEmergencyTrip := FALSE;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 2: HIGH-SPEED GRIP CLAMP FORCE OBSERVER (< 50ms LAUNCH VERIFICATION)                *)")
add("(* EN 1909: Grip must clamp haul rope with F >= 35.0 kN prior to entering line catenary     *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Low-pass filter raw piezo load cell signal: tau = 10 ms *)")
add("rFilteredGripForce_kN := rFilteredGripForce_kN + (rDt_sec / (0.010 + rDt_sec)) * (rGripClampForce_kN - rFilteredGripForce_kN);")
add("")
add("(* Optical switch detects grip passing into test gate zone *)")
add("IF bGripCloseVerifyContact THEN")
add("    tGripVerifyTimer := tGripVerifyTimer + tCycleTime_ms;")
add("    ")
add("    (* Check clamping force within 50 ms window *)")
add("    IF (rFilteredGripForce_kN >= rMinAllowableGripForce_kN) AND ")
add("       (rGripSpringDisplacement_mm >= rGripDisplacementThreshold_mm) THEN")
add("        bGripForcePassStatus := TRUE;")
add("        bMisclampConditionDetected := FALSE;")
add("        bMisclampEjectionGateCmd := FALSE;")
add("    ELSE")
add("        (* If under 35 kN or spring pack travel abnormal, trigger mis-clamp *)")
add("        IF tGripVerifyTimer >= T#50ms THEN")
add("            bGripForcePassStatus := FALSE;")
add("            bMisclampConditionDetected := TRUE;")
add("            bAlarm_GripMisclamp_HH := TRUE;")
add("            bMisclampEjectionGateCmd := TRUE; (* Open divert flap to stop launch *)")
add("        END_IF;")
add("    END_IF;")
add("ELSE")
add("    tGripVerifyTimer := T#0ms;")
add("    bGripForcePassStatus := TRUE;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 3: CATENARY SAG EVALUATION & MULTI-TOWER TOPOGRAPHIC TENSION DISTRIBUTION           *)")
add("(* y_max = (T / (w * g)) * (cosh((w * g * L) / (2 * T)) - 1)                                *)")
add("(* T_tower(i) = T_bullwheel + w * g * delta_H_i                                             *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("IF rCalculatedCatenaryTension_kN > 10.0 THEN")
add("    (* Parameter a = T / (m_prime * g) in meters *)")
add("    rCatenaryParam_a_m := (rCalculatedCatenaryTension_kN * 1000.0) / (rRopeMassPerMeter_kg_m * rGravityAcc_mps2);")
add("    rNormalizedSpanRatio := (rMaxSpanLength_m * 0.5) / rCatenaryParam_a_m;")
add("    ")
add("    (* Taylor expansion for cosh(u) - 1 = (u^2 / 2) + (u^4 / 24) *)")
add("    rCoshApproximation := (0.5 * rNormalizedSpanRatio * rNormalizedSpanRatio) + ")
add("                          (0.0416667 * rNormalizedSpanRatio * rNormalizedSpanRatio * rNormalizedSpanRatio * rNormalizedSpanRatio);")
add("    rMaxMidspanSag_m := rCatenaryParam_a_m * rCoshApproximation;")
add("ELSE")
add("    rMaxMidspanSag_m := 12.0;")
add("END_IF;")
add("")
add("(* Multi-tower gravitational static tension array reconstruction *)")
add("arrTowerElevations_m[1] := rTowerElevation_1_m;")
add("arrTowerElevations_m[2] := rTowerElevation_2_m;")
add("arrTowerElevations_m[3] := rTowerElevation_3_m;")
add("arrTowerElevations_m[4] := rTowerElevation_4_m;")
add("arrTowerElevations_m[5] := rTowerElevation_5_m;")
add("arrTowerElevations_m[6] := rTowerElevation_6_m;")
add("")
add("rPeakTowerTension_kN := rCalculatedCatenaryTension_kN;")
add("FOR i := 1 TO 6 DO")
add("    arrTowerTensions_kN[i] := rCalculatedCatenaryTension_kN + ")
add("                              ((rRopeMassPerMeter_kg_m * rGravityAcc_mps2 * arrTowerElevations_m[i]) / 1000.0);")
add("    IF arrTowerTensions_kN[i] > rPeakTowerTension_kN THEN")
add("        rPeakTowerTension_kN := arrTowerTensions_kN[i];")
add("    END_IF;")
add("END_FOR;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 4: DISCRETE ROPEWAY CATENARY & PENDULUM STATE-SPACE PROPAGATION                      *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("vecY_meas[0] := rVotedRopeSpeed_mps - rNominalRopeSpeed_mps;")
add("vecY_meas[1] := rVotedTensionPress_bar - rNominalTensionPress_bar;")
add("vecY_meas[2] := rCabinPendulumSwingAngle_deg * 0.01745329; (* Convert to radians *)")
add("")
add("(* Compute observer predicted measurements: y_est = C * x_k *)")
add("FOR i := 0 TO 2 DO")
add("    vecY_est[i] := 0.0;")
add("    FOR j := 0 TO 5 DO")
add("        vecY_est[i] := vecY_est[i] + (matC[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    vecErr_Y[i] := vecY_meas[i] - vecY_est[i];")
add("END_FOR;")
add("")
add("(* State update: x_next = A * x_k + B * u_k + L * (y_meas - y_est) *)")
add("FOR i := 0 TO 5 DO")
add("    rTempSum := 0.0;")
add("    FOR j := 0 TO 5 DO")
add("        rTempSum := rTempSum + (matA[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matB[i, j] * vecU_k[j]);")
add("    END_FOR;")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matL_Obs[i, j] * vecErr_Y[j]);")
add("    END_FOR;")
add("    vecX_next[i] := rTempSum;")
add("END_FOR;")
add("")
add("FOR i := 0 TO 5 DO")
add("    vecX_k[i] := vecX_next[i];")
add("END_FOR;")
add("")
add("(* Reconstruct lateral pendulum swing angle [deg] from state x[4] *)")
add("rCabinPendulumSwingAngle_deg := vecX_k[4] * 57.29578; (* rad -> deg *)")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 5: MODEL PREDICTIVE CONTROL (MPC) RECEDING HORIZON GRADIENT EVALUATION              *)")
add("(* Min J = sum( (x - x_ref)'*Q*(x - x_ref) + delta_u'*R*delta_u )                           *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("vecX_Ref[0] := 0.0; (* Zero speed error *)")
add("vecX_Ref[1] := 0.0; (* Zero carriage position error *)")
add("vecX_Ref[2] := 0.0; (* Zero tension pressure error *)")
add("vecX_Ref[3] := 0.0; (* Zero catenary dynamic load deviation *)")
add("vecX_Ref[4] := 0.0; (* Zero pendulum swing *)")
add("vecX_Ref[5] := 0.0; (* Zero pendulum velocity *)")
add("")
add("rMpcPredictedCost := 0.0;")
add("rMpcGrad_U0 := 0.0;")
add("rMpcGrad_U1 := 0.0;")
add("rMpcGrad_U2 := 0.0;")
add("")
add("FOR i := 0 TO 5 DO")
add("    rTempDiff := vecX_k[i] - vecX_Ref[i];")
add("    rMpcPredictedCost := rMpcPredictedCost + (vecQ_Weights[i] * rTempDiff * rTempDiff);")
add("    ")
add("    rMpcGrad_U0 := rMpcGrad_U0 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 0]);")
add("    rMpcGrad_U1 := rMpcGrad_U1 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 1]);")
add("    rMpcGrad_U2 := rMpcGrad_U2 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 2]);")
add("END_FOR;")
add("")
add("rMpcGrad_U0 := rMpcGrad_U0 + (2.0 * vecR_Weights[0] * vecU_k[0]);")
add("rMpcGrad_U1 := rMpcGrad_U1 + (2.0 * vecR_Weights[1] * vecU_k[1]);")
add("rMpcGrad_U2 := rMpcGrad_U2 + (2.0 * vecR_Weights[2] * vecU_k[2]);")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 6: BULLWHEEL HYDRAULIC TENSION CARRIAGE PROPORTIONAL-INTEGRAL CONTROLLER            *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("rTensionPressError_bar := rNominalTensionPress_bar - rVotedTensionPress_bar;")
add("")
add("(* Closed loop pressure control *)")
add("rTensionPressIntegral := rTensionPressIntegral + (0.12 * rTensionPressError_bar * rDt_sec);")
add("IF rTensionPressIntegral > 35.0 THEN rTensionPressIntegral := 35.0; END_IF;")
add("IF rTensionPressIntegral < -35.0 THEN rTensionPressIntegral := -35.0; END_IF;")
add("")
add("rTensionPropValveCmd_pct := 50.0 + (1.25 * rTensionPressError_bar) + rTensionPressIntegral - (0.005 * rMpcGrad_U1);")
add("IF rTensionPropValveCmd_pct < 0.0 THEN rTensionPropValveCmd_pct := 0.0; END_IF;")
add("IF rTensionPropValveCmd_pct > 100.0 THEN rTensionPropValveCmd_pct := 100.0; END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 7: TERMINAL TIRE-BANK SPEED SYNCHRONIZATION (ELECTRONIC LINE-SHAFT)                 *)")
add("(* Decel Bank: 6.0 m/s -> 0.3 m/s; Accel Bank: 0.3 m/s -> 6.0 m/s                           *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("IF (iStepState = 4) OR (iStepState = 3) OR (iStepState = 2) THEN")
add("    (* Synchronize launch acceleration tires strictly to current measured haul rope speed *)")
add("    rAccelTireBankSpeedCmd_mps := rVotedRopeSpeed_mps;")
add("    rDecelTireBankSpeedCmd_mps := rVotedRopeSpeed_mps;")
add("    rStationConveyorSpeedCmd_mps := rStationBoardingSpeed_mps; (* 0.3 m/s *)")
add("ELSE")
add("    rAccelTireBankSpeedCmd_mps := 0.0;")
add("    rDecelTireBankSpeedCmd_mps := 0.0;")
add("    rStationConveyorSpeedCmd_mps := 0.0;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 8: EN 12929 MULTI-STAGE FINITE STATE MACHINE (10 OPERATIONAL STATES)                 *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("CASE iStepState OF")
add("    0: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 0: SYSTEM_HYDRAULIC_TENSION_SEEK                                             *)")
add("       (* Establish hydraulic tension cylinder pressure (155 bar) and verify brakes locked   *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bRopewayTrippedStatus       := FALSE;")
add("       bServiceBrakeReleaseCmd     := FALSE; (* Clamped *)")
add("       bEmergencyBrakeReleaseCmd   := FALSE; (* Clamped *)")
add("       rMainDriveSpeedRef_mps      := 0.0;")
add("       rMainDriveTorqueLimit_kNm   := 0.0;")
add("       ")
add("       IF bEmergencyStop_ESD AND NOT bDerailmentEmergencyTrip THEN")
add("           IF (rVotedTensionPress_bar >= rTensionPress_LL_bar) AND ")
add("              (rVotedTensionPress_bar <= rTensionPress_HH_bar) THEN")
add("               IF bMasterSystemStartCmd THEN")
add("                   tStateDwellTimer := T#0ms;")
add("                   iStepState       := 1; (* Advance to Tire Bank Sync Start *)")
add("               END_IF;")
add("           END_IF;")
add("       ELSE")
add("           iStepState := 8; (* Emergency brake trip *)")
add("       END_IF;")
add("       ")
add("    1: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 1: TIRE_BANK_SYNC_START                                                      *)")
add("       (* Spin terminal tire banks and station chain conveyors before moving main haul rope  *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       tStateDwellTimer := tStateDwellTimer + tCycleTime_ms;")
add("       rStationConveyorSpeedCmd_mps := rStationBoardingSpeed_mps;")
add("       ")
add("       IF tStateDwellTimer >= T#2500ms THEN")
add("           tStateDwellTimer := T#0ms;")
add("           iStepState       := 2; (* Advance to Slow Creep Inspect *)")
add("       END_IF;")
add("       ")
add("       IF NOT bEmergencyStop_ESD OR bNormalControlledStopCmd THEN")
add("           iStepState := 7;")
add("       END_IF;")
add("       ")
add("    2: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 2: ROPEWAY_SLOW_CREEP_INSPECT (0.5 m/s Line Inspection)                      *)")
add("       (* Release service and emergency brakes, accelerate to 0.5 m/s for line visual check  *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bServiceBrakeReleaseCmd   := TRUE;")
add("       bEmergencyBrakeReleaseCmd := TRUE;")
add("       rMainDriveTorqueLimit_kNm := 120.0;")
add("       rRampRateTarget_mps       := rCreepInspectionSpeed_mps; (* 0.50 m/s *)")
add("       ")
add("       (* Ramp haul speed toward 0.50 m/s at 0.15 m/s2 *)")
add("       IF rMainDriveSpeedRef_mps < rRampRateTarget_mps THEN")
add("           rMainDriveSpeedRef_mps := rMainDriveSpeedRef_mps + (0.15 * rDt_sec);")
add("       ELSE")
add("           rMainDriveSpeedRef_mps := rRampRateTarget_mps;")
add("       END_IF;")
add("       ")
add("       (* Advance to passenger run once inspection confirmed *)")
add("       IF (rVotedRopeSpeed_mps >= 0.45) AND bMasterSystemStartCmd THEN")
add("           iStepState := 3; (* Advance to Intermediate Speed *)")
add("       END_IF;")
add("       ")
add("       IF NOT bEmergencyStop_ESD OR bDerailmentEmergencyTrip OR bAlarm_GripMisclamp_HH THEN")
add("           iStepState := 8;")
add("       END_IF;")
add("       ")
add("    3: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 3: ACCELERATION_TO_INTERMEDIATE_SPEED (3.0 m/s Half-Speed Mode)              *)")
add("       (* Smoothly accelerate ropeway to 3.0 m/s at EN 12929 allowable 0.25 m/s2             *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bServiceBrakeReleaseCmd   := TRUE;")
add("       bEmergencyBrakeReleaseCmd := TRUE;")
add("       rMainDriveTorqueLimit_kNm := 220.0;")
add("       rRampRateTarget_mps       := 3.00;")
add("       ")
add("       IF rMainDriveSpeedRef_mps < rRampRateTarget_mps THEN")
add("           rMainDriveSpeedRef_mps := rMainDriveSpeedRef_mps + (0.25 * rDt_sec);")
add("       ELSE")
add("           rMainDriveSpeedRef_mps := rRampRateTarget_mps;")
add("           IF rVotedRopeSpeed_mps >= 2.90 THEN")
add("               iStepState := 4; (* Advance to Full High-Speed Passenger Run *)")
add("           END_IF;")
add("       END_IF;")
add("       ")
add("       IF NOT bEmergencyStop_ESD OR bDerailmentEmergencyTrip OR bAlarm_GripMisclamp_HH THEN")
add("           iStepState := 8;")
add("       ELSIF bNormalControlledStopCmd THEN")
add("           iStepState := 7;")
add("       END_IF;")
