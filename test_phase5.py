    st.append("(* ==================================================================================================== *)\n")
    st.append("(* PHASE 5: DETERMINISTIC 14-STAGE PRODUCTION FINITE STATE MACHINE (FSM)                                *)\n")
    st.append("(* Deterministic Cycle-Accurate Transitions Across All Operational, Startup, Production & Trip States   *)\n")
    st.append("(* ==================================================================================================== *)\n\n")

    st.append("(* State Dwell Time Accumulation & State Change Detection *)\n")
    st.append("IF eState = ePrevState THEN\n")
    st.append("    rStateTimer_s := rStateTimer_s + tScanCycleTime_s;\n")
