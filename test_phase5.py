    st.append("END_IF;\n\n")

    st.append("(* Global Safety Trip Preemption: Emergency Stop & Catastrophic Sensor Loss *)\n")
    st.append("IF bEmergencyStop THEN\n")
    st.append("    eState := 13; (* Immediate jump to EMERGENCY_PUMP_CAVITATION_OR_STOCK_RUNOUT_TRIP *)\n")
    st.append("ELSIF bHeadPress_Trip OR bPondLevel_Trip THEN\n")
    st.append("    IF eState >= 3 THEN\n")
    st.append("        eState := 13;\n")
    st.append("    END_IF;\n")
    st.append("ELSIF bSheetBreakDetected AND (eState = 8 OR eState = 9) THEN\n")
    st.append("    eState := 10; (* Emergency Sheet Break Slurry Diversion *)\n")
    st.append("ELSIF bCleanInPlaceCmd AND (eState = 0) THEN\n")
    st.append("    eState := 12; (* CIP Washdown Cycle *)\n")
    st.append("END_IF;\n\n")

    st.append("CASE eState OF\n")

    # State 0: STATE_IDLE
    st.append("    0: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_IDLE: System Quiescent, Interlocks Clear, Waiting for Auto Cycle Start                 *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState               := 0;\n")
    st.append("       bEmergencySlurryDivertValve   := FALSE;\n")
    st.append("       bSliceLipProtectiveRetract    := FALSE;\n")
    st.append("       bFanPumpFastTrip              := FALSE;\n")
    st.append("       bAirPadFastDepressurize       := FALSE;\n")
    st.append("       bWhiteWaterBypassValve        := TRUE;\n")
    st.append("       rWhiteWaterFlushValve_Cmd_pct := 0.0;\n")
    st.append("       rAirChargeValve_Cmd_pct       := 0.0;\n")
    st.append("       rAirBleedValve_Cmd_pct        := 100.0; (* Depressurized *)\n")
    st.append("       rFanPump_SpeedCmd_pct         := 0.0;\n")
    st.append("       rSliceLipMean_Cmd_mm          := 12.0;  (* Baseline park gap *)\n")
    st.append("       rDilutionHeaderValve_Cmd_pct  := 0.0;\n")
    st.append("       rStockOverflowValve_Cmd_pct   := 100.0; (* Fully open drain *)\n")
    st.append("       IF bEnable AND bAutoCycleStart AND NOT bEmergencyStop AND bFanPumpReady AND bAirCompressorReady THEN\n")
    st.append("           eState := 1; (* Transition to STATE_HEADBOX_FLUSH_AND_WHITE_WATER_WARMUP *)\n")
    st.append("       END_IF;\n\n")

    # State 1: STATE_HEADBOX_FLUSH_AND_WHITE_WATER_WARMUP
    st.append("    1: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_HEADBOX_FLUSH_AND_WHITE_WATER_WARMUP: Deaerated White Water Flush & Thermal Priming   *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState               := 1;\n")
    st.append("       bWhiteWaterBypassValve        := FALSE;\n")
    st.append("       rWhiteWaterFlushValve_Cmd_pct := 85.0; (* Introduce warm deaerated white water *)\n")
    st.append("       rStockOverflowValve_Cmd_pct   := 80.0;\n")
    st.append("       rAirBleedValve_Cmd_pct        := 50.0;\n")
    st.append("       rAirChargeValve_Cmd_pct       := 0.0;\n")
    st.append("       rFanPump_SpeedCmd_pct         := 15.0; (* Gentle circulation *)\n")
    st.append("       rSliceLipMean_Cmd_mm          := 14.0;\n")
    st.append("       rFlushTimer_s                 := rStateTimer_s;\n")
    st.append("       IF rStateTimer_s >= 25.0 AND (rPondLevel_Voted_mm >= 180.0) AND bWhiteWaterFlushPermissive THEN\n")
    st.append("           eState := 2; (* Transition to STATE_AIR_CUSHION_PRESSURIZATION_AND_SEAL *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 0;\n")
    st.append("       END_IF;\n\n")

    # State 2: STATE_AIR_CUSHION_PRESSURIZATION_AND_SEAL
    st.append("    2: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_AIR_CUSHION_PRESSURIZATION_AND_SEAL: Vessel Seal & Air Pad Pre-Pressurization         *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState               := 2;\n")
    st.append("       rWhiteWaterFlushValve_Cmd_pct := 40.0;\n")
    st.append("       rAirBleedValve_Cmd_pct        := 0.0;  (* Close bleed vent *)\n")
    st.append("       rAirChargeValve_Cmd_pct       := 65.0; (* Pressurize air cushion pad *)\n")
    st.append("       rFanPump_SpeedCmd_pct         := 20.0;\n")
    st.append("       rStockOverflowValve_Cmd_pct   := 50.0;\n")
    st.append("       rAirSealTimer_s               := rStateTimer_s;\n")
    st.append("       IF (rHeadPress_Voted_kPa >= 60.0) AND (rStateTimer_s >= 10.0) THEN\n")
    st.append("           eState := 3; (* Transition to STATE_PRIMARY_FAN_PUMP_RAMP_TO_MINIMUM_SPEED *)\n")
    st.append("       ELSIF (rStateTimer_s >= 40.0) AND (rHeadPress_Voted_kPa < 40.0) THEN\n")
    st.append("           (* Air Cushion Seal Leakage Failure *) \n")
    st.append("           eState := 13;\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 0;\n")
    st.append("       END_IF;\n\n")

    # State 3: STATE_PRIMARY_FAN_PUMP_RAMP_TO_MINIMUM_SPEED
    st.append("    3: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_PRIMARY_FAN_PUMP_RAMP_TO_MINIMUM_SPEED: Controlled VFD Acceleration Ramp               *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState               := 3;\n")
    st.append("       rWhiteWaterFlushValve_Cmd_pct := 0.0;\n")
    st.append("       (* Soft acceleration ramp at 2.0 %/s *)\n")
    st.append("       IF rFanPump_SpeedCmd_pct < 45.0 THEN\n")
    st.append("           rFanPump_SpeedCmd_pct := rFanPump_SpeedCmd_pct + (2.0 * tScanCycleTime_s);\n")
    st.append("       ELSE\n")
    st.append("           rFanPump_SpeedCmd_pct := 45.0;\n")
    st.append("       END_IF;\n")
    st.append("       rDilutionHeaderValve_Cmd_pct  := 25.0;\n")
    st.append("       rStockOverflowValve_Cmd_pct   := 30.0;\n")
    st.append("       rFanPumpRampTimer_s           := rStateTimer_s;\n")
    st.append("       IF (rFanPump_SpeedFb_pct >= 42.0) AND (rPondLevel_Voted_mm >= 220.0) AND (rStateTimer_s >= 12.0) THEN\n")
    st.append("           eState := 4; (* Transition to STATE_STOCK_POND_LEVEL_CLOSED_LOOP_LOCK *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 11;\n")
    st.append("       END_IF;\n\n")

    # State 4: STATE_STOCK_POND_LEVEL_CLOSED_LOOP_LOCK
    st.append("    4: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_STOCK_POND_LEVEL_CLOSED_LOOP_LOCK: Level PI Equilibrium & Overflow Trim                *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState             := 4;\n")
    st.append("       (* Local Level Control Trim *)\n")
    st.append("       rTempDiff := rTarget_PondLevel_mm - rPondLevel_Voted_mm;\n")
    st.append("       rStockOverflowValve_Cmd_pct := 25.0 - (rTempDiff * 0.15);\n")
    st.append("       IF rStockOverflowValve_Cmd_pct > 60.0 THEN\n")
    st.append("           rStockOverflowValve_Cmd_pct := 60.0;\n")
    st.append("       ELSIF rStockOverflowValve_Cmd_pct < 5.0 THEN\n")
    st.append("           rStockOverflowValve_Cmd_pct := 5.0;\n")
    st.append("       END_IF;\n")
    st.append("       rLevelLockTimer_s := rStateTimer_s;\n")
    st.append("       IF (ABS(rTempDiff) <= 8.0) AND (rStateTimer_s >= 8.0) THEN\n")
    st.append("           eState := 5; (* Transition to STATE_TOTAL_HEAD_PRESSURE_STABILIZATION *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 11;\n")
    st.append("       END_IF;\n\n")

    # State 5: STATE_TOTAL_HEAD_PRESSURE_STABILIZATION
    st.append("    5: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_TOTAL_HEAD_PRESSURE_STABILIZATION: Fast Air Cushion & Fan Pump Closed Loop Lock        *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState         := 5;\n")
    st.append("       rHeadStabilizeTimer_s   := rStateTimer_s;\n")
    st.append("       rTempDiff := rTarget_TotalHead_mmH2O - rCalc_TotalHead_mmH2O;\n")
    st.append("       IF ABS(rTempDiff) > 500.0 THEN\n")
    st.append("           (* Air Cushion Rapid Charge/Bleed Proportional Interlocking *)\n")
    st.append("           IF rTempDiff > 0.0 THEN\n")
    st.append("               rAirChargeValve_Cmd_pct := 40.0;\n")
    st.append("               rAirBleedValve_Cmd_pct  := 0.0;\n")
    st.append("           ELSE\n")
    st.append("               rAirChargeValve_Cmd_pct := 0.0;\n")
    st.append("               rAirBleedValve_Cmd_pct  := 35.0;\n")
    st.append("           END_IF;\n")
    st.append("       ELSE\n")
    st.append("           rAirChargeValve_Cmd_pct := 15.0;\n")
    st.append("           rAirBleedValve_Cmd_pct  := 5.0;\n")
    st.append("       END_IF;\n")
    st.append("       IF (ABS(rTempDiff) <= 80.0) AND (rStateTimer_s >= 10.0) THEN\n")
    st.append("           eState := 6; (* Transition to STATE_JET_TO_WIRE_SPEED_SYNCHRONIZATION *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 11;\n")
    st.append("       END_IF;\n\n")

    # State 6: STATE_JET_TO_WIRE_SPEED_SYNCHRONIZATION
    st.append("    6: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_JET_TO_WIRE_SPEED_SYNCHRONIZATION: Precision 1.025 Velocity Ratio Engagement          *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState     := 6;\n")
    st.append("       rJetSyncTimer_s     := rStateTimer_s;\n")
    st.append("       rTempDiff := rCalc_JetToWireRatio - rTarget_JetToWireRatio;\n")
    st.append("       IF (ABS(rTempDiff) <= 0.008) AND (rWireSpeed_Voted_mpmin >= (rTarget_WireSpeed_mpmin * 0.95)) AND (rStateTimer_s >= 8.0) THEN\n")
    st.append("           eState := 7; (* Transition to STATE_CD_SLICE_LIP_THERMAL_PROFILE_BASELINE *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 11;\n")
    st.append("       END_IF;\n\n")

    # State 7: STATE_CD_SLICE_LIP_THERMAL_PROFILE_BASELINE
    st.append("    7: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_CD_SLICE_LIP_THERMAL_PROFILE_BASELINE: 64 Spindle Heating Equilibrium & Pre-Heat      *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState               := 7;\n")
    st.append("       rSliceThermalBaselineTimer_s  := rStateTimer_s;\n")
    st.append("       IF (rStateTimer_s >= 15.0) AND (rCalc_MaxSliceCurvature_um <= rMaxAllowedCurvature_um) AND (rCalc_MaxAdjacentDelta_um <= rMaxAllowedAdjacentDelta_um) THEN\n")
    st.append("           eState := 8; (* Transition to STATE_NOMINAL_HIGH_SPEED_WEB_PRODUCTION_MPC *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 11;\n")
    st.append("       END_IF;\n\n")

    # State 8: STATE_NOMINAL_HIGH_SPEED_WEB_PRODUCTION_MPC
    st.append("    8: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_NOMINAL_HIGH_SPEED_WEB_PRODUCTION_MPC: Full 1,800 [m/min] Steady-State Production      *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState := 8;\n")
    st.append("       IF bGradeChangeCmd THEN\n")
    st.append("           eState := 9; (* Online Grade Change *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 11; (* Controlled Rampdown *)\n")
    st.append("       END_IF;\n\n")

    # State 9: STATE_ONLINE_GRADE_CHANGE_TRANSITION_RAMP
    st.append("    9: (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       (* STATE_ONLINE_GRADE_CHANGE_TRANSITION_RAMP: High-Speed Web Weight / Speed Trajectory Shift   *)\n")
    st.append("       (* -------------------------------------------------------------------------------------------- *)\n")
    st.append("       iActiveFsmState       := 9;\n")
    st.append("       rGradeChangeTimer_s   := rStateTimer_s;\n")
    st.append("       (* Dynamic trajectory tracking validation *)\n")
    st.append("       IF (ABS(rCalc_MeanBasisWeight_gpm2 - rTarget_BasisWeight_gpm2) <= 1.2) AND (ABS(rCalc_JetToWireRatio - rTarget_JetToWireRatio) <= 0.005) AND (rStateTimer_s >= 20.0) THEN\n")
    st.append("           eState := 8; (* Return to Nominal Production *)\n")
    st.append("       ELSIF bMachineStop THEN\n")
    st.append("           eState := 11;\n")
    st.append("       END_IF;\n\n")

    # State 10: STATE_SHEET_BREAK_EMERGENCY_SLURRY_DIVERSION
    st.append("    10: (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        (* STATE_SHEET_BREAK_EMERGENCY_SLURRY_DIVERSION: Optical Break Gate Solenoid Trip & Wire Float *)\n")
    st.append("        (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        iActiveFsmState             := 10;\n")
    st.append("        bEmergencySlurryDivertValve := TRUE; (* Dump slurry to couch pit *)\n")
    st.append("        bWhiteWaterBypassValve      := TRUE;\n")
    st.append("        rFanPump_SpeedCmd_pct       := 30.0; (* Drop to recirculation idle *)\n")
    st.append("        rDilutionHeaderValve_Cmd_pct:= 10.0;\n")
    st.append("        rStockOverflowValve_Cmd_pct := 90.0;\n")
    st.append("        rAirChargeValve_Cmd_pct     := 0.0;\n")
    st.append("        rAirBleedValve_Cmd_pct      := 40.0; (* Relieve pad *)\n")
    st.append("        rSheetBreakDivertTimer_s    := rStateTimer_s;\n")
    st.append("        IF NOT bSheetBreakDetected AND bFaultReset AND (rStateTimer_s >= 10.0) THEN\n")
    st.append("            bEmergencySlurryDivertValve := FALSE;\n")
    st.append("            eState := 4; (* Re-lock pond level and ramp back up *)\n")
    st.append("        ELSIF bMachineStop THEN\n")
    st.append("            eState := 11;\n")
    st.append("        END_IF;\n\n")

    # State 11: STATE_CONTROLLED_WIRE_RAMPDOWN_AND_HEADBOX_FLOAT
    st.append("    11: (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        (* STATE_CONTROLLED_WIRE_RAMPDOWN_AND_HEADBOX_FLOAT: Controlled Web Deceleration & Float Stop  *)\n")
    st.append("        (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        iActiveFsmState             := 11;\n")
    st.append("        bEmergencySlurryDivertValve := FALSE;\n")
    st.append("        rWireRampdownTimer_s        := rStateTimer_s;\n")
    st.append("        (* Ramp down fan pump safely *)\n")
    st.append("        IF rFanPump_SpeedCmd_pct > 10.0 THEN\n")
    st.append("            rFanPump_SpeedCmd_pct := rFanPump_SpeedCmd_pct - (3.5 * tScanCycleTime_s);\n")
    st.append("        ELSE\n")
    st.append("            rFanPump_SpeedCmd_pct := 0.0;\n")
    st.append("        END_IF;\n")
    st.append("        rAirChargeValve_Cmd_pct     := 0.0;\n")
    st.append("        rAirBleedValve_Cmd_pct      := 80.0;\n")
    st.append("        rStockOverflowValve_Cmd_pct := 100.0;\n")
    st.append("        IF (rFanPump_SpeedCmd_pct <= 0.5) AND (rHeadPress_Voted_kPa <= 25.0) AND (rStateTimer_s >= 15.0) THEN\n")
    st.append("            eState := 0; (* Returned to IDLE *)\n")
    st.append("        END_IF;\n\n")

    # State 12: STATE_POST_RUN_ACID_CAUSTIC_CLEANING_CYCLE
    st.append("    12: (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        (* STATE_POST_RUN_ACID_CAUSTIC_CLEANING_CYCLE: Chemical CIP Recirculation & Biocide Washdown   *)\n")
    st.append("        (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        iActiveFsmState               := 12;\n")
    st.append("        bWhiteWaterBypassValve        := TRUE;\n")
    st.append("        rWhiteWaterFlushValve_Cmd_pct := 100.0;\n")
    st.append("        rFanPump_SpeedCmd_pct         := 35.0; (* Chemical loop recirculation *)\n")
    st.append("        rSliceLipMean_Cmd_mm          := 25.0; (* Wide open wash gap *)\n")
    st.append("        rDilutionHeaderValve_Cmd_pct  := 80.0;\n")
    st.append("        rStockOverflowValve_Cmd_pct   := 70.0;\n")
    st.append("        rAirChargeValve_Cmd_pct       := 0.0;\n")
    st.append("        rAirBleedValve_Cmd_pct        := 100.0;\n")
    st.append("        rCipCleanTimer_s              := rStateTimer_s;\n")
    st.append("        IF (rStateTimer_s >= 60.0) OR bMachineStop THEN\n")
    st.append("            eState := 0; (* Return to IDLE *)\n")
    st.append("        END_IF;\n\n")

    # State 13: STATE_EMERGENCY_PUMP_CAVITATION_OR_STOCK_RUNOUT_TRIP
    st.append("    13: (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        (* STATE_EMERGENCY_PUMP_CAVITATION_OR_STOCK_RUNOUT_TRIP: Catastrophic Hardware Protection Trip *)\n")
    st.append("        (* ------------------------------------------------------------------------------------------- *)\n")
    st.append("        iActiveFsmState             := 13;\n")
    st.append("        bFanPumpFastTrip            := TRUE;\n")
    st.append("        bEmergencySlurryDivertValve := TRUE;\n")
    st.append("        bSliceLipProtectiveRetract  := TRUE;\n")
    st.append("        bAirPadFastDepressurize     := TRUE;\n")
    st.append("        bWhiteWaterBypassValve      := TRUE;\n")
    st.append("        rFanPump_SpeedCmd_pct       := 0.0;\n")
    st.append("        rAirChargeValve_Cmd_pct     := 0.0;\n")
    st.append("        rAirBleedValve_Cmd_pct      := 100.0;\n")
    st.append("        rWhiteWaterFlushValve_Cmd_pct := 0.0;\n")
    st.append("        rDilutionHeaderValve_Cmd_pct:= 0.0;\n")
    st.append("        rStockOverflowValve_Cmd_pct := 100.0;\n")
    st.append("        rEmergencyTripTimer_s       := rStateTimer_s;\n")
    st.append("        IF bFaultReset AND NOT bEmergencyStop AND NOT bHeadPress_Trip AND NOT bPondLevel_Trip THEN\n")
    st.append("            bFanPumpFastTrip            := FALSE;\n")
    st.append("            bEmergencySlurryDivertValve := FALSE;\n")
    st.append("            bSliceLipProtectiveRetract  := FALSE;\n")
    st.append("            bAirPadFastDepressurize     := FALSE;\n")
    st.append("            eState := 0; (* Reset to IDLE *)\n")
    st.append("        END_IF;\n")

    st.append("    ELSE\n")
    st.append("        (* Undefined State Safety Fallback *)\n")
    st.append("        eState := 0;\n")
    st.append("END_CASE;\n\n")

    return "".join(st)

