# Generates Phase 3: Receding-Horizon MPC Optimization with Projected Gradient Descent & Lorentz Actuator Allocation

def get_phase3_code():
    lines = []
    lines.append("(* ====================================================================================================")
    lines.append("   PHASE 3: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) WITH PROJECTED GRADIENT DESCENT")
    lines.append("   ==================================================================================================== *)")
    lines.append("    (* Populate MPC reference trajectory over prediction horizon Np = 4 *)")
    lines.append("    FOR p := 1 TO 4 DO")
    lines.append("        aMpcRefX[p, 1] := (rTargetPosX_nm * 1.0E-9) + ((p * 0.001) * (rTargetVelX_mms * 1.0E-3));")
    lines.append("        aMpcRefX[p, 2] := (rTargetPosY_nm * 1.0E-9) + ((p * 0.001) * (rTargetVelY_mms * 1.0E-3));")
    lines.append("        aMpcRefX[p, 3] := (rTargetPosZ_nm * 1.0E-9) + (rFocusZCorrection_nm * 1.0E-9);")
    lines.append("        aMpcRefX[p, 4] := rFocusTiltRxCorrection_urad * 1.0E-6;")
    lines.append("        aMpcRefX[p, 5] := rFocusTiltRyCorrection_urad * 1.0E-6;")
    lines.append("        aMpcRefX[p, 6] := 0.000000;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* Initialize projected control sequence with warm-start shifted solution *)")
    lines.append("    FOR m := 1 TO 6 DO")
    lines.append("        aMpcSeqU[1, m] := aMpcSeqU[2, m];")
    lines.append("        aMpcSeqU[2, m] := aMpcSeqU[2, m];")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------")
    lines.append("       UNROLLED PROJECTED GRADIENT DESCENT (PGD) OPTIMIZER (6 ITERATIONS)")
    lines.append("       Minimizes Cost J = Sum(||x - x_ref||_Q^2) + Sum(||u||_R^2) + Sum(||Delta_u||_S^2) + ||x_Np - x_ref||_P^2")
    lines.append("       ------------------------------------------------------------------------------------------------ *)")
    lines.append("    FOR iter := 1 TO nPgdIterations DO")
    lines.append("        (* Forward state trajectory simulation across prediction horizon Np = 4 *)")
    lines.append("        FOR m := 1 TO 6 DO")
    lines.append("            (* Step 1 simulation using current state and u[1] *)")
    lines.append("            aMpcPredX[1, m] := aStateX[m] + (0.001 * aStateX[m + 6]) + (1.538462E-8 * aMpcSeqU[1, m]);")
    lines.append("            (* Step 2 simulation using u[1] *)")
    lines.append("            aMpcPredX[2, m] := aMpcPredX[1, m] + (0.001 * (aStateX[m + 6] + (3.076923E-5 * aMpcSeqU[1, m])));")
    lines.append("            (* Step 3 simulation using u[2] *)")
    lines.append("            aMpcPredX[3, m] := aMpcPredX[2, m] + (0.001 * (aStateX[m + 6] + (3.076923E-5 * (aMpcSeqU[1, m] + aMpcSeqU[2, m]))));")
    lines.append("            (* Step 4 terminal simulation using u[2] *)")
    lines.append("            aMpcPredX[4, m] := aMpcPredX[3, m] + (0.001 * (aStateX[m + 6] + (3.076923E-5 * (aMpcSeqU[1, m] + (2.0 * aMpcSeqU[2, m])))));")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Compute cost functional analytical gradient with respect to u[1] and u[2] *)")
    lines.append("        FOR m := 1 TO 6 DO")
    lines.append("            (* Gradient for control horizon step 1: tracking error + control penalty + slew penalty *)")
    lines.append("            aMpcGradU[1, m] := (aMatQ[m, m] * (aMpcPredX[1, m] - aMpcRefX[1, m]) * 1.538462E-8) +")
    lines.append("                               (aMatQ[m, m] * (aMpcPredX[2, m] - aMpcRefX[2, m]) * 3.076923E-8) +")
    lines.append("                               (aMatR[m, m] * aMpcSeqU[1, m]) +")
    lines.append("                               (aMatS[m, m] * (aMpcSeqU[1, m] - aMpcControlU_Prev[m])) +")
    lines.append("                               (aMatS[m, m] * (aMpcSeqU[1, m] - aMpcSeqU[2, m]));")
    lines.append("")
    lines.append("            (* Gradient for control horizon step 2: tracking error + terminal cost + slew penalty *)")
    lines.append("            aMpcGradU[2, m] := (aMatQ[m, m] * (aMpcPredX[3, m] - aMpcRefX[3, m]) * 3.076923E-8) +")
    lines.append("                               (aMatP[m, m] * (aMpcPredX[4, m] - aMpcRefX[4, m]) * 6.153846E-8) +")
    lines.append("                               (aMatR[m, m] * aMpcSeqU[2, m]) +")
    lines.append("                               (aMatS[m, m] * (aMpcSeqU[2, m] - aMpcSeqU[1, m]));")
    lines.append("")
    lines.append("            (* Gradient Descent Update Step *)")
    lines.append("            aMpcSeqU[1, m] := aMpcSeqU[1, m] - (rPgdStepSize * aMpcGradU[1, m]);")
    lines.append("            aMpcSeqU[2, m] := aMpcSeqU[2, m] - (rPgdStepSize * aMpcGradU[2, m]);")
    lines.append("")
    lines.append("            (* Actuator generalized force saturation box constraints projection *)")
    lines.append("            IF m <= 3 THEN")
    lines.append("                (* Linear forces Fx, Fy, Fz limit: +/- 650 N *)")
    lines.append("                IF aMpcSeqU[1, m] > 650.0 THEN aMpcSeqU[1, m] := 650.0; END_IF;")
    lines.append("                IF aMpcSeqU[1, m] < -650.0 THEN aMpcSeqU[1, m] := -650.0; END_IF;")
    lines.append("                IF aMpcSeqU[2, m] > 650.0 THEN aMpcSeqU[2, m] := 650.0; END_IF;")
    lines.append("                IF aMpcSeqU[2, m] < -650.0 THEN aMpcSeqU[2, m] := -650.0; END_IF;")
    lines.append("            ELSE")
    lines.append("                (* Torques Tx, Ty, Tz limit: +/- 120 N*m *)")
    lines.append("                IF aMpcSeqU[1, m] > 120.0 THEN aMpcSeqU[1, m] := 120.0; END_IF;")
    lines.append("                IF aMpcSeqU[1, m] < -120.0 THEN aMpcSeqU[1, m] := -120.0; END_IF;")
    lines.append("                IF aMpcSeqU[2, m] > 120.0 THEN aMpcSeqU[2, m] := 120.0; END_IF;")
    lines.append("                IF aMpcSeqU[2, m] < -120.0 THEN aMpcSeqU[2, m] := -120.0; END_IF;")
    lines.append("            END_IF;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* Commit optimal control command from horizon step 1 *)")
    lines.append("    FOR m := 1 TO 6 DO")
    lines.append("        aForceCmd6Dof[m] := aMpcSeqU[1, m];")
    lines.append("        aMpcControlU_Prev[m] := aForceCmd6Dof[m];")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------")
    lines.append("       LORENTZ ACTUATOR COIL CURRENT ALLOCATION & SLEW-RATE LIMITING")
    lines.append("       Transforms 6-DOF Generalized Forces into 8 Actuator Coil Demands via Pseudo-Inverse M_alloc")
    lines.append("       ------------------------------------------------------------------------------------------------ *)")
    
    # 8 Actuators
    act_names = ["X1", "X2", "Y1", "Y2", "Z1", "Z2", "Z3", "Z4"]
    for idx, act in enumerate(act_names, 1):
        lines.append(f"    rActuatorCurrent_{act}_A := 0.0;")
        lines.append(f"    FOR m := 1 TO 6 DO")
        lines.append(f"        rActuatorCurrent_{act}_A := rActuatorCurrent_{act}_A + (aMatAlloc[{idx}, m] * aForceCmd6Dof[m]);")
        lines.append(f"    END_FOR;")
        lines.append(f"    (* Actuator Continuous Thermal Clamping [-25.0 A, +25.0 A] *)")
        lines.append(f"    IF rActuatorCurrent_{act}_A > cMaxCoilCurrent_A THEN rActuatorCurrent_{act}_A := cMaxCoilCurrent_A; END_IF;")
        lines.append(f"    IF rActuatorCurrent_{act}_A < cMinCoilCurrent_A THEN rActuatorCurrent_{act}_A := cMinCoilCurrent_A; END_IF;")
        lines.append(f"    (* Slew rate limiting *)")
        lines.append(f"    IF (rActuatorCurrent_{act}_A - rCoilCurPrev_{act}) > (cMaxCoilSlewRate_A_ms * tCycleTime_ms) THEN")
        lines.append(f"        rActuatorCurrent_{act}_A := rCoilCurPrev_{act} + (cMaxCoilSlewRate_A_ms * tCycleTime_ms);")
        lines.append(f"    ELSIF (rActuatorCurrent_{act}_A - rCoilCurPrev_{act}) < (-cMaxCoilSlewRate_A_ms * tCycleTime_ms) THEN")
        lines.append(f"        rActuatorCurrent_{act}_A := rCoilCurPrev_{act} - (cMaxCoilSlewRate_A_ms * tCycleTime_ms);")
        lines.append(f"    END_IF;")
        lines.append(f"    rCoilCurPrev_{act} := rActuatorCurrent_{act}_A;")
        lines.append("")

    return "\n".join(lines)

