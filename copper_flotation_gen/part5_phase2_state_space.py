# copper_flotation_gen/part5_phase2_state_space.py

def get_phase2_state_space():
    lines = []
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL STATE-SPACE ESTIMATION & LUENBERGER OBSERVER                *)")
    lines.append("(* Explicit Slurry Hydrodynamics, Bubble Surface Area Flux Sb, Flotation Kinetics & Observer Innovation *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 1: Flotation Hydrodynamics & Aeration Gas Dispersion Physics                                *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Superficial Gas Velocity Jg [cm/s] derived from Orifice Differential Pressure & Valve Opening *)")
    lines.append("    IF rAirPress_Manifold_Voted > 0.0 THEN")
    lines.append("        rSuperficialGasVelocity_cms := (0.165 + 0.0035 * vecU[3]) * SQRT(MAX(0.0, rAirPress_Manifold_Voted * 1000.0)) * 0.045;")
    lines.append("    ELSE")
    lines.append("        rSuperficialGasVelocity_cms := 0.0;")
    lines.append("    END_IF;")
    lines.append("    rSuperficialGasVelocity_cms := LIMIT(0.20, rSuperficialGasVelocity_cms, 3.50);")
    lines.append("")
    lines.append("    (* Sauter Mean Bubble Diameter d32 [mm] as a Function of MIBC Surfactant Frother Dosing *)")
    lines.append("    (* As MIBC Concentration Increases towards CCC (Critical Coalescence Concentration), d32 Reduces *)")
    lines.append("    rBubbleDiameter_d32_mm := 0.85 + (3.20 - 0.85) * EXP(-0.045 * LIMIT(0.0, vecU[5], 100.0));")
    lines.append("    rBubbleDiameter_d32_mm := LIMIT(0.70, rBubbleDiameter_d32_mm, 4.00);")
    lines.append("")
    lines.append("    (* Bubble Surface Area Flux Sb = 6.0 * Jg / d32 [1/s] *)")
    lines.append("    IF rBubbleDiameter_d32_mm > 0.01 THEN")
    lines.append("        rBubbleSurfaceAreaFlux_Sb_s := (6.0 * (rSuperficialGasVelocity_cms * 10.0)) / rBubbleDiameter_d32_mm;")
    lines.append("    ELSE")
    lines.append("        rBubbleSurfaceAreaFlux_Sb_s := 0.0;")
    lines.append("    END_IF;")
    lines.append("    rBubbleSurfaceAreaFlux_Sb_s := LIMIT(10.0, rBubbleSurfaceAreaFlux_Sb_s, 140.0);")
    lines.append("")
    lines.append("    (* True Flotation Froth Recovery Factor Alpha_f = EXP(-Beta * h_froth / Jg) *)")
    lines.append("    IF rSuperficialGasVelocity_cms > 0.1 THEN")
    lines.append("        rFrothRecoveryFactor_Alpha := EXP(-0.0085 * rFrothHeight_Voted / rSuperficialGasVelocity_cms);")
    lines.append("    ELSE")
    lines.append("        rFrothRecoveryFactor_Alpha := 0.10;")
    lines.append("    END_IF;")
    lines.append("    rFrothRecoveryFactor_Alpha := LIMIT(0.15, rFrothRecoveryFactor_Alpha, 0.98);")
    lines.append("")
    lines.append("    (* Chalcopyrite True Flotation Kinetics Rate Constant k_Cu [1/s] Driven by PAX Collector *)")
    lines.append("    rTrueFlotationRate_k_Cu := 0.125 * (LIMIT(0.0, vecU[4], 100.0) / (22.5 + LIMIT(0.0, vecU[4], 100.0))) * (rBubbleSurfaceAreaFlux_Sb_s / 60.0) * rFrothRecoveryFactor_Alpha;")
    lines.append("    rTrueFlotationRate_k_Cu := LIMIT(0.005, rTrueFlotationRate_k_Cu, 0.450);")
    lines.append("")
    lines.append("    (* Hydrophilic Gangue (Clay/Silica) Water Entrainment Ratio *)")
    lines.append("    rEntrainmentRatio_Clay := 0.025 * (rSuperficialGasVelocity_cms / (rFrothHeight_Voted + 25.0));")
    lines.append("    rEntrainmentRatio_Clay := LIMIT(0.005, rEntrainmentRatio_Clay, 0.120);")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 2: Populate Measurement Vector vecY_meas from Fault-Tolerant Voted Sensors                 *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    vecY_meas[0] := rPulpLevel_Cell1_Voted;   (* Rougher Cell 1 Pulp Level [mm] *)")
    lines.append("    vecY_meas[1] := rPulpLevel_Cell6_Voted;   (* Cleaner Cell 6 Pulp Level [mm] *)")
    lines.append("    vecY_meas[2] := rPulpLevel_Cell12_Voted;  (* Scavenger Cell 12 Pulp Level [mm] *)")
    lines.append("    vecY_meas[3] := rFrothHeight_Voted;       (* Froth Bed Thickness [mm] *)")
    lines.append("    vecY_meas[4] := rSuperficialGasVelocity_cms; (* Superficial Gas Velocity Jg [cm/s] *)")
    lines.append("    vecY_meas[5] := rXRF_ConcCu_Voted;        (* In-Stream XRF Concentrate Copper Grade [% Cu] *)")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 3: Compute Predicted Output vecY_hat = C * vecX_hat + D * vecU & Innovation Residuals     *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    FOR iIdx := 0 TO 5 DO")
    lines.append("        rTempSum := 0.0;")
    lines.append("        FOR jIdx := 0 TO 7 DO")
    lines.append("            rTempSum := rTempSum + matC[iIdx, jIdx] * vecX_hat[jIdx];")
    lines.append("        END_FOR;")
    lines.append("        FOR mIdx := 0 TO 5 DO")
    lines.append("            rTempSum := rTempSum + matD[iIdx, mIdx] * vecU[mIdx];")
    lines.append("        END_FOR;")
    lines.append("        vecY_hat[iIdx] := rTempSum;")
    lines.append("        vecInnov[iIdx] := vecY_meas[iIdx] - vecY_hat[iIdx];")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 4: Luenberger Observer State Propagation: vecX_pred = A*vecX_hat + B*vecU + L*vecInnov      *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    FOR iIdx := 0 TO 7 DO")
    lines.append("        rTempSum := 0.0;")
    lines.append("        FOR jIdx := 0 TO 7 DO")
    lines.append("            rTempSum := rTempSum + matA[iIdx, jIdx] * vecX_hat[jIdx];")
    lines.append("        END_FOR;")
    lines.append("        FOR mIdx := 0 TO 5 DO")
    lines.append("            rTempSum := rTempSum + matB[iIdx, mIdx] * vecU[mIdx];")
    lines.append("        END_FOR;")
    lines.append("        FOR jIdx := 0 TO 5 DO")
    lines.append("            rTempSum := rTempSum + matL[iIdx, jIdx] * vecInnov[jIdx];")
    lines.append("        END_FOR;")
    lines.append("        vecX_pred[iIdx] := rTempSum;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 5: Physical State Bounds Enforcement & Observer State Vector Commitment                     *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    vecX_hat[0] := LIMIT(400.0,  vecX_pred[0], 1800.0);  (* Cell 1 Pulp Level [mm] *)")
    lines.append("    vecX_hat[1] := LIMIT(400.0,  vecX_pred[1], 1750.0);  (* Cell 6 Pulp Level [mm] *)")
    lines.append("    vecX_hat[2] := LIMIT(350.0,  vecX_pred[2], 1700.0);  (* Cell 12 Pulp Level [mm] *)")
    lines.append("    vecX_hat[3] := LIMIT(20.0,   vecX_pred[3], 450.0);   (* Froth Bed Depth [mm] *)")
    lines.append("    vecX_hat[4] := LIMIT(3.0,    vecX_pred[4], 35.0);    (* Air Holdup Fraction [% vol] *)")
    lines.append("    vecX_hat[5] := LIMIT(0.10,   vecX_pred[5], 3.80);    (* Superficial Gas Velocity Jg [cm/s] *)")
    lines.append("    vecX_hat[6] := LIMIT(8.0,    vecX_pred[6], 42.0);    (* Concentrate Cu Grade [% Cu] *)")
    lines.append("    vecX_hat[7] := LIMIT(35.0,   vecX_pred[7], 98.5);    (* Cumulative Copper Recovery [% Rec] *)")
    lines.append("")
    lines.append("    (* Update HMI and SCADA Output Observation Registers *)")
    lines.append("    rEst_PulpLevel_Cell1_mm     := vecX_hat[0];")
    lines.append("    rEst_PulpLevel_Cell6_mm     := vecX_hat[1];")
    lines.append("    rEst_PulpLevel_Cell12_mm    := vecX_hat[2];")
    lines.append("    rEst_FrothThickness_mm      := vecX_hat[3];")
    lines.append("    rEst_AirHoldup_pct          := vecX_hat[4];")
    lines.append("    rEst_SuperficialGasVel_cms  := vecX_hat[5];")
    lines.append("    rEst_ConcentrateGrade_pct   := vecX_hat[6];")
    lines.append("    rEst_CumulativeRecovery_pct := vecX_hat[7];")
    lines.append("    rCalc_BubbleSurfaceAreaFlux_s := rBubbleSurfaceAreaFlux_Sb_s;")
    lines.append("    rCalc_FrothRecoveryFactor   := rFrothRecoveryFactor_Alpha;")

    return "\n".join(lines)
