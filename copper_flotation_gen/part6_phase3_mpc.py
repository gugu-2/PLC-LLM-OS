# copper_flotation_gen/part6_phase3_mpc.py

def get_phase3_mpc():
    lines = []
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 3: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) WITH PROJECTED GRADIENT DESCENT (PGD)       *)")
    lines.append("(* Horizon N = 5 Steps (100 [ms]), 6 Unrolled PGD Iterations, Cross-Coupled Dart Valves & Slew Bounds   *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 1: Dynamic State Trajectory Setpoint Adaptation Based on Feed Slurry & Operating Mode     *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    IF eState = 7 THEN")
    lines.append("        (* State 7: Gangue Entrainment Washing - Deepen Froth Bed & Lower Slurry Pulp Levels *)")
    lines.append("        vecX_target[0] := 1075.0;  (* Cell 1 Target Level Dropped [mm] *)")
    lines.append("        vecX_target[1] := 1025.0;  (* Cell 6 Target Level Dropped [mm] *)")
    lines.append("        vecX_target[2] := 975.0;   (* Cell 12 Target Level Dropped [mm] *)")
    lines.append("        vecX_target[3] := 220.0;   (* Deeper Froth Bed to Enhance Drainage [mm] *)")
    lines.append("        vecX_target[4] := 18.2;    (* Slightly Higher Air Holdup [% vol] *)")
    lines.append("        vecX_target[5] := 1.15;    (* Reduced Superficial Gas Velocity Jg [cm/s] *)")
    lines.append("        vecX_target[6] := 30.5;    (* Target Higher Concentrate Copper Grade [% Cu] *)")
    lines.append("        vecX_target[7] := 86.5;    (* Balanced Recovery Target [% Rec] *)")
    lines.append("    ELSIF eState = 9 THEN")
    lines.append("        (* State 9: Froth Collapse Recovery - Shallow Froth & Boosted Bubble Generation *)")
    lines.append("        vecX_target[0] := 1120.0;  (* Raise Pulp Level to Assist Lip Crowding [mm] *)")
    lines.append("        vecX_target[1] := 1070.0;  (* Mid-Bank Pulp Level [mm] *)")
    lines.append("        vecX_target[2] := 1015.0;  (* Tailings Pulp Level [mm] *)")
    lines.append("        vecX_target[3] := 95.0;    (* Shorter Froth Transport Distance [mm] *)")
    lines.append("        vecX_target[4] := 19.5;    (* Elevated Holdup [% vol] *)")
    lines.append("        vecX_target[5] := 1.45;    (* High Superficial Gas Velocity [cm/s] *)")
    lines.append("        vecX_target[6] := 26.8;    (* Temporary Lower Grade Allowed [% Cu] *)")
    lines.append("        vecX_target[7] := 90.5;    (* Maximize Mineral Mass Pull [% Rec] *)")
    lines.append("    ELSIF eState = 10 THEN")
    lines.append("        (* State 10: Slurry Feed Volumetric Surge - Fast Freeboard Protection *)")
    lines.append("        vecX_target[0] := 1040.0;  (* Fast Level Suppression [mm] *)")
    lines.append("        vecX_target[1] := 990.0;   (* Freeboard Safety Margin [mm] *)")
    lines.append("        vecX_target[2] := 940.0;   (* Tailings Discharge Acceleration [mm] *)")
    lines.append("        vecX_target[3] := 165.0;   (* Stable Froth Bed [mm] *)")
    lines.append("        vecX_target[4] := 16.0;    (* Nominal Air Holdup [% vol] *)")
    lines.append("        vecX_target[5] := 1.20;    (* Nominal Superficial Velocity [cm/s] *)")
    lines.append("        vecX_target[6] := 27.5;    (* Nominal Grade Target [% Cu] *)")
    lines.append("        vecX_target[7] := 87.5;    (* Nominal Recovery Target [% Rec] *)")
    lines.append("    ELSE")
    lines.append("        (* Standard Operating Regime: Optimal Grade-Recovery Pareto Frontier *)")
    lines.append("        vecX_target[0] := 1100.0;  (* Rougher Cell 1 Standard Level [mm] *)")
    lines.append("        vecX_target[1] := 1050.0;  (* Cleaner Cell 6 Standard Level [mm] *)")
    lines.append("        vecX_target[2] := 1000.0;  (* Scavenger Cell 12 Standard Level [mm] *)")
    lines.append("        vecX_target[3] := 150.0;   (* Optimal Froth Thickness [mm] *)")
    lines.append("        vecX_target[4] := 16.5;    (* Optimal Air Holdup Fraction [% vol] *)")
    lines.append("        vecX_target[5] := 1.25;    (* Optimal Superficial Gas Velocity [cm/s] *)")
    lines.append("        vecX_target[6] := 28.5;    (* Design Copper Concentrate Grade [% Cu] *)")
    lines.append("        vecX_target[7] := 88.5;    (* Design Cumulative Recovery [% Rec] *)")
    lines.append("    END_IF;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 2: Initialize Horizon Trajectories: Seed Initial State & Warm-Start Control Sequences      *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    FOR iIdx := 0 TO 7 DO")
    lines.append("        trajX_mpc[0, iIdx] := vecX_hat[iIdx];")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    FOR kStep := 0 TO 4 DO")
    lines.append("        FOR mIdx := 0 TO 5 DO")
    lines.append("            trajU_mpc[kStep, mIdx] := vecU[mIdx];")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 3: Unrolled Projected Gradient Descent (PGD) Solver Core (6 Fixed Iterations)              *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    FOR iIter := 1 TO 6 DO")
    lines.append("        (* Sub-step 3A: Forward State Simulation Over Prediction Horizon N = 5 *)")
    lines.append("        FOR kStep := 0 TO 4 DO")
    lines.append("            FOR iIdx := 0 TO 7 DO")
    lines.append("                rTempSum := 0.0;")
    lines.append("                FOR jIdx := 0 TO 7 DO")
    lines.append("                    rTempSum := rTempSum + matA[iIdx, jIdx] * trajX_mpc[kStep, jIdx];")
    lines.append("                END_FOR;")
    lines.append("                FOR mIdx := 0 TO 5 DO")
    lines.append("                    rTempSum := rTempSum + matB[iIdx, mIdx] * trajU_mpc[kStep, mIdx];")
    lines.append("                END_FOR;")
    lines.append("")
    lines.append("                (* Hydraulic Cross-Coupling between Dart Valves on Pulp Level Compartments (i=0,1,2) *)")
    lines.append("                IF iIdx <= 2 THEN")
    lines.append("                    rTempCrossCoupling := 0.0;")
    lines.append("                    FOR mIdx := 0 TO 2 DO")
    lines.append("                        rTempCrossCoupling := rTempCrossCoupling + matM_hydro[iIdx, mIdx] * (trajU_mpc[kStep, mIdx] - vecU_target[mIdx]) * 0.082;")
    lines.append("                    END_FOR;")
    lines.append("                    rTempSum := rTempSum + rTempCrossCoupling;")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("                trajX_mpc[kStep + 1, iIdx] := rTempSum;")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Sub-step 3B: Calculate Quadratic Cost Metric J *)")
    lines.append("        rMpc_AccumulatedCost := 0.0;")
    lines.append("        FOR kStep := 1 TO 5 DO")
    lines.append("            FOR iIdx := 0 TO 7 DO")
    lines.append("                rTempDiff := trajX_mpc[kStep, iIdx] - vecX_target[iIdx];")
    lines.append("                IF kStep = 5 THEN")
    lines.append("                    rMpc_AccumulatedCost := rMpc_AccumulatedCost + vecP_terminal[iIdx] * rTempDiff * rTempDiff;")
    lines.append("                ELSE")
    lines.append("                    rMpc_AccumulatedCost := rMpc_AccumulatedCost + vecQ_weight[iIdx] * rTempDiff * rTempDiff;")
    lines.append("                END_IF;")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("        FOR kStep := 0 TO 4 DO")
    lines.append("            FOR mIdx := 0 TO 5 DO")
    lines.append("                rTempDiff := trajU_mpc[kStep, mIdx] - vecU_target[mIdx];")
    lines.append("                rMpc_AccumulatedCost := rMpc_AccumulatedCost + vecR_weight[mIdx] * rTempDiff * rTempDiff;")
    lines.append("                IF kStep = 0 THEN")
    lines.append("                    rTempDiff := trajU_mpc[0, mIdx] - vecU_prev[mIdx];")
    lines.append("                ELSE")
    lines.append("                    rTempDiff := trajU_mpc[kStep, mIdx] - trajU_mpc[kStep - 1, mIdx];")
    lines.append("                END_IF;")
    lines.append("                rMpc_AccumulatedCost := rMpc_AccumulatedCost + vecR_delta_weight[mIdx] * rTempDiff * rTempDiff;")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Sub-step 3C: Compute Analytical Gradients w.r.t Control Trajectory trajU_mpc *)")
    lines.append("        FOR kStep := 0 TO 4 DO")
    lines.append("            FOR mIdx := 0 TO 5 DO")
    lines.append("                (* Actuator Effort Gradient Component *)")
    lines.append("                rTempSum := 2.0 * vecR_weight[mIdx] * (trajU_mpc[kStep, mIdx] - vecU_target[mIdx]);")
    lines.append("")
    lines.append("                (* Actuator Slew Rate Gradient Component *)")
    lines.append("                IF kStep = 0 THEN")
    lines.append("                    rTempSum := rTempSum + 2.0 * vecR_delta_weight[mIdx] * (trajU_mpc[0, mIdx] - vecU_prev[mIdx]);")
    lines.append("                ELSE")
    lines.append("                    rTempSum := rTempSum + 2.0 * vecR_delta_weight[mIdx] * (trajU_mpc[kStep, mIdx] - trajU_mpc[kStep - 1, mIdx]);")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("                (* State Error Sensitivity Backpropagation via Matrix B and Hydraulic Matrix *)")
    lines.append("                FOR iIdx := 0 TO 7 DO")
    lines.append("                    rTempDiff := trajX_mpc[kStep + 1, iIdx] - vecX_target[iIdx];")
    lines.append("                    IF kStep = 4 THEN")
    lines.append("                        rTempSum := rTempSum + 2.0 * vecP_terminal[iIdx] * rTempDiff * matB[iIdx, mIdx];")
    lines.append("                    ELSE")
    lines.append("                        rTempSum := rTempSum + 2.0 * vecQ_weight[iIdx] * rTempDiff * matB[iIdx, mIdx];")
    lines.append("                    END_IF;")
    lines.append("                END_FOR;")
    lines.append("")
    lines.append("                (* Additional Hydraulic Coupling Gradient for Dart Valves (m=0,1,2) *)")
    lines.append("                IF mIdx <= 2 THEN")
    lines.append("                    FOR iIdx := 0 TO 2 DO")
    lines.append("                        rTempDiff := trajX_mpc[kStep + 1, iIdx] - vecX_target[iIdx];")
    lines.append("                        rTempSum := rTempSum + 2.0 * vecQ_weight[iIdx] * rTempDiff * matM_hydro[iIdx, mIdx] * 0.082;")
    lines.append("                    END_FOR;")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("                trajGrad_J[kStep, mIdx] := rTempSum;")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Sub-step 3D: Projected Gradient Descent Update with Physical Saturation & Slew Bounds *)")
    lines.append("        FOR kStep := 0 TO 4 DO")
    lines.append("            FOR mIdx := 0 TO 5 DO")
    lines.append("                rTempCandidate := trajU_mpc[kStep, mIdx] - (rPgd_StepSize * trajGrad_J[kStep, mIdx]);")
    lines.append("")
    lines.append("                (* Actuator Box Constraint Projection [0.0% to 100.0%] *)")
    lines.append("                rTempCandidate := LIMIT(vecU_min[mIdx], rTempCandidate, vecU_max[mIdx]);")
    lines.append("")
    lines.append("                (* Slew Rate Boundary Projection Relative to Preceding Control Value *)")
    lines.append("                IF kStep = 0 THEN")
    lines.append("                    rTempCandidate := LIMIT(vecU_prev[mIdx] - vecU_slewMax[mIdx], rTempCandidate, vecU_prev[mIdx] + vecU_slewMax[mIdx]);")
    lines.append("                ELSE")
    lines.append("                    rTempCandidate := LIMIT(trajU_mpc[kStep - 1, mIdx] - vecU_slewMax[mIdx], rTempCandidate, trajU_mpc[kStep - 1, mIdx] + vecU_slewMax[mIdx]);")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("                trajU_mpc[kStep, mIdx] := rTempCandidate;")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 4: Commit Optimal Control Action (Receding Horizon First Step vecU)                         *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    IF NOT bMpcManualOverride AND (eState >= 3 AND eState <= 11) THEN")
    lines.append("        FOR mIdx := 0 TO 5 DO")
    lines.append("            vecU[mIdx] := trajU_mpc[0, mIdx];")
    lines.append("            vecU_rate[mIdx] := (vecU[mIdx] - vecU_prev[mIdx]) / tScanCycleTime_s;")
    lines.append("            vecU_prev[mIdx] := vecU[mIdx];")
    lines.append("        END_FOR;")
    lines.append("    END_IF;")
    lines.append("    rMpc_QuadraticCostMetric := rMpc_AccumulatedCost;")
    lines.append("")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Step 5: Hydraulic Cascading to All 6 Compartment Dart Valves & Auxiliary Actuators              *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* Dart Valve 1: Rougher Group 1 Master Control Node *)")
    lines.append("    rDartValve_Cmd_1_pct := vecU[0];")
    lines.append("    (* Dart Valve 2: Rougher Group 2 Hydrostatic Interpolation *)")
    lines.append("    rDartValve_Cmd_2_pct := 0.65 * vecU[0] + 0.35 * vecU[1];")
    lines.append("    (* Dart Valve 3: Cleaner/Middlings Group 1 Master Control Node *)")
    lines.append("    rDartValve_Cmd_3_pct := vecU[1];")
    lines.append("    (* Dart Valve 4: Cleaner/Middlings Group 2 Hydrostatic Interpolation *)")
    lines.append("    rDartValve_Cmd_4_pct := 0.55 * vecU[1] + 0.45 * vecU[2];")
    lines.append("    (* Dart Valve 5: Scavenger Group 1 Hydrostatic Interpolation *)")
    lines.append("    rDartValve_Cmd_5_pct := 0.25 * vecU[1] + 0.75 * vecU[2];")
    lines.append("    (* Dart Valve 6: Scavenger Tailings Discharge Master Control Node *)")
    lines.append("    rDartValve_Cmd_6_pct := vecU[2];")
    lines.append("")
    lines.append("    (* Forced Aeration Flow Valve & Chemical Reagent Dosing Pump Outputs *)")
    lines.append("    rAirControlValve_Cmd_pct     := vecU[3];")
    lines.append("    rReagentPump_PaxCmd_pct      := vecU[4];")
    lines.append("    rReagentPump_MibcCmd_pct     := vecU[5];")

    return "\n".join(lines)
