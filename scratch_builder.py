    a("    ELSE")
    a("        (* Vortex shed into wake: catastrophic lift drop and buffet onset *)")
    a("        rVortexLift_CLv := 0.45 * EXP(-2.5 * (rVortexTime_tau - 2.0));")
    a("        bVortexSheddingActive := TRUE;")
    a("        bDynamicStallWarning := TRUE;")
    a("    END_IF;")
    a("ELSE")
    a("    rVortexTime_tau := 0.0;")
    a("    rVortexLift_CLv := rVortexLift_CLv * 0.92;")
    a("    IF rSeparation_Point_f > 0.70 THEN")
    a("        bDynamicStallWarning := FALSE;")
    a("        bVortexSheddingActive := FALSE;")
    a("    END_IF;")
    a("END_IF;")
    a("")
    a("(* Synthesized unsteady lift coefficient *)")
    a("rAttached_CL := rQuasiSteady_CL * EXPT((1.0 + SQRT(rSeparation_Point_f)) * 0.5, 2.0);")
    a("rTotal_Unsteady_CL := rAttached_CL + rVortexLift_CLv;")
    a("")
    a("(* Strouhal dominant vortex shedding frequency: St = 0.21, c = 1.6m *)")
    a("IF (rVoted_Airspeed_kmh > 15.0) AND (ABS(rEffective_AoA_deg) > 4.0) THEN")
    a("    rStrouhal_Freq_Calc := (0.21 * (rVoted_Airspeed_kmh / 3.6)) / (1.6 * MAX(0.08, SIN(ABS(rEffective_AoA_rad))));")
    a("ELSE")
    a("    rStrouhal_Freq_Calc := 0.0;")
    a("END_IF;")
    a("rVortexSheddingFreq_Hz := rStrouhal_Freq_Calc;")
    a("")
    a("(* 2nd-Order Digital Bandpass Filter for Piezo Buffet Accelerometer *)")
    a("(* Center freq ~ 18 Hz, sampling at 100 Hz (dt = 0.010 s) *)")
    a("rBuffetBandpass_x1 := rBuffetBandpass_x1 + (rDeltaT * rBuffetBandpass_x2);")
    a("rBuffetBandpass_x2 := rBuffetBandpass_x2 + (rDeltaT * ((125.0 * rBuffetAccel_RMS_m_s2) - (24.0 * rBuffetBandpass_x2) - (12800.0 * rBuffetBandpass_x1)));")
    a("rBuffetFiltered_RMS := ABS(rBuffetBandpass_x2) * 0.085;")
    a("IF (rBuffetFiltered_RMS > 8.5) AND (rSeparation_Point_f < 0.45) THEN")
    a("    bVortexSheddingActive := TRUE;")
    a("    dwFaultAlarmWord := dwFaultAlarmWord OR 16#0000_0020; (* Bit 5: Severe Buffet Shedding *)")
    a("END_IF;")
    a("")

    # SECTION 4: High-Rate Battery Electro-Thermal Decoupling
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* SECTION 4: HIGH-RATE BATTERY ELECTRO-THERMAL DECOUPLING OBSERVER                         *)")
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* Equivalent internal resistance calculation: R_int(SOC, T_core) *)")
    a("rBattInternalResistance := 0.018 * (1.0 + (0.0035 * (30.0 - rBattCoreTemp_Est)) + (0.065 / MAX(0.05, rBattSOC_pct * 0.01)));")
    a("rJouleHeatPower_W := EXPT(rVoted_BattCurrent_A, 2.0) * rBattInternalResistance;")
    a("")
    a("(* 2-State Lumped Thermal Model: C_core = 12,500 J/K, C_surf = 6,800 J/K *)")
    a("(* R_core_to_surf = 0.038 K/W, R_surf_to_coolant = 0.022 K/W (mass flow dependent) *)")
    a("rCoreToSurfHeatFlow_W := (rBattCoreTemp_Est - rBattSurfTemp_Est) / 0.038;")
    a("rSurfToCoolantHeatFlow_W := (rBattSurfTemp_Est - rBattCoolantInletTemp_degC) / (0.012 + (0.010 / MAX(0.2, rBattCoolantFlow_kg_s)));")
    a("")
    a("(* Discrete Euler thermal integration *)")
    a("rBattCoreTemp_Est := rBattCoreTemp_Est + (rDeltaT * ((rJouleHeatPower_W - rCoreToSurfHeatFlow_W) / 12500.0));")
    a("rBattSurfTemp_Est := rBattSurfTemp_Est + (rDeltaT * ((rCoreToSurfHeatFlow_W - rSurfToCoolantHeatFlow_W) / 6800.0));")
    a("rBattEstimatedCoreTemp_degC := rBattCoreTemp_Est;")
    a("rBattThermalReserveHeadroom_degC := 65.0 - rBattCoreTemp_Est; (* 65 deg C trip boundary *)")
    a("")
    a("(* Dynamic Thermal Current Cap *)")
    a("IF rBattThermalReserveHeadroom_degC > 0.5 THEN")
    a("    rThermalCurrentCap_A := SQRT((rBattThermalReserveHeadroom_degC * (12500.0 / 8.0) + rCoreToSurfHeatFlow_W) / MAX(0.005, rBattInternalResistance));")
    a("ELSE")
    a("    rThermalCurrentCap_A := 450.0; (* Severe thermal clamp *)")
    a("END_IF;")
    a("IF rThermalCurrentCap_A > 2600.0 THEN rThermalCurrentCap_A := 2600.0; END_IF;")
    a("")
    a("(* Terminal Voltage Sag Cap: minimum pack cut-off = 640.0 V (3.2 V/cell floor) *)")
    a("rVoltageSagCurrentCap_A := MAX(100.0, (rVoted_BattVoltage_V - 640.0) / MAX(0.008, rBattInternalResistance));")
    a("IF rVoltageSagCurrentCap_A > 2600.0 THEN rVoltageSagCurrentCap_A := 2600.0; END_IF;")
    a("")
    a("(* Overall Allowable Current Arbitrator with Rate Limiting *)")
    a("rAllowableCurrent_Ramped_A := MIN(rThermalCurrentCap_A, rVoltageSagCurrentCap_A);")
    a("rBattAllowableMaxCurrent_A := rAllowableCurrent_Ramped_A;")
    a("")
    a("(* Active Thermal Throttling Derate Factor *)")
    a("IF rBattEstimatedCoreTemp_degC >= 55.0 THEN")
    a("    bBattThermalThrottlingActive := TRUE;")
    a("    rThermalDerateThrustFactor := MAX(0.45, 1.0 - ((rBattEstimatedCoreTemp_degC - 55.0) / 10.0) * 0.55);")
    a("    dwFaultAlarmWord := dwFaultAlarmWord OR 16#0000_0040; (* Bit 6: Batt Thermal Throttling *)")
    a("ELSE")
    a("    bBattThermalThrottlingActive := FALSE;")
    a("    rThermalDerateThrustFactor := 1.0;")
    a("    dwFaultAlarmWord := dwFaultAlarmWord AND 16#FFFF_FFBF;")
    a("END_IF;")
    a("")
    a("IF rVoted_BattVoltage_V < 660.0 THEN")
    a("    bBattEmergencyVoltageSag := TRUE;")
    a("    dwFaultAlarmWord := dwFaultAlarmWord OR 16#0000_0080; (* Bit 7: Bus Voltage Sag Warning *)")
    a("ELSE")
    a("    bBattEmergencyVoltageSag := FALSE;")
    a("    dwFaultAlarmWord := dwFaultAlarmWord AND 16#FFFF_FF7F;")
    a("END_IF;")
    a("")

    # SECTION 5: State-Space MPC Optimization
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* SECTION 5: STATE-SPACE AIRCRAFT DYNAMICS & DISCRETE MPC QUADRATIC COST OPTIMIZATION       *)")
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* Update State Vector x = [u, w, theta, q, beta, betadot, f_sep, T_core]^T *)")
    a("vecX[1] := (rVoted_Airspeed_kmh / 3.6) * rCosBeta;")
    a("vecX[2] := (rVoted_Airspeed_kmh / 3.6) * rSinBeta;")
    a("vecX[3] := rVoted_PitchAngle_deg * 0.01745329;")
    a("vecX[4] := rVoted_PitchRate_degs * 0.01745329;")
    a("vecX[5] := rBetaRad;")
    a("vecX[6] := rTiltActualRate_degs * 0.01745329;")
    a("vecX[7] := rSeparation_Point_f;")
    a("vecX[8] := rBattCoreTemp_Est;")
    a("")
    a("(* Dynamic Reference State Trajectory vecRef *)")
    a("vecRef[1] := (rTargetAirspeed_kmh / 3.6) * rCosBeta;")
    a("vecRef[2] := -1.0 * rTargetClimbRate_m_s;")
    a("vecRef[3] := 0.0; (* Level deck floor target *)")
    a("vecRef[4] := 0.0;")
    a("vecRef[5] := rBetaRad;")
    a("vecRef[6] := 0.0;")
    a("vecRef[7] := 1.0; (* Desire fully attached flow *)")
    a("vecRef[8] := 35.0; (* Optimal thermal operating target *)")
    a("")
    a("(* State penalty weights Q_diag *)")
    a("matQ_diag[1] := 1.5;   (* Speed tracking *)")
    a("matQ_diag[2] := 2.5;   (* Vertical flight path tracking *)")
    a("matQ_diag[3] := 8.0;   (* Cabin pitch leveling *)")
    a("matQ_diag[4] := 4.0;   (* Pitch rate damping *)")
    a("matQ_diag[5] := 3.0;   (* Tilt angle schedule tracking *)")
    a("matQ_diag[6] := 1.0;   (* Tilt slew damping *)")
    a("matQ_diag[7] := 15.0;  (* Strong stall prevention weight *)")
    a("matQ_diag[8] := 0.8;   (* Battery thermal weight *)")
    a("")
    a("(* Control effort penalty weights R_diag and rate weights R_delta *)")
    a("matR_diag[1] := 0.00002; (* Collective thrust *)")
    a("matR_diag[2] := 0.00010; (* Pitch differential moment *)")
    a("matR_diag[3] := 0.00010; (* Roll differential moment *)")
    a("matR_diag[4] := 0.00015; (* Yaw differential moment *)")
    a("matR_diag[5] := 0.02500; (* Tilt actuator slew effort *)")
    a("matR_diag[6] := 0.01500; (* Flap deflection effort *)")
    a("")
    a("matR_delta[1] := 0.00005;")
    a("matR_delta[2] := 0.00020;")
    a("matR_delta[3] := 0.00020;")
    a("matR_delta[4] := 0.00030;")
    a("matR_delta[5] := 0.05000;")
    a("matR_delta[6] := 0.03000;")
    a("")
    a("(* State matrix A_d(beta) schedule interpolation between hover (90 deg) and cruise (0 deg) *)")
    a("FOR i := 1 TO 8 DO")
    a("    FOR j := 1 TO 8 DO")
    a("        IF i = j THEN matA[i, j] := 1.0; ELSE matA[i, j] := 0.0; END_IF;")
    a("    END_FOR;")
    a("END_FOR;")
    a("matA[1, 1] := 0.985 - (0.015 * rCosBeta);")
    a("matA[1, 3] := -9.81 * rDeltaT * rCosBeta;")
    a("matA[2, 2] := 0.970 - (0.020 * rCosBeta);")
    a("matA[2, 3] := -9.81 * rDeltaT * rSinBeta;")
    a("matA[3, 3] := 1.000;")
    a("matA[3, 4] := rDeltaT;")
    a("matA[4, 4] := 0.960 - (0.040 * rCosBeta);")
    a("matA[5, 5] := 1.000;")
    a("matA[5, 6] := rDeltaT;")
    a("matA[6, 6] := 0.920;")
    a("matA[7, 7] := 0.950;")
    a("matA[8, 8] := 0.998;")
    a("")
    a("(* Control matrix B_d(beta) schedule *)")
    a("FOR i := 1 TO 8 DO")
    a("    FOR j := 1 TO 6 DO matB[i, j] := 0.0; END_FOR;")
    a("END_FOR;")
    a("matB[1, 1] := (rDeltaT / 5500.0) * rCosBeta;")
    a("matB[2, 1] := -(rDeltaT / 5500.0) * rSinBeta;")
    a("matB[4, 2] := (rDeltaT / 32000.0); (* I_yy pitch inertia *)")
    a("matB[6, 5] := rDeltaT * 12.5;     (* Tilt drive response *)")
    a("matB[7, 6] := 0.025 * rCosBeta;   (* Flap separation suppression *)")
    a("matB[8, 1] := 0.00000085 * (rVoted_BattCurrent_A / 1000.0);")
    a("")
    a("(* Control bounds vecU_min, vecU_max, vecDeltaU_max *)")
    a("vecU_min[1] := 8000.0;  vecU_max[1] := 72000.0 * rThermalDerateThrustFactor; vecDeltaU_max[1] := 4500.0;")
    a("vecU_min[2] := -15000.0; vecU_max[2] := 15000.0; vecDeltaU_max[2] := 2500.0;")
    a("vecU_min[3] := -12000.0; vecU_max[3] := 12000.0; vecDeltaU_max[3] := 2000.0;")
    a("vecU_min[4] := -8000.0;  vecU_max[4] := 8000.0;  vecDeltaU_max[4] := 1500.0;")
    a("vecU_min[5] := -0.15;   vecU_max[5] := 0.15;    vecDeltaU_max[5] := 0.035;")
    a("vecU_min[6] := 0.0;     vecU_max[6] := 0.698;   vecDeltaU_max[6] := 0.087;")
    a("")
    a("(* Projected Gradient Active-Set MPC Solver: 3 Iterations Per Scan *)")
    a("FOR iter := 1 TO 3 DO")
    a("    (* Compute predicted state vecX_hat = matA * vecX + matB * vecU *)")
    a("    FOR i := 1 TO 8 DO")
    a("        rTempSum := 0.0;")
    a("        FOR j := 1 TO 8 DO rTempSum := rTempSum + (matA[i, j] * vecX[j]); END_FOR;")
    a("        FOR j := 1 TO 6 DO rTempSum := rTempSum + (matB[i, j] * vecU[j]); END_FOR;")
    a("        vecX_hat[i] := rTempSum;")
    a("    END_FOR;")
    a("")
    a("    (* Analytical gradient calculation: grad = R*u + R_delta*(u - u_prev) + B^T * Q * (x_hat - x_ref) *)")
    a("    FOR j := 1 TO 6 DO")
    a("        rTempSum := (matR_diag[j] * vecU[j]) + (matR_delta[j] * (vecU[j] - vecU_prev[j]));")
    a("        FOR i := 1 TO 8 DO")
    a("            rTempSum := rTempSum + (matB[i, j] * matQ_diag[i] * (vecX_hat[i] - vecRef[i]));")
    a("        END_FOR;")
    a("        vecGradient[j] := rTempSum;")
    a("        (* Gradient descent step with box and rate projection *)")
    a("        vecU[j] := vecU[j] - (rStepSize * vecGradient[j]);")
    a("        IF vecU[j] > vecU_max[j] THEN vecU[j] := vecU_max[j]; END_IF;")
    a("        IF vecU[j] < vecU_min[j] THEN vecU[j] := vecU_min[j]; END_IF;")
    a("        IF (vecU[j] - vecU_prev[j]) > vecDeltaU_max[j] THEN vecU[j] := vecU_prev[j] + vecDeltaU_max[j]; END_IF;")
    a("        IF (vecU[j] - vecU_prev[j]) < -1.0 * vecDeltaU_max[j] THEN vecU[j] := vecU_prev[j] - vecDeltaU_max[j]; END_IF;")
    a("    END_FOR;")
    a("END_FOR;")
    a("")

    # SECTION 6: Pitch-Flap Synchronization
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* SECTION 6: AERODYNAMIC PITCH-FLAP SYNCHRONIZATION & CONVERSION GOVERNOR                   *)")
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* Fowler Flap deflection schedule synchronized with wing tilt angle beta *)")
    a("(* Flap extends up to 38 deg during mid-transition (beta 40 to 65 deg) to re-energize boundary layer *)")
    a("IF (rVoted_TiltAngle_deg >= 80.0) THEN")
    a("    rTargetFlap_deg := 0.0;")
    a("ELSIF (rVoted_TiltAngle_deg >= 35.0) AND (rVoted_TiltAngle_deg < 80.0) THEN")
    a("    rTargetFlap_deg := 38.0 * SIN((80.0 - rVoted_TiltAngle_deg) * 0.03490658);")
    a("ELSIF (rVoted_TiltAngle_deg > 5.0) AND (rVoted_TiltAngle_deg < 35.0) THEN")
    a("    rTargetFlap_deg := 38.0 * (rVoted_TiltAngle_deg / 35.0);")
    a("ELSE")
    a("    rTargetFlap_deg := 0.0; (* Flaps fully clean in cruise *)")
    a("END_IF;")
    a("")
    a("(* Synchronized fuselage deck attitude reference theta_ref to keep passenger floor level *)")
    a("IF (rVoted_TiltAngle_deg >= 75.0) THEN")
    a("    rTargetFuselagePitch_deg := 0.0;")
    a("ELSIF (rVoted_TiltAngle_deg >= 25.0) AND (rVoted_TiltAngle_deg < 75.0) THEN")
    a("    rTargetFuselagePitch_deg := 1.8 * SIN((75.0 - rVoted_TiltAngle_deg) * 0.0314159);")
    a("ELSE")
    a("    rTargetFuselagePitch_deg := 0.5; (* Nominal cruise deck pitch *)")
    a("END_IF;")
    a("")
    a("(* Apply actuator slew rate filtering on flap deflection *)")
    a("IF (rTargetFlap_deg - rFlapActuator_Cmd_deg) > (12.0 * rDeltaT) THEN")
    a("    rFlapActuator_Cmd_deg := rFlapActuator_Cmd_deg + (12.0 * rDeltaT);")
    a("ELSIF (rTargetFlap_deg - rFlapActuator_Cmd_deg) < (-12.0 * rDeltaT) THEN")
    a("    rFlapActuator_Cmd_deg := rFlapActuator_Cmd_deg - (12.0 * rDeltaT);")
    a("ELSE")
    a("    rFlapActuator_Cmd_deg := rTargetFlap_deg;")
    a("END_IF;")
    a("")

    # SECTION 7: 8-Propeller Vector Allocation
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* SECTION 7: 8-PROPELLER DISTRIBUTED ELECTRIC PROPULSION (DEP) VECTOR THRUST ALLOCATION     *)")
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* Motor Geometry Setup: Spanwise positions arrPropY_m [m] *)")
    a("arrPropY_m[1] := -6.2; arrPropY_m[2] := -4.5; arrPropY_m[3] := -2.8; arrPropY_m[4] := -1.1;")
    a("arrPropY_m[5] :=  1.1; arrPropY_m[6] :=  2.8; arrPropY_m[7] :=  4.5; arrPropY_m[8] :=  6.2;")
    a("FOR i := 1 TO 8 DO arrPropZ_m[i] := 0.22; END_FOR;")
    a("")
    a("(* Verify individual motor health flags and construct degradation weighting *)")
    a("arrPropHealthyMask[1] := bMotorHealthy_1; arrPropHealthyMask[2] := bMotorHealthy_2;")
    a("arrPropHealthyMask[3] := bMotorHealthy_3; arrPropHealthyMask[4] := bMotorHealthy_4;")
    a("arrPropHealthyMask[5] := bMotorHealthy_5; arrPropHealthyMask[6] := bMotorHealthy_6;")
    a("arrPropHealthyMask[7] := bMotorHealthy_7; arrPropHealthyMask[8] := bMotorHealthy_8;")
    a("")
    a("iHealthyMotorCount := 0;")
    a("FOR i := 1 TO 8 DO")
    a("    IF arrPropHealthyMask[i] THEN")
    a("        arrPropWeight[i] := 1.0;")
    a("        iHealthyMotorCount := iHealthyMotorCount + 1;")
    a("    ELSE")
    a("        arrPropWeight[i] := 0.0001; (* Zero allocation to failed unit *)")
    a("        bOEI_Latched := TRUE;")
    a("        iFailedMotorIndex := i;")
    a("    END_IF;")
    a("END_FOR;")
    a("")
    a("IF bOEI_Latched THEN")
    a("    dwDegradedModeWord := dwDegradedModeWord OR 16#0000_0100; (* Bit 8: OEI Degraded Mode *)")
    a("END_IF;")
    a("")
    a("(* Weighted Pseudo-Inverse Thrust Allocation: distribute Total Thrust, Pitch, Roll, Yaw *)")
    a("(* T_base = T_tot / HealthyCount *)")
    a("FOR i := 1 TO 8 DO")
    a("    IF arrPropHealthyMask[i] THEN")
    a("        (* Base thrust share + differential moments *)")
    a("        rTempSum := (vecU[1] / MAX(1.0, INT_TO_REAL(iHealthyMotorCount)))")
    a("                  + (vecU[2] * arrPropZ_m[i] * 0.05)")
    a("                  + (vecU[3] * arrPropY_m[i] * (0.045 / 6.2))")
    a("                  + (vecU[4] * arrPropY_m[i] * (0.025 / 6.2) * (1.0 - rSinBeta));")
    a("        arrPropThrust_N[i] := MAX(450.0, MIN(11500.0, rTempSum));")
    a("    ELSE")
    a("        arrPropThrust_N[i] := 0.0;")
    a("    END_IF;")
    a("END_FOR;")
    a("")
    a("(* Convert Allocated Thrust Commands to Motor RPM and Torque *)")
    a("(* Aerodynamic formula: T = k_T * rho * D^4 * (RPM / 60)^2 => RPM = 60 * SQRT(T / (k_T * rho * D^4)) *)")
    a("(* For D = 1.85 m, k_T = 0.095, rho = 1.225 => k_factor ~ 0.095 * 1.225 * 11.71 ~ 1.363 *)")
    a("FOR i := 1 TO 8 DO")
    a("    IF arrPropHealthyMask[i] AND (arrPropThrust_N[i] > 10.0) THEN")
    a("        arrPropRPM[i] := 60.0 * SQRT(arrPropThrust_N[i] / MAX(0.1, 1.363 * (rAirDensity_kg_m3 / 1.225)));")
    a("        IF arrPropRPM[i] < 450.0 THEN arrPropRPM[i] := 450.0; END_IF;")
    a("        IF arrPropRPM[i] > 2850.0 THEN arrPropRPM[i] := 2850.0; END_IF;")
    a("        arrPropTorque_Nm[i] := arrPropThrust_N[i] * 0.145;")
    a("    ELSE")
    a("        arrPropRPM[i] := 0.0;")
    a("        arrPropTorque_Nm[i] := 0.0;")
    a("    END_IF;")
    a("END_FOR;")
    a("")
    a("(* Assign outputs to 8 motors *)")
    a("rMotorSpeed_Cmd_RPM_1 := arrPropRPM[1]; rMotorTorque_Cmd_Nm_1 := arrPropTorque_Nm[1];")
    a("rMotorSpeed_Cmd_RPM_2 := arrPropRPM[2]; rMotorTorque_Cmd_Nm_2 := arrPropTorque_Nm[2];")
    a("rMotorSpeed_Cmd_RPM_3 := arrPropRPM[3]; rMotorTorque_Cmd_Nm_3 := arrPropTorque_Nm[3];")
    a("rMotorSpeed_Cmd_RPM_4 := arrPropRPM[4]; rMotorTorque_Cmd_Nm_4 := arrPropTorque_Nm[4];")
    a("rMotorSpeed_Cmd_RPM_5 := arrPropRPM[5]; rMotorTorque_Cmd_Nm_5 := arrPropTorque_Nm[5];")
    a("rMotorSpeed_Cmd_RPM_6 := arrPropRPM[6]; rMotorTorque_Cmd_Nm_6 := arrPropTorque_Nm[6];")
    a("rMotorSpeed_Cmd_RPM_7 := arrPropRPM[7]; rMotorTorque_Cmd_Nm_7 := arrPropTorque_Nm[7];")
    a("rMotorSpeed_Cmd_RPM_8 := arrPropRPM[8]; rMotorTorque_Cmd_Nm_8 := arrPropTorque_Nm[8];")
    a("")
    a("(* Total thrust synthesis *)")
    a("rTotalThrust_Cmd_N := 0.0;")
    a("FOR i := 1 TO 8 DO rTotalThrust_Cmd_N := rTotalThrust_Cmd_N + arrPropThrust_N[i]; END_FOR;")
    a("rThrustElevation_Cmd_deg := rVoted_TiltAngle_deg;")
    a("")
    a("(* Vertical and Wing Lift Shares *)")
    a("rVerticalPropThrust_N := rTotalThrust_Cmd_N * rSinBeta;")
    a("rWingAeroLift_N := rDynamicPressure_Pa * 28.5 * rTotal_Unsteady_CL; (* Wing area S = 28.5 m2 *)")
    a("rWingLiftFraction_pct := (rWingAeroLift_N / rAircraftWeight_N) * 100.0;")
    a("rPropThrustFraction_pct := (rVerticalPropThrust_N / rAircraftWeight_N) * 100.0;")
    a("")

    # SECTION 8: Multi-Stage State Machine
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* SECTION 8: MULTI-STAGE TRANSITION FINITE STATE MACHINE                                    *)")
    a("(* ----------------------------------------------------------------------------------------- *)")
    a("(* State change detection *)")
    a("IF (iTransitionState <> iTransitionPrevState) THEN")
    a("    bStateFirstScan := TRUE;")
    a("    rStateElapsedTime_s := 0.0;")
    a("    iTransitionPrevState := iTransitionState;")
    a("ELSE")
    a("    bStateFirstScan := FALSE;")
    a("    rStateElapsedTime_s := rStateElapsedTime_s + rDeltaT;")
    a("END_IF;")
    a("")
