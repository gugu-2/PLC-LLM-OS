# paintshop_builder/build_st_phases_4_to_6.py

def get_phases_4_to_6():
    lines = []

    # =========================================================================
    # PHASE 4: DETERMINISTIC 14-STAGE PRODUCTION FINITE STATE MACHINE (FSM)
    # =========================================================================
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 4: DETERMINISTIC 14-STAGE PRODUCTION FINITE STATE MACHINE (FSM)                              *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("")
    lines.append("(* State Elapsed Timer Clock & Transition One-Shot Logic *)")
    lines.append("IF nState = nStatePrev THEN")
    lines.append("    rStateTimer_s := rStateTimer_s + rTs_s;")
    lines.append("    bStateFirstCycle := FALSE;")
    lines.append("ELSE")
    lines.append("    rStateTimer_s := 0.0;")
    lines.append("    bStateFirstCycle := TRUE;")
    lines.append("    nStatePrev := nState;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Emergency Stop & Hard Safety Trip Interlock Override *)")
    lines.append("IF NOT bEmergencyStop OR bArcQuenchLatched OR (rAT_601_ExhaustVOC_LEL_pct >= rAT_Trip_HH_LEL_pct) THEN")
    lines.append("    nState := 13; (* Immediate Jump to Sub-5 ms Arc Quench & Emergency Safe Park *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("CASE nState OF")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 0: FSM_BOOT_IDLE - Safe Booth Idle Standby & Health Verification                           *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    0: (* FSM_BOOT_IDLE *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := FALSE;")
    lines.append("        bColorChangeActive := FALSE;")
    lines.append("        bTipWashActive := FALSE;")
    lines.append("        bPaintTriggerValve := FALSE;")
    lines.append("        bSolventFlushValve := FALSE;")
    lines.append("        bPushOutAirValve := FALSE;")
    lines.append("        bDumpWasteValve := FALSE;")
    lines.append("        bTipWashSolventValve := FALSE;")
    lines.append("        bTipWashAirDryValve := FALSE;")
    lines.append("        bSafetyGroundRelay := TRUE; (* Ground electrostatic cascade when idle *)")
    lines.append("        rTurbineBrakeAirCmd_pct := 0.0;")
    lines.append("")
    lines.append("        (* Idle Control Outputs *)")
    lines.append("        u_ctrl[1] := 0.0; (* Turbine drive air off *)")
    lines.append("        u_ctrl[2] := 0.0; (* High voltage off *)")
    lines.append("        u_ctrl[3] := 0.0; (* Dosing pump stopped *)")
    lines.append("        u_ctrl[4] := 0.50; (* Inner shaping air minimum purge *)")
    lines.append("        u_ctrl[5] := 0.50; (* Outer shaping air minimum purge *)")
    lines.append("        u_ctrl[6] := 35.0; (* Downdraft recirc damper idle low flow *)")
    lines.append("")
    lines.append("        (* State Transitions *)")
    lines.append("        IF bEnable AND NOT bMasterFault THEN")
    lines.append("            IF bBoothPrePurgeCmd AND NOT bPrePurgeDone THEN")
    lines.append("                nState := 1; (* Initiate Booth Pre-Purge *)")
    lines.append("            ELSIF bColorChangeReq THEN")
    lines.append("                nState := 4; (* Initiate Rapid Color Change *)")
    lines.append("            ELSIF bTipWashReq THEN")
    lines.append("                nState := 11; (* Initiate Bell Cup Tip Wash *)")
    lines.append("            ELSIF bPrePurgeDone AND bStartCycleCmd THEN")
    lines.append("                nState := 2; (* Lock Laminar Downdraft Air Balance *)")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 1: FSM_PREPURGE_VENTILATION - 4-Volume Air Exchange Fresh Cleanroom Purge                  *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    1: (* FSM_PREPURGE_VENTILATION *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := FALSE;")
    lines.append("        bBoothPurgeFanRun := TRUE;")
    lines.append("        bExhaustRtoFanRun := TRUE;")
    lines.append("        bSafetyGroundRelay := TRUE;")
    lines.append("        bPaintTriggerValve := FALSE;")
    lines.append("        bSolventFlushValve := FALSE;")
    lines.append("")
    lines.append("        (* Force VAV Dampers to 100% Full Fresh Air Purge *)")
    lines.append("        u_ctrl[1] := 0.0;")
    lines.append("        u_ctrl[2] := 0.0;")
    lines.append("        u_ctrl[3] := 0.0;")
    lines.append("        u_ctrl[4] := 0.50;")
    lines.append("        u_ctrl[5] := 0.50;")
    lines.append("        u_ctrl[6] := 100.0; (* Full draft exchange *)")
    lines.append("        rDowndraftDamperCmd_pct := 100.0;")
    lines.append("        rRtoPurgeDamperCmd_pct := 100.0;")
    lines.append("")
    lines.append("        (* Accumulate Pre-Purge Duration & Turnover Volume *)")
    lines.append("        rPurgeElapsedTimer_s := rPurgeElapsedTimer_s + rTs_s;")
    lines.append("        rAirVolumeAccumulator_m3 := rAirVolumeAccumulator_m3 + ((120000.0 / 3600.0) * rTs_s);")
    lines.append("")
    lines.append("        (* Complete Purge Criteria: Required time elapsed and VOC < 5% LEL *)")
    lines.append("        IF (rPurgeElapsedTimer_s >= rPurgeRequiredDuration_s) AND (rAT_601_ExhaustVOC_LEL_pct < 5.0) THEN")
    lines.append("            bPrePurgeDone := TRUE;")
    lines.append("            nState := 0; (* Return to Idle with Purge Certified *)")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 2: FSM_DOWNDRAFT_AIR_BALANCE_LOCK - Laminar Velocity Balancing (0.35 m/s +/- 0.02 m/s)     *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    2: (* FSM_DOWNDRAFT_AIR_BALANCE_LOCK *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bBoothPurgeFanRun := TRUE;")
    lines.append("        bExhaustRtoFanRun := TRUE;")
    lines.append("        bSafetyGroundRelay := TRUE;")
    lines.append("")
    lines.append("        (* Active Damper Regulation to Lock Plenum Delta-P at 12.5 Pa and Velocity at 0.35 m/s *)")
    lines.append("        u_ctrl[6] := MAX(15.0, MIN(95.0, 55.0 + ((rDowndraftPressSP_Pa - rVotedDowndraftPress_Pa) * 3.50)));")
    lines.append("        rDowndraftDamperCmd_pct := u_ctrl[6];")
    lines.append("")
    lines.append("        (* Stability Verification: Error within +/- 1.0 Pa and +/- 0.02 m/s for 2.0 s *)")
    lines.append("        IF (ABS(rVotedDowndraftPress_Pa - rDowndraftPressSP_Pa) <= 1.00) AND")
    lines.append("           (ABS(rVT_701_DowndraftVelocity_mps - rDowndraftVelocitySP_mps) <= 0.025) THEN")
    lines.append("            IF rStateTimer_s >= 2.00 THEN")
    lines.append("                nState := 3; (* Downdraft Balanced: Advance to HV Diagnostics *)")
    lines.append("            END_IF;")
    lines.append("        ELSE")
    lines.append("            (* Reset stability timer if draft surges *)")
    lines.append("            IF rStateTimer_s > 15.0 THEN")
    lines.append("                bWarningActive := TRUE; (* Air balance taking longer than expected *)")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 3: FSM_HV_CASCADE_DIAGNOSTICS - High-Voltage Bleed & Isolation Check                       *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    3: (* FSM_HV_CASCADE_DIAGNOSTICS *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("")
    lines.append("        (* Open Safety Ground Bleed Relay to permit test ionization *)")
    lines.append("        bSafetyGroundRelay := FALSE;")
    lines.append("")
    lines.append("        (* Sub-Cycle Step 1: Brief Test Voltage Pulse to -10 kV *)")
    lines.append("        IF rStateTimer_s < 0.60 THEN")
    lines.append("            u_ctrl[2] := 11.0; (* Approx -10 kV PWM command *)")
    lines.append("            rHighVoltageCmd_pct := u_ctrl[2];")
    lines.append("        ELSIF rStateTimer_s < 1.20 THEN")
    lines.append("            (* Step 2: Diagnostic Verification of Return Current & Voltage Level *)")
    lines.append("            IF (ABS(rVotedHighVoltage_kV) < 6.0) OR (rIT_202_HVCurrent_uA > 35.0) THEN")
    lines.append("                bMasterFault := TRUE; (* HV Cascade short-circuit or bleed leakage *)")
    lines.append("                nState := 13;")
    lines.append("            END_IF;")
    lines.append("            u_ctrl[2] := 0.0;")
    lines.append("            rHighVoltageCmd_pct := 0.0;")
    lines.append("        ELSE")
    lines.append("            (* Step 3: Bleed Verification and Advance *)")
    lines.append("            bSafetyGroundRelay := TRUE; (* Re-assert ground relay *)")
    lines.append("            IF ABS(rVotedHighVoltage_kV) < 1.0 THEN")
    lines.append("                IF bColorChangeReq THEN")
    lines.append("                    nState := 4; (* Divert to Color Change *)")
    lines.append("                ELSE")
    lines.append("                    nState := 6; (* Advance to Paint Line Fast Pre-Fill *)")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 4: FSM_COLOR_BLOCK_SOLVENT_FLUSH - Rapid Color-Change Valve Block Flush (< 12 s)          *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    4: (* FSM_COLOR_BLOCK_SOLVENT_FLUSH *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bColorChangeActive := TRUE;")
    lines.append("        bSafetyGroundRelay := TRUE;")
    lines.append("        u_ctrl[2] := 0.0; (* HV Disabled *)")
    lines.append("        rHighVoltageCmd_pct := 0.0;")
    lines.append("        rColorChangeCycleTime_s := rStateTimer_s;")
    lines.append("")
    lines.append("        (* Chop-Chop Micro-Sequencer Logic *)")
    lines.append("        IF bStateFirstCycle THEN")
    lines.append("            nChopSubPhase := 1; (* Begin with Solvent Pre-Purge *)")
    lines.append("            rChopTimer_s := 0.0;")
    lines.append("            nChopCyclesCount := 0;")
    lines.append("        ELSE")
    lines.append("            rChopTimer_s := rChopTimer_s + rTs_s;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("        CASE nChopSubPhase OF")
    lines.append("            1: (* Sub-Phase 1: Solvent Initial Flush (1.8 s) *)")
    lines.append("                bPaintTriggerValve := FALSE;")
    lines.append("                bSolventFlushValve := TRUE;")
    lines.append("                bPushOutAirValve := FALSE;")
    lines.append("                bDumpWasteValve := TRUE;")
    lines.append("                rSolventAccumulator_mL := rSolventAccumulator_mL + (350.0 * (rTs_s / 60.0));")
    lines.append("                rSolventVolPurged_mL := rSolventAccumulator_mL;")
    lines.append("                IF rChopTimer_s >= 1.80 THEN")
    lines.append("                    nChopSubPhase := 2;")
    lines.append("                    rChopTimer_s := 0.0;")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("            2: (* Sub-Phase 2: High-Velocity Air Push-Out (1.5 s) *)")
    lines.append("                bSolventFlushValve := FALSE;")
    lines.append("                bPushOutAirValve := TRUE;")
    lines.append("                bDumpWasteValve := TRUE;")
    lines.append("                IF rChopTimer_s >= 1.50 THEN")
    lines.append("                    nChopSubPhase := 3; (* Advance to Chop-Chop Alternating *)")
    lines.append("                    rChopTimer_s := 0.0;")
    lines.append("                    nChopCyclesCount := 0;")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("            3: (* Sub-Phase 3: Alternating Solvent/Air High-Shear Chop-Chop (4.0 s) *)")
    lines.append("                bDumpWasteValve := TRUE;")
    lines.append("                IF (rChopTimer_s < 0.25) THEN")
    lines.append("                    bSolventFlushValve := TRUE;")
    lines.append("                    bPushOutAirValve := FALSE;")
    lines.append("                    rSolventAccumulator_mL := rSolventAccumulator_mL + (280.0 * (rTs_s / 60.0));")
    lines.append("                    rSolventVolPurged_mL := rSolventAccumulator_mL;")
    lines.append("                ELSIF (rChopTimer_s < 0.50) THEN")
    lines.append("                    bSolventFlushValve := FALSE;")
    lines.append("                    bPushOutAirValve := TRUE;")
    lines.append("                ELSE")
    lines.append("                    rChopTimer_s := 0.0;")
    lines.append("                    nChopCyclesCount := nChopCyclesCount + 1;")
    lines.append("                    IF nChopCyclesCount >= nChopCyclesTarget THEN")
    lines.append("                        nChopSubPhase := 4;")
    lines.append("                    END_IF;")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("            4: (* Sub-Phase 4: Sequence Concluded *)")
    lines.append("                bSolventFlushValve := FALSE;")
    lines.append("                bPushOutAirValve := FALSE;")
    lines.append("                bDumpWasteValve := FALSE;")
    lines.append("                nState := 5; (* Advance to High Velocity Air Dry *)")
    lines.append("        END_CASE;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 5: FSM_HIGH_VELOCITY_AIR_DRY - High-Velocity Line Blow-Down & Scour                        *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    5: (* FSM_HIGH_VELOCITY_AIR_DRY *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bColorChangeActive := TRUE;")
    lines.append("        bSolventFlushValve := FALSE;")
    lines.append("        bPushOutAirValve := TRUE; (* Max air scouring *)")
    lines.append("        bDumpWasteValve := TRUE;")
    lines.append("        bPaintTriggerValve := FALSE;")
    lines.append("")
    lines.append("        (* Dry for 2.2 seconds to eliminate solvent pooling *)")
    lines.append("        IF rStateTimer_s >= 2.20 THEN")
    lines.append("            bPushOutAirValve := FALSE;")
    lines.append("            bDumpWasteValve := FALSE;")
    lines.append("            bColorChangeActive := FALSE;")
    lines.append("            nState := 6; (* Advance to Paint Fluid Line Fast Pre-Fill *)")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 6: FSM_PAINT_FLUID_FAST_PREFILL - Paint Line Fast Pre-Fill to Tip Valve                     *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    6: (* FSM_PAINT_FLUID_FAST_PREFILL *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bDumpWasteValve := TRUE; (* Divert initial paint interface to dump *)")
    lines.append("        bPaintTriggerValve := FALSE;")
    lines.append("")
    lines.append("        (* Micro-Gear Pump High-Speed Pre-Fill (140 rpm) *)")
    lines.append("        u_ctrl[3] := 140.0;")
    lines.append("        rGearPumpSpeedCmd_rpm := u_ctrl[3];")
    lines.append("")
    lines.append("        (* Check Coriolis Meter flow rate and hydraulic line pressure rise *)")
    lines.append("        IF (rVotedPaintFlow_mlpm > 180.0) AND (rPT_302_PaintLinePress_bar >= 3.20) THEN")
    lines.append("            IF rStateTimer_s >= 1.50 THEN")
    lines.append("                bDumpWasteValve := FALSE; (* Line primed right to trigger needle *)")
    lines.append("                u_ctrl[3] := 0.0; (* Pause pump momentarily *)")
    lines.append("                rGearPumpSpeedCmd_rpm := 0.0;")
    lines.append("                nState := 7; (* Advance to Bell Turbine Ramp-Up *)")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 7: FSM_BELL_TURBINE_RAMPUP - Bell Turbine Soft-Start & Ramp to Operating Speed             *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    7: (* FSM_BELL_TURBINE_RAMPUP *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bSafetyGroundRelay := TRUE;")
    lines.append("        rTurbineBrakeAirCmd_pct := 0.0;")
    lines.append("")
    lines.append("        (* Ramp Drive Air Valve Command with MPC tracking *)")
    lines.append("        u_ctrl[1] := MIN(85.0, 15.0 + (rStateTimer_s * 18.0));")
    lines.append("        rTurbineDriveAirCmd_pct := u_ctrl[1];")
    lines.append("")
    lines.append("        (* Verify Turbine Speed reaches Setpoint within +/- 1500 rpm *)")
    lines.append("        IF ABS(rVotedTurbineSpeed_rpm - rTurbineSpeedSP_rpm) <= 1500.0 THEN")
    lines.append("            IF rStateTimer_s >= 2.50 THEN")
    lines.append("                nState := 8; (* Advance to Electrostatic Charge Enable *)")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 8: FSM_HV_CHARGE_ENABLE - -90 kV Electrostatic Charge Soft Ramp & Corona Stabilization      *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    8: (* FSM_HV_CHARGE_ENABLE *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bSafetyGroundRelay := FALSE; (* Open safety ground discharge relay *)")
    lines.append("")
    lines.append("        (* Soft Ramp PWM Command to reach High Voltage Setpoint *)")
    lines.append("        u_ctrl[2] := MIN(ABS(rHighVoltageSP_kV), rStateTimer_s * 25.0);")
    lines.append("        rHighVoltageCmd_pct := u_ctrl[2];")
    lines.append("")
    lines.append("        (* Verify Voltage Target Reached & Current Plausible (< 180 uA) *)")
    lines.append("        IF (ABS(rVotedHighVoltage_kV - rHighVoltageSP_kV) <= 2.50) AND (rIT_202_HVCurrent_uA < 180.0) THEN")
    lines.append("            bSystemReady := TRUE;")
    lines.append("            (* Await Robot In-Position Trajectory Permissive *)")
    lines.append("            IF bRobotTriggerPermissive THEN")
    lines.append("                nState := 9; (* Launch Car Body Spray Application *)")
    lines.append("            END_IF;")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 9: FSM_CAR_BODY_ROBOT_SPRAY - Body-in-White Contouring Trajectory Active Spray              *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    9: (* FSM_CAR_BODY_ROBOT_SPRAY *)")
    lines.append("        bSystemReady := TRUE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bPaintTriggerValve := TRUE; (* Open Bell Tip Fluid Valve *)")
    lines.append("        bSafetyGroundRelay := FALSE;")
    lines.append("")
    lines.append("        (* Full Closed-Loop MPC Regulation Active Across All Actuators *)")
    lines.append("        rTurbineDriveAirCmd_pct := u_ctrl[1];")
    lines.append("        rHighVoltageCmd_pct := u_ctrl[2];")
    lines.append("        rGearPumpSpeedCmd_rpm := u_ctrl[3];")
    lines.append("        rInnerShapingAirCmd_bar := u_ctrl[4];")
    lines.append("        rOuterShapingAirCmd_bar := u_ctrl[5];")
    lines.append("        rDowndraftDamperCmd_pct := u_ctrl[6];")
    lines.append("")
    lines.append("        (* Branch to Edge Wrap / Recess Compensation if Robot enters Body Cavity *)")
    lines.append("        IF bEdgeWrapCompensationEnable AND bRecessZoneActive THEN")
    lines.append("            nState := 10; (* Edge Wrap Compensation *)")
    lines.append("        ELSIF bStopCycleCmd OR NOT bRobotTriggerPermissive THEN")
    lines.append("            bPaintTriggerValve := FALSE;")
    lines.append("            bCycleComplete := TRUE;")
    lines.append("            nState := 11; (* Proceed to Bell Cup Tip Wash *)")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 10: FSM_EDGE_WRAP_RECESS_COMPENSATION - Dynamic Shaping Air & Faraday Cage Recess Shaping  *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    10: (* FSM_EDGE_WRAP_RECESS_COMPENSATION *)")
    lines.append("        bSystemReady := TRUE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bPaintTriggerValve := TRUE;")
    lines.append("        bSafetyGroundRelay := FALSE;")
    lines.append("")
    lines.append("        (* Deploy Adjusted Control Profile to Overcome Faraday Repulsion *)")
    lines.append("        rTurbineDriveAirCmd_pct := u_ctrl[1];")
    lines.append("        rHighVoltageCmd_pct := u_ctrl[2] * 0.820; (* Lower voltage in deep cavity *)")
    lines.append("        rGearPumpSpeedCmd_rpm := u_ctrl[3];")
    lines.append("        rInnerShapingAirCmd_bar := u_ctrl[4] * 0.800;")
    lines.append("        rOuterShapingAirCmd_bar := u_ctrl[5] * 1.350; (* Widen spray envelope *)")
    lines.append("        rDowndraftDamperCmd_pct := u_ctrl[6];")
    lines.append("")
    lines.append("        (* Return to Standard Trajectory once Robot Exits Body Cavity *)")
    lines.append("        IF NOT bRecessZoneActive THEN")
    lines.append("            nState := 9; (* Return to Standard Spray *)")
    lines.append("        ELSIF bStopCycleCmd OR NOT bRobotTriggerPermissive THEN")
    lines.append("            bPaintTriggerValve := FALSE;")
    lines.append("            bCycleComplete := TRUE;")
    lines.append("            nState := 11; (* Proceed to Tip Wash *)")
    lines.append("        END_IF;")
    lines.append("")

    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    (* STAGE 11: FSM_BELL_CUP_TIP_WASH - Atomizer Bell Cup Rim Solvent Wash & Spin Dry                  *)")
    lines.append("    (* ------------------------------------------------------------------------------------------------ *)")
    lines.append("    11: (* FSM_BELL_CUP_TIP_WASH *)")
    lines.append("        bSystemReady := FALSE;")
    lines.append("        bCycleActive := TRUE;")
    lines.append("        bTipWashActive := TRUE;")
    lines.append("        bPaintTriggerValve := FALSE;")
    lines.append("        bSafetyGroundRelay := TRUE; (* Safety ground during tip wash *)")
    lines.append("        u_ctrl[2] := 0.0; (* HV Disabled *)")
    lines.append("        rHighVoltageCmd_pct := 0.0;")
    lines.append("        u_ctrl[3] := 0.0; (* Paint pump stopped *)")
    lines.append("        rGearPumpSpeedCmd_rpm := 0.0;")
    lines.append("")
    lines.append("        IF bStateFirstCycle THEN")
    lines.append("            nTipWashSubPhase := 1;")
    lines.append("            rTipWashTimer_s := 0.0;")
    lines.append("        ELSE")
    lines.append("            rTipWashTimer_s := rTipWashTimer_s + rTs_s;")
    lines.append("        END_IF;")
    lines.append("")
    lines.append("        CASE nTipWashSubPhase OF")
    lines.append("            1: (* Sub-Phase 1: Spin down to 40,000 rpm & Solvent Needle Jet Spray (1.2 s) *)")
    lines.append("                u_ctrl[1] := 35.0; (* Decelerate bell to moderate speed *)")
    lines.append("                rTurbineDriveAirCmd_pct := u_ctrl[1];")
    lines.append("                bTipWashSolventValve := TRUE;")
    lines.append("                bTipWashAirDryValve := FALSE;")
    lines.append("                IF rTipWashTimer_s >= 1.20 THEN")
    lines.append("                    nTipWashSubPhase := 2;")
    lines.append("                    rTipWashTimer_s := 0.0;")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("            2: (* Sub-Phase 2: High-Velocity Air Knife & 55,000 rpm Centrifugal Spin Dry (1.5 s) *)")
    lines.append("                u_ctrl[1] := 65.0; (* Accelerate for spin-off *)")
    lines.append("                rTurbineDriveAirCmd_pct := u_ctrl[1];")
    lines.append("                bTipWashSolventValve := FALSE;")
    lines.append("                bTipWashAirDryValve := TRUE;")
    lines.append("                IF rTipWashTimer_s >= 1.50 THEN")
    lines.append("                    bTipWashAirDryValve := FALSE;")
    lines.append("                    bTipWashActive := FALSE;")
