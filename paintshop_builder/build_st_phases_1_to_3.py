    lines.append("        rPT_TmrC_s := MAX(0.0, rPT_TmrC_s - (rTs_s * 0.50));")
    lines.append("    END_IF;")
    lines.append("ELSIF bPT_ChA_Healthy AND bPT_ChB_Healthy THEN")
    lines.append("    nPT_DegradedMode := 2;")
    lines.append("    rVotedDowndraftPress_Pa := (rPT_ChA_Press_Pa + rPT_ChB_Press_Pa) * 0.50;")
    lines.append("ELSIF bPT_ChA_Healthy AND bPT_ChC_Healthy THEN")
    lines.append("    nPT_DegradedMode := 2;")
    lines.append("    rVotedDowndraftPress_Pa := (rPT_ChA_Press_Pa + rPT_ChC_Press_Pa) * 0.50;")
    lines.append("ELSIF bPT_ChB_Healthy AND bPT_ChC_Healthy THEN")
    lines.append("    nPT_DegradedMode := 2;")
    lines.append("    rVotedDowndraftPress_Pa := (rPT_ChB_Press_Pa + rPT_ChC_Press_Pa) * 0.50;")
    lines.append("ELSIF bPT_ChA_Healthy THEN")
    lines.append("    nPT_DegradedMode := 1;")
    lines.append("    rVotedDowndraftPress_Pa := rPT_ChA_Press_Pa;")
    lines.append("ELSIF bPT_ChB_Healthy THEN")
    lines.append("    nPT_DegradedMode := 1;")
    lines.append("    rVotedDowndraftPress_Pa := rPT_ChB_Press_Pa;")
    lines.append("ELSIF bPT_ChC_Healthy THEN")
    lines.append("    nPT_DegradedMode := 1;")
    lines.append("    rVotedDowndraftPress_Pa := rPT_ChC_Press_Pa;")
    lines.append("ELSE")
    lines.append("    nPT_DegradedMode := 0;")
    lines.append("    rVotedDowndraftPress_Pa := 0.0;")
    lines.append("    bMasterFault := TRUE;")
    lines.append("END_IF;")
    lines.append("")

    # =========================================================================
    # PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL STATE-SPACE ESTIMATION
    # =========================================================================
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL STATE-SPACE ESTIMATION & ATOMIZATION HYDRODYNAMICS       *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("")
    lines.append("(* 2.1 Update Validated Sensor Measurement Vector y_meas (6x1) *)")
    lines.append("y_meas[1] := rVotedTurbineSpeed_rpm;")
    lines.append("y_meas[2] := rVotedHighVoltage_kV;")
    lines.append("y_meas[3] := rVotedPaintFlow_mlpm;")
    lines.append("y_meas[4] := rInnerShapingAirCmd_bar; (* Pneumatic regulator manifold feedback *)")
    lines.append("y_meas[5] := rOuterShapingAirCmd_bar; (* Pneumatic regulator manifold feedback *)")
    lines.append("y_meas[6] := rVotedDowndraftPress_Pa;")
    lines.append("")
    lines.append("(* 2.2 Update Real-Time Physical Disturbances Vector w_dist (3x1) *)")
    lines.append("w_dist[1] := rRobotTCPVelocity_mps * 1.850; (* Centrifugal fluid inertia during robot contouring *)")
    lines.append("w_dist[2] := (rPaintViscosity_mPas - 80.0) * 0.0125; (* Viscosity variance from nominal 80 mPa.s *)")
    lines.append("w_dist[3] := (rVT_701_DowndraftVelocity_mps - 0.350) * 2.80; (* Downdraft velocity disturbance *)")
    lines.append("")
    lines.append("(* 2.3 Compute Output Estimation y_est = C*x_pred + D*u_ctrl and Measurement Innovation Residual e_innov *)")
    lines.append("FOR i_idx := 1 TO 6 DO")
    lines.append("    rSum := 0.0;")
    lines.append("    FOR j_idx := 1 TO 8 DO")
    lines.append("        rSum := rSum + (C_mat[i_idx, j_idx] * x_pred[j_idx]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j_idx := 1 TO 6 DO")
    lines.append("        rSum := rSum + (D_mat[i_idx, j_idx] * u_ctrl[j_idx]);")
    lines.append("    END_FOR;")
    lines.append("    y_est[i_idx] := rSum;")
    lines.append("    e_innov[i_idx] := y_meas[i_idx] - y_est[i_idx];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 2.4 A Posteriori Kalman State Correction: x_hat = x_pred + K_obs * e_innov *)")
    lines.append("FOR i_idx := 1 TO 8 DO")
    lines.append("    rSum := 0.0;")
    lines.append("    FOR j_idx := 1 TO 6 DO")
    lines.append("        rSum := rSum + (K_obs[i_idx, j_idx] * e_innov[j_idx]);")
    lines.append("    END_FOR;")
    lines.append("    x_hat[i_idx] := x_pred[i_idx] + rSum;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 2.5 A Priori State Projection for Next Discrete Cycle: x_pred[k+1] = A*x_hat[k] + B*u[k] + E_w*w[k] *)")
    lines.append("FOR i_idx := 1 TO 8 DO")
    lines.append("    rSum := 0.0;")
    lines.append("    FOR j_idx := 1 TO 8 DO")
    lines.append("        rSum := rSum + (A[i_idx, j_idx] * x_hat[j_idx]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j_idx := 1 TO 6 DO")
    lines.append("        rSum := rSum + (B[i_idx, j_idx] * u_ctrl[j_idx]);")
    lines.append("    END_FOR;")
    lines.append("    FOR j_idx := 1 TO 3 DO")
    lines.append("        rSum := rSum + (E_w[i_idx, j_idx] * w_dist[j_idx]);")
    lines.append("    END_FOR;")
    lines.append("    x_pred[i_idx] := rSum;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 2.6 Cyber-Physical Hydrodynamic Atomization & Electrostatic Coupling Equations *)")
    lines.append("(* 2.6.1 Bell Cup Rim Velocity: v_rim = omega * R_bell (R_bell = 0.0325 m for 65 mm serrated bell cup) *)")
    lines.append("rWork1 := (rVotedTurbineSpeed_rpm * 6.2831853) / 60.0; (* Angular velocity omega [rad/s] *)")
    lines.append("rWork2 := rWork1 * 0.0325; (* Rim tip linear velocity [m/s] *)")
    lines.append("")
    lines.append("(* 2.6.2 Aerodynamic Weber Number for Ligament Breakup: We = (rho * v_rim^2 * d_ligament) / sigma *)")
    lines.append("(* Surface tension sigma assumed 0.028 N/m for automotive solvent-borne clearcoat *)")
    lines.append("IF rPaintDensity_kgpm3 > 100.0 THEN")
    lines.append("    rDropletWeberNumber := (rPaintDensity_kgpm3 * (rWork2 * rWork2) * 0.000150) / 0.0280;")
    lines.append("ELSE")
    lines.append("    rDropletWeberNumber := 500.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.6.3 Droplet Sauter Mean Diameter D32 [um] (Modified Lefebvre/Tanasawa-Tesima Equation) *)")
    lines.append("(* D32 decreases with higher turbine speed, increases with flow rate and viscosity *)")
    lines.append("IF rVotedTurbineSpeed_rpm > 5000.0 THEN")
    lines.append("    rDropletSauterDia_um := 185.0 * EXP(-0.0000350 * rVotedTurbineSpeed_rpm) +")
    lines.append("                            (0.0450 * rVotedPaintFlow_mlpm) +")
    lines.append("                            (0.0800 * (rPaintViscosity_mPas - 60.0));")
    lines.append("    rDropletSauterDia_um := MAX(12.0, MIN(65.0, rDropletSauterDia_um));")
    lines.append("ELSE")
    lines.append("    rDropletSauterDia_um := 85.0; (* Poor atomization / coarse ligament regime *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.6.4 Electrostatic Electric Field Strength & Space Charge Gradient: E = |V| / d_standoff [kV/m] *)")
    lines.append("IF rRobotTCPDistance_mm > 50.0 THEN")
    lines.append("    rElectricFieldStrength_kV_per_m := (ABS(rVotedHighVoltage_kV) * 1000.0) / rRobotTCPDistance_mm;")
    lines.append("ELSE")
    lines.append("    rElectricFieldStrength_kV_per_m := 100.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.6.5 Specific Charge-to-Mass Ratio [mC/kg]: q/m = f(V_bell, Flow, Resistivity) *)")
    lines.append("IF rVotedPaintFlow_mlpm > 10.0 AND rPaintDensity_kgpm3 > 500.0 THEN")
    lines.append("    rChargeToMassRatio_C_per_kg := (ABS(rIT_202_HVCurrent_uA) * 0.000060) /")
    lines.append("                                   ((rVotedPaintFlow_mlpm * rPaintDensity_kgpm3) / 60000.0);")
    lines.append("ELSE")
    lines.append("    rChargeToMassRatio_C_per_kg := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.6.6 Real-Time Electrostatic Transfer Efficiency [%] *)")
    lines.append("(* Baseline mechanical transfer: 45%; Electrostatic boost: up to +42%; Downdraft penalty if draft deviates *)")
    lines.append("rWork3 := 45.0 + (ABS(rVotedHighVoltage_kV) * 0.460);")
    lines.append("(* Subtract velocity shear penalty if downdraft air velocity deviates from 0.35 m/s *)")
    lines.append("rWork4 := ABS(rVT_701_DowndraftVelocity_mps - 0.350) * 45.0;")
    lines.append("rTransferEfficiency_pct := MAX(30.0, MIN(92.0, rWork3 - rWork4));")
    lines.append("")
    lines.append("(* 2.6.7 Hydrodynamic Spray Pattern Fan Width at Substrate [mm] *)")
    lines.append("(* Pattern width expands with outer shaping air and bell speed, narrows with inner shaping air *)")
    lines.append("rSprayFanWidth_mm := 160.0 + (rOuterShapingAirCmd_bar * 42.0) -")
    lines.append("                     (rInnerShapingAirCmd_bar * 35.0) +")
    lines.append("                     (rRobotTCPDistance_mm * 0.450);")
    lines.append("rSprayFanWidth_mm := MAX(100.0, MIN(450.0, rSprayFanWidth_mm));")
    lines.append("")
    lines.append("(* 2.6.8 Real-Time Dry Film Thickness (DFT) Dynamic Estimator [um] *)")
    lines.append("(* DFT = (TransferEff * PaintFlow * SolidsFraction) / (RobotTCPVelocity * SprayFanWidth) *)")
    lines.append("IF rRobotTCPVelocity_mps > 0.05 AND rSprayFanWidth_mm > 50.0 AND bPaintTriggerValve THEN")
    lines.append("    rDryFilmThickness_um := ((rTransferEfficiency_pct * 0.010) *")
    lines.append("                             (rVotedPaintFlow_mlpm / 60.0) *")
    lines.append("                             (rPaintSolidsContent_pct * 0.010) * 1000.0) /")
    lines.append("                            (rRobotTCPVelocity_mps * (rSprayFanWidth_mm * 0.0010));")
    lines.append("    rEstimatedDFT_um := MAX(0.0, MIN(120.0, rDryFilmThickness_um));")
    lines.append("ELSE")
    lines.append("    rDryFilmThickness_um := 0.0;")
    lines.append("    rEstimatedDFT_um := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.6.9 Exhaust Solvent VOC Mass Flow Rate to RTO [g/min] *)")
    lines.append("(* Non-deposited overspray + evaporated carrier solvent *)")
    lines.append("IF bPaintTriggerValve AND rVotedPaintFlow_mlpm > 5.0 THEN")
    lines.append("    rVOCMassRate_g_per_s := ((rVotedPaintFlow_mlpm / 60.0) * (rPaintDensity_kgpm3 * 0.0010)) *")
    lines.append("                            ((1.0 - (rPaintSolidsContent_pct * 0.010)) +")
    lines.append("                             ((1.0 - (rTransferEfficiency_pct * 0.010)) * (rPaintSolidsContent_pct * 0.010)));")
    lines.append("    rVOCExhaustRate_gpm := rVOCMassRate_g_per_s * 60.0;")
    lines.append("ELSE")
    lines.append("    rVOCMassRate_g_per_s := 0.0;")
    lines.append("    rVOCExhaustRate_gpm := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.6.10 Paint Mass & Purge Totalizers *)")
    lines.append("IF bPaintTriggerValve THEN")
    lines.append("    rPaintAccumulator_g := rPaintAccumulator_g +")
    lines.append("                           ((rVotedPaintFlow_mlpm / 60.0) * (rPaintDensity_kgpm3 * 0.0010) * rTs_s);")
    lines.append("    rPaintMassDelivered_g := rPaintAccumulator_g;")
    lines.append("END_IF;")
    lines.append("")

    # =========================================================================
    # PHASE 3: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) WITH PGD
    # =========================================================================
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 3: RECEDING-HORIZON MODEL PREDICTIVE CONTROL (MPC) WITH PROJECTED GRADIENT DESCENT           *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("")
    lines.append("(* 3.1 Establish Dynamic Reference Targets r_ref (8x1) *)")
    lines.append("r_ref[1] := rTurbineSpeedSP_rpm;")
    lines.append("r_ref[2] := rHighVoltageSP_kV;")
    lines.append("r_ref[3] := 4.50; (* Nominal clearcoat line pressure [bar] *)")
    lines.append("r_ref[4] := rPaintFlowSP_mlpm;")
    lines.append("r_ref[5] := rInnerShapingAirSP_bar;")
    lines.append("r_ref[6] := rOuterShapingAirSP_bar;")
    lines.append("r_ref[7] := rDowndraftPressSP_Pa;")
    lines.append("r_ref[8] := 15.0; (* Target safe exhaust VOC flammability ceiling [%LEL] *)")
    lines.append("")
    lines.append("(* If Edge Wrap Compensation is active, dynamically widen spray pattern and adjust setpoints *)")
    lines.append("IF bEdgeWrapCompensationEnable AND bRecessZoneActive THEN")
    lines.append("    r_ref[5] := rInnerShapingAirSP_bar * 0.750; (* Relax inner shaping air to soften center core *)")
    lines.append("    r_ref[6] := rOuterShapingAirSP_bar * 1.350; (* Boost outer shaping air for edge wraparound *)")
    lines.append("    r_ref[2] := rHighVoltageSP_kV * 0.800;      (* De-rate electrostatic voltage to combat Faraday cage effect *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 3.2 Initialize Horizon State Prediction Trajectory at Step 0: x_traj[0] = x_hat *)")
    lines.append("FOR i_idx := 1 TO 8 DO")
    lines.append("    x_traj[0, i_idx] := x_hat[i_idx];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Warm-Start Control Trajectory with Previous Solution shifted by one step *)")
    lines.append("FOR tau_step := 0 TO 3 DO")
    lines.append("    FOR j_idx := 1 TO 6 DO")
    lines.append("        u_traj[tau_step, j_idx] := u_traj[tau_step + 1, j_idx];")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("FOR j_idx := 1 TO 6 DO")
    lines.append("    u_traj[4, j_idx] := u_traj[3, j_idx];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 3.3 Unrolled Projected Gradient Descent (PGD) Multi-Iteration Optimization Loop *)")
    lines.append("FOR n_iter := 1 TO nMaxPgdIters DO")
    lines.append("    (* 3.3.1 Forward State Rollout Over Prediction Horizon N = 5 *)")
    lines.append("    FOR tau_step := 0 TO 4 DO")
    lines.append("        FOR i_idx := 1 TO 8 DO")
    lines.append("            rSum := 0.0;")
    lines.append("            FOR j_idx := 1 TO 8 DO")
    lines.append("                rSum := rSum + (A[i_idx, j_idx] * x_traj[tau_step, j_idx]);")
    lines.append("            END_FOR;")
    lines.append("            FOR j_idx := 1 TO 6 DO")
    lines.append("                rSum := rSum + (B[i_idx, j_idx] * u_traj[tau_step, j_idx]);")
    lines.append("            END_FOR;")
    lines.append("            x_traj[tau_step + 1, i_idx] := rSum;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* 3.3.2 Backward Adjoint Costate Backpropagation: lambda_N = P*(x_N - r) *)")
    lines.append("    FOR i_idx := 1 TO 8 DO")
    lines.append("        rSum := 0.0;")
    lines.append("        FOR j_idx := 1 TO 8 DO")
    lines.append("            rSum := rSum + (P_term[i_idx, j_idx] * (x_traj[5, j_idx] - r_ref[j_idx]));")
    lines.append("        END_FOR;")
    lines.append("        lambda_adj[5, i_idx] := rSum;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* Backward Recurrence: lambda_tau = A^T * lambda_{tau+1} + Q * (x_tau - r) *)")
    lines.append("    FOR tau_step := 4 TO 0 BY -1 DO")
    lines.append("        FOR i_idx := 1 TO 8 DO")
    lines.append("            rSum := 0.0;")
    lines.append("            FOR j_idx := 1 TO 8 DO")
    lines.append("                rSum := rSum + (A[j_idx, i_idx] * lambda_adj[tau_step + 1, j_idx]);")
    lines.append("            END_FOR;")
    lines.append("            rSum := rSum + (Q_cost[i_idx, i_idx] * (x_traj[tau_step, i_idx] - r_ref[i_idx]));")
    lines.append("            lambda_adj[tau_step, i_idx] := rSum;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* 3.3.3 Gradient Computation & Actuator Projection Across Horizon *)")
    lines.append("    rGradNorm := 0.0;")
    lines.append("    FOR tau_step := 0 TO 4 DO")
    lines.append("        FOR j_idx := 1 TO 6 DO")
    lines.append("            rSum := 0.0;")
    lines.append("            FOR i_idx := 1 TO 8 DO")
    lines.append("                rSum := rSum + (B[i_idx, j_idx] * lambda_adj[tau_step + 1, i_idx]);")
    lines.append("            END_FOR;")
    lines.append("            (* Add Control Effort Penalty: R * u *)")
    lines.append("            rSum := rSum + (R_cost[j_idx, j_idx] * u_traj[tau_step, j_idx]);")
    lines.append("            (* Add Slew Rate Penalty: S * (u - u_prev) *)")
    lines.append("            IF tau_step = 0 THEN")
    lines.append("                rSum := rSum + (S_slew[j_idx, j_idx] * (u_traj[0, j_idx] - u_prev[j_idx]));")
    lines.append("            ELSE")
    lines.append("                rSum := rSum + (S_slew[j_idx, j_idx] * (u_traj[tau_step, j_idx] - u_traj[tau_step - 1, j_idx]));")
    lines.append("            END_IF;")
    lines.append("            grad_u[tau_step, j_idx] := rSum;")
    lines.append("            rGradNorm := rGradNorm + (rSum * rSum);")
    lines.append("")
    lines.append("            (* Gradient Descent Step *)")
    lines.append("            rWork1 := u_traj[tau_step, j_idx] - (rAlpha_pgd * rSum);")
    lines.append("")
    lines.append("            (* Project onto Hard Physical Box Constraints [u_min, u_max] *)")
    lines.append("            rWork1 := MAX(u_min[j_idx], MIN(u_max[j_idx], rWork1));")
    lines.append("")
    lines.append("            (* Slew Rate Clamping *)")
    lines.append("            IF tau_step = 0 THEN")
    lines.append("                rSlewDelta := rWork1 - u_prev[j_idx];")
    lines.append("                rSlewDelta := MAX(-du_max[j_idx], MIN(du_max[j_idx], rSlewDelta));")
    lines.append("                u_traj[0, j_idx] := u_prev[j_idx] + rSlewDelta;")
    lines.append("            ELSE")
    lines.append("                rSlewDelta := rWork1 - u_traj[tau_step - 1, j_idx];")
    lines.append("                rSlewDelta := MAX(-du_max[j_idx], MIN(du_max[j_idx], rSlewDelta));")
    lines.append("                u_traj[tau_step, j_idx] := u_traj[tau_step - 1, j_idx] + rSlewDelta;")
    lines.append("            END_IF;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 3.4 Extract Optimal Control Command u_ctrl for Actuator Deployment *)")
    lines.append("FOR j_idx := 1 TO 6 DO")
    lines.append("    u_ctrl[j_idx] := u_traj[0, j_idx];")
    lines.append("END_FOR;")
    lines.append("")
    return "\n".join(lines)
