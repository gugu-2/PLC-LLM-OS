# lng_reliquefaction_builder/phase2_physics.py

def get_phase2():
    lines = []
    def emit(s=""):
        lines.append(s)

    emit("(* ================================================================================================================= *)")
    emit("(* === PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL STATE-SPACE ESTIMATION (x[k+1] = A*x[k] + B*u[k]) ===                *)")
    emit("(* ================================================================================================================= *)")
    emit("(* 8-State Marine Cryogenic Boil-Off Gas Re-Liquefaction Plant State-Space Observer & Polytropic Physics Engine     *)")
    emit("(* Luenberger / Kalman Innovation Observer with Real-Time Dynamic Decoupling & Marine Hull Hydrodynamics             *)")
    emit("")

    # --- 2.1 SENSOR MEASUREMENT DEVIATION VECTOR Y[k] ---
    emit("(* --- 2.1 PROCESS OUTPUT DEVIATION VECTOR y[k] FROM NOMINAL OPERATING BASES --- *)")
    emit("y_MeasuredSensors[1] := rVoted_TankUllagePres_Out - rNominal_UllagePres_Tank1;")
    emit("y_MeasuredSensors[2] := rCargoUllagePres_Tank4_In - rNominal_UllagePres_Tank4;")
    emit("y_MeasuredSensors[3] := rBOGStage2DischPres_In - rNominal_Stage2DischPres;")
    emit("y_MeasuredSensors[4] := rVoted_N2ExpTemp_Out - rNominal_N2ExpanderTemp;")
    emit("y_MeasuredSensors[5] := rColdBoxLNGOutTemp_In - rNominal_CondensateTemp;")
    emit("y_MeasuredSensors[6] := rVoted_CondensateFlow_Out - rNominal_CondensateFlow;")
    emit("")

    # --- 2.2 OBSERVER MODEL OUTPUT y_hat[k] = C * x[k] + D * u[k] ---
    emit("(* --- 2.2 OBSERVER ESTIMATED PHYSICAL OUTPUT y_hat[k] = C * x_StateEst[k] + D * u_ActuatorCurrent[k] --- *)")
    emit("FOR idxLoop := 1 TO 6 DO")
    emit("    rTempSum := 0.0;")
    emit("    FOR jdxLoop := 1 TO 8 DO")
    emit("        rTempSum := rTempSum + (matC[idxLoop, jdxLoop] * x_StateEst[jdxLoop]);")
    emit("    END_FOR;")
    emit("    FOR jdxLoop := 1 TO 6 DO")
    emit("        rTempSum := rTempSum + (matD[idxLoop, jdxLoop] * u_ActuatorCurrent[jdxLoop]);")
    emit("    END_FOR;")
    emit("    y_ModelOutput[idxLoop] := rTempSum;")
    emit("END_FOR;")
    emit("")

    # --- 2.3 INNOVATION RESIDUAL e[k] = y[k] - y_hat[k] ---
    emit("(* --- 2.3 KALMAN / LUENBERGER INNOVATION RESIDUAL e[k] = y_MeasuredSensors - y_ModelOutput --- *)")
    emit("FOR idxLoop := 1 TO 6 DO")
    emit("    innov_ObserverResidual[idxLoop] := y_MeasuredSensors[idxLoop] - y_ModelOutput[idxLoop];")
    emit("END_FOR;")
    emit("")

    # --- 2.4 A-PRIORI PREDICTED STATE PROPAGATION x_pred[k+1] = A * x[k] + B * u[k] ---
    emit("(* --- 2.4 STATE PROPAGATION x_pred[k+1] = matA * x_StateEst[k] + matB * u_ActuatorCurrent[k] --- *)")
    emit("FOR idxLoop := 1 TO 8 DO")
    emit("    rTempSum := 0.0;")
    emit("    FOR jdxLoop := 1 TO 8 DO")
    emit("        rTempSum := rTempSum + (matA[idxLoop, jdxLoop] * x_StateEst[jdxLoop]);")
    emit("    END_FOR;")
    emit("    FOR jdxLoop := 1 TO 6 DO")
    emit("        rTempSum := rTempSum + (matB[idxLoop, jdxLoop] * u_ActuatorCurrent[jdxLoop]);")
    emit("    END_FOR;")
    emit("    x_StatePred[idxLoop] := rTempSum;")
    emit("END_FOR;")
    emit("")

    # --- 2.5 A-POSTERIORI STATE ESTIMATE UPDATE x_hat[k+1] = x_pred + L * innov ---
    emit("(* --- 2.5 OBSERVER STATE CORRECTION x_StateEst[k+1] = x_StatePred[k+1] + matL * innov_ObserverResidual --- *)")
    emit("FOR idxLoop := 1 TO 8 DO")
    emit("    rTempSum := 0.0;")
    emit("    FOR jdxLoop := 1 TO 6 DO")
    emit("        rTempSum := rTempSum + (matL[idxLoop, jdxLoop] * innov_ObserverResidual[jdxLoop]);")
    emit("    END_FOR;")
    emit("    x_StateEst[idxLoop] := x_StatePred[idxLoop] + rTempSum;")
    emit("END_FOR;")
    emit("")

    # --- 2.6 MARINE HULL 6-DOF HYDRODYNAMIC MOTION & SLOSHING PRESSURE SURGE DAMPING ---
    emit("(* --- 2.6 MARINE HULL 6-DOF HYDRODYNAMICS & SLOSHING DYNAMIC ULLAGE PRESSURE PERTURBATION --- *)")
    emit("(* Infinite Impulse Response (IIR) Low-Pass Filter on Vessel Pitch and Roll Motions *)")
    emit("rHullPitchFilterMemory := (0.880 * rHullPitchFilterMemory) + (0.120 * rShipPitchAngle_In);")
    emit("rHullRollFilterMemory := (0.900 * rHullRollFilterMemory) + (0.100 * rShipRollAngle_In);")
    emit("")
    emit("(* Dynamic Sloshing Ullage Pressure Perturbation: Coupling of Pitch Oscillation, Roll Wave Action & Vertical Heave *)")
    emit("rDynamicSloshingDeltaPres := rSloshingWaveInertialGain *")
    emit("    (ABS(rShipPitchAngle_In - rHullPitchFilterMemory) + (0.750 * ABS(rShipRollAngle_In - rHullRollFilterMemory))) *")
    emit("    (1.000 + (0.150 * ABS(rShipHeaveAcc_In))) *")
    emit("    MAX(0.50, (rWaveSignificantHeight_In / 4.00));")
    emit("")
    emit("rSloshingPressurePeak_Out := rDynamicSloshingDeltaPres;")
    emit("")
    emit("(* Dynamic Boil-Off Rate Mass Generation Compensation Due to Sloshing Kinetic Energy Dissipation *)")
    emit("rDynamicBOR_Compensation := (28.50 * rDynamicSloshingDeltaPres) + (14.20 * MAX(0.0, (rCargoLiquidTemp_Tank1_In - (-161.50))));")
    emit("")

    # --- 2.7 CENTRIFUGAL BOG COMPRESSOR POLYTROPIC THERMODYNAMICS & ANTI-SURGE MARGINS ---
    emit("(* --- 2.7 CENTRIFUGAL BOG COMPRESSOR POLYTROPIC THERMODYNAMICS & SURGE LIMIT LINES --- *)")
    emit("(* Suction to Discharge Compression Pressure Ratio *)")
    emit("IF (rVoted_BOGSuctionPres_Out + 101.325) > 10.0 THEN")
    emit("    rCompressorPolytropicHead_Out := (rMethane_Isentropic_k / (rMethane_Isentropic_k - 1.000)) *")
    emit("        rCompressorPolytropicEfficiency * rGasConstant_R_Methane * (rBOGStage1SuctTemp_In + 273.15) *")
    emit("        (MAX(0.01, ((rBOGStage2DischPres_In + 101.325) / (rVoted_BOGSuctionPres_Out + 101.325)) - 1.000));")
    emit("ELSE")
    emit("    rCompressorPolytropicHead_Out := 0.0;")
    emit("END_IF;")
    emit("")
    emit("(* Stage 1 Equivalent Flow Differential Pressure & Surge Limit Line *)")
    emit("rStg1_EquivalentFlowDP := MAX(0.50, (rVoted_BOGSuctionPres_Out * 0.180));")
    emit("rStg1_SurgeLimitDP := rStg1_SurgeLineSlope_K1 * MAX(1.0, (rBOGStage1DischPres_In - rVoted_BOGSuctionPres_Out));")
    emit("IF rStg1_SurgeLimitDP > 0.10 THEN")
    emit("    rStg1_SurgeMarginRatio := rStg1_EquivalentFlowDP / rStg1_SurgeLimitDP;")
    emit("ELSE")
    emit("    rStg1_SurgeMarginRatio := 1.50;")
    emit("END_IF;")
    emit("rBOGStage1SurgeMargin_Out := rStg1_SurgeMarginRatio;")
    emit("")
    emit("(* Stage 2 Venturi Flow Differential Pressure & Surge Limit Line *)")
    emit("rStg2_EquivalentFlowDP := rVoted_BOGDischargeDP_Out;")
    emit("rStg2_SurgeLimitDP := rStg2_SurgeLineSlope_K2 * MAX(5.0, (rBOGStage2DischPres_In - rBOGStage1DischPres_In));")
    emit("IF rStg2_SurgeLimitDP > 0.10 THEN")
    emit("    rStg2_SurgeMarginRatio := rStg2_EquivalentFlowDP / rStg2_SurgeLimitDP;")
    emit("ELSE")
    emit("    rStg2_SurgeMarginRatio := 1.50;")
    emit("END_IF;")
    emit("rBOGStage2SurgeMargin_Out := rStg2_SurgeMarginRatio;")
    emit("")
    emit("(* Surge Limit Protection Flags *)")
    emit("IF rStg1_SurgeMarginRatio < rSurgeTripThreshold THEN")
    emit("    bAlarm_Surge_Stg1_Trip := TRUE;")
    emit("END_IF;")
    emit("IF rStg2_SurgeMarginRatio < rSurgeTripThreshold THEN")
    emit("    bAlarm_Surge_Stg2_Trip := TRUE;")
    emit("END_IF;")
    emit("")

    # --- 2.8 NITROGEN REVERSE BRAYTON COMPANDER & COLD BOX HEAT TRANSFER ---
    emit("(* --- 2.8 NITROGEN REVERSE BRAYTON COMPANDER & COLD BOX HEAT EXCHANGER BALANCE --- *)")
    emit("(* Nitrogen Cycle Compander Pressure Ratio *)")
    emit("IF (rN2CompSuctPres_In > 10.0) THEN")
    emit("    rN2CompanderPressureRatio_Out := rN2CompDischPres_In / rN2CompSuctPres_In;")
    emit("ELSE")
    emit("    rN2CompanderPressureRatio_Out := 1.0;")
    emit("END_IF;")
    emit("")
    emit("(* Cold Box Counter-Current Temperature Differentials *)")
    emit("(* Hot Side: BOG Gas Inflow to Subcooled Condensate Outflow *)")
    emit("(* Cold Side: Nitrogen Expander Cryogenic Inflow to Warm Nitrogen Outflow *)")
    emit("IF (rBOGStage2DischTemp_In > rVoted_N2ExpTemp_Out) AND (rColdBoxLNGOutTemp_In > rVoted_N2ExpTemp_Out) THEN")
    emit("    rColdBoxLMTD_Calculated := ((rBOGStage2DischTemp_In - (rVoted_N2ExpTemp_Out + 32.0)) -")
    emit("                                (rColdBoxLNGOutTemp_In - rVoted_N2ExpTemp_Out)) /")
    emit("                               MAX(0.050, (0.500 * (ABS(rBOGStage2DischTemp_In - rColdBoxLNGOutTemp_In) + 0.100)));")
    emit("    IF rColdBoxLMTD_Calculated < 1.0 THEN")
    emit("        rColdBoxLMTD_Calculated := 1.0;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rColdBoxLMTD_Calculated := 5.0;")
    emit("END_IF;")
    emit("rColdBoxLMTD_Out := rColdBoxLMTD_Calculated;")
    emit("")
    emit("(* Cryogenic Heat Extraction Duty Delivered [kW] *)")
    emit("rCryogenicCoolingDuty := rColdBox_HeatTransferCoeff_UA * rColdBoxLMTD_Calculated;")
    emit("rTotalCoolingPower_kW_Out := rCryogenicCoolingDuty;")
    emit("")
    emit("(* Net Reliquefaction Mass Flow Generation Rate [kg/h] *)")
    emit("IF rLNG_LatentHeatVap > 100.0 THEN")
    emit("    rNetReliquefactionMassFlow := (rCryogenicCoolingDuty / rLNG_LatentHeatVap) * 3600.0;")
    emit("ELSE")
    emit("    rNetReliquefactionMassFlow := 0.0;")
    emit("END_IF;")
    emit("rReliquefiedRate_kg_h_Out := rNetReliquefactionMassFlow;")
    emit("")

    # --- 2.9 DUAL-FUEL PROPULSION SENDOUT & DAILY BOR ESTIMATION ---
    emit("(* --- 2.9 DUAL-FUEL PROPULSION SENDOUT COORDINATION & DAILY BOR ESTIMATION --- *)")
    emit("IF (bDualFuelEngineOnline_In > 0.50) THEN")
    emit("    rFuelGasMassDelivered_kg_h_Out := MIN(rMaxAllowableFuelGasFlow_In, (rFuelGasEngineDem_In + rFuelGasAuxGenDem_In));")
    emit("ELSE")
    emit("    rFuelGasMassDelivered_kg_h_Out := 0.0;")
    emit("END_IF;")
    emit("")
    emit("(* Daily Boil-Off Rate Equivalent Calculation [% of Total Cargo Volume per 24h Day] *)")
    emit("IF (rLNG_LiquidDensity > 100.0) THEN")
    emit("    rEstimatedBOR_PctPerDay_Out := ((rVoted_CondensateFlow_Out + rFuelGasMassDelivered_kg_h_Out + rDynamicBOR_Compensation) /")
    emit("                                   (rLNG_LiquidDensity * 174000.0)) * 2400.0;")
    emit("ELSE")
    emit("    rEstimatedBOR_PctPerDay_Out := 0.085;")
    emit("END_IF;")
    emit("")
    return "\n".join(lines)
