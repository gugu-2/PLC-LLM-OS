# lng_reliquefaction_builder/phase3_mpc.py

def get_phase3():
    lines = []
    def emit(s=""):
        lines.append(s)

    emit("(* ================================================================================================================= *)")
    emit("(* === PHASE 3: RECEDING-HORIZON MPC OPTIMIZATION WITH PGD & SLEW LIMITS ===                                         *)")
    emit("(* ================================================================================================================= *)")
    emit("(* Receding Horizon Np = 5 steps, Nu = 5 steps, 6 Unrolled Iterations of Projected Gradient Descent (PGD)           *)")
    emit("(* Coordinated Multivariable Decoupling between BOG Anti-Surge Bypass, N2 Compander IGV, Condensate Return & GCU  *)")
    emit("")

    # --- 3.1 TARGET TRAJECTORY INITIALIZATION ---
    emit("(* --- 3.1 REFERENCE TARGET TRAJECTORY SYNTHESIS OVER PREDICTION HORIZON --- *)")
    emit("FOR kdxLoop := 1 TO 5 DO")
    emit("    (* State 1: Cargo Tank 1 Ullage Pressure Setpoint Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 1] := rUllageTargetPres_SP_In - rNominal_UllagePres_Tank1;")
    emit("    (* State 2: Cargo Tank 4 Ullage Pressure Setpoint Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 2] := rUllageTargetPres_SP_In - rNominal_UllagePres_Tank4;")
    emit("    (* State 3: Compressor Suction Temperature Target Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 3] := 0.0;")
    emit("    (* State 4: Stage 2 Discharge Pressure Target Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 4] := 0.0;")
    emit("    (* State 5: Nitrogen Expander Cryogenic Temperature Target Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 5] := -rSubcoolingDeltaT_SP_In;")
    emit("    (* State 6: Plate-Fin Condensate Outlet Temperature Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 6] := -rSubcoolingDeltaT_SP_In;")
    emit("    (* State 7: Subcooled Condensate Target Return Flow Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 7] := 0.0;")
    emit("    (* State 8: Nitrogen Mass Inventory Target Deviation *)")
    emit("    x_MpcTargetTrajectory[kdxLoop, 8] := 0.0;")
    emit("END_FOR;")
    emit("")

    # --- 3.2 SEED INITIAL HORIZON STATES FROM CURRENT OBSERVER ESTIMATES ---
    emit("(* --- 3.2 INITIALIZE MPC TRAJECTORY BUFFER WITH CURRENT STATE ESTIMATE --- *)")
    emit("FOR idxLoop := 1 TO 8 DO")
    emit("    x_MpcHorizon[1, idxLoop] := x_StateEst[idxLoop];")
    emit("END_FOR;")
    emit("")

    # --- 3.3 PROJECTED GRADIENT DESCENT (PGD) OPTIMIZATION LOOP ---
    emit("(* --- 3.3 MULTIVARIABLE PROJECTED GRADIENT DESCENT (6 UNROLLED ITERATIONS) --- *)")
    emit("FOR iterPGD := 1 TO 6 DO")
    emit("")
    emit("    (* Step A: Forward State Simulation over 5-Step Horizon *)")
    emit("    FOR kdxLoop := 1 TO 4 DO")
    emit("        FOR idxLoop := 1 TO 8 DO")
    emit("            rTempSum := 0.0;")
    emit("            FOR jdxLoop := 1 TO 8 DO")
    emit("                rTempSum := rTempSum + (matA[idxLoop, jdxLoop] * x_MpcHorizon[kdxLoop, jdxLoop]);")
    emit("            END_FOR;")
    emit("            FOR jdxLoop := 1 TO 6 DO")
    emit("                rTempSum := rTempSum + (matB[idxLoop, jdxLoop] * u_MpcHorizon[kdxLoop, jdxLoop]);")
    emit("            END_FOR;")
    emit("            x_MpcHorizon[kdxLoop + 1, idxLoop] := rTempSum;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* Step B: Analytical Cost Function Gradient Evaluation *)")
    emit("    FOR kdxLoop := 1 TO 5 DO")
    emit("        FOR idxLoop := 1 TO 6 DO")
    emit("            (* State Tracking Error Gradient Component: B^T * Q * (x - x_target) *)")
    emit("            rTempCost := 0.0;")
    emit("            FOR jdxLoop := 1 TO 8 DO")
    emit("                rTempCost := rTempCost + (matB[jdxLoop, idxLoop] * weightQ_State[jdxLoop] *")
    emit("                    (x_MpcHorizon[kdxLoop, jdxLoop] - x_MpcTargetTrajectory[kdxLoop, jdxLoop]));")
    emit("            END_FOR;")
    emit("")
    emit("            (* Terminal Cost Weighting on Final Prediction Step N = 5 *)")
    emit("            IF kdxLoop = 5 THEN")
    emit("                FOR jdxLoop := 1 TO 8 DO")
    emit("                    rTempCost := rTempCost + (matB[jdxLoop, idxLoop] * weightP_TerminalState[jdxLoop] *")
    emit("                        (x_MpcHorizon[5, jdxLoop] - x_MpcTargetTrajectory[5, jdxLoop]));")
    emit("                END_FOR;")
    emit("            END_IF;")
    emit("")
    emit("            (* Actuator Energy Penalty Component: R * u *)")
    emit("            rTempCost := rTempCost + (weightR_Actuator[idxLoop] * u_MpcHorizon[kdxLoop, idxLoop]);")
    emit("")
    emit("            (* Dynamic Compressor Anti-Surge Barrier Function Gradient *)")
    emit("            (* If Stage 1 or Stage 2 Surge Margin Approaches SLL, Add Barrier Gradient to Open ASVs *)")
    emit("            IF (idxLoop = 1) AND (rBOGStage1SurgeMargin_Out < rSurgeMarginSetPoint) THEN")
    emit("                rTempCost := rTempCost - (rSurgeBarrierGain * (rSurgeMarginSetPoint - rBOGStage1SurgeMargin_Out));")
    emit("            END_IF;")
    emit("            IF (idxLoop = 2) AND (rBOGStage2SurgeMargin_Out < rSurgeMarginSetPoint) THEN")
    emit("                rTempCost := rTempCost - (rSurgeBarrierGain * (rSurgeMarginSetPoint - rBOGStage2SurgeMargin_Out));")
    emit("            END_IF;")
    emit("")
    emit("            (* Compressor Speed Surge Decoupling: Avoid Excessive Ramp-Down When Close to Surge *)")
    emit("            IF (idxLoop = 6) AND ((rBOGStage1SurgeMargin_Out < rSurgeMarginSetPoint) OR (rBOGStage2SurgeMargin_Out < rSurgeMarginSetPoint)) THEN")
    emit("                rTempCost := rTempCost + (rSurgeBarrierGain * 0.500);")
    emit("            END_IF;")
    emit("")
    emit("            grad_CostFunction[kdxLoop, idxLoop] := rTempCost;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("")
    emit("    (* Step C: Gradient Step & Convex Box Projection [0.0% .. 100.0%] *)")
    emit("    FOR kdxLoop := 1 TO 5 DO")
    emit("        FOR idxLoop := 1 TO 6 DO")
    emit("            u_MpcHorizon[kdxLoop, idxLoop] := u_MpcHorizon[kdxLoop, idxLoop] - (rPGD_StepSize * grad_CostFunction[kdxLoop, idxLoop]);")
    emit("            (* Actuator Feasible Domain Projection *)")
    emit("            IF u_MpcHorizon[kdxLoop, idxLoop] < 0.0 THEN")
    emit("                u_MpcHorizon[kdxLoop, idxLoop] := 0.0;")
    emit("            ELSIF u_MpcHorizon[kdxLoop, idxLoop] > 100.0 THEN")
    emit("                u_MpcHorizon[kdxLoop, idxLoop] := 100.0;")
    emit("            END_IF;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("END_FOR;")
    emit("")

    # --- 3.4 RECEDING HORIZON INJECTION & ASYMMETRIC SLEW RATE LIMITING ---
    emit("(* --- 3.4 RECEDING-HORIZON INJECTION & ACTUATOR ASYMMETRIC SLEW RATE LIMITING --- *)")
    emit("(* Actuator 1: BOG Stage 1 Anti-Surge Bypass Valve (ASV-1) - Fast Open, Slow Close *)")
    emit("rTargetInput := u_MpcHorizon[1, 1];")
    emit("rSlewDelta := rTargetInput - u_ActuatorPrevious[1];")
    emit("IF rSlewDelta > rMaxSlew_ASV_Open THEN")
    emit("    u_ActuatorCurrent[1] := u_ActuatorPrevious[1] + rMaxSlew_ASV_Open;")
    emit("ELSIF rSlewDelta < -rMaxSlew_ASV_Close THEN")
    emit("    u_ActuatorCurrent[1] := u_ActuatorPrevious[1] - rMaxSlew_ASV_Close;")
    emit("ELSE")
    emit("    u_ActuatorCurrent[1] := rTargetInput;")
    emit("END_IF;")
    emit("u_ActuatorPrevious[1] := u_ActuatorCurrent[1];")
    emit("")
    emit("(* Actuator 2: BOG Stage 2 Anti-Surge Bypass Valve (ASV-2) - Fast Open, Slow Close *)")
    emit("rTargetInput := u_MpcHorizon[1, 2];")
    emit("rSlewDelta := rTargetInput - u_ActuatorPrevious[2];")
    emit("IF rSlewDelta > rMaxSlew_ASV_Open THEN")
    emit("    u_ActuatorCurrent[2] := u_ActuatorPrevious[2] + rMaxSlew_ASV_Open;")
    emit("ELSIF rSlewDelta < -rMaxSlew_ASV_Close THEN")
    emit("    u_ActuatorCurrent[2] := u_ActuatorPrevious[2] - rMaxSlew_ASV_Close;")
    emit("ELSE")
    emit("    u_ActuatorCurrent[2] := rTargetInput;")
    emit("END_IF;")
    emit("u_ActuatorPrevious[2] := u_ActuatorCurrent[2];")
    emit("")
    emit("(* Actuator 3: Nitrogen Compander Variable Inlet Guide Vanes (IGV) *)")
    emit("rTargetInput := u_MpcHorizon[1, 3];")
    emit("rSlewDelta := rTargetInput - u_ActuatorPrevious[3];")
    emit("IF rSlewDelta > rMaxSlew_IGV THEN")
    emit("    u_ActuatorCurrent[3] := u_ActuatorPrevious[3] + rMaxSlew_IGV;")
    emit("ELSIF rSlewDelta < -rMaxSlew_IGV THEN")
    emit("    u_ActuatorCurrent[3] := u_ActuatorPrevious[3] - rMaxSlew_IGV;")
    emit("ELSE")
    emit("    u_ActuatorCurrent[3] := rTargetInput;")
    emit("END_IF;")
    emit("u_ActuatorPrevious[3] := u_ActuatorCurrent[3];")
    emit("")
    emit("(* Actuator 4: Subcooled LNG Condensate Tank Bottom Return Valve *)")
    emit("rTargetInput := u_MpcHorizon[1, 4];")
    emit("rSlewDelta := rTargetInput - u_ActuatorPrevious[4];")
    emit("IF rSlewDelta > rMaxSlew_CondValve THEN")
    emit("    u_ActuatorCurrent[4] := u_ActuatorPrevious[4] + rMaxSlew_CondValve;")
    emit("ELSIF rSlewDelta < -rMaxSlew_CondValve THEN")
    emit("    u_ActuatorCurrent[4] := u_ActuatorPrevious[4] - rMaxSlew_CondValve;")
    emit("ELSE")
    emit("    u_ActuatorCurrent[4] := rTargetInput;")
    emit("END_IF;")
    emit("u_ActuatorPrevious[4] := u_ActuatorCurrent[4];")
    emit("")
    emit("(* Actuator 5: Gas Combustion Unit (GCU) Fast-Dump Throttle Valve *)")
    emit("rTargetInput := u_MpcHorizon[1, 5];")
    emit("rSlewDelta := rTargetInput - u_ActuatorPrevious[5];")
    emit("IF rSlewDelta > rMaxSlew_GCU_Valve THEN")
    emit("    u_ActuatorCurrent[5] := u_ActuatorPrevious[5] + rMaxSlew_GCU_Valve;")
    emit("ELSIF rSlewDelta < -rMaxSlew_GCU_Valve THEN")
    emit("    u_ActuatorCurrent[5] := u_ActuatorPrevious[5] - rMaxSlew_GCU_Valve;")
    emit("ELSE")
    emit("    u_ActuatorCurrent[5] := rTargetInput;")
    emit("END_IF;")
    emit("u_ActuatorPrevious[5] := u_ActuatorCurrent[5];")
    emit("")
    emit("(* Actuator 6: BOG Centrifugal Compressor 3.5 MW Drive VFD Speed Reference *)")
    emit("rTargetInput := u_MpcHorizon[1, 6];")
    emit("rSlewDelta := rTargetInput - u_ActuatorPrevious[6];")
    emit("IF rSlewDelta > rMaxSlew_VFD THEN")
    emit("    u_ActuatorCurrent[6] := u_ActuatorPrevious[6] + rMaxSlew_VFD;")
    emit("ELSIF rSlewDelta < -rMaxSlew_VFD THEN")
    emit("    u_ActuatorCurrent[6] := u_ActuatorPrevious[6] - rMaxSlew_VFD;")
    emit("ELSE")
    emit("    u_ActuatorCurrent[6] := rTargetInput;")
    emit("END_IF;")
    emit("u_ActuatorPrevious[6] := u_ActuatorCurrent[6];")
    emit("")
    return "\n".join(lines)
