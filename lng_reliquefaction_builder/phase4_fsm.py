# lng_reliquefaction_builder/phase4_fsm.py

def get_phase4():
    lines = []
    def emit(s=""):
        lines.append(s)

    emit("(* ================================================================================================================= *)")
    emit("(* === PHASE 4: 14-STAGE DETERMINISTIC PRODUCTION FINITE STATE MACHINE (FSM) ===                                    *)")
    emit("(* ================================================================================================================= *)")
    emit("(* Deterministic Multi-Stage Cryogenic Propulsion & Re-Liquefaction Plant Supervisory State Machine                   *)")
    emit("(* IMO IGC Code, SIGTTO, API 617, and IEC 61508 SIL-3 Certified Deterministic Transition Logic                         *)")
    emit("")

    # Global Trip Override: If SIL-3 ESD is active or plant trip is latched, force transition to State 13
    emit("(* Master SIL-3 Emergency Shutdown Override *)")
    emit("IF (bESD1_Trip_In > 0.50) OR (bESD2_CargoTrip_In > 0.50) OR bPlantTripLatched THEN")
    emit("    IF eState <> 13 THEN")
    emit("        ePreviousState := eState;")
    emit("        eState := 13;")
    emit("        tStateStepTimer := 0.0;")
    emit("        bStateInitialized := FALSE;")
    emit("    END_IF;")
    emit("END_IF;")
    emit("")

    # Update state step timer
    emit("tStateStepTimer := tStateStepTimer + dtCycle;")
    emit("")

    # CASE eState OF
    emit("CASE eState OF")
    emit("")

    # --- STATE 0: PORT_STANDBY_AND_WARM_NITROGEN_INERT ---
    emit("    0: (* PORT_STANDBY_AND_WARM_NITROGEN_INERT *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bPlantRunning_Out := FALSE;")
    emit("            bGCU_Active_Out := FALSE;")
    emit("            bMastVentActive_Out := FALSE;")
    emit("            bPlantTripped_Out := FALSE;")
    emit("            rASV1_Demand_Out := 100.0; (* Full Open Bypass *)")
    emit("            rASV2_Demand_Out := 100.0; (* Full Open Bypass *)")
    emit("            rN2_IGV_Demand_Out := 0.0; (* Closed Guide Vanes *)")
    emit("            rCondReturnValv_Demand_Out := 0.0; (* Closed Condensate Return *)")
    emit("            rGCU_DumpValve_Demand_Out := 0.0;")
    emit("            rBOG_VFD_Speed_Demand_Out := 0.0; (* Motor Stopped *)")
    emit("            rFuelGasSupplyValv_Demand_Out := 0.0;")
    emit("            rMastVentValv_Demand_Out := 0.0;")
    emit("            rN2MakeupValve_Demand_Out := 0.0;")
    emit("            rN2VentValve_Demand_Out := 0.0;")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Verify Warm Nitrogen Inert Purge Permissive & Operator Plant Enable *)")
    emit("        IF (bEnablePlant_In > 0.50) AND (bInertGasPermissive_In > 0.50) AND (NOT bPlantTripLatched) THEN")
    emit("            IF tStateStepTimer >= 5.000 THEN")
    emit("                ePreviousState := 0;")
    emit("                eState := 1; (* Transition to Refrigeration Cold Box N2 Dry Run *)")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")

    # --- STATE 1: REFRIGERATION_COLD_BOX_NITROGEN_DRY_RUN ---
    emit("    1: (* REFRIGERATION_COLD_BOX_NITROGEN_DRY_RUN *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            rN2MakeupValve_Demand_Out := 15.0; (* Charge Nitrogen Circuit to 15 bar *)")
    emit("            rN2_IGV_Demand_Out := 10.0; (* Slight IGV crack to verify compander seal *)")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Nitrogen Circuit Leak & Pressure Integrity Hold *)")
    emit("        IF (rN2CompSuctPres_In >= 800.0) AND (rN2InventoryMass_In >= 1800.0) THEN")
    emit("            rN2MakeupValve_Demand_Out := 0.0; (* Isolate makeup valve *)")
    emit("            IF tStateStepTimer >= 10.000 THEN")
    emit("                ePreviousState := 1;")
    emit("                eState := 2; (* Transition to Compressor Lube Oil & Seal Gas Lock *)")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        ELSIF tStateStepTimer >= 60.000 THEN")
    emit("            (* Timeout on nitrogen loop charging *)")
    emit("            bPlantTripLatched := TRUE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 2: BOG_COMPRESSOR_LUBE_OIL_AND_SEAL_GAS_LOCK ---
    emit("    2: (* BOG_COMPRESSOR_LUBE_OIL_AND_SEAL_GAS_LOCK *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Verify Auxiliary Mechanical Support: Lube Oil Pressure > 2.4 bar, Seal Gas DP > 1.0 bar *)")
    emit("        IF (rLubeOilPres_In >= 2.40) AND (rLubeOilTemp_In <= 55.0) AND (rSealGasSupplyDP_In >= 1.00) THEN")
    emit("            IF tStateStepTimer >= 5.000 THEN")
    emit("                ePreviousState := 2;")
    emit("                eState := 3; (* Transition to Cargo Tank Pressure Equilibrium Check *)")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        ELSIF tStateStepTimer >= 30.000 THEN")
    emit("            bAlarm_LubeOilPres_L := TRUE;")
    emit("            bPlantTripLatched := TRUE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 3: CARGO_TANK_PRESSURE_EQUILIBRIUM_CHECK ---
    emit("    3: (* CARGO_TANK_PRESSURE_EQUILIBRIUM_CHECK *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Check Differential Pressure Between Cargo Tank 1 and Tank 4 *)")
    emit("        IF ABS(rVoted_TankUllagePres_Out - rCargoUllagePres_Tank4_In) <= 2.50 THEN")
    emit("            (* Suction header ready for boil-off vapor admission *)")
    emit("            IF tStateStepTimer >= 4.000 THEN")
    emit("                ePreviousState := 3;")
    emit("                eState := 4; (* Transition to BOG Compressor Stage 1 Spinup *)")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        ELSIF tStateStepTimer >= 20.000 THEN")
    emit("            (* Cargo header imbalance advisory *)")
    emit("            bAlarm_Ullage_H := TRUE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 4: BOG_COMPRESSOR_STAGE1_SPINUP ---
    emit("    4: (* BOG_COMPRESSOR_STAGE1_SPINUP *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            rASV1_Demand_Out := 100.0; (* Keep 100% full recycle to avoid surge on spinup *)")
    emit("            rASV2_Demand_Out := 100.0;")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Ramp VFD Speed Smoothly to Idle (40.0%) *)")
    emit("        IF rBOG_VFD_Speed_Demand_Out < 40.0 THEN")
    emit("            rBOG_VFD_Speed_Demand_Out := rBOG_VFD_Speed_Demand_Out + (rMaxSlew_VFD * 0.50);")
    emit("        END_IF;")
    emit("")
    emit("        (* Check Motor Electrical Current and Mechanical Vibration *)")
    emit("        IF (rBOG_VFD_Speed_Demand_Out >= 39.5) AND (rMotorCurrent_In < 450.0) AND (rMotorVibration_In < 30.0) THEN")
    emit("            IF tStateStepTimer >= 8.000 THEN")
    emit("                ePreviousState := 4;")
    emit("                eState := 5; (* Transition to Stage 2 & Anti-Surge Lock *)")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")

    # --- STATE 5: BOG_COMPRESSOR_STAGE2_AND_ANTI_SURGE_LOCK ---
    emit("    5: (* BOG_COMPRESSOR_STAGE2_AND_ANTI_SURGE_LOCK *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Ramp VFD Speed to Normal Minimum Operating Speed (70.0%) *)")
    emit("        IF rBOG_VFD_Speed_Demand_Out < 70.0 THEN")
    emit("            rBOG_VFD_Speed_Demand_Out := rBOG_VFD_Speed_Demand_Out + rMaxSlew_VFD;")
    emit("        END_IF;")
    emit("")
    emit("        (* Slowly Throttle Back ASV1 and ASV2 to Establish Intermediate Compression Ratio *)")
    emit("        IF (rASV1_Demand_Out > 45.0) AND (rBOGStage1SurgeMargin_Out >= 1.25) THEN")
    emit("            rASV1_Demand_Out := rASV1_Demand_Out - rMaxSlew_ASV_Close;")
    emit("        END_IF;")
    emit("        IF (rASV2_Demand_Out > 50.0) AND (rBOGStage2SurgeMargin_Out >= 1.25) THEN")
    emit("            rASV2_Demand_Out := rASV2_Demand_Out - rMaxSlew_ASV_Close;")
    emit("        END_IF;")
    emit("")
    emit("        (* Transition when Stage 2 Discharge Pressure Reaches 450 kPa *)")
    emit("        IF (rBOGStage2DischPres_In >= 450.0) AND (rBOGStage1SurgeMargin_Out >= 1.20) AND (rBOGStage2SurgeMargin_Out >= 1.20) THEN")
    emit("            IF tStateStepTimer >= 10.000 THEN")
    emit("                ePreviousState := 5;")
    emit("                eState := 6; (* Transition to Nitrogen Compander Expansion Chilldown *)")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")

    # --- STATE 6: NITROGEN_COMPANDER_EXPANSION_CHILLDOWN (-160 deg C) ---
    emit("    6: (* NITROGEN_COMPANDER_EXPANSION_CHILLDOWN *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Open Nitrogen Compander Guide Vanes to Accelerate Expander Chilldown *)")
    emit("        IF rN2_IGV_Demand_Out < 65.0 THEN")
    emit("            rN2_IGV_Demand_Out := rN2_IGV_Demand_Out + rMaxSlew_IGV;")
    emit("        END_IF;")
    emit("")
    emit("        (* Monitor Nitrogen Expander Cryogenic Temperature TT401 *)")
    emit("        IF (rVoted_N2ExpTemp_Out <= -155.0) AND (rColdBoxLNGOutTemp_In <= -145.0) THEN")
    emit("            IF tStateStepTimer >= 12.000 THEN")
    emit("                ePreviousState := 6;")
    emit("                eState := 7; (* Transition to Full Condensate Reliquefaction Optimal MPC *)")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        ELSIF tStateStepTimer >= 300.000 THEN")
    emit("            (* Cryogenic chilldown failure timeout *)")
    emit("            bAlarm_N2ExpTemp_H := TRUE;")
    emit("            bPlantTripLatched := TRUE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 7: FULL_CONDENSATE_RELIQUEFACTION_OPTIMAL_MPC ---
    emit("    7: (* FULL_CONDENSATE_RELIQUEFACTION_OPTIMAL_MPC *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bPlantRunning_Out := TRUE;")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Apply Fully Modulated Actuator Outputs from Receding-Horizon MPC *)")
    emit("        rASV1_Demand_Out := u_ActuatorCurrent[1];")
    emit("        rASV2_Demand_Out := u_ActuatorCurrent[2];")
    emit("        rN2_IGV_Demand_Out := u_ActuatorCurrent[3];")
    emit("        rCondReturnValv_Demand_Out := u_ActuatorCurrent[4];")
    emit("        rGCU_DumpValve_Demand_Out := u_ActuatorCurrent[5];")
    emit("        rBOG_VFD_Speed_Demand_Out := u_ActuatorCurrent[6];")
    emit("")
    emit("        (* Mode Transition Branches *)")
    emit("        (* 1. Dual-Fuel Engines Demand Gas *)")
    emit("        IF (bDualFuelEngineOnline_In > 0.50) AND ((rFuelGasEngineDem_In + rFuelGasAuxGenDem_In) > 500.0) THEN")
    emit("            ePreviousState := 7;")
    emit("            eState := 8; (* Dual Fuel Engine Fuel Gas Sendout *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        (* 2. Severe Sea State Rough Wave Sloshing Surge *)")
    emit("        ELSIF (rWaveSignificantHeight_In > 5.50) OR (rDynamicSloshingDeltaPres > 4.50) THEN")
    emit("            ePreviousState := 7;")
    emit("            eState := 10; (* Rough Sea Sloshing Pressure Surge Damping *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        (* 3. Cargo Tank High Pressure Ullage Accumulation Requiring GCU Thermal Burning *)")
    emit("        ELSIF (rVoted_TankUllagePres_Out >= rSP_Ullage_H) AND (bGCUReady_In > 0.50) THEN")
    emit("            ePreviousState := 7;")
    emit("            eState := 9; (* GCU Excess BOG Burning *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        (* 4. Operator Turn Down / Low Cargo Boil-Off Rate *)")
    emit("        ELSIF (rVoted_TankUllagePres_Out < rSP_Ullage_L) THEN")
    emit("            ePreviousState := 7;")
    emit("            eState := 11; (* Hot Standby Recycle *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 8: DUAL_FUEL_ENGINE_FUEL_GAS_SENDOUT_COORDINATION ---
    emit("    8: (* DUAL_FUEL_ENGINE_FUEL_GAS_SENDOUT_COORDINATION *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Modulate Fuel Gas Supply Valve to Regulate Engine Header Pressure at 5.5 bar *)")
    emit("        IF rFuelGasEnginePres_In < 5.40 THEN")
    emit("            rFuelGasSupplyValv_Demand_Out := MIN(100.0, rFuelGasSupplyValv_Demand_Out + 0.250);")
    emit("        ELSIF rFuelGasEnginePres_In > 5.60 THEN")
    emit("            rFuelGasSupplyValv_Demand_Out := MAX(0.0, rFuelGasSupplyValv_Demand_Out - 0.250);")
    emit("        END_IF;")
    emit("")
    emit("        (* Reliquefaction Plant Subcools Remainder of BOG Not Consumed by Propulsion *)")
    emit("        rASV1_Demand_Out := u_ActuatorCurrent[1];")
    emit("        rASV2_Demand_Out := u_ActuatorCurrent[2];")
    emit("        rN2_IGV_Demand_Out := MAX(25.0, u_ActuatorCurrent[3] * 0.75);")
    emit("        rCondReturnValv_Demand_Out := u_ActuatorCurrent[4];")
    emit("        rBOG_VFD_Speed_Demand_Out := MAX(60.0, u_ActuatorCurrent[6]);")
    emit("")
    emit("        (* Return to Full Reliquefaction if Propulsion Engines Stop Consuming Gas *)")
    emit("        IF (bDualFuelEngineOnline_In <= 0.50) OR ((rFuelGasEngineDem_In + rFuelGasAuxGenDem_In) < 200.0) THEN")
    emit("            rFuelGasSupplyValv_Demand_Out := 0.0;")
    emit("            ePreviousState := 8;")
    emit("            eState := 7; (* Return to Optimal Reliquefaction *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 9: GCU_EXCESS_BOG_THERMAL_BURNING_MODE ---
    emit("    9: (* GCU_EXCESS_BOG_THERMAL_BURNING_MODE *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bGCU_Active_Out := TRUE;")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Throttle GCU Dump Valve Proportionally to Cargo Ullage Pressure Overpressure *)")
    emit("        IF rVoted_TankUllagePres_Out > rSP_Ullage_H THEN")
    emit("            rGCU_DumpValve_Demand_Out := MIN(100.0, (rVoted_TankUllagePres_Out - rSP_Ullage_H) * 10.0);")
    emit("        ELSE")
    emit("            rGCU_DumpValve_Demand_Out := 0.0;")
    emit("        END_IF;")
    emit("")
    emit("        (* Once Cargo Tank Pressure Clears Below H Deadband, Terminate GCU Mode *)")
    emit("        IF rVoted_TankUllagePres_Out <= (rSP_Ullage_H - rDB_Ullage) THEN")
    emit("            bGCU_Active_Out := FALSE;")
    emit("            rGCU_DumpValve_Demand_Out := 0.0;")
    emit("            ePreviousState := 9;")
    emit("            eState := 7; (* Return to Normal Reliquefaction *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        (* If Ullage Pressure Continues Escalating Past HH Trip, Force Mast Vent *)")
    emit("        ELSIF rVoted_TankUllagePres_Out >= rSP_Ullage_HH THEN")
    emit("            ePreviousState := 9;")
    emit("            eState := 12; (* Emergency Mast Vent *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 10: ROUGH_SEA_SLOSHING_PRESSURE_SURGE_DAMPING ---
    emit("    10: (* ROUGH_SEA_SLOSHING_PRESSURE_SURGE_DAMPING *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Sloshing Feedforward Compensation: Preemptively Boost Compressor VFD Speed *)")
    emit("        rBOG_VFD_Speed_Demand_Out := MIN(98.0, u_ActuatorCurrent[6] + (rDynamicSloshingDeltaPres * 3.50));")
    emit("        (* Open ASVs Slightly to Protect Against Wave-Induced Backpressure Surges *)")
    emit("        rASV1_Demand_Out := MAX(u_ActuatorCurrent[1], 15.0);")
    emit("        rASV2_Demand_Out := MAX(u_ActuatorCurrent[2], 18.0);")
    emit("        rN2_IGV_Demand_Out := MIN(100.0, u_ActuatorCurrent[3] + 10.0);")
    emit("        rCondReturnValv_Demand_Out := u_ActuatorCurrent[4];")
    emit("")
    emit("        (* Return to Normal State When Sea State Calms Below Threshold *)")
    emit("        IF (rWaveSignificantHeight_In <= 4.00) AND (rDynamicSloshingDeltaPres <= 1.50) THEN")
    emit("            IF tStateStepTimer >= 15.000 THEN")
    emit("                ePreviousState := 10;")
    emit("                eState := 7;")
    emit("                tStateStepTimer := 0.0;")
    emit("                bStateInitialized := FALSE;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")

    # --- STATE 11: REFRIGERATION_LOOP_HOT_STANDBY_RECYCLE ---
    emit("    11: (* REFRIGERATION_LOOP_HOT_STANDBY_RECYCLE *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Keep Machinery Running in 100% Internal Recycle to Avoid Cold Shock Thermal Cycling *)")
    emit("        rASV1_Demand_Out := 85.0;")
    emit("        rASV2_Demand_Out := 85.0;")
    emit("        rBOG_VFD_Speed_Demand_Out := 55.0;")
    emit("        rN2_IGV_Demand_Out := 30.0;")
    emit("        rCondReturnValv_Demand_Out := 5.0; (* Minimum Circulation Bleed *)")
    emit("        rGCU_DumpValve_Demand_Out := 0.0;")
    emit("")
    emit("        (* Resume Normal Reliquefaction When Tank Pressure Recovers *)")
    emit("        IF rVoted_TankUllagePres_Out >= (rSP_Ullage_L + rDB_Ullage) THEN")
    emit("            ePreviousState := 11;")
    emit("            eState := 7;")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 12: EMERGENCY_CARGO_MAST_VENT_ISOLATION ---
    emit("    12: (* EMERGENCY_CARGO_MAST_VENT_ISOLATION *)")
    emit("        IF NOT bStateInitialized THEN")
    emit("            bMastVentActive_Out := TRUE;")
    emit("            rMastVentValv_Demand_Out := 100.0; (* Quick Opening Relief Mast *)")
    emit("            rGCU_DumpValve_Demand_Out := 100.0; (* Full Thermal Dump *)")
    emit("            bStateInitialized := TRUE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Rapid Atmospheric Pressure Relief to Protect Membrane Integrity *)")
    emit("        IF rVoted_TankUllagePres_Out <= (rSP_Ullage_HH - (2.0 * rDB_Ullage)) THEN")
    emit("            rMastVentValv_Demand_Out := 0.0; (* Close Mast Vent *)")
    emit("            bMastVentActive_Out := FALSE;")
    emit("            ePreviousState := 12;")
    emit("            eState := 9; (* Fall Back to GCU Burning *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        END_IF;")
    emit("")

    # --- STATE 13: SIL-3_QUICK_CLOSING_SAFETY_SHUTDOWN (ESD-1/2) ---
    emit("    13: (* SIL-3_QUICK_CLOSING_SAFETY_SHUTDOWN (ESD-1/2) *)")
    emit("        bPlantRunning_Out := FALSE;")
    emit("        bPlantTripped_Out := TRUE;")
    emit("        (* Fail-Safe Actuator Positioning *)")
    emit("        rASV1_Demand_Out := 100.0; (* Fail-Open Anti-Surge Bypass *)")
    emit("        rASV2_Demand_Out := 100.0; (* Fail-Open Anti-Surge Bypass *)")
    emit("        rN2_IGV_Demand_Out := 0.0; (* Fail-Closed Guide Vanes *)")
    emit("        rCondReturnValv_Demand_Out := 0.0; (* Fail-Closed Condensate Return Isolation *)")
    emit("        rFuelGasSupplyValv_Demand_Out := 0.0; (* Fast Double Block & Bleed Fuel Gas Closure *)")
    emit("        rBOG_VFD_Speed_Demand_Out := 0.0; (* Instant Motor De-energization *)")
    emit("        rN2MakeupValve_Demand_Out := 0.0;")
    emit("        rN2VentValve_Demand_Out := 0.0;")
    emit("")
    emit("        (* If Ullage Overpressure is the Cause of Trip, Allow GCU or Mast Venting *)")
    emit("        IF rVoted_TankUllagePres_Out >= rSP_Ullage_HH THEN")
    emit("            rMastVentValv_Demand_Out := 100.0;")
    emit("            bMastVentActive_Out := TRUE;")
    emit("        ELSE")
    emit("            rMastVentValv_Demand_Out := 0.0;")
    emit("            bMastVentActive_Out := FALSE;")
    emit("        END_IF;")
    emit("")
    emit("        (* Alarm Reset Interlock Permissive *)")
    emit("        IF (bResetFaults_In > 0.50) AND (bESD1_Trip_In <= 0.50) AND (bESD2_CargoTrip_In <= 0.50) AND")
    emit("           (NOT bAlarm_Ullage_HH) AND (NOT bAlarm_Ullage_LL) AND (NOT bAlarm_DischPres_HH) THEN")
    emit("            bPlantTripLatched := FALSE;")
    emit("            bAlarm_Surge_Stg1_Trip := FALSE;")
    emit("            bAlarm_Surge_Stg2_Trip := FALSE;")
    emit("            ePreviousState := 13;")
    emit("            eState := 0; (* Reset Back to Port Standby *)")
    emit("            tStateStepTimer := 0.0;")
    emit("            bStateInitialized := FALSE;")
    emit("        END_IF;")
    emit("")
    emit("END_CASE;")
    emit("")
    emit("(* Map Active FSM State to Output *)")
    emit("eCurrentState_Out := eState;")
    emit("")
    return "\n".join(lines)
