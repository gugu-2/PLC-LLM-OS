def get_phase3():
    lines = []
    lines.append("(* === PHASE 3: RECEDING-HORIZON MPC CONTROL ACTION === *)")
    lines.append("(* Evaluates tracking errors against stage-dependent reference trajectories, computes  *)")
    lines.append("(* analytical projected gradients across 12 states, and enforces box constraints.       *)")
    lines.append("")
    lines.append("(* 3.1 Load Stage-Dependent Reference Setpoint Trajectory *)")
    lines.append("IF (iState = 4) THEN")
    lines.append("    (* Dash Necking Stage: Target 3.5 mm diameter *)")
    lines.append("    aSetpoint_ref[1] := 3.5 - 300.0;   (* Delta D_c [mm] *)")
    lines.append("    aSetpoint_ref[2] := 2.1 - 4.50;    (* Delta h_m [mm] *)")
    lines.append("    aSetpoint_ref[3] := 11.0 - 11.0;   (* Delta phi_L [deg] *)")
    lines.append("    aSetpoint_ref[4] := 1422.0 - 1414.0;")
    lines.append("    aSetpoint_ref[5] := 1435.0;")
    lines.append("    aSetpoint_ref[6] := 1480.0;")
    lines.append("    aSetpoint_ref[7] := 1470.0;")
    lines.append("    aSetpoint_ref[8] := 1450.0;")
    lines.append("    aSetpoint_ref[9] := 1490.0;")
    lines.append("    aSetpoint_ref[10] := 0.0;")
    lines.append("    aSetpoint_ref[11] := 42.0;         (* High gradient during necking *)")
    lines.append("    aSetpoint_ref[12] := 0.5;")
    lines.append("ELSIF (iState = 5) THEN")
    lines.append("    (* Crown Expansion Shoulder Stage: Target ramping to 300 mm *)")
    lines.append("    aSetpoint_ref[1] := (rVotedMeniscusDiam_mm + 5.0) - 300.0;")
    lines.append("    aSetpoint_ref[2] := 5.8 - 4.50;    (* Taller meniscus during expansion *)")
    lines.append("    aSetpoint_ref[3] := 68.0 - 11.0;   (* Expanding shoulder contact angle *)")
    lines.append("    aSetpoint_ref[4] := 1416.0 - 1414.0;")
    lines.append("    aSetpoint_ref[5] := 1428.0;")
    lines.append("    aSetpoint_ref[6] := 1470.0;")
    lines.append("    aSetpoint_ref[7] := 1465.0;")
    lines.append("    aSetpoint_ref[8] := 1445.0;")
    lines.append("    aSetpoint_ref[9] := 1485.0;")
    lines.append("    aSetpoint_ref[10] := 0.0;")
    lines.append("    aSetpoint_ref[11] := 38.0;")
    lines.append("    aSetpoint_ref[12] := 15.0;")
    lines.append("ELSIF (iState = 6) OR (iState = 7) THEN")
    lines.append("    (* Body Diameter Stabilization & Steady-State Body Pull: Target 300.0 mm *)")
    lines.append("    aSetpoint_ref[1] := 0.0;            (* Perfect 300.0 mm lock *)")
    lines.append("    aSetpoint_ref[2] := 0.0;            (* Meniscus height at 4.50 mm *)")
    lines.append("    aSetpoint_ref[3] := 0.0;            (* Contact angle at 11.0 deg *)")
    lines.append("    aSetpoint_ref[4] := 1414.0 - 1414.0;(* Solidification isotherm *)")
    lines.append("    aSetpoint_ref[5] := 1424.0;")
    lines.append("    aSetpoint_ref[6] := 1475.0;")
    lines.append("    aSetpoint_ref[7] := 1480.0;")
    lines.append("    aSetpoint_ref[8] := 1450.0;")
    lines.append("    aSetpoint_ref[9] := 1495.0;")
    lines.append("    aSetpoint_ref[10] := 0.0;           (* Melt level locked to optical zero *)")
    lines.append("    aSetpoint_ref[11] := 35.0;          (* Voronkov design gradient *)")
    lines.append("    aSetpoint_ref[12] := rCumulativeMass_kg + 0.5;")
    lines.append("ELSIF (iState = 8) THEN")
    lines.append("    (* Tail-Off Cone Reduction Stage: Tapering to 0 mm *)")
    lines.append("    aSetpoint_ref[1] := (rVotedMeniscusDiam_mm - 12.0) - 300.0;")
    lines.append("    aSetpoint_ref[2] := 3.2 - 4.50;")
    lines.append("    aSetpoint_ref[3] := 4.0 - 11.0;     (* Negative growth angle *)")
    lines.append("    aSetpoint_ref[4] := 1418.0 - 1414.0;")
    lines.append("    aSetpoint_ref[5] := 1430.0;")
    lines.append("    aSetpoint_ref[6] := 1485.0;")
    lines.append("    aSetpoint_ref[7] := 1490.0;")
    lines.append("    aSetpoint_ref[8] := 1460.0;")
    lines.append("    aSetpoint_ref[9] := 1500.0;")
    lines.append("    aSetpoint_ref[10] := 0.0;")
    lines.append("    aSetpoint_ref[11] := 32.0;")
    lines.append("    aSetpoint_ref[12] := rCumulativeMass_kg;")
    lines.append("ELSE")
    lines.append("    (* Idle, Melting, or Cooldown Stages *)")
    lines.append("    aSetpoint_ref[1] := 0.0;")
    lines.append("    aSetpoint_ref[2] := 0.0;")
    lines.append("    aSetpoint_ref[3] := 0.0;")
    lines.append("    aSetpoint_ref[4] := 0.0;")
    lines.append("    aSetpoint_ref[5] := 1420.0;")
    lines.append("    aSetpoint_ref[6] := 1480.0;")
    lines.append("    aSetpoint_ref[7] := 1480.0;")
    lines.append("    aSetpoint_ref[8] := 1450.0;")
    lines.append("    aSetpoint_ref[9] := 1490.0;")
    lines.append("    aSetpoint_ref[10] := 0.0;")
    lines.append("    aSetpoint_ref[11] := 35.0;")
    lines.append("    aSetpoint_ref[12] := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 3.2 Quadratic Cost Weighting Matrices (Q, R, P) *)")
    lines.append("aWeight_Q[1] := 180.0;  (* Ingot diameter error penalty *)")
    lines.append("aWeight_Q[2] := 55.0;   (* Meniscus height deviation penalty *)")
    lines.append("aWeight_Q[3] := 70.0;   (* Wetting growth angle penalty *)")
    lines.append("aWeight_Q[4] := 35.0;   (* Interface temperature error penalty *)")
    lines.append("aWeight_Q[5] := 12.0;   (* Bulk melt temperature penalty *)")
    lines.append("aWeight_Q[6] := 6.0;    (* Upper heater core temp penalty *)")
    lines.append("aWeight_Q[7] := 6.0;    (* Lower heater core temp penalty *)")
    lines.append("aWeight_Q[8] := 5.0;    (* Bottom heater core temp penalty *)")
    lines.append("aWeight_Q[9] := 8.0;    (* Crucible graphite susceptor penalty *)")
    lines.append("aWeight_Q[10] := 95.0;  (* Melt surface vertical level penalty *)")
    lines.append("aWeight_Q[11] := 45.0;  (* Voronkov axial gradient penalty *)")
    lines.append("aWeight_Q[12] := 0.05;  (* Ingot mass progress penalty *)")
    lines.append("")
    lines.append("aWeight_R[1] := 1.25;   (* Slew rate penalty on seed pull speed *)")
    lines.append("aWeight_R[2] := 1.50;   (* Slew penalty on crucible lift speed *)")
    lines.append("aWeight_R[3] := 0.20;   (* Slew penalty on upper side heater power *)")
    lines.append("aWeight_R[4] := 0.20;   (* Slew penalty on lower side heater power *)")
    lines.append("aWeight_R[5] := 0.15;   (* Slew penalty on bottom heater power *)")
    lines.append("aWeight_R[6] := 0.35;   (* Slew penalty on seed rotation speed *)")
    lines.append("aWeight_R[7] := 0.45;   (* Slew penalty on crucible rotation speed *)")
    lines.append("aWeight_R[8] := 0.08;   (* Slew penalty on argon purge flow *)")
    lines.append("")
    for i in range(12):
        lines.append(f"aWeight_P[{i+1}] := aWeight_Q[{i+1}] * 1.75; (* Terminal state penalty *)")

    lines.append("")
    lines.append("(* 3.3 Analytical Projected Gradient Descent Computation: Grad_J = dJ/du *)")

    # For each control input j in 1..8:
    for j in range(8):
        terms = [f"(2.0 * aWeight_P[{i+1}] * (aState_x_next[{i+1}] - aSetpoint_ref[{i+1}]) * aMatrix_B[{i+1},{j+1}])" for i in range(12)]
        term_B_sum = " +\n              ".join(terms)
        lines.append(f"aGrad_J[{j+1}] := (2.0 * aWeight_R[{j+1}] * (aControl_u[{j+1}] - aControl_u_prev[{j+1}])) +\n              {term_B_sum};")

    lines.append("")
    lines.append("(* 3.4 Projected Gradient Descent Iterative Update *)")
    lines.append("aStep_u[1] := 0.0018;")
    lines.append("aStep_u[2] := 0.0015;")
    lines.append("aStep_u[3] := 0.0120;")
    lines.append("aStep_u[4] := 0.0120;")
    lines.append("aStep_u[5] := 0.0080;")
    lines.append("aStep_u[6] := 0.0250;")
    lines.append("aStep_u[7] := 0.0200;")
    lines.append("aStep_u[8] := 0.0500;")
    lines.append("")
    lines.append("IF (iState >= 4) AND (iState <= 8) AND NOT bSystemTripped THEN")
    lines.append("    (* Execute iterative optimization steps *)")
    for j in range(8):
        lines.append(f"    aControl_u[{j+1}] := aControl_u[{j+1}] - (aStep_u[{j+1}] * aGrad_J[{j+1}]);")
    lines.append("    bMpcOptimalConverged := TRUE;")
    lines.append("ELSE")
    lines.append("    bMpcOptimalConverged := FALSE;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 3.5 Actuator Saturation Box Clamping *)")
    lines.append("(* Pull speed: 0.05 to 6.50 mm/min *)")
    lines.append("IF aControl_u[1] > 6.50 THEN aControl_u[1] := 6.50; END_IF;")
    lines.append("IF aControl_u[1] < 0.05 THEN aControl_u[1] := 0.05; END_IF;")
    lines.append("(* Crucible lift: 0.00 to 4.50 mm/min *)")
    lines.append("IF aControl_u[2] > 4.50 THEN aControl_u[2] := 4.50; END_IF;")
    lines.append("IF aControl_u[2] < 0.00 THEN aControl_u[2] := 0.00; END_IF;")
    lines.append("(* Upper heater power: 15.0 to 145.0 kW *)")
    lines.append("IF aControl_u[3] > 145.0 THEN aControl_u[3] := 145.0; END_IF;")
    lines.append("IF aControl_u[3] < 15.0 THEN aControl_u[3] := 15.0; END_IF;")
    lines.append("(* Lower heater power: 15.0 to 125.0 kW *)")
    lines.append("IF aControl_u[4] > 125.0 THEN aControl_u[4] := 125.0; END_IF;")
    lines.append("IF aControl_u[4] < 15.0 THEN aControl_u[4] := 15.0; END_IF;")
    lines.append("(* Bottom heater power: 5.0 to 70.0 kW *)")
    lines.append("IF aControl_u[5] > 70.0 THEN aControl_u[5] := 70.0; END_IF;")
    lines.append("IF aControl_u[5] < 5.0 THEN aControl_u[5] := 5.0; END_IF;")
    lines.append("(* Seed rotation: 2.0 to 25.0 rpm *)")
    lines.append("IF aControl_u[6] > 25.0 THEN aControl_u[6] := 25.0; END_IF;")
    lines.append("IF aControl_u[6] < 2.0 THEN aControl_u[6] := 2.0; END_IF;")
    lines.append("(* Crucible rotation: 1.0 to 12.0 rpm *)")
    lines.append("IF aControl_u[7] > 12.0 THEN aControl_u[7] := 12.0; END_IF;")
    lines.append("IF aControl_u[7] < 1.0 THEN aControl_u[7] := 1.0; END_IF;")
    lines.append("(* Argon purge flow: 30.0 to 160.0 slpm *)")
    lines.append("IF aControl_u[8] > 160.0 THEN aControl_u[8] := 160.0; END_IF;")
    lines.append("IF aControl_u[8] < 30.0 THEN aControl_u[8] := 30.0; END_IF;")
    lines.append("")
    lines.append("(* 3.6 Voronkov Point Defect Envelope Safety Override *)")
    lines.append("IF (iState = 7) THEN")
    lines.append("    IF rVoronkovRatio_vG < rConst_VoronkovMin_mm2minK THEN")
    lines.append("        (* Interstitial-dominant risk: Accelerate pull speed to suppress A-swirl loops *)")
    lines.append("        rVoronkovCorrection_mmpm := (rConst_VoronkovCrit_mm2minK - rVoronkovRatio_vG) * (rAxialGradient_Kcm * 0.1) * 10.0;")
    lines.append("        aControl_u[1] := aControl_u[1] + (0.35 * rVoronkovCorrection_mmpm);")
    lines.append("        dwWarningWord := dwWarningWord OR 16#0000_0020; (* Interstitial defect risk override *)")
    lines.append("    ELSIF rVoronkovRatio_vG > rConst_VoronkovMax_mm2minK THEN")
    lines.append("        (* Vacancy-dominant risk: Decelerate pull speed to suppress COP vacancy pits *)")
    lines.append("        rVoronkovCorrection_mmpm := (rVoronkovRatio_vG - rConst_VoronkovCrit_mm2minK) * (rAxialGradient_Kcm * 0.1) * 10.0;")
    lines.append("        aControl_u[1] := aControl_u[1] - (0.35 * rVoronkovCorrection_mmpm);")
    lines.append("        dwWarningWord := dwWarningWord OR 16#0000_0040; (* Vacancy COP defect risk override *)")
    lines.append("    END_IF;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* Store Previous Actuator Commands *)")
    for j in range(8):
        lines.append(f"aControl_u_prev[{j+1}] := aControl_u[{j+1}];")

    return "\n".join(lines) + "\n"
