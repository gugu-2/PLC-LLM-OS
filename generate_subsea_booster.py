add("    rVotedAcousticNoise_dB := rAcousticLeak_C_dB;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 2: GAS VOLUME FRACTION (GVF) & MULTIPHASE FLOW OBSERVER                              *)")
add("(* Dual-energy gamma densitometer and venturi differential pressure model                   *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Low-pass filter raw gamma density: tau = 150 ms *)")
add("rFilteredGammaDensity_kg_m3 := rFilteredGammaDensity_kg_m3 + (rDt_sec / (0.150 + rDt_sec)) * (rGammaDensitometer_kg_m3 - rFilteredGammaDensity_kg_m3);")
add("")
add("(* Clamp filtered mixture density to physical subsea limits *)")
add("IF rFilteredGammaDensity_kg_m3 < rGasDensityStandard_kg_m3 THEN")
add("    rFilteredGammaDensity_kg_m3 := rGasDensityStandard_kg_m3;")
add("ELSIF rFilteredGammaDensity_kg_m3 > rWaterDensityStandard_kg_m3 THEN")
add("    rFilteredGammaDensity_kg_m3 := rWaterDensityStandard_kg_m3;")
add("END_IF;")
add("rMixtureDensityEst_kg_m3 := rFilteredGammaDensity_kg_m3;")
add("")
add("(* Average liquid density between crude oil and formation water (assume 20% water cut) *)")
add("rGammaLiquidFrac := (0.80 * rOilDensityStandard_kg_m3) + (0.20 * rWaterDensityStandard_kg_m3);")
add("")
add("(* Calculate Gas Volume Fraction (GVF): GVF = (rho_liq - rho_mix) / (rho_liq - rho_gas) *)")
add("IF rGammaLiquidFrac > rGasDensityStandard_kg_m3 THEN")
add("    rCalculatedGVF_pct := ((rGammaLiquidFrac - rFilteredGammaDensity_kg_m3) / (rGammaLiquidFrac - rGasDensityStandard_kg_m3)) * 100.0;")
add("ELSE")
add("    rCalculatedGVF_pct := 0.0;")
add("END_IF;")
add("")
add("IF rCalculatedGVF_pct < 0.0 THEN")
add("    rCalculatedGVF_pct := 0.0;")
add("ELSIF rCalculatedGVF_pct > 100.0 THEN")
add("    rCalculatedGVF_pct := 100.0;")
add("END_IF;")
add("")
add("(* Calculate rate of change of GVF [%/second] to detect fast gas slug fronts *)")
add("IF rDt_sec > 0.001 THEN")
add("    rRateOfChangeGVF_pct_s := (rCalculatedGVF_pct - rPrevCalculatedGVF) / rDt_sec;")
add("ELSE")
add("    rRateOfChangeGVF_pct_s := 0.0;")
add("END_IF;")
add("rPrevCalculatedGVF := rCalculatedGVF_pct;")
add("")
add("(* Multiphase venturi mass flow estimation: m_dot = C_d * E * (pi/4)*d^2 * sqrt(2 * rho_mix * delta_P_v) *)")
add("IF rVenturiDiffPress_mbar > 0.1 THEN")
add("    rSqrtArg := 2.0 * rFilteredGammaDensity_kg_m3 * (rVenturiDiffPress_mbar * 100.0); (* Convert mbar to Pa *)")
add("    IF rSqrtArg > 0.0 THEN")
add("        rVenturiMassFlow_kg_s := rVenturiDischargeCoeff * 0.01227 * SQRT(rSqrtArg);")
add("    ELSE")
add("        rVenturiMassFlow_kg_s := 0.0;")
add("    END_IF;")
add("ELSE")
add("    rVenturiMassFlow_kg_s := 0.0;")
add("END_IF;")
add("")
add("(* --- FAST SLUG MITIGATION FEEDFORWARD (< 200 ms response) --- *)")
add("(* Condition: GVF rises above 92% OR positive GVF slew rate exceeds +45%/sec *)")
add("IF (rCalculatedGVF_pct > rGVF_Slug_H_pct) OR (rRateOfChangeGVF_pct_s > 45.0) THEN")
add("    bSlugConditionLatched := TRUE;")
add("    tSlugTransientTimer   := T#0ms; (* Reset active slug timer *)")
add("END_IF;")
add("")
add("IF bSlugConditionLatched THEN")
add("    tSlugTransientTimer := tSlugTransientTimer + tCycleTime_ms;")
add("    bSlugMitigationActive := TRUE;")
add("    ")
add("    (* Immediate choke kick: +40% recycle choke to prevent dry gas lock & rotor friction overheat *)")
add("    rSlugChokeFeedforwardBoost := 45.0 * (1.0 - (TIME_TO_REAL(tSlugTransientTimer) / 4000.0));")
add("    IF rSlugChokeFeedforwardBoost < 0.0 THEN")
add("        rSlugChokeFeedforwardBoost := 0.0;")
add("    END_IF;")
add("    ")
add("    (* Speed governor derate: clamp speed command to 1500 rpm during gas slug *)")
add("    rSlugSpeedGovernorLimit_rpm := 1450.0;")
add("    ")
add("    (* Release slug mitigation latch after 4.0 seconds if GVF subsides *)")
add("    IF tSlugTransientTimer >= T#4000ms AND rCalculatedGVF_pct < 80.0 THEN")
add("        bSlugConditionLatched := FALSE;")
add("        bSlugMitigationActive := FALSE;")
add("        rSlugChokeFeedforwardBoost := 0.0;")
add("        rSlugSpeedGovernorLimit_rpm := rMaxMotorRpm;")
add("    END_IF;")
add("ELSE")
add("    bSlugMitigationActive := FALSE;")
add("    rSlugChokeFeedforwardBoost := 0.0;")
add("    rSlugSpeedGovernorLimit_rpm := rMaxMotorRpm;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 3: DISCRETE STATE-SPACE KALMAN PREDICTOR (x[k+1] = A*x[k] + B*u[k] + L*(y - C*x))    *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Assemble measured output vector y_meas *)")
add("vecY_meas[0] := rVotedDischargePress_bar - rVotedSuctionPress_bar; (* Pump differential pressure *)")
add("vecY_meas[1] := rVotedBarrierDiffPress_bar;                      (* Barrier seal differential overpressure *)")
add("vecY_meas[2] := rFilteredGammaDensity_kg_m3;                     (* Bulk mixture density *)")
add("")
add("(* Compute observer predicted measurement: y_est = C * x_k *)")
add("FOR i := 0 TO 2 DO")
add("    vecY_est[i] := 0.0;")
add("    FOR j := 0 TO 5 DO")
add("        vecY_est[i] := vecY_est[i] + (matC[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    vecErr_Y[i] := vecY_meas[i] - vecY_est[i];")
add("END_FOR;")
add("")
add("(* State propagation: x_next = A * x_k + B * u_k + L_obs * (y_meas - y_est) *)")
add("FOR i := 0 TO 5 DO")
add("    rTempSum := 0.0;")
add("    (* Matrix A multiplication *)")
add("    FOR j := 0 TO 5 DO")
add("        rTempSum := rTempSum + (matA[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    ")
add("    (* Matrix B multiplication with actuator control vector *)")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matB[i, j] * vecU_k[j]);")
add("    END_FOR;")
add("    ")
add("    (* Kalman Observer innovation feedback *)")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matL_Obs[i, j] * vecErr_Y[j]);")
add("    END_FOR;")
add("    ")
add("    vecX_next[i] := rTempSum;")
add("END_FOR;")
add("")
add("(* Update discrete state vector for next cycle *)")
add("FOR i := 0 TO 5 DO")
add("    vecX_k[i] := vecX_next[i];")
add("END_FOR;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 4: MODEL PREDICTIVE CONTROL (MPC) RECEDING HORIZON GRADIENT EVALUATION              *)")
add("(* Quadratic cost optimization: min J = sum( (x - x_ref)'*Q*(x - x_ref) + delta_u'*R*delta_u)*)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Define Reference state setpoints *)")
add("vecX_Ref[0] := 0.0; (* Density deviation reference *)")
add("vecX_Ref[1] := rTargetDiffPress_bar; (* Target boosting pressure *)")
add("vecX_Ref[2] := rBarrierNominalDeltaP_bar; (* 25.0 bar seal overpressure *)")
add("vecX_Ref[3] := 0.0; (* Surge pressure attenuation *)")
add("vecX_Ref[4] := 15.0; (* Minimum bypass circulation [kg/s] *)")
add("vecX_Ref[5] := 0.0; (* Motor temp deviation target *)")
add("")
add("(* Calculate instantaneous quadratic state cost and analytical gradients with respect to controls *)")
add("rMpcPredictedCost := 0.0;")
add("rMpcGrad_U0 := 0.0;")
add("rMpcGrad_U1 := 0.0;")
add("rMpcGrad_U2 := 0.0;")
add("")
add("FOR i := 0 TO 5 DO")
add("    rTempDiff := vecX_k[i] - vecX_Ref[i];")
add("    rMpcPredictedCost := rMpcPredictedCost + (vecQ_Weights[i] * rTempDiff * rTempDiff);")
add("    ")
add("    (* Analytical gradient backpropagation through B matrix: dJ/du_j = 2 * sum(Q_i * (x_i - x_ref_i) * B_ij) *)")
add("    rMpcGrad_U0 := rMpcGrad_U0 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 0]);")
add("    rMpcGrad_U1 := rMpcGrad_U1 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 1]);")
add("    rMpcGrad_U2 := rMpcGrad_U2 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 2]);")
add("END_FOR;")
add("")
add("(* Add actuator effort penalty gradient *)")
add("rMpcGrad_U0 := rMpcGrad_U0 + (2.0 * vecR_Weights[0] * vecU_k[0]);")
add("rMpcGrad_U1 := rMpcGrad_U1 + (2.0 * vecR_Weights[1] * vecU_k[1]);")
add("rMpcGrad_U2 := rMpcGrad_U2 + (2.0 * vecR_Weights[2] * vecU_k[2]);")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 5: HAMMERSCHMIDT HYDRATE THERMODYNAMICS & MEG CHEMICAL DOSING                        *)")
add("(* Natural gas hydrate equilibrium: T_eq = 8.9 * ln(P_suction) - 18.2                      *)")
add("(* MEG freezing point depression: delta_T = (2220 * W_meg) / (62.07 * (100 - W_meg))       *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Natural log approximation for suction pressure [15 to 150 bar range] *)")
add("IF rVotedSuctionPress_bar > 1.0 THEN")
add("    (* Rational Chebyshev fit for natural logarithm: ln(P) *)")
