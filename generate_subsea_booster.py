add("        rTempSum := rBarrierOilPress_A_bar;")
add("    ELSIF (rBarrierOilPress_B_bar >= rBarrierOilPress_A_bar AND rBarrierOilPress_B_bar <= rBarrierOilPress_C_bar) OR")
add("          (rBarrierOilPress_B_bar <= rBarrierOilPress_A_bar AND rBarrierOilPress_B_bar >= rBarrierOilPress_C_bar) THEN")
add("        rTempSum := rBarrierOilPress_B_bar;")
add("    ELSE")
add("        rTempSum := rBarrierOilPress_C_bar;")
add("    END_IF;")
add("ELSIF bBarrier_ChA_Fault AND NOT bBarrier_ChB_Fault AND NOT bBarrier_ChC_Fault THEN")
add("    rTempSum := (rBarrierOilPress_B_bar + rBarrierOilPress_C_bar) * 0.5;")
add("ELSIF bBarrier_ChB_Fault AND NOT bBarrier_ChA_Fault AND NOT bBarrier_ChC_Fault THEN")
add("    rTempSum := (rBarrierOilPress_A_bar + rBarrierOilPress_C_bar) * 0.5;")
add("ELSE")
add("    rTempSum := (rBarrierOilPress_A_bar + rBarrierOilPress_B_bar) * 0.5;")
add("END_IF;")
add("")
add("(* Compute Barrier Overpressure strictly relative to ambient seabed hydrostatic reference *)")
add("rVotedBarrierDiffPress_bar := rTempSum - rAmbientSeaPress_bar;")
add("")
add("(* --- TRIAD 4: SUBSEA ACOUSTIC EMISSION SENSORS (A, B, C) --- *)")
add("IF ABS(rAcousticLeak_A_dB - rAcousticLeak_B_dB) > 10.0 THEN")
add("    tAcoustic_DiscrepTimer_A := tAcoustic_DiscrepTimer_A + tCycleTime_ms;")
add("ELSE")
add("    tAcoustic_DiscrepTimer_A := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rAcousticLeak_B_dB - rAcousticLeak_C_dB) > 10.0 THEN")
add("    tAcoustic_DiscrepTimer_B := tAcoustic_DiscrepTimer_B + tCycleTime_ms;")
add("ELSE")
add("    tAcoustic_DiscrepTimer_B := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rAcousticLeak_A_dB - rAcousticLeak_C_dB) > 10.0 THEN")
