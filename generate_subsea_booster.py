add("")
add("(* Calculate Voted Absolute Barrier Pressure *)")
add("IF NOT bBarrier_ChA_Fault AND NOT bBarrier_ChB_Fault AND NOT bBarrier_ChC_Fault THEN")
add("    IF (rBarrierOilPress_A_bar >= rBarrierOilPress_B_bar AND rBarrierOilPress_A_bar <= rBarrierOilPress_C_bar) OR")
