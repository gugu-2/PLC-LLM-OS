add("    tAcoustic_DiscrepTimer_C := T#0ms;")
add("END_IF;")
add("")
add("IF tAcoustic_DiscrepTimer_A > T#2000ms AND tAcoustic_DiscrepTimer_C > T#2000ms THEN")
add("    bAcoustic_ChA_Fault := TRUE;")
add("END_IF;")
add("IF tAcoustic_DiscrepTimer_A > T#2000ms AND tAcoustic_DiscrepTimer_B > T#2000ms THEN")
add("    bAcoustic_ChB_Fault := TRUE;")
add("END_IF;")
add("IF tAcoustic_DiscrepTimer_B > T#2000ms AND tAcoustic_DiscrepTimer_C > T#2000ms THEN")
add("    bAcoustic_ChC_Fault := TRUE;")
add("END_IF;")
add("")
add("(* High-value select for acoustic emission to guarantee prompt leak alert *)")
add("rVotedAcousticNoise_dB := rAcousticLeak_A_dB;")
add("IF NOT bAcoustic_ChB_Fault AND rAcousticLeak_B_dB > rVotedAcousticNoise_dB THEN")
add("    rVotedAcousticNoise_dB := rAcousticLeak_B_dB;")
