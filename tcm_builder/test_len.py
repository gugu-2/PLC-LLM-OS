    emit("(* Continuous Variable Crown (CVC) Intermediate Roll Profile Equivalent Crown *)")
    emit("rCVC_EquivalentCrown_S1_um := 4.0 * c_rCVC_Coeff_a3 * rIntermRollShift_S1_mm * (rNominalWidth_mm * rNominalWidth_mm * 0.25) * 1000.0;")
    emit("rCVC_EquivalentCrown_S5_um := 4.0 * c_rCVC_Coeff_a3 * rIntermRollShift_S5_mm * (rNominalWidth_mm * rNominalWidth_mm * 0.25) * 1000.0;")
    emit()

    emit("(* ==================================================================================================================== *)")
    emit("(* PHASE 3: ROLL ECCENTRICITY ACTIVE COMPENSATION (REC) HARMONIC FILTER                                                *)")
    emit("(* ==================================================================================================================== *)")
    emit()
    emit("(* Stand 1 Backup Roll Eccentricity Harmonic Extraction *)")
    emit("rStripSpeed_S1_mpm := (rRollSpeed_S1_RPM * 2.0 * 3.14159265 * (c_rWorkRollRadius_mm * 0.001)) * (1.0 + rForwardSlip_S1_pct * 0.01);")
    emit("rBUR_Angle_S1_rad := rBUR_Angle_S1_rad + (rStripSpeed_S1_mpm / (60.0 * (2.0 * c_rBackupRollRadius_mm * 0.001 * 3.14159265))) * 2.0 * 3.14159265 * c_rTs;")
    emit("IF rBUR_Angle_S1_rad >= 6.2831853 THEN")
    emit("    rBUR_Angle_S1_rad := rBUR_Angle_S1_rad - 6.2831853;")
    emit("END_IF;")
    emit("rREC_Cosine_Int_S1 := rREC_Cosine_Int_S1 * 0.998 + (rForceTotal_S1_kN - rBlandFordForce_S1_kN) * COS(rBUR_Angle_S1_rad) * 0.002;")
    emit("rREC_Sine_Int_S1   := rREC_Sine_Int_S1 * 0.998 + (rForceTotal_S1_kN - rBlandFordForce_S1_kN) * SIN(rBUR_Angle_S1_rad) * 0.002;")
    emit("rREC_Amplitude_S1_um := (2.0 / c_rModulus_S1_kNpmm) * SQRT(rREC_Cosine_Int_S1 * rREC_Cosine_Int_S1 + rREC_Sine_Int_S1 * rREC_Sine_Int_S1) * 1000.0;")
    emit("IF rREC_Amplitude_S1_um > 45.0 THEN rREC_Amplitude_S1_um := 45.0; END_IF;")
