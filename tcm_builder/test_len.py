    emit("        rHGC_Command_S2_WS_um := 4200.0;")
    emit("        rHGC_Command_S3_DS_um := 3900.0;")
    emit("        rHGC_Command_S3_WS_um := 3900.0;")
    emit("        rHGC_Command_S4_DS_um := 3600.0;")
    emit("        rHGC_Command_S4_WS_um := 3600.0;")
    emit("        rHGC_Command_S5_DS_um := 3200.0;")
    emit("        rHGC_Command_S5_WS_um := 3200.0;")
    emit("        rMotorSpeedRef_S1_RPM := 15.0; (* Crawl speed *)")
    emit("        rMotorSpeedRef_S2_RPM := 15.0;")
    emit("        rMotorSpeedRef_S3_RPM := 15.0;")
    emit("        rMotorSpeedRef_S4_RPM := 15.0;")
    emit("        rMotorSpeedRef_S5_RPM := 15.0;")
    emit("        IF bMillMasterRunPermissive AND bEmergencyStopCircuit_NC AND bSafetyGatesInterlocked_NC AND")
    emit("           (rCoilMandrelExpansionPress_bar >= 195.0) THEN")
    emit("            iFSM_State := 20; (* Proceed to Stand 1 Entry Threading *)")
    emit("            rFSM_StateTimer_s := 0.0;")
    emit("        END_IF;")
    emit()

    emit("    20: (* STATE_STAND1_ENTRY_THREAD_BITE: Stand 1 bite detection via roll separating force trigger *)")
    emit("        rHGC_Command_S1_DS_um := 2450.0; (* Pre-bite kissing gap *)")
    emit("        rHGC_Command_S1_WS_um := 2450.0;")
    emit("        rMotorSpeedRef_S1_RPM := 25.0;")
    emit("        bCoolantEmulsionFloodValveCmd := TRUE;")
    emit("        IF (rForceTotal_S1_kN >= 850.0) THEN")
    emit("            (* Metal In Stand 1 confirmed *)")
    emit("            rHGC_Command_S1_DS_um := 1850.0; (* Clamp to nominal gauge *)")
    emit("            rHGC_Command_S1_WS_um := 1850.0;")
    emit("            iFSM_State := 30; (* Proceed to Cascaded Threading *)")
    emit("            rFSM_StateTimer_s := 0.0;")
    emit("            iThreadStageIndex := 2;")
    emit("        ELSIF rFSM_StateTimer_s >= 45.0 THEN")
    emit("            (* Threading bite timeout *)")
    emit("            iFSM_State := 999;")
    emit("        END_IF;")
    emit()

    emit("    30: (* STATE_INTERSTAND_CASCADED_THREAD: Sequential bite pickup through Stands 2, 3, 4, 5 *)")
    emit("        IF iThreadStageIndex = 2 THEN")
    emit("            rHGC_Command_S2_DS_um := 1950.0;")
    emit("            rHGC_Command_S2_WS_um := 1950.0;")
    emit("            rMotorSpeedRef_S2_RPM := 35.0;")
    emit("            IF rForceTotal_S2_kN >= 900.0 THEN")
    emit("                rHGC_Command_S2_DS_um := 1520.0;")
    emit("                rHGC_Command_S2_WS_um := 1520.0;")
    emit("                iThreadStageIndex := 3;")
    emit("            END_IF;")
    emit("        ELSIF iThreadStageIndex = 3 THEN")
    emit("            rHGC_Command_S3_DS_um := 1600.0;")
    emit("            rHGC_Command_S3_WS_um := 1600.0;")
    emit("            rMotorSpeedRef_S3_RPM := 48.0;")
    emit("            IF rForceTotal_S3_kN >= 950.0 THEN")
    emit("                rHGC_Command_S3_DS_um := 1210.0;")
    emit("                rHGC_Command_S3_WS_um := 1210.0;")
    emit("                iThreadStageIndex := 4;")
    emit("            END_IF;")
    emit("        ELSIF iThreadStageIndex = 4 THEN")
    emit("            rHGC_Command_S4_DS_um := 1300.0;")
    emit("            rHGC_Command_S4_WS_um := 1300.0;")
    emit("            rMotorSpeedRef_S4_RPM := 65.0;")
    emit("            IF rForceTotal_S4_kN >= 1000.0 THEN")
    emit("                rHGC_Command_S4_DS_um := 980.0;")
    emit("                rHGC_Command_S4_WS_um := 980.0;")
    emit("                iThreadStageIndex := 5;")
    emit("            END_IF;")
    emit("        ELSIF iThreadStageIndex = 5 THEN")
    emit("            rHGC_Command_S5_DS_um := 1050.0;")
    emit("            rHGC_Command_S5_WS_um := 1050.0;")
    emit("            rMotorSpeedRef_S5_RPM := 88.0;")
    emit("            IF rForceTotal_S5_kN >= 900.0 THEN")
    emit("                rHGC_Command_S5_DS_um := 750.0;")
    emit("                rHGC_Command_S5_WS_um := 750.0;")
    emit("                iFSM_State := 40; (* Proceed to Tension Reel Wrapper Lock *)")
    emit("                rFSM_StateTimer_s := 0.0;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("        IF rFSM_StateTimer_s >= 60.0 THEN")
    emit("            iFSM_State := 999; (* Cascaded thread timeout trip *)")
    emit("        END_IF;")
    emit()

    emit("    40: (* STATE_STAND5_EXIT_REEL_WRAPPER: Belt wrapper clamping & coiling tension establishment *)")
    emit("        bTensionReelWrapperClampCmd := TRUE;")
    emit("        rMotorSpeedRef_S5_RPM := 100.0;")
    emit("        IF (rVotedTension_4_5_kN >= 120.0) AND (rExitReelMandrelExpansionPress_bar >= 230.0) THEN")
    emit("            bTensionReelWrapperClampCmd := FALSE; (* Retract wrapper *)")
    emit("            iFSM_State := 50; (* Accelerate Mill *)")
    emit("            rFSM_StateTimer_s := 0.0;")
    emit("        ELSIF rFSM_StateTimer_s >= 25.0 THEN")
    emit("            iFSM_State := 999; (* Wrapper lock failure *)")
    emit("        END_IF;")
    emit()

    emit("    50: (* STATE_MILL_ACCEL_HIGH_SPEED: Synchronized acceleration ramp to high speed 1250-1500 mpm *)")
    emit("        IF rMotorSpeedRef_S5_RPM < 835.0 THEN")
    emit("            rMotorSpeedRef_S1_RPM := rMotorSpeedRef_S1_RPM + 2.5 * c_rTs * 60.0;")
    emit("            rMotorSpeedRef_S2_RPM := rMotorSpeedRef_S2_RPM + 3.4 * c_rTs * 60.0;")
    emit("            rMotorSpeedRef_S3_RPM := rMotorSpeedRef_S3_RPM + 4.6 * c_rTs * 60.0;")
    emit("            rMotorSpeedRef_S4_RPM := rMotorSpeedRef_S4_RPM + 6.2 * c_rTs * 60.0;")
    emit("            rMotorSpeedRef_S5_RPM := rMotorSpeedRef_S5_RPM + 8.4 * c_rTs * 60.0;")
    emit("        ELSE")
    emit("            rMotorSpeedRef_S1_RPM := 248.5;")
    emit("            rMotorSpeedRef_S2_RPM := 335.2;")
    emit("            rMotorSpeedRef_S3_RPM := 452.8;")
    emit("            rMotorSpeedRef_S4_RPM := 615.4;")
    emit("            rMotorSpeedRef_S5_RPM := 835.0;")
    emit("            iFSM_State := 60; (* Closed-loop AGC & Flatness Hold *)")
    emit("            rFSM_StateTimer_s := 0.0;")
    emit("        END_IF;")
    emit()

