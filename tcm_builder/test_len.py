    emit("rBFE_DeltaH_S5 := (995.0 - rVotedExitThickness_um) * 0.001; (* mm *)")
    emit("IF rBFE_DeltaH_S5 < 0.05 THEN rBFE_DeltaH_S5 := 0.05; END_IF;")
    emit("rDeformedRadius_S5_mm := c_rWorkRollRadius_mm * (1.0 + (c_rHitchcockConstant * rForceTotal_S5_kN / (rNominalWidth_mm * rBFE_DeltaH_S5)));")
    emit("rTempCalc := SQRT(rBFE_DeltaH_S5 / (rVotedExitThickness_um * 0.001));")
    emit("rNeutralAngle_S5_rad := SQRT((rVotedExitThickness_um * 0.001) / rDeformedRadius_S5_mm) *")
    emit("    (0.5 * rTempCalc - (0.25 / rFrictionCoeff_S5) * ((-rTargetInterstandTension_4_5_MPa) / rYieldStress_S5_MPa));")
    emit("IF rNeutralAngle_S5_rad < 0.004 THEN rNeutralAngle_S5_rad := 0.004; END_IF;")
    emit("rForwardSlip_S5_pct := (rDeformedRadius_S5_mm / (rVotedExitThickness_um * 0.001)) * (rNeutralAngle_S5_rad * rNeutralAngle_S5_rad) * 100.0;")
    emit("rGaugemeterThick_S5_um := 0.5 * (rGapPos_S5_DS_um + rGapPos_S5_WS_um) +")
    emit("    ((rForceTotal_S5_kN - rNominalRollForce_Zero_S5_kN) / c_rModulus_S5_kNpmm) * 1000.0 + rREC_GapInjection_S5_um;")
    emit()

    emit("(* Exit Thickness Deviation Metrics *)")
    emit("rExitThicknessDeviation_um := rVotedExitThickness_um - rTargetExitThickness_um;")
    emit("rExitThicknessDeviation_Percent := (rExitThicknessDeviation_um / rTargetExitThickness_um) * 100.0;")
