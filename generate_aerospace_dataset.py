    # 10 Unrolled PGD Iterations
    for it in range(1, 11):
        a(f"(* --- PGD Iteration {it} of 10 --- *)")
        a(f"FOR idxRow := 1 TO 6 DO")
        a(f"    rScratch_SumAx := 0.0;")
        a(f"    rScratch_SumBu := 0.0;")
        a(f"    FOR idxCol := 1 TO 6 DO")
