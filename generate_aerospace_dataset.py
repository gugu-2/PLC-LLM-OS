    a("        rScratch_SumL  := rScratch_SumL  + (matL_Kalman[idxRow, idxCol] * arrInnov[idxCol]);")
    a("    END_FOR;")
    a("    FOR idxCol := 1 TO 5 DO")
    a("        rScratch_SumBu := rScratch_SumBu + (matB[idxRow, idxCol] * arrInputU[idxCol]);")
    a("    END_FOR;")
    a("    arrStateX_Next[idxRow] := rScratch_SumAx + rScratch_SumBu + rScratch_SumL;")
    a("END_FOR;")
    a("")
    a("FOR idxRow := 1 TO 6 DO")
    a("    arrStateX_Hat[idxRow] := arrStateX_Next[idxRow];")
    a("END_FOR;")
    a("")
    a("rEst_RCSManifoldPressure_bar := arrStateX_Hat[4];")
    a("")
    a("(* 3.2 GNC Attitude Torque Allocation to 6 Thruster Channels *)")
    a("arrTorqueCmd[1] := rGNC_TorqueCmd_Roll_Nm;")
    a("arrTorqueCmd[2] := rGNC_TorqueCmd_Pitch_Nm;")
    a("arrTorqueCmd[3] := rGNC_TorqueCmd_Yaw_Nm;")
    a("")
    a("FOR idxThruster := 1 TO 6 DO")
    a("    arrThrusterDemand[idxThruster] := 0.0;")
    a("    FOR idxAxis := 1 TO 3 DO")
    a("        arrThrusterDemand[idxThruster] := arrThrusterDemand[idxThruster] + ")
