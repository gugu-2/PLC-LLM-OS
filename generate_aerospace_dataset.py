    a("        (arrStateX_Hat[idxRow] - arrStateX_Ref[idxRow]) * (arrStateX_Hat[idxRow] - arrStateX_Ref[idxRow]));")
    a("END_FOR;")
    a("FOR idxCol := 1 TO 5 DO")
    a("    rMpcTotalCost := rMpcTotalCost + (matR[idxCol, idxCol] * ")
    a("        (arrInputU[idxCol] - arrInputU_Ref[idxCol]) * (arrInputU[idxCol] - arrInputU_Ref[idxCol]));")
    a("END_FOR;")
    a("")
    a("(* ============================================================================================================= *)")
