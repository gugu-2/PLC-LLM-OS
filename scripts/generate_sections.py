# scripts/generate_sections.py
"""
Generates specific code sections for FB_Water_Desalination_SWRO_EnergyRecovery_PX
"""

def generate_phase0_and_phase1():
    lines = []
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 0: SYSTEM INITIALIZATION, PHYSICAL CONSTANTS & SAFETY PERMISSIVE AUDIT                         *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("IF NOT bEnable THEN")
    lines.append("    rCmd_HpPumpSpeed_rpm        := 0.0;")
    lines.append("    rCmd_BoosterSpeed_rpm       := 0.0;")
    lines.append("    rCmd_BrineValve_pct         := 0.0;")
    lines.append("    rCmd_AntiscalantDosing_pct  := 0.0;")
    lines.append("    rCmd_DivertValve_pct        := 100.0; (* Failsafe Diverted to Sea Outfall *)")
    lines.append("    rCmd_LpFlushValve_pct       := 0.0;")
    lines.append("    rCmd_SbsDosing_pct          := 0.0;")
    lines.append("    rCmd_CipCirculationPump_pct := 0.0;")
    lines.append("    bTrainRunning               := FALSE;")
    lines.append("    bMpcActive                  := FALSE;")
    lines.append("    iCurrentState               := 0;")
    lines.append("    sCurrentStateName           := 'SWRO_TRAIN_STANDBY_AND_INSTRUMENT_LOCK';")
    lines.append("    RETURN;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* ASTM D4516 Seawater Feed Temperature Correction Factor (TCF) Calculation *)")
    lines.append("(* TCF accounts for membrane polymer compaction and feed water viscosity variations relative to 25.0 [deg C] *)")
    lines.append("IF rFeedTemp_degC >= 25.0 THEN")
    lines.append("    rTempCorrectionFactor_TCF := EXP(0.0265 * (rFeedTemp_degC - 25.0));")
    lines.append("ELSE")
    lines.append("    rTempCorrectionFactor_TCF := EXP(0.0315 * (rFeedTemp_degC - 25.0));")
    lines.append("END_IF;")
    lines.append("IF rTempCorrectionFactor_TCF < 0.50 THEN")
    lines.append("    rTempCorrectionFactor_TCF := 0.50;")
    lines.append("ELSIF rTempCorrectionFactor_TCF > 1.85 THEN")
    lines.append("    rTempCorrectionFactor_TCF := 1.85;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* van 't Hoff Theoretical Osmotic Pressure of Raw Seawater Feed Stream *)")
    lines.append("(* Pi_feed [bar] = rho_sw * R * (T + 273.15) * Sum(mi) approx rFeedOsmoticCoeff * Salinity_gL *)")
    lines.append("rCalc_OsmoticPress_Feed_bar := rFeedSalinity_TDS_gL * rFeedOsmoticCoeff * ( (rFeedTemp_degC + 273.15) / 298.15 );")
    lines.append("IF rCalc_OsmoticPress_Feed_bar < 15.0 THEN")
    lines.append("    rCalc_OsmoticPress_Feed_bar := 15.0; (* Standard Seawater Lower Bound Guard *)")
    lines.append("ELSIF rCalc_OsmoticPress_Feed_bar > 45.0 THEN")
    lines.append("    rCalc_OsmoticPress_Feed_bar := 45.0; (* Extreme Red Sea / Arabian Gulf Upper Bound *)")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 1: 2oo3 TRIPLE MODULAR REDUNDANCY (TMR) SENSOR VOTING SUITE WITH DISCREPANCY TIMERS           *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("")
    
    # Generate Voting for the 5 channels
    channels = [
        ("Ch1", "PT101", "FeedPress", "bar", "rFeedPress_PT101A_bar", "rFeedPress_PT101B_bar", "rFeedPress_PT101C_bar", "0.0", "100.0", "65.0", "High-Pressure Feed Pressure Transmitters"),
        ("Ch2", "FT201", "PermFlow", "m3h", "rPermFlow_FT201A_m3h", "rPermFlow_FT201B_m3h", "rPermFlow_FT201C_m3h", "0.0", "3000.0", "1812.5", "Permeate Coriolis Mass Flowmeters"),
        ("Ch3", "PT301", "BrinePress", "bar", "rBrinePress_PT301A_bar", "rBrinePress_PT301B_bar", "rBrinePress_PT301C_bar", "0.0", "100.0", "63.5", "High-Pressure Brine Concentrate Return Pressure Transmitters"),
        ("Ch4", "AT401", "PermTds", "uS", "rPermTds_AT401A_uS", "rPermTds_AT401B_uS", "rPermTds_AT401C_uS", "0.0", "2000.0", "250.0", "Permeate Toroidal Conductivity Analyzers"),
        ("Ch5", "ST501", "PxSpeed", "rpm", "rPxSpeed_ST501A_rpm", "rPxSpeed_ST501B_rpm", "rPxSpeed_ST501C_rpm", "0.0", "2500.0", "1150.0", "Isobaric Energy Recovery Rotor Magnetic Speed Pickups")
    ]
    
    for ch_id, tag, var_name, unit, in_a, in_b, in_c, min_val, max_val, default_val, desc in channels:
        lines.append(f"(* --- 2oo3 TMR VOTING: {desc} ({tag}A/B/C) [{unit}] --- *)")
        lines.append(f"(* Range & Hardware Integrity Sanity Validation *)")
        lines.append(f"IF ({in_a} < {min_val}) OR ({in_a} > {max_val}) THEN b{ch_id}_Fault_A := TRUE; END_IF;")
        lines.append(f"IF ({in_b} < {min_val}) OR ({in_b} > {max_val}) THEN b{ch_id}_Fault_B := TRUE; END_IF;")
        lines.append(f"IF ({in_c} < {min_val}) OR ({in_c} > {max_val}) THEN b{ch_id}_Fault_C := TRUE; END_IF;")
        lines.append("")
        lines.append(f"(* Pairwise Discrepancy Evaluation *)")
        lines.append(f"IF ABS({in_a} - {in_b}) > r{ch_id}_Tol_{unit} THEN")
        lines.append(f"    r{ch_id}_Timer_AB_s := r{ch_id}_Timer_AB_s + rCycleTime_Ts_s;")
        lines.append(f"ELSE")
        lines.append(f"    r{ch_id}_Timer_AB_s := MAX(0.0, r{ch_id}_Timer_AB_s - (2.0 * rCycleTime_Ts_s));")
        lines.append(f"END_IF;")
        lines.append(f"IF ABS({in_b} - {in_c}) > r{ch_id}_Tol_{unit} THEN")
        lines.append(f"    r{ch_id}_Timer_BC_s := r{ch_id}_Timer_BC_s + rCycleTime_Ts_s;")
        lines.append(f"ELSE")
        lines.append(f"    r{ch_id}_Timer_BC_s := MAX(0.0, r{ch_id}_Timer_BC_s - (2.0 * rCycleTime_Ts_s));")
        lines.append(f"END_IF;")
        lines.append(f"IF ABS({in_c} - {in_a}) > r{ch_id}_Tol_{unit} THEN")
        lines.append(f"    r{ch_id}_Timer_CA_s := r{ch_id}_Timer_CA_s + rCycleTime_Ts_s;")
        lines.append(f"ELSE")
        lines.append(f"    r{ch_id}_Timer_CA_s := MAX(0.0, r{ch_id}_Timer_CA_s - (2.0 * rCycleTime_Ts_s));")
        lines.append(f"END_IF;")
        lines.append("")
        lines.append(f"(* Discrepancy Persistence Latching (200 [ms] Continuous Threshold) *)")
        lines.append(f"IF (r{ch_id}_Timer_AB_s >= 0.200) AND (r{ch_id}_Timer_CA_s >= 0.200) THEN")
        lines.append(f"    b{ch_id}_Fault_A := TRUE; (* Transmitter A Discrepant with both B and C *)")
        lines.append(f"END_IF;")
        lines.append(f"IF (r{ch_id}_Timer_AB_s >= 0.200) AND (r{ch_id}_Timer_BC_s >= 0.200) THEN")
        lines.append(f"    b{ch_id}_Fault_B := TRUE; (* Transmitter B Discrepant with both A and C *)")
        lines.append(f"END_IF;")
        lines.append(f"IF (r{ch_id}_Timer_BC_s >= 0.200) AND (r{ch_id}_Timer_CA_s >= 0.200) THEN")
        lines.append(f"    b{ch_id}_Fault_C := TRUE; (* Transmitter C Discrepant with both A and B *)")
        lines.append(f"END_IF;")
        lines.append("")
        lines.append(f"(* Fault Reset Latch Clearing on Operator Demand *)")
        lines.append(f"IF bFaultReset THEN")
        lines.append(f"    IF ({in_a} >= {min_val}) AND ({in_a} <= {max_val}) AND (r{ch_id}_Timer_AB_s < 0.05) AND (r{ch_id}_Timer_CA_s < 0.05) THEN")
        lines.append(f"        b{ch_id}_Fault_A := FALSE;")
        lines.append(f"    END_IF;")
        lines.append(f"    IF ({in_b} >= {min_val}) AND ({in_b} <= {max_val}) AND (r{ch_id}_Timer_AB_s < 0.05) AND (r{ch_id}_Timer_BC_s < 0.05) THEN")
        lines.append(f"        b{ch_id}_Fault_B := FALSE;")
        lines.append(f"    END_IF;")
        lines.append(f"    IF ({in_c} >= {min_val}) AND ({in_c} <= {max_val}) AND (r{ch_id}_Timer_BC_s < 0.05) AND (r{ch_id}_Timer_CA_s < 0.05) THEN")
        lines.append(f"        b{ch_id}_Fault_C := FALSE;")
        lines.append(f"    END_IF;")
        lines.append(f"END_IF;")
        lines.append("")
        lines.append(f"(* 2oo3 Voting & Bumpless Degradation Logic *)")
        lines.append(f"IF (NOT b{ch_id}_Fault_A) AND (NOT b{ch_id}_Fault_B) AND (NOT b{ch_id}_Fault_C) THEN")
        lines.append(f"    (* All 3 Sensors Healthy: True Mid-Value Median Selection *)")
        lines.append(f"    b{ch_id}_Degraded := FALSE;")
        lines.append(f"    b{ch_id}_Failover := FALSE;")
        lines.append(f"    IF (({in_a} >= {in_b}) AND ({in_a} <= {in_c})) OR (({in_a} >= {in_c}) AND ({in_a} <= {in_b})) THEN")
        lines.append(f"        rVoted_{var_name}_{unit} := {in_a};")
        lines.append(f"    ELSIF (({in_b} >= {in_a}) AND ({in_b} <= {in_c})) OR (({in_b} >= {in_c}) AND ({in_b} <= {in_a})) THEN")
        lines.append(f"        rVoted_{var_name}_{unit} := {in_b};")
        lines.append(f"    ELSE")
        lines.append(f"        rVoted_{var_name}_{unit} := {in_c};")
        lines.append(f"    END_IF;")
        lines.append(f"    r{ch_id}_LastGood_{unit} := rVoted_{var_name}_{unit};")
        lines.append(f"ELSIF (NOT b{ch_id}_Fault_A) AND (NOT b{ch_id}_Fault_B) AND b{ch_id}_Fault_C THEN")
        lines.append(f"    (* Degradation Mode 1: Sensor C Faulted, Mean of Healthy A and B *)")
        lines.append(f"    b{ch_id}_Degraded := TRUE;")
        lines.append(f"    b{ch_id}_Failover := FALSE;")
        lines.append(f"    rVoted_{var_name}_{unit} := 0.5 * ({in_a} + {in_b});")
        lines.append(f"    r{ch_id}_LastGood_{unit} := rVoted_{var_name}_{unit};")
        lines.append(f"ELSIF (NOT b{ch_id}_Fault_B) AND (NOT b{ch_id}_Fault_C) AND b{ch_id}_Fault_A THEN")
        lines.append(f"    (* Degradation Mode 1: Sensor A Faulted, Mean of Healthy B and C *)")
        lines.append(f"    b{ch_id}_Degraded := TRUE;")
        lines.append(f"    b{ch_id}_Failover := FALSE;")
        lines.append(f"    rVoted_{var_name}_{unit} := 0.5 * ({in_b} + {in_c});")
        lines.append(f"    r{ch_id}_LastGood_{unit} := rVoted_{var_name}_{unit};")
        lines.append(f"ELSIF (NOT b{ch_id}_Fault_A) AND (NOT b{ch_id}_Fault_C) AND b{ch_id}_Fault_B THEN")
        lines.append(f"    (* Degradation Mode 1: Sensor B Faulted, Mean of Healthy A and C *)")
        lines.append(f"    b{ch_id}_Degraded := TRUE;")
        lines.append(f"    b{ch_id}_Failover := FALSE;")
        lines.append(f"    rVoted_{var_name}_{unit} := 0.5 * ({in_a} + {in_c});")
        lines.append(f"    r{ch_id}_LastGood_{unit} := rVoted_{var_name}_{unit};")
        lines.append(f"ELSIF (NOT b{ch_id}_Fault_A) AND b{ch_id}_Fault_B AND b{ch_id}_Fault_C THEN")
        lines.append(f"    (* Degradation Mode 2: Sensors B and C Faulted, Single Healthy Sensor A *)")
        lines.append(f"    b{ch_id}_Degraded := TRUE;")
        lines.append(f"    b{ch_id}_Failover := FALSE;")
        lines.append(f"    rVoted_{var_name}_{unit} := {in_a};")
        lines.append(f"    r{ch_id}_LastGood_{unit} := rVoted_{var_name}_{unit};")
        lines.append(f"ELSIF (NOT b{ch_id}_Fault_B) AND b{ch_id}_Fault_A AND b{ch_id}_Fault_C THEN")
        lines.append(f"    (* Degradation Mode 2: Sensors A and C Faulted, Single Healthy Sensor B *)")
        lines.append(f"    b{ch_id}_Degraded := TRUE;")
        lines.append(f"    b{ch_id}_Failover := FALSE;")
        lines.append(f"    rVoted_{var_name}_{unit} := {in_b};")
        lines.append(f"    r{ch_id}_LastGood_{unit} := rVoted_{var_name}_{unit};")
        lines.append(f"ELSIF (NOT b{ch_id}_Fault_C) AND b{ch_id}_Fault_A AND b{ch_id}_Fault_B THEN")
        lines.append(f"    (* Degradation Mode 2: Sensors A and B Faulted, Single Healthy Sensor C *)")
        lines.append(f"    b{ch_id}_Degraded := TRUE;")
        lines.append(f"    b{ch_id}_Failover := FALSE;")
        lines.append(f"    rVoted_{var_name}_{unit} := {in_c};")
        lines.append(f"    r{ch_id}_LastGood_{unit} := rVoted_{var_name}_{unit};")
        lines.append(f"ELSE")
        lines.append(f"    (* Critical Failover: All 3 Sensors Faulted, Hold Last Valid Process Value *)")
        lines.append(f"    b{ch_id}_Degraded := TRUE;")
        lines.append(f"    b{ch_id}_Failover := TRUE;")
        lines.append(f"    rVoted_{var_name}_{unit} := r{ch_id}_LastGood_{unit};")
        lines.append(f"END_IF;")
        lines.append("")
    
    return "\n".join(lines)

if __name__ == "__main__":
    t = generate_phase0_and_phase1()
    print("Phase 0 and 1 length:", len(t))
