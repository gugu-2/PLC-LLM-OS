# scripts/generate_fsm_and_alarms.py
"""
Generates Phase 4 (14-Stage FSM) and Phase 5 (ISA-18.2 Alarms & Bit-Packed Telemetry)
"""

def build_phase4():
    lines = []
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 4: DETERMINISTIC 14-STAGE SWRO PRODUCTION FINITE STATE MACHINE (FSM, STATES 0 TO 13)         *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("IF eState <> ePrevState THEN")
    lines.append("    bStateFirstScan := TRUE;")
    lines.append("    rInternalStateTimer_s := 0.0;")
    lines.append("    ePrevState := eState;")
    lines.append("ELSE")
    lines.append("    bStateFirstScan := FALSE;")
    lines.append("    rInternalStateTimer_s := rInternalStateTimer_s + rCycleTime_Ts_s;")
    lines.append("END_IF;")
    lines.append("rStateTimer_s := rInternalStateTimer_s;")
    lines.append("iCurrentState := eState;")
    lines.append("")
    lines.append("CASE eState OF")
    
    # State 0
    lines.append("    0: (* SWRO_TRAIN_STANDBY_AND_INSTRUMENT_LOCK *)")
    lines.append("        sCurrentStateName := 'STANDBY_AND_INSTRUMENT_LOCK';")
    lines.append("        bTrainRunning     := FALSE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* Standby Actuator Commanded Profile *)")
    lines.append("        rCmd_HpPumpSpeed_rpm        := 0.0;")
    lines.append("        rCmd_BoosterSpeed_rpm       := 0.0;")
    lines.append("        rCmd_BrineValve_pct         := 0.0;")
    lines.append("        rCmd_AntiscalantDosing_pct  := 0.0;")
    lines.append("        rCmd_DivertValve_pct        := 100.0; (* Diverted to Sea Outfall *)")
    lines.append("        rCmd_LpFlushValve_pct       := 0.0;")
    lines.append("        rCmd_SbsDosing_pct          := 0.0;")
    lines.append("        rCmd_CipCirculationPump_pct := 0.0;")
    lines.append("        ")
    lines.append("        (* Permissive Check & Transition to Stage 1 *)")
    lines.append("        bStateTransitionPermissive := (NOT bEmergencyStop) AND (NOT bEmergencyTripLatched) AND ")
    lines.append("                                      (NOT bHighPressureVfdFault) AND (NOT bBoosterVfdFault) AND ")
    lines.append("                                      bSeawaterIntakeReady AND bPermeateTankPermissive AND ")
    lines.append("                                      (NOT bCh1_Failover) AND (NOT bCh3_Failover);")
    lines.append("        ")
    lines.append("        IF bAutoCycleStart AND bStateTransitionPermissive THEN")
    lines.append("            eState := 1; (* Advance to Low-Pressure De-aeration & Flush *)")
    lines.append("        ELSIF bCipPermissive THEN")
    lines.append("            eState := 11; (* Jump to Clean-In-Place Sequence *)")
    lines.append("        ELSIF bPreservativeFlushPermissive THEN")
    lines.append("            eState := 12; (* Jump to SBS Preservative Flush & Seal *)")
    lines.append("        END_IF;")
    lines.append("")

    # State 1
    lines.append("    1: (* LOW_PRESSURE_DE-AERATION_AND_FLUSH_RUN *)")
    lines.append("        sCurrentStateName := 'LP_DE-AERATION_AND_FLUSH';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* Flush Actuator Profile: Fill Vessels & Lubricate PX Ceramic Bearings *)")
    lines.append("        rCmd_HpPumpSpeed_rpm        := 0.0;")
    lines.append("        rCmd_BoosterSpeed_rpm       := 0.0;")
    lines.append("        rCmd_BrineValve_pct         := 100.0; (* Fully Open Brine Valve to Displace Air *)")
    lines.append("        rCmd_AntiscalantDosing_pct  := 0.0;")
    lines.append("        rCmd_DivertValve_pct        := 100.0; (* Dump to Outfall *)")
    lines.append("        rCmd_LpFlushValve_pct       := 100.0; (* Open Low-Pressure Supply Line *)")
    lines.append("        rCmd_SbsDosing_pct          := 0.0;")
    lines.append("        rCmd_CipCirculationPump_pct := 0.0;")
    lines.append("        ")
    lines.append("        rDeAerationFlushTimer_s := rInternalStateTimer_s;")
    lines.append("        (* Verify Flush Duration (45.0 s) and Feed Manifold Pressurization (2.0 to 4.5 bar) *)")
    lines.append("        IF (rDeAerationFlushTimer_s >= 45.0) AND (rVoted_FeedPress_bar >= 2.0) THEN")
    lines.append("            eState := 2; (* Advance to Chemical Pretreatment Prime *)")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 2
    lines.append("    2: (* ANTISCALANT_AND_SODIUM_BISULFITE_PRIME *)")
    lines.append("        sCurrentStateName := 'CHEMICAL_DOSING_PRIME';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* Start Dosing Pumps to Establish Protective Chemical Boundary *)")
    lines.append("        rCmd_HpPumpSpeed_rpm        := 0.0;")
    lines.append("        rCmd_BoosterSpeed_rpm       := 0.0;")
    lines.append("        rCmd_BrineValve_pct         := 100.0;")
    lines.append("        rCmd_AntiscalantDosing_pct  := 65.0; (* Phosphonate/Polyacrylate Scale Inhibitor *)")
    lines.append("        rCmd_DivertValve_pct        := 100.0;")
    lines.append("        rCmd_LpFlushValve_pct       := 100.0;")
    lines.append("        rCmd_SbsDosing_pct          := 55.0; (* Sodium Bisulfite for Dechlorination *)")
    lines.append("        rCmd_CipCirculationPump_pct := 0.0;")
    lines.append("        ")
    lines.append("        rAntiscalantPrimeTimer_s := rInternalStateTimer_s;")
    lines.append("        (* Confirm Dosing Line Primed (25.0 s) and ORP Scavenging Active (< 240 mV) *)")
    lines.append("        IF (rAntiscalantPrimeTimer_s >= 25.0) AND (rFeedORP_mV < 240.0) THEN")
    lines.append("            eState := 3; (* Advance to Main HP Pump VFD Soft Start *)")
    lines.append("        ELSIF (rAntiscalantPrimeTimer_s >= 60.0) AND (rFeedORP_mV >= 240.0) THEN")
    lines.append("            (* Free Chlorine Oxidation Threat: Abort to Standby *)")
    lines.append("            eState := 0;")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 3
    lines.append("    3: (* HP_PUMP_VARIABLE_FREQUENCY_SOFT_START *)")
    lines.append("        sCurrentStateName := 'HP_PUMP_VFD_SOFT_START';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* Close Low Pressure Flush Line and Ramp Primary Feed Pump *)")
    lines.append("        rCmd_LpFlushValve_pct      := 0.0;")
    lines.append("        rCmd_AntiscalantDosing_pct := 65.0;")
    lines.append("        rCmd_SbsDosing_pct         := 55.0;")
    lines.append("        rCmd_BrineValve_pct        := 85.0; (* Relieve Starting Head *)")
    lines.append("        rCmd_DivertValve_pct       := 100.0;")
    lines.append("        ")
    lines.append("        rSoftStartRampTimer_s := rInternalStateTimer_s;")
    lines.append("        (* Ramp HP Pump Speed from 0 to 1250 rpm at Controlled 50 rpm/s *)")
    lines.append("        rCmd_HpPumpSpeed_rpm := MIN(1250.0, rSoftStartRampTimer_s * 50.0);")
    lines.append("        rCmd_BoosterSpeed_rpm := 0.0;")
    lines.append("        ")
    lines.append("        (* Verify Suction Pressure Permissive PT001 >= 1.8 bar *)")
    lines.append("        IF rSuctionPress_PT001_bar < 1.8 THEN")
    lines.append("            eState := 13; (* Cavitation Danger Trip *)")
    lines.append("        ELSIF (rCmd_HpPumpSpeed_rpm >= 1250.0) AND (rVoted_FeedPress_bar >= 24.0) THEN")
    lines.append("            eState := 4; (* Advance to PX Rotor Spinup & Fill *)")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 4
    lines.append("    4: (* PX_ISOBARIC_ROTOR_SPINUP_AND_FILL *)")
    lines.append("        sCurrentStateName := 'PX_ROTOR_SPINUP_AND_FILL';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        rPxRotorSpinupTimer_s := rInternalStateTimer_s;")
    lines.append("        rCmd_HpPumpSpeed_rpm  := 1250.0;")
    lines.append("        (* Soft Start PX Booster Pump VFD up to 750 rpm to Circulate Lubrication Stream *)")
    lines.append("        rCmd_BoosterSpeed_rpm := MIN(750.0, rPxRotorSpinupTimer_s * 40.0);")
    lines.append("        rCmd_BrineValve_pct   := 75.0;")
    lines.append("        rCmd_DivertValve_pct  := 100.0;")
    lines.append("        ")
    lines.append("        (* Check Ceramic Rotor Speed ST501 >= 450 rpm and Booster Discharge PT002 >= 22 bar *)")
    lines.append("        IF (rPxRotorSpinupTimer_s >= 20.0) AND (rVoted_PxSpeed_rpm >= 450.0) AND (rBoosterDischarge_PT002_bar >= 22.0) THEN")
    lines.append("            eState := 5; (* Advance to Controlled Membrane Pressure Rampup *)")
    lines.append("        ELSIF (rPxRotorSpinupTimer_s >= 45.0) AND (rVoted_PxSpeed_rpm < 300.0) THEN")
    lines.append("            (* PX Rotor Ceramic Stall Detected *)")
    lines.append("            bPxStallDetected := TRUE;")
    lines.append("            eState := 13;")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 5
    lines.append("    5: (* MEMBRANE_PRESSURE_RAMPUP (Controlled <= 1.5 bar/s to 65.0 bar) *)")
    lines.append("        sCurrentStateName := 'MEMBRANE_PRESSURE_RAMPUP';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        rPressureRampTimer_s := rInternalStateTimer_s;")
    lines.append("        (* Synchronous Closed-Loop Ramp of HP Pump VFD and Booster VFD *)")
    lines.append("        (* Ramp Rate strictly limited to 1.25 bar/s to prevent polyamide leaf compaction shock *)")
    lines.append("        rCmd_HpPumpSpeed_rpm := MIN(2150.0, 1250.0 + (rPressureRampTimer_s * 25.0));")
    lines.append("        rCmd_BoosterSpeed_rpm := MIN(1850.0, 750.0 + (rPressureRampTimer_s * 30.0));")
    lines.append("        rCmd_BrineValve_pct := MAX(45.0, 75.0 - (rPressureRampTimer_s * 0.75));")
    lines.append("        rCmd_DivertValve_pct := 100.0;")
    lines.append("        ")
    lines.append("        (* Monitor Membrane Differential Pressure: Must Remain <= 2.2 bar during ramp *)")
    lines.append("        IF rCalc_MembraneDiffPress_bar > 2.50 THEN")
    lines.append("            rCmd_BrineValve_pct := rCmd_BrineValve_pct + 10.0; (* Fast Pressure Relief Trim *)")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        (* Target Transition Conditions: Feed Pressure >= 63.5 bar and Stable *)")
    lines.append("        IF (rVoted_FeedPress_bar >= 63.5) AND (rPressureRampTimer_s >= 40.0) THEN")
    lines.append("            eState := 6; (* Advance to Full Desalination MPC Optimization *)")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 6
    lines.append("    6: (* FULL_DESALINATION_OPTIMAL_ENERGY_MPC_RUN *)")
    lines.append("        sCurrentStateName := 'OPTIMAL_ENERGY_MPC_RUN';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := NOT bMpcManualOverride;")
    lines.append("        ")
    lines.append("        (* Check Permeate Quality Specification *)")
    lines.append("        bPermeateInSpec := (rVoted_PermTds_uS <= rMaxPermTds_Limit_uS) AND (rVoted_PermTds_uS >= 30.0);")
    lines.append("        IF bPermeateInSpec THEN")
    lines.append("            rCmd_DivertValve_pct := 0.0; (* Permeate Routed to Potable Drinking Water Header *)")
    lines.append("            bPermeateDiverted := FALSE;")
    lines.append("        ELSE")
    lines.append("            rCmd_DivertValve_pct := 100.0; (* Off-Spec Water Dumped to Outfall *)")
    lines.append("            bPermeateDiverted := TRUE;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        (* Assign Control Actions from Receding-Horizon MPC Optimization (Stage 0) *)")
    lines.append("        IF bMpcActive THEN")
    lines.append("            rCmd_HpPumpSpeed_rpm       := rU_cand[0,1];")
    lines.append("            rCmd_BoosterSpeed_rpm      := rU_cand[0,2];")
    lines.append("            rCmd_BrineValve_pct        := rU_cand[0,3];")
    lines.append("            rCmd_AntiscalantDosing_pct := rU_cand[0,4];")
    lines.append("            rCmd_LpFlushValve_pct      := 0.0;")
    lines.append("        ELSE")
    lines.append("            (* Operator Manual Actuator Override *)")
    lines.append("            rCmd_HpPumpSpeed_rpm       := rManual_HpPumpSpeed_rpm;")
    lines.append("            rCmd_BoosterSpeed_rpm      := rManual_BoosterSpeed_rpm;")
    lines.append("            rCmd_BrineValve_pct        := rManual_BrineValve_pct;")
    lines.append("            rCmd_AntiscalantDosing_pct := rManual_Antiscalant_pct;")
    lines.append("            rCmd_DivertValve_pct       := rManual_DivertValve_pct;")
    lines.append("            rCmd_LpFlushValve_pct      := rManual_FlushValve_pct;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        (* Dynamic Operational Branching *)")
    lines.append("        IF rVoted_PermTds_uS > rMaxPermTds_Limit_uS THEN")
    lines.append("            eState := 9; (* Divert to Off-Spec Permeate Purge *)")
    lines.append("        ELSIF rFeedSalinity_TDS_gL > 41.5 THEN")
    lines.append("            eState := 7; (* Intake Salinity Spike Compensation *)")
    lines.append("        ELSIF (rCalc_MembraneFoulingIndex_pct > 22.0) AND (rInternalStateTimer_s > 300.0) THEN")
    lines.append("            eState := 8; (* ASTM Fouling Audit & Normalization *)")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 7
    lines.append("    7: (* SALINITY_SPIKE_RECOVERY_RATIO_TRIM *)")
    lines.append("        sCurrentStateName := 'SALINITY_SPIKE_RECOVERY_TRIM';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := TRUE;")
    lines.append("        bPermeateDiverted := FALSE;")
    lines.append("        ")
    lines.append("        rSalinityTrimTimer_s := rInternalStateTimer_s;")
    lines.append("        (* Trim Target Recovery Ratio Down from 45% to 38% to Alleviate Osmotic Backpressure *)")
    lines.append("        rCmd_BrineValve_pct        := MIN(65.0, rU_cand[0,3] + 12.0);")
    lines.append("        rCmd_AntiscalantDosing_pct := 85.0; (* Boost Scale Inhibitor Dosing *)")
    lines.append("        rCmd_HpPumpSpeed_rpm       := rU_cand[0,1];")
    lines.append("        rCmd_BoosterSpeed_rpm      := rU_cand[0,2];")
    lines.append("        rCmd_DivertValve_pct       := 0.0;")
    lines.append("        ")
    lines.append("        (* Return to Standard MPC Run once Salinity Settles Below 39.5 g/L for 90 s *)")
    lines.append("        IF (rFeedSalinity_TDS_gL <= 39.5) AND (rSalinityTrimTimer_s >= 90.0) THEN")
    lines.append("            eState := 6;")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 8
    lines.append("    8: (* FLUX_NORMALIZATION_AND_FOULING_LOG *)")
    lines.append("        sCurrentStateName := 'FLUX_NORMALIZATION_AND_FOULING';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := TRUE;")
    lines.append("        ")
    lines.append("        (* Maintain Current Production while Executing ASTM D4516 Mathematical Normalization *)")
    lines.append("        rCmd_HpPumpSpeed_rpm       := rU_cand[0,1];")
    lines.append("        rCmd_BoosterSpeed_rpm      := rU_cand[0,2];")
    lines.append("        rCmd_BrineValve_pct        := rU_cand[0,3];")
    lines.append("        rCmd_AntiscalantDosing_pct := rU_cand[0,4];")
    lines.append("        ")
    lines.append("        (* Log Normalized Metrics and Return to Active Run *)")
    lines.append("        IF rInternalStateTimer_s >= 10.0 THEN")
    lines.append("            eState := 6;")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 9
    lines.append("    9: (* OFF_SPEC_PERMEATE_AUTOMATIC_DIVERT *)")
    lines.append("        sCurrentStateName := 'OFF_SPEC_PERMEATE_DIVERT';")
    lines.append("        bTrainRunning     := TRUE;")
    lines.append("        bMpcActive        := TRUE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* High-Speed Divert Valve Snaps to Dump in < 1.0 s *)")
    lines.append("        rCmd_DivertValve_pct       := 100.0;")
    lines.append("        rCmd_AntiscalantDosing_pct := 75.0;")
    lines.append("        rCmd_HpPumpSpeed_rpm       := rU_cand[0,1];")
    lines.append("        rCmd_BoosterSpeed_rpm      := rU_cand[0,2];")
    lines.append("        rCmd_BrineValve_pct        := rU_cand[0,3];")
    lines.append("        ")
    lines.append("        (* Confirm Permeate Conductivity Recovers Below Target for 30.0 Continuous Seconds *)")
    lines.append("        IF (rVoted_PermTds_uS <= (rMaxPermTds_Limit_uS - 25.0)) AND (rInternalStateTimer_s >= 30.0) THEN")
    lines.append("            eState := 6; (* Restore Distribution to Potable Drinking Water Header *)")
    lines.append("        END_IF;")
    lines.append("        IF bTrainStop THEN eState := 10; END_IF;")
    lines.append("")

    # State 10
    lines.append("    10: (* LOW_PRESSURE_PRODUCT_WATER_DISPLACEMENT *)")
    lines.append("        sCurrentStateName := 'LP_PRODUCT_DISPLACEMENT';")
    lines.append("        bTrainRunning     := FALSE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* Controlled Deceleration of High-Pressure Drives *)")
    lines.append("        rDisplacementFlushTimer_s := rInternalStateTimer_s;")
    lines.append("        rCmd_HpPumpSpeed_rpm      := MAX(0.0, 1250.0 - (rDisplacementFlushTimer_s * 50.0));")
    lines.append("        rCmd_BoosterSpeed_rpm     := MAX(0.0, 750.0 - (rDisplacementFlushTimer_s * 40.0));")
    lines.append("        rCmd_BrineValve_pct       := 100.0; (* Fully Open to Depressurize *)")
    lines.append("        rCmd_DivertValve_pct      := 100.0;")
    lines.append("        rCmd_AntiscalantDosing_pct := 0.0;")
    lines.append("        rCmd_SbsDosing_pct        := 0.0;")
    lines.append("        ")
    lines.append("        (* Once HP Pumps Stop, Introduce Permeate Flush Water to Displace Saline Brine *)")
    lines.append("        IF (rCmd_HpPumpSpeed_rpm <= 0.0) AND (rCmd_BoosterSpeed_rpm <= 0.0) THEN")
    lines.append("            rCmd_LpFlushValve_pct := 100.0;")
    lines.append("        ELSE")
    lines.append("            rCmd_LpFlushValve_pct := 0.0;")
    lines.append("        END_IF;")
    lines.append("        ")
    lines.append("        (* Permeate Flush Runs for 120.0 s to Inhibit Osmotic Backflow Shock & Precipitation *)")
    lines.append("        IF rDisplacementFlushTimer_s >= 120.0 THEN")
    lines.append("            rCmd_LpFlushValve_pct := 0.0;")
    lines.append("            rCmd_BrineValve_pct   := 0.0;")
    lines.append("            eState := 0; (* Return to Standby & Instrument Lock *)")
    lines.append("        END_IF;")
    lines.append("")

    # State 11
    lines.append("    11: (* MEMBRANE_CIP_CHEMICAL_WASH_SEQUENCE *)")
    lines.append("        sCurrentStateName := 'MEMBRANE_CIP_CHEMICAL_WASH';")
    lines.append("        bTrainRunning     := FALSE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* High-Pressure Equipment Locked Out *)")
    lines.append("        rCmd_HpPumpSpeed_rpm        := 0.0;")
    lines.append("        rCmd_BoosterSpeed_rpm       := 0.0;")
    lines.append("        rCmd_AntiscalantDosing_pct  := 0.0;")
    lines.append("        rCmd_SbsDosing_pct          := 0.0;")
    lines.append("        rCmd_BrineValve_pct         := 100.0;")
    lines.append("        rCmd_LpFlushValve_pct       := 0.0;")
    lines.append("        rCmd_DivertValve_pct        := 100.0;")
    lines.append("        ")
    lines.append("        rCipCirculationTimer_s := rInternalStateTimer_s;")
    lines.append("        (* Modulate CIP Skid Circulation Pump: 60% Recirculation Flow *)")
    lines.append("        rCmd_CipCirculationPump_pct := 60.0;")
    lines.append("        ")
    lines.append("        (* CIP Sequence Duration: 1800.0 s (30 Minutes Recirculation & Soak) *)")
    lines.append("        IF (rCipCirculationTimer_s >= 1800.0) OR (NOT bCipPermissive) THEN")
    lines.append("            rCmd_CipCirculationPump_pct := 0.0;")
    lines.append("            eState := 10; (* Rinse Out Residual Chemicals with Product Displacement *)")
    lines.append("        END_IF;")
    lines.append("")

    # State 12
    lines.append("    12: (* PRESERVATIVE_SBS_FLUSH_AND_SEAL *)")
    lines.append("        sCurrentStateName := 'PRESERVATIVE_SBS_FLUSH_SEAL';")
    lines.append("        bTrainRunning     := FALSE;")
    lines.append("        bMpcActive        := FALSE;")
    lines.append("        bPermeateDiverted := TRUE;")
    lines.append("        ")
    lines.append("        (* High-Pressure Equipment Locked Out *)")
    lines.append("        rCmd_HpPumpSpeed_rpm        := 0.0;")
    lines.append("        rCmd_BoosterSpeed_rpm       := 0.0;")
    lines.append("        rCmd_AntiscalantDosing_pct  := 0.0;")
    lines.append("        rCmd_LpFlushValve_pct       := 50.0; (* Flush Permeate Carrier Water *)")
    lines.append("        rCmd_SbsDosing_pct          := 100.0; (* 1.0% Sodium Bisulfite Preservation Solution *)")
    lines.append("        rCmd_BrineValve_pct         := 50.0;")
    lines.append("        rCmd_DivertValve_pct        := 100.0;")
    lines.append("        rCmd_CipCirculationPump_pct := 0.0;")
    lines.append("        ")
    lines.append("        rPreservativeSealTimer_s := rInternalStateTimer_s;")
    lines.append("        (* Preservation Soak Duration: 300.0 s, then Seal Train Isolations *)")
    lines.append("        IF (rPreservativeSealTimer_s >= 300.0) OR (NOT bPreservativeFlushPermissive) THEN")
    lines.append("            rCmd_LpFlushValve_pct := 0.0;")
    lines.append("            rCmd_SbsDosing_pct    := 0.0;")
    lines.append("            rCmd_BrineValve_pct   := 0.0;")
    lines.append("            eState := 0; (* Locked in Preservation Standby *)")
    lines.append("        END_IF;")
    lines.append("")

