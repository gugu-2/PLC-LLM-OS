def run():
    prompt, code = generate_dataset()
    
    # 1. Structure checks
    assert code.startswith("```iec-st\n"), "Missing leading ```iec-st"
    assert code.endswith("\n```"), "Missing trailing ```"
    
    st_body = code[len("```iec-st\n"):-len("\n```")]
    st_lines = st_body.splitlines()
    first_line = st_lines[0].strip()
    last_line = st_lines[-1].strip()
    
    assert first_line == "FUNCTION_BLOCK FB_Electronics_SMT_ReflowOven_12ZoneThermalProfile", f"Wrong first line: {first_line}"
    assert last_line == "END_FUNCTION_BLOCK", f"Wrong last line: {last_line}"
    
    # 2. Section blocks
    assert "VAR_INPUT" in st_body, "VAR_INPUT block missing"
    assert "VAR_OUTPUT" in st_body, "VAR_OUTPUT block missing"
    assert "VAR" in st_body, "VAR block missing"
    
    # 3. Units check in VAR_INPUT
    units = ["[bar]", "[deg C]", "[Nm3/h]", "[kPa]", "[m/min]", "[l/min]", "[ppm]", "[Pa]", "[ms]"]
    for u in units:
        assert u in st_body, f"Unit {u} missing in code"
        
    # 4. Parity check (ignoring comments)
    no_comments = re.sub(r'\(\*.*?\*\)', '', st_body, flags=re.DOTALL)
    if_count = len(re.findall(r'\bIF\b', no_comments))
    endif_count = len(re.findall(r'\bEND_IF\b', no_comments))
    case_count = len(re.findall(r'\bCASE\b', no_comments))
    endcase_count = len(re.findall(r'\bEND_CASE\b', no_comments))
    for_count = len(re.findall(r'\bFOR\b', no_comments))
    endfor_count = len(re.findall(r'\bEND_FOR\b', no_comments))
    while_count = len(re.findall(r'\bWHILE\b', no_comments))
    endwhile_count = len(re.findall(r'\bEND_WHILE\b', no_comments))
    
    assert if_count == endif_count, f"IF ({if_count}) != END_IF ({endif_count})"
    assert case_count == endcase_count, f"CASE ({case_count}) != END_CASE ({endcase_count})"
    assert for_count == endfor_count, f"FOR ({for_count}) != END_FOR ({endfor_count})"
    assert while_count == endwhile_count, f"WHILE ({while_count}) != END_WHILE ({endwhile_count})"
    
    # 5. Comment parity
    open_comm = st_body.count("(*")
    close_comm = st_body.count("*)")
    assert open_comm == close_comm, f"Comment parity (* ({open_comm}) != *) ({close_comm})"
    
    print(f"Validation successful!")
    print(f"ST Body Characters: {len(st_body)}")
    print(f"Total Assistant Content Characters: {len(code)}")
    print(f"IF: {if_count}, END_IF: {endif_count}")
    print(f"CASE: {case_count}, END_CASE: {endcase_count}")
    print(f"FOR: {for_count}, END_FOR: {endfor_count}")
    
    # 6. Check length
    # Target length: 45,000 to 75,000+ characters
    print(f"Current length: {len(code)}")

    # 7. Save JSON to data/swarm_raw/agent_<uuid>.json
    record = {
        "messages": [
            {"role": "user", "content": prompt},
            {"role": "assistant", "content": code}
        ]
    }
    
    agent_id = uuid.uuid4().hex[:8]
    filepath = f"data/swarm_raw/agent_{agent_id}.json"
    os.makedirs("data/swarm_raw", exist_ok=True)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(record, f, ensure_ascii=False)
        
    print(f"Dataset successfully saved to: {filepath}")
    return filepath, len(code), agent_id

if __name__ == "__main__":
    filepath, chars, agent_id = run()
    print(f"Result: {filepath} ({chars} chars, ID: {agent_id})")
