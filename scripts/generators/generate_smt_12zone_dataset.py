    w("    END_IF;")
    w("ELSIF rVotedOxygen_PPM >= rAlarmLimit_O2_H_ppm THEN")
    w("    dwAlarmWord_Warning := dwAlarmWord_Warning OR 16#00000004; (* O2 H Elevated Warn *)")
