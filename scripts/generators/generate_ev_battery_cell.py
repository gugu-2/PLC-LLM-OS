    w("")
    w("(* ========================================================================================= *)")
    w("(*  SECTION 4.0: 1070nm FIBER LASER WOBBLE TRAJECTORY & OCT INTERFEROMETRY                   *)")
    w("(* ========================================================================================= *)")
    w("(* Continuous Galvanometric Wobble Phase Accumulation *)")
    w("rWobbleTimeBasePhaseAccumulator := rWobbleTimeBasePhaseAccumulator +")
    w("                                   (c_rTwoPI * c_rNominalWobbleFrequency * rCycleScanTime_Ts);")
    w("IF rWobbleTimeBasePhaseAccumulator >= c_rTwoPI THEN")
    w("    rWobbleTimeBasePhaseAccumulator := rWobbleTimeBasePhaseAccumulator - c_rTwoPI;")
