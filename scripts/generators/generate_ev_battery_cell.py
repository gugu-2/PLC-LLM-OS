    w("END_FOR;")
    w("")
    w("(* Matrix Propagation: x[k+1] = A * x[k] + B * u[k] *)")
    w("FOR iLoopIndex_i := 1 TO 4 DO")
    w("    rMatrixSumAccumulator := 0.0;")
    w("    (* Evaluate Row dot-product with state vector *)")
    w("    FOR iLoopIndex_j := 1 TO 4 DO")
    w("        rMatrixSumAccumulator := rMatrixSumAccumulator +")
    w("                                (aStateMatrix_A[iLoopIndex_i, iLoopIndex_j] * x_StateVector_Actual[iLoopIndex_j]);")
    w("    END_FOR;")
    w("    (* Add input coupling terms B * u *)")
    w("    rMatrixSumAccumulator := rMatrixSumAccumulator + (aInputMatrix_B[iLoopIndex_i, 1] * u_ControlVector[1]);")
    w("    rMatrixSumAccumulator := rMatrixSumAccumulator + (aInputMatrix_B[iLoopIndex_i, 2] * u_ControlVector[2]);")
    w("    x_StateVector_Predicted[iLoopIndex_i] := rMatrixSumAccumulator;")
    w("END_FOR;")
    w("")
