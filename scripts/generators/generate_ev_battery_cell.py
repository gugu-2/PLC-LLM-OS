    w("")
    w("(* ========================================================================================= *)")
    w("(*  SECTION 8.0: PHASE 4: MULTI-STAGE FINITE STATE MACHINE (FSM)                             *)")
    w("(*  States: 0(IDLE) -> 10(CLAMP) -> 20(LOCATE) -> 30(DISPENSE) -> 40(POST_DISP) ->          *)")
