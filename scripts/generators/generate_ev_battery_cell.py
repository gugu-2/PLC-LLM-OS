    w("(*  SECTION 3.0: 2K POLYURETHANE ADHESIVE RHEOLOGY & DYNAMIC BEAD METERING                   *)")
    w("(* ========================================================================================= *)")
    w("(* Calculate actual volumetric mixing ratio *)")
    w("IF rFlowMeterPartB_Actual > 0.05 THEN")
