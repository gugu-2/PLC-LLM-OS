    w("(* Non-Newtonian Herschel-Bulkley Dynamic Viscosity Evaluation *)")
    w("(* Effective wall shear rate: gamma_dot = (4 * Q) / (PI * R^3) * ((3*n + 1)/(4*n)) *)")
    w("rTempShearRateTerm := (4.0 * MAX(0.1, rFlowMeterPartA_Actual + rFlowMeterPartB_Actual) * 1000.0) /")
    w("                      (c_rPI * 27.0); (* Assuming nozzle equivalent internal radius R = 3.0 mm, R^3 = 27 *)")
    w("rAdhesiveEffectiveShearRate := rTempShearRateTerm * ((3.0 * c_rHerschelBulkleyFlowIndex_n + 1.0) / (4.0 * c_rHerschelBulkleyFlowIndex_n));")
    w("IF rAdhesiveEffectiveShearRate < 0.1 THEN")
    w("    rAdhesiveEffectiveShearRate := 0.1;")
    w("END_IF;")
