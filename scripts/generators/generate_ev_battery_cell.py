    w("    END_IF;")
    w("    ")
    w("    (* Update Control Inputs *)")
    w("    u_ControlVector[1] := u_ControlVector_Prev[1] + delta_u_Vector[1];")
    w("    u_ControlVector[2] := u_ControlVector_Prev[2] + delta_u_Vector[2];")
