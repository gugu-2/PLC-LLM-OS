    w("                      (u_ControlVector[1] * aWeightMatrix_R[1, 1] * u_ControlVector[1]) +")
    w("                      (u_ControlVector[2] * aWeightMatrix_R[2, 2] * u_ControlVector[2]);")
    w("")
    w("(* Step 2: Unrolled Gradient Evaluation for Receding Horizon Step *)")
    w("(* grad_u = 2 * B' * P * (A * x + B * u) + 2 * R * u *)")
    w("rMpcOptimalGradient_u1 := 0.0;")
    w("rMpcOptimalGradient_u2 := 0.0;")
    w("FOR iLoopIndex_i := 1 TO 4 DO")
    w("    rTempMathVariable := 0.0;")
    w("    FOR iLoopIndex_j := 1 TO 4 DO")
    w("        rTempMathVariable := rTempMathVariable +")
    w("                             (aTerminalMatrix_P[iLoopIndex_i, iLoopIndex_j] * x_StateVector_Predicted[iLoopIndex_j]);")
    w("    END_FOR;")
    w("    rMpcOptimalGradient_u1 := rMpcOptimalGradient_u1 + (2.0 * aInputMatrix_B[iLoopIndex_i, 1] * rTempMathVariable);")
