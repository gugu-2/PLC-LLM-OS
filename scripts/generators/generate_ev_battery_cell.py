    w("")
    w("(* ========================================================================================= *)")
    w("(*  SECTION 5.0: PHASE 2: DISCRETE STATE-SPACE MATRIX PROPAGATION                            *)")
    w("(*  Equation: x[k+1] = A * x[k] + B * u[k]                                                  *)")
    w("(* ========================================================================================= *)")
    w("(* Update state vector measurements *)")
    w("x_StateVector_Actual[1] := rVisionBeadHeightMeasured - c_rNominalBeadHeight;")
    w("x_StateVector_Actual[2] := rTemperatureStaticMixerTube;")
