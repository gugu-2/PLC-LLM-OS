    w("    3: (* Elliptical Transverse Pattern: X = A*cos(theta), Y = B*sin(theta) *)")
    w("        rWobbleInstantaneousOffsetX := c_rNominalWobbleAmplitudeX * COS(rWobbleTimeBasePhaseAccumulator);")
    w("        rWobbleInstantaneousOffsetY := (c_rNominalWobbleAmplitudeY * 0.5) * SIN(rWobbleTimeBasePhaseAccumulator);")
    w("        ")
    w("    ELSE (* Transverse Linear Wobble: X = 0, Y = A*sin(theta) *)")
    w("        rWobbleInstantaneousOffsetX := 0.0;")
    w("        rWobbleInstantaneousOffsetY := c_rNominalWobbleAmplitudeY * SIN(rWobbleTimeBasePhaseAccumulator);")
    w("END_CASE;")
    w("")
    w("(* Optical Coherence Tomography (OCT) Moving Average Filter *)")
    w("rOctKeyholeDepthHistoryBuffer[iOctBufferIndex] := rOctKeyholeDepthMeasured_Raw;")
