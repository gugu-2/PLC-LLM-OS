    a("                rStateTimer_s := 0.0;")
    a("            ELSIF iSupervisoryCommandState = 20 AND bKissCalibrationComplete THEN")
    a("                eCurrentState := 20; (* Thread Standby Mode *)")
    a("                rStateTimer_s := 0.0;")
    a("            ELSIF iSupervisoryCommandState = 80 THEN")
