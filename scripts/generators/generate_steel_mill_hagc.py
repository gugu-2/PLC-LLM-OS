    a("                rStateTimer_s := 0.0;")
    a("            END_IF;")
    a("        END_IF;")
    a("")
    a("    10: (* ROLL_GAP_ZERO_CALIBRATE: Kiss-Roll Kissing Calibration & Modulus Measurement *)")
    a("        bDumpValveEnergize := TRUE;")
    a("        bLooperSafetyDropValve := FALSE;")
    a("        rLooperHydraulicCommand_Pct := -30.0;")
    a("        bMillReadyForBite := FALSE;")
    a("        bHAGC_LoopActive := FALSE;")
    a("        (* Phase A: Advance Cylinders Slowly to Low Kiss Load (500 kN) *)")
    a("        IF rStateTimer_s < 3.00 THEN")
