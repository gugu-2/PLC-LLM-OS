    a("")
    a("rRollBendingServoCommand_Pct := (rBendingKp * rBendingForceError_kN) + rBendingIntegralState_bar + (arrControl_u[3] * 0.50);")
    a("rRollBendingServoCommand_Pct := MAX(-100.0, MIN(100.0, rRollBendingServoCommand_Pct));")
    a("")

    # =========================================================================
    # PHASE 10: 10-STAGE FINITE STATE MACHINE (FSM)
    # =========================================================================
    a("(* ==================================================================================================== *)")
    a("(* PHASE 10: 10-STAGE FINITE STATE MACHINE (FSM) ARCHITECTURE                                           *)")
    a("(* ==================================================================================================== *)")
    a("rStateTimer_s := rStateTimer_s + rSampleTime_s;")
    a("")
    a("(* Master E-Stop or Cobble Trip Override to Emergency Stop State 99 *)")
    a("IF bMillEmergencyStop OR bAlarmLatched_Thickness_HH OR bAlarmLatched_Force_HH OR")
    a("   bAlarmLatched_Tension_LL OR bAlarmLatched_Tension_HH OR bAlarmLatched_MDT_TMR_Trip THEN")
    a("    eCurrentState := 99;")
    a("END_IF;")
    a("")
    a("CASE eCurrentState OF")
    a("    0: (* MILL_STANDBY_IDLE: Stand Cylinders Retracted, Looper Parked Down *)")
    a("        rMoogServoValveCommand_Pct := 0.0;")
    a("        rLooperHydraulicCommand_Pct := -25.0; (* Negative drive to bottom mechanical stop *)")
    a("        bDumpValveEnergize := FALSE;")
    a("        bLooperSafetyDropValve := FALSE;")
    a("        bMillReadyForBite := FALSE;")
    a("        bHAGC_LoopActive := FALSE;")
    a("        bLooperTensionLoopActive := FALSE;")
    a("        bRollBendingLoopActive := FALSE;")
