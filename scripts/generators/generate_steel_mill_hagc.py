    a("            IF rTotalRollSeparatingForce_kN >= rKissCalibLowForce_kN THEN")
    a("                rKissMDT_LowForceStroke_um := rVotedCylinderPosition_um;")
    a("            END_IF;")
    a("        (* Phase B: Ramp to Calibration Tonnage (2500 kN) to verify Modulus *)")
    a("        ELSIF rStateTimer_s < 6.00 THEN")
    a("            rMoogServoValveCommand_Pct := 2.0;")
    a("            IF rTotalRollSeparatingForce_kN >= rKissCalibTargetForce_kN THEN")
    a("                rKissMDT_HighForceStroke_um := rVotedCylinderPosition_um;")
    a("            END_IF;")
    a("        (* Phase C: Calculate Measured Spring Constant and Retract to Datum *)")
    a("        ELSIF rStateTimer_s < 8.00 THEN")
    a("            IF ABS(rKissMDT_HighForceStroke_um - rKissMDT_LowForceStroke_um) > 10.0 THEN")
    a("                rMillStandModulus_Nominal_kN_per_um := (rKissCalibTargetForce_kN - rKissCalibLowForce_kN) /")
    a("                    ABS(rKissMDT_HighForceStroke_um - rKissMDT_LowForceStroke_um);")
    a("            END_IF;")
    a("            rMillZeroReferenceGap_S0_um := rKissMDT_LowForceStroke_um;")
    a("            bKissCalibrationComplete := TRUE;")
    a("            rMoogServoValveCommand_Pct := -12.0; (* Retract cylinders *)")
    a("        ELSE")
    a("            eCurrentState := 20; (* Proceed to Thread Standby *)")
    a("            rStateTimer_s := 0.0;")
