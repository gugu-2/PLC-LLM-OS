    a("    (1.0 - (rMillHousingNonLinearKneeCoeff * EXP(-rTotalRollSeparatingForce_kN / rMillHousingKneeForce_kN))) +")
    a("    (rMillHousingLinearModulusCoeff * rTotalRollSeparatingForce_kN);")
    a("rEffectiveMillModulus_kN_per_um := MAX(4.50, MIN(12.50, rEffectiveMillModulus_kN_per_um));")
    a("")
    a("(* BISRA Gaugemeter Equation: h = S0 + (F / M_eff) - Delta_thermal + Delta_wear + Delta_oil - Delta_ecc *)")
    a("rRawBISRA_Thickness_um := rVotedCylinderPosition_um +")
    a("                          (rBISRA_TuningGainAlpha * (rTotalRollSeparatingForce_kN / rEffectiveMillModulus_kN_per_um)) -")
    a("                          rThermalRollExpansion_um +")
    a("                          rRollWearProfile_um +")
    a("                          rMorgoilOilFilmThickness_um -")
    a("                          rTotalEccentricityCompensation_um;")
    a("")
    a("(* High-Speed Pre-Filter to Suppress High-Frequency Rolling Noise *)")
    a("rFilteredBISRA_Thickness_um := rFilteredBISRA_Thickness_um +")
    a("    (rSampleTime_s / (rBISRA_FilterTimeConst_s + rSampleTime_s)) * (rRawBISRA_Thickness_um - rFilteredBISRA_Thickness_um);")
    a("rCalculatedBISRA_Thickness_um := rFilteredBISRA_Thickness_um;")
    a("")

    # =========================================================================
    # PHASE 4: ACTIVE ROLL ECCENTRICITY COMPENSATION (AREC)
    # =========================================================================
    a("(* ==================================================================================================== *)")
    a("(* PHASE 4: ACTIVE ROLL ECCENTRICITY COMPENSATION VIA 4-HARMONIC RECURSIVE FOURIER DECOMPOSITION        *)")
    a("(* ==================================================================================================== *)")
    a("(* Separate Mean Rolling Force from High-Frequency Eccentricity Ripple using Low-Pass Filtering *)")
    a("rRollForceMeanFiltered_kN := rRollForceMeanFiltered_kN * 0.9960 + rTotalRollSeparatingForce_kN * 0.0040;")
    a("rRollForceRipple_kN := rTotalRollSeparatingForce_kN - rRollForceMeanFiltered_kN;")
    a("rEquivalentGapRipple_um := rRollForceRipple_kN / rEffectiveMillModulus_kN_per_um;")
    a("")
    a("(* Convert Backup Roll Resolver Angles from Degrees to Radians *)")
    a("rTopBackupAngle_Rad := (rBackupRollAngle_Top_deg * rPI) / 180.0;")
    a("rBotBackupAngle_Rad := (rBackupRollAngle_Bot_deg * rPI) / 180.0;")
    a("")
    a("(* Recursive Sliding Fourier Integration for Top Backup Roll: Harmonics 1 to 4 *)")
    a("IF bStripPresentStandEntry AND rNominalStripSpeed_mps > 1.50 AND eCurrentState = 50 THEN")
    a("    FOR nIdx_h := 1 TO 4 DO")
    a("        (* Top BUR Harmonics Update *)")
    a("        rFourier_A_Top[nIdx_h] := rFourier_A_Top[nIdx_h] +")
    a("            rFourierLearningGain * ((rEquivalentGapRipple_um * COS(INT_TO_REAL(nIdx_h) * rTopBackupAngle_Rad)) - rFourier_A_Top[nIdx_h]);")
    a("        rFourier_B_Top[nIdx_h] := rFourier_B_Top[nIdx_h] +")
    a("            rFourierLearningGain * ((rEquivalentGapRipple_um * SIN(INT_TO_REAL(nIdx_h) * rTopBackupAngle_Rad)) - rFourier_B_Top[nIdx_h]);")
    a("        (* Bottom BUR Harmonics Update *)")
    a("        rFourier_A_Bot[nIdx_h] := rFourier_A_Bot[nIdx_h] +")
    a("            rFourierLearningGain * ((rEquivalentGapRipple_um * COS(INT_TO_REAL(nIdx_h) * rBotBackupAngle_Rad)) - rFourier_A_Bot[nIdx_h]);")
    a("        rFourier_B_Bot[nIdx_h] := rFourier_B_Bot[nIdx_h] +")
    a("            rFourierLearningGain * ((rEquivalentGapRipple_um * SIN(INT_TO_REAL(nIdx_h) * rBotBackupAngle_Rad)) - rFourier_B_Bot[nIdx_h]);")
    a("    END_FOR;")
    a("ELSE")
    a("    (* Gently Decay Coefficients when Not Rolling at Steady State *)")
    a("    FOR nIdx_h := 1 TO 4 DO")
    a("        rFourier_A_Top[nIdx_h] := rFourier_A_Top[nIdx_h] * 0.9995;")
    a("        rFourier_B_Top[nIdx_h] := rFourier_B_Top[nIdx_h] * 0.9995;")
    a("        rFourier_A_Bot[nIdx_h] := rFourier_A_Bot[nIdx_h] * 0.9995;")
    a("        rFourier_B_Bot[nIdx_h] := rFourier_B_Bot[nIdx_h] * 0.9995;")
    a("    END_FOR;")
    a("END_IF;")
    a("")
    a("(* Reconstruct Phase-Lead Compensated Eccentricity Feedforward Signal *)")
    a("rEccentricityComp_Top_um := 0.0;")
    a("rEccentricityComp_Bot_um := 0.0;")
    a("FOR nIdx_h := 1 TO 4 DO")
    a("    rEccentricityComp_Top_um := rEccentricityComp_Top_um +")
    a("        (rFourier_A_Top[nIdx_h] * COS((INT_TO_REAL(nIdx_h) * rTopBackupAngle_Rad) + rPhaseLead_Top_Rad[nIdx_h])) +")
    a("        (rFourier_B_Top[nIdx_h] * SIN((INT_TO_REAL(nIdx_h) * rTopBackupAngle_Rad) + rPhaseLead_Top_Rad[nIdx_h]));")
    a("    rEccentricityComp_Bot_um := rEccentricityComp_Bot_um +")
    a("        (rFourier_A_Bot[nIdx_h] * COS((INT_TO_REAL(nIdx_h) * rBotBackupAngle_Rad) + rPhaseLead_Bot_Rad[nIdx_h])) +")
    a("        (rFourier_B_Bot[nIdx_h] * SIN((INT_TO_REAL(nIdx_h) * rBotBackupAngle_Rad) + rPhaseLead_Bot_Rad[nIdx_h]));")
    a("END_FOR;")
    a("rTotalEccentricityCompensation_um := (rEccentricityComp_Top_um + rEccentricityComp_Bot_um) * 0.50;")
    a("rTotalEccentricityCompensation_um := MAX(-80.0, MIN(80.0, rTotalEccentricityCompensation_um));")
    a("")

    # =========================================================================
    # PHASE 5: HYDRAULIC LOOPER DYNAMICS & INTERSTAND TENSION
    # =========================================================================
    a("(* ==================================================================================================== *)")
    a("(* PHASE 5: HYDRAULIC INTERSTAND LOOPER KINEMATICS & DYNAMIC STRIP TENSION DECOUPLING                   *)")
    a("(* ==================================================================================================== *)")
    a("rLooperAngle_Rad := (rLooperAngle_Actual_deg * rPI) / 180.0;")
    a("rLooperHeight_m := rLooperArmLength_m * SIN(rLooperAngle_Rad);")
    a("")
    a("(* Interstand Strip Geometry: Entry and Exit Angles to Looper Roll Center *)")
    a("rStripEntryAngle_Rad := ATAN(MAX(0.001, rLooperHeight_m) / (rInterstandDistance_m * 0.50));")
    a("rStripExitAngle_Rad  := ATAN(MAX(0.001, rLooperHeight_m) / (rInterstandDistance_m * 0.50));")
    a("rGeomTensionFactor := SIN(rStripEntryAngle_Rad) + SIN(rStripExitAngle_Rad);")
    a("rGeomTensionFactor := MAX(0.08, rGeomTensionFactor);")
    a("")
    a("(* Looper Mechanical Deadweight Tare Torque *)")
    a("rLooperTareTorque_Nm := rLooperRollMass_kg * rGravity_mps2 * rLooperArmLength_m * COS(rLooperAngle_Rad);")
    a("")
    a("(* Strip Suspended Span Weight Torque *)")
    a("rStripCrossSectionArea_mm2 := (rTargetStripWidth_mm * rCalculatedBISRA_Thickness_um) / 1000.0;")
    a("rStripWeightTorque_Nm := (rSteelDensity_kg_per_m3 * (rStripCrossSectionArea_mm2 * 0.000001) * rInterstandDistance_m) *")
    a("                          rGravity_mps2 * (rLooperArmLength_m * 0.50) * COS(rLooperAngle_Rad);")
    a("")
    a("(* Strip Bending Stiffness Resistance Moment *)")
    a("rStripBendingTorque_Nm := (rSteelPlasticStiffness_kN_per_um * 0.001) * (rCalculatedBISRA_Thickness_um / 1000.0) *")
    a("                          rTargetStripWidth_mm * SIN(rLooperAngle_Rad);")
    a("")
    a("(* Dynamic Inertial Acceleration Torque J * alpha *)")
    a("rLooperAngleVelocity_radps := (rLooperAngle_Rad - rPrevLooperAngle_Rad) / rSampleTime_s;")
    a("rPrevLooperAngle_Rad := rLooperAngle_Rad;")
    a("rLooperInertiaTorque_Nm := (rLooperRollMass_kg * rLooperArmLength_m * rLooperArmLength_m) *")
    a("                            (rLooperAngleVelocity_radps / rSampleTime_s) * 0.001;")
    a("")
    a("(* Actual Torque Developed by Hydraulic Cylinder Piston *)")
    a("rLooperHydraulicTorque_Nm := ((rLooperHydraulicPressure_bar - (rLooperRodSidePressure_bar * 0.65)) * 100000.0) *")
    a("                             (rLooperPistonArea_cm2 * 0.0001) * (rLooperArmLength_m * 0.42);")
    a("")
    a("(* Net Dynamic Strip Longitudinal Tensile Force Calculation *)")
    a("rCalculatedStripForce_N := (rLooperHydraulicTorque_Nm - rLooperTareTorque_Nm - rStripWeightTorque_Nm - rStripBendingTorque_Nm - rLooperInertiaTorque_Nm) /")
    a("                           (rLooperArmLength_m * rGeomTensionFactor);")
    a("rCalculatedStripForce_N := MAX(100.0, rCalculatedStripForce_N);")
    a("")
    a("(* Real-Time Calculated Specific Interstand Tension [MPa = N/mm^2] *)")
    a("IF rStripCrossSectionArea_mm2 > 10.0 THEN")
    a("    rCalculatedInterstandTension_MPa := rCalculatedStripForce_N / rStripCrossSectionArea_mm2;")
    a("ELSE")
    a("    rCalculatedInterstandTension_MPa := rTargetInterstandTension_MPa;")
    a("END_IF;")
    a("rCalculatedInterstandTension_MPa := MAX(0.0, MIN(65.0, rCalculatedInterstandTension_MPa));")
    a("")

    # =========================================================================
    # PHASE 6: DISCRETE 4x4 STATE-SPACE MODEL DYNAMICS (1 ms scan)
    # =========================================================================
    a("(* ==================================================================================================== *)")
    a("(* PHASE 6: DISCRETE 4x4 STATE-SPACE MATRIX PROPAGATION (1 ms Fast Scan Model)                           *)")
    a("(* ==================================================================================================== *)")
    a("(* Update State Vector x[k]: [h_err_um, S_pos_um, theta_deg, sigma_tension_MPa] *)")
    a("arrState_x[1] := rCalculatedBISRA_Thickness_um - rTargetExitThickness_um;")
    a("arrState_x[2] := rVotedCylinderPosition_um;")
    a("arrState_x[3] := rLooperAngle_Actual_deg - rTargetLooperAngle_deg;")
    a("arrState_x[4] := rCalculatedInterstandTension_MPa - rTargetInterstandTension_MPa;")
    a("")
    a("(* Propagate Discrete State-Space Model: x[k+1] = A * x[k] + B * u[k] *)")
    a("FOR nIdx_i := 1 TO 4 DO")
    a("    rTempAcc := 0.0;")
    a("    (* Matrix A multiplication *)")
    a("    FOR nIdx_j := 1 TO 4 DO")
    a("        rTempAcc := rTempAcc + (matA[nIdx_i, nIdx_j] * arrState_x[nIdx_j]);")
    a("    END_FOR;")
    a("    (* Matrix B multiplication *)")
    a("    FOR nIdx_m := 1 TO 3 DO")
    a("        rTempAcc := rTempAcc + (matB[nIdx_i, nIdx_m] * arrControl_u[nIdx_m]);")
    a("    END_FOR;")
    a("    arrStateNext_x[nIdx_i] := rTempAcc;")
    a("END_FOR;")
    a("")
    a("(* Telemetry Outputs for Level-2 / Observer *)")
    a("rMPC_PredictedThicknessError_um := arrStateNext_x[1];")
    a("rMPC_PredictedLooperAngle_deg   := arrStateNext_x[3] + rTargetLooperAngle_deg;")
    a("rMPC_PredictedTensionError_MPa  := arrStateNext_x[4];")
    a("")

    # =========================================================================
    # PHASE 7: RECEDING-HORIZON MPC QUADRATIC COST OPTIMIZATION
    # =========================================================================
    a("(* ==================================================================================================== *)")
    a("(* PHASE 7: RECEDING-HORIZON MPC QUADRATIC COST LAW & RATE-LIMITED ACTUATOR SYNTHESIS                    *)")
    a("(* ==================================================================================================== *)")
    a("(* Error vector relative to rolling schedule targets *)")
    a("arrStateError_e[1] := arrState_x[1]; (* Thickness deviation *)")
    a("arrStateError_e[2] := arrState_x[2] - rMillZeroReferenceGap_S0_um; (* Hydraulic stroke datum *)")
    a("arrStateError_e[3] := arrState_x[3]; (* Looper angle deviation *)")
    a("arrStateError_e[4] := arrState_x[4]; (* Strip tension deviation *)")
    a("")
    a("(* Instantaneous Quadratic Cost J_k = e^T * Q * e + u^T * R * u *)")
    a("rMPC_QuadraticCostValue := 0.0;")
    a("FOR nIdx_i := 1 TO 4 DO")
    a("    FOR nIdx_j := 1 TO 4 DO")
    a("        rMPC_QuadraticCostValue := rMPC_QuadraticCostValue + (arrStateError_e[nIdx_i] * matQ[nIdx_i, nIdx_j] * arrStateError_e[nIdx_j]);")
    a("    END_FOR;")
    a("END_FOR;")
    a("FOR nIdx_m := 1 TO 3 DO")
    a("    rMPC_QuadraticCostValue := rMPC_QuadraticCostValue + (arrControl_u[nIdx_m] * matR[nIdx_m, nIdx_m] * arrControl_u[nIdx_m]);")
    a("END_FOR;")
    a("")
    a("(* Compute Optimal Unconstrained State Feedback Law: u_opt = -K_mpc * e *)")
    a("FOR nIdx_m := 1 TO 3 DO")
    a("    rTempAcc := 0.0;")
    a("    FOR nIdx_j := 1 TO 4 DO")
    a("        rTempAcc := rTempAcc - (matK_mpc[nIdx_m, nIdx_j] * arrStateError_e[nIdx_j]);")
    a("    END_FOR;")
    a("    arrRawDelta_u[nIdx_m] := rTempAcc;")
    a("END_FOR;")
    a("")
    a("(* Actuator Slew-Rate Limiters & Physical Saturation Clamping *)")
    a("(* Actuator 1: Moog Servo Valve Slew-Rate Limiter (Max 1000 %/s -> 1.0 %/ms) *)")
    a("rDelta_u_Moog := arrRawDelta_u[1] - arrControl_u_prev[1];")
    a("rDelta_u_Moog := MAX(-rMaxSlewMoog_Pct_per_ms, MIN(rMaxSlewMoog_Pct_per_ms, rDelta_u_Moog));")
    a("arrControl_u[1] := arrControl_u_prev[1] + rDelta_u_Moog;")
    a("arrControl_u[1] := MAX(-100.0, MIN(100.0, arrControl_u[1]));")
    a("")
    a("(* Actuator 2: Looper Hydraulic Torque Valve Slew-Rate Limiter (Max 500 %/s -> 0.5 %/ms) *)")
    a("rDelta_u_Looper := arrRawDelta_u[2] - arrControl_u_prev[2];")
    a("rDelta_u_Looper := MAX(-rMaxSlewLooper_Pct_per_ms, MIN(rMaxSlewLooper_Pct_per_ms, rDelta_u_Looper));")
    a("arrControl_u[2] := arrControl_u_prev[2] + rDelta_u_Looper;")
    a("arrControl_u[2] := MAX(-100.0, MIN(100.0, arrControl_u[2]));")
    a("")
    a("(* Actuator 3: Work Roll Bending Slew-Rate Limiter (Max 200 %/s -> 0.2 %/ms) *)")
    a("rDelta_u_Bending := arrRawDelta_u[3] - arrControl_u_prev[3];")
    a("rDelta_u_Bending := MAX(-rMaxSlewBending_Pct_per_ms, MIN(rMaxSlewBending_Pct_per_ms, rDelta_u_Bending));")
    a("arrControl_u[3] := arrControl_u_prev[3] + rDelta_u_Bending;")
    a("arrControl_u[3] := MAX(-100.0, MIN(100.0, arrControl_u[3]));")
    a("")
    a("(* Update Previous Cycle Inputs *)")
    a("arrControl_u_prev[1] := arrControl_u[1];")
    a("arrControl_u_prev[2] := arrControl_u[2];")
    a("arrControl_u_prev[3] := arrControl_u[3];")
    a("")

    # =========================================================================
    # PHASE 8: SMITH PREDICTOR FOR DOWNSTREAM X-RAY GAUGE TRANSPORT DELAY
    # =========================================================================
    a("(* ==================================================================================================== *)")
    a("(* PHASE 8: SMITH PREDICTOR WITH CIRCULAR BUFFER FOR DOWNSTREAM X-RAY TRANSPORT DELAY                  *)")
    a("(* ==================================================================================================== *)")
    a("rEffectiveStripSpeed_mps := MAX(0.50, rNominalStripSpeed_mps);")
    a("rEstimatedTransportDelay_s := rXRayDistance_Exit_m / rEffectiveStripSpeed_mps;")
    a("nComputedDelaySteps := REAL_TO_INT(rEstimatedTransportDelay_s * 1000.0);")
    a("nComputedDelaySteps := MAX(20, MIN(1000, nComputedDelaySteps));")
    a("")
    a("(* Write Current Undelayed Predicted BISRA Model Thickness into Ring Buffer *)")
    a("arrSmithRingBuffer[nSmithWriteIndex] := rCalculatedBISRA_Thickness_um;")
    a("")
    a("(* Compute Read Pointer for Delayed Model Output *)")
    a("nSmithReadIndex := nSmithWriteIndex - nComputedDelaySteps;")
    a("IF nSmithReadIndex < 0 THEN")
    a("    nSmithReadIndex := nSmithReadIndex + 1025;")
    a("END_IF;")
    a("rSmithDelayedModelThickness_um := arrSmithRingBuffer[nSmithReadIndex];")
    a("rSmithInstantModelThickness_um := rCalculatedBISRA_Thickness_um;")
    a("")
    a("(* Increment Circular Write Pointer *)")
    a("nSmithWriteIndex := nSmithWriteIndex + 1;")
    a("IF nSmithWriteIndex > 1024 THEN")
    a("    nSmithWriteIndex := 0;")
    a("END_IF;")
    a("")
    a("(* Calculate Residual and Integrate Monitor AGC Correction *)")
    a("IF bXRayGaugeHealthy AND bXRayGaugeMeasuring AND bStripPresentStandExit AND eCurrentState = 50 THEN")
    a("    rSmithDiscrepancyError_um := rXRayThickness_Exit_um - rSmithDelayedModelThickness_um;")
    a("    (* Anti-Windup Integration on Gauge Deviation *)")
    a("    IF ABS(rSmithDiscrepancyError_um) < 65.0 THEN")
    a("        rSmithIntegrator_um := rSmithIntegrator_um + (rSmithIntegratorGain * rSmithDiscrepancyError_um);")
    a("    END_IF;")
    a("ELSE")
    a("    rSmithDiscrepancyError_um := 0.0;")
    a("    rSmithIntegrator_um := rSmithIntegrator_um * 0.9998; (* Gentle Bleed-off *)")
    a("END_IF;")
    a("rSmithIntegrator_um := MAX(-45.0, MIN(45.0, rSmithIntegrator_um));")
    a("rSmithPredictorCorrection_um := rSmithIntegrator_um;")
    a("")

    # =========================================================================
    # PHASE 9: WORK ROLL BENDING HYDRAULIC FLATNESS & CROWN COMPENSATION
    # =========================================================================
    a("(* ==================================================================================================== *)")
    a("(* PHASE 9: WORK ROLL BENDING HYDRAULIC FLATNESS & PROFILE CROWN COMPENSATION                          *)")
    a("(* ==================================================================================================== *)")
    a("(* Parabolic Crown Equivalence Calculation from Separating Force Changes *)")
