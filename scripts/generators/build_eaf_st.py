    add("    END_IF;")
    add("END_IF;")
    add("")
    add("(* State Dwell Timer Handling *)")
    add("IF nFSM_State = nFSM_PrevState THEN")
    add("    tFSM_StateTimer_s := tFSM_StateTimer_s + rT_CYCLE_S;")
    add("    bFSM_FirstScan := FALSE;")
    add("ELSE")
    add("    tFSM_StateTimer_s := 0.0;")
    add("    bFSM_FirstScan := TRUE;")
    add("    nFSM_PrevState := nFSM_State;")
    add("END_IF;")
    add("")
    add("CASE nFSM_State OF")
    add("    0: (* STATE_STANDBY_AND_ISOLATED *)")
    add("        bEmergencyFastPullActive := FALSE;")
    add("        bWaterLeakEmergencyDump := FALSE;")
    add("        bExplosionHazardVentActive := FALSE;")
    add("        bTransformerMediumVoltageTrip := FALSE;")
    add("        IF bEnableEAF AND bEBTFlapperClosed AND bLadleInTappingPosition THEN")
