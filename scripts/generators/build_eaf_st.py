    # Phase 4: State-Space Propagation & Receding-Horizon MPC
    add("(* ==================================================================================================== *)")
    add("(* PHASE 4: STATE-SPACE PREDICTION & RECEDING-HORIZON MPC OPTIMIZATION                                 *)")
    add("(* ==================================================================================================== *)")
    add("(* Assemble Current State Vector x_k *)")
    add("rState_x[1] := rMastPos_Voted_A;")
    add("rState_x[2] := rMastPos_Voted_B;")
    add("rState_x[3] := rMastPos_Voted_C;")
    add("rState_x[4] := rImpedanceErr_A;")
    add("rState_x[5] := rImpedanceErr_B;")
    add("rState_x[6] := rImpedanceErr_C;")
    add("")
    add("(* Assemble Reference Trajectory Vector r_set *)")
    add("rRef_r[1] := rMastPos_Voted_A; (* Neutral Mast Position Target *)")
    add("rRef_r[2] := rMastPos_Voted_B;")
    add("rRef_r[3] := rMastPos_Voted_C;")
    add("rRef_r[4] := 0.0;             (* Target Impedance Error = 0.0 mOhm *)")
    add("rRef_r[5] := 0.0;")
    add("rRef_r[6] := 0.0;")
    add("")
    add("(* Discrete State-Space Propagation: x[k+1] = A * x[k] + B * u[k] *)")
    add("FOR iIdxRow := 1 TO 6 DO")
    add("    rTempAccumulator := 0.0;")
    add("    FOR iIdxCol := 1 TO 6 DO")
    add("        rTempAccumulator := rTempAccumulator + (rMatrix_A[iIdxRow, iIdxCol] * rState_x[iIdxCol]);")
    add("    END_FOR;")
    add("    FOR iIdxCol := 1 TO 3 DO")
    add("        rTempAccumulator := rTempAccumulator + (rMatrix_B[iIdxRow, iIdxCol] * rInput_u_prev[iIdxCol]);")
    add("    END_FOR;")
    add("    rState_x_pred[iIdxRow] := rTempAccumulator;")
    add("END_FOR;")
    add("")
    add("(* Receding-Horizon Quadratic Cost Functional Gradient Evaluation *)")
    add("(* J = (x_pred - r)^T * Q * (x_pred - r) + u^T * R * u + delta_u^T * S * delta_u *)")
    add("(* Analytical Gradient: dJ/du = 2 * B^T * Q * (x_pred - r) + 2 * R * u + 2 * S * (u - u_prev) *)")
    add("FOR iIdxCol := 1 TO 3 DO")
    add("    rTempAccumulator := 0.0;")
    add("    (* State Error Contribution through B^T * Q *)")
    add("    FOR iIdxRow := 1 TO 6 DO")
    add("        rTempAccumulator := rTempAccumulator + (rMatrix_B[iIdxRow, iIdxCol] * rWeight_Q[iIdxRow, iIdxRow] * (rState_x_pred[iIdxRow] - rRef_r[iIdxRow]));")
    add("    END_FOR;")
    add("    (* Actuator Effort and Slew Rate Penalty Terms *)")
    add("    rMPC_Gradient[iIdxCol] := (2.0 * rTempAccumulator) + (2.0 * rWeight_R[iIdxCol, iIdxCol] * rInput_u_prev[iIdxCol]) + (2.0 * rWeight_S[iIdxCol, iIdxCol] * rDelta_u[iIdxCol]);")
    add("END_FOR;")
    add("")
    add("(* Projected Gradient Descent Optimization Step *)")
    add("FOR iIdxCol := 1 TO 3 DO")
    add("    rMPC_Optimal_u[iIdxCol] := rInput_u_prev[iIdxCol] - (rMPC_StepSize * rMPC_Gradient[iIdxCol]);")
    add("    (* Direct Scrap Short-Circuit Override Ejection *)")
    add("    IF (iIdxCol = 1) AND bScrapShortCircuit_A THEN")
    add("        rMPC_Optimal_u[iIdxCol] := 38.0; (* Full Hydraulic Mast Raise *)")
    add("    ELSIF (iIdxCol = 2) AND bScrapShortCircuit_B THEN")
    add("        rMPC_Optimal_u[iIdxCol] := 38.0;")
    add("    ELSIF (iIdxCol = 3) AND bScrapShortCircuit_C THEN")
    add("        rMPC_Optimal_u[iIdxCol] := 38.0;")
    add("    END_IF;")
    add("END_FOR;")
    add("")
    add("(* Actuator Slew Rate Limiter & Saturation Enforcement *)")
    add("FOR iIdxCol := 1 TO 3 DO")
    add("    rDelta_u[iIdxCol] := rMPC_Optimal_u[iIdxCol] - rInput_u_prev[iIdxCol];")
    add("    IF rDelta_u[iIdxCol] > rMAX_SERVO_SLEW_RATE_MA_SCAN THEN")
    add("        rDelta_u[iIdxCol] := rMAX_SERVO_SLEW_RATE_MA_SCAN;")
    add("    ELSIF rDelta_u[iIdxCol] < -rMAX_SERVO_SLEW_RATE_MA_SCAN THEN")
    add("        rDelta_u[iIdxCol] := -rMAX_SERVO_SLEW_RATE_MA_SCAN;")
    add("    END_IF;")
    add("    rInput_u[iIdxCol] := rInput_u_prev[iIdxCol] + rDelta_u[iIdxCol];")
    add("    (* Hard Saturation Clamp [-40.0..+40.0 mA] *)")
    add("    IF rInput_u[iIdxCol] > rMAX_SERVO_CURRENT_MA THEN")
    add("        rInput_u[iIdxCol] := rMAX_SERVO_CURRENT_MA;")
    add("    ELSIF rInput_u[iIdxCol] < -rMAX_SERVO_CURRENT_MA THEN")
    add("        rInput_u[iIdxCol] := -rMAX_SERVO_CURRENT_MA;")
    add("    END_IF;")
    add("    rInput_u_prev[iIdxCol] := rInput_u[iIdxCol];")
    add("END_FOR;")
    add("")
    add("(* Mode Multiplexing: Manual Jog vs Automatic MPC *)")
    add("IF bManualModeSelect THEN")
    add("    rServoCmd_PhaseA := (rManualHydraulicJog_A / 100.0) * rMAX_SERVO_CURRENT_MA;")
    add("    rServoCmd_PhaseB := (rManualHydraulicJog_B / 100.0) * rMAX_SERVO_CURRENT_MA;")
    add("    rServoCmd_PhaseC := (rManualHydraulicJog_C / 100.0) * rMAX_SERVO_CURRENT_MA;")
    add("ELSIF bEmergencyFastPullActive THEN")
    add("    rServoCmd_PhaseA := 40.0; (* 100% Retract Command *)")
    add("    rServoCmd_PhaseB := 40.0;")
    add("    rServoCmd_PhaseC := 40.0;")
    add("ELSE")
    add("    rServoCmd_PhaseA := rInput_u[1];")
    add("    rServoCmd_PhaseB := rInput_u[2];")
    add("    rServoCmd_PhaseC := rInput_u[3];")
    add("END_IF;")
    add("")

    # Phase 5: Finite State Machine (11 States)
    add("(* ==================================================================================================== *)")
    add("(* PHASE 5: MULTI-STAGE PRODUCTION FINITE STATE MACHINE (FSM)                                          *)")
    add("(* ==================================================================================================== *)")
    add("(* Heat Elapsed Run Timer *)")
    add("IF (nFSM_State >= 20) AND (nFSM_State <= 90) THEN")
    add("    rTapToTapTime_Elapsed_s := rTapToTapTime_Elapsed_s + rT_CYCLE_S;")
