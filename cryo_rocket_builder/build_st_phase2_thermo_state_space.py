# cryo_rocket_builder/build_st_phase2_thermo_state_space.py

def get_phase2_thermo_state_space():
    lines = []
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL STATE-SPACE ESTIMATION & CRYOGENIC HYDRODYNAMICS            *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* 2.1 Antoine Cryogenic Saturation Vapor Pressure Computations *)")
    lines.append("(* Subcooled Liquid Oxygen (LOX) Vapor Pressure at Suction Bulk Temperature [bar] *)")
    lines.append("rP_sat_lox := EXP(9.102000 - (735.000000 / (MAX(65.0, rTT401_LOX_PumpSuctionTemp_K) - 6.500000)));")
    lines.append("")
    lines.append("(* Subcooled Liquid Methane (LCH4) Vapor Pressure at Suction Bulk Temperature [bar] *)")
    lines.append("rP_sat_ch4 := EXP(8.980000 - (890.000000 / (MAX(85.0, rTT402_CH4_PumpSuctionTemp_K) - 12.000000)));")
    lines.append("")
    lines.append("(* 2.2 Choked Cavitating Venturi Propellant Mass Flow Metering [kg/s] *)")
    lines.append("(* Under choked sonic cavitation, downstream backpressure acoustic waves cannot propagate upstream. *)")
    lines.append("IF rLOX_VenturiPintleCmd_Pct > 0.5 THEN")
    lines.append("    rEstimated_LOX_MassFlow_kgs := rCd_LOX * (rThroatArea_LOX * (rLOX_VenturiPintleCmd_Pct * 0.010000))")
    lines.append("        * SQRT(MAX(1.0, 2.000000 * rRho_LOX * MAX(0.10, (rVoted_LOX_FeedPress_bar - rP_sat_lox)) * 100000.0));")
    lines.append("ELSE")
    lines.append("    rEstimated_LOX_MassFlow_kgs := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("IF rCH4_VenturiPintleCmd_Pct > 0.5 THEN")
    lines.append("    rEstimated_CH4_MassFlow_kgs := rCd_CH4 * (rThroatArea_CH4 * (rCH4_VenturiPintleCmd_Pct * 0.010000))")
    lines.append("        * SQRT(MAX(1.0, 2.000000 * rRho_CH4 * MAX(0.10, (rVoted_CH4_FeedPress_bar - rP_sat_ch4)) * 100000.0));")
    lines.append("ELSE")
    lines.append("    rEstimated_CH4_MassFlow_kgs := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.3 Propellant Mixture Ratio O/F Estimation *)")
    lines.append("IF rEstimated_CH4_MassFlow_kgs > 0.10 THEN")
    lines.append("    rEstimated_MixtureRatio_OF := rEstimated_LOX_MassFlow_kgs / rEstimated_CH4_MassFlow_kgs;")
    lines.append("ELSE")
    lines.append("    rEstimated_MixtureRatio_OF := 0.0;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 2.4 Turbopump Suction Net Positive Suction Margin (NPSM) & Hydraulic Cavitation Index *)")
    lines.append("(* Inducer Inlet Pipe Flow Velocities [m/s] *)")
    lines.append("rLOX_InletVelocity_ms := rEstimated_LOX_MassFlow_kgs / (rRho_LOX * 0.017671);")
    lines.append("rCH4_InletVelocity_ms := rEstimated_CH4_MassFlow_kgs / (rRho_CH4 * 0.025447);")
    lines.append("")
    lines.append("(* Dynamic Head Velocity Components V^2 / (2*g) [m] *)")
    lines.append("rLOX_DynamicHead_m := (rLOX_InletVelocity_ms * rLOX_InletVelocity_ms) / (2.000000 * rGrav_acc);")
    lines.append("rCH4_DynamicHead_m := (rCH4_InletVelocity_ms * rCH4_InletVelocity_ms) / (2.000000 * rGrav_acc);")
    lines.append("")
    lines.append("(* Static Head Margin Above Saturation Pressure (P_suction - P_vapor) / (rho*g) [m] *)")
    lines.append("rLOX_StaticHeadMargin_m := ((rPT401_LOX_PumpSuctionPress_bar - rP_sat_lox) * 100000.0) / (rRho_LOX * rGrav_acc);")
    lines.append("rCH4_StaticHeadMargin_m := ((rPT402_CH4_PumpSuctionPress_bar - rP_sat_ch4) * 100000.0) / (rRho_CH4 * rGrav_acc);")
    lines.append("")
    lines.append("(* Total Net Positive Suction Margin (NPSM = H_static + H_dynamic) [m] *)")
    lines.append("rLOX_Pump_NPSM_m := rLOX_StaticHeadMargin_m + rLOX_DynamicHead_m;")
    lines.append("rCH4_Pump_NPSM_m := rCH4_StaticHeadMargin_m + rCH4_DynamicHead_m;")
    lines.append("")
    lines.append("(* Dimensionless Acoustic Hydrodynamic Cavitation Number sigma = (P_s - P_v) / (0.5 * rho * V^2) [-] *)")
    lines.append("rAcousticCavitationIndex_LOX := (MAX(0.001, (rPT401_LOX_PumpSuctionPress_bar - rP_sat_lox) * 100000.0))")
    lines.append("    / MAX(50.0, 0.500000 * rRho_LOX * MAX(0.25, rLOX_InletVelocity_ms * rLOX_InletVelocity_ms));")
    lines.append("rAcousticCavitationIndex_CH4 := (MAX(0.001, (rPT402_CH4_PumpSuctionPress_bar - rP_sat_ch4) * 100000.0))")
    lines.append("    / MAX(50.0, 0.500000 * rRho_CH4 * MAX(0.25, rCH4_InletVelocity_ms * rCH4_InletVelocity_ms));")
    lines.append("")
    lines.append("(* 2.5 Combustion Chamber Acoustic Dynamic Roughness Filtering [bar RMS] *)")
    lines.append("rCombustionRoughness_barRMS := (rCombustionRoughness_barRMS * 0.880000) + (rPT202_ChamberAcoustic_barRMS * 0.120000);")
    lines.append("")
    lines.append("(* 2.6 Run Tank Helium Ullage Gaseous Mass Inventory Estimation [kg] *)")
    lines.append("rHe_UllageGasMass_kg := (rPT502_He_UllageDomePress_bar * 100000.0 * rUllageTankVolume_m3)")
    lines.append("    / (rR_He * MAX(50.0, rTT501_He_UllageTemp_K));")
    lines.append("")
    lines.append("(* 2.7 6-State Cyber-Physical Observer Update & Dynamic Propagation (Ts = 1.0 ms) *)")
    lines.append("vecY_meas[0] := rVoted_LOX_FeedPress_bar;")
    lines.append("vecY_meas[1] := rTT101_LOX_FeedlineTemp_K;")
    lines.append("vecY_meas[2] := rVoted_CH4_FeedPress_bar;")
    lines.append("vecY_meas[3] := rTT102_CH4_FeedlineTemp_K;")
    lines.append("vecY_meas[4] := rVoted_ChamberPress_bar;")
    lines.append("vecY_meas[5] := rHe_UllageGasMass_kg;")
    lines.append("")
    lines.append("(* Compute Estimated Outputs y_est = C * x_est + D * u_applied *)")
    lines.append("FOR idx_i := 0 TO 5 DO")
    lines.append("    vecY_est[idx_i] := 0.0;")
    lines.append("    FOR idx_j := 0 TO 5 DO")
    lines.append("        vecY_est[idx_i] := vecY_est[idx_i] + (matC[idx_i, idx_j] * vecX_est[idx_j]);")
    lines.append("    END_FOR;")
    lines.append("    FOR idx_k := 0 TO 4 DO")
    lines.append("        vecY_est[idx_i] := vecY_est[idx_i] + (matD[idx_i, idx_k] * vecU_applied[idx_k]);")
    lines.append("    END_FOR;")
    lines.append("    vecInnov[idx_i] := vecY_meas[idx_i] - vecY_est[idx_i];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Compute Observer Corrected State Vector x_corr = x_est + L * innov *)")
    lines.append("FOR idx_i := 0 TO 5 DO")
    lines.append("    vecX_corr[idx_i] := vecX_est[idx_i];")
    lines.append("    FOR idx_j := 0 TO 5 DO")
    lines.append("        vecX_corr[idx_i] := vecX_corr[idx_i] + (matL[idx_i, idx_j] * vecInnov[idx_j]);")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Forward Discrete State Propagation x[k+1] = A * x_corr + B * u_applied *)")
    lines.append("FOR idx_i := 0 TO 5 DO")
    lines.append("    vecX_next[idx_i] := 0.0;")
    lines.append("    FOR idx_j := 0 TO 5 DO")
    lines.append("        vecX_next[idx_i] := vecX_next[idx_i] + (matA[idx_i, idx_j] * vecX_corr[idx_j]);")
    lines.append("    END_FOR;")
    lines.append("    FOR idx_k := 0 TO 4 DO")
    lines.append("        vecX_next[idx_i] := vecX_next[idx_i] + (matB[idx_i, idx_k] * vecU_applied[idx_k]);")
    lines.append("    END_FOR;")
    lines.append("    vecX_est[idx_i] := vecX_next[idx_i];")
    lines.append("END_FOR;")
    return "\n".join(lines)
