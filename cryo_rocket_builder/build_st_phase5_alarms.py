    lines.append("IF bTrip_Pc_HH           THEN dwAlarmWord1 := dwAlarmWord1 OR 16#00000001; END_IF;")
    lines.append("IF bTrip_Pc_LL           THEN dwAlarmWord1 := dwAlarmWord1 OR 16#00000002; END_IF;")
