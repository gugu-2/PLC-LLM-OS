    lines.append("    bTrip_PumpVib_HH := TRUE;")
    lines.append("ELSIF (rAT401_LOX_PumpVib_gRMS <= (rAlarm_PumpVib_HH_Trip - rAlarm_Vib_Deadband)) AND (rAT402_CH4_PumpVib_gRMS <= (rAlarm_PumpVib_HH_Trip - rAlarm_Vib_Deadband)) THEN")
