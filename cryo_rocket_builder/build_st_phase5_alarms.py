    lines.append("IF (iCurrentFSM_State >= 6) AND (iCurrentFSM_State <= 9) THEN")
    lines.append("    IF rCombustionRoughness_barRMS >= rAlarm_AcousticRough_HH_Trip THEN")
    lines.append("        bTrip_Acoustic_HH := TRUE; (* Severe combustion instability abort trip *)")
    lines.append("    ELSIF rCombustionRoughness_barRMS <= (rAlarm_AcousticRough_HH_Trip - rAlarm_Vib_Deadband) THEN")
