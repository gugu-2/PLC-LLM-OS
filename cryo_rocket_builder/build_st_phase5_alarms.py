    lines.append("dwAlarmWord2 := 16#00000000;")
    lines.append("IF bWarn_Pc_H                 THEN dwAlarmWord2 := dwAlarmWord2 OR 16#00000001; END_IF;")
    lines.append("IF bWarn_Pc_L                 THEN dwAlarmWord2 := dwAlarmWord2 OR 16#00000002; END_IF;")
