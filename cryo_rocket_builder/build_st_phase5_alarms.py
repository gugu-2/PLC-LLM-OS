    lines.append("        bWarn_OF_H := TRUE;")
    lines.append("    ELSIF rEstimated_MixtureRatio_OF <= (rAlarm_OF_H_Warn - rAlarm_OF_Deadband) THEN")
    lines.append("        bWarn_OF_H := FALSE;")
    lines.append("    END_IF;")
    lines.append("    ")
