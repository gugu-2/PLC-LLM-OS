# cryo_rocket_builder/build_st_phase3_mpc.py

def get_phase3_mpc():
    lines = []
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* PHASE 3: RECEDING-HORIZON MPC OPTIMIZATION WITH UNROLLED PGD (10 ITERATIONS)                         *)")
    lines.append("(* ==================================================================================================== *)")
    lines.append("(* 3.1 Dynamic State Reference Trajectory Determination Based on Active Sequence State *)")
    lines.append("IF (iCurrentFSM_State = 7) OR (iCurrentFSM_State = 8) OR (iCurrentFSM_State = 9) THEN")
    lines.append("    (* Hot-Fire Burn Active: Track Nominal 100% RPL Staged-Combustion Operating Targets *)")
    lines.append("    vecX_ref[0] := 285.000000; (* LOX feedline downstream pressure target [bar] *)")
    lines.append("    vecX_ref[1] := 90.000000;  (* LOX subcooled fluid temperature target [K] *)")
    lines.append("    vecX_ref[2] := 275.000000; (* LCH4 feedline downstream pressure target [bar] *)")
    lines.append("    vecX_ref[3] := 112.000000; (* LCH4 subcooled fluid temperature target [K] *)")
    lines.append("    vecX_ref[4] := rTargetChamberPress_bar; (* Main chamber combustion static pressure target [bar] *)")
    lines.append("    vecX_ref[5] := 175.000000; (* Run tank gaseous helium ullage target mass inventory [kg] *)")
    lines.append("ELSIF (iCurrentFSM_State = 6) THEN")
    lines.append("    (* Chamber Bootstrap Phase: Low-Pressure Initial Ignition Plateau at 35% RPL *)")
    lines.append("    vecX_ref[0] := 195.000000;")
    lines.append("    vecX_ref[1] := 90.500000;")
    lines.append("    vecX_ref[2] := 190.000000;")
    lines.append("    vecX_ref[3] := 112.500000;")
    lines.append("    vecX_ref[4] := 35.000000;  (* 35 bar low-pressure bootstrap plateau *)")
    lines.append("    vecX_ref[5] := 185.000000;")
    lines.append("ELSIF (iCurrentFSM_State = 4) THEN")
    lines.append("    (* Ullage Pressurization Ramp: Pressurizing Run Tanks to 285-300 bar *)")
    lines.append("    vecX_ref[0] := 285.000000;")
    lines.append("    vecX_ref[1] := 91.000000;")
    lines.append("    vecX_ref[2] := 275.000000;")
    lines.append("    vecX_ref[3] := 113.000000;")
    lines.append("    vecX_ref[4] := 1.013000;")
    lines.append("    vecX_ref[5] := 195.000000;")
    lines.append("ELSIF (iCurrentFSM_State = 2) OR (iCurrentFSM_State = 3) THEN")
    lines.append("    (* Chilldown Conditioning: Low pressure line chill and two-phase boiloff bleed *)")
    lines.append("    vecX_ref[0] := 22.000000;")
    lines.append("    vecX_ref[1] := 90.000000;")
    lines.append("    vecX_ref[2] := 18.000000;")
    lines.append("    vecX_ref[3] := 112.000000;")
    lines.append("    vecX_ref[4] := 1.013000;")
    lines.append("    vecX_ref[5] := 198.000000;")
    lines.append("ELSE")
    lines.append("    (* Secure Idle, Purge, Shutdown, Vent, or Abort Trip State *)")
    lines.append("    vecX_ref[0] := 1.500000;")
    lines.append("    vecX_ref[1] := 288.150000;")
    lines.append("    vecX_ref[2] := 1.500000;")
    lines.append("    vecX_ref[3] := 288.150000;")
    lines.append("    vecX_ref[4] := 1.013000;")
    lines.append("    vecX_ref[5] := 50.000000;")
    lines.append("END_IF;")
    lines.append("")
    lines.append("(* 3.2 Initialize Candidate Optimization Vector from Last Commanded State *)")
    lines.append("FOR idx_j := 0 TO 4 DO")
    lines.append("    vecU_opt[idx_j] := vecU_applied[idx_j];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 3.3 Unrolled Projected Gradient Descent (PGD) Execution (10 Iterations) *)")
    lines.append("FOR iPGD_Iter := 1 TO 10 DO")
    lines.append("    (* Forward Receding Horizon Trajectory Simulation (Horizon Steps H = 0..4) *)")
    lines.append("    FOR idx_i := 0 TO 5 DO")
    lines.append("        matX_pred_horiz[0, idx_i] := vecX_est[idx_i];")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    FOR idx_h := 0 TO 3 DO")
    lines.append("        FOR idx_i := 0 TO 5 DO")
    lines.append("            matX_pred_horiz[idx_h + 1, idx_i] := 0.0;")
    lines.append("            FOR idx_j := 0 TO 5 DO")
    lines.append("                matX_pred_horiz[idx_h + 1, idx_i] := matX_pred_horiz[idx_h + 1, idx_i]")
    lines.append("                    + (matA[idx_i, idx_j] * matX_pred_horiz[idx_h, idx_j]);")
    lines.append("            END_FOR;")
    lines.append("            FOR idx_k := 0 TO 4 DO")
    lines.append("                matX_pred_horiz[idx_h + 1, idx_i] := matX_pred_horiz[idx_h + 1, idx_i]")
    lines.append("                    + (matB[idx_i, idx_k] * vecU_opt[idx_k]);")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* Evaluate Multi-Component Quadratic Objective Cost Function J *)")
    lines.append("    rCost_State := 0.0;")
    lines.append("    FOR idx_h := 0 TO 4 DO")
    lines.append("        FOR idx_i := 0 TO 5 DO")
    lines.append("            rCost_State := rCost_State + (vecQ[idx_i]")
    lines.append("                * (matX_pred_horiz[idx_h, idx_i] - vecX_ref[idx_i])")
    lines.append("                * (matX_pred_horiz[idx_h, idx_i] - vecX_ref[idx_i]));")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    rCost_Input := 0.0;")
    lines.append("    rCost_Slew := 0.0;")
    lines.append("    FOR idx_j := 0 TO 4 DO")
    lines.append("        rCost_Input := rCost_Input + (vecR[idx_j] * vecU_opt[idx_j] * vecU_opt[idx_j]);")
    lines.append("        rCost_Slew := rCost_Slew + (vecR_rate[idx_j]")
    lines.append("            * (vecU_opt[idx_j] - vecU_prev[idx_j])")
    lines.append("            * (vecU_opt[idx_j] - vecU_prev[idx_j]));")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    rCost_Terminal := 0.0;")
    lines.append("    FOR idx_i := 0 TO 5 DO")
    lines.append("        rCost_Terminal := rCost_Terminal + (vecP_terminal[idx_i]")
    lines.append("            * (matX_pred_horiz[4, idx_i] - vecX_ref[idx_i])")
    lines.append("            * (matX_pred_horiz[4, idx_i] - vecX_ref[idx_i]));")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    rCost_Total := rCost_State + rCost_Input + rCost_Slew + rCost_Terminal;")
    lines.append("")
    lines.append("    (* Compute Analytical Gradients dJ/du_j Across Horizon *)")
    lines.append("    FOR idx_j := 0 TO 4 DO")
    lines.append("        vecU_grad[idx_j] := (2.000000 * vecR[idx_j] * vecU_opt[idx_j])")
    lines.append("            + (2.000000 * vecR_rate[idx_j] * (vecU_opt[idx_j] - vecU_prev[idx_j]));")
    lines.append("")
    lines.append("        FOR idx_h := 1 TO 4 DO")
    lines.append("            FOR idx_i := 0 TO 5 DO")
    lines.append("                vecU_grad[idx_j] := vecU_grad[idx_j]")
    lines.append("                    + (2.000000 * vecQ[idx_i] * (matX_pred_horiz[idx_h, idx_i] - vecX_ref[idx_i]) * matB[idx_i, idx_j]);")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Terminal Horizon Sensitivity Coupling *)")
    lines.append("        FOR idx_i := 0 TO 5 DO")
    lines.append("            vecU_grad[idx_j] := vecU_grad[idx_j]")
    lines.append("                + (2.000000 * vecP_terminal[idx_i] * (matX_pred_horiz[4, idx_i] - vecX_ref[idx_i]) * matB[idx_i, idx_j]);")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Projected Gradient Descent Descent Step *)")
    lines.append("        vecU_trial[idx_j] := vecU_opt[idx_j] - (rAlpha_PGD * vecU_grad[idx_j]);")
    lines.append("")
    lines.append("        (* Hard Box Constraint Saturation Projection: u in [0.0%, 100.0%] *)")
    lines.append("        vecU_opt[idx_j] := MIN(vecU_box_max[idx_j], MAX(vecU_box_min[idx_j], vecU_trial[idx_j]));")
    lines.append("    END_FOR;")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* 3.4 Rate-of-Change Slew Enforcement per PLC Task Scan (Ts = 1.0 ms) *)")
    lines.append("FOR idx_j := 0 TO 4 DO")
    lines.append("    IF (vecU_opt[idx_j] - vecU_prev[idx_j]) > vecSlewMax_per_scan[idx_j] THEN")
    lines.append("        vecU_applied[idx_j] := vecU_prev[idx_j] + vecSlewMax_per_scan[idx_j];")
    lines.append("    ELSIF (vecU_opt[idx_j] - vecU_prev[idx_j]) < (-vecSlewMax_per_scan[idx_j]) THEN")
    lines.append("        vecU_applied[idx_j] := vecU_prev[idx_j] - vecSlewMax_per_scan[idx_j];")
    lines.append("    ELSE")
    lines.append("        vecU_applied[idx_j] := vecU_opt[idx_j];")
    lines.append("    END_IF;")
    lines.append("    vecU_prev[idx_j] := vecU_applied[idx_j];")
    lines.append("END_FOR;")
    lines.append("")
    lines.append("(* Actuator Commanded Channel Mapping *)")
    lines.append("rLOX_VenturiPintleCmd_Pct := vecU_applied[0];")
    lines.append("rCH4_VenturiPintleCmd_Pct := vecU_applied[1];")
    lines.append("rHe_UllageDomeRegCmd_Pct  := vecU_applied[2];")
    lines.append("rLOX_ChilldownBleedCmd_Pct := vecU_applied[3];")
    lines.append("rCH4_ChilldownBleedCmd_Pct := vecU_applied[3];")
    lines.append("rPreburnerBypassThrottleCmd_Pct := vecU_applied[4];")
    return "\n".join(lines)
