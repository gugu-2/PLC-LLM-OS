        "IF rInertGasFlowVelocity_mps < 1.20 THEN",
        "    arrAlarm_Active[11] := TRUE; (* Alarm 11: Cross-flow gas velocity collapse *)",
        "ELSE",
        "    IF bAcknowledgeFaults AND arrAlarm_Acknowledged[11] THEN",
        "        arrAlarm_Active[11] := FALSE;",
        "    END_IF;",
        "END_IF;",
        "",
        "(* Store spot origins from actual galvo positions *)",
        "arrPlumeOrigin_X[1] := rGalvo1_PosActual_X_mm;",
        "arrPlumeOrigin_Y[1] := rGalvo1_PosActual_Y_mm;",
        "arrPlumeOrigin_X[2] := rGalvo2_PosActual_X_mm;",
        "arrPlumeOrigin_Y[2] := rGalvo2_PosActual_Y_mm;",
        "arrPlumeOrigin_X[3] := rGalvo3_PosActual_X_mm;",
        "arrPlumeOrigin_Y[3] := rGalvo3_PosActual_Y_mm;",
        "arrPlumeOrigin_X[4] := rGalvo4_PosActual_X_mm;",
        "arrPlumeOrigin_Y[4] := rGalvo4_PosActual_Y_mm;",
        "",
        "(* Compute plume downwind trajectory vectors based on gas velocity *)",
        "FOR idxI := 1 TO 4 DO",
        "    arrPlumeTrailEnd_X[idxI] := arrPlumeOrigin_X[idxI] + (c_rArgonGasVector_Vx * 18.0);",
        "    arrPlumeTrailEnd_Y[idxI] := arrPlumeOrigin_Y[idxI] + (c_rArgonGasVector_Vy * 18.0);",
        "END_FOR;",
        "",
        "(* Pairwise cross-attenuation integral *)",
        "FOR idxJ := 1 TO 4 DO (* Downwind laser beam target *)",
        "    rPlumeIntegratedExtinction := 0.0;",
        "    FOR idxI := 1 TO 4 DO (* Upwind plume emitter *)",
        "        IF idxI <> idxJ THEN",
        "            (* Relative position vector from emitter to target beam *)",
        "            rPlumeDistX := arrPlumeOrigin_X[idxJ] - arrPlumeOrigin_X[idxI];",
        "            rPlumeDistY := arrPlumeOrigin_Y[idxJ] - arrPlumeOrigin_Y[idxI];",
        "            ",
        "            (* Perpendicular distance to plume advection axis (assumed predominantly along +X) *)",
        "            rPlumeNormalDistance := ABS(rPlumeDistY);",
        "",
        "            (* Target beam must be downwind (rPlumeDistX > 0) and within core plume width *)",
        "            IF (rPlumeDistX > 0.0) AND (rPlumeDistX < c_rPlumeDecayLength_mm) AND (rPlumeNormalDistance < c_rPlumeCoreRadius_mm) THEN",
        "                rTempSum := (1.0 - (rPlumeDistX / c_rPlumeDecayLength_mm)) * (1.0 - (rPlumeNormalDistance / c_rPlumeCoreRadius_mm));",
        "                rPlumeIntegratedExtinction := rPlumeIntegratedExtinction + (rTempSum * c_rPlumeExtinctionCoeff * 12.0);",
        "            END_IF;",
        "        END_IF;",
        "    END_FOR;",
        "",
        "    (* Compute percentage optical power loss via Beer-Lambert law: 1 - exp(-tau) *)",
        "    IF idxJ = 1 THEN",
        "        rVaporPlumeAttenuation_L1_pct := (1.0 - EXP(-rPlumeIntegratedExtinction)) * 100.0;",
        "    ELSIF idxJ = 2 THEN",
        "        rVaporPlumeAttenuation_L2_pct := (1.0 - EXP(-rPlumeIntegratedExtinction)) * 100.0;",
        "    ELSIF idxJ = 3 THEN",
        "        rVaporPlumeAttenuation_L3_pct := (1.0 - EXP(-rPlumeIntegratedExtinction)) * 100.0;",
        "    ELSE",
        "        rVaporPlumeAttenuation_L4_pct := (1.0 - EXP(-rPlumeIntegratedExtinction)) * 100.0;",
        "    END_IF;",
        "END_FOR;",
        "",
        "(* Optical attenuation advisory alarm *)",
        "IF (rVaporPlumeAttenuation_L1_pct > 18.0) OR (rVaporPlumeAttenuation_L2_pct > 18.0) OR",
        "   (rVaporPlumeAttenuation_L3_pct > 18.0) OR (rVaporPlumeAttenuation_L4_pct > 18.0) THEN",
