# parts_phase4.py
# Generates Phase 4: Deterministic 15-Stage (0 to 14) Production Lithography Finite State Machine (FSM)

def get_phase4_code():
    lines = []
    lines.append("(* ====================================================================================================")
    lines.append("   PHASE 4: DETERMINISTIC 15-STAGE (0 TO 14) PRODUCTION LITHOGRAPHY FINITE STATE MACHINE (FSM)")
    lines.append("   ==================================================================================================== *)")
    lines.append("    (* Track FSM state transition edges and dwell timers *)")
    lines.append("    IF nFsmState <> nFsmPrevState THEN")
    lines.append("        bFsmStageEntry := TRUE;")
    lines.append("        rFsmStageTimer_s := 0.0;")
    lines.append("        nFsmPrevState := nFsmState;")
    lines.append("    ELSE")
    lines.append("        bFsmStageEntry := FALSE;")
    lines.append("        rFsmStageTimer_s := rFsmStageTimer_s + (tCycleTime_ms * 0.001);")
    lines.append("    END_IF;")
    lines.append("    nActiveFsmStage := nFsmState;")
    lines.append("")
    lines.append("    CASE nFsmState OF")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 0: STANDBY & PRE-FLIGHT SUB-SYSTEM DIAGNOSTICS")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        0: (* STAGE_0_STANDBY_AND_DIAGNOSTICS *)")
    lines.append("            bServoReady := FALSE;")
    lines.append("            bInPositionNanometer := FALSE;")
    lines.append("            bExposurePermissive := FALSE;")
    lines.append("            bRobotLoadPermissive := FALSE;")
    lines.append("            bRobotUnloadPermissive := FALSE;")
    lines.append("            bTwinScanSwapPermissive := FALSE;")
    lines.append("            rEscHighVoltageSupplyCmd_V := 0.0;")
    lines.append("            rHeGasSupplyValveCmd_pct := 0.0;")
    lines.append("            rHeGasVentValveCmd_pct := 100.0; (* Full vacuum vent in standby *)")
    lines.append("")
    lines.append("            IF bEnable AND bChuckVacuumPermissive AND bEuvInterlockClear AND NOT bEmergencyStop THEN")
    lines.append("                IF (dwIsaAlarmTripHH = 16#00000000) AND (dwIsaAlarmTripLL = 16#00000000) THEN")
    lines.append("                    nFsmState := 1; (* Advance to Homing & Mirror Calibration *)")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 1: STAGE HOMING & LASER INTERFEROMETER MIRROR CALIBRATION")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        1: (* STAGE_1_STAGE_HOMING_MIRROR_CAL *)")
    lines.append("            bServoReady := TRUE;")
    lines.append("            rTargetPosX_nm := 0.0;")
    lines.append("            rTargetPosY_nm := 0.0;")
    lines.append("            rTargetPosZ_nm := 0.0;")
    lines.append("            rTargetVelX_mms := 0.0;")
    lines.append("            rTargetVelY_mms := 0.0;")
    lines.append("            rTargetAccX_mps2 := 0.0;")
    lines.append("            rTargetAccY_mps2 := 0.0;")
    lines.append("")
    lines.append("            (* Verify optical laser lock and wait for 0.50 s mirror thermal settling *)")
    lines.append("            IF rFsmStageTimer_s >= 0.500 THEN")
    lines.append("                IF (ABS(rEstimatedPosErrorX_nm) < 5.0) AND (ABS(rEstimatedPosErrorY_nm) < 5.0) THEN")
    lines.append("                    nFsmState := 2; (* Advance to ESC Pre-Charge *)")
    lines.append("                ELSIF rFsmStageTimer_s >= 3.000 THEN")
    lines.append("                    (* Homing timeout fault *)")
    lines.append("                    dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000002;")
    lines.append("                    nFsmState := 14;")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 2: ELECTROSTATIC CHUCK (ESC) PRE-CHARGE VOLTAGE & LEAKAGE CHECK")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        2: (* STAGE_2_ESC_PRECHARGE_VOLTAGE *)")
    lines.append("            rEscHighVoltageSupplyCmd_V := 300.0; (* Pre-charge dielectric threshold *)")
    lines.append("            IF rFsmStageTimer_s >= 0.250 THEN")
    lines.append("                (* Verify dielectric ceramic leakage current < 15.0 uA *)")
    lines.append("                IF rEscLeakageCurrent_uA < 15.000 THEN")
    lines.append("                    nFsmState := 3; (* Advance to Wafer Robot Load Transfer *)")
    lines.append("                ELSE")
    lines.append("                    (* Dielectric insulation breakdown trip *)")
    lines.append("                    dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000004;")
    lines.append("                    nFsmState := 14;")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 3: WAFER ROBOT LOAD TRANSFER & EJECTOR PIN HANDOFF")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        3: (* STAGE_3_WAFER_ROBOT_LOAD_TRANSFER *)")
    lines.append("            bRobotLoadPermissive := TRUE;")
    lines.append("            IF bWaferRobotPresent AND (rFsmStageTimer_s >= 1.200) THEN")
    lines.append("                (* Verify 3-point capacitive gap seating planarity *)")
    lines.append("                IF (ABS(rTmrVoted_CapZ1 - rTmrVoted_CapZ2) < 0.500) AND (ABS(rTmrVoted_CapZ2 - rTmrVoted_CapZ3) < 0.500) THEN")
    lines.append("                    bRobotLoadPermissive := FALSE;")
    lines.append("                    nFsmState := 4; (* Advance to ESC Clamping & He Pressure Build *)")
    lines.append("                ELSIF rFsmStageTimer_s >= 5.000 THEN")
    lines.append("                    dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000008;")
    lines.append("                    nFsmState := 14;")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 4: BIPOLAR ESC CLAMPING & BACKSIDE HELIUM PRESSURE BUILD-UP")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        4: (* STAGE_4_BIPOLAR_ESC_CLAMP_HE_BUILD *)")
    lines.append("            rEscHighVoltageSupplyCmd_V := rEscTargetVoltage_V; (* 1500 V Bipolar *)")
    lines.append("            rHePressTarget_mbar := 15.000; (* 15 mbar Helium *)")
    lines.append("            IF bEscClamped AND bHeThermalStabilized AND (rFsmStageTimer_s >= 0.800) THEN")
    lines.append("                nFsmState := 5; (* Advance to Global Wafer Alignment *)")
    lines.append("            ELSIF rFsmStageTimer_s >= 4.000 THEN")
    lines.append("                dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000010;")
    lines.append("                nFsmState := 14;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 5: GLOBAL WAFER ALIGNMENT MARK SCAN & 6-DOF COORDINATE MAPPING")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        5: (* STAGE_5_GLOBAL_WAFER_ALIGNMENT_SCAN *)")
    lines.append("            (* Stepping across 4 wafer peripheral alignment fiducials *)")
    lines.append("            IF rFsmStageTimer_s >= 0.650 THEN")
    lines.append("                IF (ABS(rTmrVoted_OptAlignX) < 15.0) AND (ABS(rTmrVoted_OptAlignY) < 15.0) THEN")
    lines.append("                    nFsmState := 6; (* Advance to Focus/Leveling Map Ingestion *)")
    lines.append("                ELSIF rFsmStageTimer_s >= 2.500 THEN")
    lines.append("                    dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000020;")
    lines.append("                    nFsmState := 14;")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 6: GRAZING-INCIDENCE LASER FOCUS & LEVELING SURFACE MAP INGESTION")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        6: (* STAGE_6_FOCUS_LEVELING_SURFACE_MAP *)")
    lines.append("            IF rFsmStageTimer_s >= 0.400 THEN")
    lines.append("                (* Verify wafer surface bow curvature is within 15 um allowable envelope *)")
    lines.append("                IF (ABS(rFocusPolyCxx) < 0.005) AND (ABS(rFocusPolyCyy) < 0.005) THEN")
    lines.append("                    nDieIndex := 1;")
    lines.append("                    bScanDirForward := TRUE;")
    lines.append("                    nFsmState := 7; (* Advance to High-Speed Exposure Scan *)")
    lines.append("                ELSE")
    lines.append("                    dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000040;")
    lines.append("                    nFsmState := 14;")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 7: HIGH-SPEED EXPOSURE SCAN SYNCHRONIZATION WITH RETICLE MASK")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        7: (* STAGE_7_HIGH_SPEED_EXPOSURE_SYNC *)")
    lines.append("            (* Execute 15g acceleration ramp and 650 mm/s constant scanning velocity *)")
    lines.append("            IF bScanDirForward THEN")
    lines.append("                rTargetVelY_mms := rExposureScanVel_mms;")
    lines.append("                rTargetAccY_mps2 := rExposureScanAcc_mps2;")
    lines.append("            ELSE")
    lines.append("                rTargetVelY_mms := -rExposureScanVel_mms;")
    lines.append("                rTargetAccY_mps2 := -rExposureScanAcc_mps2;")
    lines.append("            END_IF;")
    lines.append("            rTargetVelX_mms := 0.0;")
    lines.append("            rTargetAccX_mps2 := 0.0;")
    lines.append("")
    lines.append("            (* Verify nanometer overlay jitter window (3-sigma < 1.2 nm) before dose trigger *)")
    lines.append("            IF bInPositionNanometer AND (rFsmStageTimer_s >= 0.050) AND (rFsmStageTimer_s <= 0.120) THEN")
    lines.append("                bExposurePermissive := TRUE;")
    lines.append("            ELSE")
    lines.append("                bExposurePermissive := FALSE;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("            (* Completed scanning stroke across 33 mm die field *)")
    lines.append("            IF rFsmStageTimer_s >= 0.140 THEN")
    lines.append("                bExposurePermissive := FALSE;")
    lines.append("                rTargetVelY_mms := 0.0;")
    lines.append("                rTargetAccY_mps2 := 0.0;")
    lines.append("                nFsmState := 8; (* Advance to Step-and-Scan Field Indexing *)")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 8: STEP-AND-SCAN FIELD INDEXING & DYNAMIC SETTLING")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        8: (* STAGE_8_STEP_AND_SCAN_FIELD_INDEX *)")
    lines.append("            bExposurePermissive := FALSE;")
    lines.append("            (* Die-to-die stepping pitch along X axis *)")
    lines.append("            rTargetVelX_mms := 450.0;")
    lines.append("            rTargetAccX_mps2 := 80.0;")
    lines.append("            rTargetVelY_mms := 0.0;")
    lines.append("            rTargetAccY_mps2 := 0.0;")
    lines.append("")
    lines.append("            IF rFsmStageTimer_s >= 0.065 THEN")
    lines.append("                rTargetVelX_mms := 0.0;")
    lines.append("                rTargetAccX_mps2 := 0.0;")
    lines.append("                IF bInPositionNanometer THEN")
    lines.append("                    IF nDieIndex < nTotalDies THEN")
    lines.append("                        nDieIndex := nDieIndex + 1;")
    lines.append("                        bScanDirForward := NOT bScanDirForward; (* Reverse meander scanning *)")
    lines.append("                        nFsmState := 7; (* Repeat exposure scan for next die *)")
    lines.append("                    ELSE")
    lines.append("                        (* All 96 exposure fields completed on wafer *)")
    lines.append("                        nFsmState := 9; (* Advance to TwinScan Dual Stage Exchange *)")
    lines.append("                    END_IF;")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 9: TWINSCAN DUAL STAGE TRAJECTORY SWAP & COLLISION AVOIDANCE")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        9: (* STAGE_9_TWINSCAN_DUAL_EXCHANGE *)")
    lines.append("            bTwinScanSwapPermissive := (rTwinScanStageDistance_mm >= 25.000);")
    lines.append("            IF bTwinScanSwapAck AND (rFsmStageTimer_s >= 1.500) THEN")
    lines.append("                bTwinScanSwapPermissive := FALSE;")
    lines.append("                nFsmState := 10; (* Advance to ESC Depolarization & He Vent *)")
    lines.append("            ELSIF rFsmStageTimer_s >= 6.000 THEN")
    lines.append("                dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000080;")
    lines.append("                nFsmState := 14;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 10: ESC BIPOLAR DEPOLARIZATION & HELIUM VACUUM VENTING")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        10: (* STAGE_10_ESC_DEPOLARIZE_HE_VENT *)")
    lines.append("            rEscHighVoltageSupplyCmd_V := 0.0;")
    lines.append("            rHeGasSupplyValveCmd_pct := 0.0;")
    lines.append("            rHeGasVentValveCmd_pct := 100.0; (* Full turbo-drag vacuum venting *)")
    lines.append("            rEscDepolarizeTimer_s := rFsmStageTimer_s;")
    lines.append("            rEscResidualCharge_pct := 100.0 * EXP(-rEscDepolarizeTimer_s / 4.200);")
    lines.append("")
    lines.append("            (* Permissive release: Helium pressure < 0.10 mbar and Residual force < 15.0 N *)")
    lines.append("            IF (rTmrVoted_HePress <= 0.100) AND (rEscResidualCharge_pct <= 2.000) AND (rFsmStageTimer_s >= 0.850) THEN")
    lines.append("                nFsmState := 11; (* Advance to Wafer Robot Unload *)")
    lines.append("            ELSIF rFsmStageTimer_s >= 4.000 THEN")
    lines.append("                dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000100;")
    lines.append("                nFsmState := 14;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 11: WAFER ROBOT UNLOAD PERMISSIVE & PIN HANDOFF")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        11: (* STAGE_11_WAFER_ROBOT_UNLOAD_PERMIT *)")
    lines.append("            bRobotUnloadPermissive := TRUE;")
    lines.append("            IF (NOT bWaferRobotPresent) AND (rFsmStageTimer_s >= 1.500) THEN")
    lines.append("                bRobotUnloadPermissive := FALSE;")
    lines.append("                nFsmState := 12; (* Advance to Thermal Mirror Drift Calibration *)")
    lines.append("            ELSIF rFsmStageTimer_s >= 8.000 THEN")
    lines.append("                dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000200;")
    lines.append("                nFsmState := 14;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 12: THERMAL MIRROR EXPANSION DRIFT RE-CALIBRATION")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        12: (* STAGE_12_THERMAL_MIRROR_DRIFT_CAL *)")
    lines.append("            IF rFsmStageTimer_s >= 0.350 THEN")
    lines.append("                IF bStartAutoCycle AND NOT bEmergencyStop THEN")
    lines.append("                    nFsmState := 3; (* Continuous production: Load next wafer *)")
    lines.append("                ELSE")
    lines.append("                    nFsmState := 0; (* Cycle complete: Return to Standby *)")
    lines.append("                END_IF;")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 13: LASER INTERFEROMETER FRINGE-SLIP COARSE-TO-FINE RECOVERY")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        13: (* STAGE_13_INTERFEROMETER_FRINGE_RECOVER *)")
    lines.append("            bExposurePermissive := FALSE;")
    lines.append("            bServoReady := FALSE;")
    lines.append("            rTargetVelX_mms := 0.0;")
    lines.append("            rTargetVelY_mms := 0.0;")
    lines.append("            rTargetAccX_mps2 := 0.0;")
    lines.append("            rTargetAccY_mps2 := 0.0;")
    lines.append("")
    lines.append("            (* Attempt optical zero-datum fringe relock *)")
    lines.append("            IF (NOT bFringeSlipDetected_Ext) AND (rFsmStageTimer_s >= 0.800) THEN")
    lines.append("                bServoReady := TRUE;")
    lines.append("                nFsmState := 1; (* Re-execute homing and mirror calibration *)")
    lines.append("            ELSIF rFsmStageTimer_s >= 2.500 THEN")
    lines.append("                dwIsaAlarmTripHH := dwIsaAlarmTripHH OR 16#00000400;")
    lines.append("                nFsmState := 14; (* Fatal fringe slip unrecoverable: Drop stage *)")
    lines.append("            END_IF;")
    lines.append("")
    lines.append("        (* --------------------------------------------------------------------------------------------")
    lines.append("           STAGE 14: SEVERE COLLISION / EMERGENCY MAGNET FAILSAFE DROP")
    lines.append("           -------------------------------------------------------------------------------------------- *)")
    lines.append("        14: (* STAGE_14_FAILSAFE_MAGNET_DROP *)")
    lines.append("            bServoReady := FALSE;")
    lines.append("            bInPositionNanometer := FALSE;")
    lines.append("            bExposurePermissive := FALSE;")
    lines.append("            bRobotLoadPermissive := FALSE;")
    lines.append("            bRobotUnloadPermissive := FALSE;")
    lines.append("            bTwinScanSwapPermissive := FALSE;")
    lines.append("            (* Cut off all coil currents to allow passive eddy current brake landing *)")
    lines.append("            rActuatorCurrent_X1_A := 0.0;")
    lines.append("            rActuatorCurrent_X2_A := 0.0;")
    lines.append("            rActuatorCurrent_Y1_A := 0.0;")
    lines.append("            rActuatorCurrent_Y2_A := 0.0;")
    lines.append("            rActuatorCurrent_Z1_A := 0.0;")
    lines.append("            rActuatorCurrent_Z2_A := 0.0;")
    lines.append("            rActuatorCurrent_Z3_A := 0.0;")
    lines.append("            rActuatorCurrent_Z4_A := 0.0;")
    lines.append("            rCounterMassForceCmdX_N := 0.0;")
    lines.append("            rCounterMassForceCmdY_N := 0.0;")
    lines.append("            rEscHighVoltageSupplyCmd_V := 0.0;")
    lines.append("            rHeGasSupplyValveCmd_pct := 0.0;")
    lines.append("            rHeGasVentValveCmd_pct := 100.0; (* Immediate helium vacuum vent *)")
    lines.append("")
    lines.append("            (* Require manual alarm reset to clear emergency drop condition *)")
    lines.append("            IF bResetAlarms AND (NOT bEmergencyStop) AND (NOT bFringeSlipDetected_Ext) THEN")
    lines.append("                dwIsaAlarmTripHH := 16#00000000;")
    lines.append("                dwIsaAlarmTripLL := 16#00000000;")
    lines.append("                nFsmState := 0; (* Return to Standby *)")
    lines.append("            END_IF;")
    lines.append("    END_CASE;")
    lines.append("")
    return "\n".join(lines)

print("parts_phase4.py defined.")
