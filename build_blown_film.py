    code_lines.append("xState[1]  := rIBC_NeckDiameter_Sensor;              (* Neck Diameter [mm] *)")
    code_lines.append("xState[2]  := rVotedIBCBubbleDiameter_mm;            (* Frost Line Diameter [mm] *)")
    code_lines.append("xState[3]  := rCalculatedFrostLineHeight_mm;         (* Frost Line Elevation [mm] *)")
    code_lines.append("xState[4]  := rIBC_InternalPressure_Sensor;          (* IBC Internal Static Pressure [Pa] *)")
    code_lines.append("xState[5]  := rCalculatedAverageThickness_um;        (* Film Gauge Thickness [um] *)")
    code_lines.append("xState[6]  := rThicknessProfile_MaxDev_Pct * 0.45;   (* 1st Harmonic Amplitude [um] *)")
    code_lines.append("xState[7]  := rThicknessProfile_2Sigma_Pct * 0.35;   (* 2nd Harmonic Ovality [um] *)")
    code_lines.append("xState[8]  := rMeltTemp_LayerF;                      (* Bulk Melt Temperature [deg C] *)")
    code_lines.append("xState[9]  := rVotedDieMeltPressure_bar;             (* Annular Die Melt Pressure [bar] *)")
    code_lines.append("xState[10] := rWinderDancerTension_Sensor;           (* Web Tension at Nip [N] *)")
    code_lines.append("xState[11] := rWinderDancerTension_Sensor;           (* Web Tension at Winder Dancer [N] *)")
    code_lines.append("xState[12] := rWinderRollDiameter_mm;                (* Active Roll Diameter [mm] *)")
    code_lines.append("xState[13] := rHaulOffOscillatingAngle_deg;          (* Turntable Azimuth Angle [deg] *)")
    code_lines.append("xState[14] := rAirRingPlenumTemp;                    (* Air Ring Plenum Temperature [deg C] *)")
    code_lines.append("")
    code_lines.append("(* Setpoint Vector Assembly *)")
    code_lines.append("xSetpoint[1]  := rTargetBubbleDiameter_mm * 0.50;")
    code_lines.append("xSetpoint[2]  := rTargetBubbleDiameter_mm;")
    code_lines.append("xSetpoint[3]  := rTargetFrostLineHeight_mm;")
    code_lines.append("xSetpoint[4]  := 45.0; (* Regulated 45 Pa Internal Differential *)")
    code_lines.append("xSetpoint[5]  := rTargetNominalThickness_um;")
    code_lines.append("xSetpoint[6]  := 0.0;  (* Zero 1st Harmonic *)")
    code_lines.append("xSetpoint[7]  := 0.0;  (* Zero Ovality *)")
    code_lines.append("xSetpoint[8]  := 212.0;")
    code_lines.append("xSetpoint[9]  := 220.0;")
    code_lines.append("xSetpoint[10] := rTargetWebTension_N;")
    code_lines.append("xSetpoint[11] := rTargetWebTension_N;")
    code_lines.append("xSetpoint[12] := rWinderRollDiameter_mm;")
    code_lines.append("xSetpoint[13] := rHaulOffOscillatingAngle_deg;")
    code_lines.append("xSetpoint[14] := 14.5;")
    code_lines.append("")
    code_lines.append("(* Tracking Error Evaluation *)")
    code_lines.append("FOR kStateIdx := 1 TO 14 DO")
    code_lines.append("    xError[kStateIdx] := xState[kStateIdx] - xSetpoint[kStateIdx];")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("(* State Space One-Step Prediction xPred = A*x + B*u *)")
    code_lines.append("FOR iRowIdx := 1 TO 14 DO")
    code_lines.append("    xPred[iRowIdx] := 0.0;")
    code_lines.append("    FOR jColIdx := 1 TO 14 DO")
    code_lines.append("        xPred[iRowIdx] := xPred[iRowIdx] + (matA[iRowIdx, jColIdx] * xState[jColIdx]);")
    code_lines.append("    END_FOR;")
    code_lines.append("    FOR mInputIdx := 1 TO 8 DO")
    code_lines.append("        xPred[iRowIdx] := xPred[iRowIdx] + (matB[iRowIdx, mInputIdx] * uActuator[mInputIdx]);")
    code_lines.append("    END_FOR;")
    code_lines.append("END_FOR;")
    code_lines.append("")
    
    # Phase 3: Receding-Horizon MPC & 64-Zone Air Ring Profile Regulation
    code_lines.append("(* ===========================================================================================")
    code_lines.append("   PHASE 3: RECEDING-HORIZON MPC & 64-ZONE SEGMENTED AIR RING GAUGE PROFILE CONTROL")
    code_lines.append("   =========================================================================================== *)")
    code_lines.append("(* 3.1 Receding Horizon Trajectory Simulation (Np = 5 Steps) *)")
    code_lines.append("FOR iRowIdx := 1 TO 14 DO")
    code_lines.append("    xHorizonTrajectory[1, iRowIdx] := xPred[iRowIdx];")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("FOR iHorizonStep := 2 TO 5 DO")
    code_lines.append("    FOR iRowIdx := 1 TO 14 DO")
    code_lines.append("        xHorizonTrajectory[iHorizonStep, iRowIdx] := 0.0;")
    code_lines.append("        FOR jColIdx := 1 TO 14 DO")
    code_lines.append("            xHorizonTrajectory[iHorizonStep, iRowIdx] := xHorizonTrajectory[iHorizonStep, iRowIdx] +")
    code_lines.append("                (matA[iRowIdx, jColIdx] * xHorizonTrajectory[iHorizonStep - 1, jColIdx]);")
    code_lines.append("        END_FOR;")
    code_lines.append("        FOR mInputIdx := 1 TO 8 DO")
    code_lines.append("            xHorizonTrajectory[iHorizonStep, iRowIdx] := xHorizonTrajectory[iHorizonStep, iRowIdx] +")
    code_lines.append("                (matB[iRowIdx, mInputIdx] * uActuator[mInputIdx]);")
    code_lines.append("        END_FOR;")
    code_lines.append("    END_FOR;")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("(* Cost Function Evaluation: J = sum(xQx) + sum(uRu) + terminal(xPx) *)")
    code_lines.append("rStateCostAccum := 0.0;")
    code_lines.append("FOR iHorizonStep := 1 TO 5 DO")
    code_lines.append("    FOR iRowIdx := 1 TO 14 DO")
    code_lines.append("        rStateCostAccum := rStateCostAccum +")
    code_lines.append("            (xHorizonTrajectory[iHorizonStep, iRowIdx] - xSetpoint[iRowIdx]) *")
    code_lines.append("            matQ[iRowIdx, iRowIdx] *")
    code_lines.append("            (xHorizonTrajectory[iHorizonStep, iRowIdx] - xSetpoint[iRowIdx]);")
    code_lines.append("    END_FOR;")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("rControlCostAccum := 0.0;")
    code_lines.append("FOR mInputIdx := 1 TO 8 DO")
    code_lines.append("    rControlCostAccum := rControlCostAccum +")
    code_lines.append("        (uActuator[mInputIdx] - uPrevious[mInputIdx]) *")
    code_lines.append("        matR[mInputIdx, mInputIdx] *")
    code_lines.append("        (uActuator[mInputIdx] - uPrevious[mInputIdx]);")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("rTerminalCostAccum := 0.0;")
    code_lines.append("FOR iRowIdx := 1 TO 14 DO")
    code_lines.append("    rTerminalCostAccum := rTerminalCostAccum +")
    code_lines.append("        (xHorizonTrajectory[5, iRowIdx] - xSetpoint[iRowIdx]) *")
    code_lines.append("        matP[iRowIdx, iRowIdx] *")
    code_lines.append("        (xHorizonTrajectory[5, iRowIdx] - xSetpoint[iRowIdx]);")
    code_lines.append("END_FOR;")
    code_lines.append("rTotalQuadraticCost := rStateCostAccum + rControlCostAccum + rTerminalCostAccum;")
    code_lines.append("")
    code_lines.append("(* Analytic Gradient Evaluation & Projected Conjugate Step *)")
    code_lines.append("FOR mInputIdx := 1 TO 8 DO")
    code_lines.append("    rMpcGrad[mInputIdx] := 0.0;")
    code_lines.append("    FOR iRowIdx := 1 TO 14 DO")
    code_lines.append("        rMpcGrad[mInputIdx] := rMpcGrad[mInputIdx] +")
    code_lines.append("            2.0 * matB[iRowIdx, mInputIdx] * matQ[iRowIdx, iRowIdx] * (xPred[iRowIdx] - xSetpoint[iRowIdx]);")
    code_lines.append("    END_FOR;")
    code_lines.append("    rMpcGrad[mInputIdx] := rMpcGrad[mInputIdx] + 2.0 * matR[mInputIdx, mInputIdx] * (uActuator[mInputIdx] - uPrevious[mInputIdx]);")
    code_lines.append("    ")
    code_lines.append("    (* Gradient Descent Update *)")
    code_lines.append("    uOptimal[mInputIdx] := uActuator[mInputIdx] - (rMpcStepSize * rMpcGrad[mInputIdx]);")
    code_lines.append("    ")
    code_lines.append("    (* Rate Slew Clamping *)")
    code_lines.append("    IF (uOptimal[mInputIdx] - uPrevious[mInputIdx]) > deltaUMax[mInputIdx] THEN")
    code_lines.append("        uOptimal[mInputIdx] := uPrevious[mInputIdx] + deltaUMax[mInputIdx];")
    code_lines.append("    ELSIF (uOptimal[mInputIdx] - uPrevious[mInputIdx]) < -deltaUMax[mInputIdx] THEN")
    code_lines.append("        uOptimal[mInputIdx] := uPrevious[mInputIdx] - deltaUMax[mInputIdx];")
    code_lines.append("    END_IF;")
    code_lines.append("    ")
    code_lines.append("    (* Hard Saturation Boundary Clamping *)")
    code_lines.append("    IF uOptimal[mInputIdx] > uUpperBound[mInputIdx] THEN")
    code_lines.append("        uOptimal[mInputIdx] := uUpperBound[mInputIdx];")
    code_lines.append("    ELSIF uOptimal[mInputIdx] < uLowerBound[mInputIdx] THEN")
    code_lines.append("        uOptimal[mInputIdx] := uLowerBound[mInputIdx];")
    code_lines.append("    END_IF;")
    code_lines.append("    ")
    code_lines.append("    uPrevious[mInputIdx] := uActuator[mInputIdx];")
    code_lines.append("    uActuator[mInputIdx] := uOptimal[mInputIdx];")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("(* Assign Optimal Coordinated Actuators *)")
    code_lines.append("rIBC_SupplyBlower_Cmd_Pct      := uActuator[1];")
    code_lines.append("rIBC_ExhaustBlower_Cmd_Pct     := uActuator[2];")
    code_lines.append("rAirRing_MainBlower_Cmd_Pct    := uActuator[3];")
    code_lines.append("rHaulOffNipSpeed_Cmd_MPM       := uActuator[4];")
    code_lines.append("rWinderSurfaceSpeed_Cmd_MPM    := (uActuator[4] * 1.002) + (uActuator[5] * 0.05);")
    code_lines.append("rCollapsingCageDiameter_Cmd_mm := uActuator[8];")
    code_lines.append("")
    code_lines.append("(* 3.2 Capacitive Thickness Gauge Polar Binning & Statistical Analysis *)")
    code_lines.append("IF bGaugeScanActive THEN")
    code_lines.append("    (* Map Current Traversing Scanner Angle (0 to 360 deg) to 64 Angular Bins *)")
    code_lines.append("    iProfileBinIdx := TRUNC((rGaugeScanAngularPosition_deg / 360.0) * 64.0) + 1;")
    code_lines.append("    IF iProfileBinIdx < 1 THEN iProfileBinIdx := 1; END_IF;")
    code_lines.append("    IF iProfileBinIdx > 64 THEN iProfileBinIdx := 64; END_IF;")
    code_lines.append("    ")
    code_lines.append("    (* Low-Pass Filter New Gauge Measurement into Polar Bin *)")
    code_lines.append("    IF (rGaugeScanThickness_Raw > 10.0) AND (rGaugeScanThickness_Raw < 200.0) THEN")
    code_lines.append("        rThicknessProfile_Raw[iProfileBinIdx] := (0.35 * rGaugeScanThickness_Raw) +")
    code_lines.append("                                                 (0.65 * rThicknessProfile_Raw[iProfileBinIdx]);")
    code_lines.append("    END_IF;")
    code_lines.append("END_IF;")
    code_lines.append("")
    code_lines.append("(* Polar Mean, 2-Sigma Variance & Peak-to-Peak Deviation Calculation *)")
    code_lines.append("rProfileMeanSum := 0.0;")
    code_lines.append("rProfileMinVal := 999.0;")
    code_lines.append("rProfileMaxVal := 0.0;")
    code_lines.append("FOR iProfileBinIdx := 1 TO 64 DO")
    code_lines.append("    rProfileMeanSum := rProfileMeanSum + rThicknessProfile_Raw[iProfileBinIdx];")
    code_lines.append("    IF rThicknessProfile_Raw[iProfileBinIdx] < rProfileMinVal THEN")
    code_lines.append("        rProfileMinVal := rThicknessProfile_Raw[iProfileBinIdx];")
    code_lines.append("    END_IF;")
    code_lines.append("    IF rThicknessProfile_Raw[iProfileBinIdx] > rProfileMaxVal THEN")
    code_lines.append("        rProfileMaxVal := rThicknessProfile_Raw[iProfileBinIdx];")
    code_lines.append("    END_IF;")
    code_lines.append("END_FOR;")
    code_lines.append("rProfileMeanVal := rProfileMeanSum / 64.0;")
    code_lines.append("rCalculatedAverageThickness_um := rProfileMeanVal;")
    code_lines.append("")
    code_lines.append("rVarianceSum := 0.0;")
    code_lines.append("FOR iProfileBinIdx := 1 TO 64 DO")
    code_lines.append("    rVarianceSum := rVarianceSum + ((rThicknessProfile_Raw[iProfileBinIdx] - rProfileMeanVal) *")
    code_lines.append("                                    (rThicknessProfile_Raw[iProfileBinIdx] - rProfileMeanVal));")
    code_lines.append("END_FOR;")
    code_lines.append("rProfileVariance := rVarianceSum / 64.0;")
    code_lines.append("IF rProfileVariance > 0.0001 THEN")
    code_lines.append("    rThicknessProfile_2Sigma_Pct := (2.0 * SQRT(rProfileVariance) / (rProfileMeanVal + 1.0E-6)) * 100.0;")
    code_lines.append("ELSE")
    code_lines.append("    rThicknessProfile_2Sigma_Pct := 0.0;")
    code_lines.append("END_IF;")
    code_lines.append("rThicknessProfile_MaxDev_Pct := ((rProfileMaxVal - rProfileMinVal) / (rProfileMeanVal + 1.0E-6)) * 100.0;")
    code_lines.append("")
    code_lines.append("(* 3.3 Dynamic Polar Mapping: Dynamic Bubble Twist Offset & Spatial Gaussian Filtering *)")
    code_lines.append("iTwistShiftBins := TRUNC((rDynamicBubbleTwistAngle_deg / 360.0) * 64.0) MOD 64;")
    code_lines.append("IF iTwistShiftBins < 0 THEN iTwistShiftBins := iTwistShiftBins + 64; END_IF;")
    code_lines.append("")
    code_lines.append("(* 3-Tap Spatial Gaussian Convolution Filter [0.15, 0.70, 0.15] across Circular Bins *)")
    code_lines.append("FOR iProfileBinIdx := 1 TO 64 DO")
    code_lines.append("    iAdjacentLeft := iProfileBinIdx - 1;")
    code_lines.append("    IF iAdjacentLeft < 1 THEN iAdjacentLeft := 64; END_IF;")
    code_lines.append("    iAdjacentRight := iProfileBinIdx + 1;")
    code_lines.append("    IF iAdjacentRight > 64 THEN iAdjacentRight := 1; END_IF;")
    code_lines.append("    ")
    code_lines.append("    rSpatialFilteredBin := (0.15 * rThicknessProfile_Raw[iAdjacentLeft]) +")
    code_lines.append("                           (0.70 * rThicknessProfile_Raw[iProfileBinIdx]) +")
    code_lines.append("                           (0.15 * rThicknessProfile_Raw[iAdjacentRight]);")
    code_lines.append("    rThicknessProfile_Filtered[iProfileBinIdx] := rSpatialFilteredBin;")
    code_lines.append("END_FOR;")
    code_lines.append("")
    code_lines.append("(* Map Filtered Bins to 64 Physical Air Ring Heating Cartridges with Twist Shift *)")
    code_lines.append("FOR iHeaterZoneIdx := 1 TO 64 DO")
    code_lines.append("    iProfileBinIdx := ((iHeaterZoneIdx + iTwistShiftBins - 1) MOD 64) + 1;")
    code_lines.append("    rMappedHeaterZoneError[iHeaterZoneIdx] := rThicknessProfile_Filtered[iProfileBinIdx] - rTargetNominalThickness_um;")
    code_lines.append("    ")
    code_lines.append("    (* 64 Closed-Loop PI Controllers with Anti-Windup Clamping *)")
    code_lines.append("    IF (eCurrentFsmState = STATE_AUTOGAUGE_THERMAL_OPTIMIZE) OR")
    code_lines.append("       (eCurrentFsmState = STATE_OSCILLATING_HAUL_TRACKING) THEN")
    code_lines.append("        rAirRingHeaterIntegral[iHeaterZoneIdx] := rAirRingHeaterIntegral[iHeaterZoneIdx] +")
    code_lines.append("                                                 (rHeaterKi * rMappedHeaterZoneError[iHeaterZoneIdx] * rDeltaTime_Seconds);")
    code_lines.append("        (* Integral Anti-Windup Limits *)")
    code_lines.append("        IF rAirRingHeaterIntegral[iHeaterZoneIdx] > 40.0 THEN")
    code_lines.append("            rAirRingHeaterIntegral[iHeaterZoneIdx] := 40.0;")
    code_lines.append("        ELSIF rAirRingHeaterIntegral[iHeaterZoneIdx] < -40.0 THEN")
    code_lines.append("            rAirRingHeaterIntegral[iHeaterZoneIdx] := -40.0;")
    code_lines.append("        END_IF;")
    code_lines.append("        ")
    code_lines.append("        (* Proportional + Integral + Base Bias Actuation *)")
    code_lines.append("        (* Positive error (too thick) -> Increase heater power to warm localized air -> thins film *)")
    code_lines.append("        rAirRingHeaterCmd_Internal[iHeaterZoneIdx] := uActuator[7] +")
    code_lines.append("                                                     (rHeaterKp * rMappedHeaterZoneError[iHeaterZoneIdx]) +")
    code_lines.append("                                                     rAirRingHeaterIntegral[iHeaterZoneIdx];")
    code_lines.append("    ELSE")
    code_lines.append("        (* Standby Pre-warm Duty Cycle *)")
    code_lines.append("        rAirRingHeaterCmd_Internal[iHeaterZoneIdx] := 15.0;")
    code_lines.append("        rAirRingHeaterIntegral[iHeaterZoneIdx] := 0.0;")
    code_lines.append("    END_IF;")
    code_lines.append("    ")
    code_lines.append("    (* Actuator Clamping 0.0 to 100.0% *)")
    code_lines.append("    IF rAirRingHeaterCmd_Internal[iHeaterZoneIdx] > 100.0 THEN")
    code_lines.append("        rAirRingHeaterCmd_Internal[iHeaterZoneIdx] := 100.0;")
    code_lines.append("    ELSIF rAirRingHeaterCmd_Internal[iHeaterZoneIdx] < 0.0 THEN")
    code_lines.append("        rAirRingHeaterCmd_Internal[iHeaterZoneIdx] := 0.0;")
    code_lines.append("    END_IF;")
    code_lines.append("    ")
    code_lines.append("    rAirRingHeaterCmd[iHeaterZoneIdx] := rAirRingHeaterCmd_Internal[iHeaterZoneIdx];")
    code_lines.append("END_FOR;")
    code_lines.append("")
    
    # Phase 4: 12-Stage Operational Finite State Machine
    code_lines.append("(* ===========================================================================================")
    code_lines.append("   PHASE 4: 12-STAGE OPERATIONAL FINITE STATE MACHINE (FSM)")
    code_lines.append("   =========================================================================================== *)")
    code_lines.append("CASE eCurrentFsmState OF")
    
    # State 0: IDLE
    code_lines.append("    0: (* STATE_IDLE_OFFLINE: Safe Offline Standby *)")
    code_lines.append("        tStateDwellTimer := T#0S;")
    code_lines.append("        bProductionReleaseQualified := FALSE;")
    code_lines.append("        IF bEnable AND bEmergencyStop THEN")
    code_lines.append("            eCurrentFsmState := STATE_EXTRUDER_DIE_HEAT_SOAK;")
    code_lines.append("        END_IF;")
    code_lines.append("")
    
    # State 10: HEAT SOAK
    code_lines.append("    10: (* STATE_EXTRUDER_DIE_HEAT_SOAK: Barrel & Spiral Die Thermal Soaking *)")
    code_lines.append("        tHeatSoakTimer := tHeatSoakTimer + tTaskScanInterval;")
    code_lines.append("        (* Check all 7 extruder melt temperature thermal windows *)")
    code_lines.append("        bHeatSoakComplete := (ABS(rMeltTemp_LayerA - 215.0) < 3.5) AND")
    code_lines.append("                             (ABS(rMeltTemp_LayerB - 220.0) < 3.5) AND")
    code_lines.append("                             (ABS(rMeltTemp_LayerC - 232.0) < 3.5) AND")
    code_lines.append("                             (ABS(rMeltTemp_LayerD - 222.0) < 3.5) AND")
    code_lines.append("                             (ABS(rMeltTemp_LayerE - 218.0) < 3.5) AND")
    code_lines.append("                             (ABS(rMeltTemp_LayerF - 212.0) < 3.5) AND")
    code_lines.append("                             (ABS(rMeltTemp_LayerG - 208.0) < 3.5);")
    code_lines.append("        ")
    code_lines.append("        IF bHeatSoakComplete OR (tHeatSoakTimer > T#30S) THEN")
    code_lines.append("            eCurrentFsmState := STATE_LAYER_GRAVIMETRIC_TARE;")
    code_lines.append("            tStateDwellTimer := T#0S;")
    code_lines.append("        END_IF;")
    code_lines.append("")
    
    # State 20: GRAVIMETRIC TARE
    code_lines.append("    20: (* STATE_LAYER_GRAVIMETRIC_TARE: Loss-in-Weight Feeder Calibration *)")
    code_lines.append("        tStateDwellTimer := tStateDwellTimer + tTaskScanInterval;")
    code_lines.append("        IF tStateDwellTimer > T#5S THEN")
    code_lines.append("            bGravimetricTareComplete := TRUE;")
    code_lines.append("            eCurrentFsmState := STATE_MANUAL_BUBBLE_INIT;")
    code_lines.append("            tStateDwellTimer := T#0S;")
