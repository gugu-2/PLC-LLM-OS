    code_lines.append("    30: (* STATE_MANUAL_BUBBLE_INIT: Creep Speed Extrusion & Rope Threading *)")
    code_lines.append("        rExtruderSpeedCmd_LayerA := 8.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerB := 5.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerC := 5.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerD := 5.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerE := 8.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerF := 12.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerG := 8.0;")
    code_lines.append("        rMeltPumpSpeedCmd_LayerA := 3.5;")
    code_lines.append("        rMeltPumpSpeedCmd_LayerB := 1.2;")
    code_lines.append("        rMeltPumpSpeedCmd_LayerC := 1.5;")
    code_lines.append("        rMeltPumpSpeedCmd_LayerD := 1.2;")
    code_lines.append("        rMeltPumpSpeedCmd_LayerE := 3.2;")
    code_lines.append("        rMeltPumpSpeedCmd_LayerF := 6.5;")
    code_lines.append("        rMeltPumpSpeedCmd_LayerG := 3.3;")
    code_lines.append("        rHaulOffNipSpeed_Cmd_MPM := 6.0;")
    code_lines.append("        rAirRing_MainBlower_Cmd_Pct := 25.0;")
    code_lines.append("        ")
    code_lines.append("        tStateDwellTimer := tStateDwellTimer + tTaskScanInterval;")
    code_lines.append("        IF (tStateDwellTimer > T#10S) AND (rVotedDieMeltPressure_bar > 100.0) THEN")
    code_lines.append("            eCurrentFsmState := STATE_BUBBLE_LOCK_CAGE_ENGAGE;")
    code_lines.append("            tStateDwellTimer := T#0S;")
    code_lines.append("        END_IF;")
    code_lines.append("")
    
    # State 40: BUBBLE LOCK & CAGE
    code_lines.append("    40: (* STATE_BUBBLE_LOCK_CAGE_ENGAGE: Internal Air Inflation & Sizing Cage Engagement *)")
    code_lines.append("        rIBC_SupplyBlower_Cmd_Pct := 40.0;")
    code_lines.append("        rIBC_ExhaustBlower_Cmd_Pct := 20.0;")
    code_lines.append("        rCollapsingCageDiameter_Cmd_mm := rTargetBubbleDiameter_mm;")
    code_lines.append("        ")
    code_lines.append("        tStateDwellTimer := tStateDwellTimer + tTaskScanInterval;")
    code_lines.append("        IF (rVotedIBCBubbleDiameter_mm >= (rTargetBubbleDiameter_mm * 0.88)) AND (tStateDwellTimer > T#8S) THEN")
    code_lines.append("            bBubbleLocked := TRUE;")
    code_lines.append("            eCurrentFsmState := STATE_IBC_AERO_STABILIZATION;")
    code_lines.append("            tStateDwellTimer := T#0S;")
    code_lines.append("        END_IF;")
    code_lines.append("")
    
    # State 50: IBC STABILIZATION
    code_lines.append("    50: (* STATE_IBC_AERO_STABILIZATION: Closed-Loop IBC Aerodynamic Balancing *)")
    code_lines.append("        (* Ramp Extruders to Recipe Production Rates *)")
    code_lines.append("        rExtruderSpeedCmd_LayerA := 42.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerB := 28.0;")
    code_lines.append("        rExtruderSpeedCmd_LayerC := 32.0;")
