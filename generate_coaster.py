add("    ELSE")
add("        rVotedLaunchSpeed_mps := rLaunchSpeed_C_mps;")
add("    END_IF;")
add("ELSIF bLaunchSpd_ChA_Fault AND NOT bLaunchSpd_ChB_Fault AND NOT bLaunchSpd_ChC_Fault THEN")
add("    rVotedLaunchSpeed_mps := (rLaunchSpeed_B_mps + rLaunchSpeed_C_mps) * 0.5;")
add("ELSIF bLaunchSpd_ChB_Fault AND NOT bLaunchSpd_ChA_Fault AND NOT bLaunchSpd_ChC_Fault THEN")
add("    rVotedLaunchSpeed_mps := (rLaunchSpeed_A_mps + rLaunchSpeed_C_mps) * 0.5;")
add("ELSE")
add("    rVotedLaunchSpeed_mps := rLaunchSpeed_A_mps;")
add("    IF rLaunchSpeed_B_mps > rVotedLaunchSpeed_mps THEN rVotedLaunchSpeed_mps := rLaunchSpeed_B_mps; END_IF;")
add("    IF rLaunchSpeed_C_mps > rVotedLaunchSpeed_mps THEN rVotedLaunchSpeed_mps := rLaunchSpeed_C_mps; END_IF;")
add("END_IF;")
add("")
add("(* --- TRIAD 2: MCBR SPEED TRANSDUCERS (A, B, C) --- *)")
add("IF ABS(rMcbrEntrySpeed_A_mps - rMcbrEntrySpeed_B_mps) > 1.0 THEN")
add("    tMcbrSpd_DiscrepTimer_A := tMcbrSpd_DiscrepTimer_A + tCycleTime_ms;")
add("ELSE")
add("    tMcbrSpd_DiscrepTimer_A := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rMcbrEntrySpeed_B_mps - rMcbrEntrySpeed_C_mps) > 1.0 THEN")
add("    tMcbrSpd_DiscrepTimer_B := tMcbrSpd_DiscrepTimer_B + tCycleTime_ms;")
add("ELSE")
add("    tMcbrSpd_DiscrepTimer_B := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rMcbrEntrySpeed_A_mps - rMcbrEntrySpeed_C_mps) > 1.0 THEN")
add("    tMcbrSpd_DiscrepTimer_C := tMcbrSpd_DiscrepTimer_C + tCycleTime_ms;")
add("ELSE")
add("    tMcbrSpd_DiscrepTimer_C := T#0ms;")
add("END_IF;")
add("")
add("IF tMcbrSpd_DiscrepTimer_A > T#200ms AND tMcbrSpd_DiscrepTimer_C > T#200ms THEN bMcbrSpd_ChA_Fault := TRUE; END_IF;")
add("IF tMcbrSpd_DiscrepTimer_A > T#200ms AND tMcbrSpd_DiscrepTimer_B > T#200ms THEN bMcbrSpd_ChB_Fault := TRUE; END_IF;")
add("IF tMcbrSpd_DiscrepTimer_B > T#200ms AND tMcbrSpd_DiscrepTimer_C > T#200ms THEN bMcbrSpd_ChC_Fault := TRUE; END_IF;")
add("")
add("(* MCBR Speed Median Selection *)")
add("IF NOT bMcbrSpd_ChA_Fault AND NOT bMcbrSpd_ChB_Fault AND NOT bMcbrSpd_ChC_Fault THEN")
add("    IF (rMcbrEntrySpeed_A_mps >= rMcbrEntrySpeed_B_mps AND rMcbrEntrySpeed_A_mps <= rMcbrEntrySpeed_C_mps) OR")
add("       (rMcbrEntrySpeed_A_mps <= rMcbrEntrySpeed_B_mps AND rMcbrEntrySpeed_A_mps >= rMcbrEntrySpeed_C_mps) THEN")
add("        rVotedMcbrSpeed_mps := rMcbrEntrySpeed_A_mps;")
add("    ELSIF (rMcbrEntrySpeed_B_mps >= rMcbrEntrySpeed_A_mps AND rMcbrEntrySpeed_B_mps <= rMcbrEntrySpeed_C_mps) OR")
add("          (rMcbrEntrySpeed_B_mps <= rMcbrEntrySpeed_A_mps AND rMcbrEntrySpeed_B_mps >= rMcbrEntrySpeed_C_mps) THEN")
add("        rVotedMcbrSpeed_mps := rMcbrEntrySpeed_B_mps;")
add("    ELSE")
add("        rVotedMcbrSpeed_mps := rMcbrEntrySpeed_C_mps;")
add("    END_IF;")
add("ELSIF bMcbrSpd_ChA_Fault AND NOT bMcbrSpd_ChB_Fault AND NOT bMcbrSpd_ChC_Fault THEN")
add("    rVotedMcbrSpeed_mps := (rMcbrEntrySpeed_B_mps + rMcbrEntrySpeed_C_mps) * 0.5;")
add("ELSE")
add("    rVotedMcbrSpeed_mps := rMcbrEntrySpeed_A_mps;")
add("END_IF;")
add("")
add("(* --- TRIAD 3: PNEUMATIC SAFETY BRAKE SUPPLY PRESSURE (A, B, C) --- *)")
add("IF ABS(rBrakePneumaticPress_A_bar - rBrakePneumaticPress_B_bar) > 0.40 THEN")
add("    tPneumatic_DiscrepTimer_A := tPneumatic_DiscrepTimer_A + tCycleTime_ms;")
add("ELSE")
add("    tPneumatic_DiscrepTimer_A := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rBrakePneumaticPress_B_bar - rBrakePneumaticPress_C_bar) > 0.40 THEN")
add("    tPneumatic_DiscrepTimer_B := tPneumatic_DiscrepTimer_B + tCycleTime_ms;")
add("ELSE")
add("    tPneumatic_DiscrepTimer_B := T#0ms;")
add("END_IF;")
add("")
add("IF ABS(rBrakePneumaticPress_A_bar - rBrakePneumaticPress_C_bar) > 0.40 THEN")
add("    tPneumatic_DiscrepTimer_C := tPneumatic_DiscrepTimer_C + tCycleTime_ms;")
add("ELSE")
add("    tPneumatic_DiscrepTimer_C := T#0ms;")
add("END_IF;")
add("")
add("IF tPneumatic_DiscrepTimer_A > T#400ms AND tPneumatic_DiscrepTimer_C > T#400ms THEN bPneumatic_ChA_Fault := TRUE; END_IF;")
add("IF tPneumatic_DiscrepTimer_A > T#400ms AND tPneumatic_DiscrepTimer_B > T#400ms THEN bPneumatic_ChB_Fault := TRUE; END_IF;")
add("IF tPneumatic_DiscrepTimer_B > T#400ms AND tPneumatic_DiscrepTimer_C > T#400ms THEN bPneumatic_ChC_Fault := TRUE; END_IF;")
add("")
add("(* Pneumatic Air Pressure Median Selection *)")
add("IF NOT bPneumatic_ChA_Fault AND NOT bPneumatic_ChB_Fault AND NOT bPneumatic_ChC_Fault THEN")
add("    IF (rBrakePneumaticPress_A_bar >= rBrakePneumaticPress_B_bar AND rBrakePneumaticPress_A_bar <= rBrakePneumaticPress_C_bar) OR")
add("       (rBrakePneumaticPress_A_bar <= rBrakePneumaticPress_B_bar AND rBrakePneumaticPress_A_bar >= rBrakePneumaticPress_C_bar) THEN")
add("        rVotedBrakeAirPress_bar := rBrakePneumaticPress_A_bar;")
add("    ELSIF (rBrakePneumaticPress_B_bar >= rBrakePneumaticPress_A_bar AND rBrakePneumaticPress_B_bar <= rBrakePneumaticPress_C_bar) OR")
add("          (rBrakePneumaticPress_B_bar <= rBrakePneumaticPress_A_bar AND rBrakePneumaticPress_B_bar >= rBrakePneumaticPress_C_bar) THEN")
add("        rVotedBrakeAirPress_bar := rBrakePneumaticPress_B_bar;")
add("    ELSE")
add("        rVotedBrakeAirPress_bar := rBrakePneumaticPress_C_bar;")
add("    END_IF;")
add("ELSIF bPneumatic_ChA_Fault AND NOT bPneumatic_ChB_Fault AND NOT bPneumatic_ChC_Fault THEN")
add("    rVotedBrakeAirPress_bar := (rBrakePneumaticPress_B_bar + rBrakePneumaticPress_C_bar) * 0.5;")
add("ELSE")
add("    (* Conservative lowest reading for brake pressure failure detection *)")
add("    rVotedBrakeAirPress_bar := rBrakePneumaticPress_A_bar;")
add("    IF rBrakePneumaticPress_B_bar < rVotedBrakeAirPress_bar THEN rVotedBrakeAirPress_bar := rBrakePneumaticPress_B_bar; END_IF;")
add("    IF rBrakePneumaticPress_C_bar < rVotedBrakeAirPress_bar THEN rVotedBrakeAirPress_bar := rBrakePneumaticPress_C_bar; END_IF;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 2: LINEAR SYNCHRONOUS MOTOR (LSM) BACK-EMF & THERMAL OBSERVER                       *)")
add("(* e_back_emf = (pi / tau_p) * v_train * lambda_pm                                           *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("rLsmBackEmf_V := (3.14159265 / rLsmPolePitch_m) * rVotedLaunchSpeed_mps * rLsmMagnetFlux_Wb;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 3: EDDY-CURRENT COPPER FIN & RAIL FRICTION COEFFICIENT OBSERVER                      *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* Rail moisture compensation: dry = 0.32, saturated wet = 0.14 *)")
add("IF rRailMoistureSensor_pct > 80.0 THEN")
add("    rEffectiveRailFrictionCoeff := rWetFrictionDegradationCoeff;")
add("ELSIF rRailMoistureSensor_pct < 10.0 THEN")
add("    rEffectiveRailFrictionCoeff := rNominalDryFrictionCoeff;")
add("ELSE")
add("    rEffectiveRailFrictionCoeff := rNominalDryFrictionCoeff - ")
add("                                  ((rRailMoistureSensor_pct - 10.0) / 70.0) * (rNominalDryFrictionCoeff - rWetFrictionDegradationCoeff);")
add("END_IF;")
add("")
add("(* Analytical velocity-dependent eddy current braking force approximation *)")
add("IF rVotedMcbrSpeed_mps > 0.5 THEN")
add("    rEddyDenominator := 1.0 + (0.0018 * rVotedMcbrSpeed_mps * rVotedMcbrSpeed_mps);")
add("    rEstimatedEddyBrakeForce_kN := (4.25 * rVotedMcbrSpeed_mps) / rEddyDenominator;")
add("ELSE")
add("    rEstimatedEddyBrakeForce_kN := 0.0;")
add("END_IF;")
add("")
add("(* Emergency stopping distance prediction: s_stop = v^2 / (2 * mu * g) *)")
add("IF rEffectiveRailFrictionCoeff > 0.05 THEN")
add("    rEstimatedStoppingDistance_m := (rVotedLaunchSpeed_mps * rVotedLaunchSpeed_mps) / ")
add("                                    (2.0 * rEffectiveRailFrictionCoeff * 9.80665);")
add("ELSE")
add("    rEstimatedStoppingDistance_m := 150.0;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 4: SIL-3 MULTI-TRAIN BLOCK ZONE OCCUPANCY TRACKER & ANTI-COLLISION ENGINE            *)")
add("(* Track layout geometry:                                                                    *)")
add("(*   Block 0: Station Block (0m to 35m)                                                      *)")
add("(*   Block 1: LSM Launch Propulsion (35m to 160m)                                            *)")
add("(*   Block 2: Main Inversion Flight Zone (160m to 620m)                                      *)")
add("(*   Block 3: Mid-Course Brake Run MCBR (620m to 685m)                                       *)")
add("(*   Block 4: Secondary Airtime Helix Zone (685m to 1180m)                                   *)")
add("(*   Block 5: Final Brake Run FBR (1180m to 1260m)                                           *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("bBlock0_StationOccupied := (rTrain1_TrackPosition_m >= 0.0 AND rTrain1_TrackPosition_m < 35.0) OR ")
add("                           (rTrain2_TrackPosition_m >= 0.0 AND rTrain2_TrackPosition_m < 35.0) OR ")
add("                           (rTrain3_TrackPosition_m >= 0.0 AND rTrain3_TrackPosition_m < 35.0);")
add("")
add("bBlock1_LaunchOccupied  := (rTrain1_TrackPosition_m >= 35.0 AND rTrain1_TrackPosition_m < 160.0) OR ")
add("                           (rTrain2_TrackPosition_m >= 35.0 AND rTrain2_TrackPosition_m < 160.0) OR ")
add("                           (rTrain3_TrackPosition_m >= 35.0 AND rTrain3_TrackPosition_m < 160.0);")
add("")
add("bBlock2_Flight1Occupied := (rTrain1_TrackPosition_m >= 160.0 AND rTrain1_TrackPosition_m < 620.0) OR ")
add("                           (rTrain2_TrackPosition_m >= 160.0 AND rTrain2_TrackPosition_m < 620.0) OR ")
add("                           (rTrain3_TrackPosition_m >= 160.0 AND rTrain3_TrackPosition_m < 620.0);")
add("")
add("bBlock3_McbrOccupied    := (rTrain1_TrackPosition_m >= 620.0 AND rTrain1_TrackPosition_m < 685.0) OR ")
add("                           (rTrain2_TrackPosition_m >= 620.0 AND rTrain2_TrackPosition_m < 685.0) OR ")
add("                           (rTrain3_TrackPosition_m >= 620.0 AND rTrain3_TrackPosition_m < 685.0);")
add("")
add("bBlock4_Flight2Occupied := (rTrain1_TrackPosition_m >= 685.0 AND rTrain1_TrackPosition_m < 1180.0) OR ")
add("                           (rTrain2_TrackPosition_m >= 685.0 AND rTrain2_TrackPosition_m < 1180.0) OR ")
add("                           (rTrain3_TrackPosition_m >= 685.0 AND rTrain3_TrackPosition_m < 1180.0);")
add("")
add("bBlock5_FbrOccupied     := (rTrain1_TrackPosition_m >= 1180.0 AND rTrain1_TrackPosition_m <= 1260.0) OR ")
add("                           (rTrain2_TrackPosition_m >= 1180.0 AND rTrain2_TrackPosition_m <= 1260.0) OR ")
add("                           (rTrain3_TrackPosition_m >= 1180.0 AND rTrain3_TrackPosition_m <= 1260.0);")
add("")
add("(* HARD BLOCK SAFETY CRITICAL INTERLOCK: ABSOLUTE ANTI-COLLISION TRIP *)")
add("(* A train approaching MCBR cannot be cleared if Block 4 or Block 5 is occupied *)")
add("IF (bBlock2_Flight1Occupied AND bBlock3_McbrOccupied) OR ")
add("   (bBlock3_McbrOccupied AND bBlock4_Flight2Occupied AND (rVotedMcbrSpeed_mps > 5.0)) THEN")
add("    bAntiCollisionTripActive := TRUE;")
add("    bAlarm_BlockViolation_HH := TRUE;")
add("ELSE")
add("    bAntiCollisionTripActive := FALSE;")
add("END_IF;")
add("")
add("(* Maintenance Transfer Track Alignment Interlock *)")
add("IF bTransferTableAlignedLock THEN")
add("    bTransferTrackInterlockSafe := TRUE;")
add("ELSE")
add("    bTransferTrackInterlockSafe := FALSE;")
add("END_IF;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 5: DISCRETE KINEMATIC STATE-SPACE OBSERVER PROPAGATION                               *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("vecY_meas[0] := rVotedLaunchSpeed_mps - rTargetLaunchSpeed_mps;")
add("vecY_meas[1] := rLsmStatorCurrentActual_A * 0.125; (* Current to force scaling *)")
add("vecY_meas[2] := rTrainVertical_G - 1.0; (* Deviation from 1.0g resting gravity *)")
add("")
add("(* Compute observer predicted measurements: y_est = C * x_k *)")
add("FOR i := 0 TO 2 DO")
add("    vecY_est[i] := 0.0;")
add("    FOR j := 0 TO 5 DO")
add("        vecY_est[i] := vecY_est[i] + (matC[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    vecErr_Y[i] := vecY_meas[i] - vecY_est[i];")
add("END_FOR;")
add("")
add("(* State update: x_next = A * x_k + B * u_k + L * (y_meas - y_est) *)")
add("FOR i := 0 TO 5 DO")
add("    rTempSum := 0.0;")
add("    FOR j := 0 TO 5 DO")
add("        rTempSum := rTempSum + (matA[i, j] * vecX_k[j]);")
add("    END_FOR;")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matB[i, j] * vecU_k[j]);")
add("    END_FOR;")
add("    FOR j := 0 TO 2 DO")
add("        rTempSum := rTempSum + (matL_Obs[i, j] * vecErr_Y[j]);")
add("    END_FOR;")
add("    vecX_next[i] := rTempSum;")
add("END_FOR;")
add("")
add("FOR i := 0 TO 5 DO")
add("    vecX_k[i] := vecX_next[i];")
add("END_FOR;")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 6: MODEL PREDICTIVE CONTROL (MPC) LAUNCH PROFILING & G-FORCE LIMITING                *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("vecX_Ref[0] := 0.0; (* Speed tracking error target *)")
add("vecX_Ref[1] := 0.0; (* Position tracking error target *)")
add("vecX_Ref[2] := 0.0; (* Thrust force deviation target *)")
add("vecX_Ref[3] := 0.0; (* Trim brake force target *)")
add("vecX_Ref[4] := 0.0; (* Vertical G deviation target *)")
add("vecX_Ref[5] := 0.0; (* Lateral G deviation target *)")
add("")
add("rMpcPredictedCost := 0.0;")
add("rMpcGrad_U0 := 0.0;")
add("rMpcGrad_U1 := 0.0;")
add("rMpcGrad_U2 := 0.0;")
add("")
add("FOR i := 0 TO 5 DO")
add("    rTempDiff := vecX_k[i] - vecX_Ref[i];")
add("    rMpcPredictedCost := rMpcPredictedCost + (vecQ_Weights[i] * rTempDiff * rTempDiff);")
add("    ")
add("    rMpcGrad_U0 := rMpcGrad_U0 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 0]);")
add("    rMpcGrad_U1 := rMpcGrad_U1 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 1]);")
add("    rMpcGrad_U2 := rMpcGrad_U2 + (2.0 * vecQ_Weights[i] * rTempDiff * matB[i, 2]);")
add("END_FOR;")
add("")
add("rMpcGrad_U0 := rMpcGrad_U0 + (2.0 * vecR_Weights[0] * vecU_k[0]);")
add("rMpcGrad_U1 := rMpcGrad_U1 + (2.0 * vecR_Weights[1] * vecU_k[1]);")
add("rMpcGrad_U2 := rMpcGrad_U2 + (2.0 * vecR_Weights[2] * vecU_k[2]);")
add("")
add("(* ----------------------------------------------------------------------------------------- *)")
add("(* STEP 7: ASTM F2291 FINITE STATE MACHINE (10 OPERATIONAL STATES)                           *)")
add("(* ----------------------------------------------------------------------------------------- *)")
add("CASE iStepState OF")
add("    0: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 0: SYSTEM_SAFETY_CIRCUIT_ARM                                                 *)")
add("       (* Verify dual-channel hardware safety loop, pneumatic air pressure, and brake clamps *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bCoasterMasterTripStatus     := FALSE;")
add("       bLsmInverterEnableCmd        := FALSE;")
add("       rLsmThrustForceCmd_kN        := 0.0;")
add("       bStationHoldingBrakeClampCmd := TRUE; (* Caliper clamped *)")
add("       bMcbrFailSafeClampSolCmd     := FALSE; (* Clamped de-energized *)")
add("       bFbrFailSafeClampSolCmd      := FALSE; (* Clamped de-energized *)")
add("       bStationDispatchGateOpenCmd  := FALSE;")
add("       rStationPusherTireSpeed_mps  := 0.0;")
add("       ")
add("       IF bHardwiredEmergencyStop_ESD AND NOT bAntiCollisionTripActive THEN")
add("           IF rVotedBrakeAirPress_bar >= rMinPneumaticAir_LL_bar THEN")
add("               tStateDwellTimer := T#0ms;")
add("               iStepState       := 1; (* Advance to Station Boarding Lock *)")
add("           ELSE")
add("               bAlarm_PneumaticAir_LL := TRUE;")
add("           END_IF;")
add("       ELSE")
add("           iStepState := 8; (* Emergency brake clamp *)")
add("       END_IF;")
add("       ")
add("    1: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 1: STATION_PASSENGER_BOARDING_LOCK                                           *)")
add("       (* Restraints locked, waiting for dual-operator dispatch push buttons                 *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bStationHoldingBrakeClampCmd := TRUE;")
add("       bMcbrFailSafeClampSolCmd     := TRUE; (* Energize to open MCBR *)")
add("       bFbrFailSafeClampSolCmd      := TRUE; (* Energize to open FBR *)")
add("       ")
add("       IF bStationHarnessLockedContact AND bTransferTrackInterlockSafe THEN")
add("           (* Dual operator concurrence check within 500 ms window *)")
add("           IF bStationDispatchButton_Op1 AND bStationDispatchButton_Op2 THEN")
add("               (* Verify Block 1 (Launch) and Block 2 (Main Flight) are completely clear *)")
add("               IF NOT bBlock1_LaunchOccupied AND NOT bBlock2_Flight1Occupied THEN")
add("                   tDispatchClearTimer := T#0ms;")
add("                   iStepState          := 2; (* Advance to Dispatch Concurrence Verify *)")
add("               ELSE")
add("                   bAlarm_DispatchInterlock_H := TRUE;")
add("               END_IF;")
add("           END_IF;")
add("       END_IF;")
add("       ")
add("       IF NOT bHardwiredEmergencyStop_ESD OR bAntiCollisionTripActive THEN")
add("           iStepState := 8;")
add("       END_IF;")
add("       ")
add("    2: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 2: DISPATCH_CONCURRENCE_VERIFY                                               *)")
add("       (* Release station holding brakes, open gate, advance train with pusher tires         *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bStationHoldingBrakeClampCmd := FALSE; (* Release station brakes *)")
add("       bStationDispatchGateOpenCmd  := TRUE;  (* Lower barrier gate *)")
add("       rStationPusherTireSpeed_mps  := 2.50;  (* 2.5 m/s dispatch pusher *)")
add("       tDispatchClearTimer          := tDispatchClearTimer + tCycleTime_ms;")
add("       ")
add("       (* When train nose triggers optical launch entrance photo-eye *)")
add("       IF (rTrain1_TrackPosition_m >= 35.0) OR (tDispatchClearTimer >= T#4000ms) THEN")
add("           tLaunchTimer := T#0ms;")
add("           iStepState   := 3; (* Advance to LSM Launch Zone Acceleration *)")
add("       END_IF;")
add("       ")
add("       IF NOT bHardwiredEmergencyStop_ESD OR bAntiCollisionTripActive THEN")
add("           iStepState := 8;")
add("       END_IF;")
add("       ")
add("    3: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 3: LSM_LAUNCH_ZONE_ACCELERATION (0 to 34.0 m/s in 2.8 seconds)                *)")
add("       (* Synchronous linear motor thrust ramp with active MPC G-force profiling             *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       bLsmInverterEnableCmd := TRUE;")
add("       tLaunchTimer := tLaunchTimer + tCycleTime_ms;")
add("       ")
add("       (* Trajectory velocity setpoint calculation: S-curve acceleration *)")
add("       rLaunchProfileProgress_pct := TIME_TO_REAL(tLaunchTimer) / 2800.0;")
add("       IF rLaunchProfileProgress_pct > 1.0 THEN")
add("           rLaunchProfileProgress_pct := 1.0;")
add("       END_IF;")
add("       ")
add("       rLsmSpeedReference_mps := rTargetLaunchSpeed_mps * rLaunchProfileProgress_pct;")
add("       ")
add("       (* Closed loop thrust calculation with MPC gradient feedback *)")
add("       rLsmThrustForceCmd_kN := (48.0 * (1.0 - 0.3 * rLaunchProfileProgress_pct)) - (0.05 * rMpcGrad_U0);")
add("       IF rLsmThrustForceCmd_kN > 65.0 THEN rLsmThrustForceCmd_kN := 65.0; END_IF;")
add("       IF rLsmThrustForceCmd_kN < 0.0 THEN rLsmThrustForceCmd_kN := 0.0; END_IF;")
add("       ")
add("       (* Over-speed safety envelope trip check *)")
add("       IF rVotedLaunchSpeed_mps >= rMaxLaunchSpeed_HH_mps THEN")
add("           bAlarm_LaunchOverspeed_HH := TRUE;")
add("           iStepState := 8; (* Emergency brake clamp *)")
add("       END_IF;")
add("       ")
add("       (* When launch complete and train enters main flight track *)")
add("       IF (tLaunchTimer >= T#2900ms) OR (rTrain1_TrackPosition_m >= 160.0) THEN")
add("           bLsmInverterEnableCmd := FALSE;")
add("           rLsmThrustForceCmd_kN := 0.0;")
add("           iStepState            := 4; (* Advance to Main Flight Trajectory Monitor *)")
add("       END_IF;")
add("       ")
add("       IF NOT bHardwiredEmergencyStop_ESD OR bAntiCollisionTripActive THEN")
add("           iStepState := 8;")
add("       END_IF;")
add("       ")
add("    4: (* ---------------------------------------------------------------------------------- *)")
add("       (* STATE 4: MAIN_FLIGHT_TRAJECTORY_MONITOR (Coasting through Inversions & Hills)      *)")
add("       (* Continuous monitoring of passenger G-forces and track boundary timers              *)")
add("       (* ---------------------------------------------------------------------------------- *)")
add("       (* Check dynamic G-force limits *)")
add("       IF rTrainVertical_G > rMaxVerticalG_Limit THEN")
add("           bAlarm_VerticalG_Exceeded_HH := TRUE;")
add("       END_IF;")
add("       IF ABS(rTrainLateral_G) > rMaxLateralG_Limit THEN")
add("           bAlarm_LateralG_Exceeded_HH := TRUE;")
add("       END_IF;")
add("       ")
add("       (* Train approaches Mid-Course Brake Run MCBR *)")
add("       IF rTrain1_TrackPosition_m >= 600.0 THEN")
add("           iStepState := 5; (* Advance to MCBR Speed Trim Zone *)")
add("       END_IF;")
