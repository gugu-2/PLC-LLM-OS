    emit("            rScratch_SumBu := rScratch_SumBu + (matB[idxRow, idxCol] * arrU_PGD_Iter[idxIter - 1, idxCol]);")
    emit("        END_FOR;")
    emit("        arrStateX_Next[idxRow] := rScratch_SumAx + rScratch_SumBu;")
    emit("    END_FOR;")
    emit()
    emit("    (* B. Compute quadratic cost gradient nabla_J(u) = 2*R*(u - u_ref) + 2*B^T * (Q + P) * (x_pred - x_ref) *)")
    emit("    FOR idxCol := 1 TO 6 DO")
