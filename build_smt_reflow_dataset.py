    w("    FOR iCol := 1 TO 6 DO")
    w("        rWorkSum := 0.0;")
    w("        FOR iRow := 1 TO 8 DO")
    w("            rWorkSum := rWorkSum + (B_mat[iRow, iCol] * Q_diag[iRow] * (x_pred[iRow] - x_ref[iRow]));")
    w("        END_FOR;")
    w("        grad_J[iCol] := (2.0 * rWorkSum) +")
    w("                        (2.0 * R_diag[iCol] * (u_ctrl[iCol] - u_ref[iCol])) +")
    w("                        (2.0 * S_diag[iCol] * (u_ctrl[iCol] - u_prev[iCol]));")
    w("")
    w("        (* Gradient descent step with projection onto convex constraint set *)")
    w("        u_ctrl[iCol] := u_ctrl[iCol] - (rStepSizePGD * grad_J[iCol]);")
    w("")
    w("        (* Slew rate clamping *)")
    w("        delta_u[iCol] := LIMIT(-delta_u_max[iCol], u_ctrl[iCol] - u_prev[iCol], delta_u_max[iCol]);")
    w("        u_ctrl[iCol]  := u_prev[iCol] + delta_u[iCol];")
    w("")
    w("        (* Absolute actuator saturation bounding *)")
    w("        u_ctrl[iCol]  := LIMIT(u_min[iCol], u_ctrl[iCol], u_max[iCol]);")
    w("    END_FOR;")
    w("END_FOR;")
    w("")
    w("(* Save controls for next cycle derivative penalty *)")
    w("FOR iCol := 1 TO 6 DO")
    w("    u_prev[iCol] := u_ctrl[iCol];")
    w("END_FOR;")
    w("")
    w("")
    w("(* ========================================================================================= *)")
    w("(* PHASE 5: MULTI-ZONE CASCADE PID TEMPERATURE GOVERNOR (24 CONTROL LOOPS)                    *)")
    w("(* ========================================================================================= *)")
    w("(* Populate individual zone profile setpoints based on recipe and MPC master commands *)")
    w("rZoneSetpoint_degC[1]  := 100.0 + (0.15 * u_ctrl[1]);  (* Preheat Ingress Zone 1 *)")
    w("rZoneSetpoint_degC[2]  := 135.0 + (0.20 * u_ctrl[1]);  (* Preheat Ramp Zone 2 *)")
    w("rZoneSetpoint_degC[3]  := 155.0 + (0.15 * u_ctrl[1]);  (* Preheat Plateau Entry Zone 3 *)")
    w("rZoneSetpoint_degC[4]  := rRecipeSoakTemp_degC - 10.0; (* Soak Zone 4 *)")
    w("rZoneSetpoint_degC[5]  := rRecipeSoakTemp_degC - 3.0;  (* Soak Zone 5 *)")
    w("rZoneSetpoint_degC[6]  := rRecipeSoakTemp_degC + 2.0;  (* Soak Zone 6 *)")
    w("rZoneSetpoint_degC[7]  := rRecipeSoakTemp_degC + 5.0;  (* Soak Exit Zone 7 *)")
    w("rZoneSetpoint_degC[8]  := 215.0 + (0.10 * u_ctrl[3]);  (* Liquidus Approach Zone 8 *)")
    w("rZoneSetpoint_degC[9]  := rRecipePeakReflowTemp_degC;  (* Peak Reflow Spike Zone 9 *)")
    w("rZoneSetpoint_degC[10] := 235.0 + (0.10 * u_ctrl[3]);  (* Liquidus Dwell Zone 10 *)")
    w("rZoneSetpoint_degC[11] := 130.0 - (0.50 * u_ctrl[4]);  (* Controlled Convective Cool Zone 11 *)")
    w("rZoneSetpoint_degC[12] := 70.0 - (0.40 * u_ctrl[4]);   (* Exit Chilled Cool Zone 12 *)")
    w("")
    w("(* Conveyor speed lead-lag feedforward compensation *)")
    w("rLeadLagFiltSpeed := rLeadLagFiltSpeed + (NOMINAL_CYCLE_PERIOD_S / rSpeedLagTime_s) *")
    w("                     (rFiltConveyorSpeed_cm_min + (rSpeedLeadTime_s * (rFiltConveyorSpeed_cm_min - rSpeedHistoryBuf[1]) / NOMINAL_CYCLE_PERIOD_S) - rLeadLagFiltSpeed);")
    w("rSpeedHistoryBuf[1] := rFiltConveyorSpeed_cm_min;")
    w("rFeedforwardOffset_pct := (rLeadLagFiltSpeed - 90.0) * rFeedforwardPowerGain;")
    w("")
    w("(* Execute 12 Upper and 12 Lower Cascade PID Control Loops *)")
    w("FOR iZoneIdx := 1 TO 12 DO")
    w("    (* Upper Zone Heating Loop *)")
    w("    rTempError := rZoneSetpoint_degC[iZoneIdx] - rFiltZoneUpperTemp_degC[iZoneIdx];")
    w("    rPropAction := rKp_Upper[iZoneIdx] * rTempError;")
    w("    rIntAccumUpper[iZoneIdx] := LIMIT(-25.0, rIntAccumUpper[iZoneIdx] + (rKp_Upper[iZoneIdx] * (NOMINAL_CYCLE_PERIOD_S / LIMIT(1.0, rTi_Upper[iZoneIdx], 500.0)) * rTempError), 45.0);")
    w("    rDerivAction := rKp_Upper[iZoneIdx] * (rTd_Upper[iZoneIdx] / NOMINAL_CYCLE_PERIOD_S) * (rTempError - rPrevErrUpper[iZoneIdx]);")
    w("    rPrevErrUpper[iZoneIdx] := rTempError;")
    w("")
    w("    rPIDCommand := rPropAction + rIntAccumUpper[iZoneIdx] + rDerivAction + rFeedforwardOffset_pct;")
    w("    IF iZoneIdx <= 10 THEN")
    w("        rZoneUpperHeaterPower_pct[iZoneIdx] := LIMIT(0.0, rPIDCommand, 100.0);")
    w("    ELSE")
    w("        (* Cooling zones 11-12 do not engage heaters under normal production *)")
    w("        rZoneUpperHeaterPower_pct[iZoneIdx] := 0.0;")
    w("    END_IF;")
    w("")
    w("    (* Lower Zone Heating Loop *)")
    w("    rTempError := rZoneSetpoint_degC[iZoneIdx] - rFiltZoneLowerTemp_degC[iZoneIdx];")
    w("    rPropAction := rKp_Lower[iZoneIdx] * rTempError;")
    w("    rIntAccumLower[iZoneIdx] := LIMIT(-25.0, rIntAccumLower[iZoneIdx] + (rKp_Lower[iZoneIdx] * (NOMINAL_CYCLE_PERIOD_S / LIMIT(1.0, rTi_Lower[iZoneIdx], 500.0)) * rTempError), 45.0);")
    w("    rDerivAction := rKp_Lower[iZoneIdx] * (rTd_Lower[iZoneIdx] / NOMINAL_CYCLE_PERIOD_S) * (rTempError - rPrevErrLower[iZoneIdx]);")
    w("    rPrevErrLower[iZoneIdx] := rTempError;")
    w("")
    w("    rPIDCommand := rPropAction + rIntAccumLower[iZoneIdx] + rDerivAction + rFeedforwardOffset_pct;")
    w("    IF iZoneIdx <= 10 THEN")
    w("        rZoneLowerHeaterPower_pct[iZoneIdx] := LIMIT(0.0, rPIDCommand, 100.0);")
    w("    ELSE")
    w("        rZoneLowerHeaterPower_pct[iZoneIdx] := 0.0;")
    w("    END_IF;")
    w("")
    w("    (* Upper & Lower Blower Fan VFD Speeds: 45 to 60 Hz nominal, proportional to zone heat duty *)")
    w("    rZoneUpperBlowerFreq_Hz[iZoneIdx] := 45.0 + (0.15 * rZoneUpperHeaterPower_pct[iZoneIdx]);")
    w("    rZoneLowerBlowerFreq_Hz[iZoneIdx] := 45.0 + (0.15 * rZoneLowerHeaterPower_pct[iZoneIdx]);")
    w("END_FOR;")
    w("")
    w("(* Cooling Zone Dedicated Actuators *)")
    w("rCoolingInjectionFlow_pct := LIMIT(0.0, u_ctrl[4], 100.0);")
    w("rCoolingBlowerSpeed_pct   := 50.0 + (0.50 * rCoolingInjectionFlow_pct);")
    w("")
    w("")
    w("(* ========================================================================================= *)")
    w("(* PHASE 6: CLOSED-LOOP NITROGEN (N2) ATMOSPHERE & SUB-50 PPM OXYGEN PURGE GOVERNOR          *)")
    w("(* ========================================================================================= *)")
    w("(* Residual oxygen error calculation: e_O2 = C_O2_meas - C_O2_target *)")
    w("rTempError := rFiltResidualO2_ppm - rRecipeTargetO2_ppm;")
    w("rPropAction := rO2_Kp * rTempError;")
    w("rO2_IntAccum := LIMIT(5.0, rO2_IntAccum + (rO2_Kp * (NOMINAL_CYCLE_PERIOD_S / rO2_Ti) * rTempError), 85.0);")
    w("rDerivAction := rO2_Kp * (rO2_Td / NOMINAL_CYCLE_PERIOD_S) * (rTempError - rO2_PrevErr);")
    w("rO2_PrevErr := rTempError;")
    w("")
    w("(* Combined oxygen control action *)")
    w("rO2_ControlOutput_pct := LIMIT(10.0, rPropAction + rO2_IntAccum + rDerivAction + (0.25 * u_ctrl[5]), 100.0);")
    w("")
    w("(* Atmosphere knife barrier curtains: Entrance and exit gas knives prevent cleanroom air infiltration *)")
    w("rN2InletCurtainValve_pct := LIMIT(20.0, 35.0 + (0.45 * rO2_ControlOutput_pct), 95.0);")
    w("rN2ExitCurtainValve_pct  := LIMIT(20.0, 35.0 + (0.45 * rO2_ControlOutput_pct), 95.0);")
    w("rN2CenterTunnelValve_pct := LIMIT(15.0, rO2_ControlOutput_pct, 100.0);")
    w("")
    w("(* Exhaust extraction booster damper: balanced to maintain +0.25 mbar internal tunnel pressure *)")
    w("rExhaustExtractionCmd_pct := LIMIT(15.0, 45.0 + (rTunnelPress_Kp * (rFiltTunnelPress_mbar - rTunnelPress_Target_mbar)), 85.0);")
    w("")
    w("(* Estimated total N2 volumetric consumption rate [Nm3/h] *)")
    w("rEstimatedN2ConsumptionRate_Nm3_h := (0.28 * rN2InletCurtainValve_pct) +")
    w("                                    (0.28 * rN2ExitCurtainValve_pct) +")
    w("                                    (0.65 * rN2CenterTunnelValve_pct) +")
    w("                                    (0.40 * rCoolingInjectionFlow_pct);")
    w("")
    w("(* Inert atmosphere secured flag *)")
    w("bInertAtmosphereSecured := (rFiltResidualO2_ppm <= rRecipeTargetO2_ppm) AND (rFiltTunnelPress_mbar >= LIMIT_TUNNEL_PRESS_L_MBAR);")
    w("")
    w("")
    w("(* ========================================================================================= *)")
    w("(* PHASE 7: MULTI-STAGE FINITE STATE MACHINE (FSM) GOVERNOR                                  *)")
    w("(* ========================================================================================= *)")
    w("(* Track state transition scans *)")
    w("IF iState <> iPrevState THEN")
    w("    bStateFirstScan := TRUE;")
    w("    iPrevState      := iState;")
    w("ELSE")
    w("    bStateFirstScan := FALSE;")
    w("END_IF;")
    w("")
    w("(* Execute multi-stage CASE state transitions *)")
    w("CASE iState OF")
    w("")
    w("    (* State 0: INITIAL COLD START & SENSOR CALIBRATION *)")
    w("    FSM_INIT_DIAGNOSTICS:")
    w("        bSystemReady             := FALSE;")
    w("        bProductionPermissive    := FALSE;")
    w("        bConveyorRun             := FALSE;")
    w("        rConveyorSpeedCmd_cm_min := 0.0;")
    w("        bPurgeComplete           := FALSE;")
    w("")
    w("        (* Default PID gain assignments *)")
    w("        FOR iZoneIdx := 1 TO 12 DO")
    w("            rKp_Upper[iZoneIdx] := 1.85;")
    w("            rTi_Upper[iZoneIdx] := 65.0;")
    w("            rTd_Upper[iZoneIdx] := 8.50;")
    w("            rKp_Lower[iZoneIdx] := 1.85;")
    w("            rTi_Lower[iZoneIdx] := 65.0;")
    w("            rTd_Lower[iZoneIdx] := 8.50;")
    w("            rZoneUpperHeaterPower_pct[iZoneIdx] := 0.0;")
    w("            rZoneLowerHeaterPower_pct[iZoneIdx] := 0.0;")
    w("        END_FOR;")
    w("")
    w("        IF (bStartProfileCommand OR bPurgeN2Command) AND ((dwCriticalAlarmWord AND 16#0000_FFFF) = 0) THEN")
    w("            iState := FSM_PRE_PURGE_N2; (* Advance to State 10 *)")
    w("        END_IF;")
    w("")
    w("    (* State 10: NITROGEN PRE-PURGE (DISPLACE AIR UNTIL SUB-100 PPM O2) *)")
    w("    FSM_PRE_PURGE_N2:")
    w("        bSystemReady             := FALSE;")
    w("        bProductionPermissive    := FALSE;")
    w("        bConveyorRun             := TRUE;  (* Run conveyor slowly to purge chain pockets *)")
    w("        rConveyorSpeedCmd_cm_min := 45.0;")
    w("        rN2InletCurtainValve_pct := 85.0;  (* High purge curtains *)")
    w("        rN2ExitCurtainValve_pct  := 85.0;")
    w("        rN2CenterTunnelValve_pct := 90.0;")
    w("")
    w("        tPrePurgeTimer(IN := TRUE, PT := T#180S); (* Minimum 3 minutes purge dwell *)")
    w("")
    w("        IF tPrePurgeTimer.Q AND (rFiltResidualO2_ppm <= 100.0) THEN")
    w("            tPrePurgeTimer(IN := FALSE);")
    w("            bPurgeComplete := TRUE;")
    w("            iState         := FSM_THERMAL_PROFILE_RAMP; (* Advance to State 20 *)")
    w("        END_IF;")
    w("")
    w("        IF bStopProfileCommand THEN")
    w("            tPrePurgeTimer(IN := FALSE);")
    w("            iState := FSM_CONTROLLED_SHUTDOWN;")
    w("        END_IF;")
    w("")
    w("    (* State 20: THERMAL PROFILE CONTROLLED RAMP-UP *)")
    w("    FSM_THERMAL_PROFILE_RAMP:")
    w("        bSystemReady             := FALSE;")
    w("        bProductionPermissive    := FALSE;")
    w("        bConveyorRun             := TRUE;")
    w("        rConveyorSpeedCmd_cm_min := rConveyorSpeedSetpoint_cm_min;")
    w("")
    w("        (* Verify all zones approaching setpoints within +/- 5.0°C *)")
    w("        rWorkSum := 0.0;")
    w("        FOR iZoneIdx := 1 TO 10 DO")
    w("            rWorkSum := rWorkSum + ABS(rZoneSetpoint_degC[iZoneIdx] - rFiltZoneUpperTemp_degC[iZoneIdx]);")
    w("        END_FOR;")
    w("")
    w("        tRampStabilityTimer(IN := (rWorkSum < 35.0), PT := T#45S);")
    w("")
    w("        IF tRampStabilityTimer.Q THEN")
    w("            tRampStabilityTimer(IN := FALSE);")
    w("            iState := FSM_THERMAL_EQUILIBRIUM_SOAK; (* Advance to State 30 *)")
    w("        END_IF;")
    w("")
    w("        IF bStopProfileCommand THEN")
    w("            tRampStabilityTimer(IN := FALSE);")
    w("            iState := FSM_CONTROLLED_SHUTDOWN;")
    w("        END_IF;")
    w("")
    w("    (* State 30: THERMAL EQUILIBRIUM & SOAK STABILIZATION DWELL *)")
    w("    FSM_THERMAL_EQUILIBRIUM_SOAK:")
    w("        bSystemReady             := FALSE;")
    w("        bProductionPermissive    := FALSE;")
    w("        bConveyorRun             := TRUE;")
    w("        rConveyorSpeedCmd_cm_min := rConveyorSpeedSetpoint_cm_min;")
    w("")
    w("        tSoakEquilibriumTimer(IN := (rZoneTempUniformityDelta_degC <= 4.0) AND (rFiltResidualO2_ppm <= rRecipeTargetO2_ppm), PT := T#60S);")
    w("")
    w("        IF tSoakEquilibriumTimer.Q THEN")
    w("            tSoakEquilibriumTimer(IN := FALSE);")
    w("            iState := FSM_STEADY_PRODUCTION_CONVEY; (* Advance to State 40 *)")
    w("        END_IF;")
    w("")
    w("        IF bStopProfileCommand THEN")
    w("            tSoakEquilibriumTimer(IN := FALSE);")
    w("            iState := FSM_CONTROLLED_SHUTDOWN;")
    w("        END_IF;")
    w("")
    w("    (* State 40: CLOSED-LOOP STEADY-STATE MASS PRODUCTION CONVEY *)")
    w("    FSM_STEADY_PRODUCTION_CONVEY:")
    w("        bSystemReady             := TRUE;")
    w("        bProductionPermissive    := TRUE;")
    w("        bConveyorRun             := TRUE;")
    w("        rConveyorSpeedCmd_cm_min := rConveyorSpeedSetpoint_cm_min;")
    w("")
    w("        (* Check for downstream/upstream line starvation or conveyor pacing hold *)")
    w("        IF bConveyorPacingInhibit AND (iTotalBoardsInOven >= 28) THEN")
    w("            iState := FSM_DYNAMIC_PACING_HOLD; (* Advance to State 50 *)")
    w("        END_IF;")
    w("")
    w("        IF bStandbyModeCommand THEN")
    w("            iState := FSM_LOW_POWER_STANDBY; (* Advance to State 60 *)")
    w("        END_IF;")
    w("")
    w("        IF bStopProfileCommand THEN")
    w("            iState := FSM_CONTROLLED_SHUTDOWN;")
    w("        END_IF;")
    w("")
    w("    (* State 50: DYNAMIC PACING HOLD (BOARD BOTTLENECK / BUFFER FULL) *)")
    w("    FSM_DYNAMIC_PACING_HOLD:")
    w("        bSystemReady             := TRUE;")
    w("        bProductionPermissive    := FALSE; (* Stop upstream feeding *)")
    w("        bConveyorRun             := TRUE;  (* Keep conveyor running to empty active boards *)")
    w("        rConveyorSpeedCmd_cm_min := rConveyorSpeedSetpoint_cm_min;")
    w("")
    w("        (* Return to production when boards drop below 20 *)")
    w("        IF iTotalBoardsInOven <= 20 THEN")
    w("            iState := FSM_STEADY_PRODUCTION_CONVEY;")
    w("        END_IF;")
    w("")
    w("        IF bStopProfileCommand THEN")
    w("            iState := FSM_CONTROLLED_SHUTDOWN;")
    w("        END_IF;")
    w("")
    w("    (* State 60: LOW-POWER NITROGEN CONSERVATION STANDBY (IDLE / NIGHT) *)")
    w("    FSM_LOW_POWER_STANDBY:")
    w("        bSystemReady             := FALSE;")
    w("        bProductionPermissive    := FALSE;")
    w("        bConveyorRun             := FALSE;")
    w("        rConveyorSpeedCmd_cm_min := 0.0;")
    w("")
    w("        (* Depress zone setpoints to 130°C to conserve energy while preventing thermal cycle stress *)")
    w("        FOR iZoneIdx := 1 TO 10 DO")
    w("            rZoneSetpoint_degC[iZoneIdx] := 130.0;")
    w("        END_FOR;")
    w("        rZoneSetpoint_degC[11] := 60.0;")
    w("        rZoneSetpoint_degC[12] := 50.0;")
    w("")
    w("        (* Throttle N2 to minimal blanket sweep flow *)")
    w("        rN2InletCurtainValve_pct := 15.0;")
    w("        rN2ExitCurtainValve_pct  := 15.0;")
    w("        rN2CenterTunnelValve_pct := 10.0;")
    w("")
    w("        IF bStartProfileCommand THEN")
    w("            iState := FSM_THERMAL_PROFILE_RAMP; (* Reheat to production setpoints *)")
    w("        END_IF;")
    w("")
    w("        IF bStopProfileCommand THEN")
    w("            iState := FSM_CONTROLLED_SHUTDOWN;")
    w("        END_IF;")
    w("")
    w("    (* State 90: CONTROLLED SHUTDOWN & GRADUAL COOLDOWN *)")
    w("    FSM_CONTROLLED_SHUTDOWN:")
    w("        bSystemReady             := FALSE;")
    w("        bProductionPermissive    := FALSE;")
    w("        bConveyorRun             := (iTotalBoardsInOven > 0); (* Run conveyor until empty *)")
    w("        rConveyorSpeedCmd_cm_min := 60.0;")
    w("")
    w("        (* Shut off all heating elements *)")
    w("        FOR iZoneIdx := 1 TO 12 DO")
    w("            rZoneUpperHeaterPower_pct[iZoneIdx] := 0.0;")
    w("            rZoneLowerHeaterPower_pct[iZoneIdx] := 0.0;")
    w("        END_FOR;")
    w("")
    w("        (* Maintain moderate blowers to cool oven safely without thermal shock (< 50°C) *)")
    w("        IF (rFiltZoneUpperTemp_degC[9] <= 50.0) AND (iTotalBoardsInOven = 0) THEN")
    w("            bConveyorRun             := FALSE;")
    w("            rConveyorSpeedCmd_cm_min := 0.0;")
    w("            rN2InletCurtainValve_pct := 0.0;")
    w("            rN2ExitCurtainValve_pct  := 0.0;")
    w("            rN2CenterTunnelValve_pct := 0.0;")
    w("            iState                   := FSM_INIT_DIAGNOSTICS;")
    w("        END_IF;")
    w("")
    w("    (* State 100: EMERGENCY COOLDOWN & HARDWIRED SAFETY SHUTDOWN *)")
    w("    FSM_EMERGENCY_COOLING:")
    w("        bSystemReady             := FALSE;")
    w("        bProductionPermissive    := FALSE;")
    w("")
    w("        (* De-energize all heaters immediately *)")
    w("        FOR iZoneIdx := 1 TO 12 DO")
    w("            rZoneUpperHeaterPower_pct[iZoneIdx] := 0.0;")
    w("            rZoneLowerHeaterPower_pct[iZoneIdx] := 0.0;")
    w("            rZoneUpperBlowerFreq_Hz[iZoneIdx]   := 60.0; (* Max convection blowers for heat dump *)")
    w("            rZoneLowerBlowerFreq_Hz[iZoneIdx]   := 60.0;")
    w("        END_FOR;")
    w("")
    w("        (* Maximize cooling actuators *)")
    w("        rCoolingInjectionFlow_pct := 100.0;")
    w("        rCoolingBlowerSpeed_pct   := 100.0;")
    w("        rExhaustExtractionCmd_pct := 100.0;")
    w("")
    w("        (* Keep conveyor running to eject stuck boards unless mechanical jam occurred *)")
    w("        IF bConveyorTorqueHealthy THEN")
    w("            bConveyorRun             := TRUE;")
    w("            rConveyorSpeedCmd_cm_min := 150.0; (* High speed board evacuation *)")
    w("        ELSE")
    w("            bConveyorRun             := FALSE;")
    w("            rConveyorSpeedCmd_cm_min := 0.0;")
    w("        END_IF;")
    w("")
    w("        (* Return to Init when alarms cleared and reset acknowledged *)")
    w("        IF bResetAlarms AND ((dwCriticalAlarmWord AND 16#0000_FFFF) = 0) THEN")
    w("            iState := FSM_INIT_DIAGNOSTICS;")
    w("        END_IF;")
    w("")
    w("    ELSE")
    w("        iState := FSM_INIT_DIAGNOSTICS;")
    w("END_CASE;")
    w("")
    w("")
    w("(* ========================================================================================= *)")
    w("(* PHASE 8: ISA-18.2 MULTI-TIERED ALARM MATRIX & 32-BIT DIAGNOSTIC WORD PACKING              *)")
    w("(* ========================================================================================= *)")
    w("(* Clear non-latched warning flags *)")
    w("dwWarningWord := dwWarningWord AND 16#FFFF_0000;")
    w("dwZoneTripWord := 16#0000_0000;")
    w("")
    w("(* Peak Reflow High Temperature Warning H (> 250.0°C) *)")
    w("IF rVotedPeakReflowTemp_degC > LIMIT_PEAK_TEMP_H_DEGC THEN")
    w("    dwWarningWord := dwWarningWord OR 16#0000_0010; (* Warning Bit 4: Peak Reflow High H *)")
    w("END_IF;")
    w("")
    w("(* Peak Reflow Low Temperature Warning L (< 232.0°C during production) *)")
    w("IF (iState = FSM_STEADY_PRODUCTION_CONVEY) AND (rVotedPeakReflowTemp_degC < LIMIT_PEAK_TEMP_L_DEGC) THEN")
    w("    dwWarningWord := dwWarningWord OR 16#0000_0020; (* Warning Bit 5: Peak Reflow Low L *)")
    w("END_IF;")
    w("")
    w("(* Preheat Thermal Ramp Rate High Warning H (> 2.60°C/s) *)")
    w("IF rMeasuredRampRate_degC_s > LIMIT_RAMP_RATE_H_DEGC_S THEN")
    w("    dwWarningWord := dwWarningWord OR 16#0000_0040; (* Warning Bit 6: Preheat Ramp Rate High *)")
    w("END_IF;")
    w("")
    w("(* Controlled Cooling Thermal Shock Warning LL (< -4.80°C/s) *)")
    w("IF rMeasuredCoolingRate_degC_s < LIMIT_COOL_RATE_LL_DEGC_S THEN")
    w("    dwWarningWord := dwWarningWord OR 16#0000_0080; (* Warning Bit 7: Thermal Shock Fast Cooling *)")
    w("END_IF;")
    w("")
    w("(* Residual Oxygen High Contamination Warning H (> 60.0 ppm) *)")
    w("IF rFiltResidualO2_ppm > LIMIT_OXYGEN_H_PPM THEN")
    w("    dwWarningWord := dwWarningWord OR 16#0000_0100; (* Warning Bit 8: Residual Oxygen High *)")
    w("END_IF;")
    w("")
    w("(* Residual Oxygen Critical Contamination Runaway HH (> 120.0 ppm in Production) *)")
    w("IF (iState = FSM_STEADY_PRODUCTION_CONVEY) AND (rFiltResidualO2_ppm > LIMIT_OXYGEN_HH_PPM) THEN")
    w("    dwCriticalAlarmWord := dwCriticalAlarmWord OR 16#0000_0100; (* Critical Bit 8: Solder Oxidation Contamination *)")
    w("END_IF;")
    w("")
    w("(* Nitrogen Cryogenic Supply Pressure Low Warning L (< 4.80 bar) *)")
    w("IF rN2SupplyPressure_bar < LIMIT_N2_PRESS_L_BAR THEN")
    w("    dwWarningWord := dwWarningWord OR 16#0000_0200; (* Warning Bit 9: Nitrogen Header Low *)")
    w("END_IF;")
