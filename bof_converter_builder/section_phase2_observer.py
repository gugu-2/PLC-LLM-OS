"""
Section 4: Phase 2 - First-Principles Cyber-Physical Metallurgical & Gas-Dynamic Observer
for FB_Steel_BOF_Converter_DynamicLance_SublanceEndpoint_Offgas
"""

def get_phase2_code():
    L = []
    def emit(s=""):
        L.append(s)

    emit("(* ========================================================================= *)")
    emit("(* PHASE 2: FIRST-PRINCIPLES CYBER-PHYSICAL STATE-SPACE OBSERVER             *)")
    emit("(* ========================================================================= *)")
    emit("(* Real-time thermodynamic, fluid-mechanical, compressible flow, and          *)")
    emit("(* metallurgical reaction kinetics coupling to 6x6 discrete state observer.  *)")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.1: TOTAL LIQUID STEEL MASS & ENTHALPY INERTIA EVALUATION           *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("rTotalSteelMass_t := rHotMetalChargeWeight_t + (rScrapChargeWeight_t * 0.94);")
    emit("IF rTotalSteelMass_t < 150.0 THEN")
    emit("    rTotalSteelMass_t := 300.0; (* Safety clamping to nominal 300t capacity *)")
    emit("END_IF;")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.2: SUPERSONIC MULTI-HOLE LAVAL NOZZLE GAS DYNAMICS                 *)")
    emit("(* Calculates Mach number, nozzle exit velocity, jet momentum, and dynamic   *)")
    emit("(* penetration cavity depth Lp [mm] based on Koria-Lange formulation.       *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* Header pressure absolute [Pa]: 1 bar = 100,000 Pa *)")
    emit("rTmpVal := (rO2_Press_Voted + 1.013) / 1.013;")
    emit("IF rTmpVal < 1.893 THEN")
    emit("    (* Sub-critical unchoked flow *)")
    emit("    rLavalMachNumber := 1.00;")
    emit("ELSE")
    emit("    (* Isentropic supersonic expansion: gamma = 1.40 for pure O2 *)")
    emit("    (* M = SQRT( (2 / (gamma - 1)) * [ (P0 / P)^((gamma-1)/gamma) - 1 ] ) *)")
    emit("    rLavalMachNumber := SQRT(5.0 * (EXPT(rTmpVal, 0.285714) - 1.0));")
    emit("    IF rLavalMachNumber > 2.45 THEN rLavalMachNumber := 2.45; END_IF;")
    emit("    IF rLavalMachNumber < 1.20 THEN rLavalMachNumber := 1.20; END_IF;")
    emit("END_IF;")
    emit()
    emit("(* Supersonic gas exit velocity v_exit = M * SQRT(gamma * R_spec * T_exit) *)")
    emit("(* For O2: R_spec = 259.8 J/kg-K. T_exit ~ 185 K under Mach 2.2 expansion *)")
    emit("rLavalExitVelocity_ms := rLavalMachNumber * SQRT(1.40 * 259.8 * (rO2_HeaderTemperature_degC + 273.15) * 0.5079);")
    emit()
    emit("(* Koria-Lange Supersonic Jet Cavity Penetration Depth Lp [mm] *)")
    emit("(* Throat diameter d_t = 38.5 mm, 6-hole nozzle, inclination theta = 12.0 deg *)")
    emit("(* Liquid iron density rho_m = 6980 kg/m3 *)")
    emit("IF rLanceHeightActual_Z_mm > 500.0 THEN")
    emit("    rCavityPenetrationDepth_mm := 4.46e-3 * SQRT((rO2_Press_Voted * 1482.25) / (9.81 * 6.980)) *")
    emit("                                  EXPT(rO2_FlowSetpoint_Nm3min / rLanceHeightActual_Z_mm, 0.667) *")
    emit("                                  EXP(-0.0014 * 12.0) * 1000.0;")
    emit("    (* Dynamic cavity diameter at bath surface *)")
    emit("    rCavityDiameter_mm := 2.0 * rLanceHeightActual_Z_mm * TAN(0.2094) + 250.0; (* 12 deg half-angle expansion *)")
    emit("ELSE")
    emit("    rCavityPenetrationDepth_mm := 150.0;")
    emit("    rCavityDiameter_mm := 500.0;")
    emit("END_IF;")
    emit()
    emit("(* Clamp cavity depth to physical vessel bath depth ceiling (max 1400 mm) *)")
    emit("IF rCavityPenetrationDepth_mm > 1200.0 THEN rCavityPenetrationDepth_mm := 1200.0; END_IF;")
    emit("IF rCavityPenetrationDepth_mm < 50.0 THEN rCavityPenetrationDepth_mm := 50.0; END_IF;")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.3: REAL-TIME OFFGAS MASS SPECTROMETRY & TOTAL FLOW CALCULATION     *)")
    emit("(* Total evacuation flow via continuous Nitrogen mass balance across hood:   *)")
    emit("(* Q_offgas * (%N2 / 100) = Q_bottom_N2 + Q_ingress_air * 0.7808            *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("IF rOffgas_N2_Conc_pct > 1.50 THEN")
    emit("    rTmpVal := (rBottomNitrogenFlowActual_Nm3min * 60.0) + (rAirIngressFlow_Nm3h * 0.7808);")
    emit("    rOffgasTotalFlowCalc_Nm3h := (rTmpVal / (rOffgas_N2_Conc_pct / 100.0));")
    emit("ELSE")
    emit("    rOffgasTotalFlowCalc_Nm3h := rOffgasTotalFlowRaw_Nm3h;")
    emit("END_IF;")
    emit()
    emit("(* Filtered offgas flow bounded to realistic duct capacities: 40,000 to 240,000 Nm3/h *)")
    emit("IF rOffgasTotalFlowCalc_Nm3h < 40000.0 THEN rOffgasTotalFlowCalc_Nm3h := 40000.0; END_IF;")
    emit("IF rOffgasTotalFlowCalc_Nm3h > 240000.0 THEN rOffgasTotalFlowCalc_Nm3h := 240000.0; END_IF;")
    emit()
    emit("(* Instantaneous Decarburization Rate dC/dt [%/min] derived from offgas CO + CO2 carbon flux: *)")
    emit("(* Molar carbon: 12.011 g/mol, Molar volume standard: 22.414 Nm3/kmol *)")
    emit("(* dC/dt = (12.011 / 22.414) * (Q_offgas / 60.0) * ((%CO + %CO2)/100.0) / (W_steel * 1000.0) * 100.0 *)")
    emit("rInstantaneousDecarbRate_pctmin := (12.011 / 22.414) * (rOffgasTotalFlowCalc_Nm3h / 60.0) *")
    emit("                                  ((rOffgas_CO_Voted + rOffgas_CO2_Conc_pct) / 100.0) /")
    emit("                                  (rTotalSteelMass_t * 10.0);")
    emit("IF rInstantaneousDecarbRate_pctmin < 0.0 THEN rInstantaneousDecarbRate_pctmin := 0.0; END_IF;")
    emit("IF rInstantaneousDecarbRate_pctmin > 0.45 THEN rInstantaneousDecarbRate_pctmin := 0.45; END_IF;")
    emit("rCalculatedDecarbRate_pctmin := rInstantaneousDecarbRate_pctmin;")
    emit()
    emit("(* Post-Combustion Ratio PCR [%] in converter mouth and waste heat boiler hood *)")
    emit("IF (rOffgas_CO_Voted + rOffgas_CO2_Conc_pct) > 1.0 THEN")
    emit("    rPostCombustionRatio_calc := (rOffgas_CO2_Conc_pct / (rOffgas_CO_Voted + rOffgas_CO2_Conc_pct)) * 100.0;")
    emit("ELSE")
    emit("    rPostCombustionRatio_calc := 0.0;")
    emit("END_IF;")
    emit("rPostCombustionRatio_pct := rPostCombustionRatio_calc;")
    emit()
    emit("(* Calorific Lower Heating Value (LHV) of offgas: CO = 12.636 MJ/Nm3, H2 = 10.788 MJ/Nm3 *)")
    emit("rGasCalorificValue_MJNm3 := (rOffgas_CO_Voted * 0.12636) + (rOffgas_H2_Conc_pct * 0.10788);")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.4: SLAG-METAL REACTION EQUILIBRIUM & CHEMICAL KINETICS             *)")
    emit("(* Basicities B2, B3, dephosphorization partition LP, dynamic FeO formation *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* Slag Binary Basicity B2 = %CaO / %SiO2 *)")
    emit("IF rDynamicSlagSiO2_pct > 0.5 THEN")
    emit("    rSlagBasicity_B2 := rDynamicSlagCaO_pct / rDynamicSlagSiO2_pct;")
    emit("ELSE")
    emit("    rSlagBasicity_B2 := 3.50;")
    emit("END_IF;")
    emit()
    emit("(* Slag Ternary Basicity B3 = %CaO / (%SiO2 + 2.5) *)")
    emit("rSlagBasicity_B3 := rDynamicSlagCaO_pct / (rDynamicSlagSiO2_pct + 2.5);")
    emit()
    emit("(* Healy Dephosphorization Partition LP = (%P) / [%P] *)")
    emit("(* log10(LP) = 22,350 / T_bath - 16.0 + 0.08 * %CaO + 2.5 * log10(%FeO) *)")
    emit("rTmpVal := (22350.0 / (x_est[1] + 273.15)) - 16.0 + (0.08 * rDynamicSlagCaO_pct) + (2.5 * (LN(MAX(2.0, x_est[3])) / 2.302585));")
    emit("IF rTmpVal > 4.5 THEN rTmpVal := 4.5; END_IF;")
    emit("IF rTmpVal < 0.5 THEN rTmpVal := 0.5; END_IF;")
    emit("rDephosphorizationPartition_Lp := EXPT(10.0, rTmpVal);")
    emit()
    emit("(* Dynamic Oxygen Accumulation in Slag (determining FeO concentration) *)")
    emit("(* O2 supplied - O2 consumed in decarb - O2 consumed in Si/Mn/P oxidation *)")
    emit("rTmpVal := (rO2_FlowSetpoint_Nm3min / 60.0 * 1.429) - (* kg O2/s supplied *)")
    emit("           (rInstantaneousDecarbRate_pctmin / 60.0 * (rTotalSteelMass_t * 1000.0) / 100.0 * (16.0 / 12.011) * (1.0 + rPostCombustionRatio_calc / 100.0));")
    emit("rDynamicOxygenAccumulation_kg := rDynamicOxygenAccumulation_kg + (rTmpVal * rCycleTime_dt_s);")
    emit("IF rDynamicOxygenAccumulation_kg < 0.0 THEN rDynamicOxygenAccumulation_kg := 0.0; END_IF;")
    emit()
    emit("(* Approximate Slag FeO from accumulated oxygen mass *)")
    emit("IF rDynamicSlagMass_t > 5.0 THEN")
    emit("    rDynamicSlagFeO_pct := (rDynamicOxygenAccumulation_kg * (71.844 / 16.0) / (rDynamicSlagMass_t * 1000.0)) * 100.0 + 5.0;")
    emit("ELSE")
    emit("    rDynamicSlagFeO_pct := 14.5;")
    emit("END_IF;")
    emit("IF rDynamicSlagFeO_pct < 6.0 THEN rDynamicSlagFeO_pct := 6.0; END_IF;")
    emit("IF rDynamicSlagFeO_pct > 38.0 THEN rDynamicSlagFeO_pct := 38.0; END_IF;")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.5: ACOUSTIC SLOPPING SURVEILLANCE & ATTENUATION INDEX              *)")
    emit("(* Drop in high-frequency acoustic noise indicates muffling by foam layer.   *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("rAcousticAttenuation_dB := MAX(0.0, rAcousticBaselineQuiet_dB - rTrunnionAcoustic_Voted);")
    emit("rAcousticFoamIndex_dB := rTrunnionAcoustic_Voted;")
    emit()
    emit("(* Slopping Severity Score [0.0..10.0]: Combined Acoustic & Hood Draft Fluctuations *)")
    emit("rTmpVal := (rAcousticAttenuation_dB / 25.0) * 6.0 + (MAX(0.0, rHoodDraftPressure_Pa + 100.0) / 100.0) * 4.0;")
    emit("IF rTmpVal > 10.0 THEN rTmpVal := 10.0; END_IF;")
    emit("IF rTmpVal < 0.0 THEN rTmpVal := 0.0; END_IF;")
    emit("rSloppingSeverityIndex := rTmpVal;")
    emit()
    emit("(* Slopping Alarm Bit & Automatic Anti-Slopping Flag *)")
    emit("IF (rSloppingSeverityIndex >= 6.5) OR (rAcousticAttenuation_dB > 18.0) THEN")
    emit("    bAlarm_SloppingSevere := TRUE;")
    emit("    bAntiSloppingActive := TRUE;")
    emit("    rAntiSloppingCooldownTimer_s := 15.0; (* Persist suppression for 15s *)")
    emit("ELSE")
    emit("    IF rAntiSloppingCooldownTimer_s > 0.0 THEN")
    emit("        rAntiSloppingCooldownTimer_s := rAntiSloppingCooldownTimer_s - rCycleTime_dt_s;")
    emit("        bAntiSloppingActive := TRUE;")
    emit("    ELSE")
    emit("        bAlarm_SloppingSevere := FALSE;")
    emit("        bAntiSloppingActive := FALSE;")
    emit("    END_IF;")
    emit("END_IF;")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.6: BOTTOM-STIRRING INERT GAS THERMO-HYDRAULIC ENERGY DISSIPATION   *)")
    emit("(* Specific stirring power epsilon_dot [W/t] (Sundberg / Nakanishi)          *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("rTmpVal := rBottomArgonFlowActual_Nm3min + rBottomNitrogenFlowActual_Nm3min;")
    emit("IF rTmpVal > 0.1 THEN")
    emit("    (* Bath height H_bath ~ 1.55 m, ferrostatic pressure term *)")
    emit("    rStirringEnergyDensity_Wt := 28.5 * (rTmpVal / rTotalSteelMass_t) * (x_est[1] + 273.15) *")
    emit("                                 (LN(1.0 + (6980.0 * 9.81 * 1.55 / 101325.0)) + (1.0 - 298.15 / (x_est[1] + 273.15)));")
    emit("ELSE")
    emit("    rStirringEnergyDensity_Wt := 0.0;")
    emit("END_IF;")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.7: DYNAMIC SUBLANCE IN-BLOW LIQUIDUS ARREST CALCULATION             *)")
    emit("(* TSC probe liquidus arrest temperature T_liq directly converts to %C.     *)")
    emit("(* Fe-C Phase Diagram: %C = 4.30 - 0.00762 * (1538 - T_liq)                 *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("IF bSublanceBathContact_Sig AND (rSublanceLiquidusTemp_degC > 1400.0) AND (rSublanceLiquidusTemp_degC < 1538.0) THEN")
    emit("    rSublanceLiquidusCalculatedC_pct := 4.30 - (0.00762 * (1538.0 - rSublanceLiquidusTemp_degC)) -")
    emit("                                        (0.0000045 * EXPT(1538.0 - rSublanceLiquidusTemp_degC, 2.0));")
    emit("    IF rSublanceLiquidusCalculatedC_pct < 0.02 THEN rSublanceLiquidusCalculatedC_pct := 0.02; END_IF;")
    emit("    IF rSublanceLiquidusCalculatedC_pct > 1.80 THEN rSublanceLiquidusCalculatedC_pct := 1.80; END_IF;")
    emit("    bSublanceSampleValid := TRUE;")
    emit("    rSublanceLatchedCarbon_pct := rSublanceLiquidusCalculatedC_pct;")
    emit("    rSublanceLatchedTemp_degC := rSublanceBathTemp_degC;")
    emit("    rSublanceLatchedOxygen_ppm := rSublanceOxygenActivity_ppm;")
    emit("    bSublanceAcquisitionSuccessful := TRUE;")
    emit("END_IF;")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.8: SYNTHESIZE MEASUREMENT VECTOR y_meas[6]                         *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("IF bSublanceAcquisitionSuccessful AND (rSublanceLatchedCarbon_pct > 0.01) THEN")
    emit("    y_meas[0] := rSublanceLatchedCarbon_pct; (* High-precision sublance ground truth *)")
    emit("ELSE")
    emit("    (* Estimate from integrated decarb rate *)")
    emit("    y_meas[0] := MAX(0.03, x_est[0] - (rCalculatedDecarbRate_pctmin * (rCycleTime_dt_s / 60.0)));")
    emit("END_IF;")
    emit()
    emit("IF bSublanceAcquisitionSuccessful AND (rSublanceLatchedTemp_degC > 1450.0) THEN")
    emit("    y_meas[1] := rSublanceLatchedTemp_degC;")
    emit("ELSE")
    emit("    y_meas[1] := x_est[1];")
    emit("END_IF;")
    emit()
    emit("y_meas[2] := rCalculatedDecarbRate_pctmin;")
    emit("y_meas[3] := rDynamicSlagFeO_pct;")
    emit("y_meas[4] := rAcousticFoamIndex_dB;")
    emit("y_meas[5] := rHoodDraftPressure_Pa;")
    emit()
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* STEP 2.9: DISCRETE STATE PROPAGATION & KALMAN OBSERVER INNOVATION UPDATE  *)")
    emit("(* x_pred = A * x_est + B * u_prev                                          *)")
    emit("(* y_est  = C * x_pred + D * u_prev                                          *)")
    emit("(* innov  = y_meas - y_est                                                  *)")
    emit("(* x_est  = x_pred + L_obs * innov                                          *)")
    emit("(* ------------------------------------------------------------------------- *)")
    emit("(* Matrix Multiplication: x_pred = A * x_est + B * u_prev *)")
    emit("FOR iIdx := 0 TO 5 DO")
    emit("    rTmpSum := 0.0;")
    emit("    FOR jIdx := 0 TO 5 DO")
    emit("        rTmpSum := rTmpSum + (A_mat[iIdx, jIdx] * x_est[jIdx]);")
    emit("    END_FOR;")
    emit("    FOR kIdx := 0 TO 4 DO")
    emit("        rTmpSum := rTmpSum + (B_mat[iIdx, kIdx] * u_prev[kIdx]);")
    emit("    END_FOR;")
    emit("    x_pred[iIdx] := rTmpSum;")
    emit("END_FOR;")
    emit()
    emit("(* Matrix Multiplication: y_est = C * x_pred *)")
    emit("FOR iIdx := 0 TO 5 DO")
    emit("    rTmpSum := 0.0;")
    emit("    FOR jIdx := 0 TO 5 DO")
    emit("        rTmpSum := rTmpSum + (C_mat[iIdx, jIdx] * x_pred[jIdx]);")
    emit("    END_FOR;")
    emit("    y_est[iIdx] := rTmpSum;")
    emit("    innov[iIdx] := y_meas[iIdx] - y_est[iIdx];")
    emit("END_FOR;")
    emit()
    emit("(* Observer State Correction: x_est = x_pred + L_obs * innov *)")
    emit("FOR iIdx := 0 TO 5 DO")
    emit("    rTmpSum := 0.0;")
    emit("    FOR jIdx := 0 TO 5 DO")
    emit("        rTmpSum := rTmpSum + (L_obs[iIdx, jIdx] * innov[jIdx]);")
    emit("    END_FOR;")
    emit("    x_est[iIdx] := x_pred[iIdx] + rTmpSum;")
    emit("END_FOR;")
    emit()
    emit("(* Physical Sanity Clamping on Estimated State Vector *)")
    emit("IF x_est[0] < 0.020 THEN x_est[0] := 0.020; END_IF;   (* Bath Carbon min 0.02% *)")
    emit("IF x_est[0] > 5.000 THEN x_est[0] := 5.000; END_IF;   (* Bath Carbon max 5.0% *)")
    emit("IF x_est[1] < 1200.0 THEN x_est[1] := 1200.0; END_IF; (* Bath Temp min 1200 deg C *)")
    emit("IF x_est[1] > 1750.0 THEN x_est[1] := 1750.0; END_IF; (* Bath Temp max 1750 deg C *)")
    emit("IF x_est[2] < 0.000 THEN x_est[2] := 0.000; END_IF;   (* Decarb rate min 0.0 %/min *)")
    emit("IF x_est[2] > 0.450 THEN x_est[2] := 0.450; END_IF;   (* Decarb rate max 0.45 %/min *)")
    emit("IF x_est[3] < 5.00 THEN x_est[3] := 5.00; END_IF;     (* Slag FeO min 5% *)")
    emit("IF x_est[3] > 45.00 THEN x_est[3] := 45.00; END_IF;   (* Slag FeO max 45% *)")
    emit("IF x_est[4] < 30.00 THEN x_est[4] := 30.00; END_IF;   (* Acoustic index min 30 dB *)")
    emit("IF x_est[4] > 125.00 THEN x_est[4] := 125.00; END_IF; (* Acoustic index max 125 dB *)")
    emit("IF x_est[5] < -600.0 THEN x_est[5] := -600.0; END_IF; (* Hood draft min -600 Pa *)")
    emit("IF x_est[5] > 200.0 THEN x_est[5] := 200.0; END_IF;   (* Hood draft max +200 Pa *)")
    emit()
    emit("(* Map to Output Variables *)")
    emit("rEstimatedBathCarbon_pct := x_est[0];")
    emit("rEstimatedBathTemp_degC := x_est[1];")
    emit("rEstimatedSlagFeO_pct := x_est[3];")
    emit()

    return "\n".join(L)

if __name__ == "__main__":
    txt = get_phase2_code()
    print(f"Phase 2 length: {len(txt)} chars")
