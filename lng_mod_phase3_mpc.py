"""
Module 6: Phase 3 Discrete State-Space Model & Receding-Horizon MPC Controller
"""

def get_phase3_mpc():
    lines = []
    lines.append("(* =========================================================================================== *)")
    lines.append("(* PHASE 3: DISCRETE STATE-SPACE MODEL & RECEDING-HORIZON MPC CONTROLLER                       *)")
    lines.append("(* =========================================================================================== *)")
    lines.append("    (* --------------------------------------------------------------------------------------- *)")
    lines.append("    (* 3.1 CURRENT SYSTEM STATE VECTOR VECTORIZATION                                           *)")
    lines.append("    (* --------------------------------------------------------------------------------------- *)")
    lines.append("    vecX[1] := rVoted_CargoTankUllage_mbar - 1060.0;    (* x1: Delta Ullage Pressure [mbar] *)")
    lines.append("    vecX[2] := rVoted_CargoLiquidTemp_degC - (-161.5);  (* x2: Delta Bulk Liquid Temp [deg C] *)")
    lines.append("    vecX[3] := rEst_TotalBOG_Generation_kgh - 1570.0;   (* x3: Delta Total BOG Flow [kg/h] *)")
    lines.append("    vecX[4] := rVoted_BOGCompDischarge_bar - 300.0;     (* x4: Delta Comp Discharge [bar] *)")
    lines.append("    vecX[5] := rVoted_BOGStage4Temp_degC - 42.0;        (* x5: Delta Stage 4 Temp [deg C] *)")
    lines.append("    vecX[6] := rVoted_N2ReliquefierReturn_degC - (-162.0); (* x6: Delta Reliq Return [deg C] *)")
    lines.append("    vecX[7] := rVoted_FGSSManifold_bar - 300.0;         (* x7: Delta Engine Fuel Rail [bar] *)")
    lines.append("    vecX[8] := rEst_MembraneThermalStress_MPa - 18.5;   (* x8: Delta Membrane Stress [MPa] *)")
    lines.append("")
    lines.append("    (* Compute Multivariable State Tracking Errors *)")
    lines.append("    FOR idx_i := 1 TO 8 DO")
    lines.append("        vecErr[idx_i] := vecX[idx_i] - vecRef[idx_i];")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* --------------------------------------------------------------------------------------- *)")
    lines.append("    (* 3.2 8x8 CYBER-PHYSICAL STATE-SPACE PROPAGATION (x[k+1] = A*x[k] + B*u[k])                *)")
    lines.append("    (* --------------------------------------------------------------------------------------- *)")
    lines.append("    FOR idx_i := 1 TO 8 DO")
    lines.append("        vecX_Next[idx_i] := 0.0;")
    lines.append("        FOR idx_j := 1 TO 8 DO")
    lines.append("            vecX_Next[idx_i] := vecX_Next[idx_i] + (matA[idx_i, idx_j] * vecX[idx_j]);")
    lines.append("        END_FOR;")
    lines.append("        FOR idx_m := 1 TO 4 DO")
    lines.append("            vecX_Next[idx_i] := vecX_Next[idx_i] + (matB[idx_i, idx_m] * vecU_Cmd[idx_m]);")
    lines.append("        END_FOR;")
    lines.append("    END_FOR;")
    lines.append("")
    lines.append("    (* --------------------------------------------------------------------------------------- *)")
    lines.append("    (* 3.3 RECEDING-HORIZON MPC OPTIMIZATION VIA PROJECTED GRADIENT DESCENT (4 ITERATIONS)      *)")
    lines.append("    (* --------------------------------------------------------------------------------------- *)")
    lines.append("    IF bAutoMpcEnable AND bMasterEnable AND NOT bEmergencyShutdownActive THEN")
    lines.append("        FOR idx_iter := 1 TO 4 DO")
    lines.append("            FOR idx_m := 1 TO 4 DO")
    lines.append("                (* Calculate Analytic Cost Gradient: Grad_u = R*u + S*(u - u_prev) + B^T * Q * (x_next - r) *)")
    lines.append("                vecGradJ[idx_m] := (matR_Weight[idx_m] * vecU_Cmd[idx_m]) + (matS_Weight[idx_m] * (vecU_Cmd[idx_m] - vecU_Prev[idx_m]));")
    lines.append("                FOR idx_i := 1 TO 8 DO")
    lines.append("                    vecGradJ[idx_m] := vecGradJ[idx_m] + (matB[idx_i, idx_m] * matQ_Weight[idx_i] * (vecX_Next[idx_i] - vecRef[idx_i]));")
    lines.append("                END_FOR;")
    lines.append("")
    lines.append("                (* Gradient Descent Descent Step *)")
    lines.append("                vecU_Cmd[idx_m] := vecU_Cmd[idx_m] - (rAlpha_Step * vecGradJ[idx_m]);")
    lines.append("")
    lines.append("                (* Actuator Physical Saturation Box Projection *)")
    lines.append("                IF vecU_Cmd[idx_m] < vecU_Min[idx_m] THEN")
    lines.append("                    vecU_Cmd[idx_m] := vecU_Min[idx_m];")
    lines.append("                END_IF;")
    lines.append("                IF vecU_Cmd[idx_m] > vecU_Max[idx_m] THEN")
    lines.append("                    vecU_Cmd[idx_m] := vecU_Max[idx_m];")
    lines.append("                END_IF;")
    lines.append("")
    lines.append("                (* Dynamic Rate-Of-Change Slew Rate Constraint Clamping *)")
    lines.append("                IF (vecU_Cmd[idx_m] - vecU_Prev[idx_m]) > vecDeltaU_Max[idx_m] THEN")
    lines.append("                    vecU_Cmd[idx_m] := vecU_Prev[idx_m] + vecDeltaU_Max[idx_m];")
    lines.append("                ELSIF (vecU_Cmd[idx_m] - vecU_Prev[idx_m]) < -vecDeltaU_Max[idx_m] THEN")
    lines.append("                    vecU_Cmd[idx_m] := vecU_Prev[idx_m] - vecDeltaU_Max[idx_m];")
    lines.append("                END_IF;")
    lines.append("            END_FOR;")
    lines.append("")
    lines.append("            (* Propagate Internal Prediction Model for Subsequent Gradient Iteration *)")
    lines.append("            FOR idx_i := 1 TO 8 DO")
    lines.append("                vecX_Next[idx_i] := 0.0;")
    lines.append("                FOR idx_j := 1 TO 8 DO")
    lines.append("                    vecX_Next[idx_i] := vecX_Next[idx_i] + (matA[idx_i, idx_j] * vecX[idx_j]);")
    lines.append("                END_FOR;")
    lines.append("                FOR idx_m := 1 TO 4 DO")
    lines.append("                    vecX_Next[idx_i] := vecX_Next[idx_i] + (matB[idx_i, idx_m] * vecU_Cmd[idx_m]);")
    lines.append("                END_FOR;")
    lines.append("            END_FOR;")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Compute Total Quadratic Objective Cost Functional J *)")
    lines.append("        rMPC_CostObjective_J := 0.0;")
    lines.append("        FOR idx_i := 1 TO 8 DO")
    lines.append("            rMPC_CostObjective_J := rMPC_CostObjective_J + (0.5 * matQ_Weight[idx_i] * (vecX_Next[idx_i] - vecRef[idx_i]) * (vecX_Next[idx_i] - vecRef[idx_i]));")
    lines.append("        END_FOR;")
    lines.append("        FOR idx_m := 1 TO 4 DO")
    lines.append("            rMPC_CostObjective_J := rMPC_CostObjective_J + (0.5 * matR_Weight[idx_m] * vecU_Cmd[idx_m] * vecU_Cmd[idx_m]) + (0.5 * matS_Weight[idx_m] * (vecU_Cmd[idx_m] - vecU_Prev[idx_m]) * (vecU_Cmd[idx_m] - vecU_Prev[idx_m]));")
    lines.append("        END_FOR;")
    lines.append("")
    lines.append("        (* Store Historical Commands for Slew Penalization *)")
    lines.append("        FOR idx_m := 1 TO 4 DO")
    lines.append("            vecU_Prev[idx_m] := vecU_Cmd[idx_m];")
    lines.append("        END_FOR;")
    lines.append("    END_IF;")
    lines.append("")
    return "\n".join(lines)

print("Module 6 (Phase 3 MPC) ready.")
