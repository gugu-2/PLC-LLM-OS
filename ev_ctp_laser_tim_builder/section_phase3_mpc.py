"""
Phase 3: Receding-Horizon Model Predictive Control (MPC)
with 10 Unrolled Projected Gradient Descent (PGD) Iterations.
"""

def get_phase3_code():
    L = []
    def emit(s=""):
        L.append(s)

    emit("(* ==================================================================================================== *)")
    emit("(* PHASE 3: RECEDING-HORIZON MPC OPTIMIZATION WITH 10 UNROLLED PGD ITERATIONS                          *)")
    emit("(* Finite Horizon N = 5 Steps, Adjoint Backward Costate Propagation, Box & Slew Projections            *)")
    emit("(* Inputs: u[0]=Laser Power [%], u[1]=Galvo Trim [%], u[2]=Pump A [RPM], u[3]=Pump B [RPM],           *)")
    emit("(*         u[4]=Snort Valve [%], u[5]=Clamping Pressure Regulator [%]                                    *)")
    emit("(* ==================================================================================================== *)")
    emit()
    emit("(* Seed Initial Control Trajectory with Previous Solution or Shifted Warm Start *)")
    emit("FOR kHorizon := 0 TO 4 DO")
    emit("    FOR iInput := 0 TO 5 DO")
    emit("        trajU_mpc[kHorizon, iInput] := vecU[iInput];")
    emit("    END_FOR;")
    emit("END_FOR;")
    emit()
    emit("(* Unroll 10 Iterations of Projected Gradient Descent (PGD) Optimization Engine *)")
    emit("FOR iIteration := 0 TO 9 DO")
    emit("    (* Step 3.1: Forward State Trajectory Simulation Across Horizon N = 5 *)")
    emit("    FOR iRow := 0 TO 5 DO")
    emit("        trajX_mpc[0, iRow] := vecX_hat[iRow];")
    emit("    END_FOR;")
    emit()
    emit("    FOR kHorizon := 0 TO 4 DO")
    emit("        FOR iRow := 0 TO 5 DO")
    emit("            rDotAccum := 0.0;")
    emit("            FOR iCol := 0 TO 5 DO")
    emit("                rDotAccum := rDotAccum + (matA[iRow, iCol] * trajX_mpc[kHorizon, iCol]);")
    emit("            END_FOR;")
    emit("            FOR iInput := 0 TO 5 DO")
    emit("                rDotAccum := rDotAccum + (matB[iRow, iInput] * trajU_mpc[kHorizon, iInput]);")
    emit("            END_FOR;")
    emit("            trajX_mpc[kHorizon + 1, iRow] := rDotAccum;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit()
    emit("    (* Step 3.2: Evaluate Quadratic Objective Cost Functional *)")
    emit("    rMpc_AccumulatedCost := 0.0;")
    emit("    FOR kHorizon := 0 TO 4 DO")
    emit("        FOR iRow := 0 TO 5 DO")
    emit("            rStateDiff := trajX_mpc[kHorizon, iRow] - vecX_target[iRow];")
    emit("            rMpc_AccumulatedCost := rMpc_AccumulatedCost + (vecQ_weight[iRow] * rStateDiff * rStateDiff);")
    emit("        END_FOR;")
    emit("        FOR iInput := 0 TO 5 DO")
    emit("            rGradVal := trajU_mpc[kHorizon, iInput] - vecU_target[iInput];")
    emit("            rMpc_AccumulatedCost := rMpc_AccumulatedCost + (vecR_weight[iInput] * rGradVal * rGradVal);")
    emit("            rSlewDelta := trajU_mpc[kHorizon, iInput] - vecU_prev[iInput];")
    emit("            rMpc_AccumulatedCost := rMpc_AccumulatedCost + (vecR_delta_weight[iInput] * rSlewDelta * rSlewDelta);")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("    (* Terminal State Penalty at Horizon Step N = 5 *)")
    emit("    FOR iRow := 0 TO 5 DO")
    emit("        rStateDiff := trajX_mpc[5, iRow] - vecX_target[iRow];")
    emit("        rMpc_AccumulatedCost := rMpc_AccumulatedCost + (vecP_terminal[iRow] * rStateDiff * rStateDiff);")
    emit("    END_FOR;")
    emit()
    emit("    (* Step 3.3: Backward Costate Adjoint Propagation lambda[k] *)")
    emit("    (* Terminal Costate Boundary Condition at Step N = 5 *)")
    emit("    FOR iRow := 0 TO 5 DO")
    emit("        vecCostate[5, iRow] := 2.0 * vecP_terminal[iRow] * (trajX_mpc[5, iRow] - vecX_target[iRow]);")
    emit("    END_FOR;")
    emit()
    emit("    (* Backward Recurrence from k = 4 Down to 0 *)")
    emit("    FOR kHorizon := 4 TO 0 BY -1 DO")
    emit("        FOR iRow := 0 TO 5 DO")
    emit("            rDotAccum := 2.0 * vecQ_weight[iRow] * (trajX_mpc[kHorizon, iRow] - vecX_target[iRow]);")
    emit("            FOR iCol := 0 TO 5 DO")
    emit("                (* A^T * lambda[k+1] *)")
    emit("                rDotAccum := rDotAccum + (matA[iCol, iRow] * vecCostate[kHorizon + 1, iCol]);")
    emit("            END_FOR;")
    emit("            vecCostate[kHorizon, iRow] := rDotAccum;")
    emit("        END_FOR;")
    emit()
    emit("        (* Step 3.4: Compute Analytical Gradient w.r.t Actuator Vector u[k] *)")
    emit("        FOR iInput := 0 TO 5 DO")
    emit("            (* Effort gradient + Slew gradient + B^T * lambda[k+1] *)")
    emit("            rGradVal := 2.0 * vecR_weight[iInput] * (trajU_mpc[kHorizon, iInput] - vecU_target[iInput]);")
    emit("            rGradVal := rGradVal + (2.0 * vecR_delta_weight[iInput] * (trajU_mpc[kHorizon, iInput] - vecU_prev[iInput]));")
    emit("            FOR iRow := 0 TO 5 DO")
    emit("                rGradVal := rGradVal + (matB[iRow, iInput] * vecCostate[kHorizon + 1, iRow]);")
    emit("            END_FOR;")
    emit("            trajGrad_J[kHorizon, iInput] := rGradVal;")
    emit()
    emit("            (* Step 3.5: Projected Gradient Step with Slew Clamping and Box Saturation *)")
    emit("            rCandVal := trajU_mpc[kHorizon, iInput] - (rPgd_StepSize * trajGrad_J[kHorizon, iInput]);")
    emit()
    emit("            (* Slew Rate Clamping *)")
    emit("            IF rCandVal > (vecU_prev[iInput] + vecU_slewMax[iInput]) THEN")
    emit("                rCandVal := vecU_prev[iInput] + vecU_slewMax[iInput];")
    emit("            ELSIF rCandVal < (vecU_prev[iInput] - vecU_slewMax[iInput]) THEN")
    emit("                rCandVal := vecU_prev[iInput] - vecU_slewMax[iInput];")
    emit("            END_IF;")
    emit()
    emit("            (* Physical Saturation Box Bounds Clamping *)")
    emit("            IF rCandVal > vecU_max[iInput] THEN")
    emit("                rCandVal := vecU_max[iInput];")
    emit("            ELSIF rCandVal < vecU_min[iInput] THEN")
    emit("                rCandVal := vecU_min[iInput];")
    emit("            END_IF;")
    emit()
    emit("            trajU_mpc[kHorizon, iInput] := rCandVal;")
    emit("        END_FOR;")
    emit("    END_FOR;")
    emit("END_FOR;")
    emit()
    emit("(* Extract First Horizon Step Optimal Actuator Command Vector u[0] *)")
    emit("IF NOT bManualMpcOverride THEN")
    emit("    FOR iInput := 0 TO 5 DO")
    emit("        vecU[iInput] := trajU_mpc[0, iInput];")
    emit("    END_FOR;")
    emit("END_IF;")
    emit()
    emit("(* Assign Hardware Actuator Output Commands from Optimal Control Vector *)")
    emit("rLaser_PowerCmd_W := (vecU[0] / 100.0) * 6000.0; (* Scale 0..100% to 0..6000 W Single-Mode Laser *)")
    emit("rGalvo_MirrorVelCmd_X_mms := (vecU[1] / 100.0) * 1000.0; (* Scale 0..100% to 0..1000 mm/s Scan Vector *)")
    emit("rGalvo_MirrorVelCmd_Y_mms := (vecU[1] / 100.0) * 1000.0;")
    emit("rTIM_PumpSpeedCmd_A_rpm := vecU[2] + rTIM_LeadLag_State; (* Base Pump Speed + Lead-Lag Dynamic Boost *)")
    emit("rTIM_PumpSpeedCmd_B_rpm := vecU[3] + rTIM_LeadLag_State;")
    emit("rTIM_SnortValve_PosCmd_pct := vecU[4]; (* Tip Snort / Suckback Valve Position *)")
    emit("rGeoClamp_PneumaticPressCmd_bar := (vecU[5] / 100.0) * 6.0; (* Scale 0..100% to 0..6 bar Pneumatics *)")
    emit()
    emit("(* Cache Previous Actuation Command Vector for Slew Clamping *)")
    emit("FOR iInput := 0 TO 5 DO")
    emit("    vecU_prev[iInput] := vecU[iInput];")
    emit("END_FOR;")
    emit("rMpc_CostObjectiveValue := rMpc_AccumulatedCost;")
    emit()

    return "\n".join(L)

if __name__ == "__main__":
    code = get_phase3_code()
    print(f"Phase 3 lines: {len(code.splitlines())}")
    print(f"Phase 3 characters: {len(code)}")
