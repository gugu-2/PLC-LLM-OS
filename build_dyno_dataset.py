    emit("            rCyl_SumMin[iCylIdx] := rCyl_SumMin[iCylIdx] + rCyl_CurrentMin[iCylIdx];")
    emit("        END_FOR;")
    emit("        IF iCycleAccumulator >= 8 THEN")
    emit("            rCompressionMean_bar := 0.0;")
    emit("            rCylPressure_MaxOverall := 0.0;")
    emit("            rCylPressure_MinOverall := 999.0;")
    emit("            FOR iCylIdx := 1 TO 6 DO")
    emit("                rCyl_Pmax[iCylIdx] := rCyl_SumMax[iCylIdx] / INT_TO_REAL(iCycleAccumulator);")
    emit("                rCyl_Pmin[iCylIdx] := rCyl_SumMin[iCylIdx] / INT_TO_REAL(iCycleAccumulator);")
    emit("                rCompressionMean_bar := rCompressionMean_bar + rCyl_Pmax[iCylIdx];")
    emit("                IF rCyl_Pmax[iCylIdx] > rCylPressure_MaxOverall THEN")
    emit("                    rCylPressure_MaxOverall := rCyl_Pmax[iCylIdx];")
    emit("                END_IF;")
    emit("                IF rCyl_Pmax[iCylIdx] < rCylPressure_MinOverall THEN")
    emit("                    rCylPressure_MinOverall := rCyl_Pmax[iCylIdx];")
    emit("                END_IF;")
    emit("            END_FOR;")
    emit("            rCompressionMean_bar := rCompressionMean_bar / 6.0;")
    emit("            IF rCompressionMean_bar > 1.0 THEN")
    emit("                rCompressionDelta_Pct := ((rCylPressure_MaxOverall - rCylPressure_MinOverall) / rCompressionMean_bar) * 100.0;")
    emit("            ELSE")
    emit("                rCompressionDelta_Pct := 0.0;")
    emit("            END_IF;")
    emit("            bCompressionMeasurementReady := TRUE;")
    emit("        END_IF;")
    emit("    END_IF;")
    emit("    (* Reset peak hold for next cycle *)")
    emit("    FOR iCylIdx := 1 TO 6 DO")
    emit("        rCyl_CurrentMax[iCylIdx] := 0.0;")
    emit("        rCyl_CurrentMin[iCylIdx] := 999.0;")
    emit("    END_FOR;")
    emit("END_IF;")
    emit("")
    emit("(* ===========================================================================================")
    emit("   PHASE 5: SYNCHRONOUS CRANKSHAFT TORSIONAL VIBRATION ORDER ANALYSIS (DFT)")
    emit("   =========================================================================================== *)")
    emit("IF (iCurrentStage = STATE_08_HIGH_SPEED_TORSIONAL) AND (rDynoSpeed_Feedback_RPM > 1750.0) THEN")
    emit("    bTorsionalAnalysisActive := TRUE;")
    emit("    rCrankAngle_rad := rVotedCrankAngle_deg * rCONST_DEG_TO_RAD;")
    emit("    iOrderSampleCount := iOrderSampleCount + 1;")
    emit("")
    emit("    (* 0.5th Engine Order (Camshaft frequency: 1 cycle per 720 deg) *)")
    emit("    rHarmonicTheta05 := 0.5 * rCrankAngle_rad;")
    emit("    rAngleMod := rHarmonicTheta05 - (DINT_TO_REAL(TRUNC(rHarmonicTheta05 / rCONST_TWO_PI)) * rCONST_TWO_PI);")
    emit("    IF rAngleMod > rCONST_PI THEN rAngleMod := rAngleMod - rCONST_TWO_PI; END_IF;")
    emit("    rAngleSq := rAngleMod * rAngleMod;")
    emit("    rCosVal := 1.0 - (0.5 * rAngleSq) + (0.04166667 * rAngleSq * rAngleSq) - (0.00138889 * rAngleSq * rAngleSq * rAngleSq);")
    emit("    rSinVal := rAngleMod - (0.16666667 * rAngleMod * rAngleSq) + (0.00833333 * rAngleMod * rAngleSq * rAngleSq);")
    emit("    rOrder05_CosAccum := rOrder05_CosAccum + (rVotedTorque_Nm * rCosVal);")
    emit("    rOrder05_SinAccum := rOrder05_SinAccum + (rVotedTorque_Nm * rSinVal);")
    emit("")
    emit("    (* 1.0th Engine Order (Rotational unbalance: 1 cycle per 360 deg) *)")
    emit("    rHarmonicTheta10 := 1.0 * rCrankAngle_rad;")
    emit("    rAngleMod := rHarmonicTheta10 - (DINT_TO_REAL(TRUNC(rHarmonicTheta10 / rCONST_TWO_PI)) * rCONST_TWO_PI);")
    emit("    IF rAngleMod > rCONST_PI THEN rAngleMod := rAngleMod - rCONST_TWO_PI; END_IF;")
    emit("    rAngleSq := rAngleMod * rAngleMod;")
    emit("    rCosVal := 1.0 - (0.5 * rAngleSq) + (0.04166667 * rAngleSq * rAngleSq) - (0.00138889 * rAngleSq * rAngleSq * rAngleSq);")
    emit("    rSinVal := rAngleMod - (0.16666667 * rAngleMod * rAngleSq) + (0.00833333 * rAngleMod * rAngleSq * rAngleSq);")
    emit("    rOrder10_CosAccum := rOrder10_CosAccum + (rVotedTorque_Nm * rCosVal);")
    emit("    rOrder10_SinAccum := rOrder10_SinAccum + (rVotedTorque_Nm * rSinVal);")
    emit("")
    emit("    (* 1.5th Engine Order (Bank/half-engine sub-harmonic) *)")
    emit("    rHarmonicTheta15 := 1.5 * rCrankAngle_rad;")
    emit("    rAngleMod := rHarmonicTheta15 - (DINT_TO_REAL(TRUNC(rHarmonicTheta15 / rCONST_TWO_PI)) * rCONST_TWO_PI);")
    emit("    IF rAngleMod > rCONST_PI THEN rAngleMod := rAngleMod - rCONST_TWO_PI; END_IF;")
    emit("    rAngleSq := rAngleMod * rAngleMod;")
    emit("    rCosVal := 1.0 - (0.5 * rAngleSq) + (0.04166667 * rAngleSq * rAngleSq) - (0.00138889 * rAngleSq * rAngleSq * rAngleSq);")
    emit("    rSinVal := rAngleMod - (0.16666667 * rAngleMod * rAngleSq) + (0.00833333 * rAngleMod * rAngleSq * rAngleSq);")
    emit("    rOrder15_CosAccum := rOrder15_CosAccum + (rVotedTorque_Nm * rCosVal);")
    emit("    rOrder15_SinAccum := rOrder15_SinAccum + (rVotedTorque_Nm * rSinVal);")
    emit("")
    emit("    (* 2.0th Engine Order (Secondary reciprocating mass unbalance) *)")
    emit("    rHarmonicTheta20 := 2.0 * rCrankAngle_rad;")
    emit("    rAngleMod := rHarmonicTheta20 - (DINT_TO_REAL(TRUNC(rHarmonicTheta20 / rCONST_TWO_PI)) * rCONST_TWO_PI);")
    emit("    IF rAngleMod > rCONST_PI THEN rAngleMod := rAngleMod - rCONST_TWO_PI; END_IF;")
    emit("    rAngleSq := rAngleMod * rAngleMod;")
    emit("    rCosVal := 1.0 - (0.5 * rAngleSq) + (0.04166667 * rAngleSq * rAngleSq) - (0.00138889 * rAngleSq * rAngleSq * rAngleSq);")
    emit("    rSinVal := rAngleMod - (0.16666667 * rAngleMod * rAngleSq) + (0.00833333 * rAngleMod * rAngleSq * rAngleSq);")
    emit("    rOrder20_CosAccum := rOrder20_CosAccum + (rVotedTorque_Nm * rCosVal);")
    emit("    rOrder20_SinAccum := rOrder20_SinAccum + (rVotedTorque_Nm * rSinVal);")
    emit("")
    emit("    (* 3.0th Engine Order (Primary 6-cylinder compression firing order harmonic) *)")
    emit("    rHarmonicTheta30 := 3.0 * rCrankAngle_rad;")
    emit("    rAngleMod := rHarmonicTheta30 - (DINT_TO_REAL(TRUNC(rHarmonicTheta30 / rCONST_TWO_PI)) * rCONST_TWO_PI);")
    emit("    IF rAngleMod > rCONST_PI THEN rAngleMod := rAngleMod - rCONST_TWO_PI; END_IF;")
    emit("    rAngleSq := rAngleMod * rAngleMod;")
    emit("    rCosVal := 1.0 - (0.5 * rAngleSq) + (0.04166667 * rAngleSq * rAngleSq) - (0.00138889 * rAngleSq * rAngleSq * rAngleSq);")
    emit("    rSinVal := rAngleMod - (0.16666667 * rAngleMod * rAngleSq) + (0.00833333 * rAngleMod * rAngleSq * rAngleSq);")
    emit("    rOrder30_CosAccum := rOrder30_CosAccum + (rVotedTorque_Nm * rCosVal);")
    emit("    rOrder30_SinAccum := rOrder30_SinAccum + (rVotedTorque_Nm * rSinVal);")
    emit("")
    emit("    (* Resolve Harmonic Order Amplitudes after 1200 Samples (approx 1.2 s dwell) *)")
    emit("    IF iOrderSampleCount >= 1200 THEN")
    emit("        rHarmonicOrder_0_5 := (2.0 / DINT_TO_REAL(iOrderSampleCount)) * SQRT((rOrder05_CosAccum * rOrder05_CosAccum) + (rOrder05_SinAccum * rOrder05_SinAccum));")
    emit("        rHarmonicOrder_1_0 := (2.0 / DINT_TO_REAL(iOrderSampleCount)) * SQRT((rOrder10_CosAccum * rOrder10_CosAccum) + (rOrder10_SinAccum * rOrder10_SinAccum));")
    emit("        rHarmonicOrder_1_5 := (2.0 / DINT_TO_REAL(iOrderSampleCount)) * SQRT((rOrder15_CosAccum * rOrder15_CosAccum) + (rOrder15_SinAccum * rOrder15_SinAccum));")
    emit("        rHarmonicOrder_2_0 := (2.0 / DINT_TO_REAL(iOrderSampleCount)) * SQRT((rOrder20_CosAccum * rOrder20_CosAccum) + (rOrder20_SinAccum * rOrder20_SinAccum));")
    emit("        rHarmonicOrder_3_0 := (2.0 / DINT_TO_REAL(iOrderSampleCount)) * SQRT((rOrder30_CosAccum * rOrder30_CosAccum) + (rOrder30_SinAccum * rOrder30_SinAccum));")
    emit("    END_IF;")
    emit("ELSE")
    emit("    bTorsionalAnalysisActive := FALSE;")
    emit("END_IF;")
    emit("")
    emit("(* ===========================================================================================")
    emit("   PHASE 6: DYNAMIC OIL GALLERY PRESSURE VS VVT CAM PHASER ACTUATION")
    emit("   =========================================================================================== *)")
    emit("IF iCurrentStage = STATE_07_VVT_PHASER_EXCURSION THEN")
    emit("    tVVT_ResponseTimer := tVVT_ResponseTimer + tTaskScanInterval;")
    emit("    IF NOT bVVT_StepInitiated THEN")
    emit("        rOilPressure_PreVVT := rVotedOilPressure_bar;")
    emit("        rOilPressure_MinDuringVVT := rVotedOilPressure_bar;")
    emit("        bVVT_StepInitiated := TRUE;")
    emit("        bVVT_IntakeTargetReached := FALSE;")
    emit("        bVVT_ExhaustTargetReached := FALSE;")
    emit("    END_IF;")
    emit("    (* Actuate VVT PWM valves to target calibration positions *)")
    emit("    rVVT_IntakeDuty_Pct := 75.0;  (* Step advance command *)")
    emit("    rVVT_ExhaustDuty_Pct := 25.0; (* Step retard command *)")
    emit("    (* Track minimum oil pressure during hydraulic phaser filling *)")
    emit("    IF rVotedOilPressure_bar < rOilPressure_MinDuringVVT THEN")
    emit("        rOilPressure_MinDuringVVT := rVotedOilPressure_bar;")
    emit("    END_IF;")
    emit("    rOilPressure_DropVVT := rOilPressure_PreVVT - rOilPressure_MinDuringVVT;")
    emit("    (* Track response arrival time *)")
    emit("    IF NOT bVVT_IntakeTargetReached AND (ABS(rIntakeCamAngle_deg - rVVT_IntakeStepTarget_deg) < 1.2) THEN")
    emit("        rVVT_IntakeLag_ms := TIME_TO_REAL(tVVT_ResponseTimer);")
    emit("        bVVT_IntakeTargetReached := TRUE;")
    emit("    END_IF;")
    emit("    IF NOT bVVT_ExhaustTargetReached AND (ABS(rExhaustCamAngle_deg - rVVT_ExhaustStepTarget_deg) < 1.2) THEN")
    emit("        rVVT_ExhaustLag_ms := TIME_TO_REAL(tVVT_ResponseTimer);")
    emit("        bVVT_ExhaustTargetReached := TRUE;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    bVVT_StepInitiated := FALSE;")
    emit("    rVVT_IntakeDuty_Pct := 0.0;")
    emit("    rVVT_ExhaustDuty_Pct := 0.0;")
    emit("    tVVT_ResponseTimer := T#0S;")
    emit("END_IF;")
    emit("")
    emit("(* ===========================================================================================")
    emit("   PHASE 7: COAST-DOWN DRAG TORQUE & MECHANICAL FRICTION INTEGRATION")
    emit("   =========================================================================================== *)")
    emit("IF iCurrentStage = STATE_09_COASTDOWN_DRAG_INTEG THEN")
    emit("    IF (rDynoSpeed_Feedback_RPM < 1650.0) AND (rDynoSpeed_Feedback_RPM > 350.0) THEN")
    emit("        iCoastdown_SampleCount := iCoastdown_SampleCount + 1;")
    emit("        (* Compute angular deceleration: alpha = (omega_prev - omega) / dt *)")
    emit("        rCoastdown_DecelAccum := rCoastdown_DecelAccum + ((rCoastdown_PrevSpeed_RPM - rDynoSpeed_Feedback_RPM) * rCONST_RPM_TO_RADS / rDeltaTime_Seconds);")
    emit("    END_IF;")
    emit("    rCoastdown_PrevSpeed_RPM := rDynoSpeed_Feedback_RPM;")
    emit("    IF (rDynoSpeed_Feedback_RPM <= 350.0) AND (iCoastdown_SampleCount > 100) THEN")
    emit("        rCoastdown_AvgDecel_rad_s2 := rCoastdown_DecelAccum / DINT_TO_REAL(iCoastdown_SampleCount);")
    emit("        (* Total tare friction torque: T_tare = (J_dyno + J_engine) * alpha_decel *)")
    emit("        rCoastdownFrictionTorque_Nm := (rDYNO_ROTOR_INERTIA + rENGINE_CRANK_INERTIA) * rCoastdown_AvgDecel_rad_s2;")
    emit("    END_IF;")
    emit("ELSE")
    emit("    rCoastdown_PrevSpeed_RPM := rDynoSpeed_Feedback_RPM;")
    emit("END_IF;")
    emit("")
    emit("(* ===========================================================================================")
    emit("   PHASE 8: 12-STAGE OPERATIONAL FINITE STATE MACHINE")
    emit("   =========================================================================================== *)")
    emit("CASE iCurrentStage OF")
    emit("    STATE_00_STANDBY_IDLE:")
    emit("        bSequenceBusy := FALSE;")
    emit("        bPalletClamp_Cmd := FALSE;")
    emit("        bDrivelineDock_Cmd := FALSE;")
    emit("        bFluidCouplerDock_Cmd := FALSE;")
    emit("        bOilScavengePurge_Cmd := FALSE;")
    emit("        rAuxLubePumpSpeed_Cmd := 0.0;")
    emit("        tStageElapsedTimer := T#0S;")
    emit("        IF bAutoSequenceStart AND bPalletClamped_FB THEN")
    emit("            bSequenceBusy := TRUE;")
    emit("            bColdTestPass := FALSE;")
    emit("            bColdTestFail := FALSE;")
    emit("            iCurrentStage := STATE_01_PALLET_CLAMPING;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_01_PALLET_CLAMPING:")
    emit("        bPalletClamp_Cmd := TRUE;")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        IF bPalletClamped_FB THEN")
    emit("            tStageElapsedTimer := T#0S;")
    emit("            iCurrentStage := STATE_02_DRIVELINE_DOCKING;")
    emit("        ELSIF tStageElapsedTimer > T#4000MS THEN")
    emit("            bAlm_PalletClampLoss := TRUE;")
    emit("            iCurrentStage := STATE_99_EMERGENCY_FAULT_LOCKOUT;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_02_DRIVELINE_DOCKING:")
    emit("        bDrivelineDock_Cmd := TRUE;")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        IF bDrivelineDocked_FB THEN")
    emit("            tStageElapsedTimer := T#0S;")
    emit("            iCurrentStage := STATE_03_FLUID_COUPLING_PREFILL;")
    emit("        ELSIF tStageElapsedTimer > T#6000MS THEN")
    emit("            bAlm_DrivelineDockSlip := TRUE;")
    emit("            iCurrentStage := STATE_99_EMERGENCY_FAULT_LOCKOUT;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_03_FLUID_COUPLING_PREFILL:")
    emit("        bFluidCouplerDock_Cmd := TRUE;")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        IF bFluidCouplerSeated_FB THEN")
    emit("            rAuxLubePumpSpeed_Cmd := 65.0; (* Pre-fill lubrication circuit *)")
    emit("            IF tStageElapsedTimer > T#3500MS THEN")
    emit("                tStageElapsedTimer := T#0S;")
    emit("                iCurrentStage := STATE_04_CRANKING_TORQUE_VERIFY;")
    emit("            END_IF;")
    emit("        ELSIF tStageElapsedTimer > T#5000MS THEN")
    emit("            iCurrentStage := STATE_99_EMERGENCY_FAULT_LOCKOUT;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_04_CRANKING_TORQUE_VERIFY:")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        IF rVotedTorque_Nm > rPeakBreakawayTorque_Nm THEN")
    emit("            rPeakBreakawayTorque_Nm := rVotedTorque_Nm;")
    emit("        END_IF;")
    emit("        IF tStageElapsedTimer > T#2500MS THEN")
    emit("            IF rPeakBreakawayTorque_Nm <= 165.0 THEN")
    emit("                bBreakawayTorquePassed := TRUE;")
    emit("                tStageElapsedTimer := T#0S;")
    emit("                iCurrentStage := STATE_05_BASE_OIL_PRIMING;")
    emit("            ELSE")
    emit("                bBreakawayTorquePassed := FALSE;")
    emit("                bColdTestFail := TRUE;")
    emit("                iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_05_BASE_OIL_PRIMING:")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        rAuxLubePumpSpeed_Cmd := 0.0; (* Test stand pump off, verify engine self-priming *)")
    emit("        IF tStageElapsedTimer > T#4000MS THEN")
    emit("            IF rVotedOilPressure_bar >= 2.2 THEN")
    emit("                bOilPrimingPassed := TRUE;")
    emit("                tStageElapsedTimer := T#0S;")
    emit("                iCurrentStage := STATE_06_LOW_SPEED_COMPRESSION;")
    emit("            ELSE")
    emit("                bOilPrimingPassed := FALSE;")
    emit("                bColdTestFail := TRUE;")
    emit("                iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
    emit("            END_IF;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_06_LOW_SPEED_COMPRESSION:")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        IF bCompressionMeasurementReady THEN")
    emit("            IF (rCompressionDelta_Pct <= 4.8) AND (rCompressionMean_bar >= 18.5) THEN")
    emit("                bCompressionPassed := TRUE;")
    emit("                tStageElapsedTimer := T#0S;")
    emit("                iCurrentStage := STATE_07_VVT_PHASER_EXCURSION;")
    emit("            ELSE")
    emit("                bCompressionPassed := FALSE;")
    emit("                bColdTestFail := TRUE;")
    emit("                iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
    emit("            END_IF;")
    emit("        ELSIF tStageElapsedTimer > T#8000MS THEN")
    emit("            bColdTestFail := TRUE;")
    emit("            iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_07_VVT_PHASER_EXCURSION:")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        IF bVVT_IntakeTargetReached AND bVVT_ExhaustTargetReached THEN")
    emit("            IF (rVVT_IntakeLag_ms <= 320.0) AND (rVVT_ExhaustLag_ms <= 320.0) AND (rOilPressure_MinDuringVVT >= 1.6) THEN")
    emit("                bVVTPassed := TRUE;")
    emit("                tStageElapsedTimer := T#0S;")
    emit("                iCurrentStage := STATE_08_HIGH_SPEED_TORSIONAL;")
    emit("            ELSE")
    emit("                bVVTPassed := FALSE;")
    emit("                bColdTestFail := TRUE;")
    emit("                iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
    emit("            END_IF;")
    emit("        ELSIF tStageElapsedTimer > T#6000MS THEN")
    emit("            bColdTestFail := TRUE;")
    emit("            iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
    emit("        END_IF;")
    emit("")
    emit("    STATE_08_HIGH_SPEED_TORSIONAL:")
    emit("        tStageElapsedTimer := tStageElapsedTimer + tTaskScanInterval;")
    emit("        IF iOrderSampleCount >= 1200 THEN")
    emit("            IF (rHarmonicOrder_0_5 <= 9.5) AND (rHarmonicOrder_1_0 <= 13.5) AND")
    emit("               (rHarmonicOrder_1_5 <= 9.0) AND (rHarmonicOrder_2_0 <= 18.0) AND (rHarmonicOrder_3_0 <= 55.0) THEN")
    emit("                bTorsionalPassed := TRUE;")
    emit("                tStageElapsedTimer := T#0S;")
    emit("                iCurrentStage := STATE_09_COASTDOWN_DRAG_INTEG;")
    emit("            ELSE")
    emit("                bTorsionalPassed := FALSE;")
    emit("                bColdTestFail := TRUE;")
    emit("                iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
    emit("            END_IF;")
    emit("        ELSIF tStageElapsedTimer > T#8000MS THEN")
    emit("            bColdTestFail := TRUE;")
    emit("            iCurrentStage := STATE_11_AUTOMATED_UNDOCKING;")
